"""Помнит на весь процесс два замера упаковщика: доверие карте и начало ленты фильма.

Читают их упаковщик (:mod:`torrcast.adapters.stream_pack`) и сценарий подачи
(:mod:`torrcast.usecases.feed_pack`). Замеры лежат отдельно от самого упаковщика
намеренно: их берут раньше, чем собирается упаковщик, и общий модуль замкнул бы
импорты в кольцо.
"""

from __future__ import annotations

import threading
from typing import Final

#: Файлы, на которых карта опорных кадров разошлась с фактом нарезки: по ним место захода
#: считает только пробный прогон (:func:`pack_start`). Ключ - URL потока, как и у кэша
#: карты. Пусто по умолчанию: карте верят сразу, а сюда файл попадает уже уложенным
#: куском, разъехавшимся с манифестом (:func:`torrcast.usecases.feed_pack.feed_astray._astray`).
_MAP_LIED: set[str] = set()
_SEEK_LOCK: Final = threading.Lock()
#: Начало ленты по фильмам: ``URL -> сдвиг`` (:func:`pack_origin`). Считается один раз на
#: файл, потому что заходов на него много (старт, перемотка, прогрев, перекод), а сдвиг
#: у них обязан быть ОДИН.
_ORIGIN: dict[str, float] = {}
_ORIGIN_LOCK: Final = threading.Lock()
