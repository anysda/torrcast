"""Отпечаток правил кодирования: чем кусок собран, а не только каким решением взят.

Спрашивает его ключ прогретого (:func:`torrcast.usecases.warm.warm_key.warm_key`) через
:attr:`torrcast.adapters.recode.encode.Encode.imprint`.
"""

from __future__ import annotations

import hashlib
from typing import Protocol

from torrcast.adapters.stream_pack.grid import Grid

#: Сетка-образец, на которой снимается отпечаток: три границы через 10 с.
#:
#: Своя, а не сетка показа, и это не экономия. Границы уже входят в ключ отдельным
#: слагаемым (:func:`torrcast.usecases.warm.warm_key._bounds_mark`), и отпечаток обязан
#: молчать о них: считай он их второй раз, каждый фильм давал бы свой отпечаток, и
#: сравнивать два выпуска между собой стало бы нечем.
#:
#: Числа тут не важны, важно что они НЕ МЕНЯЮТСЯ: любое из них, попав в аргументы,
#: попадает туда одинаково до правки и после. Границы стоят ровно, чтобы отступ
#: принудительного опорного кадра (:data:`torrcast.adapters.recode.encode_settings._KEY_SLACK`)
#: было видно в отпечатке - он тоже правило кодирования.
PROBE_GRID = Grid(bounds=(0.0, 10.0, 20.0), duration=30.0, on_keys=True)


class _Encoder(Protocol):
    """Тот, у кого есть боевая команда кодировщика; больше отпечатку ничего не нужно."""

    def args(self, grid: Grid, slot: int, until: int) -> list[str]:
        """Аргументы видеокодера, которыми кусок и будет собран."""


def encode_imprint(encode: _Encoder) -> str:
    """Отпечаток аргументов кодировщика, снятый с ТОЙ ЖЕ формы, из которой идёт команда.

    🔴 Здесь нет ни одного имени поля и ни одного флага ffmpeg. Отпечаток берётся тем же
    вызовом (:meth:`torrcast.adapters.recode.encode.Encode.args`), которым собирается
    боевая команда, и потому не умеет отстать от неё. Список имён рядом умеет: ровно так
    протух чёрный список установщика (TC-549), где забытое имя месяцами жило на старом
    числе, и ровно так протух бы список полей тут - снятый ``-level`` (TC-871) поля не
    трогал вовсе, а байты в SPS менял.

    Считается по ОБРАЗЦОВОЙ сетке (:data:`PROBE_GRID`), а не по сетке показа: отпечатку
    положено говорить о правилах, а не о фильме. Поэтому выпуск, не тронувший правил
    кодирования, отдаёт ту же строку до знака, и уже прогретая полка переживает
    обновление; выпуск, тронувший их, отдаёт другую, и старые куски перестают находиться
    под своими именами - пересобираются, а не подсовываются.

    Двенадцати знаков хватает: отпечаток не защищает от подбора, он различает соседние
    выпуски одного продукта.
    """
    line = "\x00".join(encode.args(PROBE_GRID, 0, 0))
    return hashlib.sha1(line.encode("utf-8")).hexdigest()[:12]
