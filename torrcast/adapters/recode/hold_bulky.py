"""Ждать перекод куска, копия которого тяжелее потолка приёмника: правило про факт.

Зовёт его придержка копии (:func:`_holding`), и только она."""

from __future__ import annotations

from typing import TYPE_CHECKING

from torrcast.ports.journal import journal

if TYPE_CHECKING:
    from torrcast.adapters.recode.recoder_state import _State


def _hold_bulky(state: _State, slot: int, now: float) -> bool:
    """Ждать перекод куска, копия которого тяжелее потолка. Правило про факт, не срок.

    Замер, ради которого правило написано («Тачки 3» со старта 3880):
    сетка поставила ``v364`` длиной 10.43 с, предсказав его вес по ``ceiling_mbit``
    в 11.7 МБ — «тяжёлое перекодируют». Кодировщик к сроку не успел, :meth:`holding`
    отпустил копию по сроку, и на ТВ уехали **51.4 МБ** — втрое выше потолка. Двадцать
    опросов ``BUFFERING`` за 46 с. Обе половины по отдельности честны, а вместе дают
    дыру; закрывает её ровно одна мысль: **отпускать такую копию некуда**. Приёмник её
    не переварит ни при каком сроке, значит выбор не «ждать или отдать», а «ждать или
    ждать зря».

    ⚠️ Разрезать этот кусок сеткой мельче было НЕЛЬЗЯ, и это замерено, а не сказано:
    внутри 3914.911…3925.338 нет ни одного опорного кадра — это один GOP на 51 МБ.
    Сетка режет только по опорным кадрам (иначе кусок не декодируется сам по себе), и
    никакая настройка потолка тут границы не добавит. Отсюда и деление труда: сетка
    отвечает за то, что можно разрезать, кодировщик — за то, что нельзя.

    Ждём, пока кодировщик за кусок берётся. Три случая, когда ждать нечего:
    кодировщик снят, кусок не в его списке или он на нём уже сдался (:attr:`done`).
    Плюс предохранитель :attr:`over_wait` - на случай, когда ffmpeg не поднимается
    вовсе. Что делать с отпущенной копией, решает выкладка: ужимает её на месте
    или честно пропускает (:meth:`torrcast.stream.Feed._shrink`).

    🔴 Каждый отказ ждать - это заявка на второй кодировщик в машине, и отсюда же
    она и отмечается (:attr:`shrinking`): следующим делом выкладка поднимет своё
    ужатие, а заход обязан на это время замереть (:meth:`_yield_to_shrink`).
    """
    if state.stopped:
        return False
    if slot in state.done or slot not in set(state.targets):
        # Кодировщик за это место не берётся: либо уже сдался, либо профиль тяжести
        # его промахнул - вес копии оказался выше предсказанного. Ровно так ушли в
        # ужатие слоты 0, 2 и 4 разбираемого показа: ни один из них не был в
        # :attr:`targets`, и ни на одном не встала выкладка - она просто ужала их
        # сама, втроём за первые двенадцать секунд, рядом с чужим заходом.
        state.shrinking = (slot, now)
        return False
    since = state.stuck.get(slot)
    if since is None:
        state.stuck[slot] = since = now
        state.blocked = slot
        journal().mark("держу тяжёлую копию", слот=slot, мбит=round(state.weights.at(slot), 1))
        state._say(
            f"v{slot} копией тяжелее {state.cap / 1e6:.0f} МБ - жду перекод: "
            "такой кусок приёмник не доигрывает"
        )
    if now - since < state.over_wait:
        state.blocked = slot
        return True
    # Предохранитель сработал: кодировщик за эти секунды не дал ничего. Снимаем
    # ожидание - дальше кусок решает выкладка (ужатие на месте или пропуск).
    state._say(f"⚠️ v{slot}: перекода нет {state.over_wait:.0f} с - снимаю ожидание")
    state._unstick(slot)
    state.shrinking = (slot, now)
    return False
