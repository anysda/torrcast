"""Чем перекодировать ВЕСЬ файл: пресет, битрейт и кадр одним решением.

Спрашивают об этом трое: показ, сетка прогрева и щупы замера."""

from __future__ import annotations

from typing import Final

from torrcast.adapters.recode.encode import Encode

#: Пресет сплошного перекода - того, которым идёт ВЕСЬ файл, который не разрешено отдать
#: копией (:meth:`torrcast.profile.Profile.verdict`). Выбирать тут не из чего, и это
#: замер, а не осторожность: на стенде (4 vCPU) декод HEVC вместе с ``ultrafast`` даёт
#: ~2× реального времени - двукратный запас, - а уже ``veryfast`` падает до 1.0-1.3×,
#: то есть упаковка идёт вровень с показом и первый же трудный кусок её обгоняет.
#: Здесь пресет не торгуется по сроку (:func:`preset_for`): срок один на весь фильм.
FULL_PRESET: Final = "ultrafast"

#: Во сколько раз битрейт сплошного перекода выше исходного. H.264 на ``ultrafast`` - это
#: без CABAC и почти без анализа, то есть заметно дороже HEVC при той же картинке; вдвое
#: с небольшим - цена, за которую перекод не видно глазом.
FULL_GAIN: Final = 2.5

#: Ниже этого 1080p на ``ultrafast`` разваливается на блоки, сколько бы ни весил источник.
FULL_FLOOR: Final = 3.0


def whole_encode(
    mbit: float, video_mbit: float = 0.0, frame: int = 0, ceiling: int = 0, hdr: bool = False
) -> Encode:
    """Чем перекодировать ВЕСЬ файл: пресет, битрейт и кадр - одним решением.

    Живёт здесь, а не у показа, ровно потому, что спрашивают об этом трое: сам показ
    (:func:`torrcast.cli._encode_all`), сетка прогрева и щупы замера. Разойдись они хоть
    в одном числе - щуп мерил бы не тот тракт, а прогретое легло бы под чужим ключом.

    ``video_mbit`` - вес видеодорожки источника: перекодировать лёгкое аниме в полные
    ``mbit`` значит потратить процессор на биты, которых во входе нет
    (:data:`FULL_GAIN`, :data:`FULL_FLOOR`).
    """
    want = mbit
    if video_mbit > 0:
        want = min(want, max(FULL_FLOOR, video_mbit * FULL_GAIN))
    return Encode(preset=FULL_PRESET, mbit=want, frame=frame, ceiling=ceiling, hdr=hdr)
