"""Замеренные пороги перекода: потолок кодера, буфер VBV, отступ цели и цепочка HDR→SDR.

Зовёт их :class:`torrcast.adapters.recode.encode.Encode` - и никто больше."""

from __future__ import annotations

from typing import Final

#: Во сколько раз мгновенный потолок кодера выше цели (:attr:`Encode.maxrate`). Всё, что
#: считает вес куска заранее, обязано брать именно его: цель - это средний битрейт, а
#: положить в кусок кодер вправе вплоть до этого потолка.
MAXRATE_GAIN: Final = 1.08

#: Сколько СЕКУНД своего потолка кодеру разрешено копить впрок - буфер VBV
#: (``-bufsize``), выраженный в долях :attr:`Encode.maxrate`.
#:
#: 🔴 Это защита показа, а не настройка качества. Буфер VBV - это кредит: секунды, на
#: которых картинка почти ничего не стоит (чёрный экран, логотипы, затемнение), кодер не
#: тратит, а копит, и в первый же настоящий кадр вправе высыпать накопленное целиком.
#: Средний битрейт куска при этом честно держится ниже потолка приёмника, а вот
#: СЕКУНДА внутри куска улетает многократно выше - и приёмник спотыкается ровно о неё.
#:
#: Замер (h264 1080p, цель 9.0 Мбит/с, потолок 9.72): худшая секунда куска идёт
#: ``0.9 * bufsize + maxrate`` - буфер 18.00 дал 25.0 Мбит, 9.00 - 17.1, 4.86 - 13.2,
#: 2.25 - 10.7. Прежний буфер был «две секунды цели», то есть кодер копил ровно столько,
#: сколько длится заставка перед первым кадром фильма.
#:
#: Полсекунды выбраны по живому приёмнику, а не на глаз: куски с худшей секундой 15.6 и
#: 16.7 Мбит он играет без запинки (замер), 25.0 Мбит роняет его детерминированно, а
#: этот буфер держит худшую секунду всего фильма в 10.1-13.2 Мбит - внутри доказанно
#: безопасной полосы. Цена замерена там же: кусок легчает на 3-9 %, время перекода то же.
VBV_SECONDS: Final = 0.5

#: Отступ от потолка приёмника, с которым считается цель под кусок (:meth:`Encode.fit`).
#:
#: Не осторожность на глаз, а замер живого показа 11-08: ужатие просило 8.87, 7.32 и
#: 9.00 Мбит/с видео, а наружу уехало 9.65, 8.33 и 10.94 Мбит/с сегмента - до 21 % выше
#: предсказанного по цели. Промах тем больше, чем короче кусок: принудительный опорный
#: кадр на границе сетки стоит одинаково, а амортизируется разной длиной.
FIT_SLACK: Final = 0.9

#: Ниже этого цель не опускаем даже под самый длинный кусок, Мбит/с: смотреть на такое
#: всё равно нельзя, а пропуск места честнее каши на экране.
FIT_FLOOR: Final = 1.0

#: Насколько раньше границы просится принудительный опорный кадр (см. вторую граблю выше).
_KEY_SLACK: Final = 0.02

#: Цепочка «HDR → SDR»: PQ разворачивается в линейный свет, тонемап сжимает динамический
#: диапазон, и картинка собирается обратно уже в BT.709.
#:
#: 🔴 TC-223. Одних выходных меток ``-color_primaries/-color_trc/-colorspace bt709`` тут
#: мало, и это не придирка: метка описывает поток, а не меняет его. Пометить кадр в PQ
#: как BT.709, не преобразовав, - переклеенный ярлык: приёмник растянет кривую не той
#: гамма-характеристикой, и картинка поедет тусклой и серой. Преобразование делает вот
#: эта цепочка, метки после неё - правда.
#:
#: ``npl=100`` - яркость экрана, на которую сводим (кд/м², обычный SDR-телевизор);
#: ``hable`` - кривая, которая не срезает света в белое пятно; ``desat=0`` - без
#: автоматического обесцвечивания ярких мест: оно и даёт тот самый «выцветший» кадр.
TONEMAP: Final = (
    "zscale=t=linear:npl=100,tonemap=tonemap=hable:desat=0,"
    "zscale=t=bt709:m=bt709:p=bt709:r=tv,format=yuv420p"
)
