"""Какие куски прогона дописаны и потому имеют право уехать наружу.

Зовёт её выкладка (:func:`torrcast.adapters.stream_pack.packer_publish._lay_out`), и только она.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from torrcast.adapters.stream_pack.packer_finished import _cuts
from torrcast.domain.hls_settings import PACK_SHORT_SECONDS
from torrcast.ports.journal.slot import journal

if TYPE_CHECKING:
    from torrcast.adapters.stream_pack.packer_state import _State


def done_slots(state: _State, slots: list[int], finished: bool) -> list[int]:
    """Куски прогона, дописанные до конца: до первого, который до конца не дописан.

    Признаков дописанности два, и второй появился здесь.

    Первый - за куском открылся следующий: сегментный муксер открывает новый файл ровно
    тогда, когда закрыл прошлый, а последнему куску такого соседа не будет никогда, и за
    него отвечает ``finished`` (:meth:`torrcast.adapters.stream_pack.packer.Packer.finished`).

    🔴 TC-771. Второй - ПОСЛЕДНИЙ КУСОК СЕТКИ дорезан до конца фильма. Одного соседа ему
    мало, и это не теория: заход, у которого сегментный муксер режет не по нашему списку,
    а по своему умолчанию, закрывает хвост раньше срока и тут же открывает следующий файл
    - то есть первый признак у обрезка выполнен полностью. Замер настоящим ffmpeg на
    заходе в один слот-хвост: вместо 7.884 с / 2 086 048 Б наружу шёл кусок
    2.113 с / 554 788 Б. Лишние куски за пределом захода выкладка отбрасывает сама, а у
    обрезанного ПЕРВОГО и имя, и начало верные - и его не ловил ни один забор, потому что
    длину куска не сверял никто. Зритель терял конец фильма.

    🔴 Сверяется ровно последний кусок сетки, и это не осторожность, а его устройство: его
    закрывает КОНЕЦ ВХОДА, а не рез. Конец входа не двигается ни от чего - ни от докатки,
    ни от места захода, - поэтому недобор у него значит ровно одно: дописать прогон не
    успел. У любого другого куска конец ставит рез, а рез отмеряется от первого пакета
    прогона: заход, вставший не туда, кладёт мимо сетки весь свой участок целиком, куски
    при этом полной длины, и разбирается с этим сверка НАЧАЛА
    (:meth:`torrcast.usecases.warm.verify._verify`,
    :func:`torrcast.usecases.feed_pack.feed_segment._warm`) - она умеет и переложить место, и
    честно объявить его непрогретым. Суди мы такой кусок ещё и здесь, заход не выкладывал бы
    ничего, сверке начала было бы нечего смотреть, и вместо переклада вышел бы вечный круг
    «прогрев не дал ни куска».

    Где кусок закрылся на самом деле, говорит сам ffmpeg в своём списке нарезки
    (:func:`_cuts`, ``-segment_list_flags +live``): он пишет абсолютный конец каждого
    закрытого куска и сходится с замером по пакетам в пределах 0.04 с. Метки в списке уже
    сдвинуты на начало ленты (:attr:`torrcast.adapters.stream_pack.grid.Grid.origin`),
    поэтому сдвиг вычитается - иначе на каждом релизе с B-кадрами «недобор» показывал бы
    ровно его.

    Допуск :data:`PACK_SHORT_SECONDS` тот же, которым :func:`_reached` отличает обрыв от
    конца фильма, и он замерен: законный недобор последнего куска - 0.000-0.065 с, обрыв
    даёт 0.6-10.0 с.

    ⚠️ Чего эта мера не видит: куска, о котором в списке нарезки строки НЕТ вовсе. Такой
    кусок уходит наружу по-прежнему. Молчание списка - не признак обрезка: список читается
    с диска, и отказ чтения обнулил бы его целиком, то есть остановил бы выкладку насмерть
    там, где всё в порядке. Сетки у прогона может не быть вовсе (:attr:`_State.grid`) -
    тогда сверять не с чем и мера молчит.
    """
    done = slots if finished else slots[:-1]
    grid = state.grid
    if grid is None:
        return done
    tail = grid.count - 1
    # Ниже своего первого - докатка, выше последнего - обрезок за ``-to``: и то и другое
    # выкладка отбрасывает сама, и судить их длиной незачем.
    if tail not in done or tail < state.first or 0 <= state.last < tail:
        return done
    end = {slot: over for slot, _began, over in _cuts(state)}.get(tail)
    if end is None or end - grid.origin >= grid.end(tail) - PACK_SHORT_SECONDS:
        return done
    journal().mark(
        "хвост короче своей границы",
        слот=tail,
        граница=round(grid.end(tail), 3),
        замер=round(end - grid.origin, 3),
    )
    return done[: done.index(tail)]
