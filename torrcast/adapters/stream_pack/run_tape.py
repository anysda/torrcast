"""Лента прогона: на сколько счётчик каждой дорожки отстоит от времени фильма.

Меряет её выкладка упаковщика (:mod:`torrcast.adapters.stream_pack.packer_publish`) один раз
на прогон, а спрашивает место слота (:func:`torrcast.adapters.stream_pack.slot_place.slot_place`).
"""

from __future__ import annotations

import math
from typing import TYPE_CHECKING

from torrcast.adapters.stream_pack.piece_with_head import piece_with_head
from torrcast.domain.segment_container import FMP4

if TYPE_CHECKING:
    from collections.abc import Callable
    from pathlib import Path

    from torrcast.adapters.stream_pack.packer_state import _State


def run_tape(
    state: _State,
    slot: int,
    piece: Path,
    head: Path | None,
    starts_of: Callable[[str | Path], tuple[float, float]],
) -> tuple[float, float] | None:
    """Отступ лент картинки и звука от времени фильма; ``None`` - мерить было не по чему.

    🔴 Ради этого написано. На mpegts метка куска - это время фильма: оба захода пакуют одну
    ленту (``-copyts`` и общий :attr:`~.grid.Grid.origin`), и место слота сверяется с меткой
    напрямую. На CMAF это неправда. Муксер mp4 начинает счёт КАЖДОЙ дорожки со своего первого
    сэмпла, и метка куска - не время фильма, а счётчик прогона. Живой замер («Матрица:
    Революция», прогон с 1:42:14, куски подряд): звук идёт 0, 476160, 954368, 1432576,
    1911808, 2390016 тиков по 1/48000, то есть ровно по длине куска, а картинка ТОГО ЖЕ куска
    стоит на 10.0 с дальше звука - у дорожек не только свой счёт, но и свой ноль.

    Поэтому лент две, и мерить их надо, а не выводить: ноль картинки уезжает на докатку
    (ffmpeg читает с опорного кадра не позже нужного места), ноль звука - на первый
    написанный звуковой сэмпл, и оба зависят от того, что муксер успел написать до первого
    выложенного куска. Пока место слота сверялось с меткой напрямую, проверка отказывала
    КАЖДОЙ склейке на CMAF: живой промах -6204.457 / -6214.425 / -6234.362 с - ровно место
    куска на фильме, - и отказывала она при этом верно.

    ``piece`` - кусок, про который известно, где он стоит: первый, который прогон выложил
    наружу. Читается он вместе с заголовком показа: голый фрагмент не открывается ничем.

    ⚠️ Чего этот замер не видит: сам опорный кусок он берёт на веру. Прогон, у которого
    нумерация файлов разъехалась С САМОГО НАЧАЛА, даст ленту, сдвинутую вместе с ним, и
    проверка места примет такой прогон целиком. Ловится этим замером то, ради чего проверка и
    заведена (TC-833): рез, пропущенный муксером ПОСРЕДИ прогона, - он двигает нумерацию
    дальше опорного куска, и промах выходит в целый слот, то есть на два порядка шире порога.

    ``None`` - сетки у прогона нет вовсе или хоть одной дорожки в опорном куске не нашлось:
    считать ленту по одной дорожке нельзя. Тогда прогон меряет её следующим выложенным
    куском, а до тех пор место склейки не проверяется.
    """
    if state.grid is None:
        return None
    # На mpegts мерить нечего: метки там - время фильма, поднятое общим origin.
    if state.container != FMP4:
        return state.grid.origin, state.grid.origin
    picture, sound = starts_of(piece_with_head(piece, head))
    place = state.grid.start(slot)
    if math.isnan(picture) or math.isnan(sound) or math.isnan(place):
        return None
    return picture - place, sound - place
