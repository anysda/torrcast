"""Заголовок своего прогона у куска: у показа два производителя картинки, а он один.

Зовёт это выкладка упаковщика (:mod:`torrcast.adapters.stream_pack.packer_publish`).
"""

from __future__ import annotations

import contextlib
import shutil
from typing import TYPE_CHECKING, Final

from torrcast.adapters.stream_pack.chunk_head import INIT, chunk_head
from torrcast.domain.cmaf_body import cmaf_body
from torrcast.domain.head_name import head_name
from torrcast.domain.hls_settings import HEAD_SENT
from torrcast.domain.segment_container import FMP4
from torrcast.domain.segment_suffix import segment_suffix

if TYPE_CHECKING:
    from pathlib import Path

    from torrcast.adapters.stream_pack.packer_state import _State

#: Исход выкладки, у которого картинка взята из потока исходника, а не от кодировщика.
#: 🔴 Ярлык внутренний ("copy"), не надпись человеку: сравнивается строкой с тем же
#: "how", каким его вернул :func:`torrcast.adapters.stream_pack._merged_out._merged_out`
#: и каким его сравнивает :mod:`torrcast.adapters.recode.note`.
_COPY: Final = "copy"

#: Сколько байт от начала куска хватает, чтобы увидеть его заголовок: у показа он
#: полторы тысячи байт, и читать ради этого весь кусок незачем.
_HEAD_PEEK: Final = 64 << 10


def _carried(source: Path) -> bytes:
    """Заголовок, который кусок уже несёт в себе; пусто - кусок голый, как все соседи.

    Несёт его ровно один исход выкладки - склейка
    (:func:`torrcast.adapters.stream_pack.merge_tracks.merge_tracks`): муксер собирает её
    самостоятельным файлом. Форма у такого куска ровно та же, что приставляет это место
    само, - ``ftyp moov moof mdat``, - а заголовок вернее любого соседского: его написал
    тот же прогон ffmpeg, что и сам кусок, поэтому описывает он именно эти байты.
    """
    try:
        with source.open("rb") as fh:
            head = fh.read(_HEAD_PEEK)
    except OSError:
        return b""
    at = cmaf_body(head)
    return head[:at] if at > 0 else b""


def _own_head(state: _State, slot: int, source: Path, how: str) -> Path:
    """Кусок, у которого параметры декодера верны: свой заголовок рядом или впереди.

    🔴 Один общий ``init.mp4`` на весь CMAF-показ держится на том, что все куски сделаны
    одним кодировщиком с одними параметрами, - а у показа их двое. Копия отдаёт битстрим
    исходника, кодировщик пишет свой, и живой замер разводит их поимённо: копия
    ``profile 77 Main, level 40, SPS 29 Б`` против перекода ``profile 66 Baseline,
    level 41, SPS 24 Б``. Приёмник настраивает декодер по общему заголовку и получает
    кадры, которые ему не отвечают: ``Selected MediaCodecVideoDecoder ... profile: h264
    main`` на кадрах Baseline, и дальше сплошные ошибки картинки на каждом ужатом месте.

    Лечится это ровно одним доводом - заголовком ТОГО прогона, который сделал картинку
    этого куска. Замер парный и живой: 3x3 на приставке, один релиз, порядок уравновешен,
    у каждой стороны свой отпечаток УСТАНОВЛЕННОГО пакета, у всех шести прогонов одна и та
    же работа - 34 куска копией и 3 ужатых. Сухая проба до этого причины не доказывала: у
    приёмника свой декодер, и «стало ровно» не равно «перестал голодать».

    ===================  ====================  ======================  ============
    код                  ошибок картинки       плёнки потеряно, с      голод ЗВУКА
    ===================  ====================  ======================  ============
    общий заголовок      12 / 15 / 13          42.0 / 42.1 / 38.0      5 / 5 / 5
    свой заголовок        0 /  0 /  0          41.8 / 50.4 / 48.4      3 / 3 / 3
    ===================  ====================  ======================  ============

    Ошибки картинки уходят в ноль, и все они до одной лежали на ужатых местах. Платит за
    это не звук, а картинка на самих стыках: пустой буфер КАРТИНКИ 1/1/1 против 4/3/3 -
    столько раз декодер пересобирается по замыслу. Разница плёнки лежит там же, у ужатых
    мест (39.2-39.4 с против 38.7-44.4 с), а не на копиях (7.0-6.5 с против 8.2-8.6 с), и
    голод звука на копиях не тронут вовсе: 1/1/1 обеими сторонами.

    ⚠️ Прежнее лечение той же беды - самодостаточные куски (``-individual_header_trailer
    1``) - отменено замером и сюда не возвращается: свой ``moov`` со своим списком правок
    у КАЖДОГО куска рвал разбор звука на границе, и парный прогон 3x3 насчитал 28/30/27
    голоданий демуксера и 134.7/134.4/134.7 с потерянной плёнки из 300 против нулей у
    общего заголовка. Платили при этом все копирующие куски, а ужатые - меньшинство.

    Здесь заголовок меняется ТОЛЬКО там, где сменился производитель картинки, и меняется
    он не абы каким: заголовки обоих прогонов пишет один муксер с одними ключами, и
    сравнение боксов показывает единственную разницу - визуальную запись ``avc1``.
    Звуковая дорожка, тайм-скейлы, ``mvex`` и списки правок у них побайтно одни и те же,
    поэтому граница звука о смене заголовка не знает вовсе.

    Обязанностей у этого места две, и делит их :attr:`~.packer_state._State.spare`:

    * прогон кодировщика (``spare`` пуст: наружу он не выкладывает, он готовит куски
      для чужой выкладки) оставляет рядом с каждым своим куском свой заголовок. Иначе
      его не найти: заходов у кодировщика много, пресет у них торгуется по сроку, а
      ``ultrafast`` и ``veryfast`` дают РАЗНЫЕ параметры картинки;
    * выкладка показа (``spare`` назван) приставляет заголовок впереди куска, когда он
      не тот, что был у предыдущего места, и записывает рядом, с каким заголовком место
      уехало (:data:`~torrcast.domain.hls_settings.HEAD_SENT`) - соседу отвечает она.

    🔴 «Что было у предыдущего места» спрашивается у ДИСКА, а не у памяти прогона, и это
    не мелочь: прогон упаковки начинается заново на каждой перемотке, а приёмник помнит
    последний заголовок и через перемотку. Память прогона тут врала бы ровно в том
    случае, ради которого всё написано, - на перемотке в место сразу за ужатым.
    """
    if state.container != FMP4:
        return source
    if state.spare is None:
        with contextlib.suppress(OSError):
            shutil.copyfile(chunk_head(state, slot, spare=False), state.out / head_name(slot))
        return source
    # Кусок со своим заголовком приставлять не к чему: он уже той формы, ради которой всё
    # это. Но соседу ответить обязано и оно - иначе следующее место сочтёт декодер
    # настроенным прошлым заголовком и уедет к приёмнику без своего.
    carried = _carried(source)
    if carried:
        with contextlib.suppress(OSError):
            (state.spare / head_name(slot, HEAD_SENT)).write_bytes(carried)
        return source
    own = chunk_head(state, slot, spare=how != _COPY)
    kept = state.spare / head_name(slot - 1, HEAD_SENT)
    known = kept.exists()
    before = kept if known else state.out / INIT
    try:
        now, was = own.read_bytes(), before.read_bytes()
    except OSError:  # заголовка нет ни у кого - показ идёт как шёл
        return source
    if not now:
        return source
    # 🔴 «Что было у предыдущего места» - это вопрос про ВЫЛОЖЕННОЕ, и отвечать на него
    # обязана запись самой выкладки. Готовый кусок кодировщика на него не отвечает:
    # перекод доезжает и ПОСЛЕ того, как место уехало копией (ровно этот случай назван в
    # :func:`~.._shrunk_out._shrunk_out`), и тогда его заголовок лежал бы за местом,
    # которого он не делал. Соседнее ужатое место сочло бы декодер настроенным собой и
    # уехало бы под чужим заголовком - то есть ровно с той бедой, ради которой всё это.
    with contextlib.suppress(OSError):
        (state.spare / head_name(slot, HEAD_SENT)).write_bytes(now)
    # Первое место прогона: записи о предыдущем нет и взяться ей неоткуда - упаковка
    # начинается заново на каждой перемотке, а прыгнуть можно и в место сразу за ужатым.
    # Тогда заголовок приставляется без сравнения: лишняя пересборка декодера стоит кадра,
    # а недостающая - всего показа. Там, где кодировщик не поднимался ни разу, сравнивать
    # не с чем и приставлять нечего: у показа из одних копий производитель картинки один.
    blind = not known and slot == state.first and (state.spare / INIT).exists()
    if now == was and not blind:
        return source
    headed = state.run / head_name(slot, segment_suffix(state.container))
    try:
        headed.write_bytes(now + source.read_bytes())
    except OSError:
        headed.unlink(missing_ok=True)
        return source
    return headed
