"""Кладёт наружу общий заголовок показа; зовёт его лента показа."""

from __future__ import annotations

import os
import shutil
from pathlib import Path


def lay_head(head: Path, out: Path) -> None:
    """Положить общий заголовок показа рядом с кусками, если его там ещё нет.

    Манифест называет заголовок (``EXT-X-MAP``), и приёмник берёт его ПЕРВЫМ, до всякого
    куска: без него разбор не начинается вовсе - живой замер на приставке, 32 скачанных
    куска, ноль картинки, позиция 0:00:00.

    Обычно заголовок кладёт в каталог показа сама упаковка, одним файлом на весь прогон
    (:func:`torrcast.adapters.ffmpeg.pack_command.pack_command`). Отсюда он берётся тогда,
    когда живая упаковка не поднимется вовсе, - на прогретом фильме с мёртвым источником.

    Уже лежащий заголовок не переписывается: приёмник читает его один раз, на старте
    показа, и разойтись с кусками, которые уже уехали, ему нельзя.
    """
    init = out / "init.mp4"
    if init.exists():
        return
    # Через временное имя: полузаписанный заголовок стоил бы приёмнику всего показа,
    # а перечитывать его он не станет.
    laying = out / "init.mp4.part"
    try:
        shutil.copyfile(head, laying)
        os.replace(laying, init)
    except OSError:
        laying.unlink(missing_ok=True)
