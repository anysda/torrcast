"""Поля одного прогона упаковки и их цена.

Наследует их :class:`torrcast.adapters.stream_pack.packer.Packer`, и только он.
"""

from __future__ import annotations

import threading
import time
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Protocol, TypeAlias

from torrcast.domain.profile import CAUTIOUS
from torrcast.domain.segment_container import MPEGTS, SegmentContainer
from torrcast.ports.feed_grid import FeedGrid

#: Кого позвать, когда сегмент ушёл наружу: ``(слот, чем он ушёл)``.
_Told: TypeAlias = Callable[[int, str], None]
#: Кого спросить про кусок по его весу: ``(слот, вес копии) -> bool``.
_Asked: TypeAlias = Callable[[int, int], bool]
#: Ужатие: ``True`` - сделано, ``None`` - перекод доехал сам, ``False`` - пропуск.
_Shrink: TypeAlias = Callable[[int, int], bool | None]


class _Process(Protocol):
    """Процесс ffmpeg в том объёме, в каком его знает прогон упаковки.

    ``send_signal`` тут не для самого прогона: сигналами процессу распоряжаются соседи -
    прогрев (:func:`torrcast.usecases.warm.throttle._throttle`) и кодировщик, - и назван
    он ровно затем, чтобы их договор не держался на `Any`.
    """

    def poll(self) -> int | None: ...
    def wait(self, timeout: float | None = None) -> int: ...
    def terminate(self) -> None: ...
    def kill(self) -> None: ...
    def send_signal(self, number: int) -> None: ...


class _Spool(Protocol):
    """Куда ffmpeg пишет свою ругань: временный файл этого прогона."""

    def seek(self, offset: int) -> int: ...
    def read(self) -> bytes: ...


@dataclass(slots=True)
class _State:
    """Всё, что прогон упаковки знает про себя: процесс, каталоги, край и потолки."""

    proc: _Process
    out: Path
    #: Каталог этого прогона: сюда ffmpeg кладёт куски, включая мусорную докатку.
    run: Path
    #: С какого сегмента сетки начат этот прогон: всё, что раньше, паковал не он.
    first: int = 0
    #: **Честный край прогона**: последний сегмент, который ЭТОТ прогон выложил наружу
    #: (:meth:`publish`). ``first - 1`` - не выложено ещё ничего.
    #:
    #: Ровно это число, а не глоб каталога (:meth:`frontier`), отвечает на вопрос «кусок
    #: вот-вот допакуется или его не будет вовсе» (:meth:`Feed._steer`). Разница не
    #: теоретическая: в каталоге показа лежат и куски прошлых прогонов - сетка одна на
    #: весь показ, поэтому они честные и отдаются приёмнику, - но к тому, докуда дошёл
    #: текущий прогон, они отношения не имеют. Глоб путал одно с другим в обе стороны:
    #: «край» уезжал вперёд на чужие куски (запрос далеко назад считался ожиданием и
    #: висел до 404) и назад на свежий каталог (замер: 20 ложных перезапусков
    #: за 100 с показа). Здесь край растёт только там, где мы сами переименовали файл, -
    #: и там, где прогон честно решил, что куска не будет никогда (:attr:`shrink`).
    edge: int = -1
    log: _Spool | None = None
    #: Выкладка может прийти из запроса приёмника и из часов показа одновременно.
    #: Второй заход не ждёт первый: горячий путь проверит готовый файл следующим
    #: оборотом, а два решения над одними исходниками опаснее пропущенного опроса.
    publish_lock: threading.Lock = field(default_factory=threading.Lock)
    #: Упаковку погасили намеренно (пауза на пульте) - смерть процесса не авария.
    halted: bool = False
    #: Зачем мы сами сняли этот прогон (:meth:`stop`); пусто - мы его не трогали.
    #:
    #: ⚠️ Без этой строки собственный ``terminate`` неотличим от аварии: ffmpeg по SIGTERM
    #: выходит **кодом 255** (положительным!), а «Exiting normally, received signal 15» он
    #: пишет уровнем ``info``, то есть при нашем ``-loglevel warning`` не пишет ничего.
    #: Ровно так и родился 🔴 «первый прогон следующей серии умирает молча»:
    #: показ ругался на труп, который сам же и снял.
    stopped: str = ""
    #: Обрыв ЭТОГО прогона уже посчитан (:meth:`Feed._survive`).
    blamed: bool = False
    #: Каталог перекодированных кусков. Если для слота там лежит готовый кусок,
    #: наружу идёт он, а копия выбрасывается: место в фильме и метки те же, а битрейт
    #: такой, который приёмник гарантированно тянет.
    #:
    #: Выкладка остаётся ровно здесь, вторым выкладывающим кодировщик не становится -
    #: иначе инвариант «край двигает только состоявшееся переименование» (:attr:`edge`)
    #: пришлось бы держать в двух местах.
    spare: Path | None = None
    #: Кого позвать, когда сегмент ушёл наружу: ``(слот, чем он ушёл)``.
    #:
    #: «Чем» - это ``копия``, ``склейка`` (картинка перекода со звуком копии),
    #: ``перекод`` (склейка не вышла) или ``ужатие`` (кусок ужат на месте самой
    #: выкладкой, склеивать было нечего и не с чем). Различать их обязательно: раньше
    #: в журнал шло одно слово «перекод» на два разных исхода, и «склейка молча не
    #: вышла» нельзя было ни увидеть, ни опровергнуть - три подвиса на сериале
    #: разбирались вслепую.
    told: _Told | None = None
    #: Последний сегмент, который этому прогону разрешено выложить; ``-1`` - без предела.
    #:
    #: ⚠️ Нужно ровно кодировщику и ровно против ОБРЕЗКА. Заход кодировщика ограничен
    #: ``-to`` с запасом в секунду (:func:`ffmpeg_pack_command`), и на этот запас муксер
    #: успевает открыть СЛЕДУЮЩИЙ файл - в нём остаётся секунда фильма вместо десяти.
    #: Дальше этот огрызок лежал в :data:`torrcast.adapters.recode.recode_dir.RECODE_DIR` как
    #: готовый кусок и выкладывался наружу вместо честной копии: живой Q70D на «Тачках 3» - ``v311``
    #: 1.3 МБ вместо 11 МБ, приёмник встал на 8 с и потерял 8 секунд фильма. У «Моаны 2» это не
    #: всплывало: там тяжелы почти все куски подряд, и огрызок всегда успевал смениться настоящим
    #: перекодом следующего захода.
    last: int = -1
    #: Когда прогон начался (``time.monotonic``) и с какой секунды ФИЛЬМА ffmpeg читает
    #: вход (``-ss``, то есть с учётом докатки). Вместе с :attr:`rate` и :attr:`burst` это
    #: и есть планка чтения ffmpeg, по которой считается :meth:`eta`.
    began: float = 0.0
    #: Монотонные часы прогона. Полем, а не именем :mod:`time` внутри модуля: замер
    #: «через сколько ffmpeg дочитает вход» (:meth:`eta`) идёт по стенным секундам, и
    #: стенду нужна ручная стрелка, а не терпеливость машины.
    now: Callable[[], float] = time.monotonic
    at: float = 0.0
    #: ``-readrate`` и ``-readrate_initial_burst`` этого прогона; ноль - читаем без темпа.
    rate: float = 0.0
    burst: float = 0.0
    #: Сетка показа: по ней прогон паковали, по ней же сверяется, дописан ли последний
    #: кусок (:meth:`finished`). ``None`` - сверять не с чем, и слово ffmpeg остаётся
    #: единственным признаком.
    grid: FeedGrid | None = None
    #: Ответ :meth:`finished`, посчитанный один раз; ``None`` - ещё не считали.
    whole: bool | None = None
    #: Кого спросить «этот кусок сейчас перекодируют, подожди»: ``(слот, вес копии) -> bool``.
    #:
    #: Нужно ровно против одной гонки, найденной живым прогоном: упаковщик на
    #: старте прогона выкладывает ``burst`` (60 с) разом, а кодировщику на эти же 60 с
    #: нужно вдвое меньше, но не мгновение, - и тяжёлые куски уходили копией просто
    #: потому, что упаковщик их обогнал. Придержанный кусок никуда не девается: он лежит
    #: в каталоге прогона и выложится либо перекодированным, либо как есть по истечении
    #: срока. Ждать при этом безопасно только там, докуда показу ещё далеко, - за этим
    #: следит спрашиваемый (:meth:`torrcast.adapters.recode.recoder.Recoder.holding`).
    hold: _Asked | None = None
    #: Кого позвать на последнем гейте, когда кусок тяжелее потолка приёмника, а ждать
    #: перекод уже не стали: ``(слот, вес копии) -> bool``. ``True`` - в :attr:`spare`
    #: лежит свежий перекод под потолок, и наружу идёт он. ``False`` - ужать не вышло:
    #: место честно пропускается, но выкладка идёт дальше. ``None`` - решать некому,
    #: выкладка встаёт на таком куске (поведение до TC-467).
    #:
    #: Без этого звонка тяжёлая копия останавливала выкладку навсегда: ``break`` не
    #: двигал край и не удалял саму копию, а всё за ней копилось в памяти до потолка
    #: несданного; потолок гасил прогон, запрос приёмника поднимал его заново - и круг
    #: повторялся, потому что тяжёлый кусок детерминирован.
    shrink: _Shrink | None = None
    #: Потолок веса куска этого приёмника. Последний гейт обязан мерить ровно им:
    #: здесь уже известен вес файла после склейки, которого не видел каталог перекода.
    cap: int = CAUTIOUS.max_segment_bytes
    container: SegmentContainer = MPEGTS
    #: Лента прогона: на сколько счётчик каждой дорожки отстоит от времени фильма
    #: (:func:`torrcast.adapters.stream_pack.run_tape.run_tape`). ``None`` - ещё не мерили.
    #:
    #: 🔴 Полем прогона, а не числом на каждый кусок: на CMAF метка куска - счётчик муксера,
    #: и начинается он там, где этот прогон написал первый сэмпл дорожки. То есть лента -
    #: свойство прогона, и меряется она один раз, по первому же выложенному куску; считать
    #: её заново на каждой склейке значило бы спрашивать проверяемый кусок о нём самом.
    tape: tuple[float, float] | None = None

    def __post_init__(self) -> None:
        # Прогон, который ещё ничего не выложил, стоит ровно перед своим первым сегментом:
        # так «край» и «ниже края» осмысленны с первой же секунды, до всякого publish.
        self.edge = max(self.edge, self.first - 1)
