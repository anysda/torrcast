"""Заголовок, вырезанный из самодостаточного куска; спрашивает выкладка упаковщика."""

from __future__ import annotations

from pathlib import Path

#: Коробка, с которой начинаются данные куска: всё до неё - и есть заголовок.
_MEDIA = b"moof"
#: Дальше этого заголовка в куске не бывает: обычный - около полутора килобайт.
_LIMIT = 1 << 16


def segment_head(piece: Path) -> bytes:
    """Начало куска до первых данных: ``ftyp`` и ``moov``; пусто - вырезать нечего.

    Кусок fMP4 у нас самодостаточен (:func:`torrcast.adapters.ffmpeg.pack_command.pack_command`):
    свой заголовок он несёт сам, и приёмник разбирает каждый кусок теми параметрами,
    которыми тот и закодирован. Но манифест обязан назвать общий заголовок показа
    (``EXT-X-MAP``), и приёмник берёт его ПЕРВЫМ, до всякого куска: без него разбор не
    начинается вовсе - живой замер на приставке, конвейер стоит в ``kStarting``, а куски
    он при этом качает.

    Брать этот общий заголовок неоткуда, кроме как из самого куска: сегментный муксер
    пишет заголовок либо в отдельный файл, либо в каждый кусок, но не в оба места сразу
    (замер по всем четырём сочетаниям флагов). Годится любой: каждый кусок дальше
    переопределяет параметры собой.

    Читается это разбором таблицы коробок - того самого оглавления, которым формат и
    задан: подряд идут ``размер`` и ``имя``, и первая же ``moof`` открывает данные.
    """
    head = bytearray()
    try:
        with piece.open("rb") as handle:
            while len(head) < _LIMIT:
                box = handle.read(8)
                if len(box) < 8:
                    return b""
                size = int.from_bytes(box[:4], "big")
                if box[4:] == _MEDIA:
                    return bytes(head)
                if size < 8:
                    return b""
                head += box + handle.read(size - 8)
    except OSError:
        return b""
    return b""
