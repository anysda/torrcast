"""Карта опорных кадров этого файла разошлась с нарезкой; говорит лента показа."""

from __future__ import annotations

from torrcast.adapters.pack_memory import _MAP_LIED, _SEEK_LOCK


def map_lied(source_url: str) -> None:
    """Запомнить, что карта этого файла врёт: дальше по нему только пробный прогон.

    🔴 TC-133. Вторая половина правила, первая -
    :func:`torrcast.adapters.stream_pack.map_trusted.map_trusted`. Порознь они
    бессмысленны: место захода берётся из карты даром ровно потому, что промах карты
    выходит наружу измеримо и лечится перезаходом.

    Навсегда в пределах процесса, и это не строгость, а цена ошибки: карта, разошедшаяся
    с потоком, уводит ВСЕ резы захода разом (замер репы: карта, соврав на 4.0 с, дала
    ``drift`` ровно 4.000 с при 0.000-0.006 с у здорового прогона), и куски ложатся под
    верными именами с чужим содержимым. Второй такой же разъезд означал бы уже не врущую
    карту, а больной источник, и лечить его перезаходами бессмысленно.
    """
    with _SEEK_LOCK:
        _MAP_LIED.add(source_url)
