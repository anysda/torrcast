"""Верить ли карте опорных кадров на этом файле; спрашивает заход упаковки."""

from __future__ import annotations

from torrcast.adapters.pack_memory import _MAP_LIED, _SEEK_LOCK


def map_trusted(source_url: str) -> bool:
    """Можно ли брать место захода из карты, не поднимая пробного прогона.

    🔴 TC-133. Верится карте сразу, а не после сверки пробным прогоном: место посадки она
    считает за микросекунды (замер репы: 1.6-10.9 мкс), а прогон стоит 0.029 с даже на
    файле в tmpfs и 0.042 с на петле по http - и стоит их на пути к первой картинке.

    Сверка при этом никуда не делась, она переехала с предсказания на ФАКТ: нарезанное
    сверяется с манифестом, и заход, разъехавшийся с ним, перезапускается уже пробным
    прогоном (:func:`torrcast.usecases.feed_pack.feed_astray._astray`). Снимает доверие
    поэтому не упаковка, а лента показа - она одна видит нарезку
    (:func:`torrcast.adapters.stream_pack.map_lied.map_lied`).
    """
    with _SEEK_LOCK:
        return source_url not in _MAP_LIED
