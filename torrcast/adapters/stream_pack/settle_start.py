"""Отводит заход назад, пока он не встанет не позже границы; спрашивает упаковка."""

from __future__ import annotations

from collections.abc import Callable
from typing import Final

from torrcast.adapters.stream_pack.pack_start import pack_start
from torrcast.domain.film_keys import FilmKeys
from torrcast.domain.hls_settings import HLS_SEGMENT_SECONDS, SPLIT_SLACK
from torrcast.domain.hls_wait import PILOT_TIMEOUT
from torrcast.ports.journal.slot import journal

#: Сколько раз заход отводится назад, прежде чем остаться там, куда встал сам.
#:
#: Отвод удваивается на каждом шаге, начиная с шага сетки, - четыре шага накрывают 80 с
#: плёнки, в которых демуксеру не за что зацепиться. Замер на живой раздаче (h264 1080p,
#: индекс отвергнут как врущий, 60 границ подряд): самый широкий провал между двумя
#: местами, куда демуксер вообще соглашается сесть, - 61.7 с (393.161 и 454.921), и
#: четвёртый шаг его накрывает. Шире провал - отвод сдаётся, и заход остаётся прежним:
#: платить пятым и шестым пробным прогоном за фильм, в котором перемотка мертва
#: целыми минутами, дороже самой дыры.
SEEK_BACK_TRIES: Final = 4


def settle_start(
    source_url: str,
    at: float,
    timeout: float = PILOT_TIMEOUT,
    keys: FilmKeys | None = None,
    *,
    start: Callable[..., float] = pack_start,
) -> tuple[float, float]:
    """С какого ``-ss`` заходить и где прогон встанет, чтобы не проскочить ``at``.

    Заход, вставший ПОЗЖЕ границы, не производит плёнку между границей и собой вовсе.
    Сегментный муксер отмеряет резы от первого пакета прогона, поэтому кусок под именем
    границы начинается тем, что прогон прочитал первым, - и приёмник упирается в дыру.
    Живой замер (h264 1080p, ровная сетка 10 с, приставка): граница 450.0, заход встал на
    454.921, зритель потерял 2.71 с плёнки, а демуксер приёмника сказал
    ``DEMUXER_UNDERFLOW`` и перепрыгнул дыру перемоткой на 449.989 - 3.249 с.

    Лечится это тем же, чем показ живёт на здоровом файле: ``-ss`` ставится РАНЬШЕ
    границы, прогон заходит с докатки, и кусок границы режется уже внутри непрерывного
    потока. Докатку выкладка не отдаёт наружу никогда (она короче своего места в
    манифесте), поэтому цена отвода - только чтение: до 80 с плёнки сверх нужного, и
    первые 60 из них прогон читает на полной скорости
    (:attr:`torrcast.domain.profile.Profile.burst`).

    Отводится заход только тогда, когда пробный прогон показал уезд ВПЕРЁД. На здоровом
    файле ``-ss`` уводит демуксер назад, докатка и так есть, и ни одного лишнего прогона
    тут не поднимается: замер на той же раздаче - 5 границ из 60 садятся назад, и все
    пять уходят отсюда первым же ответом.

    Шаг отвода начинается с уезда, но не меньше шага сетки, и дальше удваивается: место,
    куда демуксер соглашается сесть, от границы своей меркой не отмеряется, и ближний
    отвод часто приводит ровно туда же (замер: ``-ss`` 400, 410, ..., 450 - все шесть
    дают 454.921).

    ``start`` - чем меряется место посадки. Доводом, а не именем внутри модуля: настоящий
    замер поднимает ffmpeg на живой раздаче, а здесь меряется само правило отвода - на
    сколько отходим, сколько раз спрашиваем и что отдаём, когда отойти не вышло.
    """
    stood = start(source_url, at, timeout, keys)
    if stood <= at + SPLIT_SLACK:
        return at, stood
    back = max(stood - at, HLS_SEGMENT_SECONDS)
    for _ in range(SEEK_BACK_TRIES):
        seek = max(0.0, at - back)
        found = start(source_url, seek, timeout, keys)
        if found <= at + SPLIT_SLACK:
            journal().mark(
                "заход отведён от границы",
                граница=round(at, 3),
                отвод=round(at - seek, 3),
                встали=round(found, 3),
            )
            return seek, found
        if seek <= 0.0:
            break
        back *= 2.0
    journal().mark("отвести заход от границы не вышло", граница=round(at, 3), замер=round(stood, 3))
    return at, stood
