"""Предсказывает по карте, куда встанет ffmpeg после ``-ss``; сверяет его пробный прогон."""

from __future__ import annotations

import bisect
import math
from typing import Final

from torrcast.domain.film_keys import FilmKeys
from torrcast.domain.warm_open import SEEK_SHIFT

#: Пыль при сравнении цели с меткой кадра, секунды. Цель захода печатается в команду
#: ffmpeg с тремя знаками (``-ss %.3f``) - и пробным прогоном, и упаковкой - а метка в
#: карте читается из таблиц контейнера с float-пылью (замер TC-695: кадр 131.063
#: встаёт в карту как 131.06300000000002). Микросекунда в сотни раз шире этой пыли и
#: в сотни раз уже настоящего суб-мс остатка у релиза (у mp4: опорный кадр 373.206167,
#: и ``-ss 373.206`` встаёт на ПРЕЖНИЙ кадр, а не на него).
SEEK_EPS: Final = 1e-6


def mapped_start(keys: FilmKeys | None, at: float) -> float:
    """Куда встанет ffmpeg после ``-ss at`` — **по карте опорных кадров**. Не знаем — ``nan``.

    Гадания тут нет: перемотку ведёт тот же индекс контейнера, из которого снята карта
    (``Cues`` у mkv, ``stss`` у mp4), поэтому место посадки — это соседняя строка той же
    таблицы. Внутри GOP оба демуксера садятся одинаково — на **последнюю строку не позже**
    запрошенного (замер TC-695, GOP 7.28 с: ``-ss 110.000`` → 109.200 и в mkv, и в mp4,
    и в их remux). Разница демуксеров (:data:`SEEK_SHIFT`) играет только при попадании
    РОВНО в кадр карты: mkv уезжает на предыдущий (dts-эвристика ffmpeg опускает цель
    ниже кадра на задержку перестановки, то самое «через один» на «Моане» 2016:
    ``-ss 66.150`` → 62.688), mp4 стоит ровно на нём.

    Цель сравнивается с картой как ``float(f"{at:.3f}")``, а не как есть: именно с тремя
    знаками её печатают и пробный прогон, и команда упаковки, и у релиза с суб-мс метками
    (замер TC-695 на настоящем mp4: опорный кадр 373.206167) округление решает, на какой
    кадр сядет заход, — округлилась вниз, и ffmpeg встаёт на ПРЕЖНИЙ опорный кадр.

    ⚠️ Окно в первые ~0.15 с после опорного кадра карте неподвластно: там mkv с B-кадрами
    ещё садится на предыдущий (та же dts-эвристика плюс набивка звука), а без B-кадров —
    уже на него. Карта про B-кадры не знает, и угадывать не пробует: это поймает сверка
    (:func:`pack_start`) — один пробный прогон на файл, а не на каждый заход.

    Симметричное окно есть и у mp4 без списка правок, только ПЕРЕД кадром: индекс такого
    файла стоит на времени декодирования, и ``-ss`` в полосе ``ctts`` перед кадром садится
    на сам кадр. Это окно карте ИЗВЕСТНО - оно закрыто исковым временем (``via``), которое
    для такого файла несёт dts; без него предсказание промахивалось бы на опорный кадр,
    и заход по карте на границу клал бы куски с чужим содержимым под именем места.

    ``nan`` отдаётся везде, где правило не обязано работать, и каждый случай стоит своих
    трёх строк:

    * контейнера нет в :data:`SEEK_SHIFT` (карта из кэша прошлой версии, .ts) — правила нет;
    * карта пустая или ``at`` за её краями — соседней строки просто не существует;
    * посадка приходится на самое начало файла — там ffmpeg не пускает dts ниже нуля и
      сдвигает метки на кадр-два вперёд (замер: карта обещает 0.000, факт 0.080), то есть
      единственное место, где карта права, а ffmpeg встаёт не по ней.

    ⚠️ Это предсказание, а не факт: пока оно не сверено с пробным прогоном на этом самом
    файле (:func:`pack_start`), верить ему нельзя. Резы захода муксер отмеряет от ПЕРВОГО
    ПАКЕТА, и ошибка на один опорный кадр разъезжает с сеткой весь заход целиком.
    """
    if keys is None or at <= 0:
        return math.nan
    shift = SEEK_SHIFT.get(keys.kind)
    if shift is None or len(keys.at) < 2:
        return math.nan
    # Ищет ffmpeg не по метке показа, а по своему индексу, и у mp4 без списка правок этот
    # индекс стоит на времени ДЕКОДИРОВАНИЯ (замер TC-699 на живом YIFY-релизе: ``-ss``
    # в последние ``ctts`` перед кадром - 0.083 с - садится на САМ кадр, а не на прежний).
    # Для такой карты парсер отдаёт исковое время отдельным рядом (``via``); где его нет
    # (mkv, mp4 со списком правок, кэш прошлой версии), исковое время - сама метка.
    seek = keys.via if len(keys.via) == len(keys.at) else keys.at
    # Цель - то, что реально уезжает в команду: и пробный прогон, и упаковка печатают
    # ``-ss`` с тремя знаками, поэтому и правило применяется к округлённой цели.
    target = float(f"{at:.3f}")
    index = bisect.bisect_right(seek, target + SEEK_EPS) - 1
    # Попадание ровно в кадр карты: mkv уезжает на предыдущий, mp4 стоит на нём -
    # вся разница демуксеров, и она же есть весь SEEK_SHIFT. Внутри GOP сдвигу нечего
    # сдвигать: оба демуксера уже стоят на одной строке.
    if index >= 0 and abs(seek[index] - target) <= SEEK_EPS:
        index += shift
    if index < 1 or index >= len(keys.at) or at > keys.at[-1]:
        return math.nan
    return keys.at[index]
