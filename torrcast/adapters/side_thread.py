"""Поднять работу в стороне от того, кто её заказал: демон-поток и ничего больше.

Кладёт его в слоты композиционный корень; зовут те, кому висеть нельзя."""

from __future__ import annotations

import threading
from collections.abc import Callable


def side_thread(work: Callable[[], None]) -> None:
    """Начать работу в стороне и сразу вернуться.

    Демон, а не обычный поток: работа эта - подсобная, и держать ею процесс, когда
    показ окончен, незачем. Живёт она ровно столько, сколько живёт своё занятие, и
    закрывает себя сама - присматривать тут не за чем и некому.
    """
    threading.Thread(target=work, daemon=True).start()
