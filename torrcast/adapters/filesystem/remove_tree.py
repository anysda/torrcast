"""Снос каталога со всем содержимым: показ так убирает за упаковкой и перекодом."""

import shutil
from pathlib import Path


def remove_tree(path: Path) -> None:
    """Снести каталог целиком и молча: нет каталога - и сносить нечего.

    ``ignore_errors`` тут не небрежность, а решение: убирают этим уже погашенный показ,
    и падать на чужом файле, который кто-то держит открытым, ему нельзя.
    """
    shutil.rmtree(path, ignore_errors=True)
