"""Собирает голову команды упаковки: чем читаем, откуда заходим и что мапим."""

from __future__ import annotations


def pack_inputs(
    source_url: str,
    audio_index: int,
    entry: float | None,
    readrate: float = 1.0,
    burst: float = 0.0,
    voice_url: str = "",
    voice_end: float = 0.0,
) -> list[str]:
    """Начало команды прогона: темп чтения, ``-ss``, входы и карта дорожек.

    ``entry`` - с какого места фильма заходит прогон; ``None`` - с самого начала, и
    тогда ``-ss`` не называется вовсе.

    ``voice_url`` - отдельный файл со звуком, лежащий в той же раздаче рядом с видео.
    Пусто - звук берётся из самого видеофайла, и команда выходит прежняя до байта.
    Непусто - звук едет вторым входом, а ``audio_index`` считается уже внутри НЕГО.

    🔴 Второй вход обязан заходить с того же места, что и первый. Без своего ``-ss``
    он читается с начала файла: на локальном ролике это лишний расход, а на раздаче -
    чтение всего звука от нулевой секунды до места показа. Замер (ролик 60 с, заход на
    20-ю секунду): 864 звуковых кадра в докатке против 3, то есть 20 с звука
    прочитаны и перекодированы впустую.

    🔴 ``-t`` на втором входе - не осторожность, а мера. Прогон живого показа идёт до
    конца фильма и ``-to`` не называет; отдельная дорожка бывает длиннее видео, и её
    хвост целиком приклеивается к ПОСЛЕДНЕМУ куску. Замер (видео 60 с, дорожка 75 с):
    v5 обещает в манифесте 10.010 с, а несёт 1078 звуковых кадров - 25 с звука вместо
    десяти. С ``-t`` кусок несёт свои 431. Дорожка короче видео хвоста не создаёт и
    режется по себе.

    Резы сетки от второго входа не двигаются: сегментный муксер отмеряет их по опорному
    потоку, а это картинка первого входа.
    """
    command = ["ffmpeg", "-hide_banner", "-loglevel", "warning"]
    if readrate > 0:
        command += ["-readrate", f"{readrate:g}"]
        if burst > 0:
            command += ["-readrate_initial_burst", f"{burst:g}"]
    command += ["-copyts"]
    seek = 0.0 if entry is None else entry
    if entry is not None:
        command += ["-ss", f"{entry:.3f}"]
    command += ["-i", source_url]
    if voice_url:
        if entry is not None:
            command += ["-ss", f"{entry:.3f}"]
        if voice_end > seek:
            command += ["-t", f"{voice_end - seek:.3f}"]
        command += ["-i", voice_url]
    return [*command, "-map", "0:v:0", "-map", f"{1 if voice_url else 0}:a:{audio_index}"]
