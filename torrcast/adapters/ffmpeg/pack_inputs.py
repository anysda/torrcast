"""Собирает голову команды упаковки: чем читаем, откуда заходим и что мапим."""

from __future__ import annotations


def pack_inputs(
    source_url: str,
    audio_index: int,
    entry: float | None,
    readrate: float = 1.0,
    burst: float = 0.0,
    voice_url: str = "",
    voice_end: float = 0.0,
    landed: float | None = None,
) -> list[str]:
    """Начало команды прогона: темп чтения, ``-ss``, входы и карта дорожек.

    ``entry`` - с какого места фильма заходит прогон; ``None`` - с самого начала, и
    тогда ``-ss`` не называется вовсе.

    🔴 ``landed`` - где копия ВСТАЁТ на самом деле, и называют его только копирующему
    прогону. Точный вход - умолчание ffmpeg - режет каждую дорожку ровно по ``-ss``, но
    копию обрезать нечем: картинка приходит с опорного кадра ПЕРЕД названным местом, а
    звук перекодируется и обрезается честно. Разницу между этими двумя началами зритель
    и слышит как «со звуком что-то ужасное»: картинка идёт, звука нет. Поэтому копия
    просит НЕ обрезать себя вовсе (``-noaccurate_seek``) и берёт обе дорожки с того
    места, куда села, а отдельная дорожка (второй вход) заходит не на ``entry``, а на
    посадку: это другой файл, его обрезают точно, и посадку он держит ровно.

    Замер на стенде, первый кусок показа, разница ``start_time`` звука и видео:

    * картина с ``ac3`` 5.1, заход на 4652.911 при посадке 4650.479 - было +2410.7 мс и
      -70.0 LUFS, то есть тишина;
    * картина с ``ac3`` 5.1, заход на 7.471 при посадке 2.135 - было +5336 мс.

    ⚠️ Кодек источника тут ни при чём, и это проверено обоими концами: у картины с
    ``aac`` при заходе с ``-ss`` дефект тот же, а у картины с ``ac3`` при заходе с нуля
    его нет. Свод 5.1 в стерео тоже ни при чём: исходная дорожка дала -23.0 LUFS при
    пике -5.7 dBFS, наш свод - -22.4 LUFS при -3.5 dBFS.

    🔴 Назвать посадку в ``-ss`` первого входа нельзя, хотя это и напрашивается: перемотка
    САМА сдвигает посадку. Замер (ролик с опорными кадрами каждые 2.0854 с): ``-ss 41.000``
    садится на 39.623, а ``-ss 39.623`` - уже на 37.538, то есть на кластер раньше, потому
    что кластер контейнера начинается на 8 мс позже своего опорного кадра. Посадка держит
    всю сетку резов, и прогон объявил бы себя на 2.085 с позже своего первого пакета:
    замер того же ролика дал первый кусок ``v3.ts,0.000000,37.912000`` вместо границы 40.

    🔴 Перекодирующему заходу посадку НЕ называют, и это не осторожность. Он режет видео
    сам, точный вход ставит обе дорожки ровно на ``-ss``, расходиться им нечем, а без
    обрезки его первый пакет уехал бы за границу сетки, которую он обязан держать: сторож
    стыков поймал на выложенной зрителю ленте откат видео на 1.4181 с.

    ``voice_url`` - отдельный файл со звуком, лежащий в той же раздаче рядом с видео.
    Пусто - звук берётся из самого видеофайла, и команда выходит прежняя до байта.
    Непусто - звук едет вторым входом, а ``audio_index`` считается уже внутри НЕГО.

    🔴 Второй вход обязан заходить туда же, где встал первый. Без своего ``-ss``
    он читается с начала файла: на локальном ролике это лишний расход, а на раздаче -
    чтение всего звука от нулевой секунды до места показа. Замер (ролик 60 с, заход на
    20-ю секунду): 864 звуковых кадра в докатке против 3, то есть 20 с звука
    прочитаны и перекодированы впустую.

    🔴 ``-t`` на втором входе - не осторожность, а мера. Прогон живого показа идёт до
    конца фильма и ``-to`` не называет; отдельная дорожка бывает длиннее видео, и её
    хвост целиком приклеивается к ПОСЛЕДНЕМУ куску. Замер (видео 60 с, дорожка 75 с):
    v5 обещает в манифесте 10.010 с, а несёт 1078 звуковых кадров - 25 с звука вместо
    десяти. С ``-t`` кусок несёт свои 431. Дорожка короче видео хвоста не создаёт и
    режется по себе.

    Резы сетки от второго входа не двигаются: сегментный муксер отмеряет их по опорному
    потоку, а это картинка первого входа.
    """
    command = ["ffmpeg", "-hide_banner", "-loglevel", "warning"]
    if readrate > 0:
        command += ["-readrate", f"{readrate:g}"]
        if burst > 0:
            command += ["-readrate_initial_burst", f"{burst:g}"]
    command += ["-copyts"]
    if entry is not None and landed is not None:
        command += ["-noaccurate_seek"]
    if entry is not None:
        command += ["-ss", f"{entry:.3f}"]
    command += ["-i", source_url]
    if voice_url:
        seek = 0.0 if entry is None else entry
        if landed is not None:
            seek = min(seek, landed)
        if entry is not None:
            command += ["-ss", f"{seek:.3f}"]
        if voice_end > seek:
            command += ["-t", f"{voice_end - seek:.3f}"]
        command += ["-i", voice_url]
    return [*command, "-map", "0:v:0", "-map", f"{1 if voice_url else 0}:a:{audio_index}"]
