"""Доводы сегментного муксера для CMAF; их зовёт сборка команды упаковки."""

from typing import Final

#: Доводы сегментного муксера, которыми режется CMAF.
#:
#: 🔴 Каждый кусок несёт СВОЙ заголовок (``-individual_header_trailer 1``), а не берёт
#: общий на весь показ. Общий держится на том, что все куски сделаны одним кодировщиком с
#: одними параметрами, - а у показа их двое. Копия отдаёт битстрим исходника, перекод
#: кодирует свой, и наборы параметров у них разные: живой замер - копия
#: ``profile=77 (Main), level=40, SPS 29 Б`` против перекода
#: ``profile=66 (Baseline), level=41, SPS 24 Б``.
#:
#: Приёмник настраивает декодер по тому заголовку, что получил, и каждый перекодированный
#: кусок разбирал чужими параметрами: **1514 и 1680 строк ошибок картинки** на двух ужатых
#: местах против нуля у соседних копий. Приставка говорила это и сама:
#: ``Selected MediaCodecVideoDecoder … profile: h264 main`` на кадрах Baseline. С этим
#: доводом те же два места дают **ноль** строк ошибок.
#:
#: ⚠️ Параметры в самом потоке (``dump_extra``) класс НЕ лечат - 1515 строк ошибок.
#:
#: ⚠️ Общего заголовка при этом не остаётся вовсе: сегментный муксер пишет его либо в
#: отдельный файл, либо в каждый кусок, но не в оба места сразу - замер по всем четырём
#: сочетаниям флагов. Тот, что назван в манифесте (``EXT-X-MAP``), вырезается из первого
#: же выложенного куска (:func:`torrcast.adapters.stream_pack.lay_head.lay_head`), и без него
#: приёмник куски качает, а разбор не начинает вовсе - конвейер стоит в ``kStarting``.
#:
#: Цена замерена на живом показе: **+1455 Б на кусок**, то есть 0.006 % от куска в 24 МБ
#: и около мегабайта на двухчасовую картину из 692 кусков.
CMAF_OPTIONS: Final = (
    "-segment_format_options",
    "movflags=cmaf",
    "-individual_header_trailer",
    "1",
)
