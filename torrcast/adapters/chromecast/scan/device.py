"""Найденный приёмник: адрес обязателен, имя - как повезёт.

Собирают его оба способа поиска, читает меню выбора приёмника и определение профиля."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class Device:
    """Найденный приёмник: адрес обязателен, имя - как повезёт."""

    address: str
    name: str = ""
    model: str = ""
    #: Кто нашёл: ``mdns`` (по имени) или ``скан`` (по порту 8009).
    how: str = ""
    #: Производитель по паспорту устройства. В меню он не нужен - по нему выбирается
    #: профиль приёмника (:func:`torrcast.profile.for_passport`), и часто он единственное,
    #: чем устройство себя называет: у приставки Xiaomi имя и модель приходят пустыми.
    maker: str = ""

    @property
    def title(self) -> str:
        """Как назвать пункт меню: имя, за неимением - модель, за неимением - «приёмник».

        Безымянный пункт всё равно выбираем: адрес рядом, и человек узнаёт свой
        телевизор по нему. Пустая строка в меню была бы хуже честного «приёмник».
        """
        return self.name or self.model or "приёмник"
