"""Признак «зритель закрыл показ с пульта»: экран пуст, а гасили его не мы.

Спрашивает его опрос места показа
(:func:`torrcast.adapters.chromecast.cast.position._position`), и только он.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from torrcast.adapters.chromecast.cast.receiver_talk import _Talk


def _viewer_closed(rcv: _Talk) -> bool:
    """Правда ли показ закрыл ЗРИТЕЛЬ. Тогда поднимать его обратно нельзя.

    Отличать волю человека от аварии приходится ПРИЗНАКОМ, а не сроком: снаружи они
    похожи, а цена ошибки разная - воскрешённый поперёк воли показ играет в пустой
    комнате, невоскрешённая авария оставляет зрителя перед чёрным экраном.

    🔴 Слово о ходе показа для этого не годится: вместе с медиасессией приёмник теряет и
    его - вместо ``PAUSED`` или ``IDLE/ERROR`` приходит пустой статус с нулём. А вот
    приложение на экране (``app_id``) свою правду держит и после потери сессии, и
    различие тут ровно то, которое нужно: своя авария гасит медиасессию, оставляя
    приложение на экране (``IDLE/ERROR``), а рука человека убирает с экрана приложение
    целиком - остаётся пустота или заставка приёмника.

    Чужое приложение сюда не относится: пока нас не было, на том же приёмнике могли
    начать смотреть другое, и это не воля зрителя закрыть НАШ показ, а чужой показ,
    который и без того неприкосновенен
    (:meth:`torrcast.adapters.chromecast.cast.receiver_talk._Talk._free`).

    ⚠️ Пустой экран бывает и нашей собственной работой: перед каждым повтором LOAD
    приложение закрываем мы сами (:meth:`_restart_app`). Такая пустота волей зрителя не
    считается - иначе неудавшийся повтор хоронил бы показ вместо того, чтобы поднимать
    его дальше. Отметка о своём закрытии гаснет первым же появлением нашего приложения
    на экране, то есть удавшимся LOAD.
    """
    if rcv._cast is None:
        return False  # соединения нет вовсе - о чужом экране судить нечем
    app = getattr(getattr(rcv._cast, "status", None), "app_id", None)
    if app == rcv.MEDIA_APP:
        rcv._we_quit = False  # приложение снова наше - прошлое своё закрытие не в счёт
        return False
    if app and app != rcv.BACKDROP_APP:
        return False  # на экране чужое приложение - это чужой показ, а не воля зрителя
    return not rcv._we_quit
