"""Сторож перемотки: заметить её и померить, через сколько вернулась КАРТИНКА.

Зовёт его опрос места показа на каждом опросе, и только он."""

from __future__ import annotations

from typing import TYPE_CHECKING

from torrcast.adapters.chromecast.cast.drop_seek import _drop_seek
from torrcast.ports.journal.slot import journal

if TYPE_CHECKING:
    from torrcast.adapters.chromecast.cast.receiver_state import _State


def _watch_seek(rcv: _State, pos: float, state: str) -> None:
    """Заметить перемотку и померить, через сколько после неё вернулась КАРТИНКА.

    Перемотка видна только по позиции: приёмник мотает сам, никакой команды нам при
    этом не приходит. Отличаем её от хода показа по прыжку, а от собственного нуджа -
    по тому, куда прыгнули: сторож только что назвал это место сам (:attr:`_nudged_to`).

    🔴 Вперёд запас на прыжок - БОЛЬШИЙ из двух: жёсткий :attr:`SEEK_JUMP` и плёнка,
    которую показ успел бы проиграть с прошлого опроса. Пока запасом был один только
    :attr:`SEEK_JUMP`, счёт молча стоял на том, что круг опроса приходит раз в две
    секунды; круг своё расписание держит не всегда, и на каждой его задержке обычный ход
    показа писался в ленту перемоткой. Задержка тут не редкость и не авария: её даёт и
    подъём оборванной упаковки, и повтор ``LOAD``, и медленный ответ самого приёмника.

    🔴 Именно больший, а не сумма. Сумма выглядит осторожнее, но она поднимает порог и на
    ровном круге - а настоящие перемотки лежат к нему вплотную: замер по ленте живого
    сеанса (19 перемоток руками) показал, что сумма съедает три из них. Запас на дрожание
    указателя и плёнка между опросами - это не две беды подряд, а одна и та же
    неопределённость, и складывать их незачем.

    Назад плёнка не уходит никогда, поэтому время между опросами откату ничего не
    покупает: там порог остаётся жёстким.

    🔴 Конец ожидания - СДВИГ УКАЗАТЕЛЯ с места приземления (:attr:`PICTURE_STEP`), а
    не слово ``PLAYING``: приёмник говорит его раньше первого кадра, и метрика,
    верившая слову, писала 0.0 с там, где зритель ждал 6-10 с. Замер на живом Q70D:
    назад 3.8-4.2 с, вперёд 9.3-11.9 с, глубоко в непрогретое 5.2-6.8 с.

    ⚠️ Прыжок засчитывается по позиции, которая УЖЕ уехала, поэтому место приземления
    известно только с этого опроса: ``to`` - это то, куда приёмник встал, а не то, что
    нажали на пульте. Мерить от предыдущей пробы нельзя - на ней указатель ещё стоит
    там, откуда прыгнули.

    ``IDLE`` из счёта выкинут по той же причине, что и в :meth:`position`: у мёртвой
    сессии позиции нет вовсе, и её ноль - не перемотка в начало.
    """
    now = rcv.clock.monotonic()
    seen, rcv._seen = rcv._seen, pos
    was_at, rcv._seen_at = rcv._seen_at, now
    if state == "IDLE":
        # Позиции не было - и сравнивать в следующий раз не с чем. Момент снятия
        # возвращается вместе с ней: пара «где и когда» врозь не живёт, а мёртвая сессия
        # длится сколько угодно, и время под ней идёт.
        rcv._seen, rcv._seen_at = seen, was_at
        _drop_seek(rcv, "сессия оборвалась")
        return
    gone = pos - seen
    covered = max(0.0, now - was_at)  # плёнки, которую показ успел бы проиграть
    ahead = max(rcv.SEEK_JUMP, covered)
    jumped = seen >= 0.0 and not -rcv.SEEK_JUMP <= gone <= ahead
    # Картинку засчитываем только на опросе БЕЗ нового прыжка: иначе вторая перемотка
    # подряд сошла бы за возвращение картинки после первой - указатель-то уехал.
    if rcv._seek_since and not jumped and pos >= rcv._seek_to + rcv.PICTURE_STEP:
        journal().seek(frm=rcv._seek_from, to=rcv._seek_to, wait=now - rcv._seek_since)
        rcv._seek_since = 0.0
    if not jumped:
        return
    nudged, rcv._nudged_to = rcv._nudged_to, -1.0
    if nudged >= 0.0 and abs(pos - nudged) <= rcv.SEEK_JUMP:
        return  # прыжок наш: сторож уже записал его как нудж
    _drop_seek(rcv, "следом пришла ещё одна перемотка")
    rcv._seek_from, rcv._seek_to = seen, pos
    rcv._seek_since = now
