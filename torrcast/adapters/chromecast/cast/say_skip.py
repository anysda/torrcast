"""Картинка вернулась после прыжков сторожа - назвать зрителю пропущенную плёнку.

Зовёт это опрос места показа на каждом ``PLAYING``, и только он."""

from __future__ import annotations

from typing import TYPE_CHECKING

from torrcast.domain.catalogs.phrase import phrase

if TYPE_CHECKING:
    from torrcast.adapters.chromecast.cast.receiver_state import _State


def _say_skip(rcv: _State, back: float) -> None:
    """Картинка вернулась после прыжков сторожа - назвать зрителю пропущенную плёнку.

    🔴 Прыжок сторожа - это размен: приёмник, зависший на куске, оживает только тем,
    что кусок перешагнут (:meth:`_nudge`), и цена размена - секунды фильма, которых
    человек не увидел и не услышал. Замер на живом Q70D 11-08-2026: показ встал на
    103.6 с, прыжок ушёл за границу куска на 119.2 с - 15.6 с мимо, и об этом не было
    сказано ни строки. Человек у экрана слышит пропавший звук и гадает, файл это или
    техника; правильного ответа у него нет ни одного.

    Сказать это можно только ЗДЕСЬ, а не в момент прыжка: прицел сторожа - ещё не
    пропуск. Приземлиться приёмник вправе и не туда, куда целились, а лестница,
    кончившаяся ничем (:attr:`_gone`), не стоит зрителю ни секунды плёнки - показ
    поднимут с последнего показанного кадра, и счёт снимает сам подъём
    (:meth:`replay`). Пропуск известен числом ровно тогда, когда на экране снова кадр.

    ⚠️ Снимать счёт по :attr:`_gone` нельзя, хотя и тянет: ушедший приёмник иногда
    оживает сам - на том месте, куда его увела лестница. Плёнку между ним и кадром
    зрителя при этом никто не показал, и молчать о ней не за что.
    """
    frm, rcv._skip_from = rcv._skip_from, -1.0
    if frm < 0 or back - frm < rcv.SKIP_FLOOR:
        return
    print(
        phrase(
            "chromecast_talk.stalled_skip",
            gap=f"{back - frm:.0f}",
            start=f"{frm:.0f}",
            end=f"{back:.0f}",
        ),
        flush=True,
    )
