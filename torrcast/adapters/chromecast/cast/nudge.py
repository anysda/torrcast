"""Сторож подвиса: расшевелить приёмник, застрявший в BUFFERING на одной секунде.

Зовёт его опрос места показа, и только он."""

from __future__ import annotations

import contextlib
from typing import TYPE_CHECKING

from torrcast.adapters.chromecast.cast.drop_seek import _drop_seek
from torrcast.ports.journal.slot import journal

if TYPE_CHECKING:
    from torrcast.adapters.chromecast.cast.receiver_talk import _Talk


def _nudge(rcv: _Talk, pos: float, front: float = 0.0) -> None:
    """Расшевелить приёмник, зависший в BUFFERING на одной и той же секунде.

    Расшевеливать имеет смысл, только когда еда на столе: ``front`` — докуда упаковано,
    и пока запас впереди позиции меньше :attr:`READY_AHEAD`, приёмник ждёт **нас**, а
    не завис. Такой BUFFERING лечится упаковкой, и прыгать по нему нельзя: прыгнешь —
    уедешь в неупакованное место и заставишь раздачу паковать заново.

    Замерено на живом Q70D: на 273-й секунде показа ресивер перестал
    запрашивать сегменты и встал в BUFFERING **навсегда** — при том что следующий
    кусок лежал в tmpfs и отдавался curl'ом за миллисекунды, а живого соединения от ТВ
    в conntrack не было вовсе. То есть подвисает сам приёмник, и лечится это ``seek``:
    показ возобновляется немедленно. Такой же сторож годами держит на этом ТВ и
    другой сендер.

    ⚠️ Прыгать можно **только вперёд**, и целиться — от пройденного максимума.
    На растущем манифесте ресивер отрабатывал ``seek`` не точно, а с начала
    подходящего сегмента, и «нудж на месте» откатывал показ на ~35 с назад: позиция
    после отката меньше максимума, счётчик не сбрасывался — и получалась бесконечная
    лесенка назад (наблюдалась живьём: 2:12 → 1:58 → 1:44). С манифестом на весь
    фильм ``seek`` стал точным (замерено: позиция встаёт ровно в запрошенную), но
    правило остаётся: нудж — это лечение застрявшего куска, и лечится он тем, что
    кусок пропускают, а не тем, что его переигрывают.

    ⚠️ Прыжок отмеряется СЕТКОЙ, а не секундами (:attr:`next_cut`). Шаг
    (:attr:`torrcast.domain.profile.Profile.stall_skip`) - 8 с, а сегмент бывает и 14.9 с:
    замер на «Моане» 2016 - показ встал на 127.2 с внутри куска
    ``[124.583..137.095)``, прыжок целился в 135.2 с, то есть в тот же кусок, и оба
    нуджа сеанса приземлились туда, откуда прыгали. Прыжок, по устройству более
    короткий, чем сегмент, застрявший сегмент перешагнуть не может никогда, и лестница
    нуджей вырождается в топтание на месте. Сетки не назвали - остаётся прежний шаг:
    врать о границах, которых не знаешь, хуже, чем прыгать вслепую.

    ⚠️ У лестницы есть конец (:attr:`torrcast.domain.profile.Profile.blind_nudges`). Нудж
    лечит **застрявший кусок**, и доказательство того, что он вылечил, ровно одно -
    показанный кадр. Уехавший указатель доказательством не является: ушедший приёмник
    честно принимает ``seek`` и двигает ``current_time``, оставаясь в ``BUFFERING``, -
    замерено, 12 нуджей подряд без единого ``PLAYING``, 96 с фильма прошагано впустую.
    Поэтому после :attr:`torrcast.domain.profile.Profile.blind_nudges` слепых прыжков сторож
    умолкает и объявляет показ погасшим (:attr:`_gone`): дальше это работа
    воскрешения (:class:`torrcast.usecases.revive_playback._revival._Revival`), которое поднимает
    сессию с последнего показанного кадра, а не гонит указатель дальше по фильму.
    """
    now = rcv.clock.monotonic()
    if pos != rcv._stall_at:
        rcv._stall_at, rcv._stall_since = pos, now
        return
    if now - rcv._stall_since < rcv.profile.stall_seconds:
        return
    if front - pos < rcv.profile.ready_ahead:
        return  # приёмник ждёт упаковку - это наша забота, а не его зависание
    if rcv._blind >= rcv.profile.blind_nudges:
        # Прыгать больше некуда: за всю лестницу приёмник не показал ни кадра. Каждый
        # следующий прыжок стоил бы ещё 8 с неподвижной картинки и до 8 с плёнки.
        rcv._stall_since = now
        if not rcv._gone:
            rcv._gone = True
            print(
                f"нуджи не дали ни кадра ({rcv._blind} подряд) - прыгать перестаю, "
                "показ поднимется с последнего показанного кадра",
                flush=True,
            )
        return
    rcv._blind += 1
    if rcv._skip_from < 0:
        # Кадр, на котором зритель остался: дальше указатель поедет за нашими же
        # прыжками, и после лестницы спросить о нём будет уже некого.
        rcv._skip_from = pos
    stuck = now - rcv._stall_since
    rcv._stall_hits += 1
    rcv._stall_since = now
    target = rcv._peak + rcv.profile.stall_skip * rcv._stall_hits
    if rcv.next_cut is not None:
        target = max(target, rcv.next_cut(rcv._peak) + rcv.CUT_SLACK)
    rcv._nudged_to = target
    # Дальше указатель уедет от нашего же прыжка, и приписать этот сдвиг перемотке
    # человека значило бы записать её удачной ровно там, где она не удалась.
    _drop_seek(rcv, "сторож перебил нуджем")
    journal().nudge(pos=pos, to=target, hit=rcv._stall_hits, stuck=stuck, front=front)
    with contextlib.suppress(Exception):
        rcv._device().media_controller.seek(target)
