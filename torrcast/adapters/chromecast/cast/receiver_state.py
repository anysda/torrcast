"""Всё, что живой приёмник про себя знает: адрес, профиль, часы и ход показа.

Наследует их :class:`ChromecastReceiver`, и только он; занятия приёмника берут это
состояние параметром."""

from __future__ import annotations

from collections.abc import Callable
from typing import Any

from torrcast.adapters.chromecast.cast.receiver_settings import _Settings
from torrcast.adapters.system_clock import SystemClock
from torrcast.domain.infra_error import InfraError
from torrcast.domain.profile import CAUTIOUS, Profile
from torrcast.domain.segment_container import MPEGTS, SegmentContainer
from torrcast.ports.clock import Clock


class _State(_Settings):
    """Поля живого приёмника: настройки показа и ход текущей сессии."""

    def __init__(
        self,
        address: str,
        profile: Profile = CAUTIOUS,
        clock: Clock | None = None,
        device: Any = None,
    ) -> None:
        if not address:
            raise InfraError("адрес ТВ не задан: cast --tv - найдёт телевизоры в сети")
        self.address = address
        #: Профиль этого приёмника: его терпение, его повторы LOAD, его сторож нуджей.
        #: Умолчание осторожное - показ без выбранного профиля ведёт себя как раньше.
        self.profile = profile
        self.segment_container: SegmentContainer = MPEGTS
        #: Чем меряются выдержки приёмника: ожидание картинки после LOAD, пауза перед
        #: повтором, часы сторожа подвиса. Умолчание - настоящее время; сухому прогону
        #: сюда дают свои часы, чтобы не выжидать эти минуты (:class:`torrcast.ports.clock.Clock`).
        self.clock: Clock = clock if clock is not None else SystemClock()
        #: Уже поднятое соединение с приёмником. Умолчание боевое - его нет, и первый же
        #: вопрос к устройству поднимает настоящее (:meth:`_Link._device`). Называет своё
        #: только стенд: настоящее соединение будит телевизор одним лишь коннектом.
        self._cast: Any = device
        self._url = ""
        self._title = ""
        self._peak = 0.0
        self._stall_at = -1.0
        self._stall_since = 0.0
        self._stall_hits = 0
        self._reloads = 0
        self._started = False
        #: С какой секунды фильма грузили показ: повтор LOAD должен попадать туда же.
        self._at = 0.0
        #: Показ стоит на паузе ЗРИТЕЛЯ: приёмник назвал сессию ``PAUSED`` либо последний
        #: LOAD просил её не начинать (``autoplay=False``). Признак этот наш и потерю
        #: сессии переживает - слово приёмник теряет, а решение зрителя силы не теряет
        #: (:func:`torrcast.adapters.chromecast.cast.position._position`). Отсюда его
        #: спрашивают оба, кто вправе загрузить показ заново: готовность ожидания при нём
        #: - ``PAUSED`` (:meth:`_settle`), а повтор LOAD посреди показа при нём не идёт
        #: вовсе (:func:`torrcast.adapters.chromecast.cast.reload._reload`).
        self._paused = False
        #: Приложение с экрана убрали МЫ (:meth:`_restart_app`), и пустой экран сейчас -
        #: наша работа, а не воля зрителя. Гасится первым же появлением нашего приложения,
        #: то есть удавшимся LOAD
        #: (:func:`torrcast.adapters.chromecast.cast.viewer_closed._viewer_closed`).
        self._we_quit = False
        #: Последний статус взят не свежим: сокет лёг, и приёмник ответил эхом прошлого
        #: опроса (:meth:`torrcast.adapters.chromecast.cast.receiver_link._Link._status`).
        #: Уезжает в :attr:`torrcast.domain.position.Position.stale`, где по нему и судят,
        #: можно ли верить ответу про волю зрителя (TC-880).
        self._stale = False
        #: Сессия приложения приёмника, которую подняли мы (см. :meth:`_ours`).
        self._session = ""
        #: Почему последний подъём показа не дал картинки; пусто - подъёма не было либо
        #: он удался (:func:`torrcast.adapters.chromecast.cast.replay._replay`).
        #:
        #: 🔴 «Не поднял, потому что нельзя» и «не поднял, потому что упал» - разные
        #: события с разными выводами, а в ленту они уходили одним и тем же ``ok=False``
        #: (:meth:`torrcast.ports.journal.journal.Journal.revive`). Пока их различить было
        #: нечем, замер подъёмов приёмника читался двусмысленно: занятый чужим показом ТВ
        #: и легшее соединение считались одной строкой. Отсюда причина и держится тут -
        #: знает её только сам подъём, а называет её лестница воскрешения
        #: (:func:`torrcast.usecases.revive_playback._resurrect._resurrect`).
        self._refused = ""
        #: Позиция с прошлого опроса и незакрытая перемотка (:meth:`_watch_seek`):
        #: откуда прыгнули, куда и с какого монотонного момента ждём картинку.
        self._seen = -1.0
        #: Когда сняли :attr:`_seen`, монотонные секунды. Ходит с позицией одной парой:
        #: прыжок сам по себе ни о чём не говорит, пока не сказано, за какое время он
        #: случился (:func:`_watch_seek`).
        self._seen_at = 0.0
        self._seek_from = 0.0
        self._seek_to = 0.0
        self._seek_since = 0.0
        #: Куда прыгнул наш собственный сторож: его прыжок перемоткой человека не считаем.
        #: Гасится ПЕРВЫМ ЖЕ прыжком - на второй нужен и второй нудж.
        #:
        #: 🔴 Гасило раньше только совпадение, и метка, мимо которой приёмник прыгнул,
        #: оставалась взведённой до конца показа. Дальше она глотала уже человеческую
        #: перемотку - любую, приземлившуюся в тех же пятнадцати секундах, - и та не
        #: попадала в ленту вовсе. Метка описывает ОДИН наш прыжок, а не место фильма.
        self._nudged_to = -1.0
        #: Сколько нуджей подряд не дали НИ ОДНОГО показанного кадра. Обнуляется только
        #: кадром (``PLAYING``), а не уехавшим указателем: у ушедшего приёмника указатель
        #: как раз послушно едет за каждым ``seek`` (:meth:`_nudge`).
        self._blind = 0
        #: Сторож сдался: лестница нуджей не показала ни кадра, и показ считается
        #: погасшим - дальше его поднимает воскрешение
        #: (:class:`torrcast.usecases.revive_playback._revival._Revival`).
        self._gone = False
        #: Место, на котором приёмник в последний раз ПОКАЗЫВАЛ кадр; ``-1`` - кадра не
        #: было ни разу. Обновляется только живым экраном (не ``BUFFERING`` и не ``IDLE``)
        #: и только ненулевой позицией: ровно ноль приёмник отдаёт и тогда, когда места у
        #: него нет вовсе. По этому месту сторож подвиса и проверяет, что его прыжок не
        #: уводит зрителя НАЗАД (:func:`torrcast.adapters.chromecast.cast.nudge._nudge`).
        self._shown = -1.0
        #: Последний кадр, который зритель ВИДЕЛ перед тем, как сторож начал прыгать;
        #: ``-1`` - никуда не прыгали. Ставится первым прыжком лестницы, а называется
        #: зрителю тогда, когда картинка вернулась и пропуск известен числом
        #: (:meth:`position`). Мерить в момент прыжка нечего: сколько плёнки уйдёт мимо,
        #: решает не прицел, а то место, на котором приёмник в итоге оживёт.
        self._skip_from = -1.0
        #: Последняя подробная причина отказа из сырого ответа приёмника. pychromecast
        #: это поле не переносит в :class:`MediaStatus`, поэтому снимаем его до разбора
        #: ответа (:meth:`_catch_media_error`). ``None`` - за этот LOAD кода не называли:
        #: каждый новый LOAD начинает с чистого (:meth:`_load`), чтобы причина не
        #: переезжала с одной загрузки на следующую.
        self._error_code: int | None = None
        #: Где кончается сегмент, накрывающий эту секунду фильма
        #: (:meth:`torrcast.adapters.stream_pack.grid.Grid.after`); ``None`` - сетки не назвали.
        #:
        #: 🔴 Без неё и прыжок сторожа, и подъём после отказа отмеряются абсолютной
        #: секундой, а сегменты разной длины - и оба приземляются в тот же кусок, на
        #: котором показ споткнулся. Ставит её показ
        #: (:func:`torrcast.usecases.playback._play._play`): сетку знает он.
        self.next_cut: Callable[[float], float] | None = None
        #: Сколько раз показ уже умирал на каждом куске; ключ - конец куска, секунды
        #: фильма. Ведётся здесь, а не у показа, потому что спрашивают о нём обе ветки
        #: подъёма - и повтор LOAD (:meth:`_reload`), и воскрешение (:meth:`replay`).
        self._deaths: dict[float, int] = {}
