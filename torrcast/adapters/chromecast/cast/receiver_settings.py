"""Числа живого приёмника, одинаковые для всех моделей: сроки LOAD и пороги перемотки.

Наследует их состояние приёмника, а всё, что меряется на модели, живёт в её профиле."""

from __future__ import annotations

from torrcast.domain.start_timeout import START_TIMEOUT


class _Settings:
    """Пороги, которые от модели приёмника не зависят.

    🔴 Всё, что у моделей разное - терпение к темноте, повторы LOAD, обида на 404,
    пороги сторожа подвиса, - живёт в профиле приёмника
    (:mod:`torrcast.domain.profile`), и живой показ спрашивает ``self.profile``.
    """

    #: Терпение до первой картинки живёт в домене: его же складывает бюджет старта.
    START_TIMEOUT = START_TIMEOUT
    #: Сколько ждём картинку, поднимая ПОГАСШИЙ показ (:meth:`replay`). Здесь не 300 с:
    #: попытка тут не одна, интервалы держит зовущий
    #: (:class:`torrcast.usecases.revive_playback._revival._Revival`), и висеть в одной попытке пять
    #: минут значило бы проспать вернувшуюся сеть. Минуты хватает с запасом: живой Q70D отвечает
    #: PLAYING за 0.7-1.5 с, а внутри этого бюджета :meth:`_settle` успевает ещё раз перегрузить
    #: молчащий LOAD.
    WAKE_TIMEOUT = 60.0
    #: Пауза между повторами LOAD: ресиверу нужно время закрыть прошлую сессию.
    LOAD_PAUSE = 3.0
    #: Сколько ждём приёмник, чей сокет 8009 ещё переподключается, секунды
    #: (:func:`torrcast.adapters.chromecast.cast.while_connecting._while_connecting`).
    #:
    #: 🔴 Потолок тут обязателен и обязан быть числом. Приёмник, занятый чужим показом
    #: или ушедший из сети, отвечает ``is connecting`` столько, сколько его спрашивать, и
    #: повтор без потолка означал бы вечную петлю перед пустым экраном - ту же беду, что
    #: и падение, только молчаливую.
    #:
    #: Число взято из того же замера, что и :data:`torrcast.domain.revive_settings.WILL_LIMIT`:
    #: pychromecast повторяет коннект через 5 с, а следующий внятный ответ приёмника
    #: пришёл через 6 с (замер на приставке 30-08-2026). Двенадцать - этот замер с
    #: запасом вдвое; больше брать нечего, дальше начинается не переподключение, а
    #: отсутствие приёмника, и лечится оно подъёмом с чистым соединением
    #: (:meth:`torrcast.adapters.chromecast.cast.receiver_talk._Talk._restart_app`).
    CONNECT_WAIT = 12.0
    #: Выдержка между повторами команды в переподключающийся сокет, секунды. Круг опроса
    #: показа идёт раз в 2 с, и спрашивать сокет чаще незачем: ответ до следующей попытки
    #: коннекта не изменится, а лишние вопросы в переподключающийся сокет ничего не лечат.
    CONNECT_PAUSE = 2.0
    #: Столько терпим молчаливый IDLE после LOAD, прежде чем считать, что его не взяли.
    #: ⚠️ Это не противоречит «IDLE до первого показа - это загрузка»: живой Q70D отвечает
    #: PLAYING за 0.7-1.5 с, а 30 с молчания означают, что грузить он не начинал.
    STUCK_SECONDS = 30.0
    #: app_id Default Media Receiver: чужой app = каст сняли пультом, показ окончен.
    MEDIA_APP = "CC1AD845"
    #: app_id заставки приёмника: показа на экране нет вовсе, приёмник ничем не занят.
    BACKDROP_APP = "E8C28D3C"
    #: Насколько позиция должна уехать назад, чтобы считать это перемоткой человека, а не
    #: дрожанием счётчика. Больше сегмента (:data:`torrcast.domain.config.Config.hls_segment` - 10 с
    #: по умолчанию) брать нельзя: перемотка на один кусок назад - обычное дело, и «максимум»
    #: после неё обязан опуститься. Меньше шага нуджа - тоже: свой же прыжок вперёд мы
    #: перемоткой назад считать не должны.
    REWIND = 8.0
    #: Насколько позиция должна прыгнуть между опросами, чтобы это была перемотка, а не
    #: дрожание указателя. Наружу отдаётся последний ПРИСЛАННЫЙ снимок приёмника, и
    #: свежесть двух соседних снимков разная, поэтому запас нужен и на ровном круге.
    #:
    #: 🔴 Вперёд этим числом порог не исчерпывается: там берётся большее из него и плёнки,
    #: которую показ успел бы проиграть между опросами
    #: (:func:`torrcast.adapters.chromecast.cast.watch_seek._watch_seek`). Одним этим числом
    #: порог стоял, пока считалось, что круг опроса приходит раз в 2 с; круг своё
    #: расписание держит не всегда, и каждая его задержка писала в ленту перемотку,
    #: которой не было.
    #:
    #: Назад число работает как стояло: плёнка не уходит назад никогда, и время между
    #: опросами откату ничего не покупает. Собственный нудж под порог тоже попадает,
    #: поэтому он помечается отдельно (:attr:`_nudged_to`), а не вычитается из прыжка.
    SEEK_JUMP = 15.0
    #: Насколько указатель обязан уйти от места приземления, чтобы после перемотки это
    #: считалось КАРТИНКОЙ (:meth:`_watch_seek`).
    #:
    #: 🔴 Слово ``PLAYING`` приёмник говорит РАНЬШЕ первого кадра, и метрика перемотки,
    #: верившая слову, записывала в ленту 0.0 с у всех трёх прыжков подряд - при том что
    #: картинка возвращалась за 6.0, 5.9 и 9.9 с. Указатель после перемотки стоит на месте
    #: приземления, пока приёмник не наберёт свой буфер, и трогается ровно тогда, когда на
    #: экране появляется кадр. Порог взят с запасом от одного кадра (41.7 мс у 23.976 к/с)
    #: и от дрожания счётчика, но заметно меньше шага показа за опрос (2 с).
    PICTURE_STEP = 0.4
    #: Сколько раз показ должен умереть на ОДНОМ куске, чтобы кусок был признан
    #: невоспроизводимым и перешагнут (:meth:`_past_deadly`).
    #:
    #: Не единица: моргнувшая сеть тоже гасит показ, и первая смерть ещё ничего о куске
    #: не говорит - поднявшийся с того же места показ идёт дальше как ни в чём не бывало.
    #: Три - это уже не совпадение, и цена ошибки известна заранее: один пропущенный
    #: сегмент против конца сеанса.
    DEADLY_TRIES = 3
    #: На сколько секунд целиться ЗА границу куска. Ноль брать нельзя: приёмник отрабатывает
    #: ``seek`` с начала подходящего сегмента, и попадание ровно в границу он вправе
    #: округлить назад - в тот самый кусок, который мы перешагиваем.
    CUT_SLACK = 0.5
    #: Пропуск короче этого зрителю не называем: опрос приёмника идёт раз в 2 с, и всё,
    #: что мельче, - это разрешение замера, а не потерянная плёнка.
    SKIP_FLOOR = 2.0
