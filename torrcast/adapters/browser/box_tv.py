"""Идёт ли ЖИВОЙ показ на телевизоре: слово о приёмнике запуска из ящика вкладки.

Ящик знает приёмник, которым показ поднят (:func:`torrcast.adapters.browser.write_web_box`):
любому приёмнику, кроме вкладки, ``tv: true`` кладёт сам показ
(:func:`torrcast.usecases.playback._publish_box`), а вкладка пишет свой ящик без него.
Страница спрашивает то же двумя путями (:func:`web.tv_live.tv_live`); консольному
``cast`` доступен только ящик - держателя каста «На ТВ» (:mod:`web.tv_session`) в его
процессе нет. Перенос «На ТВ» ящик не переписывает: показ вкладки, унесённый на
телевизор, лежит в ящике тем же словом вкладки. Поэтому браузер называется только у
машины без телевизора, а при названном ``tv`` ящик не спрашивается вовсе.
"""

from __future__ import annotations

from pathlib import Path

from torrcast.adapters.browser.read_web_box import read_web_box


def box_tv(out: Path, tv: str | None = None) -> bool:
    """Приёмник живого показа - телевизор; ``tv`` - телевизор из настройки машины.

    Названный телевизор (не пустой и не слово ``browser``) - сразу ``True``: показ вкладки
    у такой машины мог уехать «На ТВ», и ящик этого не знает. Ящик без ключа -
    «неизвестно», и это тоже ТВ: неизвестное остаётся прежним словом («на телевизоре»),
    ящик пишется каждому запуску, и пустым он бывает у показа, который поднимался ещё без
    этого слова, - выдумывать там вторую правду незачем.
    """
    if str(tv or "") not in ("", "browser"):
        return True
    seen = read_web_box(out)
    if not str(seen.get("key", "")):
        return True
    return bool(seen.get("tv", False))
