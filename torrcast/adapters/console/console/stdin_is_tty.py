"""Есть ли живой терминал на входе. Отдельной функцией - чтобы её можно было подменить.

Спрашивают её оба вопроса консоли, режим терминала, консоль команд и щуп машины."""

from __future__ import annotations

import sys


def stdin_is_tty() -> bool:
    """Есть ли живой терминал на входе. Отдельной функцией — чтобы тесты могли соврать."""
    try:
        return bool(sys.stdin.isatty())
    except ValueError:  # закрытый stdin (так бывает в юните)
        return False
