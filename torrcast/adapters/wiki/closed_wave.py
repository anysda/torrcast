"""Волна ниток, закрытая за собой: срок решает ответ, закрытие платит поднявший."""

from __future__ import annotations

import threading
import time
from collections.abc import Callable
from typing import Final, TypeVar

from torrcast.domain.facts.settings import FACTS_BUDGET

#: Сколько ждём волну ПОСЛЕ срока, секунды. Нитку подняли мы - нам её и закрывать, а
#: закрыть её можно только дождавшись: оборвать нитку, залипшую в системном вызове, в
#: Python нечем. Потолок у закрытия не свой: дольше, чем всё меню согласно ждать справку,
#: держать его незачем - ответа к этому сроку не ждёт уже никто.
_CLOSING: Final = FACTS_BUDGET

_Answer = TypeVar("_Answer")


def closed_wave(
    wave: list[threading.Thread], deadline: float, take: Callable[[], _Answer]
) -> _Answer:
    """Дождаться поднятой волны до ``deadline``, снять ответ и закрыть за собой поднятое.

    Срок и закрытие - разные вещи, и платят их разные. Срок принадлежит спрашивающему: в
    него он получает то, что успело приехать, и ни секундой позже - ответ снимает ``take``
    РОВНО по сроку, и опоздавшая нитка его уже не меняет. Закрытие принадлежит поднявшему:
    брошенная нитка не исчезает, а доживает своё в чужой работе - в бою это показ, в
    прогоне соседняя проба, и красным там оказывается невиновный. Поэтому ответ
    объявляется по сроку, а отдаётся после того, как волна отпущена.

    Платит закрытие фоновый спрашивающий, а не человек: потолок ожидания справки держит
    тот, кто позвал сюда, и от закрытия он не сдвигается.

    Срок и закрытие - оба про ВСЮ волну, а не про каждую нитку отдельно: нитки идут
    разом, и ждать их очередью значит множить потолок на их число.
    """
    for thread in wave:
        thread.join(max(0.0, deadline - time.monotonic()))
    answer = take()
    closing = time.monotonic() + _CLOSING
    for thread in wave:
        if thread.is_alive():
            thread.join(max(0.0, closing - time.monotonic()))
    return answer
