"""Склеивает выдачи нескольких запросов, оставляя каждую раздачу один раз."""

from __future__ import annotations

from collections import Counter
from dataclasses import replace

from torrcast.domain.by_majority import by_majority
from torrcast.domain.raw_result import RawResult


def merge(*batches: list[RawResult]) -> list[RawResult]:
    """Склеить выдачи нескольких запросов, оставив каждую раздачу один раз.

    Один и тот же торрент приходит и по русскому названию, и по латинскому, а
    ещё и из разных индексеров - тождество тут ровно одно, ``infoHash``. Порядок
    сохраняем: раздачи первого запроса идут первыми.

    ⚠️ Сколькими строками раздача приехала - не пустяк, а :attr:`RawResult.copies`. Пока
    индексеры спрашивались общим запросом, зеркальный торрент считался столько раз,
    сколько индексеров его несут, и все замеры «сколько нашлось» сделаны в этих строках.
    Склейка их обнулять не вправе: иначе один и тот же каталог выглядит то полным, то
    тощим - смотря как опрошены индексеры. Считаем по РАЗНЫМ индексерам, а не по строкам:
    добор вторым именем приносит те же раздачи от тех же индексеров, и складывать круги
    значило бы удваивать каталог на ровном месте.

    🔴 Строки об ОДНОЙ раздаче у разных индексеров расходятся, и оставить строку того,
    кто ответил первым, значило бы отдать выдачу на волю сети. Расхождение массовое:
    на сырых пулах (99 запросов) из 661 раздачи, приехавшей больше чем одной строкой,
    сиды разошлись у 625, имена - у 490. Разрывы не косметические: одна и та же картина
    приезжает то на 2 сидах, то на 26, другая - 8 против 19, а сиды стоят высоко в
    отборе, и мёртвая на вид раздача уходит под все живые. Поэтому склейка выбирает поля
    сама (:func:`_fold`), а не берёт первую попавшуюся строку.

    🔴 TC-257: ИМЕНА принёсших индексеров переезжают в :attr:`RawResult.indexers` целиком.
    Раньше их считали и выбрасывали, оставляя счётчик ``copies``, - а вместе с ними
    пропадал и жанр: аниме-индексер в группе значит «аниме», кто бы ни выиграл имя.

    🔴 TC-382: ИМЕНА самих строк переезжают в :attr:`RawResult.names` целиком - по той же
    причине. Один торрент приходит от разных индексеров под разными именами, и метка
    внешней дорожки (``[RUS(ext), JAP+Sub]`` против ``| L2, L1``) выживала склейку,
    только если побеждало имя с ней. Признаки имён складываются по всем строкам раздачи,
    а не выбираются вместе с именем победителя.
    """
    rows: dict[str, list[RawResult]] = {}
    sources: dict[str, set[str]] = {}
    names: dict[str, set[str]] = {}
    titles: dict[str, set[str]] = {}
    carried: dict[str, int] = {}
    for batch in batches:
        for item in batch:
            key = item.info_hash.lower()
            rows.setdefault(key, []).append(item)
            sources.setdefault(key, set()).add(item.indexer)
            # Счёт copies идёт по СТРОКАМ выдачи (sources) и остаётся прежним, а имена
            # копятся отдельно: склейка склеенного не вправе ни терять их, ни удваивать счёт.
            names.setdefault(key, set()).update(item.indexers or (item.indexer,))
            titles.setdefault(key, set()).update(item.names or (item.title,))
            carried[key] = max(carried.get(key, 1), item.copies)
    return [
        replace(
            _fold(group),
            copies=max(len(sources[key]), carried[key]),
            indexers=tuple(sorted(name for name in names[key] if name)),
            names=tuple(sorted(titles[key])),
        )
        for key, group in rows.items()
    ]


def _fold(rows: list[RawResult]) -> RawResult:
    """Строки одной раздачи - в одну, не глядя, кто ответил первым.

    Рой у раздачи ОДИН: один ``infoHash`` - один и тот же торрент у всех индексеров.
    Расхождение в сидах - это разное время скрейпа, а не разные раздачи, поэтому берём
    максимум: свежая цифра честнее протухшей, а сиды в выдаче и так лишь подсказка -
    живость проверяется по привезённым байтам, а не по обещанию индексера.

    Имя - по большинству, тем же правилом, что у канона картины
    (:func:`~torrcast.domain.by_majority.by_majority`): чаще встретившееся, при равенстве
    короче и дальше по алфавиту.

    Размер - тем же большинством (TC-293): он идёт в прикидку битрейта напрямую, и брать
    его у строки, выигравшей ИМЯ, значило судить вес по тому, кто первым стоит в алфавите
    индексеров. Расходятся размеры на округлении: на 100 сохранённых выдачах 98% пар
    разошлись не больше чем на 0.35%, а очередь, ступень тяжести и дефолт не сменились ни
    у одной картины - поэтому ничья разводится в БОЛЬШУЮ сторону: промах в сторону
    тяжести дёшев (потолок битрейта и сплошной перекод для того и стоят), а заниженный
    размер пропустил бы неподъёмную раздачу мимо ворот. Нулевой размер - не голос, а
    «индексер не сказал»: в счёт он не идёт. Индексер остаётся у строки, чьё имя
    победило, - имя и индексер описывают один ответ каталога, а размер и сиды сводятся по
    всем строкам раздачи.

    ⚠️ Поэтому ``indexer`` тут отвечает на вопрос «чья это строка», а не «откуда раздача».
    Спрашивать его про жанр нельзя: аниме-индексер стоит в алфавите позже общего
    (Nyaa.si против Knaben), и на замере 100 сохранённых выдач аниме-признак так пропадал
    у 170 раздач на 6 аниме-запросах из 19. Кто принёс раздачу на самом деле - в
    :attr:`RawResult.indexers`, их складывает :func:`merge`.
    """
    title = by_majority(Counter(row.title for row in rows))
    sizes = Counter(row.size for row in rows if row.size)
    size = max(sizes, key=lambda s: (sizes[s], s)) if sizes else 0
    return replace(
        min((row for row in rows if row.title == title), key=lambda row: (row.indexer, row.size)),
        size=size,
        seeders=max(row.seeders for row in rows),
    )


__all__ = ["merge"]
