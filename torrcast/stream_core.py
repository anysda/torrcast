MAX_SEGMENT_BYTES: Final = CAUTIOUS.max_segment_bytes
#: Кодеки, которых приёмник не декодирует вовсе: такой файл перекодируется ЦЕЛИКОМ.
#:
#: 🔴 Замер на живом Q70D (07-08): чистый лёгкий HEVC первым куском - LOAD не берётся
#: вовсе (3 попытки из 3), а HEVC-сегмент в середине потока копий - вечный BUFFERING
#: ровно на его границе при упакованном запасе вперёд. То есть смешивать копию и перекод
#: в одном показе нельзя: решение принимается **на уровне файла**, по паспорту ffprobe,
#: а не посегментно по весу и битрейту (:func:`torrcast.cli._encode_all`).
#:
#: Здесь hevc и mpeg4, и это не лень: цена перекода замерена ровно для них - у HEVC
#: двукратный запас к реальному времени, у mpeg4 (XviD/DivX) девятнадцатикратный на
#: DVDRip и тринадцатикратный на 720p. av1/vc1 остаются отказом отбора, пока такого же
#: замера для них нет.
#:
#: ⚠️ Имени кодека для решения МАЛО, и это тоже замер, а не осторожность: H.264 бывает
#: десятибитным (:data:`COPY_DEPTH`), зовётся всё тем же ``h264`` - и приёмник его не
#: декодирует. Поэтому спрашивать надо :func:`recodes_whole`, а не членство в наборе.
#:
#: 🔴 Набор - свойство ПРИЁМНИКА и живёт в его профиле
#: (:attr:`torrcast.profile.Profile.recode_codecs`); здесь он остаётся умолчанием.
RECODE_CODECS: Final = CAUTIOUS.recode_codecs
#: Глубина цвета, которую приёмник берёт копией. Выше - перекод целиком.
#:
#: 🔴 Замер на живом Q70D (09-08, «Death Note» BDRip 1080p, ``h264`` / ``High 10`` /
#: ``yuv420p10le``, 6.5 Мбит/с): доигрывает ровно то, что успело влезть в буфер (~70 с),
#: и встаёт в вечную петлю «залип - закрываю приложение - LOAD - BUFFERING - залип».
