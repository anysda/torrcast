#: Всё, что не буква и не цифра, - разделитель слов: «[TVShows][MVO]», «AVO-Сербин»,
#: «Дубляж. (MovieDalen)» подписаны одной и той же студией, а разделены по-разному.
_WORDS_RE: Final = re.compile(r"[^0-9a-zа-яё]+", re.IGNORECASE)


def studio_of(title: str | None) -> Studio | None:
    """Студия из заголовка дорожки по :data:`STUDIOS`; ``None`` — незнакомая или её нет.

    Сравниваем по словам, а не подстрокой: иначе «Ancord» нашёлся бы в любом слове,
    которое его содержит. Из нескольких совпадений берём самое длинное имя - «HDRezka
    Studio» точнее, чем «HDRezka», и если однажды они разъедутся по ступеням, победит
    более подробная запись.
    """
    words = f" {_WORDS_RE.sub(' ', (title or '').casefold()).strip()} "
    hit = [key for key in STUDIOS if f" {key} " in words]
    return STUDIOS[max(hit, key=len)] if hit else None


#: Технический хвост заголовка: «DUB (Rus) / AC3 / 6 ch / 384 kbps / 48 kHz». Человеку
#: в строке запуска он не нужен, а подписью озвучки (она же ключ памяти) быть мешает.
_TECH_RE: Final = re.compile(
    r"^(?:ac3|eac3|dts(?:-hd)?(?:\s*ma)?|aac|mp3|flac|opus|truehd|pcm|lpcm|dd\+?|ddp"
    r"|\d+\s*ch|\d+\s*kbps|\d+(?:[.,]\d+)?\s*k?hz|\d+\s*bit|\d\.\d)\b",
    re.IGNORECASE,
)


@dataclass(frozen=True, slots=True)
class AudioTrack:
    index: int
    language: str | None = None
    title: str | None = None
    codec: str | None = None
    channels: int = 0

    @property
    def label(self) -> str:
        """Человеческая подпись озвучки: «rus · Дубляж (MovieDalen)».

        Она же ключ памяти (:attr:`torrcast.state.Entry.voice`), поэтому технический
        хвост из неё убран: «DUB (Rus) / AC3 / 6 ch / 384 kbps / 48 kHz» — это одна и та
        же озвучка что с битрейтом в имени, что без.
        """
        lang = self.language
        if (lang or "").strip().casefold() in _VAGUE_LANG:
            # «und»/«unk» человеку про язык не говорят ничего - в подпись их не тащим,
            # иначе озвучка читается как «und», а не как язык. Честную строку про
            # неизвестный язык даёт показ отдельно (:func:`torrcast.cli.sound_note`).
            lang = None
        parts = [p for p in (lang, self.clean_title) if p]
        return " · ".join(parts) if parts else f"дорожка {self.index + 1}"

    @property
    def clean_title(self) -> str:
        """Заголовок без технического хвоста (кодек, каналы, битрейт, частота)."""
        kept: list[str] = []
        for chunk in (self.title or "").split("/"):
            if _TECH_RE.match(chunk.strip()):
                break
            kept.append(chunk.strip())
        return " / ".join(p for p in kept if p).strip(" .")

    @property
    def named(self) -> bool:
        """Назвала ли раздача язык дорожки. ``und``/``unk`` и пустой тег — это «не
        назвала» (:data:`_VAGUE_LANG`): язык неизвестен, и выдавать его за русский
        нельзя (:func:`torrcast.cli.sound_note`)."""
        return (self.language or "").strip().casefold() not in _VAGUE_LANG

    @property
    def is_russian(self) -> bool:
        """Русская ли дорожка. Тег языка сильнее заголовка: «Дубляж» с тегом ``kaz`` —
        казахский дубляж, и слышать его никто не хотел (живой случай «Тачки 3»).
        """
        lang = (self.language or "").strip().casefold()
        if lang in _RU_LANG:
            return True
        if lang not in _VAGUE_LANG:  # язык назван, и он не русский - заголовок не спорит
            return False
        title = self.title or ""
        # Знакомая студия - тоже улика русской дорожки, и часто единственная: у «Барби»
        # заголовок русской дорожки состоит из имени студии целиком («TVShows»).
        named = _RU_TITLE_RE.search(title) or studio_of(title) is not None
        return bool(named) and not _FOREIGN_TITLE_RE.search(title)

    @property
    def studio(self) -> Studio | None:
        """Знакомая студия из заголовка (:func:`studio_of`); ``None`` — не узнали."""
        return studio_of(self.title)

    @property
    def kind(self) -> str:
        """Вид перевода словами: ``дубляж``, ``многоголосый``…; пусто — маркера нет.

        Сперва спрашиваем сам заголовок, и только потом таблицу студий: «MVO. (Jaskier)»
        - это многоголосый, хотя дубляжи Jaskier делает тоже. Что дорожка про себя
        написала, всегда точнее, чем что мы знаем про студию вообще.
        """
        title = self.title or ""
        if named := next((name for name, rx in _VOICE_STEPS if rx.search(title)), ""):
            return named
        studio = self.studio
        return studio.kind if studio else ""

    @property
    def step(self) -> int:
        """Ступень лестницы «самой нормальной» озвучки; меньше — ближе к дефолту."""
        title = self.title or ""
        if _SERVICE_RE.search(title):
            return STEP_SERVICE
        if not self.is_russian:
            return STEP_ORIGINAL if _ORIGINAL_RE.search(title) else STEP_FOREIGN
        steps = (i for i, (name, _) in enumerate(_VOICE_STEPS) if name == self.kind)
        return next(steps, STEP_RU_PLAIN)

    @property
    def rank_step(self) -> int:
        """Ступень, по которой дорожку судят на отборе; обычно это :attr:`step`.

        Расходится с ней только там, где студия крутее своего вида перевода
        (:attr:`Studio.ranks`). Поднимаем, а не опускаем: если дорожка уже назвалась
        дубляжом, отборная ступень студии её не ухудшает. Нерусские и служебные дорожки
        не трогаем вовсе - там ступень означает не качество перевода, а язык.
        """
        step = self.step
        studio = self.studio
        if step >= STEP_RU_PLAIN or studio is None or not studio.ranks:
            return step
        ranks = (i for i, (n, _) in enumerate(_VOICE_STEPS) if n == studio.ranks)
        return min(step, next(ranks, step))


def voice_order(track: AudioTrack) -> tuple[int, int, int]:
    """Место дорожки в очереди на дефолт: ступень, вес студии, порядок в файле.

    Сортируем по трём ключам слева направо (меньше = лучше):
    - ступень лестницы (дубляж=0, многоголосый=1, ...)
    - минус fame: чем выше вес, тем левее студия внутри ступени; отрицательный fame
      (AniDub) уходит правее незнакомых студий с нулевым весом
    - порядок дорожки в файле: сборщик раздачи кладёт первой ту, которую считает главной

    Ступень тут берётся ОТБОРНАЯ (:attr:`AudioTrack.rank_step`), а не та, что
    произносится вслух: «Кубик в Кубе» двухголосые, но крутее всей многоголосой ступени.
    Вслух они остаются двухголосыми - см. :class:`Studio`.
    """
    studio = track.studio
    return (track.rank_step, -(studio.fame if studio else 0), track.index)


@dataclass(slots=True)
class Warmup:
    """Фоновое добавление magnet в TorrServer под меню."""

    magnet: str
    torrent_hash: str = ""
    error: InfraError | None = None
    thread: threading.Thread | None = None

    def result(self, timeout: float = 30.0) -> str:
        """Дождаться hash прогретой раздачи."""
        if self.thread is not None:
            self.thread.join(timeout)
        if self.error is not None:
            raise self.error
        if not self.torrent_hash:
            raise InfraError("TorrServer не принял раздачу за отведённое время")
        return self.torrent_hash


@dataclass(frozen=True, slots=True)
class Media:
    """Что ffprobe вычитал из потока: длительность, звуковые дорожки и кодек видео."""

    duration: float = 0.0
    tracks: tuple[AudioTrack, ...] = ()
    #: Настоящий кодек видео. Имя раздачи врёт или молчит (у «Моаны 2» кодек назван
    #: в 2 именах из 8), а видео мы отдаём ``copy`` - значит ресивер получит ровно его.
    video: str | None = None
    #: Высота кадра из потока. Имя раздачи о качестве тоже молчит через раз, а сказать
    #: человеку «1080p» вместо «?» мы обязаны из того же ffprobe, что уже прочитан.
    height: int = 0
    #: Ширина кадра. Нужна не ради красоты: у широкоформатного фильма чёрные поля
    #: обрезаны, и 1920×800 - это честный 1080p, а не «800p» (:attr:`frame`).
    width: int = 0
    #: Битрейт ВИДЕОДОРОЖКИ, бит/с; ``0`` - паспорт его не несёт (:func:`_video_bps`).
    #:
    #: Это единственное честное «сколько уедет на ТВ»: контейнер тяжелее видео на все
    #: свои дорожки и субтитры, и разрыв не константа - у «Моаны 2» (10 озвучек, 12
    #: субтитров) 4.8 Мбит/с, у «Тачек 3» 2.9, у «Моаны» 2016 - 0.6. Пока этого числа не
    #: было, разрыв набирался вслепую по первым выложенным сегментам
    #: (:meth:`torrcast.recode.Weights.calibrate`) - 8-10 сегментов показа мимо профиля.
    video_bps: float = 0.0

    # ⚠️ Два поля картинки стоят в конце паспорта, а не рядом с ``video``, и это не
    # небрежность: паспорт собирают позиционно в двух десятках мест, и вклинься новое
    # поле в середину - «1080» молча стало бы именем профиля.

    #: Имя профиля видео (``High``, ``High 10``, ``Main 10``); ``None`` - паспорт молчит.
    #:
    #: Само по себе имя ничего не решает, оно второй голос при счёте глубины цвета
    #: (:func:`color_depth`). Но в паспорте оно лежит рядом с ``pix_fmt`` и стоит ноль
    #: лишних запросов, а человеку в отчёте «h264 High 10» говорит больше, чем «h264».
    profile: str | None = None
    #: Формат кадра (``yuv420p``, ``yuv420p10le``) - то, что видит декодер приёмника.
    #:
    #: 🔴 Из него считается глубина цвета (:attr:`depth`), а из неё - решение
    #: «копия или перекод целиком» (:func:`recodes_whole`). Пока этого поля в паспорте не
    #: было, десятибитный H.264 проходил как обычный: имя кодека у них одно на двоих.
    pix_fmt: str | None = None
    #: Кривая яркости потока (``smpte2084``, ``arib-std-b67``, ``bt709``); ``None`` -
    #: паспорт молчит. Из неё считается :attr:`hdr`, а больше ни из чего её не сосчитать:
    #: ни кодек, ни глубина цвета, ни ширина кадра про HDR не говорят ничего.
    color_trc: str | None = None
    #: Развёртка кадра из потока (``progressive``, ``tt``, ``bb``, ``tb``, ``bt``);
    #: ``None`` - паспорт молчит.
    #:
    #: Имя раздачи про развёртку врёт или молчит (релиз, названный «1080p», бывает
    #: чересстрочным внутри), а гребёнку на экране даёт сам файл - значит спрашивать
    #: надо ffprobe, и только его. Молчание читается как прогрессив: звать кадр
    #: чересстрочным по догадке - та же неправда, только в другую сторону.
    field_order: str | None = None

    @property
    def delivered_mbit(self) -> float:
        """Сколько Мбит/с уедет на ТВ в среднем по фильму; ``0`` — паспорт не сказал.

        Видеодорожка идёт копией, звук — всегда AAC (:data:`AUDIO_MBIT`), сверху
        оверхед mpegts (:data:`TS_OVERHEAD`). Отсюда же считается и профиль тяжести
        каждого куска: тот же множитель, только байты берутся из карты опорных кадров.
        """
        if self.video_bps <= 0:
            return 0.0
        return (self.video_bps / 1e6 + AUDIO_MBIT) * TS_OVERHEAD

    def weight_mbit(self, size: int) -> float:
        """Вес релиза для потолка отбраковки, Мбит/с: паспорт, а не размер файла.

        Отбраковка (``bitrate_hard_mbit``) спрашивает «сколько придётся
        перекодировать непрерывно», а это вес **видеодорожки**: звук показ всё равно
        сжимает в AAC 192k, субтитры и лишние озвучки не уезжают никуда. Размер файла на
        длительность отвечает на другой вопрос — «сколько весит контейнер», — и отвечает
        тем хуже, чем больше в релизе дорожек: у «Моаны 2» контейнер 19.2 против видео
        14.3, у «Тачек 3» — 17.0 против 14.1 (замер). То есть потолок 25 мерил
        десять озвучек заодно с картинкой и мог забраковать релиз, который тянется.

        Паспорт молчит (mp4 без тегов, кривой ремукс) — считаем по размеру, как раньше:
        завышенная оценка лучше пропущенного 4K-ремукса на 50 Мбит/с.
        """
        return self.video_bps / 1e6 if self.video_bps > 0 else bitrate_mbit(size, self.duration)

    @property
    def frame(self) -> int:
        """Ступень лестницы качества, к которой относится кадр.

        По одной высоте судить нельзя: 1920×800 (обрезанный скоуп) и 1150×574 дают 800 и
        574 — числа соседние, а это 1080p и SD. Ширина отвечает на это однозначно, потому
        что кадрируют по вертикали: считаем, во что кадр развернулся бы в 16:9, и берём
        большее из двух.
        """
        return max(self.height, self.width * 9 // 16)

    @property
    def interlaced(self) -> bool:
        """Кадр чересстрочный: поедет на экран гребёнкой, и об этом нельзя молчать.

        Значения ``tt``/``bb``/``tb``/``bt`` - порядок полей, который ffprobe читает
        из самого потока; ``progressive`` и молчание паспорта - обычный кадр.
        """
        return (self.field_order or "") in {"tt", "bb", "tb", "bt"}

    @property
    def quality(self) -> str:
        """Качество словами: ``1080p``; ноль высоты — честный ``?``.

        Ступени лестницы называются как принято (2160p/1080p/720p), всё, что ниже, —
        своей высотой: «574p» у «Моаны 2» и есть ответ на вопрос «что уехало на ТВ».

        Буква в конце - развёртка ПО ФАЙЛУ (:attr:`interlaced`), а не по имени раздачи:
        чересстрочный релиз, названный «1080p», называется «1080i», потому что именно
        гребёнка уедет на экран.
        """
        scan = "i" if self.interlaced else "p"
        for step in (2160, 1080, 720):
            if self.frame >= step * 0.95:
                return f"{step}{scan}"
        return f"{self.height}{scan}" if self.height else "?"

    @property
    def depth(self) -> int:
        """Глубина цвета картинки в битах (:func:`color_depth`); ``0`` - видео тут нет."""
        return color_depth(self.pix_fmt, self.profile) if self.video else 0

    @property
    def hdr(self) -> bool:
        """Картинка в HDR: яркость записана не той кривой, которой её покажет SDR-экран.

        Признак ровно один - кривая (:attr:`color_trc`), и подменять её соседями нельзя:
        десятибитный HEVC в BT.2020 бывает и обычным SDR, а 4К - тем более. HDR делает
        именно ``smpte2084`` (PQ, HDR10 и Dolby Vision) или ``arib-std-b67`` (HLG).

        Молчание паспорта (mp4 без тегов, кривой ремукс) читается как SDR: тонемап на
        SDR-исходнике портит картинку ровно так же, как его отсутствие - на HDR.
        """
        return (self.color_trc or "") in {"smpte2084", "arib-std-b67"}

    @property
    def recoded_whole(self) -> bool:
        """Этот файл придётся перекодировать целиком (:func:`recodes_whole`).

        Признак файла, а не куска: приёмник либо декодирует поток, либо нет, и середины
        тут не бывает. Ровно поэтому решение и принимается один раз по паспорту.

        ⚠️ Судит ОСТОРОЖНЫМ профилем: паспорт файла ничего не знает про приёмник, а свой
        приёмник есть не у каждого, кто спрашивает (таблица релизов, строка «перекодирую
        целиком»). Там, где от ответа зависит НАРЕЗКА, спрашивать надо
        :func:`recodes_whole` с профилем показа - иначе прогретое ляжет под другим ключом.
        """
        return recodes_whole(self.video or "", self.depth, frame=self.frame)

    @property
    def video_name(self) -> str:
        """Как называть эту картинку человеку (:func:`codec_name`)."""
        return codec_name(self.video or "", self.depth)

    @property
    def video_warning(self) -> str:
        """Пустая строка, если ресиверу это точно по зубам (HEVC и экзотика).

        ⚠️ Строка честна ровно там, где перекодирования нет: при включённом
        перекодировании HEVC мы берём на себя целиком, и говорит об этом
        :func:`recode_note`, а не она (:meth:`torrcast.cli._Bench.resolve`).

        Десятибитный H.264 сюда попадает наравне с HEVC, хотя зовётся ``h264``: на живом
        Q70D он встаёт (:data:`COPY_DEPTH`), и молчать об этом - та же подмена. Кадр 4К -
        туда же: без перекодирования его не ужать, а копией приёмник его не берёт (TC-157).

        Спрашивается тот же единственный судья, что и у показа
        (:meth:`torrcast.profile.Profile.verdict`): строка и решение обязаны говорить об
        одном файле одно и то же.
        """
        if CAUTIOUS.verdict(self.video or "", self.depth, self.frame) == COPY:
            return ""
        return f"внимание: видео {self.video_name} - ресивер может не взять, а мы не перекодируем"

    @property
    def foreign(self) -> bool:
        """Паспорт ПРЯМО говорит, что русской дорожки в файле нет.

        🔴 TC-178. «Включилось» значит «включилось с русской озвучкой», и решает это не
        имя раздачи, а паспорт: релиз, у которого русской дорожки не оказалось, отбор
        бракует и идёт дальше по очереди (:meth:`torrcast.cli._Bench.resolve`).

        Слово «прямо» тут несёт всю нагрузку. Правда - это ``rus`` рядом с ``jpn``, а
        неправда бывает двух сортов, и обе стоят зрителю картины:

        * дорожек нет вовсе (паспорт прочитан наполовину, ``ffprobe`` отдал одно видео) -
          сказать про язык нечего, и бракуем мы тут не релиз, а собственное незнание;
        * язык дорожки не назван (``und``, :attr:`AudioTrack.named`) - а таких раздач на
          рутрекере полно, и русская дорожка внутри них самая обычная. Достаточно ОДНОЙ
          безымянной дорожки, чтобы паспорт замолчал: судить её нечем, и выкидывать
          картину по догадке нельзя.

        Заголовок при этом не игнорируется: у безымянной дорожки его читает
        :attr:`AudioTrack.is_russian` (знакомая студия, «Дубляж»), и такая дорожка
        считается русской без всякого тега.
        """
        if not self.tracks or any(track.is_russian for track in self.tracks):
            return False
        return all(track.named for track in self.tracks)

    @property
    def russian(self) -> bool:
        """Паспорт ПРЯМО говорит, что русская дорожка в файле есть.

        Не отрицание :attr:`foreign`, и путать их нельзя: у паспорта три ответа, а не два.
        «Да» - вот эта строка, «нет» - :attr:`foreign`, а всё, что осталось между ними, -
        НЕЗНАНИЕ: дорожка без тега языка, про которую ни ffprobe, ни заголовок ничего не
        сказали. Отбор относится к незнанию не так, как к «нет»
        (:func:`torrcast.cli.voice_unproven`):
        отказывать по догадке нельзя, а спросить соседа, чьё имя русскую прямо обещает,
        - можно и стоит.
        """
        return any(track.is_russian for track in self.tracks)

    def default_track(self) -> int:
        """«Самая нормальная» озвучка — та, что играет без вопросов: русский дубляж →
        русский многоголосый → прочий русский → оригинал → чужой дубляж; служебные
        дорожки (тифлокомментарий, комментарии) — в самый низ. Выбор не молчаливый:
        подпись дорожки печатается в строке запуска.
        """
        if not self.tracks:
            return 0
        return min(self.tracks, key=voice_order).index

    def find_voice(self, label: str) -> int | None:
        """Дорожка с такой подписью (память озвучки); ``None`` — такой нет.

        Сравниваем подписи, а не номера: релиз мог смениться, и «дорожка 4» в новом
        релизе — это другая студия. Подпись же (`rus · MVO (LostFilm)`) переживает смену
        релиза ровно тогда, когда та же озвучка в нём есть.
        """
        want = label.casefold().strip()
        if not want:
            return None
        return next((t.index for t in self.tracks if t.label.casefold().strip() == want), None)


#: Сколько бит на цвет обещает ``pix_fmt``: ``yuv420p10le`` → 10, ``p010le`` → 10,
#: ``yuv420p`` → ничего (значит, обычные 8). Суффикс порядка байт к делу не относится,
#: одна цифра после ``p`` - тоже не глубина (``yuv420p`` кончается на ``p``, а не на число).
_DEPTH_FMT: Final = re.compile(r"p(\d{2,3})(?:[lb]e)?$")
#: То же число, но из имени профиля - на случай, когда ``pix_fmt`` не спросили или он
#: пуст: ``High 10``, ``High 10 Intra``, ``Main 10``. Отдельно стоящее число, а не любое:
#: ``High 4:4:4 Predictive`` десятибитным от цифр в имени не становится.
_DEPTH_PROFILE: Final = re.compile(r"(?<!\d)(\d{1,2})(?!\d)")


def color_depth(pix_fmt: str | None, profile: str | None = None) -> int:
    """Глубина цвета картинки в битах по паспорту ffprobe; молчит паспорт - :data:`COPY_DEPTH`.

    Спрашиваем сперва ``pix_fmt``, и это не вкусовщина: формат кадра - то, что видит
    декодер, а имя профиля пишет кодировщик, и оно бывает и пустым, и незнакомым
    (``High 10 Intra``, ``Hi10P`` в одних тулзах против ``High 10`` в ffprobe). Профиль
    остаётся вторым голосом ровно для случая, когда формата кадра в паспорте нет.

    Умолчание тут - именно 8, а не «неизвестно»: показ обязан на что-то решиться, и без
    единого признака десятибитности решаться он должен так же, как решался всегда -
    копией. Отличать «не спрашивали» от «спросили и там восемь» - дело не паспорта, а
    записи состояния (:attr:`torrcast.state.Entry.depth`).
    """
    if pix_fmt and (found := _DEPTH_FMT.search(pix_fmt.strip().casefold())):
        # ``p010le`` - тот же десятибитный кадр, только записанный как у аппаратного
        # декодера: ведущий ноль тут часть имени формата, а не часть числа.
        return int(found.group(1).lstrip("0") or COPY_DEPTH)
    if profile and (bits := _DEPTH_PROFILE.search(profile)):
        return max(COPY_DEPTH, int(bits.group(1)))
    return COPY_DEPTH


def codec_name(codec: str, depth: int = 0) -> str:
    """Как называть картинку человеку: ``h264``, ``h264 10 бит``, ``hevc``.

    Только для строк - в решениях у имени работы нет (:func:`recodes_whole`). Но врать в
    них нельзя: два потока, из которых один приёмник играет часами, а на другом встаёт
    намертво, зовутся в паспорте одинаково - значит, называть их одинаково нельзя нам.
    """
    if not codec:
        return ""
    return f"{codec} {depth} бит" if depth > COPY_DEPTH else codec


def recodes_whole(codec: str, depth: int = 0, profile: Profile = CAUTIOUS, frame: int = 0) -> bool:
    """Пойдёт ли этот файл ЦЕЛИКОМ через перекод - единственный ответ на этот вопрос.

    🔴 Вопрос упаковки задан НАОБОРОТ к тому, как он задавался раньше: не «перечислен ли
    этот кодек среди перекодируемых», а «разрешено ли ему уехать копией»
    (:meth:`torrcast.profile.Profile.verdict`). Разница не косметическая. Пока список был
    чёрным, всё, о чём никто не подумал, уезжало на приёмник как есть: VP9-раздача
    отбраковывалась на отборе, но названная руками (``--release N``) или поднятая из
    записи возобновления доезжала до упаковки, получала ``-c:v copy`` в mpegts - и
    приставка не начинала показ вовсе (``LOAD`` не взят, ``IDLE/ERROR``). Белый список
    такого пропустить не может: копия достаётся только тому, что в нём названо.

    Отказ отбора (:const:`torrcast.profile.REFUSE`) для упаковки означает ровно то же, что
    и перекод: раз мы всё-таки играем этот файл, копия - гарантированный чёрный экран, а
    сплошной перекод - хотя бы шанс. Отбраковывает такое отбор, и делает это раньше
    (:meth:`torrcast.cli._Bench._trouble`).

    🔴 Функция одна на весь код намеренно. Решение принимается дважды - показом
    (:func:`torrcast.cli._play`) и прогревом следующей серии впрок
    (:func:`torrcast.cli._next_warmer`), - и разойтись они не имеют права: прогретое лежит
    под ключом, в который входит перекод (:func:`torrcast.warm.warm_key`), и стоит одному
    месту решить иначе, как показ своего же прогретого не найдёт. Ровно так и вышло с
    десятибитным H.264: показ мешал в одном потоке копию и перекод, SPS не совпадал ни
    одним байтом, а приёмник вставал намертво.

    Поводов ровно четыре, и все - свойство файла, а не куска:

    * кодек, который мы берём на себя целиком (:data:`RECODE_CODECS`);
    * глубина цвета выше :data:`COPY_DEPTH` - десятибитный H.264 (Hi10P), которым собрана
      добрая половина аниме-BDRip. Имя кодека у него то же самое ``h264``, поэтому по
      имени он и проходил как обычный - до замера на живом ТВ;
    * кадр выше :attr:`torrcast.profile.Profile.recode_frame` - 2160p приёмник не берёт и в
      посильном кодеке (TC-157), и перекод его ужимает вниз;
    * кодек, которого нет в белом списке копии вовсе (vp9, av1, vc1, mpeg2video).

    ``depth`` ноль - глубину не спрашивали (запись прежней версии): тогда решаем по
    кодеку, как решали раньше. ``frame`` ноль - то же самое про кадр.

    ``profile`` - чей это декодер (:mod:`torrcast.profile`). Умолчание осторожное: кто
    профиля не назвал, судится по Q70D, то есть ровно как раньше.
    """
    return profile.verdict(codec, depth, frame) != COPY


def recode_note(codec: str, weight_mbit: float = 0.0, frame: int = 0, out_frame: int = 0) -> str:
    """Та самая одна честная строка про сплошной перекод.

    Одна на весь показ и одинаковая везде: и в терминале при выборе релиза, и в журнале
    показа. Прежняя строка «ресивер может не взять, а мы не перекодируем» на HEVC врала
    наполовину — перекодировали, но посегментно, и на экран уезжал смешанный поток.

    ``weight_mbit`` — перекодируем не из-за кодека, а из-за веса (BD-ремукс на
    28–37 Мбит/с). Причина называется вслух вместе с числом: молчаливой подмены «взял
    ремукс и тихо пережал» быть не должно.

    ``frame`` и ``out_frame`` — 🔴 TC-222: кадр ужимается, и молчать об этом нельзя. Взяв
    2160p, показ отдаёт наружу 1080p, и человек, который выбрал 4К-раздачу, обязан
    прочитать это строкой, а не догадаться по чёткости. Ужатия нет (``out_frame`` не ниже
    ``frame``) — строка ровно та же, что была.
    """
    shrink = f", {frame}p - играю в {out_frame}p" if 0 < out_frame < frame else ""
    if weight_mbit > 0:
        return (
            f"видео {codec} {weight_mbit:.0f} Мбит/с - тяжело приёмнику, "
            f"перекодирую целиком{shrink}"
        )
    return f"видео {codec} - перекодирую на ходу целиком{shrink}"


def _file_stats(status: dict[str, Any]) -> list[TorrFile]:
    """Файлы раздачи из ответа службы; пусто - метаданные ещё не приехали."""
    raw = status.get("file_stats")
    if not isinstance(raw, list):
        return []
    return [
        TorrFile(int(i.get("id") or 0), str(i.get("path", "")), int(i.get("length") or 0))
        for i in raw
        if isinstance(i, dict)
    ]


def swarm_alive(status: dict[str, Any]) -> bool | None:
    """Есть ли у раздачи хоть один контакт по мнению самой службы. ``None`` — она молчит.

    Это тот же приём, что :func:`swarm_pulse`, только для фазы, где потока ещё нет.
    Признак жизни у :func:`swarm_pulse` - пришедший байт, и раньше метаданных взять его
    неоткуда: ``/stream`` дожидается метаданных внутри себя, то есть до них не отдаёт ни
    байта даже у самой живой раздачи. Спросить на этой фазе можно ровно одно - что служба
    сама знает про рой, - и приезжает этот ответ тем же опросом (``action=get``), которым
    берутся файлы (:meth:`TorrServer.wait_files`): ни одного лишнего запроса.

    🔴 Считается СОСТОЯВШИЙСЯ контакт, а не найденный адрес, и это замерено, а не выведено.
    У раздачи с мёртвым роем служба бодро рапортует ``total_peers`` 7-9 и столько же
    ``half_open_peers`` и держит их так минутами: это кандидаты из DHT, с которыми никто
    не поговорил. Считай мы их жизнью, отсрочка не срабатывала бы никогда. У живой
    раздачи в тот же миг стоят ``active_peers``, ``connected_seeders`` и ``bytes_read``,
    а у мёртвой этих ключей нет вовсе.

    Отсюда два разных списка слов: «нашли адрес» (total/pending/half open) жизнью не
    считается, «поговорили» (active, connected, скорости, байты) - считается.

    Раздача, про рой которой нам НЕ сказали ВООБЩЕ, обязана ждать полный бюджет ровно
    как ждала всегда - отсюда третий ответ ``None``. Отличаем это от честного нуля по
    тому, есть ли в ответе хоть один счётчик роя: служба, которая про рой рассказывает,
    просто опускает нулевые поля.
    """
    said = False
    for key, value in status.items():
        name = key.casefold()
        if not any(word in name for word in ("peers", "speed", "bytes")):
            continue
        if not isinstance(value, int) or isinstance(value, bool):
            continue
        said = True
        if any(word in name for word in ("total", "pending", "half")):
            continue  # адрес из DHT, а не контакт: у мёртвого роя их тоже 7-9
        if value > 0:
            return True
    return False if said else None


class ServerDownError(InfraError):
    """Умерло СОБСТВЕННОЕ звено - сама служба раздач, а не рой и не раздача.

    Разница с остальными отказами принципиальна: «рой пуст» и «раздача не отдала
    метаданные» относятся к ОДНОМУ релизу, а мёртвая служба - ко всей очереди сразу,
    и перебирать релизы через неё бессмысленно. Поэтому такой отказ опознаётся
    ТИПОМ, а не текстом строки: строка пишется языком зрителя и правится, тип - нет.
    """


class TorrServer:
    """Клиент TorrServer: добавить magnet, дождаться метаданных, отдать URL потока."""

    def __init__(self, base_url: str, timeout: float = _TIMEOUT) -> None:
        self.base_url = base_url.rstrip("/")
        self.timeout = timeout
        self._session: requests.Session | None = None

    def add(self, magnet: str) -> str:
        """Добавить magnet и вернуть его hash. Метаданных на этот момент ещё нет."""
        payload = self._post("/torrents", {"action": "add", "link": magnet, "save_to_db": False})
        if not isinstance(payload, dict):
            raise ServerDownError("TorrServer вернул неожиданный ответ на добавление")
        torrent_hash = str(payload.get("hash", ""))
        if not torrent_hash:
            raise ServerDownError("TorrServer не отдал hash раздачи")
        return torrent_hash

    def warm(self, magnet: str) -> Warmup:
        """Прогрев под меню: magnet уходит фоном и набирает пиров, пока идут вопросы."""
        warmup = Warmup(magnet=magnet)
        thread = threading.Thread(target=self._warm, args=(warmup,), daemon=True)
        warmup.thread = thread
        thread.start()
        return warmup

    def _warm(self, warmup: Warmup) -> None:
        try:
            warmup.torrent_hash = self.add(warmup.magnet)
        except InfraError as exc:  # прогрев не обязан удаться - решает основной путь
            warmup.error = exc

    def status(self, torrent_hash: str) -> dict[str, Any]:
        """Всё, что служба знает про раздачу: файлы, счётчики роя, скорости.

        Отдельный метод от :meth:`files` появился ради одного числа - контактов роя
        (:func:`swarm_alive`). Запрос был и остаётся ОДИН: раньше из его ответа брался
        только список файлов, а остальное выбрасывалось, и ожидание метаданных не знало
        о рое ничего, хотя ответ про него уже лежал в руках.
        """
        payload = self._post("/torrents", {"action": "get", "hash": torrent_hash})
        if not isinstance(payload, dict):
            raise ServerDownError("TorrServer вернул неожиданный ответ на список файлов")
        return payload

    def cache(self, torrent_hash: str) -> dict[str, Any]:
        """Счётчик запаса, который служба ведёт сама: ёмкость кэша и набитое сейчас.

        Отдельный запрос (``POST /cache``), а не поле в ответе :meth:`status`: про кэш
        служба рассказывает только здесь и только про конкретную раздачу - без хэша
        ответ пуст (замер, MatriX.142). Зовётся из ``cast status`` - горячий путь
        показа его не видит, и лишних походов к службе он не добавляет.
        """
        payload = self._post("/cache", {"action": "get", "hash": torrent_hash})
        if not isinstance(payload, dict):
            raise ServerDownError("TorrServer вернул неожиданный ответ на счётчик кэша")
        return payload

    def files(self, torrent_hash: str) -> list[TorrFile]:
        """Список файлов раздачи; пуст, пока метаданные не приехали по DHT."""
        return _file_stats(self.status(torrent_hash))

    def wait_files(
        self,
        torrent_hash: str,
        timeout: float = 60.0,
        grace: float | ContactWait = 0.0,
    ) -> list[TorrFile]:
        """Дождаться метаданных: пиры по DHT и ретрекерам; нет за ``timeout`` — ошибка.

        Ждать приходится рой, и это ожидание неустранимо: TorrServer не отдаёт ни байта,
        пока метаданные не приехали. Устранима только **наша** добавка к нему - остаток
        шага опроса, который мы досыпаем поверх уже пришедших метаданных. Поэтому шаг
        мелкий вначале и растёт до потолка (:data:`META_STEP`, :data:`META_STEP_MAX`):
        в среднем это возвращает полсекунды на каждом старте, где метаданные не мгновенны.

        Последний сон подрезается по ``deadline``: срок ожидания - это срок, а не «до
        конца ближайшего шага после него».

        ``grace`` — сколько секунд рою даётся на ПЕРВЫЙ КОНТАКТ, прежде чем счесть его
        пустым (:func:`swarm_alive`); ноль - не считать вовсе, ждать весь ``timeout``, как
        ждали всегда. Отсрочка тут не второй таймаут, а разделитель двух совершенно
        разных случаев, которые до неё стоили одинаково - полного бюджета:

        * рой медленный: контакты есть, метаданные едут долго. Такой ждём весь бюджет -
          именно ради него бюджет и назначен;
        * роя нет вовсе: за отсрочку служба не насчитала ни пира, ни байта. Ждать нечего
          и некого, и следующий релиз в очереди узнает об этом на четырнадцать секунд
          раньше (:data:`torrcast.cli.PEER_GRACE` против :data:`torrcast.cli.META_BUDGET`).

        Здоровая раздача не платит за отсрочку ни миллисекунды: её метаданные приезжают
        первыми же опросами, то есть до всякой проверки контактов.
        """
        began = time.monotonic()
        deadline = began + timeout
        hopeless = began + float(grace)
        step = META_STEP
        while True:
            status = self.status(torrent_hash)
            files = _file_stats(status)
            if files:
                return files
            now = time.monotonic()
            if isinstance(grace, ContactWait):
                activated = grace.activated_at
                if activated is None:
                    time.sleep(min(step, META_STEP_MAX))
                    step = min(step * META_STEP_GROW, META_STEP_MAX)
                    continue
                deadline = activated + timeout
                hopeless = activated + grace.seconds
            seconds = grace.seconds if isinstance(grace, ContactWait) else grace
            if seconds > 0 and now >= hopeless and swarm_alive(status) is False:
                raise SwarmError(f"рой пуст - за {seconds:.0f} с ни одного пира")
            left = deadline - now
            if left <= 0:
                raise SwarmError(f"раздача не отдала метаданные за {timeout:.0f} с - нет пиров")
            time.sleep(min(step, left))
            step = min(step * META_STEP_GROW, META_STEP_MAX)

    def stream_url(self, torrent_hash: str, index: int) -> str:
        """HTTP-URL потока конкретного файла раздачи.

        ⚠️ В URL едет ТОЛЬКО хэш, и это существенно: TorrServer, не найдя такой раздачи у
        себя, заводит её по одному хэшу - без трекеров, которые были в магните. Замерено
        после перезапуска службы: раздача есть, пиры ищутся только по DHT, за 25 с ноль
        байт. Поэтому раздачу после аварии источника возвращает МАГНИТ (:class:`Supply`),
        а не наш же поток.
        """
        return f"{self.base_url}/stream?link={quote(torrent_hash)}&index={index}&play"

    def alive(self) -> bool:
        """Отвечает ли служба вообще (``GET /echo``). Молчание и ошибка сети - ``False``.

        Спрашивается только на краю показа (:class:`Supply`), поэтому срок короткий:
        живая служба отвечает за миллисекунды, а мёртвая не ответит и за минуту.
        """
        import requests

        if self._session is None:
            self._session = requests.Session()
        try:
            response = self._session.get(f"{self.base_url}/echo", timeout=PROBE_TIMEOUT)
            response.raise_for_status()
        except requests.RequestException:
            return False
        return True

    def listed(self, torrent_hash: str) -> bool:
        """Есть ли такая раздача в списке службы. Сравнение по хэшу, регистр не в счёт."""
        payload = self._post("/torrents", {"action": "list"})
        if not isinstance(payload, list):
            raise ServerDownError("TorrServer вернул неожиданный ответ на список раздач")
        want = torrent_hash.casefold()
        return any(
            isinstance(item, dict) and str(item.get("hash", "")).casefold() == want
            for item in payload
        )

    def drop(self, torrent_hash: str) -> bool:
        """Убрать раздачу; ``True`` - служба ответила, и раздачи у неё больше нет.

        Отсутствие раздачи ошибкой не считается и здесь: на хэш, которого служба не знает,
        она отвечает обычным «убрал» (замер), поэтому повторный снос ничего не стоит.
        Значит осечка тут означает ровно одно - службы сейчас нет, и раздача как была, так
        и осталась. Разницу между «убрал» и «не дозвонился» видно только по этому ответу, а
        не по исключению: ждать службу на выходе показа нельзя, поэтому осечка по-прежнему
        не авария (:func:`torrcast.cli._release_torrents`).

        ⚠️ Тело ответа на снос ПУСТОЕ, и это не поломка: службе нечего о нём рассказывать.
        Пока пустой ответ считался «не JSON», снос был неотличим от мёртвой службы вообще
        всегда - и по нему нельзя было судить ни о чём (``json_body=False``).
        """
        try:
            self._post("/torrents", {"action": "rem", "hash": torrent_hash}, json_body=False)
        except InfraError:
            return False
        return True

    def _post(self, path: str, body: dict[str, Any], json_body: bool = True) -> Any:
        import requests

        if self._session is None:
            self._session = requests.Session()
        try:
            response = self._session.post(f"{self.base_url}{path}", json=body, timeout=self.timeout)
            response.raise_for_status()
        except requests.RequestException as exc:
            raise ServerDownError(f"TorrServer не отвечает ({self.base_url}): {why(exc)}") from exc
        if not json_body:  # служба ответила - больше от неё тут ничего и не нужно
            return None
        try:
            return response.json()
        except ValueError as exc:
            raise ServerDownError("TorrServer вернул не JSON") from exc
