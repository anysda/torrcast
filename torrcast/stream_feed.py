@dataclass(slots=True)
class Packer:
    """Один прогон упаковки: процесс ffmpeg, который пакует фильм с сегмента ``first``.

    ffmpeg пишет в свой каталог (:data:`PACK_DIR`), наружу сегменты выкладывает
    :meth:`publish` переименованием. Так решаются сразу две вещи: наружу не попадает
    недописанный кусок и не затирается чужой (см. :data:`PACK_DIR`).
    """

    proc: subprocess.Popen[bytes]
    out: Path
    #: Каталог этого прогона: сюда ffmpeg кладёт куски, включая мусорную докатку.
    run: Path
    #: С какого сегмента сетки начат этот прогон: всё, что раньше, паковал не он.
    first: int = 0
    #: **Честный край прогона**: последний сегмент, который ЭТОТ прогон выложил наружу
    #: (:meth:`publish`). ``first - 1`` - не выложено ещё ничего.
    #:
    #: Ровно это число, а не глоб каталога (:meth:`frontier`), отвечает на вопрос «кусок
    #: вот-вот допакуется или его не будет вовсе» (:meth:`Feed._steer`). Разница не
    #: теоретическая: в каталоге показа лежат и куски прошлых прогонов - сетка одна на
    #: весь показ, поэтому они честные и отдаются приёмнику, - но к тому, докуда дошёл
    #: текущий прогон, они отношения не имеют. Глоб путал одно с другим в обе стороны:
    #: «край» уезжал вперёд на чужие куски (запрос далеко назад считался ожиданием и
    #: висел до 404) и назад на свежий каталог (замер: 20 ложных перезапусков
    #: за 100 с показа). Здесь край растёт только там, где мы сами переименовали файл, -
    #: и там, где прогон честно решил, что куска не будет никогда (:attr:`shrink`).
    edge: int = -1
    log: Any = None
    #: Выкладка может прийти из запроса приёмника и из часов показа одновременно.
    #: Второй заход не ждёт первый: горячий путь проверит готовый файл следующим
    #: оборотом, а два решения над одними исходниками опаснее пропущенного опроса.
    publish_lock: Any = field(default_factory=threading.Lock)
    #: Упаковку погасили намеренно (пауза на пульте) - смерть процесса не авария.
    halted: bool = False
    #: Зачем мы сами сняли этот прогон (:meth:`stop`); пусто - мы его не трогали.
    #:
    #: ⚠️ Без этой строки собственный ``terminate`` неотличим от аварии: ffmpeg по SIGTERM
    #: выходит **кодом 255** (положительным!), а «Exiting normally, received signal 15» он
    #: пишет уровнем ``info``, то есть при нашем ``-loglevel warning`` не пишет ничего.
    #: Ровно так и родился 🔴 «первый прогон следующей серии умирает молча»:
    #: показ ругался на труп, который сам же и снял.
    stopped: str = ""
    #: Обрыв ЭТОГО прогона уже посчитан (:meth:`Feed._survive`).
    blamed: bool = False
    #: Каталог перекодированных кусков. Если для слота там лежит готовый кусок,
    #: наружу идёт он, а копия выбрасывается: место в фильме и метки те же, а битрейт
    #: такой, который приёмник гарантированно тянет.
    #:
    #: Выкладка остаётся ровно здесь, вторым выкладывающим кодировщик не становится -
    #: иначе инвариант «край двигает только состоявшееся переименование» (:attr:`edge`)
    #: пришлось бы держать в двух местах.
    spare: Path | None = None
    #: Кого позвать, когда сегмент ушёл наружу: ``(слот, чем он ушёл)``.
    #:
    #: «Чем» - это ``копия``, ``склейка`` (картинка перекода со звуком копии) или
    #: ``перекод`` (склейка не вышла). Различать их обязательно: раньше в журнал шло
    #: одно слово «перекод» на два разных исхода, и «склейка молча не вышла» нельзя было
    #: ни увидеть, ни опровергнуть - три подвиса на сериале разбирались вслепую.
    told: Any = None
    #: Последний сегмент, который этому прогону разрешено выложить; ``-1`` - без предела.
    #:
    #: ⚠️ Нужно ровно кодировщику и ровно против ОБРЕЗКА. Заход кодировщика ограничен
    #: ``-to`` с запасом в секунду (:func:`ffmpeg_pack_command`), и на этот запас муксер
    #: успевает открыть СЛЕДУЮЩИЙ файл - в нём остаётся секунда фильма вместо десяти.
    #: Дальше этот огрызок лежал в :data:`torrcast.recode.RECODE_DIR` как готовый кусок и
    #: выкладывался наружу вместо честной копии: живой Q70D на «Тачках 3» -
    #: ``v311`` 1.3 МБ вместо 11 МБ, приёмник встал на 8 с и потерял 8 секунд фильма.
    #: У «Моаны 2» это не всплывало: там тяжелы почти все куски подряд, и огрызок всегда
    #: успевал смениться настоящим перекодом следующего захода.
    last: int = -1
    #: Когда прогон начался (``time.monotonic``) и с какой секунды ФИЛЬМА ffmpeg читает
    #: вход (``-ss``, то есть с учётом докатки). Вместе с :attr:`rate` и :attr:`burst` это
    #: и есть планка чтения ffmpeg, по которой считается :meth:`eta`.
    began: float = 0.0
    at: float = 0.0
    #: ``-readrate`` и ``-readrate_initial_burst`` этого прогона; ноль - читаем без темпа.
    rate: float = 0.0
    burst: float = 0.0
    #: Сетка показа: по ней прогон паковали, по ней же сверяется, дописан ли последний
    #: кусок (:meth:`finished`). ``None`` - сверять не с чем, и слово ffmpeg остаётся
    #: единственным признаком.
    grid: Grid | None = None
    #: Ответ :meth:`finished`, посчитанный один раз; ``None`` - ещё не считали.
    whole: bool | None = None
    #: Кого спросить «этот кусок сейчас перекодируют, подожди»: ``(слот, вес копии) -> bool``.
    #:
    #: Нужно ровно против одной гонки, найденной живым прогоном: упаковщик на
    #: старте прогона выкладывает ``burst`` (60 с) разом, а кодировщику на эти же 60 с
    #: нужно вдвое меньше, но не мгновение, - и тяжёлые куски уходили копией просто
    #: потому, что упаковщик их обогнал. Придержанный кусок никуда не девается: он лежит
    #: в каталоге прогона и выложится либо перекодированным, либо как есть по истечении
    #: срока. Ждать при этом безопасно только там, докуда показу ещё далеко, - за этим
    #: следит спрашиваемый (:meth:`torrcast.recode.Recoder.holding`).
    hold: Any = None
    #: Кого позвать на последнем гейте, когда кусок тяжелее потолка приёмника, а ждать
    #: перекод уже не стали: ``(слот, вес копии) -> bool``. ``True`` - в :attr:`spare`
    #: лежит свежий перекод под потолок, и наружу идёт он. ``False`` - ужать не вышло:
    #: место честно пропускается, но выкладка идёт дальше. ``None`` - решать некому,
    #: выкладка встаёт на таком куске (поведение до TC-467).
    #:
    #: Без этого звонка тяжёлая копия останавливала выкладку навсегда: ``break`` не
    #: двигал край и не удалял саму копию, а всё за ней копилось в памяти до потолка
    #: несданного; потолок гасил прогон, запрос приёмника поднимал его заново - и круг
    #: повторялся, потому что тяжёлый кусок детерминирован.
    shrink: Any = None

    def __post_init__(self) -> None:
        # Прогон, который ещё ничего не выложил, стоит ровно перед своим первым сегментом:
        # так «край» и «ниже края» осмысленны с первой же секунды, до всякого publish.
        self.edge = max(self.edge, self.first - 1)

    @classmethod
    def start(
        cls,
        command: list[str],
        out: Path,
        run: Path,
        first: int = 0,
        spare: Path | None = None,
        told: Any = None,
        hold: Any = None,
        shrink: Any = None,
        last: int = -1,
        at: float = 0.0,
        rate: float = 0.0,
        burst: float = 0.0,
        grid: Grid | None = None,
    ) -> Packer:
        log = tempfile.TemporaryFile()  # noqa: SIM115 - живёт всё воспроизведение
        shutil.rmtree(run, ignore_errors=True)
        run.mkdir(parents=True, exist_ok=True)
        began = time.monotonic()
        try:
            proc = subprocess.Popen(command, stdout=subprocess.DEVNULL, stderr=log)
        except FileNotFoundError as exc:
            raise InfraError("ffmpeg не установлен") from exc
        return cls(
            proc=proc,
            out=out,
            run=run,
            first=first,
            log=log,
            spare=spare,
            told=told,
            hold=hold,
            shrink=shrink,
            last=last,
            began=began,
            at=at,
            rate=rate,
            burst=burst,
            grid=grid,
        )

    def eta(self, film: float) -> float:
        """Через сколько секунд ffmpeg дочитает вход до секунды ``film``. Оценка снизу.

        Считается по собственной планке ffmpeg, а не по нашим наблюдениям: с
        ``-readrate R -readrate_initial_burst B`` он читает всё, что ниже
        ``-ss + B + прошло * R``, на полной скорости, а выше — ровно в темпе ``R``
        (``readrate_sleep`` в ``ffmpeg.c``). Значит место ``film`` он тронет не раньше, чем
        через ``(film - планка) / R``.

        Оценка **снизу** намеренно: реальный прогон может отставать и от планки (холодный
        рой, слабый процессор), и тогда ждать придётся дольше. Но решение, которое на ней
        строится, — «перезапустить упаковку с этого места» (:meth:`Feed._steer`), а
        перезапуск лечит ровно упирание в темп и ничем не помогает отставанию по входу.
        Поэтому недооценка тут безопасна, а переоценка стоила бы лишних перезапусков.

        ``rate <= 0`` — темпа нет, ffmpeg читает во весь опор: ждать нечего, ноль.
        """
        if self.rate <= 0:
            return 0.0
        reach = self.at + self.burst + (time.monotonic() - self.began) * self.rate
        return max(0.0, (film - reach) / self.rate)

    def finished(self) -> bool:
        """Прогон дочитал вход до конца - а не просто вышел из процесса.

        🔴 Ноль от ffmpeg этого не доказывает. Вход, умерший на середине, ffmpeg
        отмечает строкой ``Error during demuxing: Input/output error`` - и **выходит
        нулём**. Замер: 108 обрывов на 108 местах файла, ноль вышел 4 раза, и трижды
        последний кусок оказался дописан не до конца. На одном и том же месте исход не
        повторяется - это гонка между концом чтения и концом записи, поэтому редкость
        тут ничего не значит: по одному коду возврата обрезок (замер: от нуля до 9.4 с
        вместо обещанных 10) уезжает зрителю как готовый кусок, тихо и без единой жалобы
        в журнале. А оборванный файл - вход не рвётся, а кончается - даёт ноль всегда:
        12 прогонов из 12.

        Поэтому спрашивается не код, а обещание сетки. Где кончился последний кусок,
        говорит сам ffmpeg в своём списке нарезки (:meth:`cuts`); где он обязан был
        кончиться - :meth:`Grid.end`. Недобор больше :data:`PACK_SHORT_SECONDS` - прогон
        оборвался, каким бы кодом он ни вышел.

        Куски за пределом захода (:attr:`last`) в счёт не идут: заход кодировщика
        ограничен ``-to`` с запасом в секунду, и огрызок за этим пределом короче своего
        места по замыслу, а не по аварии.

        Считается один раз на прогон: у мёртвого процесса ни файлы, ни список уже не
        меняются, а спрашивают отсюда и выкладка, и горячий путь показа.
        """
        if self.whole is None:
            if self.proc.poll() != 0:
                return False
            self.whole = self._reached()
        return self.whole

    def _reached(self) -> bool:
        grid = self.grid
        if grid is None:
            return True
        mine = [
            slot
            for slot in map(segment_slot, _names(self.run))
            if slot >= 0 and (self.last < 0 or slot <= self.last)
        ]
        if not mine:
            return True  # прогон не написал ни одного своего куска - обрываться нечему
        tail = max(mine)
        ends = {slot: end for slot, _began, end in self.cuts()}
        if tail not in ends:
            # Кусок закрыт, а строки о нём нет: список ведёт тот же ffmpeg и пишет её
            # ровно на закрытии (``-segment_list_flags +live``). Верить тут нечему.
            return False
        return ends[tail] >= grid.end(tail) - PACK_SHORT_SECONDS

    def publish(self) -> None:
        """Выложить готовое одним заходом, не удерживая конкурирующий горячий путь."""
        if not self.publish_lock.acquire(blocking=False):
            return
        try:
            self._publish()
        finally:
            self.publish_lock.release()

    def _publish(self) -> None:
        """Выложить наружу куски, которые ffmpeg уже дописал.

        Дописан тот, за которым появился следующий: сегментный муксер открывает новый
        файл ровно тогда, когда закрыл прошлый. Последний кусок такого соседа не получит
        никогда, поэтому за него отвечает отдельный признак (:meth:`finished`).
        Докатка (номер меньше ``first``) не выкладывается никогда — она короче своего
        места в манифесте и под её именем может лежать честный сегмент прошлого прогона.
        """
        slots = sorted(s for s in map(segment_slot, _names(self.run)) if s >= 0)
        if not slots:
            return
        # Прогон дочитал вход до конца - дописан и последний кусок (:meth:`finished`).
        # Любой другой исход (жив, убит, оборвался) последний кусок дописанным не делает.
        done = slots if self.finished() else slots[:-1]
        for slot in done:
            path = self.run / segment_name(slot)
            # Ниже своего первого - докатка, выше последнего - обрезок за ``-to``
            # (:attr:`last`). И то и другое короче своего места в манифесте, и наружу
            # такое отдавать нельзя ни при каких обстоятельствах.
            if slot < self.first or 0 <= self.last < slot:
                path.unlink(missing_ok=True)
                continue
            # Кусок сейчас перекодируют - подождём его (:attr:`hold`). Дальше по списку не
            # идём: выложить следующий, оставив дыру, значит увести край за неё, и запрос
            # придержанного места выглядел бы для :meth:`Feed._steer` перемоткой назад.
            #
            # Спрашивающему отдаётся ВЕС уже готовой копии, и это не оптимизация, а
            # единственный честный замер: предсказание по карте зажато потолком
            # перекодирования и на «Тачках 3» промахнулось вчетверо (11.7 МБ против
            # 51.4). Стоит он один ``stat`` на выложенный сегмент.
            size = 0
            with contextlib.suppress(OSError):
                size = path.stat().st_size
            if self.hold is not None and self.hold(slot, size):
                break
            # Перекодированный кусок этого же места лучше копии: то же разрешение и те же
            # метки, но битрейт, который приёмник тянет. Копия при этом выбрасывается.
            better = self.spare / segment_name(slot) if self.spare is not None else None
            source, how = path, "копия"
            if better is not None and better.exists():
                # Наружу идёт картинка перекода со звуком копии (:func:`merge_tracks`):
                # звук показа обязан остаться одним непрерывным потоком, а сама
                # картинка - лечь на ленту ЭТОГО прогона (:func:`timeline_shift`).
                mixed = self.run / f"{MIXED_PREFIX}{slot}.ts"
                shift = timeline_shift(path, better)
                if merge_tracks(better, path, mixed, shift=shift or 0.0):
                    source, how = mixed, "склейка"
                elif shift and size and size <= MAX_SEGMENT_BYTES:
                    # Лента прогона сдвинута, а склейки нет: перекод как есть - это
                    # гарантированный разрыв на кадр, и копия своего же прогона
                    # тут меньшее зло. Но только пока она не тяжелее потолка: кусок,
                    # который приёмник не доигрывает вовсе, хуже любого стыка.
                    source, how = path, "копия"
                else:
                    source, how = better, "перекод"
            # Последний гейт стоит после склейки: только здесь известен вес ровно того
            # файла, который получит приёмник. Обе его части могут влезать по отдельности,
            # а готовый MPEG-TS - выйти за потолок из-за звука и накладных расходов.
            # Тогда голое видео перекода безопаснее; если не влезло и оно, наружу не
            # выходит ничего. Так же здесь остаётся тяжёлая копия, которую предохранитель
            # ожидания отпустил после срыва кодировщика.
            try:
                oversized = source.stat().st_size > MAX_SEGMENT_BYTES
            except OSError:
                oversized = False
            if oversized and how == "склейка" and better is not None:
                source.unlink(missing_ok=True)
                try:
                    safe_recode = better.stat().st_size <= MAX_SEGMENT_BYTES
                except OSError:
                    safe_recode = False
                if safe_recode:
                    source, how = better, "перекод"
                    oversized = False
            # Наружу такой кусок отдавать нельзя, но и вставать на нём навсегда нельзя:
            # прежний ``break`` тут не двигал край и не удалял копию, всё за ней копилось
            # в памяти до потолка несданного, потолок гасил прогон, запрос приёмника
            # поднимал его заново - и круг повторялся, потому что тяжёлый кусок
            # детерминирован. Поэтому сначала одна попытка ужать кусок прямо сейчас
            # (:attr:`shrink`) - перекод под потолок ложится в spare, и наружу идёт он,
            # как есть: его звук - та же дорожка AAC, что у копии.
            shrunk = oversized and self.shrink is not None and self.shrink(slot, size)
            if shrunk and better is not None:
                try:
                    oversized = better.stat().st_size > MAX_SEGMENT_BYTES
                except OSError:
                    oversized = True
                if not oversized:
                    source, how = better, "перекод"
            if oversized:
                if how == "склейка":
                    source.unlink(missing_ok=True)
                if self.shrink is not None:
                    # Ужать не вышло - честный пропуск: кусок не отдаём никому, но и
                    # не стоим на нём. Пропуск - тоже решение выкладки, и край двигает
                    # именно оно: иначе это место встречало бы каждый следующий прогон,
                    # а его запрос крутил бы перепаковку вечно. Приёмнику про пропуск
                    # отвечает показ (:attr:`Feed.skipped`), одной строкой и один раз.
                    path.unlink(missing_ok=True)
                    if better is not None:
                        better.unlink(missing_ok=True)
                    self.edge = max(self.edge, slot)
                    continue
                break
            moved = False
            with contextlib.suppress(OSError):
                os.replace(source, self.out / segment_name(slot))
                # Край двигает только состоявшееся переименование: «выложил» - это факт
                # этой строки, а не наличие файла в каталоге (:attr:`edge`).
                self.edge = max(self.edge, slot)
                moved = True
            # Выложили одно из трёх - остальные две копии этого места больше не нужны
            # никому: tmpfs не резиновая, а лишний файл в каталоге перекода ещё и выглядел
            # бы для кодировщика готовым куском (:meth:`torrcast.recode.Recoder.ready`).
            if moved and source is not path:
                path.unlink(missing_ok=True)
            if moved and better is not None and source is not better:
                better.unlink(missing_ok=True)
            if moved and self.told is not None:
                with contextlib.suppress(Exception):
                    self.told(slot, how)

    def cuts(self) -> list[tuple[int, float, float]]:
        """Что ffmpeg нарезал на самом деле: ``(сегмент, начало, конец)`` по его же списку.

        Нужно ровно для одного: сверить факт с манифестом (:meth:`drift`). Первую строку
        списка приходится пропускать — в ней ffmpeg пишет начало прогона нулём.
        """
        found: list[tuple[int, float, float]] = []
        try:
            text = (self.run / PACK_LIST).read_text("utf-8", "replace")
        except OSError:
            return found
        for line in text.splitlines():
            parts = line.strip().rstrip(",").split(",")
            if len(parts) < 3:
                continue
            slot = segment_slot(parts[0].rsplit("/", 1)[-1])
            with contextlib.suppress(ValueError):
                found.append((slot, float(parts[1]), float(parts[2])))
        return found

    def drift(self, grid: Grid) -> float:
        """Насколько нарезанное разошлось с обещанным в манифесте, секунды.

        Ноль (точнее, доли кадра) — манифест не врёт: ``EXTINF`` совпадает с фактом.
        Больше кадра — повод не верить нарезке и сказать об этом в журнал: значит, карта
        опорных кадров разошлась с потоком.
        """
        worst = 0.0
        for slot, began, _ in self.cuts()[1:]:
            if slot >= self.first:
                worst = max(worst, abs(began - grid.start(slot)))
        return worst

    def pending(self) -> int:
        """Сколько байт этот прогон уже написал в tmpfs, но наружу не отдал.

        Всё, что лежит в каталоге прогона: и кусок, который ffmpeg пишет прямо сейчас, и
        те, что выкладка не пропустила (придержаны под перекод, тяжелее потолка). Наружу
        уходит переименованием (:meth:`publish`), поэтому выложенное сюда не попадает и
        считается дважды быть не может.
        """
        total = 0
        with contextlib.suppress(OSError):
            for path in self.run.iterdir():
                with contextlib.suppress(OSError):
                    total += path.stat().st_size
        return total

    def frontier(self) -> int:
        """Последний готовый сегмент в каталоге показа; ``first - 1`` — готового нет.

        ⚠️ Это **не** край прогона (:attr:`edge`): счёт идёт глобом каталога, где лежат и
        куски прошлых прогонов, поэтому после перемотки назад число врёт вверх. Решения
        об упаковке на нём больше не строятся (:meth:`Feed._steer`); осталось оно ровно
        под :meth:`Feed.front` — запас показа для сторожа приёмника, который доказан на
        живом ТВ, и менять его без такой же живой проверки нельзя.
        """
        self.publish()
        slots = [s for s in map(segment_slot, _names(self.out)) if s >= self.first]
        return max(slots, default=self.first - 1)

    def halt(self, reason: str = "пауза на пульте") -> None:
        """Погасить упаковку, **не трогая уже упакованное**: приёмник на паузе, и копить
        сегменты в tmpfs незачем. Возобновление — новый прогон (:meth:`Feed.segment`).

        Раньше на этом месте стояла пауза сигналом (SIGSTOP). Она и оказалась причиной
        подвиса: манифест замирает, а приёмник намертво виснет в BUFFERING —
        держит коннект и не запрашивает ничего. Поэтому процесс именно завершается.
        """
        self.halted = True
        self.stop(keep_files=True, reason=reason)

    def poll(self) -> int | None:
        return self.proc.poll()

    def why(self) -> str:
        """Почему прогон кончился — наружу без трейсбеков.

        Порядок ответов честный: сначала «мы сами» (:attr:`stopped`), потом слово ffmpeg,
        и только если он промолчал — код возврата. Молчание при коде 255 не загадка, а
        подпись нашего же SIGTERM (см. :attr:`stopped`), и выдавать её за аварию нельзя.
        """
        if self.stopped:
            return f"сняли сами: {self.stopped}"
        code = self.proc.poll()
        if code is not None and code < 0:
            return f"убит сигналом {-code}"  # сказать он не успел - не выдумываем за него
        lines: list[str] = []
        if self.log is not None:
            self.log.seek(0)
            text = self.log.read().decode("utf-8", "replace")
            lines = [ln for ln in text.splitlines() if ln.strip()]
        if lines:
            return lines[-1][:120]
        return "нет вывода" if code is None else f"молча, код {code}"

    def stop(self, keep_files: bool = False, reason: str = "") -> None:
        self.stopped = self.stopped or reason
        if self.proc.poll() is None:
            self.proc.terminate()
            with contextlib.suppress(subprocess.TimeoutExpired):
                self.proc.wait(timeout=5)
            if self.proc.poll() is None:
                self.proc.kill()
        self.publish()  # дописанное этим прогоном остаётся показу: оно уже верное
        shutil.rmtree(self.run, ignore_errors=True)
        if not keep_files:
            for junk in _paths(self.out):
                junk.unlink(missing_ok=True)


def timeline_shift(copy: Path, recode: Path, timeout: float = _TIMEOUT) -> float | None:
    """На сколько лента прогона опережает время фильма, секунды; ``None`` — не сверили.

    Прогон упаковки и заход перекода — два разных ffmpeg, и время фильма они пишут
    одинаково **не всегда**. Когда прогон начинается с ``-ss``, метки
    выходят ровно те же, что в карте опорных кадров. Но у прогона **с нуля** (первый
    сегмент серии) отрицательного dts быть не может: у релиза с B-кадрами первый пакет
    идёт с ``dts = pts − кадр``, и mpegts-муксер двигает ВЕСЬ прогон вперёд на этот кадр
    (``avoid_negative_ts``). Замер на «Киберпанке» s1e6: копия отдаёт границу 30.072,
    перекод того же места — 30.030, разница ровно 41.7 мс = один кадр 23.976p.

    Считается по первым пакетам обоих кусков: у обоих это один и тот же опорный кадр
    фильма, поэтому разница их меток — и есть сдвиг ленты. Дороже одного ``ffprobe`` на
    файл (первые четыре пакета) это не стоит.

    ``None`` — сверить не вышло (нет ffprobe, битый кусок) или разница вышла больше
    секунды: столько между двумя кусками ОДНОГО места быть не может, значит мерили не то.
    """
    marks: list[float] = []
    for path in (copy, recode):
        command = [
            "ffprobe", "-v", "error", "-select_streams", "v", "-read_intervals", "%+#4",
            "-show_entries", "packet=pts_time", "-of", "csv=p=0", str(path),
        ]  # fmt: skip
        try:
            done = subprocess.run(command, capture_output=True, timeout=timeout, check=False)
        except (OSError, subprocess.SubprocessError):
            return None
        found = []
        for line in done.stdout.decode("utf-8", "replace").splitlines():
            with contextlib.suppress(ValueError):
                found.append(float(line.strip().rstrip(",")))
        if not found:
            return None
        marks.append(min(found))
    shift = marks[0] - marks[1]
    return None if abs(shift) > 1.0 else shift


def merge_tracks(
    video: Path, audio: Path, dst: Path, timeout: float = _TIMEOUT, shift: float = 0.0
) -> bool:
    """Собрать сегмент из картинки ``video`` и звука ``audio``; ``False`` — не вышло.

    Ради этого и написано: **звук показа должен быть одним непрерывным
    потоком одного кодировщика**, а перекодированный кусок приносит свой.

    Кадровая сетка AAC отсчитывается от начала прогона ffmpeg: первый кадр встаёт на
    ``-ss`` этого прогона, дальше через 1024 сэмпла (21.33 мс). Упаковщик и кодировщик —
    разные прогоны с разными ``-ss``, поэтому их сетки сдвинуты друг относительно друга на
    произвольную долю кадра. Пока куски берутся из одного прогона, стык звука точен до
    микросекунды; на **первом** куске каждого захода перекода звук копии обрывается, а
    звук перекода начинается позже — замер на «Тачках 3»: дыра **40.7 мс** на
    3973.678 при нуле на всех соседних стыках. Приёмник Q70D платит за эту дыру не сорока
    миллисекундами, а 2–5 секундами: он пересобирает синхронизацию.

    Поэтому наружу идёт картинка перекода со звуком копии — того самого прогона, что
    выложил соседние куски. Границы у них одни (сетка одна), метки абсолютные (``-copyts``),
    так что склейка — это переупаковка без единого перекодирования: 0.09–0.11 с на кусок
    12 МБ, замер.

    ``shift`` (:func:`timeline_shift`) кладёт картинку перекода на ленту **этого прогона**:
    у прогона с нуля метки сдвинуты на кадр вперёд относительно времени фильма, и без
    поправки на голове захода приёмник получает кадр с меткой НАЗАД, а на хвосте — дыру
    в кадр. Стоит поправка одного ``-itsoffset``: переупаковка та же.

    ⚠️ Не вышло — врать нельзя: возвращаем ``False``, и :meth:`Packer.publish` решает,
    что выкладывать вместо склейки — копию своего прогона (если она не тяжелее потолка)
    или перекод как есть.
    """
    command = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-copyts"]
    # Полкадра - порог осмысленности: ниже него сдвига нет, а не «есть, но крошечный».
    if abs(shift) >= 0.001:
        command += ["-itsoffset", f"{shift:.6f}"]
    command += [
        "-i", str(video), "-i", str(audio),
        "-map", "0:v:0", "-map", "1:a:0", "-c", "copy",
        "-muxdelay", "0", "-muxpreload", "0", "-f", "mpegts", "-y", str(dst),
    ]  # fmt: skip
    try:
        done = subprocess.run(command, capture_output=True, timeout=timeout, check=False)
    except (OSError, subprocess.SubprocessError):
        dst.unlink(missing_ok=True)
        return False
    if done.returncode != 0 or not dst.exists() or dst.stat().st_size <= 0:
        dst.unlink(missing_ok=True)
        return False
    return True


def _names(out: Path) -> list[str]:
    return [path.name for path in out.glob("v*.ts")]


def _paths(out: Path) -> list[Path]:
    return list(out.glob("v*.ts"))


@dataclass(slots=True)
class Feed:
    """Упаковка по требованию: манифест обещает весь фильм, в tmpfs лежит окно.

    Это ответ на железное ограничение: приёмнику нужен манифест на всю длительность,
    иначе у показа нет ни таймлайна, ни перемотки, — а целый фильм ни в RAM, ни на диск
    не влезает. Развязка в том, что манифест и файлы живут порознь:

    * :meth:`Grid.manifest` перечисляет **все** сегменты фильма и не меняется никогда;
    * файлы под этими именами появляются только там, где приёмник смотрит прямо сейчас;
    * запрос сегмента, которого нет, — это и есть перемотка. Показ не отвечает 404
      (после него ресивер капризничает минутами), а перезапускает упаковку с нужного
      места и отдаёт кусок, как только он готов.

    Отсюда же берётся честная позиция: имя сегмента = его место в фильме, ``-copyts``
    держит исходные метки времени, и приёмник считает время от начала фильма, а не от
    начала куска. Никаких смещений показу пересчитывать не нужно.
    """

    source: str
    audio: int
    out: Path
    grid: Grid
    readrate: float = 1.0
    #: Запас упаковки впереди показа: свойство приёмника, живёт в его профиле
    #: (:attr:`torrcast.profile.Profile.burst`). Здесь умолчание - осторожное.
    burst: float = CAUTIOUS.burst
    #: Сколько секунд позади показа держим сегменты - глубина «бесплатной» перемотки назад.
    keep: float = 120.0
    #: Запрос дальше упакованного края больше чем на столько **сегментов** - это перемотка,
    #: а не обычный ход показа. Порог считается не от балды: после ``seek`` живой Q70D
    #: просит шесть сегментов разом (замерено), и ни один из них не должен считаться новой
    #: перемоткой. Раньше тут стояли секунды - с сеткой по опорным кадрам сегменты разной
    #: длины, и считать их надо штуками.
    ahead: int = 7
    #: Сколько секунд имеет смысл ЖДАТЬ упаковку вместо того, чтобы перезапустить её с
    #: нужного места (:meth:`Packer.eta`). Считать надо и штуками, и секундами: семь
    #: сегментов впереди края - это до семидесяти секунд фильма, а упаковка идёт в темпе
    #: реального времени, и ждать их пришлось бы столько же.
    #:
    #: 15 с - вчетверо дороже перезапуска (пробный прогон, подъём ffmpeg и первый кусок
    #: стоят 3-4 с на живых смоках) и вчетверо дешевле замеренного ожидания на перемотке
    #: (57.8 с). Запас нужен с обеих сторон: после перезапуска приёмник просит шесть
    #: сегментов разом, и ни один не должен показаться новой перемоткой - но и не покажет,
    #: пока свежий прогон читает первые ``burst`` (60 с) на полной скорости.
    jump: float = 15.0
    #: Сколько держим запрос приёмника, пока упаковка догоняет. Это лучше 404: ресивер,
    #: поймавший 404, отказывается брать LOAD ещё пару минут (замерено).
    #: ⚠️ Было 30 с - и этого мало: замерено, когда TorrServer посреди показа
    #: выронил раздачу, упаковка встала, и через 30 с приёмник получил ровно тот 404,
    #: которого мы избегаем. Ждать почти бесплатно (это один поток раздачи), а зря
    #: ждать не придётся: безнадёжные случаи :meth:`_steer` отличает и говорит об этом.
    #: 🔴 Сколько именно держать - свойство приёмника: у приставки Android TV обиды на
    #: 404 нет вовсе (:data:`torrcast.profile.ANDROID_TV`), а у Q70D она стоит минут.
    wait: float = CAUTIOUS.hold_seconds
    #: Потолок веса одного куска - тоже свойство приёмника
    #: (:attr:`torrcast.profile.Profile.max_segment_bytes`). Здесь он нужен не сетке, а
    #: раздаче: прогретое на диске мимо упаковки не проходит, и проверить его вес больше
    #: негде (:meth:`_warm`). Умолчание осторожное, как и у соседей.
    cap: int = CAUTIOUS.max_segment_bytes
    #: Сколько байт несданных кусков терпим в tmpfs, прежде чем погасить прогон
    #: (:data:`PACK_PENDING_BYTES`, :meth:`sweep`).
    pending_cap: int = PACK_PENDING_BYTES
    #: Сколько раз упаковка успела оборваться сама. Пережить обрыв она обязана: TorrServer
    #: под просевшим роем закрывает вход, и ffmpeg честно умирает - а показу это уже не
    #: авария, потому что паковать заново он умеет с любого места. Но молча повторять до
    #: бесконечности нельзя: битый источник крутил бы этот круг вечно.
    limit: int = 3
    packer: Packer | None = None
    lock: Any = field(default_factory=threading.Lock)
    #: Когда последний раз перезапускали упаковку: защита от лавины на префетче.
    restarted: float = 0.0
    crashes: int = 0
    fatal: str = ""
    log: Any = None
    #: Кодировщик тяжёлых кусков (:class:`torrcast.recode.Recoder`) или ``None``, если
    #: динамический битрейт выключен либо тяжёлых кусков в фильме нет.
    recoder: Any = None
    #: Чем перекодировать ВЕСЬ фильм (:class:`torrcast.recode.Encode`); ``None`` - видео
    #: уезжает копией, как обычно.
    #:
    #: Ставится ровно на один случай: кодек, который приёмник не декодирует
    #: (:data:`RECODE_CODECS`). Тогда перекодирует сама упаковка, одним прогоном на весь
    #: показ, а кодировщик тяжёлых кусков не поднимается вовсе - перекодировать что-то
    #: ещё раз поверх уже перекодированного некуда, да и нечем: битрейт зажат тем же
    #: потолком, которым зажата сетка (``recode_mbit``).
    #:
    #: ⚠️ Смешивать копию и перекод в одном показе НЕЛЬЗЯ (:data:`RECODE_CODECS`), поэтому
    #: признак живёт на :class:`Feed`, а не на сегменте: он один на весь файл и не зависит
    #: ни от места показа, ни от перемотки.
    encode: Any = None
    #: Хранилище прогретого на диске (:class:`torrcast.warm.Vault`) или ``None``.
    #:
    #: Сетка детерминирована, поэтому прогретый кусок и живой - одно и то же место фильма
    #: под одним и тем же именем. Отсюда всё остальное: показ берёт прогретое напрямую с
    #: диска (:meth:`segment`), считает его своим запасом (:meth:`front`) и переживает на
    #: нём обрыв сети (:meth:`_survive`).
    vault: Any = None
    #: Когда упаковка в последний раз что-то выложила (:data:`MUTE_SECONDS`).
    #:
    #: Часы принадлежат ПОКАЗУ, а не прогону, и это существенно: на молчащем источнике
    #: прогон перезапускается каждые пару секунд, и часы, привязанные к прогону,
    #: обнулялись бы вечно - ровно так молчание и оставалось незамеченным.
    moved: float = field(default_factory=time.monotonic)
    #: Источник не читается (сеть пропала), а прогретое ещё есть: показ идёт с диска и
    #: ждёт возврата сети. Пусто - всё в порядке. Это НЕ :attr:`fatal`: умирать, пока на
    #: диске лежит фильм, нельзя, а молчать об этом - тем более.
    offline: str = ""
    #: Места, которых в показе не будет никогда: кусок тяжелее потолка приёмника, а
    #: ужать его не вышло (:meth:`_shrink`). Помнится на весь показ, переживая
    #: перезапуски упаковки: тяжёлый кусок детерминирован, и второй прогон над ним
    #: получит ровно ту же копию, поэтому перепаковывать это место незачем.
    #:
    #: 🔴 TC-501. Запрос такого места держится молча (:attr:`wait`), а НЕ отвечается
    #: быстрым 404. Манифест обещает весь фильм и это имя тоже (:meth:`Grid.manifest`),
    #: то есть приёмник придёт за ним обязательно, и вопрос только в том, что он
    #: услышит. Замер живого показа: на 404 приёмник гасит буфер, не доиграв его, -
    #: 24 запроса подряд, показ встал, погас, поднялся и попросил снова; на тишине тот
    #: же буфер доигрывается до конца, и застрявшее место перешагивает сторож приёмника
    #: сеткой (:meth:`torrcast.cast.ChromecastReceiver._nudge`, 8 с). 404 хуже задержки.
    skipped: set[int] = field(default_factory=set)
    #: Ужатие на месте одно на весь показ: зовётся оно из выкладки, а выкладку дёргают
    #: и запрос приёмника, и часы показа (:meth:`sweep`) - двум ffmpeg на один и тот же
    #: кусок тут не место.
    shrink_lock: Any = field(default_factory=threading.Lock)

    @property
    def duration(self) -> float:
        return self.grid.duration

    def manifest(self) -> bytes:
        return self.grid.manifest().encode("utf-8")

    def segment(self, slot: int) -> Path | None:
        """Файл сегмента ``slot``; ``None`` — его не будет (за концом фильма или не успели).

        Зовётся из потоков раздачи, поэтому решение о перезапуске упаковки принимается
        под замком: после перемотки приёмник просит несколько сегментов одновременно, и
        перезапустить упаковку должен ровно первый из них.

        ⚠️ Замок берётся без ожидания. Внутри решения лежит пробный прогон
        (:func:`pack_start`), до минуты по потолку, и сосед, вставший в очередь за
        замком, всё это время не смотрел бы даже на свой файл: тот успевает появиться,
        а ответ уходит на минуту позже. Занятый замок значит ровно «решение уже
        принимают», и правильный ход тут - ждать файл, а не очередь.
        """
        path = self.out / segment_name(slot)
        deadline = time.monotonic() + self.wait
        while True:
            if path.exists():
                return path
            # Прогретое на диске равноценно живому куску: то же место фильма, то же имя,
            # та же сетка (:attr:`vault`). Проверка стоит ЗДЕСЬ, до всякого разбирательства
            # с упаковкой, и в этом весь смысл прогрева: перемотка в прогретую зону
            # отвечает файлом сразу, не поднимая ffmpeg и не спрашивая сеть.
            warm = self._warm(slot)
            if warm is not None:
                return warm
            if self.lock.acquire(blocking=False):
                try:
                    hope = self._steer(slot)
                finally:
                    self.lock.release()
                if path.exists():
                    return path
                if not hope:
                    return None
            if time.monotonic() >= deadline:
                return None
            time.sleep(0.2)

    def _warm(self, slot: int) -> Path | None:
        """Прогретый на диске кусок этого места или ``None``.

        ⚠️ Прогретое идёт наружу мимо упаковки, а значит и мимо обоих мест, где вес куска
        зажат потолком приёмника (:meth:`Packer.publish`,
        :meth:`torrcast.recode.Recoder.holding`). Прогрев же кладёт фильм на диск копией,
        а тяжёлые места приводит к перекоду отдельным, ПОЗДНИМ заходом
        (:meth:`torrcast.warm.Warmer._spots_left`) - до него на месте тяжёлого куска лежит
        копия во весь свой вес.

        Замер, ради которого правило написано («Тачки» 2006, 1080p, 39% фильма тяжелее
        потолка): прогрев обгонял показ вчетверо, показ брал прогретые копии по 17-44 МБ,
        и приёмник вставал на каждой. 32 ``BUFFERING`` и 20 пинков за 14 минут, 31 кусок
        из 50 приёмник просил повторно, картинка шла вдвое медленнее реального времени.

        Поэтому кусок тяжелее потолка прогретым не считается: под ним живая упаковка,
        которая тот же кусок отдаст перекодом. Ждать перекод дольше, чем взять готовое с
        диска, - и это правильная цена: подгруз тут не «медленнее», а «не играет вовсе».
        """
        if self.vault is None:
            return None
        path: Path = self.vault.path(slot)
        if not path.exists():
            return None
        size = 0
        with contextlib.suppress(OSError):
            size = path.stat().st_size
        return None if size > self.cap else path

    def have(self, slot: int) -> bool:
        """Есть ли кусок этого места — всё равно, в окне показа или в прогретом."""
        return (self.out / segment_name(slot)).exists() or self._warm(slot) is not None

    def _steer(self, slot: int) -> bool:
        """Что делать с упаковкой ради сегмента ``slot``; ``False`` — файла не будет.

        Разница между «подожди» и «не будет» — это разница между медленным ответом и 404.
        Держать приёмник в ожидании можно долго и почти безнаказанно, а вот 404 он
        запоминает: замерено — поймав его, ресивер не берёт LOAD ещё пару
        минут. Поэтому 404 отдаётся только там, где ждать нечего: конец входа или
        упаковка, которая сдалась насовсем.

        🔴 TC-501. Пропущенное место (:attr:`skipped`) в этот список больше не входит.
        Файла там и правда не будет, но манифест его уже пообещал, а мерка тут не
        «есть ли надежда», а «что переживает приёмник»: 404 он не переживает, тишину -
        переживает. Ответ отсюда - «подожди», перезапуска упаковки такое ожидание не
        вызывает, и через 8 с место перешагивает сторож приёмника.
        """
        if self.fatal:
            # Показ этой раздачи кончился (:meth:`stop`) или упаковка сдалась насовсем:
            # диагностировать тут больше нечего, а труп прогона - не новость. ⚠️ Проверка
            # стоит ПЕРВОЙ намеренно: на стыке серий сюда приходит приёмник, оставшийся
            # на живом keep-alive прошлой серии, и раньше он получал в журнал «упаковка
            # оборвалась» про наш же намеренно снятый ffmpeg.
            return False
        if slot in self.skipped:
            # 🔴 TC-501. Место честно пропущено (:meth:`_shrink` уже сказал об этом один
            # раз), файла не будет никогда - но манифест это имя приёмнику УЖЕ пообещал,
            # и выбор тут не «ответить или нет», а «ответить 404 или промолчать».
            # Молчим (:attr:`skipped`): на 404 приёмник гасит недоигранный буфер и
            # начинает круг «встал - погас - поднялся - попросил снова», на тишине тот же
            # буфер доигрывается, а дыру перешагивает его собственный сторож
            # (:meth:`torrcast.cast.ChromecastReceiver._nudge`) - сеткой и через 8 с.
            # ⚠️ Упаковку это ожидание не поднимает и поднять не может: возврат отсюда
            # уходит мимо перезапуска, а иначе запрос детерминированно тяжёлого места
            # крутил бы перепаковку вечно, получая ровно ту же копию.
            return True
        packer = self.packer
        if packer is not None and not packer.halted:
            # Край берём честный - тот, что выложил ЭТОТ прогон (:attr:`Packer.edge`).
            # Глоб каталога (`frontier`) на этом месте и был багом: чужие куски
            # уводили край вперёд, запрос далеко назад попадал в «подожди, вот-вот
            # допакуется» - и висел все `wait` секунд, чтобы кончиться 404. Обратная
            # наивная починка («ждать только впереди глоба») давала 20 перезапусков за
            # 100 с. Работает только честный край: он растёт ровно на publish.
            packer.publish()
            if packer.edge >= packer.first:
                self.moved = time.monotonic()
                self.offline = ""  # прогон что-то выложил - значит источник снова читается
            else:
                self._mute()
            if (self.out / segment_name(slot)).exists():
                # ⚠️ Кусок допаковался ровно этим `publish` - и это не редкость, а
                # обычный ход показа: приёмник идёт вплотную за упаковкой и просит
                # сегмент за мгновение до того, как тот закрылся. Без этой проверки он
                # оказывался «ниже края, а файла нет», то есть перемоткой назад: замер -
                # перезапуск на каждом четвёртом сегменте.
                return True
            code, edge = packer.poll(), packer.edge
            if packer.finished() and slot > edge:
                return False  # упаковка честно дошла до конца входа - файла не будет
            if code is None and edge < slot <= edge + self.ahead:
                # ⚠️ «Вот-вот» - это про ВРЕМЯ, а не про номер сегмента, и разница стоила
                # 28 с чёрного экрана. Упаковка идёт `readrate 1`, то есть в темпе
                # реального времени: перемотка вперёд внутри прогона попадает в эти семь
                # сегментов, но семь сегментов - это ещё и семьдесят секунд фильма, которые
                # ffmpeg будет читать семьдесят секунд. Замер на живом Q70D: перемотка
                # 3984 → 4100 (+116 с), «запрос v385.ts · ждал 57.8 с» - ровно эта планка.
                # Ждать имеет смысл только то, что упаковка достанет быстрее, чем стоит её
                # перезапуск с нужного места (:meth:`Packer.eta`).
                if packer.eta(self.grid.start(slot)) <= self.jump:
                    return True  # обычный ход показа: кусок вот-вот допакуется
                mark(
                    "перемотка внутри прогона",
                    слот=slot,
                    ждать=round(packer.eta(self.grid.start(slot)), 1),
                )
            # Всё остальное при живой упаковке - перемотка. Вперёд (дальше `ahead` за
            # краем) и назад (ниже края, а файла нет - значит выметен окном или паковал
            # его не этот прогон) лечатся одинаково: перепаковкой с этого места.
            # Оборвался - это и «умер с кодом», и «вышел нулём на недописанном куске»
            # (:meth:`Packer.finished`): второе выглядит концом фильма, а на деле обрыв
            # входа, и лечится он тем же перезапуском с нужного места.
            if code is not None and not packer.finished() and not self._survive(packer):
                return False
        # Пока источник не читается, толкаться незачем: подъём ffmpeg на мёртвую сеть
        # стоит секунды и не даёт ничего, а показ в это время идёт с диска.
        if time.monotonic() - self.restarted < (5.0 if self.offline else 2.0):
            return True  # соседний запрос уже перезапустил упаковку - не толкаемся
        self.restarted = time.monotonic()
        self.restart(slot)
        return True

    def _mute(self) -> None:
        """Источник молчит: прогон жив, а не выложил ни куска дольше :data:`MUTE_SECONDS`.

        🔴 Обрыв связи бывает двух видов, и показ знал только один. Оборванный **вход**
        убивает ffmpeg, и это ловит :meth:`_survive`. А пропавший интернет при живом
        TorrServer вход не рвёт вовсе: раздача просто перестаёт отдавать байты, ffmpeg
        висит на чтении, `poll()` возвращает ``None``, и с точки зрения :meth:`_steer` всё
        в порядке - просто «кусок вот-вот допакуется», раз за разом, вечно.

        Замер на живом Q70D («Тачки 3», интернет в drop): показ доел прогретое на 1:12:35,
        встал в BUFFERING и **2.5 минуты не сказал ни слова** - ни строки о сети, ни о
        прогретом, - после чего приёмник сам перегрузил фильм с нуля. Молчаливая смерть с
        полным диском кино рядом. Отсюда эти часы: молчание дольше срока - такой же обрыв,
        как и мёртвый ffmpeg, и говорится о нём теми же словами.
        """
        if self.vault is None or self.offline:
            # Без прогретого «молчит» неотличимо от «медленный рой на старте», а идти
            # показу всё равно некуда: тут работает прежний счёт обрывов, а не часы.
            return
        if time.monotonic() - self.moved <= MUTE_SECONDS:
            return
        self.offline = f"источник молчит дольше {MUTE_SECONDS:.0f} с"
        self._say(f"источник не читается ({self.offline}) - иду с прогретого, жду возврата сети")

    def _survive(self, packer: Packer) -> bool:
        """Упаковка оборвалась сама: пробуем ещё или сдаёмся честной ошибкой.

        ⚠️ Считаются ПРОГОНЫ, а не опросы. Пока держит защита «не толкаемся» (2 с),
        перезапуска не происходит, а потоки раздачи приходят сюда каждые 0.2 с — и один
        и тот же труп съедал все попытки меньше чем за секунду, не дав показу ни одного
        настоящего перезапуска. Ровно так выглядел бы обрыв входа сразу после старта:
        TorrServer выронил раздачу — ffmpeg умирает мгновенно, то есть внутри этих 2 с.
        """
        if packer.blamed:
            return True
        packer.blamed = True
        if packer.stopped:
            return True  # прогон сняли мы сами - это не обрыв, и попытку он не тратит
        self.crashes += 1
        why = packer.why()  # там же и код возврата, если ffmpeg смолчал
        if self.crashes > self.limit:
            if self.vault is None:
                self.fatal = why
                return False
            # ⚠️ Прогретое на диске меняет смысл обрыва: раньше три подряд оборванных
            # прогона означали «источника нет, показывать нечего», теперь - «сети нет, а
            # фильм есть». Умирать тут нельзя, но и молчать нельзя: показ говорит, докуда
            # он обеспечен, и продолжает пробовать. Вернулась сеть - прогон выложит кусок,
            # и признак снимется сам (:meth:`_steer`).
            self.crashes = 0
            self.offline = why
            self._say(f"источник не читается ({why}) - иду с прогретого, жду возврата сети")
            return True
        self._say(f"упаковка оборвалась ({why}) - начинаю заново, попытка {self.crashes}")
        return True

    def restart(self, slot: int) -> None:
        """Начать упаковку с сегмента ``slot``: перемотка, возврат с паузы или старт показа.

        Границы сегментов от места старта не зависят (:class:`Grid`), поэтому уже
        упакованное не выбрасывается: под именем ``vN`` и до, и после перезапуска лежит
        ровно одно и то же место фильма. Убирать приходится только то, что прошлый прогон
        не успел дописать, — а этого наружу и не попадало.
        """
        if self.packer is not None:
            self.packer.stop(keep_files=True)
        # ⚠️ Кодировщик узнаёт о новом месте показа ПЕРВЫМ делом, до пробного прогона
        # (0.5-1.7 с): голову прогона он обязан начать не позже упаковщика, иначе
        # придерживать её копию будет нечего и первый сегмент уйдёт тяжёлым.
        if self.recoder is not None:
            self.recoder.opening(slot)
        # ⚠️ Перекодирующему прогону пробный не нужен и вреден: по ``-ss`` он встаёт точно,
        # докатки не делает (:func:`ffmpeg_pack_command`), и измеренное ``at`` увело бы
        # весь прогон на сегмент назад. Заодно это минус 0.5-1.7 с из пути старта - ровно
        # та цена, которой сплошной перекод отчасти и оплачивает свою голову.
        at = self.grid.start(slot)
        if self.encode is None:
            # Место захода считается по карте опорных кадров, а пробный прогон остаётся
            # запасным путём и сверкой: он идёт один раз на файл (:func:`pack_start`).
            # Дороже всего это на перемотке - там прогон был на пути к картинке каждый раз.
            at = pack_start(self.source, self.grid.start(slot))
            mark("заход упаковки", слот=slot, встали=round(at, 3))
        command = ffmpeg_pack_command(
            self.source,
            self.audio,
            str(self.out / PACK_DIR),
            self.grid,
            slot,
            at,
            self.readrate,
            self.burst,
            encode=self.encode,
        )
        self.restarted = time.monotonic()
        self.packer = Packer.start(
            command,
            self.out,
            self.out / PACK_DIR,
            slot,
            spare=None if self.recoder is None else self.recoder.spare,
            told=None if self.recoder is None else self.recoder.note,
            hold=None if self.recoder is None else self.recoder.holding,
            shrink=self._shrink,
            at=at,
            rate=self.readrate,
            burst=self.burst,
            grid=self.grid,
        )
        drop = self.grid.start(slot) - at
        self._say(
            f"упаковка с {self.grid.start(slot):.1f} с"
            + (f" (докатка {drop:.1f} с)" if drop > SPLIT_SLACK else "")
        )

    def _shrink(self, slot: int, size: int = 0) -> bool:
        """Ужать кусок, который не влез в потолок приёмника, прямо сейчас; ``False`` - пропуск.

        Зовётся из :meth:`Packer.publish` с последнего гейта: копия тяжелее потолка
        (или перекод, который и сам не влез), а ждать кодировщика уже не стали -
        предохранитель ожидания её отпустил (:meth:`torrcast.recode.Recoder.holding`).
        Без этого звонка выкладка вставала на таком куске навсегда: край не двигался,
        сама копия не удалялась, а всё за ней копилось в памяти до потолка несданного;
        потолок гасил прогон, запрос приёмника поднимал его заново - и круг
        повторялся каждые несколько минут, потому что тяжёлый кусок детерминирован.

        Ужатие - один короткий прогон ffmpeg ровно на этот сегмент, самым быстрым
        пресетом и с целью, посчитанной под потолки приёмника
        (:meth:`torrcast.recode.Encode.fit`).

        🔴 Потолков ДВА, и они разной природы (TC-495). Вес куска - один; битрейт,
        который приёмник тянет (:attr:`torrcast.recode.Recoder.threshold`), - второй, и
        первая версия ужатия смотрела только на вес. Живой показ 11-08: ужатие сработало
        на трёх ранних кусках и отдало наружу 9.65, 8.33 и **10.94** Мбит/с при потолке
        около десяти - четыре подгруза в первую минуту, и ранние места ровно эти. Кусок,
        влезающий по весу, роняет показ по битрейту: чем короче кусок, тем больше
        мегабит в секунду в те же 16 МБ помещается.

        Ждать можно: запрос этого места и так держится до :attr:`wait`, а секунда
        фильма самым быстрым пресетом стоит заметно дешевле секунды стены. Потолок
        ожидания тот же, что у предохранителя кодировщика
        (:attr:`torrcast.recode.Recoder.over_wait`).
        """
        recoder = self.recoder
        if slot in self.skipped:
            return False  # решение по этому месту принято и сказано ровно один раз
        if recoder is None:
            # Ужимать нечем: перекод выключен настройкой или профиль тяжести не построился.
            return self._skip(slot, size, "ужимать нечем")
        if self.encode is not None:
            # На сплошном перекоде чужой заход в середину потока - это смена SPS на
            # ходу, а её приёмник не переживает (:data:`RECODE_CODECS`).
            return self._skip(slot, size, "ужать нельзя")
        with self.shrink_lock:
            if slot in self.skipped:
                return False
            ready = recoder.ready(slot)
            if ready is not None:
                with contextlib.suppress(OSError):
                    if 0 < ready.stat().st_size <= self.cap:
                        return True  # пока ждали замок, перекод доехал сам
            span = self.grid.span(slot)
            # Оба потолка приёмника разом: вес куска (:attr:`cap`) и битрейт, который он
            # тянет (порог кодировщика - то же число). Считает их одно место на весь
            # проект, иначе о потолке появился бы третий источник правды.
            encode = recoder.fit(span, recoder.pace.table()[-1][0])
            mbit = encode.mbit
            run = recoder.spare / SHRINK_DIR
            weight = f" ({size / 1e6:.0f} МБ)" if size > 0 else ""
            self._say(f"v{slot} тяжелее потолка{weight} - ужимаю на месте до {mbit:.1f} Мбит/с")
            mark("ужатие на месте", слот=slot, мбит=round(mbit, 2))
            command = ffmpeg_pack_command(
                self.source,
                self.audio,
                str(run),
                self.grid,
                slot,
                self.grid.start(slot),
                0.0,
                0.0,
                encode=encode,
                until=slot,
            )
            packer: Packer | None = None
            try:
                packer = Packer.start(command, recoder.spare, run, slot, last=slot, grid=self.grid)
                deadline = time.monotonic() + recoder.over_wait
                while packer.edge < slot and packer.poll() is None and time.monotonic() < deadline:
                    packer.publish()
                    time.sleep(0.2)
                packer.publish()
            except Exception:  # не поднялся ffmpeg, не открылся вход - честный пропуск
                packer = None
            finally:
                if packer is not None:
                    packer.stop(keep_files=True, reason="ужатие на месте окончено")
        ready = recoder.ready(slot)
        fits = False
        if ready is not None:
            with contextlib.suppress(OSError):
                fits = 0 < ready.stat().st_size <= self.cap
        if fits:
            return True
        return self._skip(slot, size, "ужать не вышло")

    def _skip(self, slot: int, size: int, reason: str) -> bool:
        """Честный пропуск места, которое нельзя отдать приёмнику: один раз и вслух.

        Возвращает ``False`` - выкладка выбросит копию и пойдёт дальше
        (:meth:`Packer.publish`). Само место запоминается (:attr:`skipped`): запрос
        его перепаковки не поднимает - тяжёлый кусок детерминирован, второй прогон
        над ним получит ровно ту же копию, - но и 404 в ответ не получает (TC-501):
        имя уже обещано манифестом, а 404 приёмник переживает хуже тишины.
        """
        self.skipped.add(slot)
        if self.recoder is not None:
            with contextlib.suppress(Exception):
                self.recoder.done.add(slot)  # кодировщику за это место браться уже незачем
        weight = f" ({size / 1e6:.0f} МБ)" if size > 0 else ""
        self._say(
            f"⚠️ v{slot} пропускаю: кусок тяжелее потолка{weight}, а {reason} - "
            "этого места в показе не будет"
        )
        mark("пропуск тяжёлого куска", слот=slot, мб=round(size / 1e6))
        return False

    def sweep(self) -> None:
        """Сдать всё, что упаковка успела, и не дать несданному расти без предела.

        Зовётся по часам показа, а не по запросу приёмника, и в этом весь смысл. Выкладка
        (:meth:`Packer.publish`) стоит на пути запроса сегмента, а запросов может не быть
        вовсе: пока показ берёт куски с диска (:meth:`_warm`), к упаковке никто не
        обращается, а ffmpeg продолжает писать в tmpfs. Замер: 897 МБ несданного за 14
        минут показа, рост без предела и без единой строки о нём.

        Потолок (:data:`PACK_PENDING_BYTES`) нужен и сверх этого. Выкладка встаёт на
        куске, придержанном под перекод, - и всё, что за ним, копится в памяти, сколько
        бы её ни было. (Тяжёлая копия выкладку больше не держит: она ужимается на месте
        или честно пропускается - :meth:`_shrink`.) Дойдя до потолка, показ гасит прогон
        одной честной строкой: куски, которых никто не забирает, стоят памяти и не дают
        приёмнику ничего, а снятый прогон отдаёт её обратно (:meth:`Packer.stop`).

        Подгруза это не добавляет: гасится то, что и так никуда не шло, уже выложенное
        остаётся лежать, а запрос следующего сегмента поднимает упаковку заново
        (:meth:`_steer`) - ровно как после паузы на пульте.
        """
        packer = self.packer
        if packer is None or packer.halted:
            return
        packer.publish()
        pending = packer.pending()
        if pending <= self.pending_cap:
            return
        self._say(
            f"несданных кусков {pending / 1e6:.0f} МБ в памяти - упаковку гашу, "
            "подниму её по запросу приёмника"
        )
        mark("несданное копится", мб=round(pending / 1e6), край=packer.edge)
        packer.halt(reason=f"несданного {pending / 1e6:.0f} МБ в памяти")

    def prune(self, played: float) -> None:
        """Убрать из tmpfs то, чего показу уже не нужно, — и позади показа, и впереди.

        Позади окно ``keep`` секунд: глубже — уже перемотка, и она честно перепакует поток.

        Впереди убирается то, что осталось от **прошлого места показа**. После отката
        назад глубже окна упаковка идёт с нового места, а сегменты той минуты, откуда
        ушёл зритель, лежат в tmpfs и не выметаются ничем: окно смотрит только назад, а
        снова дойти до них показ может уже и не дойти. Десяток откатов подряд — и в
        памяти лежат места фильма, которых на экране не будет.

        Граница честная и не задевает ни запаса, ни префетча: остаётся всё, что этот
        прогон уже выложил или вот-вот выложит (``edge + ahead``), и всё, что рядом с
        позицией приёмника. Выше — куски, которых текущий прогон не делал и в ближайшее
        время не сделает. Упаковки нет вовсе — вперёд не трогаем ничего: без прогона край
        неизвестен, а гадать на этом месте дороже, чем подождать.
        """
        packer = self.packer
        keep_upto = -1
        if packer is not None:
            keep_upto = max(self.grid.slot_at(played), packer.edge) + self.ahead
        behind = self.grid.slot_at(played - self.keep) if played - self.keep > 0 else 0
        for path in _paths(self.out):
            slot = segment_slot(path.name)
            if slot < 0:
                continue
            if slot < behind or (keep_upto >= 0 and slot > keep_upto):
                path.unlink(missing_ok=True)

    def front(self, played: float = 0.0) -> float:
        """Докуда показ обеспечен **подряд** от позиции ``played``, секунды от начала фильма.

        Разница между этим числом и позицией приёмника — весь запас показа. Он и есть
        предмет всей возни с подвисами: пока запас положителен, приёмнику есть что взять, а
        как только он сходит в ноль — приёмник встаёт в BUFFERING. На этом числе стоит
        сторож приёмника: неподвижный BUFFERING при живом запасе — зависание и лечится
        нуджем, при пустом — законное ожидание нас и лечится упаковкой.

        ⚠️ Раньше здесь стоял глоб каталога (``Packer.frontier``), и после перемотки назад
        он врал в разы: в каталоге показа лежат честные куски прошлых прогонов (сетка
        детерминирована), и «докуда упаковано» считалось по ним. Замер на живом
        Q70D: откат с 40-й минуты на 10-ю — «показ 600 · упаковано 2010 ·
        впереди 1410 с», при том что перед приёмником не было ни одного куска. Запас,
        посчитанный за тысячу секунд от места, где показа нет, — это разрешение сторожу
        дёргать приёмник ровно тогда, когда дёргать нельзя.

        Правда считается от приёмника и только по фактам: кусок под позицией и цепочка
        за ним. Разрыв цепочки — конец запаса, что бы ни лежало дальше: перепрыгнуть
        дырку приёмник всё равно не сможет. Куска под позицией нет вовсе — запаса ноль.
        """
        slot = self.grid.slot_at(played)
        if not self.have(slot):
            return played
        while slot + 1 < self.grid.count and self.have(slot + 1):
            slot += 1
        return self.grid.end(slot)

    def drift(self) -> float:
        """Насколько нарезанное разошлось с манифестом, секунды (:meth:`Packer.drift`)."""
        return 0.0 if self.packer is None else self.packer.drift(self.grid)

    def weight(self) -> int:
        """Сколько байт лежит в tmpfs прямо сейчас (рост без предела недопустим, а это
        единственный способ увидеть пик своими глазами).

        Считается и окно показа, и несданное каталога прогона (:meth:`Packer.pending`):
        память одна на оба, и вторая половина росла невидимой ровно потому, что число
        называло только первую.
        """
        total = 0
        for path in _paths(self.out):
            with contextlib.suppress(OSError):  # вычистило окном прямо сейчас
                total += path.stat().st_size
        return total + (0 if self.packer is None else self.packer.pending())

    def trouble(self) -> str:
        """Почему показ дальше не идёт, если не идёт; пусто — всё в порядке.

        Мёртвый ffmpeg сам по себе поводом остановить показ не является: дочитанный до
        конца вход (:meth:`Packer.finished`) - это конец фильма, остаток которого уже в
        tmpfs, а обрыв лечится следующей упаковкой. ⚠️ Одного кода 0 для этого мало:
        вход, умерший на середине, тоже выходит нулём, и здесь такой прогон числится
        обрывом, а не концом (:meth:`_steer`).
        Ошибкой это становится, только когда обрывы пошли подряд (:attr:`limit`).
        """
        return self.fatal

    def stall(self, why_source: str) -> None:
        """Упаковка сдалась, но виноват ИСТОЧНИК: показ не умирает, а ждёт его возврата.

        🔴 Три оборванных подряд прогона (:attr:`limit`) означают «показывать нечего»
        только тогда, когда источник в порядке. Служба раздач, которую перезапустили,
        рвёт вход ровно так же - и старая упаковка объявляла себя мёртвой насовсем через
        3.5-12 с, хотя ждать оставалось три секунды. Спрашивает источник сторож
        (:class:`Supply`), а здесь снимается приговор: обрывы забываются, показ переходит
        в «источника нет» и продолжает пробовать. Вернулся источник - прогон выложит
        кусок, и признак снимется сам (:meth:`_steer`).
        """
        self.fatal = ""
        self.crashes = 0
        self.offline = why_source

    def halted(self) -> bool:
        return self.packer is not None and self.packer.halted

    def rest(self) -> bool:
        """Остаток фильма прогрет целиком — живую упаковку гасим; ``True`` — погасили.

        Держать её дальше значит тянуть из раздачи байты, которые уже лежат на диске, и
        отбирать полосу у прогрева головы. Это не конец показа: запрос куска, которого в
        прогретом нет, поднимет упаковку заново (:meth:`_steer`), как после паузы.
        """
        if self.vault is None or self.packer is None or self.packer.halted:
            return False
        self.packer.halt(reason="весь остаток прогрет")
        return True

    def halt(self) -> None:
        if self.packer is not None:
            self.packer.halt()

    def stop(self) -> None:
        """Показ окончен: упаковка гаснет, каталог показа пустеет.

        Флажок «картинка на экране» снимается ровно здесь и больше нигде: пока показ идёт,
        он и есть доказательство картинки для CLI, поэтому перезапуски
        упаковки (:meth:`restart`, перемотка) его не трогают. А после остановки это уже
        не доказательство, а пустой файл, который переживал `cast stop` в tmpfs.
        """
        # Закрыто насовсем: поток раздачи, спящий в segment() до двух минут, не должен
        # проснуться и поднять новый ffmpeg в каталог, который уже отдан следующей серии.
        self.fatal = self.fatal or "показ окончен"
        if self.recoder is not None:
            self.recoder.stop()
        if self.packer is not None:
            self.packer.stop()
        for junk in _paths(self.out):
            junk.unlink(missing_ok=True)
        shutil.rmtree(self.out / PACK_DIR, ignore_errors=True)
        shutil.rmtree(self.out / RECODE_DIR, ignore_errors=True)
        forget_playing(self.out)

    def _say(self, text: str) -> None:
        if self.log is not None:
            self.log(text)
