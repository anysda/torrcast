#: Видео уедет на приёмник КАК ЕСТЬ (``-c:v copy``).
COPY: Final = "copy"
#: Видео уедет перекодированным ЦЕЛИКОМ, одним прогоном на весь файл.
RECODE: Final = "recode"
#: Такое видео мы не берём: честный отказ отбора, очередь идёт к следующему релизу.
REFUSE: Final = "refuse"

#: Три исхода :meth:`Profile.verdict` и весь список того, что бывает с картинкой.
Verdict = Literal["copy", "recode", "refuse"]


@dataclass(frozen=True, slots=True)
class Profile:
    """Что приёмник умеет и как долго терпит - одним объектом.

    Каждое поле - замер на живом приёмнике, а не оценка. Значения по умолчанию - это
    :data:`CAUTIOUS`, то есть Q70D: профиль без явного значения ведёт себя ровно так, как
    вёл себя весь показ до появления второго приёмника.
    """

    #: Ключ профиля: он же значение ``receiver_profile`` в настройках и он же в следе.
    key: str
    #: Как профиль называется человеку - в ``cast doctor`` и в недельном следе.
    title: str
    #: Кодеки, сплошной перекод которых нам ПО СИЛАМ: цена их декода замерена, и релиз с
    #: таким видео не отбраковывается, а перекодируется целиком (:const:`RECODE`).
    #:
    #: Здесь один ``hevc``, и это не лень: замер есть ровно для него (HEVC-декод плюс
    #: x264 ultrafast - двукратный запас к реальному времени). vp9/av1/vc1 сюда не входят
    #: не потому, что они играют, а потому, что цена их декода не мерена: на отборе они
    #: честный отказ (:const:`REFUSE`), а не молчаливая копия.
    recode_codecs: frozenset[str] = frozenset({"hevc"})
    #: Глубина цвета, которую приёмник берёт копией; выше - перекод целиком. Имени кодека
    #: для решения не хватает: десятибитный H.264 (Hi10P) зовётся тем же ``h264``.
    copy_depth: int = 8
    #: Белый список: кодеки, которые приёмник реально играет НАШИМ HLS и которые поэтому
    #: разрешено отдать копией. Всё, чего тут нет, копией не уезжает никогда.
    #:
    #: 🔴 Список белый, а не чёрный, и это принципиально: чёрный список («вот эти четыре
    #: не берём») молча пропускал на приёмник всё, о чём никто не подумал, - так VP9
    #: уезжал в mpegts копией и приставка не начинала показ вовсе.
    #:
    #: 🔴 Список - про НАШ транспорт, а не про декодер устройства: **нативный декод ≠
    #: играет у нас**. Замер 09-08-2026 на приставке Android TV: HEVC она берёт прямым
    #: ``LOAD`` одиночного MP4 (111 с подряд), а тот же битстрим, отданный МАНИФЕСТОМ, не
    #: стартует ни в mpegts, ни в fMP4 (7 и 11 попыток LOAD, все ``IDLE/ERROR``). Значит
    #: Default Media Receiver не отдаёт HEVC декодеру по HLS - и то же у VP9 и AV1.
    #: Расширять список по «нативному» списку кодеков устройства - ловушка; условие для
    #: расширения - свой ресивер с объявленными media-capabilities.
    copy_codecs: frozenset[str] = frozenset({"h264"})
    #: Самый большой кадр, который приёмник декодирует В ПЕРЕКОДИРОВАННОМ виде, то есть в
    #: :attr:`copy_codecs`. Выше - сплошной перекод бессмыслен: он меняет кодек, который
    #: приёмник не берёт, на кадр, который приёмник не берёт.
    #:
    #: 🔴 Замер 09-08-2026 на живом Q70D (TC-157), два клипа по 90 с, вырезанных ОДНОЙ
    #: командой из одного места «Матрицы» 2160p HEVC и отличающихся ровно кадром: те же
    #: ``ultrafast``, 9 Мбит/с, ``yuv420p``, ``level 4.1``, та же метка BT.2020/PQ, те же
    #: веса сегментов (10.8 и 12-13 МБ). 3840×2160 - пять заходов LOAD подряд, каждый раз
    #: ``IDLE/ERROR`` сразу после v0, картинки нет ни разу. 1920×1080 - картинка на
    #: 2-й секунде и ровный ``PLAYING`` без единого ребуфера.
    #:
    #: ⚠️ Голодание тут ни при чём, и это доказано тем же замером: клипы лежали на диске,
    #: каждый сегмент отдавался за 0.0 с, а tcpdump показывает, что телевизор
    #: подтвердил ровно 12 496 384 байта (это v0) и закрыл соединение, не забрав v1.
    #: Прежнее объяснение («сплошной перекод 4К не успевает») замером опровергнуто:
    #: фактическая скорость на 4 vCPU - 1.03× реального времени, то есть успевает.
    recode_frame: int = 1080
    #: Потолок веса ОДНОГО сегмента, байты: сколько разрешено уехать одним куском.
    max_segment_bytes: int = 16_000_000
    #: Шаг сетки сегментов, секунды.
    segment_seconds: float = 10.0
    #: Практический потолок битрейта приёмника, Мбит/с: выше - предупреждение человеку и
    #: потолок отбора при выключенном перекодировании.
    warn_mbit: float = 16.0
    #: Битрейт, ВЫШЕ которого сегмент перекодируется на лету, Мбит/с.
    recode_at_mbit: float = 10.0
    #: Во сколько Мбит/с перекодируем тяжёлый кусок: ниже планки приёмника с запасом.
    recode_mbit: float = 9.0
    #: Запас упаковки впереди показа, секунды (``-readrate_initial_burst``).
    burst: float = 60.0
    #: Сколько держим запрос приёмника, пока упаковка догоняет, вместо того чтобы ответить
    #: 404 (:class:`torrcast.stream.Feed`).
    hold_seconds: float = 120.0
    #: Сколько приёмник терпит стоящую картинку, прежде чем МЕДИАСЕССИЯ умрёт, секунды.
    #:
    #: 🔴 Замер 09-08-2026 на живом Q70D, два независимых канала (рапорт приёмника и
    #: tcpdump): от замирания картинки до смерти сессии - 23.5 с. Прежние «около четырёх
    #: минут» были СКЛЕЙКОЙ двух разных сроков и не равны ни одному из них: второй срок -
    #: :attr:`app_patience`, и он про приложение на экране, а не про показ.
    patience: float = 23.5
    #: Сколько приложение приёмника висит на экране ПОСЛЕ смерти медиасессии, секунды.
    #:
    #: 🔴 Тот же замер: 301 с с той же ``session_id`` и заставкой Default Media Receiver,
    #: когда медиасессии уже нет. Показу это не «терпение», а окно, в котором экран ещё
    #: занят нами: из него и растёт срок ожидания картинки при возобновлении
    #: (:attr:`revive_timeout`).
    app_patience: float = 301.0
    #: Сколько приёмник терпит МЁРТВЫЙ URL, прежде чем уйти в ``IDLE/ERROR``, секунды.
    #:
    #: ⚠️ Это не :attr:`patience`, и путать их нельзя: там пустой экран при живом
    #: соединении (сервер молчит), здесь - честный ответ «этого куска нет». Замер
    #: 09-08-2026 на приставке Android TV: один запрос, ``IDLE/ERROR`` на 4-й секунде,
    #: ноль повторов. У Samsung Q70D тот же сценарий - четыре попытки подряд с бэкоффом
    #: 0.4-1.6 с, и своего срока «до ERROR» замер ему не называет; ноль здесь означает
    #: «не мерено, ведём себя как прежде».
    dead_url_seconds: float = 0.0
    #: Сколько раз МЫ повторяем LOAD посреди показа, поймав ``IDLE/ERROR``.
    load_retries: int = 2
    #: Сколько раз приёмник САМ перезабирает пропавший кусок, прежде чем сдаться.
    #:
    #: ⚠️ Это НЕ повторы LOAD, хотя раньше называлось ими: ``media_session_id`` при этом
    #: не меняется - приёмник переспрашивает тот же кусок по HTTP. Замер 09-08-2026: на
    #: тишине (сервер не отвечает) - попытка и два повтора с шагом около 11 с, на чистом
    #: 404 - четыре попытки подряд с бэкоффом 0.4-1.6 с. Число нужно заглушке
    #: (:class:`torrcast.cast.MockReceiver`), чтобы сухой прогон терял картинку так же.
    #:
    #: Оттуда же ещё один факт, который в модель пока не заложен: на тишине приёмник
    #: доигрывает буфер до конца, а на 404 гаснет раньше - буфер он в этом случае бросает.
    segment_retries: int = 2
    #: Сколько приёмник не берёт LOAD вовсе, поймав 404, секунды. Ноль - не обижается.
    #:
    #: 🔴 Ноль - это ЗАМЕР, а не умолчание: 09-08-2026 на живом Q70D наказание за 404
    #: опровергнуто трижды. LOAD после 404 берётся даже быстрее обычного тёплого
    #: (3.2-3.6 с против 5.6 с) - и на манифесте, и на сегменте, и на том же URL, и на
    #: свежем. У приставки Android TV ровно то же, то есть это свойство протокола, а не
    #: конкретного телевизора; поле оставлено, потому что третий приёмник может оказаться
    #: другим.
    #:
    #: ⚠️ Удержание запроса вместо 404 (:attr:`hold_seconds`) этим замером НЕ отменяется:
    #: мерили мгновенный чистый 404 от живого сервера внутри здоровой сессии, а исходное
    #: наблюдение «после 404 молчит минутами» пришло из другого сценария. Отдавать 404
    #: там, где можно подождать, мы по-прежнему не будем.
    sulk: float = 0.0
    #: Сколько ждём картинку, ВОЗОБНОВЛЯЯ показ, секунды.
    #:
    #: ⚠️ Прежнее объяснение («приёмник после 404 молчит две-три минуты») замером
    #: 09-08-2026 опровергнуто, а число осталось прежним, и теперь оно стоит на другом
    #: замере: приложение приёмника висит на экране 301 с после смерти сессии
    #: (:attr:`app_patience`), и пять минут - это ровно окно, в котором показ ещё может
    #: вернуться в своё же приложение.
    revive_timeout: float = 300.0
    #: Выдержка между попытками поднять погасший показ, секунды. Не про обиду за 404
    #: (её нет, см. :attr:`sulk`), а про то, чтобы не жечь попытки быстрее, чем приёмник
    #: успевает освободить экран.
    revive_pause: float = 60.0
    #: Неподвижный BUFFERING дольше этого - приёмник завис, сторож его расшевеливает.
    stall_seconds: float = 8.0
    #: Столько секунд упаковки впереди позиции считаем доказательством «еда на столе»:
    #: меньше - приёмник ждёт нас, и это лечится упаковкой, а не прыжком.
    ready_ahead: float = 8.0
    #: Шаг прыжка вперёд на каждом нудже: мимо куска, на котором приёмник споткнулся.
    stall_skip: float = 8.0
    #: Сколько нуджей подряд БЕЗ единого показанного кадра терпим, прежде чем перестать
    #: прыгать вовсе (:meth:`torrcast.cast.ChromecastReceiver._nudge`).
    #:
    #: 🔴 Замер 09-08-2026: за 780 с показа сторож сработал 24 раза, и 12 из них были
    #: ОДНОЙ лестницей подряд, без единого ``PLAYING`` между прыжками. Это не залипший
    #: кусок, а ушедший приёмник: лечится он воскрешением, а прыжки только шагают по
    #: фильму - те 12 нуджей увели указатель на 96 с вперёд впустую, и каждый стоил 8 с
    #: неподвижной картинки и до 8 с пропущенной плёнки.
    #:
    #: Три - это ровно терпение приёмника к стоящей картинке (:attr:`patience`, 23.5 с)
    #: при осторожном шаге сторожа: показ, не давший кадра за три нуджа, уже пережил тот
    #: срок, за который живая сессия умирает сама. Одиночный нудж - штатный случай, он
    #: вытаскивает подвис за 8 с, и этот счёт его не трогает: счёт обнуляет ЛЮБОЙ
    #: показанный кадр, а не просто уехавший указатель.
    blind_nudges: int = 3

    def verdict(self, codec: str, depth: int = 0) -> Verdict:
        """🔴 ЕДИНСТВЕННОЕ место, где решается судьба картинки: копия, перекод или отказ.

        Спрашивают отсюда все: отбор (:meth:`torrcast.cli._Bench._trouble`), упаковка
        (:func:`torrcast.stream.recodes_whole` и через неё :func:`torrcast.cli._encode_all`),
        прогрев впрок и ключ прогретого (:func:`torrcast.warm.warm_key`). Разойдись они
        хоть на один кодек - и приёмник получит то, чего не играет, либо показ не найдёт
        своего же прогретого. Ровно так и вышло дважды: сперва с десятибитным H.264
        (показ мешал в одном потоке копию и перекод), потом с VP9 (отбор его отбраковывал,
        а упаковка на названном руками релизе молча отдавала копией).

        Исходов ровно три:

        * :const:`COPY` - кодек в белом списке (:attr:`copy_codecs`) и глубина цвета не
          выше :attr:`copy_depth`. Только это и уезжает на приёмник как есть;
        * :const:`RECODE` - сплошной перекод: либо кодек, который мы берём на себя
          (:attr:`recode_codecs`), либо разрешённый кодек с непосильной глубиной цвета
          (Hi10P зовётся тем же ``h264``, а декодер его не берёт);
        * :const:`REFUSE` - всё остальное: vp9, av1, vc1, mpeg2video и любая экзотика,
          которой мы не мерили. На отборе это честный отказ и следующий релиз.

        ⚠️ :const:`REFUSE` - приговор ОТБОРУ, а не упаковке. Если такой файл всё же дошёл
        до показа (человек назвал релиз руками, запись возобновления снята прежней
        версией), упаковка обязана его перекодировать: копия тут - гарантированный чёрный
        экран, а перекод - хотя бы шанс. Поэтому упаковка спрашивает не «отказ ли это», а
        «уедет ли копией» (:func:`torrcast.stream.recodes_whole`).

        ``codec`` пустой - это записи прежних версий, где кодека не спрашивали вовсе: они
        играются как раньше, то есть считаются ``h264``. ``depth`` ноль - глубину не
        спрашивали, решаем по одному кодеку.
        """
        name = codec or "h264"
        if name in self.recode_codecs:
            return RECODE
        if name not in self.copy_codecs:
            return REFUSE
        return RECODE if depth > self.copy_depth else COPY

    def plays_copy(self, codec: str) -> bool:
        """Уедет ли такой кодек копией, если глубина цвета посильная (:meth:`verdict`)."""
        return self.verdict(codec) == COPY


#: Самый осторожный профиль: замеры живого Samsung Q70D, на котором доводился весь показ.
#: Он же достаётся приёмнику, который не представился или незнаком.
#:
#: 🔴 Каждое число тут - живой замер, и разбор каждого лежит там, где оно применяется:
#: вес сегмента и кодеки - :mod:`torrcast.stream`, терпение и нуджи - :mod:`torrcast.cast`,
#: пороги битрейта - :class:`torrcast.state.Config`.
CAUTIOUS: Final = Profile(key="q70d", title="осторожный (Samsung Q70D)")

#: Приставка Android TV (Xiaomi TV Stick). 🔴 Замер 09-08-2026: приставка берёт НАТИВНО
#: всё, обо что разбивался Q70D, - Hi10P (112 с подряд), HEVC 8 и 10 бит, VP9, AV1,
#: h264 1080p на 28 Мбит/с CBR, - и везде ноль ребуферов и ни одного ``BUFFERING``.
#: После 404 она делает один запрос, уходит в ``IDLE/ERROR`` на 4-й секунде, повторов не
#: делает и не обижается: следующий LOAD взят через 8.9 с.
#:
#: ⚠️ Смелым тут сделано ТОЛЬКО то, что замер подтверждает прямо:
#:
#: * пороги битрейта - 28 Мбит/с прошли начисто, потолок Q70D был около 10;
#: * терпение и перезаборы куска - измерены поимённо.
#:
#: ⚠️ Отсутствие наказания за 404 в этот список НЕ входит: замер 09-08-2026 нашёл ноль и
#: на Q70D тоже (:attr:`Profile.sulk`), то есть это свойство протокола, а не приставки.
#: Разница между приёмниками в другом: несколько перезаборов куска подряд, доигранный
#: буфер на тишине и приложение, висящее пять минут после смерти сессии, - самсунговские.
#:
#: ⚠️ Терпение к ПУСТОМУ ЭКРАНУ у приставки не мерено вовсе, поэтому :attr:`patience` ей
#: достаётся осторожное - самсунговские 23.5 с. Четыре секунды, которые замер называет,
#: относятся к другому сценарию (мёртвый URL, честный ответ «куска нет»), и живут они
#: своим полем (:attr:`dead_url_seconds`). Свалить их в :attr:`patience` значило бы
#: объявить измеренным то, чего никто не мерил. Сколько висит приложение у приставки,
#: не мерил никто тоже - :attr:`app_patience` ей достаётся осторожное.
#:
#: Набор кодеков намеренно оставлен прежним, хотя приставка их и берёт: замер снят на
#: НАТИВНЫХ файлах, а через наш mpegts ни HEVC, ни Hi10P на ней ещё не проходили. Это
#: отдельная карточка и отдельный гейт; механизм готов, ослабление ждёт замера.
#: Вес сегмента, шаг сетки, запас упаковки и пороги сторожа нуджей оставлены прежними по
#: той же причине: замер их не называет.
ANDROID_TV: Final = Profile(
    key="androidtv",
    title="приставка Android TV (Xiaomi TV Stick)",
    warn_mbit=28.0,
    recode_at_mbit=28.0,
    dead_url_seconds=4.0,
    segment_retries=0,
    revive_timeout=60.0,
    revive_pause=10.0,
)

#: Все профили по ключу: ключ пишется в ``receiver_profile``, если выбор нужно назвать
#: руками, и он же уходит в недельный след.
PROFILES: Final = {profile.key: profile for profile in (CAUTIOUS, ANDROID_TV)}

#: По какому слову в паспорте устройства узнаётся профиль. Слово ищется в склейке
#: «производитель + модель + имя», приведённой к нижнему регистру: у приставки модель и
#: имя пустые, а производитель есть, у телевизора бывает наоборот.
#:
#: ⚠️ Список короткий нарочно: тут только то, что измерено живьём. Незнакомому приёмнику
#: полагается :data:`CAUTIOUS`, а не ближайший похожий.
_KNOWN: Final[tuple[tuple[str, Profile], ...]] = (
    ("xiaomi", ANDROID_TV),
    ("android tv", ANDROID_TV),
    ("androidtv", ANDROID_TV),
)


@dataclass(frozen=True, slots=True)
class Choice:
    """Выбранный профиль и то, откуда он взялся, - для ``cast doctor`` и следа."""

    profile: Profile
    #: Человеческое «почему именно этот»: паспорт, настройка или молчание приёмника.
    how: str


def by_key(key: str) -> Profile | None:
    """Профиль по ключу; ``None`` — такого профиля нет (опечатка в настройке)."""
    return PROFILES.get(key.strip().lower())


def for_passport(maker: str = "", model: str = "", name: str = "") -> Profile:
    """Профиль по паспорту устройства; незнакомый приёмник получает :data:`CAUTIOUS`.

    Паспорт спрашивается у самого устройства (:func:`torrcast.scan.named`) обычным
    HTTP-опросом, без единой команды показа. Полей три, и полагаться на одно нельзя: у
    приставки Xiaomi имя и модель пустые, а производитель назван; у телевизора модель
    приходит от mDNS, а производителя не называет никто.
    """
    haystack = " ".join(part.lower() for part in (maker, model, name) if part)
    for word, profile in _KNOWN:
        if word in haystack:
            return profile
    return CAUTIOUS


#: Паспорта, уже спрошенные в этом процессе: адрес → профиль. Опрос стоит одного HTTP к
#: устройству, но показ спрашивает профиль в нескольких местах, и платить за каждое
#: незачем. Провал опроса кэшируется тоже: приёмник, который не ответил, за один показ
#: второй раз не оживёт, а лишние секунды в старте видны глазом.
_SEEN: dict[str, Choice] = {}

#: Сколько ждём паспорт. Больше не нужно: устройство отвечает по локальной сети сразу, а
#: молчащее (выключенный ТВ) всё равно не сыграет - и профиль ему достанется осторожный.
PASSPORT_TIMEOUT: Final = 2.0


def detect(config: Config) -> Choice:
    """Профиль приёмника для этих настроек: сперва названный руками, потом паспорт.

    Порядок ровно такой:

    * ``receiver_profile`` в настройках - последнее слово. Это и есть ручное
      переопределение: приёмник новый, паспорт врёт, хочется проверить пороги;
    * заглушка (``receiver: mock``) и показ без адреса - :data:`CAUTIOUS`: спрашивать
      паспорт не у кого;
    * иначе - опрос устройства и :func:`for_passport`.

    Опрос не имеет права уронить показ: любая осечка сети - это осторожный профиль и
    честная строка о том, что приёмник не представился.
    """
    named = str(getattr(config, "receiver_profile", "") or "")
    if named:
        chosen = by_key(named)
        if chosen is not None:
            return Choice(chosen, f"назван руками: receiver_profile={chosen.key}")
        return Choice(CAUTIOUS, f"профиля «{named}» нет - беру осторожный")
    address = str(config.tv or "")
    if config.receiver != "chromecast" or not address:
        return Choice(CAUTIOUS, "приёмника с паспортом нет - беру осторожный")
    if address in _SEEN:
        return _SEEN[address]
    choice = _asked(address)
    _SEEN[address] = choice
    return choice


def _asked(address: str) -> Choice:
    """Спросить паспорт у устройства и выбрать по нему профиль."""
    from torrcast.scan import named as ask

    try:
        device = ask(address, timeout=PASSPORT_TIMEOUT)
    except Exception:  # приёмник спит, сети нет, pychromecast не тот - это не авария
        return Choice(CAUTIOUS, "приёмник не ответил - беру осторожный")
    passport = ", ".join(part for part in (device.maker, device.model, device.name) if part)
    if not passport:
        return Choice(CAUTIOUS, "приёмник не представился - беру осторожный")
    return Choice(for_passport(device.maker, device.model, device.name), f"по паспорту: {passport}")


def forget() -> None:
    """Забыть спрошенные паспорта: нужно тестам и смене адреса ТВ на ходу."""
    _SEEN.clear()


def tune(config: Config, profile: Profile) -> Config:
    """Наложить профиль на настройки - те пороги, у которых есть свой ключ в конфиге.

    ⚠️ Названное человеком сильнее профиля: если ключ в конфиге отличается от
    осторожного умолчания, значит его писали руками, и профиль его не трогает. Равное
    умолчанию считается несказанным - иначе профиль не мог бы поменять вообще ничего,
    ведь умолчания конфига и есть :data:`CAUTIOUS`.
    """
    return replace(
        config,
        hls_segment=_said(config.hls_segment, CAUTIOUS.segment_seconds, profile.segment_seconds),
        hls_burst=_said(config.hls_burst, CAUTIOUS.burst, profile.burst),
        bitrate_warn_mbit=_said(config.bitrate_warn_mbit, CAUTIOUS.warn_mbit, profile.warn_mbit),
        recode_at_mbit=_said(
            config.recode_at_mbit, CAUTIOUS.recode_at_mbit, profile.recode_at_mbit
        ),
        recode_mbit=_said(config.recode_mbit, CAUTIOUS.recode_mbit, profile.recode_mbit),
    )


def _said(mine: float, stock: float, wanted: float) -> float:
    """Что победило: написанное человеком (``mine`` отличается от умолчания) или профиль."""
    return mine if mine != stock else wanted
