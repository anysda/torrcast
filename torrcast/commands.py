#: Сколько ПРИГОВОРОВ терпим заведомо, прежде чем начать считать деньги: подмены не
#: молчат. Приговор - это когда ffprobe раздачу прочитал и она не годится (av1, vc1,
#: тяжёлая). Осечка роя приговором не считается и попытку не жжёт (:meth:`_Bench.resolve`).
#:
#: 🔴 TC-188. Это ПОЛ, а не потолок: меньше трёх приговоров отбор не сдаётся никогда, а
#: сверху его держит уже не счётчик, а :data:`VERDICT_BUDGET` - секунды.
MAX_TRIES = 3
#: **Во что приговоры вправе обойтись ЧЕЛОВЕКУ, секунды** (:meth:`_Bench.resolve`).
#:
#: 🔴 TC-188. Счётчик приговоров мерил не то, чем платят. В замере каталога из 92 живых
#: 1080p, прошедших мимо показа, 44 просто СТОЯЛИ В ОЧЕРЕДИ: до них не дошли, потому что
#: три места :data:`MAX_TRIES` сгорали выше по списку - на именах, которые ffprobe читает
#: за секунду и тут же отбраковывает (SD-рип на 1.5 ГБ, vp9, av1). Такой приговор
#: человеку не стоит почти ничего, а место в очереди съедает ровно так же, как приговор
#: тяжёлому ремуксу, который поднимался полминуты.
#:
#: Поэтому потолок переведён в то, чем платят: в секунды ОЖИДАНИЯ. Считается не работа
#: фонового потока (он греет запасного параллельно, и часть его времени человеку ничего
#: не стоила), а ровно то, сколько отбор простоял на этой раздаче, прежде чем её осудить.
#: Раздача, прогретая ещё под меню (:data:`PREWARM_SPARE`), отвечает мгновенно - её
#: приговор и стоит почти нуля, и отнимать место у следующей ему не за что.
#:
#: Пятнадцать - это цена прежних трёх приговоров по верхней замеренной их цене (2-5 с на
#: приговор), то есть послаблением число не является: строже прежнего отбор не станет
#: (ниже :data:`MAX_TRIES` он не опускается), а мягче - только там, где приговоры
#: оказались дешёвыми. Потолок всей фазы (:data:`PICK_BUDGET`) стоит где стоял.
VERDICT_BUDGET = 15.0
#: Сколько картин франшизы греем под меню: топ-2-3 релиза уходят в TorrServer фоном,
#: пока человек отвечает на вопросы.
PREWARM = 3
#: Сколько ЗАПАСНЫХ релизов греется под меню сверх картин - у той картины, в которую
#: попадёт Enter (:func:`warm_order`). Прогрев под меню тратится на РАЗНЫЕ картины: человек
#: может ответить не дефолтом, и меню обязано вести в живое. Но внутри выбранной картины
#: до сих пор грелся ровно один релиз, а запасной поднимался только тогда, когда верх уже
#: забракован (:meth:`_Bench.resolve`) - то есть на бракованном верхе человек платил полную
#: цену подъёма второй раздачи: 6-7 с чистого ожидания DHT и ffprobe в фазе отбора.
#: Единица тут не «побольше параллели», а перенос по времени: этот же запасной всё равно
#: поднимался секундой позже, в resolve, - меняется только то, когда он начинает греться.
#: Пик одновременных раздач от этого не растёт (в отборе он и был PREWARM + 1), а вот пауза
#: под меню, которая иначе простаивает, уходит в дело.
PREWARM_SPARE = 1
#: Сколько раздач с ОБЕЩАННОЙ русской дорожкой греется под меню сверх запасного - одна,
#: ближайшая по очереди (:meth:`_Bench.spare`). 🔴 TC-309. Стоит такая раздача в очереди
#: где угодно - на 4-9 месте, - и подъём её с нуля это метаданные роя (3-6 с) плюс чтение
#: дорожек, то есть ровно те секунды, которых в отборе и не хватает.
#:
#: 🔴 TC-492. Спрашивают её теперь не отдельной проверкой, а самой очередью: гейт бракует
#: и прямое «нет», и молчание паспорта (:func:`voice_unproven`), поэтому отбор идёт дальше
#: и до обещавшей русскую раздачи доходит сам. Тёплой она нужна тем более: греется она
#: ровно тогда, когда очередь и правда может уйти дальше верха - молчаливое имя есть у
#: кого-то из первых :data:`MAX_TRIES` кандидатов, а обещавший русскую сосед в очереди
#: вообще есть.
PREWARM_DUB = 1
#: **Жёсткий потолок одновременных раздач, которые держим МЫ** (:meth:`_Bench._room`).
#:
#: Число не про вежливость к службе, а про её живучесть. Замер на стенде: TorrServer
#: падает по таймеру раз в 15 минут (паника в форке библиотеки), и срывается тем
#: вероятнее, чем больше раздач и чем активнее у них просят куски: с ОДНОЙ раздачей тик
#: проходит спокойно, со 120 раздачами и живым чтением - паника на первом же тике.
#: Прогрев по своей природе греет лишнее (:data:`PREWARM` картин плюс
#: :data:`PREWARM_SPARE`, а где верх промолчал про звук - ещё и :data:`PREWARM_DUB`), и
#: без потолка это лишнее копилось: очередь перебора поднимала
#: по раздаче за попытку, честная проверка (:meth:`_Bench._honest`) - ещё до
#: :data:`MAX_TRIES` сверху, а убиралось всё разом только перед стартом показа.
#:
#: Пять - это ровно пик прогрева под меню (:data:`PREWARM` + :data:`PREWARM_SPARE` +
#: :data:`PREWARM_DUB`), то есть замеренного выигрыша потолок не трогает: и топ-3
#: картины, и запасной релиз, и обещавший русскую сосед греются как грелись. Он режет то,
#: что живёт ПОСЛЕ того, как перестало быть нужным.
MAX_LIVE = PREWARM + PREWARM_SPARE + PREWARM_DUB
#: Бюджет одной раздачи на метаданные по DHT, секунды. Не уложилась - не «зависли
#: насмерть», а честная строка и следующий релиз.
META_BUDGET = 20.0
#: Бюджет на чтение дорожек (ffprobe) той же раздачи, секунды.
PROBE_BUDGET = 40.0
#: Сколько ffprobe ждёт первых байт потока, прежде чем счесть рой мёртвым, секунды.
#: Раздача с мёртвым роем метаданные отдаёт (они уже в TorrServer), а содержимого не
#: отдаёт вовсе - и раньше на ней сгорал весь :data:`PROBE_BUDGET` (сорок секунд на одном
#: молчащем релизе, когда рядом в очереди стояли живые). Отсрочка отделяет такой рой от
#: честно долгого заголовка («Моана 2» едет 17 с): ни байта за неё - пиров нет, обрываем
#: и берём запасного, он уже греется параллельно (:func:`torrcast.stream.swarm_pulse`).
#:
#: 🔴 TC-461. Двенадцать секунд - это КРАЙ разброса, а не его середина, и вот на чём это
#: стоит. Замер той же лентой опросов, что у :data:`PEER_GRACE`: 120 раздач сохранённого
#: каталога, поднятых по два раза каждая (240 подъёмов, 88 не дошли до этой фазы вовсе -
#: у них не приехали метаданные). Первый байт потока приходит за 1.9 с в половине случаев,
#: за 3.9 с в трёх четвертях, за 13.5 с в девяти десятых и за 19.7 с в девятнадцати
#: двадцатых; самый долгий из доехавших - 69 с.
#:
#: То есть подозрение, ради которого замер и делался, не подтвердилось: соседняя отсрочка
#: стояла на 75-м проценте своего разброса, а эта стоит на 89-м - там же, куда TC-387
#: поднял :data:`STEP_GRACE`. Видно это и по устойчивости приговора: соседние прогоны
#: одной раздачи расходятся в 4% пар против 29% у соседки до правки.
#:
#: Ложным приговор всё равно бывает часто - 15 из 26 «рой молчит» на этой ленте, - но
#: лечится это не отсрочкой: хвост распределения длинный, и даже 25 с оставляют 5 ложных
#: из 16, зато стоят молчащей раздаче лишних 13 с на пути к картинке. Цена ошибки та же,
#: что у соседки, и той же величины: место в очереди, а не показ - когда промолчали все,
#: последний спрос идёт без отсрочек вовсе (:meth:`_Bench._recheck`).
#:
#: Платят за отсрочку только раздачи, у которых роя правда нет: их в замере 4 из 80, и
#: каждый их подъём отсрочка экономит на 28 с против жизни без неё (:data:`PROBE_BUDGET`).
SWARM_GRACE = 12.0
#: **Бюджет всей фазы отбора, секунды**: столько CLI перебирает очередь, прежде чем
#: сдаться. Число не новое и не «с запасом»: это ровно прежний потолок фазы - три
#: попытки, каждая по полному бюджету раздачи (:data:`META_BUDGET` + :data:`PROBE_BUDGET`).
#: Потолок остался тем же, изменилось только, на что он тратится: раньше в него
#: укладывались строго три раздачи, теперь - сколько успеет, пока осечки идут молчанием
#: роя. Осечки эти дешёвые: запасной греется параллельно с текущим, поэтому мёртвая
#: раздача стоит не двадцати секунд, а разницы между двумя ожиданиями DHT.
PICK_BUDGET = MAX_TRIES * (META_BUDGET + PROBE_BUDGET)
#: Сколько ждём ответа от честного запасного, если верх оказался хуже, чем обещал. Запасной
#: к этой секунде уже греется (:meth:`_Bench.resolve` поднимает следующего сразу), так что
#: платим не за прогрев, а за разницу между двумя ffprobe. Не уложился - играем то, что
#: есть, и говорим об этом вслух: лишние секунды старта хуже, чем 574p.
HONEST_BUDGET = 12.0
#: Прочее на пути юнита до картинки, у чего своего потолка нет: запуск transient-юнита,
#: чтение состояния, подъём раздачи. Секунды, но считать их нулём - врать себе.
START_SLACK = 10.0
#: **Бюджет старта показа: столько CLI ждёт картинку на экране** (:func:`_await_playing`).
#:
#: Число не выбирается на глаз и не «берётся с запасом»: это сумма потолков всех фаз,
#: которые юнит проходит от запуска до первого ``PLAYING``, - метаданные раздачи, ffprobe
#: длительности, ожидание чужой карты опорных кадров, пробный прогон упаковки и терпение
#: приёмника к молчаливому ``IDLE``. Пока CLI ждал меньше суммы (120 с против 60 + 90 +
#: 60), он гасил `stop_play_unit`'ом показ, который вот-вот начался бы.
#:
#: Ждать так долго не страшно и не молчаливо: :class:`~torrcast.console.Progress` всё это
#: время показывает живую фазу, а любая честная неудача убивает юнит раньше - CLI видит
#: это по :func:`unit_active` и печатает причину из журнала, не досиживая до конца.
START_BUDGET = (
    WORKER_META
    + WORKER_DUR
    + KEYS_WAIT
    + PILOT_TIMEOUT
    + START_SLACK
    + ChromecastReceiver.START_TIMEOUT
)
#: Как часто показ пишет в журнал, что видит приёмник: позиция и общее время -
#: единственное доказательство того, что на экране есть таймлайн.
SAY_SECONDS = 30.0
#: ``TORRCAST_TRACE=1`` - писать в журнал запас показа на каждом опросе (раз в 2 с):
#: позиция приёмника, край упаковки, разница между ними и вес tmpfs. Инструмент про
#: устойчивость: её провал видно только в динамике запаса, а раз в 30 с он теряется.
TRACE_ENV = "TORRCAST_TRACE"
#: ``TORRCAST_CTL=<файл>`` - диагностический пульт показа: строка в файле («``seek 1200``»,
#: «``pause``», «``play``») исполняется владеющим сендером на ближайшем опросе, файл
#: съедается. Нужен ровно затем, что кнопку на пульте может нажать только человек, а
#: вторым pychromecast команду не подать вовсе: приёмник считает второе соединение тем же
#: сендером и отвечает пустым MEDIA_STATUS (докстринг :class:`ChromecastReceiver`).
#: Приёмнику это приходит той же MEDIA-командой, что и с пульта, поэтому проверка честная.
#: На счастливом пути не участвует: переменной нет - кода нет.
CTL_ENV = "TORRCAST_CTL"
#: Сколько терпим паузу на пульте, прежде чем погасить упаковку: дальше
#: сегменты копились бы в tmpfs впустую - приёмник их не забирает.
PAUSE_SECONDS = 60.0
#: Пауза длиннее этого - показ считается оконченным: юнит гаснет и не держит раздачу.
PAUSE_LIMIT = 3600.0
#: Сколько раз юнит поднимает погасший показ на ОДИН обрыв (:class:`_Revival`).
#: Три - это не «побольше»: столько же попыток даётся упаковке (:attr:`Feed.limit`), и
#: столько же раз человек нажал бы `cast` руками, прежде чем решить, что чинить надо не
#: показ. Удачей счётчик не обнуляется - иначе показ, гаснущий сразу после подъёма, гонял
#: бы приёмник по кругу вечно; его обнуляет пережитый обрыв (:data:`REVIVE_LIVED`).
REVIVE_TRIES = 3
#: Выдержка между попытками воскрешения.
#:
#: ⚠️ Прежнее обоснование («приёмник, поймавший 404, не берёт LOAD ещё две-три минуты»)
#: замером 09-08-2026 опровергнуто: наказания за 404 нет, ноль секунд
#: (:attr:`torrcast.profile.Profile.sulk`). Число осталось прежним по другой причине:
#: приложение Samsung Q70D занимает экран 301 с после смерти медиасессии
#: (:attr:`torrcast.profile.Profile.app_patience`), и минута между попытками - это про то,
#: чтобы не жечь их быстрее, чем приёмник успевает освободить экран.
#:
#: ⚠️ До ПЕРВОЙ попытки в темноте, которую устроил сам приёмник, эта минута больше не
#: выжидается: там своя выдержка и свой замер (:data:`REVIVE_DROP`).
REVIVE_PAUSE = 60.0
#: Сколько ждём ПРИЁМНИК, прежде чем первый раз поднять брошенный им же показ, секунды.
#:
#: 🔴 Замер: приёмник, только что погасивший показ, готов взять LOAD через 3-4 с - PLAYING
#: приходит на 3.2-3.6 с, то есть БЫСТРЕЕ обычного тёплого LOAD (5.6 с), и так трижды.
#: Минута (:data:`REVIVE_PAUSE`) в этой темноте была минутой чёрного экрана впустую: ждать
#: было уже нечего, приёмник давно готов.
#:
#: Осторожность из этого не пропала, она сдвинулась на попытки со второй: если самая
#: быстрая попытка показ не вернула, значит замер к этой аварии не подходит, и дальше
#: выдержка снова минутная. Все три попытки при этом укладываются в окно, пока экран ещё
#: занят нашим же приложением (:attr:`torrcast.profile.Profile.app_patience`, 301 с): на
#: сухом прогоне LOAD уходят на 8-й, 68-й и 128-й секундах темноты, а было 60/120/180.
#:
#: ⚠️ Восемь, а не четыре, - и это не промах: прежде чем поверить, что виноват приёмник,
#: показ шесть секунд расспрашивает источник (:data:`SOURCE_TRIES`, :func:`_blamed`), и
#: только потом начинает считать эту выдержку. Меньше 3-4 с тут ставить нечего - раньше
#: приёмник LOAD всё равно не берёт.
REVIVE_DROP = 4.0
#: Сколько показ должен идти ЖИВЫМ, чтобы запас попыток снова считался полным
#: (:meth:`_Revival.alive`). Замерено на живом Q70D: за 13 минут показа два коротких обрыва
#: съели все три попытки на весь сеанс - хотя каждый из них показ пережил, и третий обрыв
#: гасить было уже нечем. Запас попыток отмеряется обрыву, а не сеансу.
#: Меньше :data:`REVIVE_PAUSE` брать нельзя: тогда мигающий показ (поднялся и тут же погас)
#: возвращал бы себе попытки быстрее, чем тратит, и LOAD в приёмник шёл бы вечно. С этим
#: порогом поток LOAD ограничен сверху даже в самом злом случае: :data:`REVIVE_TRIES` штук
#: на каждую полную минуту НАСТОЯЩЕЙ картинки на экране.
REVIVE_LIVED = REVIVE_PAUSE
#: Сколько всего ждём в темноте, прежде чем погаснуть честно. Вчетверо дольше терпения
#: самого приёмника (~4 минуты) и вчетверо короче терпения к паузе (:data:`PAUSE_LIMIT`):
#: обрыв длиннее четверти часа - это уже не «моргнул интернет», зритель за это время
#: встал и ушёл, а держать раздачу и tmpfs ради пустого экрана незачем. Позиция к этому
#: моменту давно в состоянии, и `cast` продолжит с неё.
REVIVE_LIMIT = 900.0
#: Сколько раз спрашиваем источник, прежде чем поверить, что он в порядке (:func:`_blamed`).
#: Четыре вопроса через :data:`SOURCE_PAUSE` перекрывают замеренное окно перезапуска службы
#: (3.0-3.1 с) и её же панику (5 с) - а внутри этого окна она отвечает как живая.
SOURCE_TRIES = 4
#: Выдержка между вопросами источнику. Показ к этому моменту уже кончился, поэтому цена
#: тут одна - задержка последней строки, и платится она только за правду в ней.
SOURCE_PAUSE = 2.0

