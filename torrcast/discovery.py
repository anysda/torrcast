def _search(
    config: Config, args: Args, progress: Progress, profile: Profile = CAUTIOUS
) -> list[_Plan]:
    """Поиск и разбор выдачи: запрос → картины франшизы, каждая со своим пулом релизов.

    ``profile`` - чей декодер судит релизы (:mod:`torrcast.profile`). Пороги битрейта до
    отбора доезжают сами - профиль накладывается на настройки ещё в ``_cmd_play``
    (:func:`torrcast.profile.tune`), - а вот НАБОР КОДЕКОВ в настройках ключа не имеет, и
    спросить о нём можно только сам профиль (:func:`last_hope`). Умолчание осторожное, и
    пользуются им только ручки вроде ``cast voices``: ``cast releases`` передаёт
    обнаруженный профиль явно - таблица обязана судить про тот приёмник, на который
    поедет показ (TC-241).
    """
    from torrcast.parse import cluster, pick_franchise

    if not config.prowlarr_apikey:  # без Prowlarr искать нечем - это инфра-ошибка
        raise InfraError("не настроен Prowlarr: apikey пуст, перезапусти ./install.sh")
    query = args.title_query
    name, index = split_franchise_index(query)
    client = Prowlarr(config.prowlarr_url, config.prowlarr_apikey)
    progress.phase(f"поиск «{name}»")
    raw = _ask(client, name, progress)
    if not raw:
        # Ни одной строки - повод заподозрить забытую раскладку (:func:`unswap_layout`).
        # Проверка стоит один заход к индексерам и только там, где иначе был бы отказ.
        query, name, index, raw = _relayout(client, query, name, index, progress)
    mark("индексеры ответили", строк=len(raw))  # TC-108: замер
    pictures = cluster(to_releases(raw))
    # Номер в запросе - позиция во франшизе, а не в общей выдаче.
    found = pick_franchise(query, pictures)
    titled = False
    if index is not None and _season_asked(found, name, pictures):
        # 🔴 TC-363. У сериала номер это сезон, а не часть франшизы
        # (:func:`~torrcast.parse.reads_season`), и дальше по строке он идёт ровно тем же
        # путём, что и явное `sNeM`: своей сезонной машинерией, вплоть до честного
        # «раздач с сезоном N нет». Молчать о таком прочтении нельзя - номер человек
        # написал сам, и он вправе знать, чем мы его сочли.
        progress.note(f"«{name}» - это сериал: номер {index} читаю сезоном, а не частью")
        args = replace(args, query=[*name.split(), f"s{index}e1"])
        query, index = name, None
    if index is not None and not found:
        # Цифра оказалась частью названия, и обрубок увёз поиск не туда
        # (:func:`_titled_number`). Заход платится только вместо отказа.
        raw, pictures, found = _titled_number(client, query, name, raw, progress)
        # Каталог ответил: цифра - часть имени. Дальше по строке идут справка и добор, и
        # обрубок им не годится ровно так же, как не годился индексерам.
        titled = bool(found)
        if titled:
            name, index = query, None
    if worth_asking_original(found, args, config, profile):
        raw, pictures, found = _second_language(client, query, args, raw, found, progress, titled)
    elif index is None and not titled and _ceiling_hides_name(client, name, pictures, found):
        # Номер части и «цифра - часть названия» уточнению не подчиняются: запрос «имя +
        # год» строится по голому имени, и смысл номера в нём теряется.
        raw, pictures, found = _ceiling_reinforce(
            client, name, args, raw, pictures, found, progress
        )
    # Сериал есть, а раздач нужного сезона в нём нет - добрать сезонной строкой по
    # оригиналу, прежде чем честно отказать (:func:`_season_reinforce`).
    if _lacks_season(found, args):
        raw, pictures, found = _season_reinforce(client, query, args, raw, found, progress, titled)
    # Картина есть, а русской дорожки не обещает ни одна её играбельная раздача - добрать
    # точной строкой «оригинал + год» (:func:`_voice_reinforce`).
    if (voiceless := voiceless_pool(found, args, config, profile)) is not None:
        raw, pictures, found = _voice_reinforce(
            client, query, voiceless, raw, found, progress, titled
        )
    mark("поиск", найдено=len(raw))
    trace.emit("search", "query", query=query, raw=len(raw), pictures=len(pictures))
    if not raw:
        raise NotFoundError(f"по запросу «{name}» ничего не нашлось")
    if not pictures:
        raise NotFoundError(f"по запросу «{name}» ничего не разобралось")
    if not found:
        raise NotFoundError(_nothing(name, index, pictures))
    lead = _leading(found)
    if other := other_words(name, lead):
        progress.note(f"«{name}» - в каталоге это «{other}»")
    if lead is not None and lead.also:
        # Склейка картин (:func:`~torrcast.parse.glue`) - решение автоматическое, и молчать
        # о нём нельзя: человек спросил одно имя, а в меню и в отборе теперь оба.
        progress.note(f"«{lead.also}» и «{lead.title}» - одна картина, раздач {len(lead.releases)}")
    progress.phase("")
    # Номер пункта меню человек читает как номер части и им же отвечает: «Тачки 2» обязаны
    # стоять вторыми, а безномерные - после линейки (:func:`~torrcast.parse.menu_order`).
    found = menu_order(found)
    plans = [plan for plan in (_plan_for(p, args, config, profile) for p in found) if plan.ranked]
    for line in season_gaps(found, {plan.picture.key for plan in plans}, args.episode):
        progress.note(line)
    # Соседи по франшизе, до меню не доехавшие: понадобятся, если у выбранной картины
    # годного релиза не окажется вовсе (:func:`kin_line`).
    kin = _kin(_leading(found), pictures, {plan.picture.key for plan in plans})
    for plan in plans:
        plan.kin = kin
        # Опоздавший индексер (круг ушёл по кворуму, TC-118) доедет уже после меню -
        # ручку долива несёт план, а зовут её один раз и после ответа (:func:`_topup`).
        plan.late = client.late
    if not plans:  # картина есть, а раздач нужного сезона в ней нет
        want = args.episode or Episode(1, 1)
        raise NotFoundError(f"«{found[0].title}»: раздач с сезоном {want.season} нет")
    return plans


def worth_asking_original(
    found: list[Picture], args: Args, config: Config, profile: Profile = CAUTIOUS
) -> bool:
    """Стоит ли переспросить оригинальным названием (:func:`_second_language`).

    Поводов два, и оба про одно: русской выдачи не хватило.

    1. Пул ТОЩИЙ - строк выдачи меньше :data:`~torrcast.parse.THIN_POOL`. Мера считается
       строками (:attr:`~torrcast.parse.Picture.rows`), а не склеенными раздачами:
       зеркалящие индексеры несут один торрент по разу каждый, и по склеенному пулу
       порог срабатывал бы тем чаще, чем больше зеркал в круге.
    2. 🔴 TC-245. Пул НЕГОДЕН - раздач много, а играть нечем (:func:`unfit_pool`).
       Тощесть тут ничего не ловит, а беда та же самая: «Оранжевый хит сезона» приезжал
       57 русскими строками без единого HD, отбор перебирал мертвецов и сдавался, тогда
       как под ``Orange Is the New Black`` лежат 93 HD. То же у «Звёздного пути:
       Следующее поколение» (24 строки без HD против 116 со ста живыми HD). Толщина пула
       про его годность не говорит ровно ничего, и мерить надо годность.

    Второй повод считается по УЖЕ вынесенным приговорам отбора, а не заранее: пул
    прогоняется через тот же :func:`_plan_for`, что построит меню, и вопрос к нему один -
    осталось ли после отбора хоть что-нибудь, чем стоит играть. Лишнего круга на здоровой
    выдаче отсюда не берётся: годная раздача есть - второго захода нет.

    🔴 TC-262. **Цена второго повода замерена, и она мала.** Тысяча запросов в один поток:
    ОДИН ЛИШЬ второй повод (пул не тощий, но негоден) срабатывает в 16 запросах из 1000, и
    сквозной поиск на них дорожает на 1.84 с по медиане (p90 2.07 с, максимум 2.45 с) -
    пятая часть цели в :data:`~torrcast.search.GOAL` секунд. Мерено двумя способами: тем же
    поиском со старым поводом (только тощесть) в чередующихся арках и отдельным
    секундомером вокруг самого добора (медиана 2.18 с, из них справка до 1.5 с, круг по
    индексерам 0.5-1.8 с).

    Круг этот вдобавок не всегда лишний: в 7 запросах из 16 он ЗАМЕНЯЕТ собой тот, что
    иначе заплатил бы добор голоса (:func:`_voice_reinforce`) - там дельта нулевая. И
    платит он за дело: в 12 запросах из 16 после круга у картины впервые появился годный
    релиз, впустую круг ушёл ровно в одном.

    ⚠️ Сузить повод до «негоден И мёртв» (то есть требовать, чтобы живого не было даже
    среди старья) - соблазн, но замер против: одну лишнюю трату в 2.3 с это сняло бы
    вместе с ПЯТЬЮ спасёнными вечерами, где живым в пуле было только старьё («Конклав»,
    «Реальная любовь», «Крёстный отец 2», «Шёпот сердца», «Иван Васильевич меняет
    профессию»). Старьё играется, когда другого нет вовсе, - но это не повод не искать
    другого.

    Цель второй повод не роняет: единственный запрос замера, перевалив 10 с, простоял их
    на ПЕРВОМ круге. Тогда остаток цели отменял второй заход вовсе - и ровно это стоило
    картины (TC-386): с тех пор добор по второму имени бюджетом не отменяется, а идёт с
    полом в целую цель (:func:`_second_language`).

    Рядом, тем же решением «идти ли на второй круг», стоит третий повод: пул упёрся в
    потолок индексера, а картины с именем запроса в ней нет вовсе
    (:func:`_ceiling_hides_name`). Он срабатывает лишь когда эти два молчат: тощий или
    негодный пул важнее обрезанного хвоста.
    """
    from torrcast.parse import THIN_POOL

    if max((p.rows for p in found), default=0) < THIN_POOL:
        return True
    return unfit_pool(found, args, config, profile)


def unfit_pool(
    found: list[Picture], args: Args, config: Config, profile: Profile = CAUTIOUS
) -> bool:
    """Пул негоден: ни у одной картины нет раздачи, которой стоило бы играть.

    «Стоило бы» - это :func:`fitness`, то есть уже собранные факты отбора: раздача годна
    по :func:`is_candidate`, жива по :data:`ALIVE_SEEDERS` и не старьё по
    :func:`is_dated`. Ни одного такого релиза во всём пуле - и вечер по этой выдаче не
    состоится, сколько бы строк в ней ни было.
    """
    return not any(fitness(_plan_for(p, args, config, profile)) for p in found)


#: Сколько соседей по франшизе называем в строке отказа. Больше не помещается в строку, да
#: и незачем: это подсказка, а не второй список - список человек уже получит по `cast`.
KIN_SHOWN: Final = 3


def season_gaps(found: list[Picture], shown: set[str], want: Episode | None) -> list[str]:
    """Честные строки о сериалах, выпавших из меню целиком: сезона нет, а раздачи есть.

    🔴 Молчаливых отказов у нас не бывает, а тут был самый глухой из возможных: картина
    доезжает до меню живой, план по ней не строится (ни одна раздача не назвала нужный
    сезон - :meth:`~torrcast.parse.Release.covers`), и она просто исчезает из списка.
    Человек видит меню без неё и дефолт, вставший на соседа, - и ни одного слова о том,
    что произошло. Замер на «Гинтама»: картина 2018 года переживает привязку с 41
    раздачей и 33 живыми, на `s1e1` даёт ноль кандидатов, а дефолтом встаёт спин-офф
    «Gintama: 3-nen Z-gumi Ginpachi-sensei» - восьмым пунктом из восьми.

    Строка говорит ровно то, что мы знаем, и ни словом больше: сколько раздач у картины
    и какие сезоны они назвали. Обещать, что нужный сезон где-то есть, нельзя - его в
    этой выдаче действительно нет, и второй заход за ним уже сделан там, где он
    применим (:func:`_season_reinforce`).

    Молчат ли раздачи о сезонах вовсе (:func:`~torrcast.parse.seasons_named` пуста) -
    строки нет: сказать «сезона 1 нет» про имена, которые о сезонах не говорили,
    значило бы соврать. Такая картина в план и так попадает: молчание имени -
    «может быть», а не «нет».
    """
    from torrcast.parse import seasons_named

    asked = (want or Episode(1, 1)).season
    lines = []
    for picture in found:
        if picture.kind != "tv" or picture.key in shown or not picture.releases:
            continue
        if not (named := seasons_named(picture)):
            continue
        have = ", ".join(str(s) for s in named)
        lines.append(
            f"«{picture.title}» ({picture.year or '?'}): раздач {len(picture.releases)},"
            f" но сезона {asked} среди них нет - названы {have}"
        )
    return lines


def _kin(picture: Picture | None, pictures: list[Picture], shown: set[str]) -> list[Picture]:
    """Части франшизы, до меню не доехавшие, но в каталоге живые.

    Не доехать часть могла по-разному: запрос попал в свою половину двуязычной франшизы,
    или у картины не осталось ни одного релиза, прошедшего отбор. Обещать за них ничего
    нельзя - поэтому строка отказа говорит ровно «в каталоге есть», а не «возьми это».
    """
    from torrcast.parse import franchise_name, pick_franchise

    if picture is None:
        return []
    whole = pick_franchise(franchise_name(picture.title), pictures)
    return [p for p in whole if p.key not in shown and p.key != picture.key and p.releases]


def kin_line(kin: list[Picture]) -> str:
    """«в каталоге есть Тачки 2 (2011), Тачки 3 (2017) - cast тачки 2». Пусто - молчим.

    Строка-подсказка, и только: сама другую часть не запускает. Человек просил «cast
    cars», у этой картины годного релиза не нашлось - и подменить её соседкой по франшизе
    значило бы показать не то, что просили. А вот промолчать о живых соседях, отправив
    человека разбираться руками, - это скрыть то, что мы уже знаем.
    """
    if not kin:
        return ""
    names = ", ".join(f"{p.title} ({p.year or '?'})" for p in kin[:KIN_SHOWN])
    return f"в каталоге есть {names} - cast {kin[0].title.casefold()}"


def silent_swarm(
    plan: _Plan, queue: list[int], touched: int, shown: str, *, picked: int | None = None
) -> str:
    """Отказ, когда ни одна тронутая раздача не отозвалась ни метаданными, ни потоком.

    Прежде это была одна строка на все случаи - «рой у них мёртв, пиров нет». С виду
    честная, она врала чаще прежней: в замере каталога такой вердикт получили 18
    запросов из 225, и у девяти из них рой был ЖИВОЙ - просто очередь отбора кончилась
    на трёх раздачах из пятнадцати, а «пиров нет» было сказано про всю выдачу.

    Очередь отбора (:meth:`_Plan.candidates`) - это не вся выдача: мимо неё проходят
    раздачи с чужой серией, образы дисков, слишком тяжёлые. Молчание тех, кого
    потрогали, не говорит ни слова о тех, кого не трогали. Поэтому строк пять, и
    различает их не догадка, а счётчики:

    * сидов не числится ни у одной раздачи картины - пиров правда нет, и сказать так
      можно честно;
    * обход не дошёл до конца очереди: его остановил потолок фазы
      (:data:`PICK_BUDGET`), и сколько именно раздач осталось неспрошенными, строка
      называет числом (TC-435);
    * потрогали всю выдачу до последней - молчат все, кого вообще можно было спросить,
      но сиды у них числились: это молчание роя, а не пустой каталог;
    * нетронутое осталось, но всё оно непригодно по уже ИЗВЕСТНЫМ признакам - нужной
      серии нет по имени раздачи или она тяжелее потолка (TC-375): играть в нём
      нечего, и строка говорит об этом прямо, ручного выбора не предлагая. Замер по
      сохранённым прогонам: у таких отказов 132 нетронутые раздачи из 195 не
      содержали запрошенной серии вовсе;
    * нетронутое осталось, и пригодное в нём есть - про него мы не знаем ничего, и
      врать за него нельзя. Человеку остаётся ручной выбор, и строка говорит, чем
      именно он располагает.

    Числа в строке - всегда два: сколько раздач было в выдаче и сколько потрогали.
    Сиды называются как обещание индексера («числится»), а не как факт: раздача,
    которая молчит поток, показывает в выдаче сотню сидов ровно так же бодро. И
    числится максимум по ОЧЕРЕДИ, а не по всей выдаче (TC-376): иначе число ложилось
    на раздачу, которую ворота в очередь не пустили вовсе, и выглядело уликой против
    роя («числится 25, а молчат»), уликой не будучи. Исключение - первая строка: её
    «пиров нет ни у одной» сказано про всю выдачу и считается по всей выдаче.

    🔴 Ход человеку предлагает КАЖДАЯ из строк, и ходы эти разные, потому что разное
    осталось непроверенным. Там, где отбор до пригодной части выдачи не дошёл, ход -
    ручной выбор: непроверенные раздачи есть, и они рядом. Там, где потрогали всё или
    где нетронутое заведомо непригодно, ручной выбор врал бы надеждой - выбирать не
    из чего, и честный ход другой: назвать картину иначе (другой запрос собирает
    другую выдачу) или вернуться позже, когда рой проснётся. Отказ без хода - это
    тупик, в котором человек остаётся один; раньше таким был отказ по
    :data:`PEER_GRACE`, а он теперь и самый частый.

    Обход, срезанный часами, ход получает тот же - «иначе или позже», а не ручной
    выбор. Про неспрошенный хвост очереди неизвестно ничего, кроме одного: весь бюджет
    фазы ушёл на раздачи, которые стояли ВЫШЕ него и не отозвались ни одна. Указать на
    хвост номером значило бы выдать за подсказку то, чего мы не проверяли; сказать, что
    рой молчит и сколько раздач он молчит, - это факт.
    """
    total = len(plan.ranked)
    peers = max((plan.ranked[n - 1].seeders for n in queue), default=0)
    all_peers = max((release.seeders for release in plan.ranked), default=0)
    counts = f"раздач в выдаче {total}, потрогали {touched}"
    later = (
        "назови картину иначе или зайди позже - другой запрос соберёт другую выдачу, "
        "а рой может ожить"
    )
    if all_peers <= 0:
        return f"{counts} - пиров нет ни у одной, показывать нечего: {later} ({shown})"
    if touched < len(queue):
        # 🔴 TC-435. Обход кончился не очередью, а часами (:data:`PICK_BUDGET`): дальше
        # головы дело не дошло, и приписывать молчание хвосту нельзя - его не спрашивали.
        # Числа тут два, и оба свои: сколько раздач отбор взял и сколько успел потрогать.
        return (
            f"{counts} из очереди {len(queue)} - эти молчат, на остальных не хватило "
            f"времени (у потроганных числилось до {peers} сид), показывать нечего: "
            f"{later} ({shown})"
        )
    queued = set(queue)
    untouched = [r for n, r in enumerate(plan.ranked, start=1) if n not in queued]
    # Причины - в порядке суда отбора (:func:`drop_reason`): у выкинутой их бывает
    # несколько сразу, а называется та, на которой её и выкинули.
    no_episode = [r for r in untouched if misses_episode(r, plan.want)]
    heavy = [
        r
        for r in untouched
        if not misses_episode(r, plan.want)
        and over_ceiling(r, plan.runtime, plan.warn_mbit, plan.hard_mbit)
    ]
    if len(untouched) > len(no_episode) + len(heavy):
        seed = (
            f" (у потроганных числилось до {peers} сид)"
            if peers
            else " (сидов у потроганных не числилось)"
        )
        move = "выбери другой релиз" if picked is not None else "выбери руками"
        return (
            f"{counts} - эти молчат, до остальных отбор не дошёл{seed}: {move} - "
            f"cast releases <запрос>, потом cast <запрос> --release N ({shown})"
        )
    if not untouched:
        return (
            f"{counts} (все) - ни одна не отозвалась, хотя сиды у них числятся "
            f"(до {peers}), показывать нечего: {later} ({shown})"
        )
    why = [f"нужной серии нет - {len(no_episode)}"] if no_episode else []
    why += [f"тяжелее потолка - {len(heavy)}"] if heavy else []
    return (
        f"{counts} - эти молчат, а остальным играть нечего ({', '.join(why)}), "
        f"показывать нечего: {later} ({shown})"
    )


def unfit_line(plan: _Plan, drops: dict[str, int], kin: list[Picture]) -> str:
    """Отказ, когда ворота отбора не пропустили НИ ОДНОГО релиза картины (TC-432).

    Пустая очередь - это картина, в выдаче которой одни игры, книги, образы дисков или
    раздачи тяжелее потолка. Сыграть такую вместо спрошенной картины было бы подменой,
    худшим видом брака, и отказ тут честнее показа.

    Замер по корпусу-100 (515 планов, 100 запросов) говорит, чего этот отказ стоит:
    очередь пустеет у 51 плана, и у каждого из них она состояла ровно из одной раздачи
    - той самой, что проходила мимо ворот. Ни разу пустая очередь не досталась картине
    по умолчанию, ни разу не осталось без очереди всё меню запроса: человек видит
    отказ, только сам назвав пункт списка, и список у него перед глазами.

    Ход у отказа обязан быть всегда. Живых соседей по франшизе строка предлагает
    (:func:`kin_line`), а «выбери руками» не предлагает: раздачи отвергнуты по уже
    ИЗВЕСТНЫМ признакам, и номер этого не меняет. Названный человеком релиз при этом
    играет как играл: ворота на него не смотрят вовсе (:meth:`_Plan.candidates`).

    🔴 TC-447. Соседей нет - и ход всё равно есть, той же строкой. Честное «ничего не
    нашлось» тут врало бы: картина в каталоге есть, негодны её раздачи, - так и
    говорится, и следующий шаг тот же, что у молчащего роя (:func:`silent_swarm`):
    назвать картину иначе (другой запрос собирает другую выдачу) или зайти позже.

    Строка называет выдачу и причины: счёт отсева (:func:`queue_drops`) гарантирует,
    что сумма причин сходится с пулом, - ни одна раздача не пропадает молча.
    """
    why = ", ".join(f"{reason} - {count}" for reason, count in drops.items())
    line = (
        f"годного релиза нет: раздач в выдаче {len(plan.picture.releases)}, "
        f"и все до одной отсеял отбор ({why})"
    )
    if offer := kin_line(kin):
        return f"{line}\n{offer}"
    return (
        f"{line} - картина есть, а раздачи её негодны: назови её иначе или зайди позже - "
        "другой запрос соберёт другую выдачу, а годный рип может появиться"
    )


def _nothing(name: str, index: int | None, pictures: list[Picture]) -> str:
    """Почему ответа нет. Причины две, и человеку с ними делать разное.

    Прежде обе накрывались одной строкой - «такой картины во франшизе нет». Она честна
    ровно в одном случае из двух: когда франшизу нашли, а нужной части в ней не оказалось.
    В остальных выдача не содержала вообще ничего похожего на запрос («дети мужчин» - это
    ``Children of Men``, в каталоге такого имени нет вовсе), и строка про франшизу
    отправляла человека проверять номер части там, где не нашлось и самого фильма.

    Разводим по факту: спрашивали ли номер и стоит ли за ним живая франшиза.

    * франшиза есть, номера в ней нет → сколько в ней картин и что номера столько нет,
      плюс перечень того, что в ней есть, - молчаливого отказа быть не должно (TC-373);
    * во всём остальном → честное «ничего не нашлось», то есть «назови другими словами».
    """
    from torrcast.parse import pick_franchise

    whole = pick_franchise(name, pictures) if index is not None else []
    if whole:
        have = ", ".join(f"{p.title} ({p.year or '?'})" for p in whole[:5])
        more = " и другие" if len(whole) > 5 else ""
        return f"«{name}»: картин во франшизе {len(whole)}, номера {index} нет - есть: {have}{more}"
    return f"по запросу «{name}» ничего не нашлось"


def _ask(client: Prowlarr, query: str, progress: Progress) -> list[RawResult]:
    """Один запрос к индексерам; пусто - это не ошибка, а повод переспросить иначе.

    🔴 TC-510. Выпавший источник называется вслух ОДНОЙ строкой и ровно один раз за
    поиск (:attr:`~torrcast.search.Prowlarr.reported_silent`), но выпасть он может двумя
    способами, и оба тут названы: молчун не ответил нам, а забаненного мы и не
    спрашивали - Prowlarr не дал (TC-259). Молча источник не выпадает: без этой строки
    «ничего не нашлось» звучит приговором каталогу, хотя спрошена была его часть.
    """
    try:
        rows = client.search(query)
    except NotFoundError:
        rows = []
    # Через getattr, а не полем: в тестах на месте клиента стоят подделки, которые
    # обещают только `search`, и требовать от них весь договор Prowlarr незачем.
    reported: set[str] = getattr(client, "reported_silent", set())
    gone = [
        (name, why_gone)
        for names, why_gone in (
            (getattr(client, "silent", ()), "не ответил"),
            (getattr(client, "banned", ()), "недоступен"),
        )
        for name in names
        if name not in reported
    ]
    reported.update(name for name, _ in gone)
    if len(gone) == 1:
        progress.note(f"индексер {gone[0][0]} {gone[0][1]} - выдача может быть хуже")
    elif gone:
        listed = ", ".join(f"{name} {why_gone}" for name, why_gone in gone)
        progress.note(f"индексеры выпали из каталога: {listed} - выдача может быть хуже")
    return rows


def _no_budget(client: Prowlarr, what: str, progress: Progress) -> float | None:
    """Хватит ли остатка цели на второй заход; ``None`` - не хватит, и это сказано вслух.

    🔴 TC-228. Второй круг зовётся в 18 запросах из 100 и удваивает цену поиска: сквозной
    замер 1.93-2.39 с там, где он есть, против 0.01-0.09 с там, где его нет. Своего
    бюджета у него не было вовсе - он платил хвост первого круга плюс свой полный, и на
    хвосте Knaben (502 плюс ретрай, 10-20 с) это давало 30 с при цели в 10.

    Теперь у него есть остаток цели (:meth:`~torrcast.search.Prowlarr.spare`), и остаток
    этот честный: часы идут от начала поиска, поэтому справка на пути добора
    (:func:`~torrcast.facts.origin`) считается наравне со всем прочим, а не «бесплатно».
    Возвращается она же как потолок справки - чтобы та не съела то, на что рассчитывает
    сам круг (:data:`~torrcast.search.CIRCLE_SHARE`).

    Отказ не молчаливый: человек ждал дольше обещанного и вправе знать, что второго
    захода за него не сделали. Обещать «нашлось бы» тут нельзя - неизвестно.

    ⚠️ Охранник это заходов, у которых есть честный отступ: уточнение по потолку
    индексера, сезонная и голосовая строки, переспрос всей строкой - без них отвечает
    то, что уже найдено. Добор по второму ИМЕНИ картины сюда не приходит: у него свой
    счёт бюджета, и отмены в нём нет вовсе (:func:`_second_language`, TC-386).
    """
    spare = client.spare()
    if spare >= SECOND_LEAST:
        return min(FACTS_BUDGET, spare - CIRCLE_SHARE)
    progress.phase("")
    progress.note(f"{what} не делаю: поиск уже съел цель в {GOAL:.0f} с")
    return None


def _second_language(
    client: Prowlarr,
    query: str,
    args: Args,
    raw: list[RawResult],
    found: list[Picture],
    progress: Progress,
    titled: bool = False,
) -> tuple[list[RawResult], list[Picture], list[Picture]]:
    """Русский запрос дал пусто или тощий пул - переспросить тем же названием на латинице.

    Индексер ищет по имени раздачи, поэтому «Психо» приносит десяток русских имён, а
    сорок раздач ``Psycho.1960.*`` остаются за бортом - и человек либо смотрит 576p, либо
    (как на «Птицах») не получает ни одного годного релиза. Догадываться, что надо
    набрать латиницей, он не обязан: название на латинице лежит в первой же выдаче,
    :func:`~torrcast.parse.alt_query` его оттуда и достаёт.

    Второй заход стоит ещё одного круга по индексерам, поэтому он не всегда, а только на
    тощем пуле: на полной выдаче (порог :data:`~torrcast.parse.THIN_POOL`) поиск остаётся
    ровно таким, каким был. Цена круга - обычно 0.5-1.5 с, но ровно та же, что у первого:
    если индексер молчит, круг стоит его личного бюджета
    (:data:`~torrcast.search._QUORUM_TIMEOUT`), и тогда добор виден человеку секундами
    ожидания. Обещать «1-3 с» тут нельзя: замеры на живом стенде давали и 101.6-102.1 с -
    столько круг стоил, пока молчание одного индексера ждали общим запросом.

    🔴 TC-386. **Отмены по бюджету у добора нет.** Остаток цели (:meth:`Prowlarr.spare`)
    задавал ему потолок, а ниже :data:`~torrcast.search.SECOND_LEAST` отменял вовсе - и
    отмена стоила картины: при медленном первом круге (живой замер - Knaben 7.0 с вместо
    0.5) пул «тачек» падал с 28 раздач до 4-5, и поиск кончался отказом при живом
    каталоге. По лестнице целей «не включилось» сильнее «дольше 10 секунд», поэтому цель
    тут подчинена поиску: пол бюджета круга добора - целая цель
    (:attr:`~torrcast.search.Prowlarr.cap_floor`), а съеденный остаток не отменяет заход,
    а объявляется строкой. Остальные вторые заходы (уточнение, сезон, голос) бюджетом
    по-прежнему охраняются (:func:`_no_budget`) - у них есть честный отступ, тут его нет.

    Запросы идут последовательно, а не парой: второе имя достаётся из ПЕРВОЙ выдачи, до
    неё его просто нет. И уж точно не тем же именем: на латинском запросе оригинал из
    выдачи совпадает с самим запросом, и круг уходил целиком впустую - на живом стенде
    это стоило 102 секунды до меню.

    Строка вердикта печатается ПОСЛЕ строки того круга, о котором она говорит: ``note``
    выходит сразу, а строка фазы - только когда фазу закрыли, и в прежнем порядке «не
    беру» стояло перед «поиск… 102.1 с». Читалось это как противоречие: сначала отказ,
    а следом будто бы удавшийся второй поиск, из которого и выросло меню.

    Выдачи склеиваются, а не заменяются: русские имена несут озвучки и оригинал, по
    которому кластер и сшивает оба языка в одну картину. Если добор ничего не дал или
    картину после него не нашли, остаётся прежний результат - хуже стать не может.

    🔴 **Гейт: добор не вправе подменить картину.** Русское имя картину не определяет.
    «Восхождение» - это и фильм Шепитько 1977 года, и китайский 2019-го, подписанный
    тем же словом; оригинал ``The Climbers`` лежал прямо в русской выдаче, добор
    переспрашивал им и приносил два десятка раздач чужого кино с дорожкой ``und``.
    Раздач становилось больше, прежней проверке этого хватало, и человек молча получал
    не тот фильм. Поэтому мало «стало больше» - сверяется САМА КАРТИНА:

    * год у справки (:func:`~torrcast.facts.origin`) - она отвечает про ту картину, что
      спросили, и её слово сильнее выдачи;
    * год картины, за которой шли ДО добора, - если справки нет, годится и он;
    * франшиза - когда года не назвал никто.

    ⚠️ Год справки не в счёт, когда в запросе назван номер части: справку зовут по имени
    франшизы, и год она называет первой картины, а спрашивали другую.

    Расхождение или сомнение - добора не было. Честное «не нашлось» лучше чужого фильма,
    и это не перестраховка: подмену видно только по году, потому что кластер сшивает
    одноимённые картины в одну франшизу и «стало больше» у неё выходит честным.

    ⚠️ Право у гейта ровно одно - НЕ ДОБАВИТЬ своё. Выбросить то, что нашёл первый,
    русский запрос, он не вправе: отказ от добора возвращает прежнюю выдачу целиком
    (:func:`_as_is`), а не пустоту.

    🔴 **Привязка к картине - вторая половина того же вопроса.** Латинская раздача
    («Blue Exorcist - 01 [1080p]») не несёт ни русского имени, ни оригинала, поэтому
    кластеру нечем сшить её с русской картиной, а :func:`~torrcast.parse.pick_franchise`
    по русскому запросу до неё не достаёт. Привезённое добором уезжало в мусор ровно
    здесь: 105 раздач на 33 сида при трёх русских с нулём живых. Поэтому берутся ОБЕ
    половины - и найденная по русскому имени, и подписанная самим именем добора, - но
    вторая лишь тогда, когда за это имя ручается справка (:func:`_vouched`).

    🔴 TC-253. **Пустая русская выдача - гейт остаётся без опоры.** Сверять добор не с
    чем: картины до него не было, и :func:`same_picture` вырождается в вопрос о
    ПРОИСХОЖДЕНИИ имени, а про картину происхождение не говорит ничего. Справка же тут
    ошибается уверенно: статьи «Все мы незнакомцы» в Википедии нет, и по сходству имён
    находится «Все мы убийцы» - французская картина 1952 года, то есть ровно молчаливая
    подмена картины. Поэтому имя, лишь ПРИЗНАННОЕ похожим
    (:attr:`~torrcast.facts.Origin.guessed`), проверенным не считается. Требование одно и
    то же, есть вожак или нет (TC-359): с вожаком гейт сверяет добор со справкой, а оба
    они на этом пути про одну и ту же чужую картину, и сверка сходится на подмене:

    * справка назвала ту же картину тем же именем (:func:`~torrcast.facts.same_name`,
      «Сальтберн» и «Солтберн») - второй признак есть, идём как шли;
    * назвала другим («Все мы незнакомцы» против «Все мы убийцы») - это другая картина, и
      второго захода за ней не делаем вовсе: круг по индексерам тут не нужен, а честное
      «ничего не нашлось» не хуже чужого фильма под знакомым именем;
    * своего русского имени у статьи нет (аниме подписано латиницей) - сверить было не с
      чем, и добор берётся со строкой ровно об этом. Молча выдать его за проверенный
      нельзя: имя человек назвал сам, а картину под ним выбрала справка.

    ⚠️ Имени, за которым стоит САМА Википедия, это не касается: перенаправление «Мальчик
    и цапля» → «Мальчик и птица» - её собственное утверждение о том, что это одна вещь,
    и отметки ``guessed`` у такого паспорта нет.

    ⚠️ ``titled`` - каталог уже сказал, что хвостовая цифра это часть НАЗВАНИЯ, а не номер
    части (:func:`_titled_number`). Тогда обрубок «бен» не годится ни справке, ни строке
    добора: по нему справка отвечает про «Бен-Гур», и второй заход уходит за чужой
    картиной. Спрашиваем всей строкой - справка знает «Бен 10» и отдаёт ``Ben 10``.
    """
    from torrcast.parse import alt_query, cluster, pick_franchise

    name, index = (query, None) if titled else split_franchise_index(query)
    spare = client.spare()
    if spare >= SECOND_LEAST:
        # 🔴 TC-243. Картины не нашлось вовсе - без второго имени тут отказ, и справка
        # становится единственной опорой: ей отдаётся весь остаток цели за вычетом доли
        # круга, а не обычный потолок. Полутора секунд ей не хватает: прямая выборка
        # промолчала, а поиск Википедии и разбор описки - это ещё два-три запроса, и они
        # физически не успевают («Секреты Лос-Анджелеса» и «Реинкарнация (фильм, 2018)»
        # лежат первыми строками поиска, но приезжают уже никому не нужными).
        budget = spare - CIRCLE_SHARE if not found else min(FACTS_BUDGET, spare - CIRCLE_SHARE)
    else:
        # 🔴 TC-386. Остатка цели на добор не хватает - а добор всё равно делается. Отмена
        # тут стоила картины: на живом стенде «тачки» при медленном Knaben (7.0 с вместо
        # 0.5) теряли пул с 28 раздач до 4-5 и кончались отказом. По лестнице целей
        # «не включилось» сильнее «дольше 10 секунд», поэтому цель тут подчиняется:
        # справке - её обычный потолок, кругу добора - пол в целую цель
        # (:attr:`~torrcast.search.Prowlarr.cap_floor`), и человек читает про это строку.
        progress.phase("")
        progress.note(
            f"поиск уже съел цель в {GOAL:.0f} с - добор по «{name}» всё равно делаю: "
            "картину ищут оба её имени"
        )
        budget = FACTS_BUDGET
    pool = [r for p in found for r in p.releases] or to_releases(raw)
    lead = _leading(found)
    # Справку спрашиваем вслепую: год выдачи ей не сообщаем, иначе она подстроится под него
    # и сверять станет нечего. Тип картины - другое дело, у сериала и фильма разные статьи.
    # Сети нет - паспорт пуст, и всё дальше работает ровно так, как работало.
    kind = _asked_kind(lead, args)
    about = origin(name, series=kind, budget=budget)
    if not about and kind is not None:
        # 🔴 TC-399. Тип подсказал вожак тощего пула, и под ним справка промолчала.
        # Подсказка эта слабая: единственная строка тощего пула бывает не картиной
        # вовсе - по запросу «lain» приехал самиздатовский журнал «lainzine 1-5», он
        # назвал тип «фильм», и справка честно молчала: статьи о фильме «Lain» нет,
        # есть статья о сериале «Serial Experiments Lain». Переспрос без типа
        # (:func:`~torrcast.facts.origin_either`) спрашивает обе статьи разом и верит
        # лишь согласию - подмену он не родит, а молчание разводит.
        about = origin(name, series=None, budget=budget)
    if index is not None:
        # 🔴 Спросили номер части - год справки к делу не относится. Справку зовут по имени
        # франшизы, и отвечает она про её ПЕРВУЮ картину: у «тачек» это 2006 год, а человек
        # просил «тачки 2» - картину 2011-го. Гейт читал это расхождение как подмену и
        # выбрасывал честную выдачу; на живом стенде «тачки 2» так и не находились вовсе.
        # Название латиницей остаётся: номер части у него всё равно отрезан, и оно верное.
        about = Origin(title=about.title, name=about.name, guessed=about.guessed)
    alt = alt_query(name, pool, about.title, about.name)
    # 🔴 TC-253, TC-359. Имя добора - догадка справки, и гейт (:func:`same_picture`)
    # против неё безоружен в обоих случаях: на пустой выдаче сверять добор не с чем, а
    # с вожаком гейт сверяет добор со СПРАВКОЙ - но оба они тут про одну и ту же чужую
    # картину, и сверка сходится. Справка на этом пути ошибается уверенно: статьи «Все
    # мы незнакомцы» в Википедии нет, и по сходству имён находится «Все мы убийцы» -
    # французская картина 1952 года. Раньше эту ложь чаще прятал потолок в полторы
    # секунды; теперь справке тут отдают весь остаток цели, и доезжать она будет ЧАЩЕ.
    # Поэтому имя, лишь признанное похожим, само себя не доказывает - ему нужен второй
    # признак, и требование одно и то же, есть вожак или нет.
    hearsay = about.guessed and slugify(alt) == slugify(about.title)
    if hearsay and about.name:
        # Второй признак у справки есть, и он её же: она называет имя, под которым нашла
        # картину. То же самое имя (пусть и другой транскрипцией - «Сальтберн» и
        # «Солтберн») - подтверждение; другое слово в имени - другая картина, и второго
        # захода за ней не бывает. Отказ тут не хуже: честное «ничего не нашлось» лучше
        # чужого фильма под знакомым именем.
        if not same_name(name, about.name):
            progress.phase("")
            progress.note(
                f"по «{name}» справка нашла лишь похожее имя «{about.name}» - "
                "за чужой картиной не иду"
            )
            return _as_is(raw, found, about, progress)
        hearsay = False
    # Полное имя уже приехавшей картины может лежать только в паспорте. Короткий запрос
    # ``lain`` сам по себе выбирает журнал ``lainzine``, хотя в том же первом пуле есть
    # ``Serial Experiments Lain``. Второй круг тут ничего не находит - он лишь повторяет
    # уже имеющуюся картину другим именем. Паспортное имя применяем прямо к первому пулу,
    # но только когда оно однозначно указывает на одну картину и её год не спорит со
    # справкой. Сам короткий запрос права голоса не получает.
    first_pictures = cluster(to_releases(raw))
    passport_hits: dict[str, Picture] = {}
    for passport_name in (about.title, about.name):
        for picture in pick_franchise(passport_name, first_pictures):
            passport_hits[picture.key] = picture
    found_keys = {picture.key for picture in found}
    if len(passport_hits) == 1 and set(passport_hits) != found_keys:
        passport_found = list(passport_hits.values())
        if _vouched(passport_found, about, proven=True):
            return raw, first_pictures, passport_found
    said = _query_note(name, alt, pool, about)
    # Тем же именем второй раз ходить незачем: на «cast cars» оригинал из выдачи - «Cars»,
    # и это ещё один полный круг по всем индексерам (на живом стенде - до 102 секунд, если
    # в круге кто-то молчит) ради той же самой выдачи. Регистр и разделители имя не меняют,
    # поэтому сверяем по слагу.
    if not alt or slugify(alt) == slugify(name):
        return _as_is(raw, found, about, progress)
    # Несколько картин под одним коротким именем заполняют широкий латинский поиск
    # свежими тёзками. Если независимый паспорт назвал отсутствующий в первом круге год,
    # уточняем исходное имя им: это всё тот же один добор, но русская строка сохраняет
    # релизы с озвучкой, ради которых человек и назвал картину по-русски.
    exact_year = (
        about.year
        if index is None
        and about.year is not None
        and len(found) > 1
        and all(picture.year is None or abs(picture.year - about.year) > 1 for picture in found)
        else None
    )
    asked = f"{name} {exact_year}" if exact_year is not None else alt
    progress.phase(f"поиск «{asked}»")
    # 🔴 TC-386. Круг добора спрашивается с полом в целую цель: медленный, но живой
    # индексер (на живом стенде Knaben отвечал 7.0 с вместо 0.5) в остаток цели не
    # укладывается, и добор проходил формально, не привезя ничего, - картина пропадала
    # из каталога так же, как при отмене. На здоровом круге пол ничего не стоит:
    # кворум закрывает круг за его обычные 0.5-1.5 с.
    client.cap_floor = GOAL
    try:
        second = _ask(client, asked, progress)
        # Пока шёл второй круг, один из запросов мог завершиться уже после кворума.
        # Список картин человеку ещё не показан, поэтому готовый хвост можно включить в
        # тот же отбор без ожидания и без подмены уже прочитанного меню. Особенно важен
        # хвост первого круга: картина без латинской подписи по имени добора не найдётся.
        merged = merge(raw, second, client.late())
    finally:
        client.cap_floor = CIRCLE_SHARE
    # Круг кончился - закрываем его строку прямо здесь. Всё, что скажем дальше, это его
    # итог, а `note` печатается сразу, тогда как строка фазы ждёт закрытия фазы: без этого
    # вердикт «не беру» выходил ПЕРЕД строкой «поиск «Cars»... 102.1 с», и человек читал два
    # несвязанных сообщения как противоречие - отказ, а следом будто бы удавшийся поиск.
    progress.phase("")
    if len(merged) == len(raw):
        outcome = f"добор по «{alt}» ничего не дал"
        progress.note(f"{said}; {outcome}" if said else outcome)
        return _as_is(raw, found, about, progress)
    pictures = cluster(to_releases(merged))
    # Транслит - это сами слова запроса, чужого фильма он принести не может; оригинал из
    # справки отвечает про ту самую картину. А вот оригинал из выдачи ничем не подтверждён.
    proven = bool(about.title) or alt == about.name or alt == transliterate(name)
    # Спрашивали по-русски - им и выбираем; кластер сшил оба языка по оригиналу.
    mine = pick_franchise(query, pictures)
    # 🔴 Но сшивать бывает нечем: латинская раздача «Blue Exorcist - 01 [1080p]» не несёт
    # ни русского имени, ни поля «оригинал», и кластер оставляет её отдельной картиной, до
    # которой русский запрос не достаёт. Привезённое добором уезжало в мусор ровно на этой
    # привязке: 105 раздач на 33 сида при трёх русских с нулём живых. Поэтому картины,
    # подписанные САМИМ именем добора, берутся вдобавок к русским, а не вместо них.
    theirs = pick_franchise(f"{alt} {index}" if index else alt, pictures)
    vouched = _vouched(theirs, about, proven)
    if not (vouched or not mine):  # за это имя никто не ручается - берём лишь своё
        theirs = []
    wider = mine + [p for p in theirs if p.key not in {q.key for q in mine}]
    was = sum(len(p.releases) for p in found)
    now = sum(len(p.releases) for p in wider)
    if now <= was:
        # Прибавка не в раздачах картины, а в чужих строках выдачи: широкий пул сдвинул бы
        # нумерацию франшизы («дилижанс 1» уехал бы с 1939 года на 1936) и ничего не дал
        # взамен. Тогда второго захода как будто и не было.
        outcome = f"добор по «{alt}» новых раздач картины не дал"
        progress.note(f"{said}; {outcome}" if said else outcome)
        return _as_is(raw, found, about, progress)
    # Имя добора от справки - она отвечает про ТУ САМУЮ картину, и спор идёт лишь о том,
    # доехала ли картина нужного года. Имя из выдачи ничем не подтверждено - там гейт строг
    # и сверяет вожака: именно он станет ответом.
    after = _twin(wider, about, lead) if proven else _leading(wider)
    if not vouched and not same_picture(lead, after, about, proven):
        outcome = f"по «{alt}» приехала другая картина - остаюсь на выдаче по «{name}»"
        progress.note(f"{said}; {outcome}" if said else outcome)
        return _as_is(raw, found, about, progress)
    details = []
    if hearsay:
        # Своего русского имени у статьи нет вовсе (аниме русская Википедия подписывает
        # латиницей), и подтвердить догадку справки было нечем. Выдать её за проверенное
        # молча нельзя: человек вправе знать, на чьём слове стоит эта выдача.
        details.append(f"имя «{alt}» взято со справки, сверить было не с чем")
    details.append(f"по-русски раздач {was} - добрал по «{alt}»: стало {now}")
    progress.note("; ".join(([said] if said else []) + details))
    return merged, pictures, wider


def _asked_kind(lead: Picture | None, args: Args) -> bool | None:
    """Сериал это или фильм - для справки; ``None`` - неизвестно, и она спросит оба.

    Тип разводит статьи Википедии по разным страницам, и наугад его подсказывать нельзя:
    с ``True`` «Восхождение» уводит в чужой сериал 2024 года вместо фильма Шепитько, с
    ``False`` «Дедвуд» даёт фильм 2006 вместо сериала 2004. Поэтому источников ровно два,
    и оба говорят о картине прямо:

    * выдача первого круга - у найденной картины тип уже разобран;
    * сам запрос - серию называет человек, и «клиника s1e1» это утверждение о сериале,
      а не догадка (:attr:`Args.episode`).

    🔴 TC-243. Второй источник нужен там, где первого нет: русская выдача пуста, тип брать
    было неоткуда, и справка шла в самом слабом своём режиме - «спросить оба и поверить
    лишь согласию» (:func:`~torrcast.facts.origin_either`). Согласия у сериала с фильмом
    не бывает ровно тогда, когда одноимённый фильм существует: «Дедвуд» и «Клиника» на
    живой пробе так и теряют имя (``Deadwood``, ``Scrubs``) - а без имени второй заход
    уходит транслитом в никуда. Молчание о серии по-прежнему НЕ значит «фильм»: сериал
    зовут и без номера, поэтому там остаётся прежний осторожный режим.
    """
    if lead is not None:
        return lead.kind == "tv"
    return True if args.episode else None


def _query_note(name: str, alt: str, pool: list[Release], about: Origin) -> str:
    """Строка о том, что запрос второго захода выбрала справка, а не транслит с выдачей.

    Молчаливых подмен у нас нет, и смена ЗАПРОСА - такая же подмена, как смена картины:
    в индексер уходит не то, что человек набрал. Пока справка молчала, второй заход шёл
    транслитом («Крики и шёпот» → ``kriki i shepot``), и по одной строке фазы «поиск
    «Viskningar och rop»» не понять, откуда взялось шведское имя и почему ему верить.

    Печатается только там, где справка ДЕЙСТВИТЕЛЬНО изменила запрос: без неё второй заход
    ушёл бы другим именем (транслитом или оригиналом из выдачи). Совпали - говорить не о
    чем, и строки нет: справка тут ничего не решила.
    """
    from torrcast.parse import alt_query

    if not alt or not about.title:
        return ""
    blind = alt_query(name, pool)  # чем бы искали, не будь справки
    if not blind:
        return f"оригинал «{alt}» - по справке; без неё второго запроса не было бы"
    if slugify(blind) == slugify(alt):
        return ""
    return f"оригинал «{alt}» - по справке; без неё искал бы «{blind}»"


def _vouched(theirs: list[Picture], about: Origin, proven: bool) -> bool:
    """Ручается ли за приехавшее само имя добора: каталог подписал им эту картину.

    Гейт узнаёт «ту же вещь» по ОРИГИНАЛУ: ремейк «Корзинки фруктов» 2019 года несёт тот
    же ``Fruits Basket``, что и справка, - и это добор, а не подмена. Но у половины
    каталога поля «оригинал» нет вовсе: латинская раздача подписана одним именем, и оно
    стоит НАЗВАНИЕМ картины. Доказательство от этого не слабеет - меняется лишь место,
    где оно записано, и картина «Blue Exorcist» под именем из справки ровно так же не
    может быть однофамильцем, как и картина с таким оригиналом.

    Отсюда два условия, и оба обязательны:

    * имя добора ``proven`` - от справки или транслит запроса, а не вычитано у чужой
      раздачи (``The Climbers`` из выдачи «Восхождения» не ручается ни за что);
    * год не спорит: справка знает год, картина под этим именем называет СВОЙ, и они
      врозь - это однофамилец, и ручаться за него нельзя. Года у латинских раздач обычно
      нет вовсе (``Blue Exorcist - 01 [1080p]``), и тогда спорить не о чем.

    ⚠️ Ручательство не отменяет гейт, а даёт ему второй ключ: вожака он сверяет как
    сверял, и добор, приехавший под ИМЕНЕМ ИЗ ВЫДАЧИ, отбраковывается ровно как прежде.
    """
    lead = _leading(theirs)
    if not proven or lead is None:
        return False
    return about.year is None or lead.year is None or abs(lead.year - about.year) <= 1



