def magnet_for(info_hash: str, title: str = "") -> str:
    """Собрать magnet из hash, имени и списка публичных трекеров."""
    parts = [f"magnet:?xt=urn:btih:{info_hash.lower()}"]
    if title:
        parts.append(f"dn={quote(title)}")
    parts += [f"tr={quote(t, safe='')}" for t in PUBLIC_TRACKERS]
    return "&".join(parts)


def indexer_budget(name: str) -> float:
    """Сколько секунд ждём ЭТОГО индексера. Единственное место, где считается бюджет.

    Складывается из двух вещей, и обе замерены:

    * РОЛЬ в круге (TC-226): кворумного (:data:`QUORUM_INDEXERS`) ждём полный
      :data:`_QUORUM_TIMEOUT`, потому что без него каталога нет; остальных - столько,
      сколько их выдаче ещё есть куда лечь (:data:`_EXTRA_TIMEOUT`), круг их и так не ждёт;
    * КОРОТКИЙ СПИСОК (TC-213): у кого нечего терять, тот и ждать себя не заставляет
      (:data:`_SHORT_BUDGET`). Берём меньшее из двух - короткий список только урезает,
      поднять бюджет он не может.
    """
    low = name.lower()
    role = _QUORUM_TIMEOUT if quorum_indexer(name) else _EXTRA_TIMEOUT
    short = any(mark in low for mark in _SHORT_BUDGET)
    return min(role, _SHORT_TIMEOUT) if short else role


def anime_query(query: str) -> bool:
    """Запрос похож на аниме - значит Nyaa и прочие анимешные индексеры идут в основном
    круге, а не фолбэком (TC-229).

    Признак нарочно дешёвый, две проверки. Прямые слова - «аниме», японские жанры,
    OVA, ``[TV]`` (тот же узкий список, что судит имена раздач,
    :func:`~torrcast.parse.looks_anime`). Иначе - латиница без кино-маркеров
    (:data:`_NOT_ANIME_RE`): каталог Nyaa ромадзи/английский, и оригинальное имя аниме
    («Frieren», «Steins Gate») неотличимо от имени картины, поэтому сомнение трактуем
    в пользу вызова - полноту аниме ронять нельзя. Зато русскоязычный запрос без
    аниме-слов Nyaa молчит почти всегда (замер 09-08-2026: пусто в 79% запросов,
    строки - только на аниме), и там он зовётся лишь фолбэком на тощем пуле
    (:meth:`Prowlarr._apart`) - параллель по нему лимитирована, и лишний круг это
    лишний риск 504-бана Prowlarr на часы.
    """
    if looks_anime(query):
        return True
    if _CYRILLIC_RE.search(query):
        return False
    return not _NOT_ANIME_RE.search(query)


def quorum_indexer(name: str) -> bool:
    """Индексер из кворума (:data:`QUORUM_INDEXERS`) - тот, без которого выдачи нет.

    Имя приходит от Prowlarr как есть («Knaben», «RuTor»), поэтому сверяем подстрокой
    в нижнем регистре - ровно как :func:`~torrcast.parse.anime_indexer`.
    """
    low = name.lower()
    return any(part in low for part in QUORUM_INDEXERS)


def _moment(failed: str) -> float | None:
    """Отметка последнего отказа глазами Prowlarr в секундах эпохи; ``None`` - не прочли.

    ``failed`` - UTC-время вида «2026-08-09T20:13:28Z». Дробную часть секунды отрезаем:
    Prowlarr отдаёт её то в шесть знаков, то в семь, а :meth:`~datetime.datetime.fromisoformat`
    до 3.12 семь не принимает.
    """
    try:
        return datetime.fromisoformat(
            re.sub(r"\.\d+", "", failed).replace("Z", "+00:00")
        ).timestamp()
    except ValueError:
        return None


def _rested(failed: str) -> bool:
    """Отдохнул ли источник настолько, что в него пора стучаться (:data:`_HEAL_PAUSE`).

    Отметка отказа - это и весь наш тормоз: памяти между поисками у клиента нет, а её
    Prowlarr переписывает на КАЖДОМ отказе - в том числе на нашей неудачной проверке.
    Отсюда и свойство, ради которого отметка взята вместо своего счётчика: сколько бы
    поисков ни случилось подряд, в мёртвый источник мы постучимся не чаще раза в паузу.

    Время не прочиталось - считаем, что пора: не полечить вовсе хуже, чем сходить лишний раз.
    """
    moment = _moment(failed)
    if moment is None:
        return True
    return time.time() - moment >= _HEAL_PAUSE


def _just_now(failed: str, since: float) -> bool:
    """Случился ли отказ уже ПОСЛЕ начала этого поиска (TC-291).

    Судим строго: время не прочиталось - значит не обвиняем. Ошибиться сюда дёшево
    (промолчим о том, о чём молчали и раньше), а в другую сторону - дорого: это
    честное «ничего не нашлось», объявленное отказом канала.

    :data:`_CLOCK_SLACK` - припуск на отрезанные доли секунды и на то, что отметку
    ставит не наш секундомер. Часы при этом одни и те же: Prowlarr живёт на той же машине.
    """
    moment = _moment(failed)
    return moment is not None and moment >= since - _CLOCK_SLACK


@dataclass(slots=True)
class _Ask:
    """Один спрошенный индексер: место под ответ и флаг «поток закончил».

    Поток свой и демонский, а не из пула: опоздавший живёт дольше круга (TC-118), и
    пул задержал бы на нём выход процесса - потоки пула дожидаются на atexit, демонские
    умирают вместе с командой.
    """

    name: str
    budget: float
    done: threading.Event = field(default_factory=threading.Event)
    rows: list[RawResult] | None = None
    ms: int = 0
    err: InfraError | None = None


@dataclass(frozen=True, slots=True)
class RawResult:
    title: str
    info_hash: str
    size: int = 0
    seeders: int = 0
    indexer: str = ""
    #: Сколькими строками выдачи приехала эта раздача: индексеры зеркалят друг друга, и
    #: один торрент приходит от нескольких сразу. :func:`merge` оставляет одну строку, но
    #: помнит, сколько их было - иначе счёт «сколько нашлось» зависел бы от того, как
    #: устроен опрос индексеров, а не от каталога.
    copies: int = 1
    #: ВСЕ индексеры, принёсшие эту раздачу, по именам и по алфавиту. Склейка оставляет
    #: одну строку (:func:`_fold`), и поле :attr:`indexer` у неё - индексер той строки,
    #: чьё ИМЯ победило, а не «откуда раздача вообще пришла». Разница не бухгалтерская:
    #: у Nyaa и AniLibria аниме - всё, что там лежит, и признак жанра
    #: (:attr:`~torrcast.parse.Release.anime`) читается именно отсюда. Пусто - строка ещё
    #: не проходила склейку, и всё, что известно, стоит в :attr:`indexer`.
    indexers: tuple[str, ...] = ()

    @property
    def magnet(self) -> str:
        return magnet_for(self.info_hash, self.title)

    @classmethod
    def build(cls, title: Any, info_hash: Any, size: Any, seeders: Any, indexer: Any) -> RawResult:
        """Собрать результат из сырых полей; без валидного hash строка бесполезна."""
        text = str(info_hash or "").strip()
        if not _HASH_RE.match(text) or not str(title or "").strip():
            raise ValueError("нет hash или имени")
        return cls(str(title), text, _int(size), _int(seeders), str(indexer or ""))


def _collect(rows: Iterable[_Row]) -> list[RawResult]:
    """Собрать строки выдачи, молча пропуская непригодные (без hash или имени)."""
    out: list[RawResult] = []
    for row in rows:
        try:
            out.append(RawResult.build(*row))
        except ValueError:
            continue
    return out


def from_json(payload: Any) -> list[RawResult]:
    """Разобрать ответ ``/api/v1/search``."""
    if not isinstance(payload, list):
        raise InfraError("Prowlarr вернул неожиданный ответ")
    return _collect(
        (i.get("title"), i.get("infoHash"), i.get("size"), i.get("seeders"), i.get("indexer"))
        for i in payload
        if isinstance(i, dict)
    )


def from_torznab(xml: str) -> list[RawResult]:
    """Разобрать Torznab-RSS: ``infohash`` и ``seeders`` лежат в ``torznab:attr``."""
    try:
        root = ElementTree.fromstring(xml)
    except ElementTree.ParseError as exc:
        raise InfraError(f"индексер вернул битый XML: {exc}") from exc
    rows: list[_Row] = []
    for item in root.iter("item"):
        attrs = {a.get("name", ""): a.get("value", "") for a in item.iter(f"{_TORZNAB_NS}attr")}
        indexer = item.findtext("prowlarrindexer") or item.findtext("jackettindexer") or ""
        title, size = item.findtext("title"), item.findtext("size")
        rows.append((title, attrs.get("infohash"), size, attrs.get("seeders"), indexer))
    return _collect(rows)


class Prowlarr:
    def __init__(self, base_url: str, apikey: str, timeout: float = _TIMEOUT) -> None:
        self.base_url = base_url.rstrip("/")
        self.apikey = apikey
        self.timeout = timeout
        #: Индексеры, не уложившиеся в личный бюджет последнего поиска - по именам.
        self.silent: tuple[str, ...] = ()
        #: Индексеры, отдавшие ровно ``limit`` строк последнего поиска, - по именам.
        #: Ровно потолок - это не полнота, а обрезанный хвост: за сотней строк могут
        #: лежать раздачи, до которых выдача не дошла (:func:`~torrcast.cli._ceiling_reinforce`).
        self.capped: tuple[str, ...] = ()
        #: Уже названные человеку молчуны: повторный добор не должен повторять строку.
        self.reported_silent: set[str] = set()
        #: Индексеры, которых Prowlarr увёл в недоступные, - по именам. Молчунами они не
        #: считаются: молчун не ответил нам, а этих мы и не спрашивали (TC-259).
        self.banned: tuple[str, ...] = ()
        self._session: requests.Session | None = None
        self._indexers: tuple[tuple[int, str], ...] | None = None
        #: Опоздавшие: круг ушёл по кворуму, а эти ещё в пути (TC-118).
        self._late: list[_Ask] = []
        #: Начало поиска - от него считается остаток цели (:meth:`spare`, TC-228).
        #: Клиент живёт ровно один поиск, поэтому «создан» и «начат» тут одно и то же.
        self._began = time.monotonic()
        #: То же начало, но по стенным часам: с ними сверяются отметки отказов, которые
        #: ставит Prowlarr (:func:`_just_now`, TC-291). Монотонные тут не годятся - у них
        #: своя точка отсчёта, общей с чужими отметками у них нет.
        self._begun_at = time.time()
        #: Первый круг ещё не сделан: он один и идёт без оглядки на цель.
        self._first = True
        #: 🔴 TC-386. Пол бюджета ВТОРОГО круга: потолком ему служит остаток цели
        #: (:meth:`spare`), но ниже этой отметки он не опускается. Обычный пол -
        #: :data:`CIRCLE_SHARE`: круг, спрошенный меньше чем на секунду, -
        #: гарантированный молчун. Добор по второму имени картины поднимает пол до
        #: :data:`GOAL` (:func:`torrcast.cli._second_language`): без второго имени
        #: картина пропадает из каталога, а медленный, но живой ответ индексера
        #: (99-я доля - 5.6 с) в десять секунд укладывается.
        self.cap_floor: float = CIRCLE_SHARE

    def search(self, query: str, limit: int = 100) -> list[RawResult]:
        """Найти раздачи во всех подключённых индексерах: :class:`InfraError` — Prowlarr
        недоступен или ответил не тем, :class:`NotFoundError` — пригодных раздач нет.

        Спрашиваем КАЖДЫЙ индексер отдельным запросом (см. :meth:`_apart`): у общего
        запроса нет частичного ответа, и один молчун держит в себе выдачу всех
        остальных. Анимешные индексеры (Nyaa и прочие) - только на похожем на аниме
        запросе (:func:`anime_query`) или фолбэком на тощем пуле (TC-229). Список
        индексеров не отдали - остаётся прежний общий запрос.
        """
        found = self._apart(query, limit)
        results = found if found is not None else from_json(self._get_json(self._url(query, limit)))
        if not results:
            raise self._nothing(query)
        return results

    def _nothing(self, query: str) -> TorrcastError:
        """Чем считать пустой поиск, когда часть каталога до нас не дошла (TC-259, TC-291).

        «Ничего не нашлось» - утверждение о КАТАЛОГЕ, и делать его, не спросив половину
        каталога, нельзя: замер выдачи даёт 41% строк на Knaben и 56% на RuTor, и это
        разные половины. Поэтому бан кворумного (:func:`quorum_indexer`) превращает пустой
        ответ из «такого фильма нет» в «судить не по чему» - разные это и для человека, и
        для кода возврата. Бан некворумного пустоту не отменяет (у YTS замерено НОЛЬ
        запросов, где он единственный источник), но и молчать о нём нельзя: человек должен
        знать, что искали урезанным каталогом.

        🔴 TC-291 закрывает окно ПЕРЕД баном. Бан - это уже вторая беда; первая в том,
        что на самый первый отказ источника Prowlarr отвечает нам ``200 []`` - ровно тем
        же, чем отвечает на честное «такого фильма нет». Замер на живом стенде: источник
        отвечает отказом соединения, первый запрос - ``HTTP 200, строк 0``, и лишь со
        второго приходит 400 «выбранные индексеры недоступны» (это уже :meth:`_blocked`).
        То есть соврать хватает одного запроса - а живьём этого хватило, чтобы на
        лежащем звене сказать «ничего не нашлось» про полный каталог.
        """
        refused = self._refused()
        if any(quorum_indexer(name) for name in self.banned):
            return InfraError(
                f"по запросу «{query}» искать было нечем: Prowlarr увёл в недоступные "
                f"{', '.join(self.banned)} - без них каталога нет"
            )
        if any(quorum_indexer(name) for name in refused):
            return InfraError(
                f"по запросу «{query}» искать было нечем: отказ у {', '.join(refused)} - "
                "пустая выдача тут не «такого фильма нет», а молчание источника"
            )
        if self.banned or refused:
            urezan = "; ".join(
                part
                for part in (
                    f"Prowlarr увёл в недоступные {', '.join(self.banned)}" if self.banned else "",
                    f"отказ у {', '.join(refused)}" if refused else "",
                )
                if part
            )
            return NotFoundError(
                f"по запросу «{query}» ничего не нашлось; каталог сейчас урезан - {urezan}"
            )
        return NotFoundError(f"по запросу «{query}» ничего не нашлось")

    def _refused(self) -> tuple[str, ...]:
        """Кто отказал ПОКА ШЁЛ этот поиск, спрятав отказ за пустой выдачей (TC-291).

        Спрашиваем ту же ручку, что и :meth:`_blocked`, но ПОСЛЕ круга, а не до: до круга
        отметки ещё нет - её ставит сам отказ. Живой замер показал, что ставится она в тот
        же миг, в который нам приходит ``200 []``, так что окна между ложью и её уликой
        нет вовсе.

        Уже забаненных (:attr:`banned`) отсюда убираем нарочно: их мы и не спрашивали, а
        отметку им мог обновить наш же лечебный стук (:meth:`_heal`) - обвинить круг в
        чужом отказе значило бы соврать во вторую сторону.

        Лишним походом это не становится: зовётся ровно там, где выдача пуста, то есть
        там, где мы и так собираемся что-то заявить о каталоге. На пути к картинке
        (:data:`GOAL`) этого запроса нет.
        """
        names = dict(self._known())
        if not names:
            return ()
        return tuple(
            name
            for num, failed in sorted(self._blocked().items())
            if (name := names.get(num, ""))
            and name not in self.banned
            and _just_now(failed, self._begun_at)
        )

    def _url(self, query: str, limit: int, indexer: int | None = None) -> str:
        from torrcast.parse import wire_query

        cats = "".join(f"&categories={c}" for c in _CATEGORIES)
        one = f"&indexerIds={indexer}" if indexer is not None else ""
        # Спрашиваем ровно то, что просили, но в форме, которую переживёт санитайзер
        # Prowlarr (:func:`~torrcast.parse.wire_query`, TC-129). Само название человеку
        # не переписываем: в сообщениях и ключах состояния остаётся исходный запрос.
        return (
            f"{self.base_url}{_SEARCH_PATH}?apikey={quote(self.apikey)}"
            f"&query={quote(wire_query(query))}&type=search&limit={limit}{cats}{one}"
        )

    def _apart(self, query: str, limit: int) -> list[RawResult] | None:
        """Круг по индексерам, где у каждого свой бюджет; ``None`` - список не отдали.

        🔴 Зачем врозь, если у Prowlarr есть общий запрос. Он отвечает, только когда
        опрошены ВСЕ индексеры, и вернуть половину выдачи не умеет. Один залипший
        индексер поэтому стоил не своей задержки, а всего поиска: замерено на живом
        стенде - три индексера ответили за 0.1-0.6 с, четвёртый молчал, и `cast`
        отдал меню через 100.1 с (внутри Prowlarr это ``Failed to read complete http
        response`` ровно на сотой секунде - потолок его собственного HTTP-клиента).
        Второй круг по латинскому названию удваивал цену: человек ждал две минуты
        на живой франшизе. Врозь молчун стоит только своего бюджета, а находки
        остальных приезжают за их обычные 0.1-0.6 с.

        Параллель тут не «побольше потоков», а ровно та же, что была: общий запрос
        Prowlarr сам опрашивает индексеры разом. На хост по-прежнему приходится один
        запрос за круг - это важно для тех трекеров, что рассыпаются от нескольких
        одновременных.

        Выдачи склеиваются :func:`merge`, то есть по ``infoHash``: один и тот же торрент
        из двух индексеров - одна раздача, а не две. Общий запрос отдавал такие строки
        дважды (на живом стенде «матрица»: 190 строк против 179 склеенных).

        🔴 TC-118: круг возвращается по КВОРУМУ (:data:`QUORUM_INDEXERS`), а не по
        последнему ответившему. Раньше меню ждало ВСЕХ, и молчун жёг полный личный
        бюджет: на холодном старте тяжёлой картины (замер TC-108) это 47.8% всего
        времени пути, а по второму источнику (`cast log`) Nyaa.si замолчал после
        3-4 запросов и стоил ровно 20.1 с - при том, что в здоровых кругах отдавал
        по этим же запросам НОЛЬ строк. Опоздавший не выбрасывается: его поток живёт
        дальше, а выдачу забирает :meth:`late` - уже после того, как список показан.

        🔴 TC-229: анимешные индексеры (Nyaa и прочие, :func:`~torrcast.parse.anime_indexer`)
        - не всегда в круге. Nyaa молчит на явно не-аниме запросах (замер 09-08-2026:
        пусто в 79% запросов), а параллель по нему лимитирована - 2-4 одновременных,
        дальше 504 и health-бан Prowlarr на часы. Поэтому на не-аниме запросе
        (:func:`anime_query`) первый круг идёт без него, и лишь если пул вышел тощим
        (меньше :data:`_FALLBACK_POOL` раздач) - анимешные зовутся вторым кругом,
        фолбэком. Недоступный Nyaa ломает ровно свой круг: имя попадает в молчуны,
        находки остальных доезжают - как и у любого молчуна выше.

        🔴 TC-259: заблокированных Prowlarr'ом в круг не берём (:meth:`_blocked`). Спросить
        их всё равно нельзя - вместо выдачи придёт отказ всего поиска, - а места в круге и
        личного бюджета они стоят как живые. Взамен в них стучится :meth:`_heal`, и
        починившееся звено возвращается в каталог следующим же поиском.
        """
        known = self._known()
        if not known:
            return None
        self._session = self._session or self._new_session()
        blocked = self._blocked()
        self._heal(blocked)
        self.banned = tuple(name for num, name in known if num in blocked)
        if self.banned:
            known = tuple(pair for pair in known if pair[0] not in blocked)
        if not known:  # заблокированы все до одного - это отказ инфры, а не пустой поиск
            raise InfraError(
                "Prowlarr увёл в недоступные все индексеры "
                f"({', '.join(self.banned)}) - каталога сейчас нет"
            )
        counts: dict[str, int] = {}
        spent: dict[str, int] = {}
        lost: list[str] = []
        anime = [pair for pair in known if anime_indexer(pair[1])]
        main = [pair for pair in known if not anime_indexer(pair[1])]
        # Анимешные в основном круге - на похожем на аниме запросе; без них круг пуст
        # или они и есть весь список - тоже зовём сразу, фолбэку нечего добавить.
        whole = not main or not anime or anime_query(query)
        # 🔴 TC-228: первый круг идёт в свои личные бюджеты, а каждый следующий - в остаток
        # цели (:meth:`spare`), но не ниже пола (:attr:`cap_floor`). Первый круг это и есть
        # поиск, резать его нечем; а вот второй заход раньше платил хвост первого плюс
        # свой полный - и удваивал цену.
        cap = 0.0 if self._first else max(self.spare(), self.cap_floor)
        self._first = False
        got, why_lost = self._circle(
            known if whole else main, query, limit, counts, spent, lost, cap
        )
        # Фолбэк: пул без анимешных тощий - позвать и их. Пустая выдача ответивших
        # (got непуст, раздач ноль) - самый тощий пул из возможных.
        fallback = not whole and bool(got) and len(merge(*got)) < _FALLBACK_POOL
        if fallback:
            # Фолбэк - тоже второй круг, и цель он тратит наравне с добором.
            more, err = self._circle(
                anime, query, limit, counts, spent, lost, max(self.spare(), self.cap_floor)
            )
            got += more
            why_lost = why_lost or str(err or "")
        self.silent = tuple(lost)
        # Ровно ``limit`` строк - индексер отдал столько, сколько ему разрешили, и хвост
        # выдачи обрезан: у RuTor это его собственный потолок, повышением ``limit`` не
        # лечится. Опоздавшие сюда не попадают - их счёт неизвестен, а гадать нельзя.
        self.capped = tuple(name for name, rows in counts.items() if rows >= limit)
        waiting = [ask.name for ask in self._late]
        # Кворум не отдал ничего, и показывать пока нечего - вот тут опоздавшего и правда
        # стоит дождаться: спешить некуда, показывать всё равно нечего. Это ровно тот
        # случай, ради которого долив не выбрасывается, а живёт дальше.
        if not got and (rows := self.late(wait=_EXTRA_TIMEOUT)):
            got.append(rows)
        from torrcast import trace

        # Полный расклад круга в недельный след: кто сколько отдал, кто смолчал и сколько
        # миллисекунд каждый держал круг (поле ms - НАШ секундомер на месте вызова, а не
        # elapsedTime истории Prowlarr: та не считает провалившиеся и повторные попытки).
        # mark ниже заводится лишь на потерю (это фаза старта), а следу нужен весь круг.
        trace.emit(
            "search",
            "indexers",
            got=counts,
            silent=list(lost),
            banned=list(self.banned),
            ms=spent,
            fallback=fallback,
            late=waiting,
        )
        if self.banned:
            # Отдельной строкой от молчунов: молчун не ответил нам, а заблокированного мы
            # и не спрашивали - Prowlarr не дал. Смешать их значит спрятать причину, по
            # которой каталог урезан, за словом «молчит».
            mark("индексеры", заблокированы=list(self.banned))
        if lost:
            # Бюджет теперь у каждого свой (TC-226), и в фазе он назван поимённо: иначе
            # «молчит YTS, бюджет 20 с» врало бы про то, сколько круг на нём простоял.
            budgets = {name: indexer_budget(name) for name in lost}
            mark("индексеры", молчат=lost, бюджет=budgets)
        if not got:  # молчат все до одного - это не «ничего не нашлось», а инфра
            if lost and why_lost.startswith("Prowlarr: выбранные индексеры"):
                raise InfraError(f"индексеры не отвечают: {', '.join(lost)}")
            raise InfraError(why_lost)
        return merge(*got)

    def late(self, wait: float = 0.0) -> list[RawResult]:
        """Выдача опоздавших: круг ушёл по кворуму, а эти доехали уже потом (TC-118).

        🔴 Зовётся ОДИН раз и только там, где долив уже ничего не подменяет: список
        картин человек к этой секунде прочитал и ответил на него, и менять под курсором
        нечего. Что доехало - забирается, кто ещё в пути - остаётся ждать следующего
        вызова; ``wait`` больше нуля нужен ровно одному случаю: показывать нечего вовсе,
        и тогда опоздавший - единственное, что вообще может приехать.

        Не ждать по умолчанию - тоже решение: долив нужен там, где он бесплатен. Секунда
        ожидания здесь стоила бы ровно столько же, сколько стоила бы в круге, - а круг от
        неё и уходил.
        """
        rows: list[RawResult] = []
        rest: list[_Ask] = []
        for ask in self._late:
            if wait > 0:
                ask.done.wait(wait)
            if not ask.done.is_set():
                rest.append(ask)
                continue
            if ask.rows:
                rows += ask.rows
        self._late = rest
        return merge(rows) if rows else []

    def _circle(
        self,
        pairs: Sequence[tuple[int, str]],
        query: str,
        limit: int,
        counts: dict[str, int],
        spent: dict[str, int],
        lost: list[str],
        cap: float = 0.0,
    ) -> tuple[list[list[RawResult]], str]:
        """Один круг по индексерам: каждому свой запрос в свой бюджет, все разом.

        ``cap`` - потолок бюджета для этого круга: ноль на первом (он и есть поиск), а на
        каждом следующем - остаток цели (TC-228).

        🔴 Круг кончается, когда ответил КВОРУМ (:func:`quorum_indexer`), а не последний
        из спрошенных. Кто к этой секунде не успел - не потерян и не молчун: его поток
        живёт дальше, а выдача забирается :meth:`late` уже после показа списка (TC-118).
        Кворума в этом круге нет вовсе (фолбэк по анимешным, TC-229) - тогда ждём всех:
        иначе ждать было бы некого и круг возвращался бы пустым.

        Расклад (кто сколько отдал, кто смолчал, миллисекунды) складывает в переданные
        словари: кругов может быть два - основной и фолбэк на тощем пуле (TC-229), -
        а след и список молчунов у поиска общие. Возвращает выдачи и причину последней
        потери - она понадобится, если смолчат все.
        """
        asked = [self._spawn(query, limit, num, name, cap) for num, name in pairs]
        core = [ask for ask in asked if quorum_indexer(ask.name)] or asked
        for ask in core:
            ask.done.wait(ask.budget + _ASK_SLACK)
        got: list[list[RawResult]] = []
        why_lost = ""
        for ask in asked:
            if not ask.done.is_set():  # опоздал, но не потерян: доедет доливом
                self._late.append(ask)
                continue
            spent[ask.name] = ask.ms
            if ask.rows is None:
                lost.append(ask.name)
                why_lost = str(ask.err)
            else:
                got.append(ask.rows)
                counts[ask.name] = len(ask.rows)
        return got, why_lost

    def spare(self) -> float:
        """Сколько секунд цели (:data:`GOAL`) этот поиск ещё не потратил (TC-228).

        Часы идут от создания клиента, то есть от начала поиска, и считают ВСЁ, что
        случилось на пути: первый круг, справку на пути добора (:func:`~torrcast.facts.origin`,
        медиана 0.93 с там, где зовётся), разбор выдачи. Именно поэтому справка тут
        учтена честно - её не надо вычитать отдельно, она уже в прошедшем времени.
        """
        return max(0.0, GOAL - (time.monotonic() - self._began))

    def _spawn(self, query: str, limit: int, num: int, name: str, cap: float = 0.0) -> _Ask:
        """Пустить один индексер отдельным потоком и вернуть место под его ответ."""
        budget = indexer_budget(name)
        ask = _Ask(name=name, budget=min(budget, cap) if cap else budget)

        def work() -> None:
            ask.rows, ask.ms, ask.err = self._timed(query, limit, num, ask.budget)
            ask.done.set()

        threading.Thread(target=work, daemon=True, name=f"idx-{name}").start()
        return ask

    def _timed(
        self, query: str, limit: int, num: int, budget: float
    ) -> tuple[list[RawResult] | None, int, InfraError | None]:
        """Один индексер под нашим секундомером: выдача, миллисекунды и ошибка.

        Замер ровно вокруг вызова, чтобы хвост круга (кто и сколько держал) читался
        из следа без внешнего секундомера - и для молчунов тоже, поэтому ошибка
        возвращается значением, а не вылетает мимо замера.
        """
        began = time.monotonic()
        try:
            rows: list[RawResult] | None = self._one(query, limit, num, budget)
            return rows, int((time.monotonic() - began) * 1000), None
        except InfraError as exc:
            return None, int((time.monotonic() - began) * 1000), exc

    def _one(self, query: str, limit: int, indexer: int, budget: float) -> list[RawResult]:
        """Выдача одного индексера в его личный бюджет."""
        return from_json(self._get_json(self._url(query, limit, indexer), budget))

    def _blocked(self) -> dict[int, str]:
        """Кого Prowlarr увёл в недоступные: номер - когда обещает отпустить.

        🔴 TC-259. Включённый и доступный - разные вещи, а по списку индексеров
        (:meth:`_known`) их не различить: забаненный так и стоит ``enable: true``.
        Спросить его при этом нельзя - персональный запрос вернёт не выдачу, а отказ
        всего поиска («all selected indexers being unavailable»), то есть ровно то же,
        что вернул бы мёртвый Prowlarr. Отсюда и путаница в замерах: индексер числился
        мёртвым, хотя мёртв был не он, а наше право его спрашивать.

        Отказ этой страницы - не отказ поиска: не прочитали статус, значит идём кругом
        как раньше, вслепую. Хуже, чем было, от этого не станет.
        """
        try:
            payload = self._get_json(
                f"{self.base_url}{_STATUS_PATH}?apikey={quote(self.apikey)}", _LIST_TIMEOUT
            )
        except InfraError:
            return {}
        if not isinstance(payload, list):
            return {}
        return {
            int(item["indexerId"]): str(item.get("mostRecentFailure") or "")
            for item in payload
            if isinstance(item, dict) and str(item.get("indexerId", "")).isdigit()
        }

    def _heal(self, blocked: dict[int, str]) -> None:
        """Постучаться в заблокированные индексеры - вдруг источник уже вернулся.

        🔴 TC-272. Prowlarr снимает бан по своим часам, а не по здоровью источника, и
        каталог возвращается не когда звено починилось, а когда истечёт отсрочка (замер:
        канал пропал на 12 с - каталог был урезан 59.2 с ПОСЛЕ его возврата; на хронике
        отсрочка дорастает до часа). Ручки «снять бан» у Prowlarr нет
        (``DELETE /api/v1/indexerstatus`` отвечает 405), но есть :data:`_TEST_PATH`: он
        ходит в источник по-настоящему, и УСПЕХ гасит отсрочку - тот же замер с лечением
        дал 10.6 с вместо 59.2. Честность тут держится сама собой: бан снимает не наша
        просьба, а ответ источника; мёртвый источник так и останется мёртвым.

        Круга это не держит: стучимся отдельным потоком, как и опоздавшие (TC-118), а
        плодами пользуется уже следующий поиск. Ждать смысла нет - выдача заблокированного
        в этот круг всё равно не попадёт.
        """
        rested = tuple(num for num, failed in blocked.items() if _rested(failed))
        if not rested:
            return
        threading.Thread(target=self._probe, args=(rested,), daemon=True, name="idx-heal").start()

    def _probe(self, nums: tuple[int, ...]) -> None:
        """Стук в заблокированные - строго по одному, друг за другом.

        Параллель тут запрещена нарочно: лишние одновременные запросы к одному трекеру
        и есть та причина, по которой Prowlarr раздаёт баны (Nyaa отвечает на них 504).
        Лечить бан способом, которым он ставится, - худшее, что можно придумать.
        """
        import requests

        session = self._session or self._new_session()
        for num in nums:
            with contextlib.suppress(requests.RequestException, InfraError, ValueError):
                body = self._get_json(
                    f"{self.base_url}{_INDEXERS_PATH}/{num}?apikey={quote(self.apikey)}",
                    _LIST_TIMEOUT,
                )
                session.post(
                    f"{self.base_url}{_TEST_PATH}?apikey={quote(self.apikey)}",
                    json=body,
                    timeout=_EXTRA_TIMEOUT,
                )

    def _known(self) -> tuple[tuple[int, str], ...]:
        """Включённые индексеры (номер, имя); пусто - спрашивать придётся общим запросом."""
        if self._indexers is None:
            try:
                payload = self._get_json(
                    f"{self.base_url}{_INDEXERS_PATH}?apikey={quote(self.apikey)}", _LIST_TIMEOUT
                )
            except InfraError:
                return ()
            if not isinstance(payload, list):
                return ()
            self._indexers = tuple(
                (int(i["id"]), str(i.get("name") or i["id"]))
                for i in payload
                if isinstance(i, dict) and i.get("enable") and str(i.get("id", "")).isdigit()
            )
        return self._indexers

    def _new_session(self) -> requests.Session:
        """Сессия, поднятая ДО потоков: ленивая её сборка внутри них - гонка."""
        import requests

        return requests.Session()

    def _get_json(self, url: str, timeout: float | None = None) -> Any:
        import requests

        if self._session is None:
            self._session = self._new_session()
        try:
            response = self._session.get(url, timeout=timeout or self.timeout)
            response.raise_for_status()
            return response.json()
        except requests.RequestException as exc:
            body = str(getattr(exc.response, "text", "") or "").casefold()
            if "all selected indexers being unavailable" in body:
                raise _IndexersUnavailableError(
                    "Prowlarr: выбранные индексеры не отвечают"
                ) from exc
            raise InfraError(f"Prowlarr не отвечает ({self.base_url}): {why(exc)}") from exc
        except ValueError as exc:
            raise InfraError("Prowlarr вернул не JSON") from exc


class _IndexersUnavailableError(InfraError):
    """Prowlarr жив, но спрятал отказ всех выбранных индексеров за HTTP 400."""


def merge(*batches: list[RawResult]) -> list[RawResult]:
    """Склеить выдачи нескольких запросов, оставив каждую раздачу один раз.

    Один и тот же торрент приходит и по русскому названию, и по латинскому, а
    ещё и из разных индексеров - тождество тут ровно одно, ``infoHash``. Порядок
    сохраняем: раздачи первого запроса идут первыми.

    ⚠️ Сколькими строками раздача приехала - не пустяк, а :attr:`RawResult.copies`. Пока
    индексеры спрашивались общим запросом, зеркальный торрент считался столько раз,
    сколько индексеров его несут, и все замеры «сколько нашлось» сделаны в этих строках.
    Склейка их обнулять не вправе: иначе один и тот же каталог выглядит то полным, то
    тощим - смотря как опрошены индексеры. Считаем по РАЗНЫМ индексерам, а не по строкам:
    добор вторым именем приносит те же раздачи от тех же индексеров, и складывать круги
    значило бы удваивать каталог на ровном месте.

    🔴 Строки об ОДНОЙ раздаче у разных индексеров расходятся, и оставить строку того,
    кто ответил первым, значило бы отдать выдачу на волю сети. Расхождение массовое:
    на сырых пулах (99 запросов) из 661 раздачи, приехавшей больше чем одной строкой,
    сиды разошлись у 625, имена - у 490. Разрывы не косметические: «Дюна: Пророчество»
    приезжает то на 2 сидах, то на 26, «Матрица: Воскрешение» - 8 против 19, а сиды
    стоят высоко в отборе, и мёртвая на вид раздача уходит под все живые. Поэтому
    склейка выбирает поля сама (:func:`_fold`), а не берёт первую попавшуюся строку.

    🔴 TC-257: ИМЕНА принёсших индексеров переезжают в :attr:`RawResult.indexers` целиком.
    Раньше их считали и выбрасывали, оставляя счётчик ``copies``, - а вместе с ними
    пропадал и жанр: аниме-индексер в группе значит «аниме», кто бы ни выиграл имя.
    """
    rows: dict[str, list[RawResult]] = {}
    sources: dict[str, set[str]] = {}
    names: dict[str, set[str]] = {}
    carried: dict[str, int] = {}
    for batch in batches:
        for item in batch:
            key = item.info_hash.lower()
            rows.setdefault(key, []).append(item)
            sources.setdefault(key, set()).add(item.indexer)
            # Счёт copies идёт по СТРОКАМ выдачи (sources) и остаётся прежним, а имена
            # копятся отдельно: склейка склеенного не вправе ни терять их, ни удваивать счёт.
            names.setdefault(key, set()).update(item.indexers or (item.indexer,))
            carried[key] = max(carried.get(key, 1), item.copies)
    return [
        replace(
            _fold(group),
            copies=max(len(sources[key]), carried[key]),
            indexers=tuple(sorted(name for name in names[key] if name)),
        )
        for key, group in rows.items()
    ]


def _fold(rows: list[RawResult]) -> RawResult:
    """Строки одной раздачи - в одну, не глядя, кто ответил первым.

    Рой у раздачи ОДИН: один ``infoHash`` - один и тот же торрент у всех индексеров.
    Расхождение в сидах - это разное время скрейпа, а не разные раздачи, поэтому берём
    максимум: свежая цифра честнее протухшей, а сиды в выдаче и так лишь подсказка -
    живость проверяется по привезённым байтам, а не по обещанию индексера.

    Имя - по большинству, тем же правилом, что у канона картины
    (:func:`~torrcast.parse.by_majority`): чаще встретившееся, при равенстве короче и
    дальше по алфавиту.

    Размер - тем же большинством (TC-293): он идёт в прикидку битрейта напрямую
    (:func:`~torrcast.cli.bitrate_of`), и брать его у строки, выигравшей ИМЯ, значило
    судить вес по тому, кто первым стоит в алфавите индексеров. Расходятся размеры на
    округлении: на 100 сохранённых выдачах 98% пар разошлись не больше чем на 0.35%, а
    очередь, ступень тяжести и дефолт не сменились ни у одной картины - поэтому ничья
    разводится в БОЛЬШУЮ сторону: промах в сторону тяжести дёшев (потолок битрейта и
    сплошной перекод для того и стоят), а заниженный размер пропустил бы неподъёмную
    раздачу мимо ворот. Нулевой размер - не голос, а «индексер не сказал»: в счёт он
    не идёт. Индексер остаётся у строки, чьё имя победило, - имя и индексер описывают
    один ответ каталога, а размер и сиды сводятся по всем строкам раздачи.

    ⚠️ Поэтому ``indexer`` тут отвечает на вопрос «чья это строка», а не «откуда раздача».
    Спрашивать его про жанр нельзя: аниме-индексер стоит в алфавите позже общего
    (Nyaa.si против Knaben), и на замере 100 сохранённых выдач аниме-признак так пропадал
    у 170 раздач на 6 аниме-запросах из 19. Кто принёс раздачу на самом деле - в
    :attr:`RawResult.indexers`, их складывает :func:`merge`.
    """
    title = by_majority(Counter(row.title for row in rows))
    sizes = Counter(row.size for row in rows if row.size)
    size = max(sizes, key=lambda s: (sizes[s], s)) if sizes else 0
    return replace(
        min((row for row in rows if row.title == title), key=lambda row: (row.indexer, row.size)),
        size=size,
        seeders=max(row.seeders for row in rows),
    )


def to_releases(results: list[RawResult]) -> list[Release]:
    """Разобрать сырую выдачу в релизы, перенеся размер, сиды и magnet."""
    return [
        replace(
            parse_release_name(item.title),
            size=item.size,
            seeders=item.seeders,
            magnet=item.magnet,
            indexer=item.indexer,
            indexers=item.indexers,
            copies=item.copies,
        )
        for item in results
    ]


def _int(value: Any) -> int:
    try:
        return max(0, int(value))
    except (TypeError, ValueError):
        return 0
