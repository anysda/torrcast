@runtime_checkable
class _Revivable(Protocol):
    """Приёмник, чей погасший показ можно поднять заново (:class:`_Revival`).

    Отдельно от :class:`Receiver` намеренно: воскрешать имеет смысл только тот приёмник,
    у которого есть собственное терпение и который его тратит. Терпение mock моделирует
    нарочно и по замерам живого ТВ (:attr:`torrcast.cast.MockReceiver.PATIENCE`) - иначе
    целый класс аварий «источник моргнул» уходил бы из-под сухих прогонов вовсе.
    """

    def replay(self, at: float) -> bool: ...


@runtime_checkable
class _Steerable(Protocol):
    """Приёмник, которым можно управлять как с пульта (:data:`CTL_ENV`)."""

    def seek(self, pos: float) -> None: ...

    def pause(self) -> None: ...

    def resume(self) -> None: ...


def _ctl(receiver: Receiver) -> None:
    """Исполнить команду диагностического пульта, если она положена (:data:`CTL_ENV`).

    Файл съедается до исполнения: команда одноразовая, и повторить её на следующем опросе
    нельзя даже при осечке приёмника — иначе одна опечатка мотала бы фильм вечно.
    """
    name = os.environ.get(CTL_ENV)
    if not name or not isinstance(receiver, _Steerable):
        return
    path = Path(name)
    try:
        line = path.read_text("utf-8").strip()
    except OSError:
        return
    path.unlink(missing_ok=True)
    if not line:
        return
    word, _, rest = line.partition(" ")
    print(f"пульт: {line}", flush=True)
    with contextlib.suppress(Exception):
        if word == "seek":
            receiver.seek(float(rest))
        elif word == "pause":
            receiver.pause()
        elif word == "play":
            receiver.resume()


def liveliness(plan: _Plan) -> int:
    """Насколько картина живая — сиды самой живой раздачи, которой картина **может играть**.

    Мерок было три, и две отброшены на живой выдаче:

    * сумма сидов по всем релизам — вытягивает картину числом раздач, а не их
      качеством: у «Матрицы» 1999 сорок релизов против одиннадцати у «Воскрешения»,
      и сумма выбрала бы первую даже с мёртвыми DVD-рипами в хвосте;
    * сиды :attr:`~torrcast.parse.Picture.best_release` — не знают ни про потолок
      битрейта, ни про образы дисков, ни про старьё, а это и есть отбор.

    Осталось честное: сиды лучшей раздачи из тех, что годны по :func:`is_candidate`.
    Негодные в счёт не идут вовсе — ни 41-гигабайтный 4K-ремукс «Тачек» 2006 на 49.9
    Мбит/с (выше потолка декодера), ни образы дисков, ни старьё, которое отсеет
    :func:`is_dated`: играть ими картина не может, и вес им не положен.

    Считалось это раньше по ОДНОМУ релизу — верху :func:`rank_releases`, — и мерка
    получалась случайной: очередь сортируется не только сидами, и наверху у картины
    стоит то, что лучше СМОТРЕТЬ, а не то, что живее. У «Мальтийского сокола» 1941
    года на верху очереди 5 сидов при 97 у годного соседа ниже, и картина с 22
    раздачами весила меньше однораздачной тёзки 1931 года на 16 сидов - дефолт
    садился на неё. Считать по одному верху было честно, пока очередь и обрывалась
    на трёх номерах; с тех пор как :meth:`_Plan.candidates` отдаёт все годные
    раздачи, показ дойдёт до любой из них, и «чем играть» — это они все.

    Ворота спрашиваются те же, что у самого плана (:attr:`_Plan.loose`), и это не
    мелочь: пока они спрашивались строго, аниме с молчаливыми именами весило ноль
    целиком — у «наруто» дефолтом меню вместо сериала на 91 сид вставал полнометражный
    «Ниндзя в стране снега» на два.

    🔴 Последняя надежда (:attr:`_Plan.last_resort`) сюда НЕ спрашивается, и это
    осознанно. Вес картины решает, какой пункт меню предложить человеку, а HEVC — не
    предпочтение, а единственный оставшийся носитель ВНУТРИ уже выбранной картины.
    Замер на кэше выдачи «синий экзорцист s1e1»: стоило дать HEVC вес, и дефолт меню
    переезжал с «Blue Exorcist» (1080p H.264, 5 сидов) на одноимённую картину с
    ``HEVC``, то есть ровно то предпочтение, которого быть не должно.
    """
    return max(
        (
            release.seeders
            for release in plan.ranked
            if is_candidate(
                release,
                plan.runtime,
                plan.warn_mbit,
                plan.loose,
                plan.hard_mbit,
                copy_hevc=plan.copy_hevc,
            )
        ),
        default=0,
    )


def fitness(plan: _Plan, dubbed: bool = False) -> int:
    """Сиды лучшей раздачи, которой картину и правда стоит смотреть; 0 - такой нет.

    От :func:`liveliness` отличается двумя условиями, и оба взяты у самого отбора, а не
    придуманы заново:

    * раздача ЖИВА - сидов не меньше :data:`ALIVE_SEEDERS`. Живость картины считается
      этим же порогом (:func:`alive_numbers`), и второго значения у слова тут нет;
    * раздача НЕ СТАРЬЁ - :func:`is_dated`. Это тот самый приговор, который отбор выносит
      каждой строке: XviD и DVDRip, названная ступень ниже :data:`HD_HEIGHT`, молчаливое
      имя при SD-битрейте.

    Нужна она там, где вопрос не «кто живее», а «состоится ли вечер вообще»: пул, в
    котором ни одной такой раздачи нет, годным не бывает (:func:`unfit_pool`), а картина
    без единой такой раздачи - тупик, и дефолт меню на неё не садится, когда рядом стоит
    живая тёзка (:func:`playable`).

    ⚠️ Порядок отбора это НЕ смягчает и не ужесточает: годность релиза по-прежнему решает
    :func:`is_candidate`, а старьё по-прежнему играется, когда другого нет вовсе. Здесь
    считается только вес картины в двух вопросах выше.

    ``dubbed`` - считать только раздачи, чьё ИМЯ обещает русскую дорожку
    (:attr:`~torrcast.parse.Release.dubbed`). Тем же словом «стоит смотреть» отвечают на
    третий вопрос - «состоится ли вечер ПО-РУССКИ» (:func:`voiceless_pool`): русская дорожка
    входит в «включилось» (TC-178), и пул без единой играбельной раздачи с нею - такой же
    тупик, как пул без единой играбельной вовсе.
    """
    return max(
        (
            release.seeders
            for release in plan.ranked
            if release.seeders >= ALIVE_SEEDERS
            and (release.dubbed or not dubbed)
            and is_candidate(
                release,
                plan.runtime,
                plan.warn_mbit,
                plan.loose,
                plan.hard_mbit,
                copy_hevc=plan.copy_hevc,
            )
            and not is_dated(release, plan.runtime)
        ),
        default=0,
    )


def liveliest(plans: list[_Plan]) -> int:
    """Номер (с единицы) самой живой картины — он же дефолт меню и первый на прогрев.

    Список остаётся хронологическим, меняется только цифра в скобках:
    «моана» печатает четыре картины и предлагает вторую, а не немую документалку
    1926 года. Равный вес — берём раннюю: при ничьей хронология и есть ответ.
    """
    return max(range(1, len(plans) + 1), key=lambda n: (liveliness(plans[n - 1]), -n))


def first_alive(plans: list[_Plan]) -> int:
    """Номер (с единицы) картины по умолчанию: **первая по хронологии, чей рой жив**.

    Смотреть франшизу начинают с начала, а не с самой обсиженной части: «тачки» — это
    просьба про «Тачки» 2006, даже когда сидов больше у «Тачек 3». Прежний дефолт
    (:func:`liveliest`) на этом и ошибался — печатал `[4]`.

    Мёртвые части при этом пропускаются, иначе Enter снова упирался бы в пустой рой:
    у «моаны» первой в хронологии стоит «Моана: романтика золотого века» 1926 года,
    немая документалка одним VHS-рипом на 5 сидов.

    Живость - **свой рой картины** (:data:`ALIVE_SEEDERS`), а не доля от самой живой
    части франшизы. Доля тут была прямой ошибкой, и стоила она классики: одна свежая
    часть с большим роем объявляла мёртвой всю остальную франшизу. Замер по живой
    выдаче: «мумия» - свежая часть 2026 года набирает сотни сидов, «Мумия» 1999 года
    при живых десятках не дотягивала до четверти от неё и пропускалась, и дефолтом
    десять прогонов из десяти вставала картина, которой человек не называл. То же
    у «хищника», «голодных игр», «дюны», «безумного макса» и «джуманджи».

    * «тачки» - 66 / 0 / 1 / 121 сид: первая часть жива своим роем и выигрывает,
      а мимо проходят «Мультачки» (одни DVD-образы, играть нечем) и «Тачки 2»,
      у которых годным верхом остался 0.4-гигабайтный HDRip «фильм о фильме» на 1 сид;
    * «моана» - 0 / 222 / 140: документалка 1926 года пропускается (годного нет вовсе),
      дефолтом становится «Моана» 2016.

    Тип, названный запросом, весит больше одноимённого соседа другого типа
    (:func:`asked_kind`): «хорошая жена s1e1» — это просьба про сериал, и дефолт
    считается среди сериалов, даже если полнометражная тёзка живее.

    Живого нет вовсе — отдаём самую живую из картин названного типа: выбирать всё
    равно не из чего, но цифра в скобках обязана на что-то указывать.
    """
    return _first_alive(plans, asked_kind(plans))


def _first_alive(plans: list[_Plan], numbers: list[int]) -> int:
    """:func:`first_alive` среди перечисленных номеров - остальные картины не в счёт."""
    if not numbers:
        return liveliest(plans)
    if alive := alive_numbers(plans, numbers):
        return backed(plans, playable(plans, alive))[0]
    return max(numbers, key=lambda n: (liveliness(plans[n - 1]), -n))


def alive_numbers(plans: list[_Plan], numbers: list[int]) -> list[int]:
    """Номера картин, у которых есть чем играть; пусто - живых нет вовсе.

    Порог - свой рой картины (:data:`ALIVE_SEEDERS`), см. :func:`first_alive`. Соседи по
    франшизе в этот вопрос не входят вовсе: «есть чем играть» - свойство самой картины,
    и чужой рой его ни подтвердить, ни отменить не может.
    """
    return [n for n in numbers if liveliness(plans[n - 1]) >= ALIVE_SEEDERS]


def playable(plans: list[_Plan], alive: list[int]) -> list[int]:
    """🔴 TC-246. Тупиковая картина уступает дефолт своей ТЁЗКЕ, которой есть чем играть.

    Тупик - это картина, у которой после отбора не осталось ни одной раздачи, годной,
    живой и не старья разом (:func:`fitness`). Порог живости она проходит честно, и
    :func:`backed` за неё тоже не берётся, когда тёзка другого типа: замер каталога -
    «Призраки» приезжают 190 строками, из них 58 HD, а дефолтом вставала одноимённая
    картина с одной SD-раздачей и без нужного сезона. То же у «Ангела» (194 строки, 68
    HD), «Убийства» (189 / 91) и «Родины» (128 / 24).

    🔴 Уступают друг другу только ТЁЗКИ - картины, которые каталог подписал ОДНИМ И ТЕМ
    ЖЕ именем. Это ограждение, а не оттенок. Соседей по франшизе правило не трогает
    вовсе: дефолт франшизы - первая живая часть, и «Тачки», у которых в каталоге одни
    DVD-образы, обязаны остаться первым пунктом, а не уступить третьей части за её
    1080p. Тёзки же - это одна и та же вещь под одним именем, хронология между ними
    ничего не значит, и человек, назвавший имя, просил ту из них, которую можно смотреть.

    ⚠️ Ранжир по качеству это не смягчает: старьё как игралось последним, так и играется,
    и картина, у которой ВСЕ тёзки тупиковые, дефолта не теряет - уступать некому.

    ⚠️ TC-192 не отменяется. «Нелюбовь» - фильм 2017 года одной живой 1080p-раздачей
    против сериала-тёзки: у фильма годная раздача есть, тупиком он не был и дефолт
    остаётся за ним.
    """
    fit = {n: fitness(plans[n - 1]) for n in alive}
    if not any(fit.values()):
        return alive
    return [
        n
        for n in alive
        if fit[n] or not any(m != n and fit[m] and _same_name(plans, m, n) for m in alive)
    ]


def _same_name(plans: list[_Plan], first: int, second: int) -> bool:
    """Одним ли именем каталог подписал две картины меню."""
    return plans[first - 1].picture.title.casefold() == plans[second - 1].picture.title.casefold()


def backed(plans: list[_Plan], alive: list[int]) -> list[int]:
    """Из живых - те, кому есть чем играть: за картиной больше одной раздачи.

    Порог живости считает сиды, и по сидам однораздачная картина обходит соседку с
    очередью на законных основаниях: у «Мальтийского сокола» 1931 года ровно одна
    раздача на 16 сид, а у «Мальтийского сокола» 1941 года лучшая ГОДНАЯ раздача из
    двадцати двух держит 28 - доля честная, порог пройден, дефолт садился на 1931 год.
    То же у «Люпена»: «Rupan sansei» 2014 года одной раздачей на 3 сида обходил «Замок
    Калиостро» с десятью раздачами.

    Но «прошла порог» и «есть чем играть» - разные вещи. Сиды в выдаче это обещание
    индексера, а не факт: раздача, которая не отдаёт ни метаданных, ни потока, числится
    в выдаче ровно так же бодро (:func:`silent_swarm`). За картиной с очередью стоит
    двенадцать таких обещаний и показ переберёт их все; за однораздачной - одно, и
    осечка на нём заканчивает вечер. Ставить дефолт на монетку, когда рядом стоит
    очередь, - это и есть «формально живая».

    Ранжировать картины числом раздач эта ступень НЕ начинает, и это важно: на том уже
    обжигались - до-вожак по числу раздач выдавал сиквел вместо основной картины.
    Порядок остаётся хронологическим, а однораздачная картина уступает не всякой очереди,
    а только той, которая её же и живее. Первая часть на 100 сид одной раздачей остаётся
    дефолтом при сиквеле с двумя раздачами на 90 - она сама и есть самое живое, что
    нашлось, и уступать ей нечему. А «Мальтийский сокол» 1931 года на 16 сид уступает
    тёзке 1941 года, у которой и раздач двадцать две, и лучшая годная живее.

    Живых с очередью нет вовсе - список остаётся как был: выбирать не из чего, и
    молчаливо превращать «живую» картину в «мёртвую» не за что.

    🔴 TC-192. Уступают друг другу картины ОДНОГО типа, и это ограждение, а не оттенок.
    Глубина очереди у сериала говорит о сериале и ровно ничего - о полнометражной тёзке:
    у сериала раздача на каждый сезон, у фильма она одна на всё кино, и мерить их одной
    линейкой значит объявлять фильм «формально живым» за то, что он фильм. Замер:
    «Нелюбовь» - фильм Звягинцева 2017 года одной раздачей на 40 сид против сериала
    «НЕлюбовь [S01]» двумя раздачами на 120, и дефолтом молча вставал сериал. Тип запрос
    называет вслух ровно одним способом (:func:`asked_kind`), и там, где он промолчал,
    подменять кино сериалом за него нельзя.
    """
    deep = [n for n in alive if len(plans[n - 1].ranked) > 1]
    if not deep:
        return alive
    return [n for n in alive if n in deep or liveliness(plans[n - 1]) > _rival(plans, deep, n)]


def _rival(plans: list[_Plan], deep: list[int], number: int) -> int:
    """Самая живая очередь СВОЕГО типа - её и обязана перебить однораздачная картина.
    Очередей своего типа нет вовсе - уступать нечему, и порог равен нулю.
    """
    kind = plans[number - 1].picture.kind
    return max(
        (liveliness(plans[n - 1]) for n in deep if plans[n - 1].picture.kind == kind), default=0
    )


def asked_kind(plans: list[_Plan]) -> list[int]:
    """Номера (с единицы) картин того типа, который назвал сам запрос.

    Тип назван вслух ровно одним способом: запрос спросил СЕРИЮ (``s1e1``). Тогда
    одноимённая полнометражка — не «вариант поживее», а другое кино, и дефолт обязан
    считаться среди сериалов. Замер по живой выдаче:

    * «хорошая жена s1e1» — дефолтом вставал ФИЛЬМ 1987 года (3 раздачи, ни одной
      живой) при сериале 2015 года на 30 раздач и 18 сид;
    * «синий экзорцист s1e1» — дефолтом вставала полнометражка 2012 года;
    * «великий из бродячих псов s1e1» — дефолтом вставал чиби-спин-офф, приехавший
      отдельными сериями и потому опознанный как полный метр.

    Сериалов в выдаче нет вовсе — считаем как считали: гейт тут не судья тому, чего
    он не видел, и пустой ответ вместо картины был бы хуже неточного типа.

    Серии запрос не называл — тип не назван, и все картины равны: «мальтийский сокол»
    одинаково может оказаться и фильмом, и сериалом, и гадать за человека нечего.
    """
    if not any(plan.asked_series for plan in plans):
        return list(range(1, len(plans) + 1))
    series = [n for n, plan in enumerate(plans, start=1) if plan.picture.kind == "tv"]
    return series or list(range(1, len(plans) + 1))


def default_note(plans: list[_Plan], asked: str = "") -> str:
    """🔴 TC-198. Одна честная строка про смену картины: «спросили X - беру Y, потому что Z».

    Молчаливая подмена КАРТИНЫ - худший вид брака, а дефолт франшизы подменяет её
    буднично: пропускает мёртвую первую часть (:func:`alive_numbers`), уходит с
    однораздачной (:func:`backed`), считается среди сериалов (:func:`asked_kind`) - и
    всё это без единого слова. В замере каталога так молча прошли десять спорных
    запросов из четырнадцати: «мумия» показывала не ту «Мумию», «дюна» - не ту «Дюну»,
    «медведь s2e7» - не тот «Медведь». Ещё у четырёх строка была, но про другое: у
    «гарри поттера» человек читал про оригинальное имя и добор сезона, пока менялась
    ЧАСТЬ франшизы.

    Строка одна, и печатается она **последней перед стартом** (:func:`_cmd_play`), а не
    среди фаз поиска: фазы уезжают вверх экрана и читаются как ход работы, а это -
    решение, которое человек обязан унести с собой.

    Пусто - взято ровно то, что назвали, и говорить не о чем. Три случая молчания
    осознанные:

    * картина одна - выбора не было вовсе;
    * человек ответил на меню сам - подмены нет, есть его выбор (сравнение с
      :func:`first_alive` делает вызывающий);
    * дефолт сел на картину, чьё имя человек и назвал, а тёзок по году у неё нет:
      «голодные игры» → «Голодные игры» (2012) - это ровно запрошенное, и строка тут
      была бы шумом. Ровно это и чинит TC-196: после него три случая из четырнадцати
      перестают быть сменой вообще.

    ``asked`` - слова человека; без них строка та же, только без головы «спросили X».
    """
    numbers = asked_kind(plans)
    picked = _first_alive(plans, numbers)
    plain = _first_alive(plans, list(range(1, len(plans) + 1)))
    head = f"спросили «{asked}» - беру" if asked else "беру"
    mine = _named(plans[picked - 1].picture)
    if len(numbers) != len(plans) and picked != plain:
        other = _named(plans[plain - 1].picture)
        return f"{head} «{mine}», а не «{other}»: спросили серию, а это другой тип"
    if passed := [n for n in numbers if n < picked]:
        other = _named(plans[passed[0] - 1].picture)
        return f"{head} «{mine}», а не «{other}»: {_passed_why(plans, passed[0], numbers)}"
    if twins := [n for n in numbers if n != picked and _namesake(plans, n, picked)]:
        others = ", ".join(f"«{_named(plans[n - 1].picture)}»" for n in twins)
        return f"{head} «{mine}»: под этим именем есть ещё {others} - другая картина"
    return ""


def swap_note(plans: list[_Plan], picked: _Plan, asked: str = "") -> str:
    """Честная строка про смену картины для ТОГО, что реально пошло на показ.

    От :func:`default_note` отличается одним вопросом: а дефолт ли это. Человек, который
    ответил на меню номером, ничего не подменял - он выбрал, и говорить ему «беру не то,
    что вы назвали» было бы враньём. Поэтому строка живёт ровно там, где картину выбрали
    за него: выбранный пункт совпал с дефолтом (:func:`first_alive`).

    Картина одна - меню не задавалось вовсе, выбора не было, и строки нет.
    """
    if not _is_default(plans, picked):
        return ""
    return default_note(plans, asked)


def _is_default(plans: list[_Plan], picked: _Plan) -> bool:
    """Встал ли выбранный план дефолтом (:func:`first_alive`), а не выбором человека.

    Человек, ответивший на меню номером, ничего не подменял - он выбрал. Строки про
    подмену (:func:`swap_note`, :func:`year_note`) живут ровно там, где картину выбрали
    за него. Картина одна - меню не задавалось вовсе, выбора не было.

    План после меню пересобирается на настоящей длительности (:func:`_timed`) и это уже
    ДРУГОЙ объект - сверка идёт по картине, идентичность тут врёт.
    """
    if len(plans) < 2:
        return False
    number = next((n for n, plan in enumerate(plans, start=1) if plan.picture is picked.picture), 0)
    return number == first_alive(plans)


def year_note(picked: _Plan, about: Origin, asked: str = "") -> str:
    """🔴 TC-199/TC-200. Честная строка, когда год дефолтной картины расходится со справкой.

    Год картины склеивается из ИМЕНИ раздачи, а имя врёт: «Оно» уезжает раздачей 2014
    года, «Медведь» - 2026-го, «Брат 2» - «Брат 2025». Гейт подмены сверял этот год со
    справкой только ВОКРУГ ДОБОРА (:func:`_second_language`), а у картины, вставшей
    дефолтом, год не сверялся нигде - и человек молча получал не тот фильм.

    Сверка та же, что у добора: независимое слово справки (:func:`~torrcast.facts.origin`,
    год выдачи ей НЕ подсказан) против года картины, с тем же допуском ±1 год (год
    производства против года проката) и той же поблажкой ремейку - совпал оригинал, значит
    та же вещь, хоть годы и врозь.

    Право у строки ровно одно - сказать вслух; ни блокировать показ, ни менять год картины
    она не вправе (TC-199/TC-200 - про честность, а не про отказ). Молчим в трёх случаях,
    и все три - ограждения:

    * справка пуста или неуверенна (``about.year is None``) - латинописанное аниме, нет
      статьи, сеть легла, год в статье назван неоднозначно. Сверять нечем, и год из имени
      остаётся единственным источником: подменять его молчанием справки нельзя;
    * год картины неизвестен (``picture.year is None``) - опровергать нечего;
    * годы сошлись (±1) или это ремейк того же оригинала - решение верное, строка была бы
      шумом.
    """
    picture = picked.picture
    if about.year is None or picture.year is None:
        return ""
    if about.title and picture.original and slugify(picture.original) == slugify(about.title):
        return ""
    if abs(picture.year - about.year) <= 1:
        return ""
    head = f"спросили «{asked}» - " if asked else ""
    return (
        f"{head}беру «{picture.title}» {picture.year} года, "
        f"но справка знает эту картину как {about.year}"
    )


def namesake_note(picked: _Plan, about: Origin) -> str:
    """🔴 TC-371. Честная строка: под этим именем и годом картин ДВЕ, а играет одна.

    Двусмысленность тут не наша: именем «Девять» и годом 2009 в русском прокате подписаны
    мюзикл ``Nine`` и мультфильм ``9``. Отбор выбирает картину по имени и году - обоими
    признаками они совпадают, - и в одну кучку их сводит сам каталог: больше в раздачах не
    сказано ничего. Развести такую пару разбору нечем, и это ровно тот случай, когда
    молчать нельзя: человек просил имя, получил одну из двух, а какую - решил вес кучки.

    Сказать об этом может только независимый источник, и он уже отвечает: справка знает
    обе картины и приносит их одним ответом (:func:`~torrcast.facts.namesake`). Строка
    называет вторую картину так, как её подписала справка, - по этому имени человек
    отличит одну от другой и спросит точнее.

    Молчим, когда сверять нечего или не о чем:

    * тёзки того же года справка не нашла - строка была бы выдумкой;
    * год картины разошёлся со справкой (допуск ±1, как у :func:`year_note`): паспорт
      приехал про ДРУГУЮ картину, и её тёзка к выбранной отношения не имеет. Про сам
      разъезд годов человек читает своей строкой.
    """
    picture = picked.picture
    if not about.namesake or about.year is None or picture.year is None:
        return ""
    if abs(picture.year - about.year) > 1:
        return ""
    return (
        f"«{picture.title}» ({picture.year}): под этим именем и годом картин две - "
        f"справка знает ещё «{about.namesake}», развести их по имени и году нечем"
    )


class _Passport:
    """Фоновый паспорт дефолтной картины: :func:`_passport` пускает, :meth:`get` забирает.

    Справка (:func:`~torrcast.facts.origin`) - независимое слово для гейта года выбранной
    картины (:func:`year_note`). Нужна она лишь к последней строке перед стартом, поэтому
    едет фоном, ровно в те секунды, что уходят на меню и прогрев. :meth:`get` дожидается
    её сам добор бюджетом ограничил, так что путь до меню она не держит.
    """

    def __init__(self, picture: Picture | None) -> None:
        self._picture = picture
        self._box: list[Origin] = []
        self._thread: threading.Thread | None = None

    def start(self) -> None:
        if self._picture is None:  # меню не было - и сверять нечего
            return
        self._thread = threading.Thread(target=self._work, daemon=True)
        self._thread.start()

    def _work(self) -> None:
        # Тип картины известен из выдачи (:attr:`Picture.kind`), и его подсказать надо:
        # у сериала и фильма разные статьи. Год выдачи - нет: см. :func:`year_note`.
        with contextlib.suppress(Exception):
            self._box.append(origin(self._picture.title, series=self._picture.kind == "tv"))  # type: ignore[union-attr]

    def get(self) -> Origin:
        thread = self._thread
        if thread is not None:
            thread.join()
        return self._box[0] if self._box else Origin()


def _passport(plans: list[_Plan]) -> _Passport:
    """Пустить фоном добор паспорта верхней картины меню (:func:`year_note`).

    Только на меню из нескольких картин: одна картина - выбора не было, сверять нечего, и
    лишнего похода к справке на счастливом однокартинном пути не случается.
    """
    default = plans[0].picture if len(plans) >= 2 else None
    holder = _Passport(default)
    holder.start()
    return holder


def _passed_why(plans: list[_Plan], number: int, numbers: list[int]) -> str:
    """Почему картина, стоящая раньше по хронологии, дефолтом не стала.

    Причины ровно четыре, и человеку они разные: «играть нечем» (годной раздачи нет ни
    одной - образы дисков, 4K сверх потолка декодера, старьё), «рой мёртв» (годная
    раздача есть, но сидов у неё столько, что это подгрузы), «живого HD нет»
    (:func:`playable`: у тёзки того же имени он есть, а тут одно старьё) и «всего одна
    раздача» (:func:`backed`: одно обещание индексера против очереди у соседки).
    """
    life = liveliness(plans[number - 1])
    if life <= 0:
        return "играть у неё нечем - ни одной годной раздачи"
    if number not in alive_numbers(plans, numbers):
        return f"рой у неё мёртв - сидов {life}"
    if not fitness(plans[number - 1]):
        return "живого HD у неё нет - одно старьё"
    return f"у неё всего одна раздача, а тут их {len(plans[number - 1].ranked)}"


def part_one_swap(plans: list[_Plan], asked: str) -> str:
    """Честная строка вместо дефолта меню, когда дефолт подменил бы часть франшизы.

    🔴 TC-373. Запрос «тачки» - это просьба про «Тачки» 2006 года, и пока первая часть
    играет, дефолт стоит на ней. А вот когда её нет в выдаче или играть ей нечем, дефолт
    по правилу «первая живая часть» (:func:`first_alive`) перескакивал на «Тачки 2» - и
    Enter включал другое кино той же франшизы, которого не просили. Строка про это была
    (:func:`default_note`), но показ всё равно начинался сам.

    Теперь в этом случае дефолта нет вовсе: строка называет, что случилось с первой
    частью, список того, что есть, уже на экране над ней, и номер части называет сам
    человек. Пустой ответ - дефолт честен, и случаев тут три:

    * номер назван явно («тачки 2») - спрошенное уже отобрано до меню
      (:func:`~torrcast.parse.pick_franchise`), и дефолт - ровно оно;
    * франшиза без номерованных частей («Моана», «Мумия») - там первая ЖИВАЯ картина и
      есть ответ на запрос, решение «дефолт франшизы - первая живая часть» не тронуто;
    * дефолт встал на саму первую часть или на её ТЁЗКУ по году («Человек-невидимка» 2020
      вместо 1933): тёзка - та же вещь под тем же именем, послабление для неё остаётся.

    Запрос, назвавший франшизу оригинальным именем («cars»), читается так же, как русский:
    имя первой части сверяется в обоих языках.

    Линейкой считаются только картины: номерованная книжная серия («Homo Ludens 1» рядом
    со «Сталкером») франшизу не образует. И номер внутри одной картины («Дары Смерти:
    Часть I») - это глава, а не часть франшизы: если «первая часть» линейки младше другой
    картины меню, перед нами семья однофамильцев, и там дефолт честен.
    """
    from torrcast.parse import _numbered_line

    name, index = split_franchise_index(asked)
    if index is not None or len(plans) < 2:
        return ""
    key = slugify(name)
    pictures = [plan.picture for plan in plans]
    films = [p for p in pictures if p.kind != "other"]
    if not key or not any(p.part is not None for p in films):
        return ""
    line = _numbered_line(films)[0]
    first = line[0] if line and line[0].part in (None, 1) else None
    if first is not None and any(p.year and first.year and p.year < first.year for p in films):
        return ""
    names = {p.franchise for p in pictures}
    # Оригинальные имена зовут ту же франшизу («cars» - это «тачки»), а корень ключа
    # (:func:`franchise_key`) режет номер части: «Cars 2» подписано корнем «cars».
    names |= {franchise_key(p.original) for p in pictures if p.original}
    if key not in names:  # запрос назвал не франшизу, а картину - подменять тут нечего
        return ""
    if first is None:
        return (
            f"«{name}»: первой части в выдаче нет, и вместо неё другую часть сам не "
            f"включаю - вот что есть, назови номер"
        )
    default = plans[first_alive(plans) - 1].picture
    if default is first or default.title.casefold() == first.title.casefold():
        return ""
    number = next(n for n, plan in enumerate(plans, start=1) if plan.picture is first)
    why = _passed_why(plans, number, asked_kind(plans))
    return (
        f"«{_named(first)}» не играет: {why}; вместо неё другую часть сам не включаю - "
        f"вот что есть, назови номер"
    )


def understudy(plans: list[_Plan], failed: _Plan) -> _Plan | None:
    """🔴 TC-203. Живая ТЁЗКА выбранной картины - та, которой показ доиграет вместо неё.

    У выбранной картины кончились все раздачи, а рядом в меню стоит одноимённая живая -
    и человек читал отказ. Замер каталога: 6 отказов из 115, и самый наглядный -
    «Человек-невидимка»: дефолт садился на 1933 год (формально живой, играть нечем) при
    живой картине 2020 года в том же меню. Отказ там был честен про картину и неправдой
    про вечер: кино с этим именем в каталоге есть, и оно играет.

    Тёзка - это ровно ТО ЖЕ НАЗВАНИЕ (:func:`_namesake`), а не соседка по франшизе.
    Разница принципиальная: «Тачки 2» вместо «Тачек» - это другое кино, и уходить туда
    самому нельзя ни при каком отказе (о таких соседях говорит подсказка
    :func:`kin_line`, и она остаётся подсказкой). А «Человек-невидимка» 1933 и 2020 -
    это одна вещь, снятая дважды: имя человек назвал верно, промахнулись мы годом.

    Тип тоже обязан совпасть: полнометражка и одноимённый сериал - разные вещи, и
    подменять одно другим молча нельзя ровно по той же причине, по какой этого не делает
    дефолт (:func:`backed`).

    Круг ровно один: берём самую живую из тёзок. Лишний заход стоит человеку секунд, и
    платить их за перебор всего меню незачем - если и она не сыграет, честный отказ
    честнее долгого перебора.
    """
    number = next((n for n, plan in enumerate(plans, start=1) if plan.picture is failed.picture), 0)
    if number == 0:
        return None
    twins = [
        n
        for n in alive_numbers(plans, list(range(1, len(plans) + 1)))
        if n != number
        and _namesake(plans, n, number)
        and plans[n - 1].picture.kind == failed.picture.kind
    ]
    if not twins:
        return None
    return plans[max(twins, key=lambda n: liveliness(plans[n - 1])) - 1]


def _played(
    bench: _Bench,
    plans: list[_Plan],
    plan: _Plan,
    args: Args,
    progress: Progress,
    facts: Facts | None,
    config: Config,
    profile: Profile,
) -> tuple[_Plan, _Prep]:
    """Отбор релиза выбранной картины, а нечем играть - её живой тёзки (:func:`understudy`).

    🔴 TC-203. Отдельной функцией это стоит затем, что уход к тёзке - смена КАРТИНЫ, и
    смена эта обязана быть проверяемой отдельно от всего пути показа: печатается строка,
    пишется след, план подменяется целиком (вместе с длительностью из справки и порядком
    прогретого). Возвращается пара «чем в итоге играем» - вызывающему нужны обе половины.

    Кругов ровно два: выбранная картина и одна тёзка. Дальше - честный отказ: перебирать
    меню целиком дороже, чем сказать правду, а цель пути - десять секунд до картинки.
    """
    try:
        return plan, bench.resolve(plan, args, progress)
    except NotFoundError as refusal:
        spare = understudy(plans, plan)
        if spare is None:
            raise
        why = _why_refused(refusal)
        print(understudy_note(plan, spare, why))
        trace.emit(
            "select",
            "switch",
            **{"from": plan.picture.title, "to": spare.picture.title, "why": why},
        )
    # Тёзке достаётся ровно то же, что досталось бы ей после меню: своя длительность из
    # справки и свой порядок прогретого (:func:`_timed`, :meth:`_Bench.reorder`).
    spare = bench.reorder(spare, _timed(spare, facts, args, config, profile))
    bench.keep_plan(spare)
    return spare, bench.resolve(spare, args, progress)


def understudy_note(failed: _Plan, spare: _Plan, why: str) -> str:
    """Одна строка про уход к тёзке (:func:`understudy`) - печатается ВСЕГДА.

    Уход к тёзке - это смена картины, то есть ровно то, о чём молчать нельзя
    (:func:`default_note`). Строка называет обе стороны с годами и причину, по которой
    первая не сыграла: без причины это выглядело бы как каприз показа, а с ней человек
    видит, что выбор был сделан за него не от лени.
    """
    return (
        f"«{_named(failed.picture)}» - играть нечем ({why}); "
        f"ухожу к «{_named(spare.picture)}»: раздач {len(spare.ranked)}"
    )


def _why_refused(refusal: NotFoundError) -> str:
    """Голова отказа - без списка приговоров и без подсказки про соседей.

    В отказе есть всё: перечень осуждённых релизов, совет выбрать руками, строка
    :func:`kin_line`. В строке ухода к тёзке нужна ровно причина, потому что совет
    «выбери руками» после автоматического ухода уже неправда.
    """
    head = str(refusal).splitlines()[0]
    return _cut(head.split(":")[0].strip(), 60)


def _namesake(plans: list[_Plan], number: int, picked: int) -> bool:
    """Тёзка по году: то же название, другая картина.

    Одноимённые части - самая тихая из подмен: в меню они отличаются только годом в
    скобках, и человек, назвавший «мумия», получает «Мумию» - вопрос лишь, которую из
    трёх. Сказать вслух обязаны обе стороны выбора.
    """
    mine, other = plans[picked - 1].picture, plans[number - 1].picture
    return mine.title.casefold() == other.title.casefold() and mine.year != other.year


def warm_order(plans: list[_Plan]) -> list[_Plan]:
    """Кого греть под меню: сверху вниз, в том же порядке, который видит человек."""
    return plans


def _pick_plan(
    plans: list[_Plan], facts: Facts | None = None, pick: int | None = None, asked: str = ""
) -> _Plan:
    """Вопрос «какой фильм франшизы?»; один вариант — без вопроса.

    Дефолт — верхняя картина меню. Если играть её нечем, отбор называет причину и не
    подставляет соседнюю картину.

    🔴 TC-373. Ограждение того же дефолта: перескочив через спрошенную часть франшизы
    (её нет в выдаче или играть ей нечем), он вставал на ДРУГУЮ часть - и Enter включал
    «Тачки 2» вместо просимых «Тачек». Такому дефолту не бывать (:func:`part_one_swap`):
    строка говорит, что случилось с первой частью, список остаётся на экране, и номер
    называет сам человек.

    К каждой картине печатается справка (:mod:`torrcast.facts`) — рейтинг, хронометраж и
    фраза о том, что это за кино. Её тут не ждут: что успело приехать фоном, то и
    печатается, остальное просто не печатается.

    ``pick`` - номер пункта, названный флагом ``--pick N``: вопрос тогда не задаётся
    вовсе, и терминал не нужен. Это не молчаливая подмена, а названный человеком выбор -
    тот же номер, что стоит у пункта меню на экране. Номер вне списка - честная ошибка,
    а не тихий первый пункт.

    Без терминала (ssh без pty, cron, чужой скрипт) спрашивать некого, и общее правило —
    не висеть, а брать дефолт. Здесь мы по-прежнему отказываемся — и «дефолт стал умнее»
    ничего не меняет. У озвучки дефолт считается правилами, у «Продолжить?» это
    «продолжить», а тут любой дефолт означает **другой фильм**: разница между «Моаной»
    2016 и «Моаной 2» — это не оттенок, а не тот вечер. Цифра в скобках имеет смысл
    ровно потому, что рядом напечатан список и человек видит, от чего отказывается;
    без терминала видеть его некому. Поэтому отказываемся вслух и подсказываем, как
    назвать картину точно.
    """
    if pick is not None and not 1 <= pick <= len(plans):
        raise NotFoundError(f"подходит картин: {len(plans)}, номера {pick} нет")
    print(menu_lines(plans, facts))
    if pick is not None:  # номер назвал сам человек - ни вопроса, ни подмены
        return plans[pick - 1]
    if len(plans) == 1:
        return plans[0]
    default = 1
    if not console.stdin_is_tty():
        raise NotFoundError(
            f"подходит картин: {len(plans)}, а терминала нет - вслепую не выбираю; "
            f"назови картину точно (например «{plans[default - 1].picture.title}») "
            f"или её номер (--pick N), либо запусти cast в терминале"
        )
    if note := part_one_swap(plans, asked):
        # Дефолт подменил бы спрошенную часть другой - тогда его нет вовсе: строка
        # называет, что с первой частью, список на экране, номер зовёт человек.
        print(note)
        return plans[ask("Что смотрим?", len(plans), default=None) - 1]
    print(default_line(plans, default))
    return plans[ask("Что смотрим?", len(plans), default=default) - 1]


def default_line(plans: list[_Plan], default: int) -> str:
    """Что случится по Enter - словами, последней строкой перед вопросом.

    🔴 TC-204. Порядок меню хронологический, и это решение: франшизу читают так, как её
    снимали. А дефолт - первая ЖИВАЯ картина (:func:`first_alive`), и он с первой строкой
    не совпадает почти в половине меню: в замере 45 многокартинных меню из 82, в 13 из них
    дефолт стоял пятым и дальше, а у «ван пис s1e1» - строкой 33 из 35. Одной цифры в
    ``[33]`` человеку мало: он видит номер, а не название.

    Строка стоит именно ПЕРЕД вопросом, а не шапкой над списком. Терминал после длинного
    вывода показывает его ХВОСТ: шапка тридцатипятистрочного меню уезжает за экран вместе
    с ним, и «дефолт виден без прокрутки» она не даёт. Хвост же виден всегда - ровно
    там, где человек и держит глаза, отвечая на вопрос.

    Список при этом не переупорядочивается: показ дефолта - это показ, а не порядок.
    """
    return f"Enter - «{_named(plans[default - 1].picture)}», пункт {default} из {len(plans)}"


#: Отступ описания в меню: ровно под название, за номером с точкой.
_BLURB_INDENT = " " * 5


def _named(picture: Picture, aside: bool = False) -> str:
    """Название с годом; ``aside`` - картина стоит после нумерованной линейки франшизы.

    Подпись объясняет, почему пункт уехал вниз: номера части у неё нет, и в линейку по
    номерам ей вставать не с чем (:func:`~torrcast.parse.outside_numbering`).
    """
    marks = ", сериал" if picture.kind == "tv" else ""
    if aside:
        marks += ", без номера части"
    return f"{picture.title} ({picture.year or '?'}{marks})"


def menu_lines(plans: list[_Plan], facts: Facts | None = None, width: int = 0) -> str:
    """Список картин со справкой: номер, название с годом, рейтинг и хронометраж — в одну
    строку, описание — под ней, с отступом под номер.

    Формат такой, а не таблицей, ровно из-за узкого терминала: название бывает длинным
    («Тачки: Мультачки. Байки Мэтра»), а описание — тем более, и колонки разъехались бы
    на первой же франшизе. Отдельная строка вместо колонки ещё и читается сверху вниз:
    глаз идёт по номерам, а подробности — под ними.

    Описание переносится по словам и занимает столько строк, сколько нужно фразе (в
    восьмидесяти колонках это две-три). Раньше оно резалось по ширине терминала, и в
    меню оставался огрызок «американский компьютерно-анимационный…»: ни жанра, ни года,
    ни возможности дочитать. Место экономить тут не на чем — вопрос задаётся один раз.

    Справки нет (не приехала, сети нет, картины нет в Википедии) — печатается ровно та
    строка, что печаталась раньше, без пустых разделителей и без «не нашёл».
    """
    columns = width or shutil.get_terminal_size((80, 24)).columns
    aside = outside_numbering([plan.picture for plan in plans])
    rows: list[str] = []
    for number, plan in enumerate(plans, start=1):
        picture = plan.picture
        fact = facts.get(picture.title, picture.year) if facts else Fact()
        head = " · ".join(
            x for x in (_named(picture, picture.key in aside), fact.rating, fact.runtime) if x
        )
        rows.append(f"  {number}. {head}")
        if fact.about:
            rows += textwrap.wrap(
                shorten(fact.about),
                width=max(40, columns - 1),
                initial_indent=_BLURB_INDENT,
                subsequent_indent=_BLURB_INDENT,
                # Дефис - часть слова: «компьютерно-анимационный» рвать по нему незачем.
                break_on_hyphens=False,
            )
    return "\n".join(rows)


def warned(
    release: Release,
    runtime: float,
    warn_mbit: float,
    recode_at: float = 0.0,
    hard_mbit: float = 0.0,
) -> str:
    """Почему релиз не дефолт: HEVC ресивер может не потянуть, жирный битрейт — тоже.

    Словами, а не значками: ``⚠`` из вывода убран целиком — в терминале он не нёс
    смысла и разъезжался по ширине.

    ⚠️ «Не берём» про HEVC осталось правдой ровно там, где перекодирование выключено:
    иначе такой релиз играет, перекодированный целиком, и таблица обязана говорить то же,
    что и показ (:func:`_encode_all`).
    """
    peak = bitrate_of(release, runtime)
    marks: list[str] = []
    if release.is_hevc:
        marks += ["перекодирую целиком" if recode_at > 0 else "не берём"]
    if peak is None:  # вес неизвестен (TC-344) - пометок по весу нет, врать нечем
        return ", ".join(marks)
    if peak > warn_mbit:
        marks += ["тяжёлый"]
    elif hard_mbit > 0 and peak > hard_mbit:
        # Тяжелее прежнего потолка, но играбелен: уедет перекодированным целиком.
        if "перекодирую целиком" not in marks:
            marks += ["перекодирую целиком"]
    elif recode_at > 0 and peak > recode_at:
        # Не брак, а честное предупреждение - тяжёлые куски поедут перекодированными.
        marks += ["перекодируем"]
    return ", ".join(marks)


def last_hope_note(plan: _Plan, release: Release) -> str:
    """Та самая честная строка про последнюю надежду; пусто — путь обычный.

    Печатается ровно тогда, когда показ берёт релиз, попавший в очередь ТОЛЬКО потому,
    что живого кандидата с нужной серией нет вовсе (:func:`hevc_hope`). Человек обязан
    услышать не только «перекодирую целиком» (:func:`torrcast.stream.recode_note` скажет
    это следующей строкой), но и ПОЧЕМУ выбран дорогой путь: иначе «Гинтама» на HEVC и
    «Гинтама» на честном 1080p выглядят с экрана одинаково, а стоят разного.

    Строка одна, без числа: считать тут нечего — это не размен качества, а
    единственный оставшийся носитель серии.
    """
    if not (plan.last_resort and hevc_hope(release, plan.last_resort)):
        return ""
    what = f"серии {plan.want}" if plan.want else "картины"
    return f"живой раздачи {what} без HEVC нет - беру HEVC последней надеждой"



