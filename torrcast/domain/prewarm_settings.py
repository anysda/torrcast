"""Сколько картин и раздач греется впрок, пока человек отвечает на вопросы."""

#: Сколько картин франшизы греем под меню: топ-2-3 релиза уходят в TorrServer фоном,
#: пока человек отвечает на вопросы.
PREWARM = 3

#: Сколько ЗАПАСНЫХ релизов греется под меню сверх картин - у той картины, в которую
#: попадёт Enter (:func:`warm_order`). Прогрев под меню тратится на РАЗНЫЕ картины: человек
#: может ответить не дефолтом, и меню обязано вести в живое. Но внутри выбранной картины
#: до сих пор грелся ровно один релиз, а запасной поднимался только тогда, когда верх уже
#: забракован (:meth:`_Bench.resolve`) - то есть на бракованном верхе человек платил полную
#: цену подъёма второй раздачи: 6-7 с чистого ожидания DHT и ffprobe в фазе отбора.
#: Единица тут не «побольше параллели», а перенос по времени: этот же запасной всё равно
#: поднимался секундой позже, в resolve, - меняется только то, когда он начинает греться.
#: Пик одновременных раздач от этого не растёт (в отборе он и был PREWARM + 1), а вот пауза
#: под меню, которая иначе простаивает, уходит в дело.
PREWARM_SPARE = 1

#: Сколько раздач с ОБЕЩАННОЙ русской дорожкой греется под меню сверх запасного - одна,
#: ближайшая по очереди (:meth:`_Bench.spare`). 🔴 TC-309. Стоит такая раздача в очереди
#: где угодно - на 4-9 месте, - и подъём её с нуля это метаданные роя (3-6 с) плюс чтение
#: дорожек, то есть ровно те секунды, которых в отборе и не хватает.
#:
#: 🔴 TC-492. Спрашивают её теперь не отдельной проверкой, а самой очередью: гейт бракует
#: и прямое «нет», и молчание паспорта (:func:`voice_unproven`), поэтому отбор идёт дальше
#: и до обещавшей русскую раздачи доходит сам. Тёплой она нужна тем более: греется она
#: ровно тогда, когда очередь и правда может уйти дальше верха - молчаливое имя есть у
#: кого-то из первых :data:`MAX_TRIES` кандидатов, а обещавший русскую сосед в очереди
#: вообще есть.
PREWARM_DUB = 1

#: **Жёсткий потолок одновременных раздач, которые держим МЫ** (:meth:`_Bench._room`).
#:
#: Число не про вежливость к службе, а про её живучесть. Замер на стенде: TorrServer
#: падает по таймеру раз в 15 минут (паника в форке библиотеки), и срывается тем
#: вероятнее, чем больше раздач и чем активнее у них просят куски: с ОДНОЙ раздачей тик
#: проходит спокойно, со 120 раздачами и живым чтением - паника на первом же тике.
#: Прогрев по своей природе греет лишнее (:data:`PREWARM` картин плюс
#: :data:`PREWARM_SPARE`, а где верх промолчал про звук - ещё и :data:`PREWARM_DUB`), и
#: без потолка это лишнее копилось: очередь перебора поднимала
#: по раздаче за попытку, честная проверка (:meth:`_Bench._honest`) - ещё до
#: :data:`MAX_TRIES` сверху, а убиралось всё разом только перед стартом показа.
#:
#: Пять - это ровно пик прогрева под меню (:data:`PREWARM` + :data:`PREWARM_SPARE` +
#: :data:`PREWARM_DUB`), то есть замеренного выигрыша потолок не трогает: и топ-3
#: картины, и запасной релиз, и обещавший русскую сосед греются как грелись. Он режет то,
#: что живёт ПОСЛЕ того, как перестало быть нужным.
MAX_LIVE = PREWARM + PREWARM_SPARE + PREWARM_DUB
