"""Чем экземпляр продукта отличается от соседнего на том же узле.

Узел стенда несёт десяток экземпляров сразу (свой порт, своё состояние, свой конфиг на
каждый), и до TC-1137 все они делили одно имя юнита показа и один каталог сегментов:
запуск показа в одном экземпляре гасил идущий показ другого. Разводит их отпечаток пути
состояния - той самой ручки, которая и так уводит за собой кэш справки и недельный
след. Экземпляр с боевым путём состояния на узле один, и метка его пуста: имена и места
у него остаются прежними, как до разводки.
"""

from __future__ import annotations

import hashlib
import os
from typing import Final

#: Переменная, которой запуск называет свой файл состояния; её же читает
#: :func:`torrcast.adapters.filesystem.state.state_path.state_path`.
STATE_ENV: Final = "TORRCAST_STATE"

#: Боевое место состояния строкой: экземпляр с ним - хозяин узла, суффикс ему не нужен.
DEFAULT_STATE: Final = "/var/lib/torrcast/state.json"


def instance_slug() -> str:
    """Короткая метка экземпляра: пустая у боевого, отпечаток пути состояния у прочих.

    Отпечаток берётся от строки пути как она есть: оба процесса (запускающий и юнит)
    получают её одной и той же через :data:`torrcast.domain.unit_naming._PASS_ENV`, и
    согласие имён держится на этом, а не на нормализации пути.
    """
    where = os.environ.get(STATE_ENV) or DEFAULT_STATE
    if where == DEFAULT_STATE:
        return ""
    return hashlib.sha1(where.encode("utf-8")).hexdigest()[:8]
