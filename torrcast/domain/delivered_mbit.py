"""Сколько Мбит/с уезжает на ТВ: видеодорожка плюс наш звук плюс оверхед контейнера.

Зовут это и паспорт файла (:class:`torrcast.domain.media.Media`), и отбор релиза, и
прикидка бюджета прогрева: цифра одна на всех, и жить ей положено в одном месте.
"""

from __future__ import annotations

#: Сколько Мбит/с занимает наша звуковая дорожка в том, что уезжает на ТВ.
#:
#: ⚠️ Дорожка ИСХОДНИКА тут ни при чём, сколько бы она ни весила: показ всегда
#: перекодирует звук в AAC (см. :func:`ffmpeg_pack_command`), поэтому в сегмент уезжает
#: ровно :data:`AUDIO_MBIT`, а не 1.5 Мбит/с DTS «Тачек 3». Считать «видео + выбранная
#: дорожка» было бы враньём в полтора мегабита.
AUDIO_MBIT = 0.192
#: Во сколько раз mpegts тяжелее того, что в него упаковано: заголовки 4 байта на 188,
#: PAT/PMT/PCR и набивка на границах PES. Замер на восьми сегментах-копиях
#: «Моаны 2» подряд: поправка «контейнер → ТВ» сходилась к 4.10...4.26 Мбит/с при
#: контейнере 19.16 и видеодорожке 14.33 - то есть уезжало (14.33 + 0.19) × 1.03.
TS_OVERHEAD = 1.03


def delivered_mbit(video_bps: float) -> float:
    """Сколько Мбит/с уедет на ТВ в среднем; ``0`` - паспорт про видео ничего не сказал.

    Ноль тут не «ничего не уедет», а «считать не по чему»: молчащий паспорт (mp4 без
    тегов, кривой ремукс) отличается от честного нуля тем, что решения по нему не
    принимают вовсе.
    """
    if video_bps <= 0:
        return 0.0
    return (video_bps / 1000000.0 + AUDIO_MBIT) * TS_OVERHEAD
