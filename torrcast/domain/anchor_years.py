"""Правило anchor years; используют модели и фасады разбора имён."""

from __future__ import annotations

from torrcast.domain.picture import Picture
from torrcast.domain.slugify import slugify


def anchor_years(pictures: list[Picture]) -> None:
    """Привязать бесстрочные картины к году тех, чей разобранный оригинал зовёт их по имени.

    Латинская раздача года не несёт, поэтому её картина в каталоге бесстрочная, а порядок
    меню ставит бесстрочных в хвост - позади датированных соседей по франшизе. Дефолт
    («первая живая по хронологии») садился тогда на датированный спин-офф: добор по «Code
    Geass» привозил живой первый сезон «Code Geass: Lelouch of the Rebellion» (163 сида),
    а по Enter играл «Code Geass: Dakkan no Rozé» 2024 года - спрошенный сезон стоял в
    том же меню, но хвостом.

    Разводит их разобранное каталогом поле, а не догадка по именам: русская половина
    («Код Гиас: Восставший Лелуш», 2006) несёт ``original`` - ровную подпись латинской
    картины, а спин-офф оригиналом не назван никем. Такой подписи верим как свидетельству
    каталога: бесстрочная картина, чьё имя совпало с чужим разобранным оригиналом, - это
    языковая половина той самой картины, и год у неё есть - он просто написан у соседки.

    Стражи против ложной привязки:

    * спорные имена не привязываются вовсе: одно имя оригиналом назвали картины РАЗНЫХ
      лет - которой из них верить, каталог не говорит, и хвост честнее догадки;
    * бесстрочная картина со СВОИМ оригиналом не привязывается: она уже названа двумя
      именами, и класс дефекта - не про неё, а про половину, у которой имени на втором
      языке нет вовсе;
    * привязка - только порядок (:attr:`Picture.sort_year`): сама картина года не
      получает, её ключ и её место в склейке не меняются;
    * в один год с датированной половиной привязанная встаёт СРАЗУ ЗА ней, не впереди
      (третий член ключа хронологии - ``year is None``): живая датированная несёт русский
      голос и потому берётся первой, а привязка работает ровно там, где датированная
      мертва, - и не трогает порядок там, где та жива.
    """
    claimed: dict[str, set[int]] = {}
    for picture in pictures:
        if picture.original and picture.year is not None:
            claimed.setdefault(slugify(picture.original), set()).add(picture.year)
    for picture in pictures:
        if picture.year is not None or picture.original is not None:
            continue
        years = claimed.get(slugify(picture.title), set())
        if len(years) == 1:
            picture.anchor = next(iter(years))


__all__ = ["anchor_years"]
