"""Разобранный JSON под своим именем: то, и только то, что кладёт писатель.

Зовут его все, кто читает чужой ответ или свою же запись с диска: разбор справки,
выжимка следа, сборка настроек и состояния. Ровно этот набор значений умеет
записать :mod:`json`, и ровно его обещают писатели наших файлов и запросов.
"""

from __future__ import annotations

from typing import TypeAlias

#: Значение разобранного JSON. Псевдоним рекурсивный намеренно: вложенный объект и
#: вложенный список - такой же JSON, и обрывать описание на первом уровне значило бы
#: снова сказать «дальше что угодно».
JsonValue: TypeAlias = str | int | float | bool | list["JsonValue"] | dict[str, "JsonValue"] | None
