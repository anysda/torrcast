"""Сколько показ ждёт карту опорных кадров и первый кусок, прежде чем сдаться.

Оба срока складываются в бюджет старта (:data:`torrcast.usecases.start_budget.
START_BUDGET`), поэтому живут не внутри упаковщика, а там, где их видно обоим.
"""

from typing import Final

#: Сколько ждём чужого снятия карты опорных кадров, прежде чем снимать самим.
KEYS_WAIT: Final = 40.0

#: Потолок пробного прогона в один кадр (:func:`pack_start`). Обычная цена - 0.5-1.7 с,
#: но на холодном рое это чтение нового места, и оно упирается в раздачу. Число
#: вынесено сюда не ради красоты: из него и из соседних потолков складывается бюджет
#: старта юнита, который ждёт CLI (``torrcast.cli.START_BUDGET``).
PILOT_TIMEOUT: Final = 60.0

#: Потолок сверки входа копией (:func:`torrcast.adapters.stream_pack.opens_clean.opens_clean`):
#: один кадр с закладки. Живьём 0.12-0.44 с на прогретом, 0.7-1.25 с на холодных местах и
#: 3.17 с на самом холодном - первом чтении раздачи; 5 с накрывают и его. Сверка не главная:
#: не успела - ``None``, и показ идёт прежним путём, а не ждёт до потолка пробного прогона.
ENTRY_TIMEOUT: Final = 5.0
