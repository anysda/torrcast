"""Правило подгруза: указатель приёмника против часов, и ничего кроме этих двух чисел.

Держат его строки экрана (:mod:`torrcast.usecases.revive_playback._screen`), а зовут -
на каждом опросе показа.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Final

from torrcast.domain.freeze import Freeze

#: Просадка за один опрос, начиная с которой это подгруз, а не дрожь округления.
LAG_TICK: Final = 1.0

#: Пока просадка больше этого, подгруз ЕЩЁ идёт: замирание длиннее опроса ложится на два
#: опроса подряд, и хвост его короче :data:`LAG_TICK`. Без хвоста подгруз считался бы
#: короче, чем зритель простоял.
LAG_TAIL: Final = 0.3

#: Скачок указателя вперёд, показом не бывающий: нудж сторожа, перемотка, повтор LOAD.
#: Такой опрос про ход показа не говорит ничего, и считать по нему нечего.
LAG_JUMP: Final = 3.0

#: Круг опроса, длиннее которого мерить нечем: это опоздали МЫ, а не встала картинка.
#:
#: 🔴 Замер на живом показе: круг стоит 2.01 с в половине случаев и 2.04 с в девяти
#: десятых, но шесть кругов из 133 растянулись до 2.7-7.3 с. На семисекундном круге
#: приёмник отдал позицию, отставшую от своей же на пять секунд, а следующий круг
#: догнал её скачком - и правило без этого порога записало пять секунд потери туда,
#: где зритель не потерял ничего: догоняющий скачок уходил в :data:`LAG_JUMP`, а
#: приписанный долг оставался. Настоящая остановка картинки наш круг не удлиняет.
LAG_LATE: Final = 2.5


@dataclass(slots=True)
class PointerLag:
    """Сколько плёнки потерял зритель: ход указателя против хода часов.

    🔴 Подгруз тут - НЕ слово приёмника. Приставка Android TV рапортует ``PLAYING`` всё
    время, пока картинка стоит: на сериале 21.4 Мбит/с указатель замирал семь раз, а
    ``BUFFERING`` приёмник не назвал НИ РАЗУ - счётчик ребуферов честно насчитал ноль
    подгрузов при семи. Слову приёмника верить в этом вопросе нечем, а ход указателя он
    отдаёт честно: за две секунды по часам фильм обязан проехать две секунды, и сколько
    не проехал - то зритель и простоял.

    🔴 Круг, на котором указатель не сдвинулся ВОВСЕ, остановкой картинки сам по себе не
    является. Приёмник обновляет своё место не тогда, когда его спросили, а своей сеткой,
    и на круг, куда свежий снимок не пришёлся, он отдаёт ровно то же число. Указателем
    эти два случая не различить: он неподвижен и там и там. Различает их то, СКОЛЬКО он
    простоял против того, каким шагом потом сдвинулся, - шаг указателя и есть шаг сетки
    приёмника. Простой короче этого шага объясняется несвежим снимком; простой длиннее
    объяснить уже нечем, там стояла картинка, и он идёт в счёт целиком.

    ⚠️ Шаг опроса - величина НАША, и правило не имеет права от неё зависеть: в окне
    старта он 0.5 с, в теле показа 2 с. Замер на ленте двухчасового показа при сетке
    приёмника 2.03 с: разложенная на ровный шаг 2.0 с, она давала 179 подгрузов там, где
    их было четыре, и накопленный счёт +415 с при дефиците 16.35 с - каждый круг без
    свежего снимка брался за подгруз.

    :attr:`total` - сумма потерь по подгрузам: в счёт идёт ровно то, что правило назвало
    подгрузом, и ничего сверх того.

    🔴 Знаковой суммой по ВСЕМ опросам это число копить нельзя, хотя дефицит показа она
    вроде бы и есть. Круг, на котором сетка не сдвинулась, отдаёт своё отставание
    следующему кругу скачком вперёд. Отставание такого круга правило выбрасывает
    (:data:`LAG_LATE`), а догоняющий скачок короче :data:`LAG_JUMP` остаётся принятым - и
    пара выходит однобокой. Замер на двухчасовом показе: 333 выброшенных круга унесли
    +439 с отставания, а 442 принятых круга с опережением указателя дали -299 с, и
    знаковая сумма уверяла, что зритель ПРИОБРЁЛ 190 с плёнки - при дефиците в 16 с по
    часам самого приёмника. Опережение указателя плёнки зрителю не возвращает.

    ⚠️ Чего это правило не видит: замирание короче просадки в :data:`LAG_TICK` за один
    опрос; замирание короче шага сетки приёмника, когда мы спрашиваем чаще неё; и всё,
    что случилось на круге длиннее :data:`LAG_LATE`, - такой круг не мерит ничего.
    Незамеченное не входит и в :attr:`total`: на двухчасовом показе четыре подгруза дали
    16.8 с против 16.35 с дефицита по часам приёмника, и вся разница - как раз
    незамеченное. Мера тут - потерянная плёнка, а не число остановок.
    """

    #: Место последнего СВЕЖЕГО снимка приёмника; ``-1`` - опроса ещё не было.
    pos: float = -1.0
    #: Монотонный момент опроса, на котором этот снимок пришёл.
    at: float = 0.0
    #: Монотонный момент прошлого опроса, каким бы тот ни был.
    seen: float = 0.0
    #: Сколько указатель простоял, не получив свежего снимка.
    flat: float = 0.0
    #: Был ли в идущем отрезке круг, которым мерить нечего (:data:`LAG_LATE`).
    late: bool = False
    #: Плёнка, потерянная в идущем подгрузе.
    lost: float = 0.0
    #: Позиция фильма, на которой идущий подгруз начался; ``-1`` - подгруза нет.
    began: float = -1.0
    #: Монотонный момент начала идущего подгруза.
    since: float = 0.0
    #: Потеряно за весь показ - суммой потерь по всем его подгрузам.
    total: float = 0.0

    def see(self, pos: float, now: float, playing: bool = True) -> Freeze | None:
        """Опрос приёмника; вернуть подгруз, если он этим опросом закончился.

        ``playing`` - идёт ли показ вообще. Пауза и темнота ходом показа не считаются:
        на них указатель стоит законно, и вычитать их из плёнки не за что.
        """
        was_seen, self.seen = self.seen, now
        if self.pos < 0 or not playing:
            self.pos, self.at, self.flat, self.late = pos, now, 0.0, False
            return self._close(now)
        if not 0.0 < now - was_seen <= LAG_LATE:
            # Круг мерить нечем - и отрезок, в который он попал, тоже.
            self.late = True
        if pos == self.pos:
            # Свежего снимка не пришло. Судить по такому кругу нечего: считаем простой
            # и ждём снимка, который скажет, стояла картинка или молчала сетка.
            self.flat = now - self.at
            return None
        was_pos, was_at, flat, late = self.pos, self.at, self.flat, self.late
        self.pos, self.at, self.flat, self.late = pos, now, 0.0, False
        wall, moved = now - was_at, pos - was_pos
        if late or moved < 0 or moved > wall + LAG_JUMP:
            # Опоздавший круг, прыжок сторожа, перемотка, подъём - не ход показа.
            return self._close(now)
        # Простой короче шага, которым указатель сдвинулся, - это несвежий снимок, а не
        # стоящая картинка: столько же он простоял бы на молчащей сетке.
        lag = wall - moved - (0.0 if flat > moved else flat)
        if lag < (LAG_TAIL if self.began >= 0 else LAG_TICK):
            return self._close(now)
        if self.began < 0:
            self.began, self.since = was_pos, was_at
        self.lost += lag
        self.total += lag
        # Простой, посчитанный целиком, этим же опросом и кончился: указатель снова пошёл.
        return self._close(now) if flat else None

    def _close(self, now: float) -> Freeze | None:
        """Закончить идущий подгруз; ``None`` - его и не было."""
        if self.began < 0:
            return None
        done = Freeze(self.began, self.lost, now - self.since, self.total)
        self.began, self.lost, self.since = -1.0, 0.0, 0.0
        return done
