"""Сколько головы раздачи греем и сколько ждём её готовности."""

from typing import Final

#: Сколько байт тянем под меню одним местом (:func:`warm_at`): первый сегмент - это
#: 10-20 с видео со звуком, то есть десятки мегабайт.
HEAD_WARM: Final = 32 << 20

#: Сколько головы хватает, чтобы ffmpeg открыл вход, когда играть будем из середины:
#: заголовок контейнера и индекс, но не картинка. Тянуть все 32 МБ начала при продолжении
#: с середины вредно: это чужие байты, и они отбирают полосу у нужного места.
#:
#: Число одно на все контейнеры быть не может, и в этом была ошибка первой версии
#: («голова съедает весь бюджет»): 8 МБ выбраны с запасом под ``moov`` mp4, а
#: у mkv в голове лежат только EBML-заголовок, SeekHead, Info и Tracks - килобайты. На
#: холодном рое эта разница и есть весь бюджет раздумья: пока качается лишнее начало,
#: до места позиции дело не доходит.
#: У mp4 запас остаётся: ``moov`` бывает и на мегабайты (у «Моаны 2» от YTS - 5.3 МБ), а
#: без него ffmpeg вход не откроет вовсе.
HEAD_OPEN: Final = {"mkv": 1 << 20, "mp4": 8 << 20}

#: Контейнер неизвестен (карта из кэша прошлой версии, чужой файл) - берём больший кусок:
#: лишние мегабайты дешевле, чем ffmpeg, который не смог открыть вход.
HEAD_OPEN_DEFAULT: Final = 8 << 20

#: Потолок ожидания прогрева: дальше это уже не прогрев, а висящий поток.
WARM_TIMEOUT: Final = 120.0

#: Куда ``-ss`` уводит ffmpeg, если целиться ровно в опорный кадр карты, - **по демуксеру**.
#: Число - это сдвиг по карте от кадра, в который целятся: ``mkv`` встаёт на предыдущий
#: («через один»), ``mp4`` - ровно в него. Замер (180-секундный ролик, 90 опорных кадров,
#: h264 + B-кадры): mkv - сдвиг -1 на всех 88 границах, mp4 - 0 на всех 89; на двух разных
#: сборках ffmpeg (7.1.5 и 8.0.1) правило одно и то же. Сборка тут вообще не предмет веры:
#: на каждом файле правило сверяется пробным прогоном (:func:`pack_start`), и чужая версия
#: ffmpeg просто вернула бы показ к прежнему поведению, а не сломала бы нарезку.
#: Правило не выдумано из головы: перемотку обоих демуксеров ведёт **тот самый индекс**,
#: из которого снята карта (``Cues`` у mkv, ``stss`` у mp4), поэтому предсказывать можно
#: только по этой карте и только для этих двух контейнеров.
#:
#: ⚠️ mpegts ведёт себя наоборот - уезжает ВПЕРЁД на следующий опорный кадр (замер: +1 на
#: 89 границах), и докатки у него не бывает вовсе. В таблице его нет намеренно: карту
#: (:func:`torrcast.adapters.frames.keyframes.keyframes`) для .ts взять неоткуда, а щуп
#: на .ts, если его когда-нибудь заведут, этот класс дефектов НЕ воспроизводит.
SEEK_SHIFT: Final = {"mkv": -1, "mp4": 0}

#: Замок снятия карты считается живым столько секунд: дальше это брошенный хвост.
KEYS_LOCK: Final = 60.0

#: Сколько карт опорных кадров держим на полке (:func:`_keys_cache`).
#:
#: Карта - самый тяжёлый из кэшей рядом с состоянием: на живой полке в 299 карт медиана
#: 22 КБ, среднее 29 КБ, а самая большая - 874 КБ (длинный фильм, 7 тысяч точек Cues).
#: 256 карт - это порядка 7 МБ, то есть полка перестаёт расти где-то на месяцах показов,
#: а не «никогда». Потолок здесь по числу файлов, а не по байтам, ровно потому, что
#: число видно одним ``scandir``, а байты - только полным обходом с ``stat``
#: (:func:`_trim`), и платить его на каждом старте было бы дороже самой болезни.
KEYS_KEPT: Final = 256

#: Сколько паспортов держим на полке (:func:`_media_cache`).
#:
#: Паспорт - это длительность, дорожки и кодек, порядка килобайта; вдвое больший потолок
#: тут всё равно весит меньше мегабайта. Он больше не из щедрости: паспорт снимается и на
#: те релизы, которые показом так и не стали (отбор), поэтому паспортов заводится больше.
PROBE_KEPT: Final = 512
