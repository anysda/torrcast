"""Насколько дорожка готового куска вправе отойти от границы своего слота."""

from typing import Final

#: Допуск места дорожки, секунды: на столько метка первого пакета картинки или звука
#: вправе отстоять от границы слота (:func:`torrcast.adapters.stream_pack.track_starts`).
#: Больше - дорожка несёт ДРУГОЕ место фильма, и наружу такой кусок не выходит.
#:
#: Число снято корпусом, а не выведено. Корпус - 53 здоровые склейки настоящим ffmpeg: 24,
#: 23.976, 25, 29.97 и 50 к/с, звук 44.1 и 48 кГц, глубина перестановки 0-3 кадра, обе сетки
#: (по опорным кадрам и ровная). Против границы слота вышло:
#:
#: * картинка перекода - 0.0000-0.0417 с. Заход кодировщика ставит опорные кадры сам и режет
#:   по ним, поэтому почти всегда попадает в границу знак в знак;
#: * звук копии - 0.0000-0.1867 с, и широкая половина тут вся от РОВНОЙ сетки: там рез идёт
#:   по времени, и звуковые пакеты с меткой чуть раньше границы достаются новому куску.
#:
#: Живой показ на приставке подтвердил ту же полосу и раздвинул её: три прогона по 200 с на
#: РОВНОЙ сетке (24-27 отданных кусков в каждом, все склеены) дали максимум 0.117 у картинки
#: и 0.155 у звука - то есть синтетический корпус картинку недооценивал, а самое широкое
#: здоровое значение из всех замеров осталось прежним, 0.1867.
#:
#: 0.5 - это 2.7 самой широкой здоровой дорожки. Поломка при этом лежит на два порядка выше
#: и по построению не бывает мелкой: муксер, пропустивший рез, сдвигает НУМЕРАЦИЮ файлов, то
#: есть промахивается сразу на целый слот. Замер: 10.417 с на ролике (перекод потерял рез) и
#: 9.936 с (копия), живой замер «Матрицы» - 123-324 с. Порог стоит в пустом промежутке
#: 0.19...9.9, а не по краю одного из множеств.
#:
#: ⚠️ Рядом стоит :data:`torrcast.usecases.warm.settings.SKEW_MAX` = 0.15, и это ДРУГОЕ число
#: при том же вопросе: сторож прогрева меряет ТОЛЬКО картинку и только сдвиг НАЗАД, а здесь
#: меряются обе дорожки и в обе стороны, и широкую половину даёт звук. Связать их одним
#: именем значило бы двигать оба, поправив один.
TRACK_PLACE_MAX: Final = 0.5
