"""Правило unmarked; используют модели и фасады разбора имён."""

from __future__ import annotations

from typing import Final

#: Слова, которыми раздача называет ВИД картины, а не саму картину. «Токийский Гуль ТВ-1»,
#: «Токийский гуль ОВА» и «Токийский гуль» это один сериал, а не три франшизы, и разводит
#: их по разным ключам только приставший маркер.
#:
#: Список закрытый нарочно. Любое правило шире закрытого списка тащит в меню чужое:
#: «Оно приходит ночью» к «Оно», «Титаник 666» к «Титанику», «Друзья с колледжа» к
#: «Друзьям» - у всех имя начинается с имени франшизы, и по началу имени они неотличимы
#: от настоящего продолжения.
_KIND_MARKS: Final = frozenset(
    {
        "tv",
        "тв",
        "ova",
        "ова",
        "ona",
        "она",
        "oad",
        "movie",
        "фильм",
        "special",
        "спешл",
        "season",
        "сезон",
    }
)


def _unmarked(key: str) -> str:
    """Ключ без маркеров вида по краям.

    Середина не трогается: там стоит имя, и «нечто-фильм-о-любви» маркером не считается.
    Пустой остаток не отдаётся - ключ «ova» это всё, что о картине сказано.
    """
    parts = key.split("-")
    while len(parts) > 1 and parts[-1] in _KIND_MARKS:
        parts.pop()
    while len(parts) > 1 and parts[0] in _KIND_MARKS:
        parts.pop(0)
    return "-".join(parts)


__all__ = ["_unmarked"]
