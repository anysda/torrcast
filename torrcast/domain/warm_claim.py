"""Сколько диска прогреву ещё предстоит занять сверх уже занятого им.

Число нужно там, где кэш раздачи и прогретое делят один раздел: установка выбирает,
где кэшу больше места (``install.sh``), а ``cast doctor`` судит, не съел ли кэш чужой
запас (:mod:`torrcast.usecases.doctor`).
"""


def warm_claim(budget: int, used: int) -> int:
    """Байты, которые прогрев вправе занять ЕЩЁ; бюджет уже выбран - ноль.

    🔴 TC-725. Свободное место раздела УЖЕ не содержит того, что прогрев занял, и
    резервировать поверх этого места весь бюджет прогрева значит посчитать занятое
    дважды. Стоит это не строчки в отчёте, а места кэша: на стенде с разделом 52.7 ГБ
    прогретое занимало 15.3 ГБ, свободного оставалось 23.1 ГБ, а бюджет прогрева и
    неприкосновенный запас вместе просили 33.2 ГБ - кэшу на диске выходил ноль, и он
    уезжал в память, где стоит вдвое против своего размера
    (:data:`torrcast.domain.cache_health.CACHE_OVERHEAD`).

    Замер того же стенда: кэш 3.1 ГиБ в памяти - служба весит 5.9 ГиБ при 8 ГБ у
    машины; тот же кэш на диске - 104 МиБ.
    """
    return max(0, budget - used)
