"""Поля настроек про раздачу HLS: транспорт, адрес, сетка сегментов и темп упаковки.

Наследует их :class:`torrcast.domain.config.Config`, и только он.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Final, Literal

from torrcast.domain._config_sources import _ConfigSources
from torrcast.domain.profile import CAUTIOUS

#: Умолчание каталога сегментов - боевой tmpfs. Вынесено именем, а не только строкой
#: поля: по нему :func:`torrcast.usecases.playback.hls_root.hls_root` узнаёт
#: НЕИЗМЕНЁННОЕ умолчание и подменяет его в тестовом прогоне, не трогая явно заданный
#: каталог (TC-891).
DEFAULT_HLS_DIR: Final = "/dev/shm/torrcast"


@dataclass(slots=True)
class _ConfigHls(_ConfigSources):
    """Чем и куда раздаём ленту, каким шагом её режем и с каким запасом впереди."""

    #: Чем раздаём HLS. Дефолт - ``http``: ни серта, ни имени, ни облака в пути потока.
    #: ``https`` - выключенная опция: код жив и работает, но требует серта, которому
    #: доверяет ТВ, а с ним - имени и того, кто это имя выпишет.
    transport: Literal["http", "https"] = "http"
    #: База URL, под которой ТВ забирает HLS. **Пусто - нормальный режим**: адрес
    #: вычисляется по маршруту до ТВ (:func:`torrcast.adapters.http_server.hls_base.hls_base`), то
    #: есть берётся тот наш интерфейс, с которого нас видит сам телевизор. DNS в пути показа не
    #: участвует вовсе - упадёт локальный резолвер, каст продолжит играть. Задавать руками стоит
    #: ровно в одном случае: прямой путь почему-то не работает и нужен другой адрес.
    hls_base_url: str = ""
    hls_port: int = 8080
    #: Серт и ключ: нужны только при ``transport: https``.
    hls_cert: str = "/etc/torrcast/tls/torrcast.crt"
    hls_key: str = "/etc/torrcast/tls/torrcast.key"
    #: Сегменты живут в tmpfs - фильм на диск не пишем. Целиком он туда и не влезет: в
    #: каталоге всегда только окно вокруг того места, где смотрят.
    hls_dir: str = DEFAULT_HLS_DIR
    #: Темп упаковки - ровно реальное время, а запас впереди приёмника даёт burst.
    #: Пара 1.0/60 держит упаковку на ~минуту впереди показа и не растёт: в
    #: tmpfs всегда ``burst`` + ``hls_keep`` секунд фильма, сколько бы он ни длился.
    #: ⚠️ 1.0 БЕЗ burst дважды вреден, замерено: первый сегмент готов не раньше
    #: своей же длительности (на «Моане 2» ключевые кадры дают ~12 с сегменты → +9 с к
    #: старту), а дальше приёмник идёт вровень с упаковкой и буферится на каждом стыке.
    #: Темп заметно выше единицы (было 1.5) уводит упаковку вперёд без предела - на
    #: двухчасовом фильме это лишний час потока в RAM.
    hls_readrate: float = 1.0
    #: Сколько секунд входа ffmpeg читает на полной скорости, прежде чем встать в темп
    #: (``-readrate_initial_burst``, нужен ffmpeg ≥ 6.1 - его ставит install.sh).
    #: 🔴 Умолчание - осторожный профиль приёмника (:data:`torrcast.domain.profile.CAUTIOUS`);
    #: профиль живого приёмника его перебивает, а написанное сюда руками сильнее профиля
    #: (:func:`torrcast.domain.tune.tune`). Так же читаются и остальные ключи с этой пометкой.
    hls_burst: float = CAUTIOUS.burst
    #: Сколько секунд позади приёмника держим сегменты - это и есть глубина перемотки
    #: назад «без последствий». Глубже - не 404, а перепаковка потока с нужной секунды.
    hls_keep: float = 120.0
    #: Шаг сетки сегментов, секунды. Не «длительность»: с сеткой по опорным кадрам
    #: сегмент длиннее шага на остаток GOP (:class:`torrcast.adapters.stream_pack.grid.Grid`).
    #: 🔴 Умолчание - осторожный профиль приёмника.
    hls_segment: float = CAUTIOUS.segment_seconds
    #: Ставить границы сегментов на опорные кадры (нужна карта из mkv). Так каждый кусок
    #: декодируется сам по себе и перемотка в любую точку сразу даёт картинку. ``false`` -
    #: ровная сетка ровно по ``hls_segment``: это режим для замеров, а не для показа.
    hls_keyframes: bool = True
    #: Сколько секунд имеет смысл ждать упаковку вместо перезапуска её с нужного места.
    #: 🔴 Умолчание - осторожный профиль приёмника (:attr:`torrcast.domain.profile.Profile.jump`).
    hls_jump: float = CAUTIOUS.jump
    #: За сколько секунд плёнки до конца прогретого поднимается живая упаковка.
    #: 🔴 Умолчание - осторожный профиль приёмника
    #: (:attr:`torrcast.domain.profile.Profile.seam_lead`).
    hls_seam_lead: float = CAUTIOUS.seam_lead
