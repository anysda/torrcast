"""Первая половина записи состояния: что играет и что про этот файл известно.

Отдельным файлом эти поля лежат ради потолка раскладки, а не ради нового смысла: они
остаются началом одной и той же записи (:class:`torrcast.domain.entry.Entry`), и порядок
их в точности прежний - им же задан порядок ключей в файле состояния.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

#: Что именно записано: у записи состояния вида "other" не бывает - её заводит
#: только показ картины или серии (:func:`torrcast.usecases.cast_command._cmd_play`).
EntryKind = Literal["movie", "tv"]


@dataclass(slots=True)
class _Playing:
    """Что играем, чем, с какого места и что сказал про файл паспорт ffprobe."""

    title: str
    magnet: str
    kind: EntryKind = "movie"
    file_idx: int = 0
    audio: int = 0
    #: Звук едет не из видеофайла, а из отдельного файла, лежащего рядом с ним в той же
    #: раздаче (:func:`torrcast.domain.voice_beside.voice_beside`). Тогда :attr:`audio` -
    #: номер дорожки ВНУТРИ этого второго файла, а не внутри видео.
    #:
    #: Записан флаг, а не номер файла, и это не экономия: у сериала файл звука свой на
    #: каждую серию, а список серий (:attr:`Entry.episodes`) знает только видеофайлы.
    #: Номер, записанный на первой серии, ко второй уже врал бы; правило же находит
    #: нужный файл по имени серии на каждом переходе заново.
    voiced_apart: bool = False
    #: Память озвучки на эту картину: подпись дорожки
    #: (:attr:`torrcast.domain.audio_track.AudioTrack.label`), которую пользователь выбрал
    #: **явно** - флагом ``--voice``. Пусто - явного выбора не было.
    #:
    #: Почему подпись, а не номер: номер живёт внутри одного релиза, а память - на
    #: картину. Следующий запуск может взять другую раздачу (сиды меняются, верх отбора
    #: тоже), и «дорожка 4» там будет другой студией. Подпись переживает смену релиза, а
    #: если такой озвучки в новом релизе нет - об этом говорится вслух и берётся дефолт,
    #: причём память НЕ стирается: релиз временный, выбор пользователя - нет.
    #:
    #: Автовыбор сюда не пишет ничего: запоминается только то, что человек назвал сам.
    #: У сериала память общая на сериал - она и лежит в одной записи на всю раздачу.
    voice: str = ""
    #: Память СТУДИИ на эту картину: имя студии, чья озвучка на этой картине играла
    #: (:attr:`torrcast.domain.studio.Studio.name`). Пусто - студию не узнали.
    #:
    #: 🔴 Это другая память, чем :attr:`voice`, и заведена она ради сериала. Подпись
    #: дорожки живёт ВНУТРИ раздачи, а сезонная раздача кончается вместе с сезоном:
    #: следующий сезон - другой релиз, часто другой студии, и подпись «rus» ему
    #: подойдёт любая. Студия же переживает и смену релиза, и границу сезона - по ней
    #: отбор поднимает ту раздачу, которой сериал и смотрели
    #: (:func:`torrcast.usecases.rank.studio_step.studio_step`).
    #:
    #: Первый просмотр записывает сюда студию дорожки, которая играла
    #: (:func:`torrcast.domain.track_studio.track_studio`), и дальше поле держится: у
    #: следующего сезона запомненной студии может не быть вовсе, и тогда играется что
    #: есть, а помнится прежнее. Переписать память вправе только явный выбор человека
    #: (``--voice``) - иначе вынужденный дефолт стирал бы ровно то, ради чего память и
    #: заведена, и второй сезон подряд картина искала бы себе новую студию.
    studio: str = ""
    #: Студия, которая играет СЕЙЧАС, когда запомненной в этом релизе не нашлось; пусто -
    #: играет запомненная (или памяти нет вовсе). Поле не память, а факт показа, и живёт
    #: оно ради одной строки: подмену озвучки зритель обязан прочесть на ЭКРАНЕ, а
    #: единственное, что туда уезжает, - подпись показа
    #: (:func:`torrcast.domain.voice_swap.voice_swap`). Спросить живой показ нельзя: играет
    #: он в своём процессе, и состояние тут единственный канал.
    heard: str = ""
    pos: float = 0.0
    dur: float = 0.0
    #: Хэш раздачи, которую держит в TorrServer живой показ этой записи (hex, нижний
    #: регистр). Лежит рядом с позицией и по той же причине: спросить живой показ из CLI
    #: нельзя, состояние тут единственный канал.
    #:
    #: 🔴 Пишется в ту же секунду, когда юнит поднял раздачу, и снимается в ту, когда он
    #: её убрал. Смысл ровно один: хозяин раздачи может умереть не по-людски (SIGKILL по
    #: таймауту, паника, перезагрузка), а раздача переживает свой процесс - она живёт в
    #: TorrServer. Без записанного хэша убрать её потом нечем: в списке службы лежат и
    #: чужие раздачи, а «снести всё из list» снесло бы их. Непустое поле при
    #: мёртвом юните - сирота, и
    #: следующий ``cast`` убирает её по этому явному хэшу
    #: (:func:`torrcast.usecases.torrents._release_orphans`).
    #:
    #: По этой же отметке уборка прогрева параллельного ``cast`` видит, что раздача
    #: чья-то, и не сносит её из-под живого показа (:meth:`State.held`).
    torrent: str = ""
    #: Разрешение, ПОДТВЕРЖДЁННОЕ ffprobe у того файла, который играем
    #: (:attr:`torrcast.domain.media.Media.quality`). Заявка имени сюда не попадает никогда:
    #: «1080p» в заголовке и 1150×574 внутри - живой случай «Моаны 2», а `cast status`
    #: обязан показывать то, что уехало на ТВ: молчаливых подмен нет. Пусто -
    #: записи прежней версии, о них честно молчим.
    quality: str = ""
    #: Ступень лестницы кадра числом (:attr:`torrcast.domain.media.Media.frame`) - то же, что
    #: :attr:`quality`, но пригодное для сравнения с порогом.
    #:
    #: 🔴 Лежит рядом с кодеком и глубиной по той же причине: решение «перекодировать файл
    #: целиком» принимается ДО первого сегмента, а кадр в этом решении - последнее слово
    #: (:attr:`torrcast.domain.profile.Profile.recode_frame`). Без него запись, обошедшая отбор
    #: (``--release N``, ``--file N``), уезжала на ТВ и вставала там намертво.
    #:
    #: Ноль - кадр не спрашивали (записи прежних версий). Такая запись своё число
    #: получает на первом же продолжении (:func:`torrcast.usecases.episode_duration._duration`) -
    #: тем же одним ffprobe, что и глубину цвета: без него 4К уезжало бы на приёмник
    #: неужатым, во весь свой кадр (:attr:`Encode.ceiling`, TC-251).
    frame: int = 0
    #: Картинка в HDR по паспорту ffprobe (:attr:`torrcast.domain.media.Media.hdr`): её при
    #: сплошном перекоде надо ещё и привести к SDR (:attr:`Config.recode_tonemap`).
    #: ``false`` тут значит и «SDR», и «не спрашивали» - разницы нет: тонемап по
    #: умолчанию выключен, и запись прежней версии играется ровно как раньше.
    hdr: bool = False
    #: Битрейт видеодорожки, Мбит/с. Точное число берётся из паспорта ffprobe; если
    #: паспорт молчит, хранится верхняя оценка по размеру всего файла и длительности.
    #: Из него показ знает, сколько уедет на ТВ, ещё до первого упакованного сегмента -
    #: а значит и какие куски перекодировать. Оба числа доступны без лишних запросов.
    #:
    #: ``0`` - ещё не спрашивали (запись прежней версии), **отрицательное** - спросили,
    #: и оценить тоже не из чего. Разница нужна, чтобы молчаливый паспорт не стоил
    #: лишнего ffprobe на каждом запуске.
    vbps: float = 0.0
    #: ``True`` - :attr:`vbps` оценён по размеру всего файла и длительности, а не
    #: измерен паспортом. Отсутствующий ключ старой записи читается как ``False``.
    vbps_estimated: bool = False
    #: Кодек видео по паспорту ffprobe (``h264``, ``hevc``). Из него показ знает, играть
    #: видео копией или перекодировать файл целиком
    #: (:attr:`torrcast.domain.profile.Profile.recode_codecs`), и знает это ДО первого сегмента -
    #: решение принимается один раз на файл.
    #:
    #: Пусто - записи прежних версий и те, где паспорт не спрашивали: такие играются
    #: копией, как и раньше, а своё имя кодека получат на первом же обычном запуске.
    codec: str = ""
    #: Глубина цвета видео по паспорту ffprobe, бит
    #: (:func:`torrcast.domain.color_depth.color_depth`).
    #:
    #: 🔴 Лежит рядом с кодеком, потому что кодека для решения НЕ ХВАТАЕТ: десятибитный
    #: H.264 (Hi10P, половина аниме-BDRip) зовётся тем же ``h264``, а приёмник его не
    #: декодирует - доигрывает буфер и встаёт в вечную петлю LOAD/BUFFERING. Решение
    #: «копия или перекод целиком» принимает :func:`torrcast.domain.recodes_whole.recodes_whole` по
    #: паре «кодек + глубина», и одинаково у показа и у прогрева.
    #:
    #: ``0`` - не спрашивали (запись прежней версии). Такая запись своё число получает на
    #: первом же продолжении (:func:`torrcast.usecases.episode_duration._duration`): одним ffprobe,
    #: один раз.
    depth: int = 0
    #: Сколько секунд фильма прогрето на диск (:mod:`torrcast.usecases.warm`). Пишет сторож показа,
    #: читает ``cast status`` - только затем и хранится: спросить живой показ из CLI
    #: нельзя, состояние тут единственный канал.
    #:
    #: Число относится к файлу, который играет СЕЙЧАС: прогретое досмотренного показа
    #: стирается с диска тем же выходом, а у следующей серии своё хранилище, - поэтому
    #: переход записи (:meth:`advance`, :meth:`jump`) сбрасывает поле в ноль, и своё
    #: честное число запись получает от сторожа нового показа.
    warm: float = 0.0
    #: Правда ли приёмник хоть раз назвал живую позицию ЭТОГО запуска, а не унаследованную
    #: позицию ПРОШЛОГО сеанса. Пишет сторож показа (:meth:`torrcast.usecases.watch.Watch.see`),
    #: читает мост Home Assistant (:func:`hass.motion.Motion.phase`) вместо ``pos > 0``, которая
    #: продолжению врала бы паузой (TC-1002, 03-09-2026). Сброшен запуском и переходом записи.
    moved: bool = False
    #: Когда показ ПОГАС, стенное время (unix); ``0.0`` - на экране картинка. Пишет
    #: сторож показа, читает ``cast status`` - канал тот же, что у :attr:`warm`, и по той
    #: же причине: спросить живой показ из другого процесса нечем.
    #:
    #: 🔴 Живой юнит показом больше не считается. Пока этой отметки не было, `cast status`
    #: рапортовал «играю» всю темноту до потолка
    #: (:data:`torrcast.domain.revive_settings.REVIVE_LIMIT`) - четверть часа чёрного экрана, про
    #: который инструмент говорил, что всё хорошо.
    #:
    #: Время именно стенное, а не монотонное: читает его ДРУГОЙ процесс, а монотонное у
    #: двух процессов разное (:mod:`torrcast.adapters.filesystem.stopwatch`). Отметку
    #: ставит и снимает один писатель - сторож показа, - поэтому гонки на ней нет.
    #:
    #: 🔴 Смерть юнита её НЕ стирает, и это главное её свойство. Показ, умерший совсем,
    #: иначе неотличим от спокойно доигранного: позиции у него может не быть вовсе (кадра
    #: не показали - закладке взяться неоткуда), а журнал уходит вместе с юнитом. Замер
    #: 16-08-2026 на живой приставке: показ не дал ни кадра, юнит вышел, `cast status`
    #: ответил «ничего не играет» - ровно то же, что после конца фильма. На стыке серий,
    #: где консоли рядом нет, эта отметка - единственная дверь к правде о чёрном экране.
    #: Снимает её только следующий запуск (:func:`torrcast.usecases.playback._launch`).
    dark: float = 0.0
    #: Из-за чего погас показ, одной строкой - та же причина, что ушла человеку
    #: (:func:`torrcast.usecases.revive_playback._blame._why`). Пусто - темноты нет.
    dark_why: str = ""
    #: Год выбранной картины: структурированная часть имени для статуса и внешних пультов.
    year: int = 0
    #: Оригинальное имя картины (:attr:`torrcast.domain.picture.Picture.original`): под
    #: английской ручкой продукт зовёт её им
    #: (:func:`torrcast.domain.spoken_title.spoken_title`), а не русским названием из
    #: :attr:`title` - иначе одна и та же картина звучит в сессии двумя языками.
    #:
    #: Пусто - либо оригинального имени у картины нет вовсе (отечественная), либо запись
    #: писалась прежней версией: тогда под EN печатается записанное имя как есть.
    original: str = ""
    #: Слово показа о паузе: ``PAUSED``/``PLAYING``; пусто - правды нет (запись прежних
    #: версий). Пишется на переходе с немедленным сбросом на диск - канал и довод те же,
    #: что у :attr:`dark`. Сброшено запуском и переходом записи, как :attr:`moved`.
    paused: str = ""
