"""Правило editionless; используют модели и фасады разбора имён."""

from __future__ import annotations

from torrcast.domain._name_data.data_2 import _EDITION_TAILS


def _editionless(key: str) -> str:
    """Ключ без служебного хвоста издания: «X» и «X. Полное издание» это одна картина.

    🔴 Хвост снимается только с КОНЦА и только из закрытого списка
    :data:`~torrcast.domain._name_data.data_2._EDITION_TAILS`. Правило «выкинуть всё после
    точки» или «снять два последних слова» тут запрещено: соседним пунктом лежит
    ДРУГАЯ работа с другим хронометражом - «Игра Престолов: Дополнительные материалы»,
    «Властелин колец - история создания», «Твин Пикс: Огонь, иди со мной - Пропавшие
    фрагменты», - и такая стрижка увела бы её в пул самой картины, то есть подсунула бы
    зрителю не тот фильм. Потеря из каталога хуже чинимой беды.

    Хвосты снимаются подряд: «X. Расширенное издание. Режиссерская версия» это всё та
    же X. Пустого ключа не бывает по устройству: перед хвостом требуется дефис, а
    значит и хотя бы один знак имени, и «Полное издание» само по себе остаётся целым.
    """
    while True:
        for tail in _EDITION_TAILS:
            if key.endswith(f"-{tail}"):
                key = key[: -len(tail) - 1]
                break
        else:
            return key


__all__ = ["_editionless"]
