"""Набрал ли показ столько фильма, сколько приёмнику нужно до ПЕРВОГО кадра."""

from __future__ import annotations


def first_frame_ready(shown: bool, pos: float, front: float, start_buffer: float) -> bool:
    """Пора ли считать, что на экране картинка, а не накопление буфера.

    🔴 Замер приёмника (:attr:`torrcast.domain.profile.Profile.start_buffer`): он отвечает
    ``PLAYING``, ещё не показав ни кадра, и держит указатель на месте захода, пока не
    накопит около десяти секунд фильма. Объявить картинку по первому же сдвигу декодера
    значит показать старт на 5-6 с бодрее, чем он есть.

    Запас показу известен не всегда: ``front <= pos`` значит «впереди не названо ничего»,
    и судить тут не о чем. Кадр уже был на экране (``shown``) - правило тоже не работает:
    копит приёмник один раз, на заходе.
    """
    return shown or front <= pos or front - pos >= start_buffer
