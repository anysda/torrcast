"""Правило nearest group; используют модели и фасады разбора имён."""

from __future__ import annotations

from torrcast.domain.group_weight import _group_weight
from torrcast.domain.picture import Picture


def _nearest_group(wanted: str, groups: dict[str, list[Picture]], hits: list[str]) -> str:
    """Какая из групп, чей слаг СОДЕРЖИТ спрошенный, и есть спрошенная картина.

    🔴 TC-1025. Близость меряется ЛИШНИМИ СЛОВАМИ, а не буквами. Пока мерили длину
    слага, «властелин» уводил зрителя в «Властелин мира» (1961, 2 раздачи, 0 сид) мимо
    «Властелина колец» (48 раздач) - ровно потому, что «мира» на одну букву короче
    «колец». Обе группы дописывают к спрошенному слову РОВНО ОДНО своё, то есть стоят
    от запроса одинаково далеко, и буква тут решала жребием.

    Слов поровну - решает вес группы (:func:`_group_weight`): на одном расстоянии
    спрошенной вероятнее та картина, которой каталог отдал больше раздач. Замер по
    живой выдаче RuTor, запрос «властелин»: 9 групп содержат спрошенное слово, у шести
    из них лишнее слово одно, и вес разводит их 48 против 13, 6, 2, 2 и 2.

    Буква остаётся третьим членом, а не пропадает: при равных словах и равном весе
    выбор всё равно обязан быть одним и тем же от прогона к прогону, иначе два замера
    одного корпуса нельзя сравнить между собой.
    """
    asked = len(wanted.split("-"))
    return min(
        hits,
        key=lambda key: (
            len(key.split("-")) - asked,
            -_group_weight(groups, key),
            len(key),
            key,
        ),
    )


__all__ = ["_nearest_group"]
