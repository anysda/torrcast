"""Какими ключами файла настроек владеет человек, а какими - код.

Спрашивают это запись настроек и установщик: всё, чего здесь нет, собирается заново
из умолчаний кода при каждой установке.
"""

from __future__ import annotations

from typing import Final

#: Настройки, которых из кода не вывести: человек назвал их сам, и заново он их не
#: наберёт. Всё остальное в файле - замеры и устройство системы (пороги битрейта, окно
#: сегментов, бюджет прогрева, пути раздачи), и владеет ими код.
#:
#: 🔴 TC-549. Список белый нарочно, и полярность эта обратна прежней. Установка
#: вычищала из живого конфига ЧЁРНЫЙ список имён, а значит всякое поднятое умолчание
#: надо было дописывать в тот список руками. Забытое молча жило на старом числе:
#: ``warm_budget_gb`` в него не попал, и у поставивших продукт раньше бюджет прогрева
#: остался 20 ГБ против 30 в коде - прогрев вставал посреди фильма со строкой про
#: исчерпанный бюджет диска (живой прогон 12-08). Белый список ошибается в другую
#: сторону: забытое имя вернётся к умолчанию кода, а не застрянет на старом числе.
#:
#: Языка тут не было бы, если бы его писал только установщик, - но его пишет и человек
#: (``cast --ru`` / ``cast --en``, TC-926), поэтому владеет им он.
#: Три ключа телеграм-бота (``token``, ``chat_id``, ``proxy``) живут в том же файле, но
#: не в :class:`~torrcast.domain.config.Config` вовсе: их список - поля
#: :class:`tgbot.config.Config`, и хранит их бот сам.
OWNED_BY_HUMAN: Final[frozenset[str]] = frozenset(
    {
        "tv",
        "receiver",
        "receiver_profile",
        "torrserver_url",
        "prowlarr_url",
        "prowlarr_apikey",
        "language",
    }
)
