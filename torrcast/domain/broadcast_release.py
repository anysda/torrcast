"""Спортивная трансляция по имени: русская форма с видом спорта или английское шоу.

Полке нужны кино и сериалы, и только они (ТЗ §9), а трансляция матча - ни то, ни другое.
:mod:`torrcast.domain.nonvideo_release` её не ловит и не должен: он различает НЕ-видео, а
трансляция - самое настоящее видео, у неё стоят те же приметы (``HDTV 720p``,
``WEBRip 1080p``), которые там имеют право вето.

Различитель - не слово «футбол» где угодно, а **заголовок**: русскоязычный трекер
печатает трансляции одной формой, «вид спорта, точка, турнир, точка, участники».
Фильм с тем же словом в имени («Бокс (2010) BDRip») точки сразу за словом не имеет и
остаётся на полке. Англоязычный источник этой пунктуации не даёт, поэтому для него
названы только полные бренды спортивных программ в начале имени. Слова ``Match`` или
``Collision`` по отдельности не являются признаком.

Замерено 06-09-2026 на живом пуле стенда (5 индексеров, широкая лента): 316 строк, 201
после отсева не-видео, 18 трансляций - и все 18 этой формы, пять видов спорта («Футбол»,
«Бокс», «Велоспорт», «Формула 1», «Смешанные единоборства»). Остальные слова перечня той
же формы и от того же издателя, но в замер не попали: их пока не публиковали.
"""

from __future__ import annotations

import re

#: Вид спорта в САМОМ начале имени и точка сразу за ним. Перечень закрытый: широкое
#: правило «первое слово до точки» съело бы «Брат. Часть 2» и любое имя с точкой.
_BROADCAST_RE = re.compile(
    r"(?i)^\s*(футбол|хоккей|баскетбол|волейбол|теннис|бокс|велоспорт|биатлон|регби|"
    r"гандбол|плавание|лыжные гонки|фигурное катание|лёгкая атлетика|"
    r"формула 1|формула-1|смешанные единоборства|mma|ufc)\s*\."
)

#: Англоязычные спортивные программы в САМОМ начале имени. Это полный заголовок
#: передачи, а не слово из него: фильм с ``Match`` или ``Collision`` в имени остаётся.
#: Форма не требует точки - английский источник печатает название шоу без неё.
_ENGLISH_BROADCAST_RE = re.compile(
    r"(?i)^\s*(?:"
    r"match of the day(?:\s+2)?|"
    r"(?:all elite wrestling|aew)\s+(?:collision|dynamite|rampage)|"
    r"wwe\s+(?:monday night\s+)?raw|"
    r"wwe\s+(?:friday night\s+)?smackdown|"
    r"wwe\s+nxt|"
    r"ufc\s+fight night|"
    r"nfl\s+redzone"
    r")\b"
)


def _is_broadcast_release(name: str) -> bool:
    """Правда, если имя раздачи - спортивная трансляция, а не картина."""
    return bool(_BROADCAST_RE.match(name) or _ENGLISH_BROADCAST_RE.match(name))


__all__ = ["_is_broadcast_release"]
