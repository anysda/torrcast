"""Кто отдал полную страницу выдачи: за такой строкой лежит обрезанный хвост."""

from __future__ import annotations

from typing import Final

#: Максимум строк одного индексера в ответе Prowlarr. Параметр ``limit`` этого
#: потолка не меняет: запросы на 100 и 200 возвращают одну и ту же сотню.
INDEXER_PAGE: Final = 100


def capped_indexers(counts: dict[str, int]) -> tuple[str, ...]:
    """Кто упёрся в потолок страницы (:data:`INDEXER_PAGE`) - по именам.

    Ровно потолок - это не полнота, а обрезанный хвост: за сотней строк могут лежать
    раздачи, до которых выдача не дошла. Потолок источника от запрошенного ``limit`` не
    зависит, поэтому и меряется своей меркой, а не клиентской.

    Считается по ответившим: у опоздавшего счёт неизвестен, а гадать нельзя.
    """
    return tuple(name for name, rows in counts.items() if rows >= INDEXER_PAGE)


__all__ = ["INDEXER_PAGE", "capped_indexers"]
