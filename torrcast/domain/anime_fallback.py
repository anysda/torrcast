"""Звать ли анимешные индексеры вторым кругом, когда первый вышел тощим."""

from __future__ import annotations

from typing import Final

#: Меньше стольких раздач после основного круга - пул тощий, и анимешные индексеры
#: зовём фолбэком (TC-229). Порог нарочно мал: это не мера полноты каталога (та -
#: :data:`~torrcast.domain._name_data.THIN_POOL`, и мерится строками), а отсечка «почти пусто»,
#: после которой лишний круг по Nyaa дешевле, чем промах мимо аниме-раздач.
FALLBACK_POOL: Final = 3


def anime_fallback(found: int, answered: bool) -> bool:
    """Пул без анимешных вышел тощим - позвать и их (:data:`FALLBACK_POOL`).

    ``found`` - сколько РАЗДАЧ собрал первый круг после склейки, ``answered`` - ответил
    ли в нём хоть кто-то. Не ответил никто - фолбэка нет: это уже не тощий пул, а
    молчание, и лечится оно не лишним кругом.

    Пустая выдача ответивших - самый тощий пул из возможных, и фолбэк тут положен.
    """
    return answered and found < FALLBACK_POOL


__all__ = ["FALLBACK_POOL", "anime_fallback"]
