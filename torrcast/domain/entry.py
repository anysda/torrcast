"""Запись состояния показа: что смотрим, чем, с какого места и досмотрено ли.

Чистая модель без файлов: читает и пишет её файловое состояние
(:class:`torrcast.adapters.filesystem.state.State`).
"""

from __future__ import annotations

from dataclasses import dataclass, field, replace
from datetime import UTC, datetime
from typing import Any, Literal

#: Что именно записано: у записи состояния вида "other" не бывает - её заводит
#: только показ картины или серии (:func:`torrcast.usecases.cast_command._cmd_play`).
EntryKind = Literal["movie", "tv"]

#: Доля длительности, после которой сохранённая закладка считается досмотренной.
WATCHED_RATIO = 0.95

#: Доля длительности, после которой конец показа читается как титры, а не как авария.
#: Мерка щедрая намеренно: ею показ решает, воскрешать ли погасший экран, и сузить её
#: значит начать воскрешать доигранное. Переключением она не заведует: серия доигрывает
#: до конца потока, а доля отвечает только на вопрос «это был конец или обрыв».
ENDING_RATIO = 0.95


@dataclass(slots=True)
class Entry:
    """Запись состояния: что смотрим, чем и с какого места."""

    title: str
    magnet: str
    kind: EntryKind = "movie"
    file_idx: int = 0
    audio: int = 0
    #: Память озвучки на эту картину: подпись дорожки
    #: (:attr:`torrcast.stream.AudioTrack.label`), которую пользователь выбрал
    #: **явно** - флагом ``--voice``. Пусто - явного выбора не было.
    #:
    #: Почему подпись, а не номер: номер живёт внутри одного релиза, а память - на
    #: картину. Следующий запуск может взять другую раздачу (сиды меняются, верх отбора
    #: тоже), и «дорожка 4» там будет другой студией. Подпись переживает смену релиза, а
    #: если такой озвучки в новом релизе нет - об этом говорится вслух и берётся дефолт,
    #: причём память НЕ стирается: релиз временный, выбор пользователя - нет.
    #:
    #: Автовыбор сюда не пишет ничего: запоминается только то, что человек назвал сам.
    #: У сериала память общая на сериал - она и лежит в одной записи на всю раздачу.
    voice: str = ""
    pos: float = 0.0
    dur: float = 0.0
    #: Хэш раздачи, которую держит в TorrServer живой показ этой записи (hex, нижний
    #: регистр). Лежит рядом с позицией и по той же причине: спросить живой показ из CLI
    #: нельзя, состояние тут единственный канал.
    #:
    #: 🔴 Пишется в ту же секунду, когда юнит поднял раздачу, и снимается в ту, когда он
    #: её убрал. Смысл ровно один: хозяин раздачи может умереть не по-людски (SIGKILL по
    #: таймауту, паника, перезагрузка), а раздача переживает свой процесс - она живёт в
    #: TorrServer до его перезапуска. Без записанного хэша убрать её потом нечем: после
    #: перезапуска службы своих раздач в её списке не остаётся вовсе (заводим их с
    #: ``save_to_db: false``), а «снести всё из list» снесло бы чужое. Непустое поле при
    #: мёртвом юните - сирота, и
    #: следующий ``cast`` убирает её по этому явному хэшу
    #: (:func:`torrcast.cli._release_orphans`).
    #:
    #: По этой же отметке уборка прогрева параллельного ``cast`` видит, что раздача
    #: чья-то, и не сносит её из-под живого показа (:meth:`State.held`).
    torrent: str = ""
    #: Разрешение, ПОДТВЕРЖДЁННОЕ ffprobe у того файла, который играем
    #: (:attr:`torrcast.stream.Media.quality`). Заявка имени сюда не попадает никогда:
    #: «1080p» в заголовке и 1150×574 внутри - живой случай «Моаны 2», а `cast status`
    #: обязан показывать то, что уехало на ТВ: молчаливых подмен нет. Пусто -
    #: записи прежней версии, о них честно молчим.
    quality: str = ""
    #: Ступень лестницы кадра числом (:attr:`torrcast.stream.Media.frame`) - то же, что
    #: :attr:`quality`, но пригодное для сравнения с порогом.
    #:
    #: 🔴 Лежит рядом с кодеком и глубиной по той же причине: решение «перекодировать файл
    #: целиком» принимается ДО первого сегмента, а кадр в этом решении - последнее слово
    #: (:attr:`torrcast.profile.Profile.recode_frame`). Без него запись, обошедшая отбор
    #: (``--release N``, ``--file N``), уезжала на ТВ и вставала там намертво.
    #:
    #: Ноль - кадр не спрашивали (записи прежних версий). Такая запись своё число
    #: получает на первом же продолжении (:func:`torrcast.cli._duration`) - тем же одним
    #: ffprobe, что и глубину цвета: без него 4К уезжало бы в поток с уровнем «4.1»
    #: (:func:`torrcast.recode.level_for`, TC-251).
    frame: int = 0
    #: Картинка в HDR по паспорту ffprobe (:attr:`torrcast.stream.Media.hdr`): её при
    #: сплошном перекоде надо ещё и привести к SDR (:attr:`Config.recode_tonemap`).
    #:
    #: ``false`` тут значит и «SDR», и «не спрашивали» - разницы нет: тонемап по
    #: умолчанию выключен, и запись прежней версии играется ровно как раньше.
    hdr: bool = False
    #: Битрейт видеодорожки по паспорту ffprobe, Мбит/с. Из него показ знает, сколько
    #: уедет на ТВ, ещё до первого упакованного сегмента - а значит и какие куски
    #: перекодировать. Читается тем же ffprobe, которым выбирается озвучка, и
    #: стоит ноль лишних запросов.
    #:
    #: ``0`` - ещё не спрашивали (запись прежней версии), **отрицательное** - спросили,
    #: и паспорт промолчал (mp4 без тегов mkvmerge). Разница нужна, чтобы молчаливый
    #: паспорт не стоил лишнего ffprobe на каждом запуске.
    vbps: float = 0.0
    #: Кодек видео по паспорту ffprobe (``h264``, ``hevc``). Из него показ знает, играть
    #: видео копией или перекодировать файл целиком (:data:`torrcast.stream.RECODE_CODECS`),
    #: и знает это ДО первого сегмента - решение принимается один раз на файл.
    #:
    #: Пусто - записи прежних версий и те, где паспорт не спрашивали: такие играются
    #: копией, как и раньше, а своё имя кодека получат на первом же обычном запуске.
    codec: str = ""
    #: Глубина цвета видео по паспорту ffprobe, бит (:func:`torrcast.stream.color_depth`).
    #:
    #: 🔴 Лежит рядом с кодеком, потому что кодека для решения НЕ ХВАТАЕТ: десятибитный
    #: H.264 (Hi10P, половина аниме-BDRip) зовётся тем же ``h264``, а приёмник его не
    #: декодирует - доигрывает буфер и встаёт в вечную петлю LOAD/BUFFERING. Решение
    #: «копия или перекод целиком» принимает :func:`torrcast.stream.recodes_whole` по
    #: паре «кодек + глубина», и одинаково у показа и у прогрева.
    #:
    #: ``0`` - не спрашивали (запись прежней версии). Такая запись своё число получает на
    #: первом же продолжении (:func:`torrcast.cli._duration`): одним ffprobe, один раз.
    depth: int = 0
    #: Сколько секунд фильма прогрето на диск (:mod:`torrcast.warm`). Пишет сторож показа,
    #: читает ``cast status`` - только затем и хранится: спросить живой показ из CLI
    #: нельзя, состояние тут единственный канал.
    #:
    #: Число относится к файлу, который играет СЕЙЧАС: прогретое досмотренного показа
    #: стирается с диска тем же выходом, а у следующей серии своё хранилище, - поэтому
    #: переход записи (:meth:`advance`, :meth:`jump`) сбрасывает поле в ноль, и своё
    #: честное число запись получает от сторожа нового показа.
    warm: float = 0.0
    #: Когда показ ПОГАС, стенное время (unix); ``0.0`` - на экране картинка. Пишет
    #: сторож показа, читает ``cast status`` - канал тот же, что у :attr:`warm`, и по той
    #: же причине: спросить живой показ из другого процесса нечем.
    #:
    #: 🔴 Живой юнит показом больше не считается. Пока этой отметки не было, `cast status`
    #: рапортовал «играю» всю темноту до потолка (:data:`torrcast.cli.REVIVE_LIMIT`) -
    #: четверть часа чёрного экрана, про который инструмент говорил, что всё хорошо.
    #:
    #: Время именно стенное, а не монотонное: читает его ДРУГОЙ процесс, а монотонное у
    #: двух процессов разное (:mod:`torrcast.timing`). Отметку ставит и снимает один
    #: писатель - сторож показа, - поэтому гонки на ней нет.
    #:
    #: 🔴 Смерть юнита её НЕ стирает, и это главное её свойство. Показ, умерший совсем,
    #: иначе неотличим от спокойно доигранного: позиции у него может не быть вовсе (кадра
    #: не показали - закладке взяться неоткуда), а журнал уходит вместе с юнитом. Замер
    #: 16-08-2026 на живой приставке: показ не дал ни кадра, юнит вышел, `cast status`
    #: ответил «ничего не играет» - ровно то же, что после конца фильма. На стыке серий,
    #: где консоли рядом нет, эта отметка - единственная дверь к правде о чёрном экране.
    #: Снимает её только следующий запуск (:func:`torrcast.playback._launch`).
    dark: float = 0.0
    #: Из-за чего погас показ, одной строкой: та же причина, что ушла человеку в консоль
    #: и в недельный след (:meth:`torrcast.cli._Revival._why`). Пусто - темноты нет.
    dark_why: str = ""
    season: int | None = None
    episode: int | None = None
    #: Серии раздачи по порядку: ``[сезон, серия, номер файла]``. Это и есть кэш
    #: выбора: стык серий и прыжок на s2e5 обходятся без Prowlarr и без вопросов.
    episodes: list[list[int]] = field(default_factory=list)
    #: Slug исходного запроса: по нему resume находит запись, не ходя в Prowlarr.
    query: str = ""
    #: Досмотрено. У фильма это конец истории, у сериала - повод взять следующую.
    done: bool = False
    updated: str = ""

    @property
    def ending(self) -> bool:
        """Дошёл ли показ до титров: позиция ≥ 95 % длительности.

        🔴 Мерка не «досмотрено», а «это был конец, а не обрыв», и порогом переключения
        она НЕ является. Серия доигрывает до самого конца, и следующую берёт естественный
        конец потока (:meth:`torrcast.commands.Watch.close`); доля же отвечает на другой
        вопрос - считать ли погасший экран титрами или аварией, которую надо поднимать
        (:meth:`torrcast.playback_revival._Revival.resurrect`). Поэтому она щедрая: сузишь
        её - и обычный конец начнёт читаться как смерть, а показ полезет воскрешать
        доигранное. Она же и страховка: приёмник, который залип на последнем куске или
        молча ушёл в IDLE, кончает сеанс не сам, а по терпению - и переход всё равно
        случается, потому что позиция к этому времени давно за долей.
        """
        return self.dur > 0 and self.pos >= self.dur * ENDING_RATIO

    @property
    def watched(self) -> bool:
        """Досмотрена ли сохранённая закладка: позиция >= 95 % всей картины.

        Неизвестная длительность не даёт права угадывать долю. Нулевая позиция также
        никогда сюда не попадает: IDLE-приёмник сообщает ноль уже после показа, а
        сторож сохраняет последнюю положительную позицию живого сеанса.
        """
        return self.dur > 0 and self.pos > 0 and self.pos >= self.dur * WATCHED_RATIO

    @property
    def resumable(self) -> bool:
        """Есть ли что продолжать: недосмотренный прогресс."""
        return self.pos > 0 and not self.done

    @property
    def serial(self) -> bool:
        """Правда ли это сериал: тип ``tv`` и в раздаче **несколько** серий.

        Одна серия в списке — это не сериал, а осечка разбора: так в состоянии осталась
        «Moana 2», которую ``x264`` в имени сделал s1e1. Парсер починен, но записи-то
        остались, и строки «Серии: серий 1: s1e1…s1e1» в выводе фильма быть не должно
        ни у кого. Настоящей раздаче с одной серией это ничего не стоит: переходить
        всё равно некуда.
        """
        return self.kind == "tv" and len(self.episodes) > 1

    @property
    def label(self) -> str:
        """Подпись серии ``s1e2``; у фильма — пусто."""
        if not self.serial or self.season is None or self.episode is None:
            return ""
        return f"s{self.season}e{self.episode}"

    @property
    def shown_as(self) -> str:
        """Как показ зовёт эту картину человеку: «Название» с подписью серии."""
        return f"«{self.title}»" + (f" {self.label}" if self.label else "")

    def where(self, season: int, episode: int) -> int:
        """Место серии в списке серий раздачи; ``-1`` — такой серии в раздаче нет."""
        for at, item in enumerate(self.episodes):
            if len(item) >= 2 and item[0] == season and item[1] == episode:
                return at
        return -1

    def jump(self, season: int, episode: int) -> Entry | None:
        """Прыжок на серию в пределах уже выбранной раздачи: ни поиска, ни вопросов.
        Серии в раздаче нет — ``None``, и цепочка честно идёт искать релиз нужного сезона.
        """
        at = self.where(season, episode)
        if at < 0:
            return None
        return self._go(at)

    def advance(self) -> Entry:
        """Что записать по достижении порога перехода: фильму — пометка «досмотрено» и
        сброс позиции (следующий ``cast`` начнёт сначала), сериалу — следующая серия
        раздачи с нуля, выбор релиза и дорожки при этом сохраняется. Серия была
        последней — «досмотрено» и для сериала: конец сезона или конец раздачи.

        Прогрев (``warm``) переход не переживает: досмотренному его стирает с диска
        сам выход показа, а прогретое следующей серии лежит в своём хранилище и своё
        число придёт от её сторожа - чужое здесь было бы враньём наружу. Отметка темноты
        (``dark``) не переживает по той же причине: она про экран, который погас на
        ПРОШЛОМ файле.
        """
        at = self.where(self.season or 0, self.episode or 0)
        if self.kind == "tv" and 0 <= at < len(self.episodes) - 1:
            return self._go(at + 1)
        return replace(self, pos=0.0, done=True, warm=0.0, dark=0.0, dark_why="")

    def _go(self, at: int) -> Entry:
        """Встать на серию номер ``at`` списка: новый файл, позиция, длительность,
        прогрев и отметка темноты с нуля - всё это относится к файлу, а файл теперь
        другой."""
        season, episode, file_idx = self.episodes[at][:3]
        return replace(
            self,
            season=season,
            episode=episode,
            file_idx=file_idx,
            pos=0.0,
            dur=0.0,
            done=False,
            warm=0.0,
            dark=0.0,
            dark_why="",
        )

    def touch(self) -> Entry:
        """Копия записи со свежей меткой времени."""
        return replace(self, updated=datetime.now(UTC).astimezone().isoformat())

    @classmethod
    def from_json(cls, data: dict[str, Any]) -> Entry:
        fields = {k: v for k, v in data.items() if k in cls.__dataclass_fields__}
        raw = fields.get("episodes")
        if isinstance(raw, list):  # битую строку списка серий лучше потерять, чем упасть
            fields["episodes"] = [
                [int(n) for n in item[:3]]
                for item in raw
                if isinstance(item, list) and len(item) >= 3
            ]
        return cls(**fields)
