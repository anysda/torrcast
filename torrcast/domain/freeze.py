"""Один подгруз: где встала картинка, сколько плёнки на нём потеряно и как долго он шёл."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class Freeze:
    """Подгруз, который зритель видел стоящей картинкой.

    ``pos`` - секунда фильма, на которой указатель встал; ``lost`` - сколько плёнки не
    проехало против часов, то есть сколько зритель простоял; ``secs`` - сколько подгруз
    длился по стене; ``total`` - сколько плёнки потеряно за показ целиком, вместе с этим.

    ``lost`` и ``secs`` - разные числа, и путать их нельзя: подгруз считается по опросам
    показа, и в его стену попадает вся длина опроса, на котором указатель снова пошёл.
    Простоял зритель ровно ``lost``.
    """

    pos: float
    lost: float
    secs: float
    total: float
