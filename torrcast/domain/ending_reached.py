"""Титры или обрыв: досмотрен ли поток к месту, где декодер закрыл вход."""

from __future__ import annotations

from torrcast.domain.entry import ENDING_RATIO


def ending_reached(pos: float, whole: float) -> bool:
    """Дошёл ли показ туда, где фильму и положено кончиться.

    🔴 Нулевой выход декодера сам по себе титрами не является: источник, пропавший под
    показом, тоже закрывает вход нулём - на 0:04:42 из 2:46:55. Пока такой ноль читался
    успехом, любая смерть источника на пятой минуте записывалась как «фильм доигран».

    Мерка взята та же, по которой показ отличает титры от аварии
    (:data:`torrcast.domain.entry.ENDING_RATIO`). Длину фильма приёмник знает не всегда:
    ``whole <= 0`` - судить не по чему, и работает прежнее правило, иначе конец фильма не
    опознавался бы вовсе.
    """
    return whole <= 0 or pos >= whole * ENDING_RATIO
