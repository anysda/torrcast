"""Титры или обрыв: дошёл ли показ туда, где картине и положено кончиться."""

from __future__ import annotations

from torrcast.domain.watch_ratios import ENDING_RATIO


def ending_reached(pos: float, whole: float) -> bool:
    """Дошёл ли показ до конца картины: место ``pos`` не ближе доли всей длины ``whole``.

    Это единственный ответ на такой вопрос во всём показе: его спрашивает и запись
    состояния (:attr:`torrcast.domain.entry.Entry.ending`), и приёмник, у которого декодер
    закрыл вход. Два правила на один вопрос превращают страховку конца в лотерею - какое
    спросят, такой ответ и будет, - поэтому правило тут одно.

    🔴 Мерка не «досмотрено», и порогом переключения серий она НЕ является. Серия доигрывает
    до самого конца, и следующую берёт естественный конец потока
    (:meth:`torrcast.usecases.watch.Watch.close`); доля же отвечает на другой вопрос -
    считать ли погасший экран титрами или аварией, которую надо поднимать
    (:meth:`torrcast.usecases.revive_playback._revival._Revival.resurrect`). Поэтому она
    щедрая: сузишь её - и обычный конец начнёт читаться как смерть, а показ полезет
    воскрешать доигранное. Она же и страховка: приёмник, который залип на последнем куске
    или молча ушёл в IDLE, кончает сеанс не сам, а по терпению - и переход всё равно
    случается, потому что место к этому времени давно за долей.

    🔴 Неизвестная длина (``whole <= 0``) - это «не конец». Доли считать не от чего, а
    угадать тут значит объявить конец ровно там, где показ начинается: длина приезжает от
    пробы медиатракта и на стыке серий обнуляется вместе с местом
    (:meth:`torrcast.domain.entry.Entry.advance`). Ошибка в эту сторону стоит хвоста и целой
    серии: запись ушла бы в «досмотрено», а страховка конца выстрелила бы по стоящему
    указателю ещё не начавшегося показа. Ошибка в другую сторону стоит перехода, и он
    дороже хвоста, - но платить его здесь не приходится, потому что переход держит конец
    потока, а не доля.
    """
    return whole > 0 and pos >= whole * ENDING_RATIO
