"""Сроки старта показа: бюджет до картинки, паузы и что говорится вслух."""

#: Прочее на пути юнита до картинки, у чего своего потолка нет: запуск transient-юнита,
#: чтение состояния, подъём раздачи. Секунды, но считать их нулём - врать себе.
START_SLACK = 10.0

#: Как часто юнит спрашивает приёмник между словом ``PLAYING`` и первым доказанным
#: кадром. Флажок «картинка» ставится только на круге опроса, и при обычном шаге (2 с)
#: строка «старт NN с» запаздывала за настоящим кадром на 1.9-3.8 с (медиана 2.5 с -
#: замер 20-08-2026 на живой приставке). Учащение живёт ровно в этом окне: до слова
#: ``PLAYING`` кадру взяться неоткуда, а после первого кадра шаг снова 2 с.
FIRST_FRAME_POLL = 0.5


#: Как часто показ пишет в журнал, что видит приёмник: позиция и общее время -
#: единственное доказательство того, что на экране есть таймлайн.
SAY_SECONDS = 30.0

#: Сколько терпим паузу на пульте, прежде чем погасить упаковку: дальше
#: сегменты копились бы в tmpfs впустую - приёмник их не забирает.
PAUSE_SECONDS = 60.0

#: Пауза длиннее этого - показ считается оконченным: юнит гаснет и не держит раздачу.
PAUSE_LIMIT = 3600.0
