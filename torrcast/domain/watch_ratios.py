"""Две доли длительности, по которым показ судит о конце: досмотрено и титры.

Отвечают они на РАЗНЫЕ вопросы и живут вместе затем, чтобы разъехаться не могли: доля
титров обязана быть не строже доли «досмотрено». Спрашивают их запись состояния
(:class:`torrcast.domain.entry.Entry`) и конец потока
(:func:`torrcast.domain.ending_reached.ending_reached`).
"""

from __future__ import annotations

#: Доля длительности, после которой сохранённая закладка считается досмотренной.
WATCHED_RATIO = 0.95

#: Доля длительности, после которой конец показа читается как титры, а не как авария.
#: Мерка щедрая намеренно: ею показ решает, воскрешать ли погасший экран, и сузить её
#: значит начать воскрешать доигранное. Переключением она не заведует: серия доигрывает
#: до конца потока, а доля отвечает только на вопрос «это был конец или обрыв».
ENDING_RATIO = 0.95
