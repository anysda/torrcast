"""Точка индекса ``Cues`` целиком: опорный кадр, место его блока и время как в файле."""

from __future__ import annotations

from typing import NamedTuple

from torrcast.domain.frames.keymap.point import Point


class Cue(NamedTuple):
    """Опорный кадр карты и смещение его блока от начала данных кластера.

    ``inside`` (``CueRelativePosition``) наружу не уезжает: карте нужен кластер, потому
    что рой греется байтами от начала файла и о матрёшке не знает. Внутрь кластера
    смотрит только проверка честности индекса - ей нужен ТОТ САМЫЙ блок, который назвала
    точка, а не первый попавшийся видеоблок кластера.

    Ноль значит «муксер места не назвал»: элемент необязателен по списку EBML. Настоящим
    смещением ноль быть не может - в начале данных кластера стоит ``Timestamp``, и любой
    блок лежит дальше него.

    ``tick`` - ``CueTime`` как он лежит в файле, в единицах ``TimestampScale``. По нему
    проверка находит названный блок, когда ``inside`` ноль: время блока - это метка
    кластера плюс метка блока, в тех же единицах, и сравнивается точно, без секунд.
    """

    point: Point
    inside: int
    tick: int = 0
