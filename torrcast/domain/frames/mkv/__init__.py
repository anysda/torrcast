"""Карта опорных кадров mkv: индекс ``Cues``.

Общее для всех контейнеров — в :mod:`torrcast.domain.frames.keymap`, вход - в
:func:`torrcast.adapters.frames.keyframes.keyframes`. Здесь только матрёшка EBML.

В mkv есть собственный индекс перемотки — элемент ``Cues``. В нём для каждого опорного
кадра лежат время и позиция кластера в байтах, то есть готовая карта GOP: длительность —
разница времён, вес — разница позиций. Лежит он в хвосте файла, а его адрес — в
``SeekHead`` в голове.

⚠️ «Для каждого опорного кадра» — это обещание спецификации, а не свойство файла. Муксер
вправе поставить точку на каждый кластер, а флаг опорности — на каждый видеоблок, и тогда
индекс врёт: замер TC-639 на живом ремуксе дал 8065 точек через 1.251 с при 830 настоящих
IDR на весь фильм. Поэтому индекс проверяется содержимым кадра
(:mod:`torrcast.domain.frames.mkv.key_frame`), а непроверенному верить нельзя.

Замер цены: «Моана 2» (3.4 ГБ, 1119 опорных кадров) — 0.45 МБ и 4.3 с холодным роем,
«Моана» 2016 (4.5 ГБ, 2830 опорных) — 2.1 с; сверху три пробы честности раз на файл.
"""

