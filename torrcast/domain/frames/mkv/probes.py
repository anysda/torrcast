"""Какие точки индекса ``Cues`` проверять на опорность: соседняя пара, а не доли ленты.

Проба стоит Range-запроса к рою на старте показа - замер на живой раздаче в 18 ГБ дал
0.74 с медианы на пробу, - поэтому проб мало, и место каждой обязано что-то доказывать.

Фиксированные доли ленты (середина, четверти) доказывают мало. Врун, который ставит
точку на каждый кадр, оставляет настоящие опорные кадры стоять через ровный шаг, и шаг
этот делит доли нацело: замер на собранном файле - 2880 точек при шаге 48, доли 1440,
720 и 2160 делятся на 48, все три пробы садятся ровно на настоящие кадры, и индекс, у
которого 719 точек доказанно не опорные, проходит целиком. Добавить долей не помогает:
под любой их набор находится шаг, который его делит.

Соседняя пара обходится без удачи. Если настоящий опорный кадр стоит через каждые ``s``
точек, то в любом окне из ``s`` подряд идущих точек настоящая ровно одна - значит из
ДВУХ СОСЕДНИХ хотя бы одна призрак, при любом ``s`` от двух и при любом сдвиге. А
``s = 1`` - это «настоящая каждая точка», то есть честный индекс. Поэтому проб две, а не
три: старт стал на один запрос дешевле, а выравненный врун ловится не удачей, а счётом.
"""

from __future__ import annotations

from typing import Final

from torrcast.domain.frames.mkv.cue import Cue
from torrcast.domain.frames.mkv.key_frame import BLOCK_BYTES

#: Меньше этого числа точек проверять незачем: такую карту всё равно отвергнет сетка.
ENOUGH: Final = 4

#: Насколько глубоко в кластер проба видит. Окно у неё одно и начинается с начала
#: кластера (:data:`~torrcast.domain.frames.mkv.key_frame.BLOCK_BYTES`), поэтому блок,
#: названный дальше окна, - это ответ «не разобрать», то есть запрос к рою впустую.
#: Замер на собранном файле: точка с местом 127478 разобралась, а с местом 136034 - нет.
#: Запас снят с края окна на заголовок блока и служебные NAL перед срезом кадра.
REACH: Final = BLOCK_BYTES - (8 << 10)


def probes(cues: list[Cue]) -> list[Cue]:
    """Точки одной дорожки, которые стоит спросить о содержимом кадра, - по порядку.

    Пара берётся от середины ленты и сдвигается к краю ровно настолько, чтобы обе её
    точки называли РАЗНЫЕ блоки и обе лежали в досягаемости пробы (:data:`REACH`).
    Место блока внутри кластера лежит в самом индексе, так что сдвиг не стоит ни одного
    запроса, а вот проба по недосягаемому блоку стоила бы запроса и не ответила бы
    ничего: у собранного вруна так молчат 2101 точка из 2880.

    Пусто - когда точек меньше :data:`ENOUGH`.
    """
    if len(cues) < ENOUGH:
        return []
    row = sorted(cues)
    middle = min(len(row) - 2, len(row) // 2)
    order = sorted(range(len(row) - 1), key=lambda k: abs(k - middle))
    k = next((k for k in order if _apart(row[k], row[k + 1])), middle)
    return [row[k], row[k + 1]]


def _apart(one: Cue, other: Cue) -> bool:
    """Пара и правда спрашивает два разных кадра, и оба видны пробе в её окне."""
    if one.inside >= REACH or other.inside >= REACH:
        return False
    return one.point.offset != other.point.offset or one.inside != other.inside
