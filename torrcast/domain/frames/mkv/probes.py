"""Какие точки индекса ``Cues`` проверять на опорность: соседняя пара, а не доли ленты.

Проба стоит Range-запроса к рою на старте показа - замер на живой раздаче в 18 ГБ дал
0.74 с медианы на пробу, - поэтому проб мало, и место каждой обязано что-то доказывать.

Фиксированные доли ленты (середина, четверти) доказывают мало. Врун, который ставит
точку на каждый кадр, оставляет настоящие опорные кадры стоять через ровный шаг, и шаг
этот делит доли нацело: замер на собранном файле - 2880 точек при шаге 48, доли 1440,
720 и 2160 делятся на 48, все три пробы садятся ровно на настоящие кадры, и индекс, у
которого 719 точек доказанно не опорные, проходит целиком. Добавить долей не помогает:
под любой их набор находится шаг, который его делит.

Соседняя пара обходится без удачи. Если настоящий опорный кадр стоит через каждые ``s``
точек, то в любом окне из ``s`` подряд идущих точек настоящая ровно одна - значит из
ДВУХ СОСЕДНИХ хотя бы одна призрак, при любом ``s`` от двух и при любом сдвиге. А
``s = 1`` - это «настоящая каждая точка», то есть честный индекс. Поэтому проб две, а не
три: старт стал на один запрос дешевле, а выравненный врун ловится не удачей, а счётом.

🔴 Довод про пару не зависит от того, ГДЕ она стоит, - но ловит он только вруна, который
врёт одинаково по всей ленте. Файл, чей индекс честен в голове и врёт дальше, одна пара в
голове пропускает, а сверка карты с прогоном (:func:`~torrcast.adapters.stream_pack.grid_for.
grid_for`) смотрит туда же, в первую границу сетки. Поэтому пар две: в начале ленты и у
самого индекса. Первая читает байты, которые первый сегмент читает всё равно
(:data:`~torrcast.domain.warm_open.HEAD_WARM`). Вторая берётся из кластеров рядом с
индексом (адрес его известен из ``SeekHead``), то есть из места, которое рой только что
отдал вместе с индексом. На всех четырёх файлах замера 30-09 индекс лежит в конце файла,
и эта пара - в 0.2-1.1 МБ перед ним: медианы по холодной раздаче 0.01-0.43 с против
0.51-0.89 с у прежней пары в середине.

🔴 Место второй пары задаёт индекс, а не лента: если муксер положил индекс в голову, пара
у индекса совпадает с первой, и хвост не читается вовсе. Заход в дальний хвост холодной
раздачи держал бы старт до отказа роя (до 120 с), а показу эти байты не нужны. Цена
названа: у такого файла враньё только в хвосте пробой не ловится, как и враньё только
посередине у файла, честного в голове и у индекса. За них пришлось бы платить заходом
в место, которое показу не нужно.
"""

from __future__ import annotations

from typing import Final

from torrcast.domain.frames.mkv.cue import Cue
from torrcast.domain.frames.mkv.key_frame import BLOCK_BYTES

#: Меньше этого числа точек проверять незачем: такую карту всё равно отвергнет сетка.
ENOUGH: Final = 4

#: Насколько глубоко в кластер проба видит. Окно у неё одно и начинается с начала
#: кластера (:data:`~torrcast.domain.frames.mkv.key_frame.BLOCK_BYTES`), поэтому блок,
#: названный дальше окна, - это ответ «не разобрать», то есть запрос к рою впустую.
#: Замер на собранном файле: точка с местом 127478 разобралась, а с местом 136034 - нет.
#: Запас снят с края окна на заголовок блока и служебные NAL перед срезом кадра.
REACH: Final = BLOCK_BYTES - (8 << 10)


def probes(cues: list[Cue], near: int) -> list[Cue]:
    """Точки одной дорожки, которые стоит спросить о содержимом кадра, - по порядку.

    Две соседние пары, у которых обе точки называют РАЗНЫЕ блоки и обе лежат в
    досягаемости пробы (:data:`REACH`): самая ранняя и та, что ближе всех к индексу -
    ``near``, абсолютный адрес ``Cues`` в файле. Ранняя идёт первой: её байты нужны
    показу и так, а врун, пойманный на ней, не стоит второго захода. Место блока
    внутри кластера лежит в самом индексе, так что пропуск не стоит ни одного запроса, а
    вот проба по недосягаемому блоку стоила бы запроса и не ответила бы ничего: у
    собранного вруна так молчат 2101 точка из 2880. Точка, попавшая в обе пары на
    короткой ленте, спрашивается один раз.

    Пусто - когда точек меньше :data:`ENOUGH`.
    """
    if len(cues) < ENOUGH:
        return []
    row = sorted(cues)
    fit = [k for k in range(len(row) - 1) if _apart(row[k], row[k + 1])] or [0]
    last = min(fit, key=lambda k: abs(row[k].point.offset - near))
    picked = [row[fit[0]], row[fit[0] + 1], row[last], row[last + 1]]
    return list(dict.fromkeys(picked))


def _apart(one: Cue, other: Cue) -> bool:
    """Пара и правда спрашивает два разных кадра, и оба видны пробе в её окне."""
    if one.inside >= REACH or other.inside >= REACH:
        return False
    return one.point.offset != other.point.offset or one.inside != other.inside
