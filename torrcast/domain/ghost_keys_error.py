"""Ошибка GhostKeysError; используется публичным API."""

from __future__ import annotations

from torrcast.domain.frames.keymap.key_map import KeyMap
from torrcast.domain.infra_error import InfraError


class GhostKeysError(InfraError):
    """Индекс контейнера разобран целиком, но опорные кадры в нём нарисованы. Код выхода 2.

    Отдельное имя нужно ровно одному решению - что из отвергнутой карты можно ОСТАВИТЬ.
    Прочие отказы разбора говорят «карты нет вовсе»: индекса в файле не нашлось, по
    адресу лежит не Cues, точек в нём ноль, контейнер незнакомый. Здесь же карта снята и
    разобрана до последней точки, а ложным в ней оказалось ровно одно утверждение -
    «здесь стоит опорный кадр». Пара «время - смещение» при этом честная: это позиции
    кластеров контейнера, и на «Матрице» 1999 (18.2 ГБ, тот самый врущий индекс) её
    проверили живым чтением - **17 Range-проб вразброс из 17** попали в настоящий кластер
    Matroska, метка каждого сошлась с картой в пределах кадра (0.042-0.125 с).

    Поэтому разобранная карта едет вместе с приговором (:attr:`drawn`): по ней нельзя
    РЕЗАТЬ, но можно ВЗВЕШИВАТЬ, а без веса ровная сетка остаётся без профиля тяжести,
    и каждый её кусок уходит ужатием на месте
    (:func:`torrcast.usecases.feed_pack.feed_shrink._shrink`), посреди которого упаковка
    замирает.
    """

    def __init__(self, message: str, drawn: KeyMap) -> None:
        super().__init__(message)
        #: Разобранный индекс целиком - тот самый, чьи опорные кадры признаны нарисованными.
        #: Наружу из него идёт только байтовый указатель (:func:`refuse_keys`).
        self.drawn = drawn
