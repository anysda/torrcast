"""Оценивает вес видеодорожки по размеру всего медиафайла."""


def estimated_video_mbit(size: int, duration: float) -> float:
    """Верхняя оценка среднего веса видео, Мбит/с, по контейнеру целиком.

    Звук и служебные данные отдельно неизвестны, поэтому входят в оценку. Для выбора
    тяжёлых кусков это безопасная ошибка вверх: кодировщик может взять лишний кусок,
    но не останется лежать из-за отсутствующего числа в паспорте.
    """
    return size * 8 / duration / 1_000_000.0 if size > 0 and duration > 0 else 0.0
