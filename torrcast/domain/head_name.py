"""Имя заголовка того прогона, которым сделана картинка куска этого места.

Кладёт его рядом с куском выкладка кодировщика, а приставляет к куску выкладка показа
(:func:`torrcast.adapters.stream_pack._own_head._own_head`).
"""

from torrcast.domain.hls_settings import HEAD_PREFIX


def head_name(slot: int, suffix: str = ".mp4") -> str:
    """Как зовётся заголовок этого места: приставка, слот и расширение.

    Начинается **не** с ``v``, и это не вкус: каталог прогона и каталог перекода
    перебираются глобом ``v*``, и заголовок не должен попасть в них ни как готовый
    сегмент, ни как признак «следующий открыт, прошлый дописан».

    ``suffix`` доводом, потому что имён у заголовка три и они про разное: ``.mp4`` -
    сам заголовок, лежащий рядом с куском; расширение контейнера - кусок, которому этот
    заголовок уже приставлен впереди; :data:`~torrcast.domain.hls_settings.HEAD_SENT` -
    запись выкладки о том, с каким заголовком место УШЛО наружу.
    """
    return f"{HEAD_PREFIX}{slot}{suffix}"
