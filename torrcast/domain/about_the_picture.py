"""Правило about_the_picture; используют модели и фасады разбора имён."""

from __future__ import annotations

import re
from typing import Final

#: Хвосты, за которыми стоит работа О КАРТИНЕ, а не сама картина: дополнительные
#: материалы, история создания, пропавшие фрагменты. Список - те самые примеры, ради
#: которых закрыт `_EDITION_TAILS`, и назначение у него встречное: там перечислено, что
#: снимать МОЖНО, здесь - чем две стороны отличаются НАСТОЯЩИМ образом.
#:
#: Нужен он ровно межвидовому правилу склейки: оно спрашивает оригинал, а выдача пишет
#: под бонусом оригинал самой картины («Евангелион Нового Поколения: дополнительные
#: материалы / Neon Genesis Evangelion [Bonus]» 1995 года при сериале «Евангелион /
#: Neon Genesis Evangelion» того же года). Отличает их только русское имя, и без этого
#: списка бонусный DVDRip уезжал бы в пул сериала.
_ABOUT_PICTURE_RE: Final = re.compile(
    "\\bдополнительн\\w*\\s+материал\\w*|\\bдополнение\\b|\\bистори\\w*\\s+создания"
    "|\\bпропавш\\w*\\s+фрагмент\\w*|\\bпрезентаци\\w*\\s+с\\b",
    re.IGNORECASE,
)


def _about_the_picture(title: str) -> bool:
    """Названа ли этим именем работа О КАРТИНЕ, а не сама картина.

    Спрашивает межвидовое правило склейки, и спрашивает по русскому имени нарочно:
    оригинал у бонусной раздачи стоит от самой картины и стороны не разводит вовсе
    («Евангелион Нового Поколения: дополнительные материалы / Neon Genesis Evangelion
    [Bonus]» 1995 года при сериале «Евангелион / Neon Genesis Evangelion» того же года).

    🔴 Список закрытый, как и у :func:`~torrcast.domain.editionless._editionless`, и это
    его встречная половина: там перечислено, какой хвост снять МОЖНО, здесь - каким
    хвостом две стороны отличаются по-настоящему. Правило «выкинуть всё после точки»
    запрещено обоим: за таким хвостом стоит другая работа с другим хронометражом.
    """
    return bool(_ABOUT_PICTURE_RE.search(title))


__all__ = ["_about_the_picture"]
