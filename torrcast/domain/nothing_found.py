"""Чем считать пустой поиск, когда часть каталога до нас не дошла."""

from __future__ import annotations

from collections.abc import Sequence

from torrcast.domain.catalogs.phrase import phrase
from torrcast.domain.not_found_error import NotFoundError


def nothing_found(
    query: str,
    banned: Sequence[str] = (),
    refused: Sequence[str] = (),
    silent: Sequence[str] = (),
) -> NotFoundError:
    """Отказ «ничего не нашлось», называющий выпавшие звенья каталога (TC-259, TC-291).

    «Ничего не нашлось» - утверждение о КАТАЛОГЕ, и делать его, не спросив половину
    каталога, нельзя: замер выдачи даёт 41% строк на Knaben и 56% на RuTor, и это
    разные половины. Поэтому выпавшее звено называется прямо в отказе: и бан (``banned``),
    и спрятанный за ``200 []`` отказ (``refused``, TC-291), и молчание в свой бюджет
    (``silent``). Человек должен знать, что искали урезанным каталогом, - иначе «нет
    такого фильма» звучит приговором каталогу.

    🔴 TC-291 закрывает окно ПЕРЕД баном. Бан - это уже вторая беда; первая в том, что на
    самый первый отказ источника Prowlarr отвечает нам ``200 []`` - ровно тем же, чем
    отвечает на честное «такого фильма нет». Замер на живом стенде: источник отвечает
    отказом соединения, первый запрос - ``HTTP 200, строк 0``, и лишь со второго приходит
    400 «выбранные индексеры недоступны». То есть соврать хватает одного запроса - а
    живьём этого хватило, чтобы на лежащем звене сказать «ничего не нашлось» про полный
    каталог.

    🔴 TC-510. Отказом инфры («искать было нечем») пустота тут не становится НИКОГДА, и
    это не смягчение TC-259/TC-291, а их же мысль, доведённая до конца. Отказ инфры
    обрывает поиск целиком, и вместе с ним пропадают и добор второй строкой, и уже
    найденный пул. Пока нам отвечал хоть кто-то, «нечем искать» просто неправда - искать
    было чем, только урезанным каталогом. Замер офлайн по сохранённым выдачам (10
    запросов, молчит один Knaben, остальные живы): 6 запросов из 10 кончались кодом 2 и
    пустым экраном, причём у четырёх из них пул первого круга был непуст (17, 6, 15 и 43
    раздачи) - его выбрасывал отказ ВТОРОГО круга.
    """
    gone = "; ".join(
        phrase(key, names=", ".join(names))
        for key, names in (
            ("hunt.banned", banned),
            ("hunt.refused", refused),
            ("hunt.silent", silent),
        )
        if names
    )
    if gone:
        return NotFoundError(phrase("hunt.nothing_cut", query=query, gone=gone))
    return NotFoundError(phrase("hunt.nothing", query=query))


__all__ = ["nothing_found"]
