"""Пороговые значения чистых правил ранжирования релизов.

Числа тут не круглые и не на глаз: у каждого в комментарии стоит замер, которым его
поставили. Читают их правила ранжирования (:mod:`torrcast.usecases.rank`) и разбор
аргументов; менять их без нового замера нельзя.
"""

import re
from typing import Final

#: Сколько строк таблицы релизов показываем: ниже начинаются раздачи без сидов.
TABLE_LIMIT: Final = 12
#: ``--voice`` без номера: показать меню озвучек. Ноль тут свободен - дорожки для
#: человека нумеруются с единицы.
VOICE_MENU: Final = 0
#: Сколько ждём ПЕРВОГО КОНТАКТА роя, прежде чем счесть раздачу пустой, секунды.
#:
#: Тот же приём, что :data:`SWARM_GRACE`, но фазой раньше - на метаданных
#: (:func:`torrcast.domain.swarm_alive.swarm_alive`). До сих пор эта фаза стоила одинаково и
#: медленному рою, и пустому: полные :data:`META_BUDGET` на релиз. В замере каталога на 225 запросах
#: таких запросов 6 - там, где в каталоге правда 0-4 сида, - и человек получал честный отказ, но по
#: двадцать секунд молчания на каждый мёртвый релиз.
#:
#: 🔴 Отсрочка не про сиды из выдачи: те врут в обе стороны, и отказывать по их обещанию
#: нельзя. Спрашивается ФАКТ - насчитала ли служба хоть один контакт. Раздача, у которой
#: контакты есть, ждёт весь :data:`META_BUDGET` ровно как ждала: медленный рой - это рой,
#: а не пустота. Раздача, метаданные которой приехали за доли секунды, до проверки не
#: доходит вовсе.
#:
#: 🔴 Шесть секунд - это середина разброса, а не его край, и цена такого приговора
#: замерена: 140 раздач сохранённого каталога, поднятых по шесть раз каждая (840
#: подъёмов), отдают первый контакт за 4.3 с в половине случаев, за 6.0 с в трёх
#: четвертях и за 7.6 с в девяти десятых. Отсюда два следствия, и оба надо держать в
#: голове, читая приговор «рой пуст»: он неустойчив (29% соседних прогонов одной и той же
#: раздачи расходятся) и в 73% случаев ложен - метаданные приезжают в обычный
#: :data:`META_BUDGET`. Ошибка в эту сторону стоит одного места в очереди: следующий релиз
#: всё равно спрашивается, а осечка роя попытку не жжёт (:data:`MAX_TRIES`).
#:
#: 🔴 TC-300. Ровно поэтому отсрочка снимается там, где очереди больше нет: когда
#: промолчали все до одной, её ошибка стоит уже не места, а показа, и последний спрос
#: идёт по полному бюджету раздачи (:meth:`Bench._recheck`).
#:
#: 🔴 TC-387. И по той же причине она длиннее там, где очередь ниже ступенью
#: (:data:`STEP_GRACE`).
PEER_GRACE: Final = 6.0
#: Сколько ждём первого контакта у раздачи, чья осечка стоит СТУПЕНИ ЧЁТКОСТИ, секунды.
#:
#: 🔴 TC-387. Отсрочка назначается ценой ошибки (:func:`peer_grace`), и у релиза, под
#: которым в очереди стоит ступень ниже, эта цена - обещанные 1080p: человек видит 720p
#: там, где в выдаче был живой 1080p, и узнаёт об этом только глазами.
#:
#: Десять секунд - это край того же разброса, что описан у :data:`PEER_GRACE`, и цена
#: перехода замерена на той же ленте подъёмов: соседние прогоны одной раздачи расходятся
#: в 5% случаев вместо 29%, а ложным оказывается каждый пятый приговор вместо трёх из
#: четырёх (18 из 86 против 191 из 262). На запросах, где ступень решает ровно этот
#: приговор, качество скачет между прогонами у 11% картин вместо 74%.
#:
#: Платят за это раздачи, у которых роя правда нет: их в замере 5 из 140, и каждая стоит
#: четырёх лишних секунд. Идут они не в пустоту: запасной релиз эти секунды греется рядом
#: (:data:`PREWARM_SPARE`), поэтому спуск ступенью ниже после них стоит уже не подъёма
#: раздачи, а разницы между двумя ffprobe - в замере это 0.9 с медианой и 3.6 с в худшем
#: случае. Дальше десятой секунды разброс кончается: двенадцатая вернула бы ещё 12 ложных
#: приговоров из 262, двадцатая - ещё 5 поверх них, и обе секунды уже дороже цели старта.
STEP_GRACE: Final = 10.0
#: Ниже этой высоты кадра HD уже не назовёшь. Имя раздачи о разрешении молчит чаще, чем
#: врёт (у «Моаны 2» - в 5 именах из 11), поэтому «имя молчало, а внутри SD» - такой же
#: повод посмотреть на соседа, как и прямое враньё в имени.
HD_HEIGHT: Final = 720
#: Ступень, ради которой затеян отбор: честный 1080p. Имя, называющее её (или выше),
#: поднимается над названным 720p - но только если раздача жива (:func:`is_full_hd`).
FULL_HEIGHT: Final = 1080
#: Насколько живым обязан быть названный 1080p, чтобы обойти 720p: доля от сидов
#: сильнейшего соседа, с которым он спорит за верх (:func:`rank_releases` считает
#: максимум среди равных по ступеням выше). Не абсолютное число, потому что живость
#: у картин разная: у новинки сосед набирает сотни сидов, у кино 1994 года - четыре
#: десятка, и «20 сидов» означало бы в этих двух пулах совершенно разное. Замер по
#: живой выдаче: у «Мастера и Маргариты» 1080p держит 0.40 от соперника (59 против 146)
#: и обязан выиграть, у «Зелёной мили» - 0.10 (4 против 38), у «Форреста Гампа» - 0.05
#: (2 против 41), и эти обязаны проиграть: 15 ГБ на двух сидах - это не 1080p, а подгрузы.
FULL_HD_LIVENESS: Final = 0.25
#: Насколько живым обязан быть именной кандидат, чтобы ворота отбора остались закрытыми:
#: доля от сидов самой обсиженной раздачи картины. Доля, а не абсолютное число, ровно по
#: той же причине, что и у :data:`FULL_HD_LIVENESS`.
#:
#: Замер по живой выдаче «наруто»: у картины «Наруто» (2002) именных кандидатов два - на
#: 3 и на 1 сид, - а полный сериал «[E220 of 220]» с 91 сидом в кандидаты не проходил
#: вовсе. 3/91 = 0.03: живым такой кандидат не назовёшь, и выбор между ним и ничем - это
#: выбор между подгрузами и подгрузами. У фильмов с богатой выдачей доля лидера-кандидата
#: заметно выше порога, и ворота там не открываются никогда.
GATE_LIVENESS: Final = 0.25
#: Насколько живым обязан быть релиз с обещанной русской дорожкой, чтобы обойти по звуку
#: более обсиженного соседа (:func:`sound_step`). Порог ниже, чем у HD (0.10 против 0.25),
#: и это не небрежность: «1080p вместо 720p» - оттенок, а «по-русски вместо по-японски» -
#: разница между «посмотрел» и «не посмотрел», и платить за неё сидами можно дороже.
#: Замер по живой выдаче: у «Врат Штейна» русский BDRip 1080p держит 86 сидов против 397
#: у самого живого «[Anime Time]» - 0.22, и обязан выиграть; у «Наруто: Ураганные
#: хроники» русская раздача имеет НОЛЬ сидов против трёх - 0.0, и обязана проиграть,
#: потому что мёртвый рой это не показ ни на каком языке.
SOUND_LIVENESS: Final = 0.10
#: **Сколько сидов делают картину играбельной** - порог живости части франшизы
#: (:func:`alive_numbers`). Здесь, в отличие от трёх порогов выше, доля от лидера не
#: годится, и это не оттенок, а разные вопросы. Те три - про РАЗМЕН внутри одной картины
#: («1080p вместо 720p», «по-русски вместо по-японски»), и цена размена честно меряется
#: в сидах соседа по тому же пулу. А этот - про то, есть ли у картины чем играть вообще,
#: и ответ на него сосед не даёт: рой чужой части не качает и не тормозит эту.
#:
#: Доля тут стояла и обходилась дороже всего: свежая часть с сотнями сидов объявляла
#: мёртвой всю классику франшизы, и дефолт садился на картину, которую человек не звал
#: («мумия» - 2026 год вместо 1999, десять прогонов из десяти; то же у «хищника»,
#: «голодных игр», «дюны», «безумного макса», «джуманджи»).
#:
#: Пять - это нижняя граница между двумя замеренными случаями, а не число из воздуха:
#: у «Тачек 2» годным верхом остался HDRip «фильм о фильме» на 1 сид, и играть им
#: нельзя; у «Мальтийского сокола» 1931 года 16 сид - и он играет. Точнее порог поставит
#: только замер по доехавшим показам; пока он стоит там, где ошибка дешевле всего -
#: лишняя живая часть в дефолте видна человеку в меню, а лишняя мёртвая стоит вечера.
ALIVE_SEEDERS: Final = 5
#: Насколько подтверждённая высота вправе отставать от заявленной. 0.9 - это про обрезку
#: чёрных полей: у 1080p-широкоформатника реальная высота 800-816, и релиз честен. А
#: 574 против 1080 - это уже другая ступень лестницы, а не кадрирование.
HONEST_RATIO: Final = 0.9
#: Битрейт, ниже которого раздача без единого маркера качества в имени - это SD-рип
#: (MPEG-4 в .avi), а не скромный 1080p. Порог выбран по замеру, а не на глаз: из 264
#: раздач живой выдачи («моана», «тачки», «матрица», «интерстеллар», «аватар») удалось
#: достать .torrent и заглянуть внутрь у 36. Все восемь .avi в этой выборке не называют
#: ни разрешения, ни кодека, и у пяти полнометражных потолок вышел 3.5 Мбит/с; ближайший
#: снизу подтверждённый .mkv с такой же безымянной шапкой - 5.4 Мбит/с. Порог поставлен
#: посередине этого зазора.
SD_BITRATE: Final = 4.0
#: Насколько глубоко ступень потолка приёмника (:func:`fits_receiver`) вправе облегчить
#: раздачу: доля от битрейта самого тяжёлого её соседа по группе, которого она сместит.
#:
#: Доля, а не Мбит/с, и это показано замером, а не выбрано на вкус. Абсолютное число тут
#: не разделяет честное и кашу ни плоское, ни посчитанное от кадра: на корпусе из 100
#: запросов честный 1080p аниме лежит на 0.70-1.03 Мбит/с, а названный 1080p игрового
#: кино - на 1.03-1.91, и эти два множества перекрываются. Порог между ними невозможен:
#: любое число либо топит законную раздачу, либо пропускает кашу. Доля этой беды не
#: знает: числитель и знаменатель - одна и та же картина, снятая одним способом, и
#: жанр из отношения сокращается сам.
#:
#: Цена плоского пола замерена: 3.5 Мбит/с отнимают предпочтение у 611 раздач из 995,
#: доля - у 13. Пол, посчитанный от потолка приёмника, отпадает по другой причине: он
#: судит одну и ту же раздачу по-разному на разных приёмниках (785 из 1447 против
#: 273 из 995), а качество картинки от приёмника не зависит.
#:
#: 0.13 - середина замеренного зазора, а не его край. Из 175 разменов, которые ступень
#: может сделать на осторожном приёмнике, глубже 0.102 лежат 13, и все до одного - рип
#: на 0.95-2.37 Мбит/с вместо источника на 16.7-23.2. Между 0.102 и 0.160 нет ни одного,
#: и первый законный размен над зазором - 1080p на 3.66 Мбит/с вместо 22.91. Порог
#: держится на всём зазоре: с 0.11 по 0.15 отнятых предпочтений ровно 13, ни одним
#: больше. Самый глубокий законный размен корпуса - 0.200 (4.91 Мбит/с вместо 24.60),
#: у аниме - 0.218 (3.54 вместо 16.22), и обе стороны зазора от порога далеко.
TRADE_FLOOR: Final = 0.13
#: Битрейт, ниже которого раздача с пометкой приложения
#: (:attr:`~torrcast.domain.release.Release.extras`) самой картиной быть уже не может: при
#: длительности, которую назвала справка, столько весит ролик, а не фильм. Порог взят по сохранённым
#: выдачам, а не на глаз: у «Тачек 2» (1 ч 46 мин) «фильм о фильме» весит 0.4 ГБ - это 0.5 Мбит/с, у
#: «Кунг-фу Панды» трейлер 0.12 ГБ, у «Робокопа» интервью 0.05 ГБ; самый скромный ЦЕЛЬНЫЙ рип тех же
#: картин в тех же пулах - 0.7-1.5 ГБ, то есть 0.8-1.7 Мбит/с. Порог стоит выше этого зазора
#: нарочно: имя уже сказало «это приложение», и цена ошибки тут несимметрична - лишний отсев стоит
#: одной раздачи из очереди, а пропуск стоит подменённой картины на экране.
EXTRAS_MBIT: Final = 2.0
#: Сколько серий в сезоне считаем МИНИМУМОМ, когда имя пака называет сезоны, но не серии
#: (:func:`pack_mbit`). Число выбрано снизу нарочно: делим размер на заведомо МЕНЬШЕЕ
#: число серий, значит получаем ПОТОЛОК битрейта серии, а не выдуманную оценку. Сезон
#: короче шести серий бывает (британские мини-сериалы), и такому паку потолок достанется
#: завышенный - то есть в сторону «не трогать», а не в сторону ложного понижения.
SEASON_EPISODES: Final = 6
#: Признаки образа диска в имени раздачи - внутри VOB/BDMV, а не один файл.
DISC_RE: Final = re.compile(
    r"\b(?:video_?ts|bdmv|dvd[- ]?video|dvd[59]|iso|blu-?ray\s*(?:disc|cee)|avc\+?\s*iso)\b",
    re.IGNORECASE,
)
