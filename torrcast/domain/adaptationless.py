"""Правило adaptationless; используют модели и фасады разбора имён."""

from __future__ import annotations

from torrcast.domain._name_data.data_2 import _ADAPTATION_WORDS


def _adaptationless(key: str) -> str:
    """Ключ без слова-приметы экранизации: «X The Animation» и «X» - одна работа.

    🔴 Примета снимается ТОЛЬКО с хвоста ключа, и это не осторожность, а сама граница
    класса. Примета - приписка: выдача дописывает её к готовому имени. Стоящее в НАЧАЛЕ
    «The Animation» - не приписка, а первое слово имени, и снятие съело бы имя: у «The
    Animation Runner Kuromi» осталось бы «runner-kuromi», то есть починка развела бы одну
    картину надвое ровно тем способом, который лечит. Закрытый список от этого не спасает:
    многословность приметы обходится ведущим «The» самого имени.

    Замерено на замороженной выдаче: примета стоит в хвосте у 17 строк из 25, ещё у 8 она
    в середине - но все 8 остаются отдельными картинами по мусорному хвосту за приметой
    («... The Animation Episode 02 English», «... The Animation uncen»), и снятие в
    середине не меняет НИ ОДНОГО пункта меню на пяти запросах. Поэтому берётся узкое
    правило: оно даёт тот же итог и не может съесть имя.

    🔴 Номер за словом тут НЕ трогается, и этим правило отличается от
    :func:`~torrcast.domain.formless._formless`. За словом формы стоит номер ЧАСТИ
    («Naruto Movie 3»), и снять его - подменить картину. Номер после приметы означает
    ровно то, что примета тут не хвост, - и ключ остаётся целым.

    Пустой остаток не отдаётся: ключ «the-animation» это всё, что о картине сказано.
    """
    parts = key.split("-")
    if len(parts) > 2 and "-".join(parts[-2:]) in _ADAPTATION_WORDS:
        return "-".join(parts[:-2])
    return key


__all__ = ["_adaptationless"]
