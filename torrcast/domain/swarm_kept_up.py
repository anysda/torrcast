"""Держал ли рой сеанс - по ОКНУ наблюдений, а не по последнему замеру."""

from __future__ import annotations

from collections.abc import Sequence

from torrcast.domain.swarm_supply import ENOUGH


def swarm_kept_up(seen: Sequence[float]) -> bool:
    """Правда ли рой хоть раз за сеанс вёз достаточно (:data:`ENOUGH` и выше).

    🔴 Скорость службы (``download_speed``) - величина СПРОСА: она меряет то, что мы у
    роя просим, а не то, что рой способен привезти. Пока упаковка тянет байты, короткий
    замер и правда говорит о рое; после того как показ сдался, тянуть перестали, и тот же
    короткий замер не говорит уже ни о чём. Замер 03-09-2026 на стенде `.136`: весь сеанс
    след писал долю 2.99-3.61 (53-64 Мбит/с при нужных 17.81), а человеку показ назвал
    последнее посмертное показание - 0.20 Мбит/с - и обвинил здоровую раздачу.

    Отсюда правило: на ПОХОРОНАХ показа рой, доказавший себя хоть одним наблюдением
    сеанса, за темноту не отвечает. Приговор ему остаётся только там, где он не вёз
    достаточно НИ РАЗУ, - и посмертные показания перевернуть этот ответ не могут.

    ⚠️ Окно отвечает только на посмертный вопрос. Живому показу оно не судья: там
    просевший рой называется просевшим и показ его ЖДЁТ.

    ⚠️ Потолок правила: в последней строке рой, умерший в середине сеанса после здорового
    начала, виноватым не назовут. Отличить его от посмертного замера полями
    ``ratio``/``got``/``need`` нечем - в обоих случаях спрос упал вместе с показом, - а
    заводить ради этого новый прибор дороже, чем один раз промолчать. Живьём такую
    просадку показ по-прежнему видит, называет и пережидает.
    """
    return any(ratio >= ENOUGH for ratio in seen)
