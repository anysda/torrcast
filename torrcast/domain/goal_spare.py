"""Продуктовая цель пути до картинки и то, сколько её у поиска ещё осталось."""

from __future__ import annotations

from typing import Final

#: Цель пути: столько секунд от `cast` до картинки на экране. Здесь она не потолок, а
#: мера - ею меряются бюджеты, которые иначе не с чем сравнить.
GOAL: Final = 10.0
#: Сколько цели (:data:`GOAL`) оставляем самому кругу второго захода. Круг по индексерам
#: дешевле секунды и не бывает: медиана 0.53 с, 75-я доля 1.20 с. Это же и пол бюджета:
#: круг, спрошенный меньше чем на секунду, - гарантированный молчун, то есть лишний
#: запрос к трекеру за заранее известный отказ.
CIRCLE_SHARE: Final = 1.0
#: 🔴 TC-228. Ниже стольких секунд цели второй заход не зовём вовсе. Второй круг (добор
#: вторым языком, сезонная строка, чтение забытой раскладки) зовётся в 18 запросах из 100
#: и УДВАИВАЕТ цену поиска: сквозной замер 1.93-2.39 с против 0.01-0.09 с там, где его
#: нет. Своего бюджета у него не было ни секунды - он платил хвост первого круга плюс
#: полный второй, и на хвосте Knaben это давало 30 с при цели в 10. Порог складывается из
#: замеренных частей: справка на пути (:data:`~torrcast.domain.facts.settings.FACTS_BUDGET`, медиана
#: 0.93 с там, где зовётся, и 9 запросов из 100 упираются в её потолок 1.5 с) плюс сам круг
#: (:data:`CIRCLE_SHARE`). Меньше этого оставлять добору незачем: он не успеет ни спросить справку,
#: ни дождаться круга, а стоить будет как полный. ⚠️ TC-386. Порог охраняет заходы, у которых есть
#: честный отступ (уточнение, сезонная и голосовая строки, переспрос всей строкой). Добор по второму
#: ИМЕНИ картины им не отменяется: без второго имени картина пропадает из каталога, и цель тут
#: подчинена поиску - такой заход поднимает пол бюджета круга до целой цели.
SECOND_LEAST: Final = 2.5


def goal_spare(elapsed: float) -> float:
    """Сколько секунд цели (:data:`GOAL`) поиск ещё не потратил (TC-228).

    ``elapsed`` считает ВСЁ, что случилось на пути от начала поиска: первый круг, справку
    на пути добора (медиана 0.93 с там, где зовётся), разбор выдачи. Именно поэтому
    справка тут учтена честно - её не надо вычитать отдельно, она уже в прошедшем времени.

    Цель съедена целиком - остатка ноль, а не долг: отрицательным бюджетом спрашивать
    нечего.
    """
    return max(0.0, GOAL - elapsed)


__all__ = ["CIRCLE_SHARE", "GOAL", "SECOND_LEAST", "goal_spare"]
