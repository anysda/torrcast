"""Насколько хвост фильма без опорных кадров разрешено быть шире самой широкой дыры карты."""

from typing import Final

#: Во сколько раз хвост фильма, до которого карта опорных кадров не дотянулась, разрешено
#: быть шире самой широкой дыры внутри самой карты.
#:
#: 🔴 Карта, кончающаяся раньше фильма, даёт последний кусок, который резать НЕЧЕМ: границ
#: за последним кадром карты не ставит никто, потолок веса на хвост не распространяется
#: (:meth:`~torrcast.adapters.stream_pack.grid.Grid.on_keyframes` - «хвост прилипает к
#: последнему»), и в манифест уезжает один кусок на весь остаток. Боевая запись 26-08
#: («Матрица» 1999): последняя точка Cues 7778.899 при длительности 8175.488 - кусок
#: **396.6 с**, и это ровно тот ``EXT-X-TARGETDURATION: 397`` при обещанных 10.5 с,
#: который стоял в манифесте показа. Ещё три такие карты нашлись на той же полке.
#:
#: Мерка своя у каждой карты, а не общая секунда: правильно кончившаяся карта оставляет
#: без кадров не больше одного своего GOP, а «один GOP» у фильма с GOP 1.3 с и у фильма с
#: GOP 10.4 с - разные секунды.
#:
#: Порог стоит в ПУСТОМ промежутке, а не выбран. Замер по 142 картам живой полки владельца:
#: у 138 карт доля «хвост / самая широкая дыра» лежит в 0.00-2.33, у четырёх - 28.25,
#: 28.70, 43.46 и 316.76. Между 2.33 и 28.25 нет ни одной карты, то есть промежуток шире
#: чем в десять раз, и любое число внутри него делит корпус одинаково.
KEYS_TAIL_GAPS: Final = 5.0
