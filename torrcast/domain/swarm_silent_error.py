"""Ошибка SwarmSilentError; используется публичным API."""

from torrcast.domain.infra_error import InfraError


class SwarmSilentError(InfraError):
    """Байты не приехали: молчит рой, а не файл виноват. Код выхода 2.

    Отдельное имя нужно ровно одному решению - что о неудаче можно ЗАПОМНИТЬ. Разбор
    контейнера отвечает про сам файл («индекс врёт», «это не mkv и не mp4»), и такой ответ
    не изменится, пока не изменится файл, - его помнят
    (:func:`~torrcast.adapters.stream_pack.film_keys.film_keys`). Молчание роя не говорит о
    файле НИЧЕГО: раздача бывает холодной минуту и живой через минуту, и запоминать это
    значило бы объявить файл негодным за чужую беду.

    Разбор ввода-вывода не делает вовсе, поэтому граница проходит ровно по читателю:
    своё имя ставит он один (:class:`~torrcast.adapters.frames.http_range_reader.HttpRangeReader`).
    """
