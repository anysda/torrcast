"""Описывает студию озвучки и справочник студий."""

from dataclasses import dataclass
from typing import Final


@dataclass(frozen=True, slots=True)
class Studio:
    """Что мы знаем про студию озвучки: как её звать и какой перевод она делает.

    ``fame`` - вес студии внутри своей ступени, больше = ближе к дефолту; 0 - нейтральная
    студия, порядок внутри ступени авторский. Отрицательное значение опускает студию НИЖЕ
    незнакомых - используем это для AniDub, которые встраивают рекламу прямо в файл:
    лучше незнакомая студия, чем 20 секунд рекламы ставок перед началом серии.

    Ключевой случай - «Кубик в Кубе»: они действительно ДВУХГОЛОСЫЕ, но по крутости
    стоят ВЫШЕ LostFilm, то есть выше целой ступени. Одним ``fame`` этого не выразить -
    он разводит только соседей по ступени. Поэтому у студии два разных поля: ``kind`` -
    какой перевод она делает НА САМОМ ДЕЛЕ (его и произносим вслух), а ``ranks`` - по
    какой ступени её СУДЯТ на отборе, если это не одно и то же. Слить их в одно поле
    значило бы печатать человеку «беру многоголосый (Кубик в Кубе)» - молчаливое враньё
    ровно того сорта, который проект не допускает.

    ⚠️ ``ranks`` - исключение, а не приём: заполнять его можно только там, где крутость
    студии подтверждена, иначе лестница поплывёт в непредсказуемых местах.
    """

    kind: str
    name: str = ""
    fame: int = 0
    ranks: str = ""


