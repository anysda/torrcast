"""Имя, сказанное латиницей; зовёт розыск обложки у источника, знающего только её.

Подсказчик IMDb называет картину латиницей ВСЕГДА, и сверка имени у него - это
посимвольное равенство (:meth:`~torrcast.adapters.wiki.imdb_poster.ImdbPoster._by_name`).
Русское имя там не совпадёт ни с чем, и спрашивать им - значит пускать в ответ любую
картину ранжировщика. Отсюда вопрос перед запросом: сказано ли имя тем алфавитом,
которым отвечает источник.

🔴 Требуется И латиница, И отсутствие кириллицы. Одной латиницы мало: «Брат / Brat» в
одной строке даёт совпадение обеих половин, а спрашивать надо только вторую. Отсутствия
кириллицы тоже мало: японское или греческое имя не кириллица, но и не латиница, и
равенство с ответом источника не даст ни одно из них.
"""

from __future__ import annotations

import re
from typing import Final

_CYRILLIC: Final = re.compile("[а-яё]", re.IGNORECASE)
_LATIN: Final = re.compile("[a-z]", re.IGNORECASE)


def _said_in_latin(text: str) -> bool:
    """Это имя сказано латиницей и только ей."""
    return bool(_LATIN.search(text)) and not _CYRILLIC.search(text)


__all__ = ["_said_in_latin"]
