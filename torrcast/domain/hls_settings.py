"""Формат HLS для телевизора: сетка, каталоги, звук и потолок куска.

Числа читают и упаковщик (:mod:`torrcast.adapters.stream_pack`), и сценарий подачи
потока (:mod:`torrcast.usecases.feed_pack`): формат один на обоих.
"""

import re
from typing import Final

from torrcast.domain.profile import CAUTIOUS

#: Шаг сетки сегментов, секунды. Было 4 - стало 10, и это не вкусовщина, а
#: измерение (живой Q70D, «Моана» 2016, место 1:24).
#:
#: Спотыкач на 1:24 оказался **нашей нарезкой, а не фильмом и не роем**. Доказано так:
#:
#: * тот же битстрим видео (``-c:v copy``) и тот же AAC, но одним прогрессивным mp4 -
#:   ТВ проходит место 1:24 без единого BUFFERING (70 с показа, 0 подвисов);
#: * сеткой по 4 с - встаёт намертво на границе сегмента и сам не оживает никогда
#:   (5 прогонов из 5: четыре обычным показом и один диагностическим прогоном);
#: * сдвиг сетки на 0.21 с (упаковка с ``-ss 20``) - встаёт там же;
#: * SPS/PPS в каждый кадр (``dump_extra``) - встаёт там же;
#: * рез строго по ключевым кадрам - встаёт там же;
#: * сеткой по 10 с - проходит чисто (0:00→1:42, ни одного BUFFERING).
#:
#: ⚠️ Объяснение «граница не должна трогать тяжёлый GOP» **проверено и не подтвердилось**
#: (замеры на живом Q70D, «Моана 2» 2024, карта опорных кадров снята
#: ``scripts/keyframes.py``). Сетка 10 с на этом файле:
#:
#: * режет 585 GOP из 1118, в том числе самый тяжёлый в фильме (13.31 МБ / 10.38 с,
#:   место 87:11, граница ровно внутри него) - показ идёт чисто, ни одного BUFFERING;
#: * оставляет 12 сегментов, внутри которых нет ни одного опорного кадра (GOP длиннее
#:   сетки), первый из них - 1:10...1:20 - тоже играется чисто.
#:
#: То есть ни «тяжёлый GOP разрезан», ни «в сегменте нет опорного кадра» сами по себе
#: приёмник не роняют, и правила «сетка обязана быть длиннее самого длинного GOP» из
#: этих цифр не следует.
#:
#: Что подтвердилось: провал зависит от **фазы** сетки, а не от веса GOP. Сетка 4 с на
#: «Моане» 2016 воспроизводимо встаёт ровно на 84.0 с, когда упаковка начата с нуля
#: (BUFFERING, позиция стоит, сторож вытаскивает нуджем через ~9 с), и та же сетка 4 с
#: в том же месте проходит чисто, когда упаковка начата с 1:10 - то есть когда границы
#: сегментов сдвинуты относительно фильма. Единственный внятный вывод, который цифры
#: держат: 10 с - это в 2.5 раза меньше границ, чем 4 с, и на всех замеренных местах
#: обоих фильмов эта сетка проходит. Класс НЕ закрыт: правило, по которому можно было бы
#: заранее сказать, какая именно граница убьёт показ, не найдено.
#:
#: 🔴 Число - **осторожный профиль приёмника** (:data:`torrcast.domain.profile.CAUTIOUS`), а не
#: свойство HLS: живой показ берёт шаг из профиля через ``hls_segment``. Здесь оно
#: остаётся умолчанием для всего, что зовётся без настроек, - тестов и щупов.
#:
#: ⚠️ Это был шаг сетки, а не её место в фильме: **фаза** сетки раньше зависела от
#: того, откуда начата упаковка. ``split_by_time`` отсчитывает границы от ПЕРВОГО пакета
#: прогона, а ``-ss`` уводит ffmpeg на опорный кадр не позже запрошенного места, поэтому
#: после рестарта с 70 с сегмент с именем ``v17`` (сетка 4 с, то есть «68.0 с») начинался
#: на 67.55 с. Теперь границы абсолютные: см. :class:`Grid` и :func:`pack_start`.
HLS_SEGMENT_SECONDS: Final = CAUTIOUS.segment_seconds

#: Каталог одного прогона упаковки внутри каталога показа. ffmpeg пишет сегменты сюда, а
#: наружу они попадают переименованием (:meth:`Packer.publish`) - по двум причинам:
#:
#: * готовность. Сегментный муксер, в отличие от hls, не пишет через временный файл:
#:   файл появляется пустым и наполняется. «Есть файл» перестало значить «кусок готов»,
#:   а вот «появился следующий» - значит, и это видно только внутри прогона;
#: * докатка. Прогон почти всегда начинается раньше своей границы (``-ss`` уводит на
#:   опорный кадр), и этот огрызок ffmpeg кладёт под именем предыдущего сегмента. Отдать
#:   его наружу нельзя: под этим именем уже может лежать честный сегмент прошлого прогона.
PACK_DIR: Final = "pack"

#: Каталог одноразового прогона «ужатия на месте» внутри каталога перекода
#: (:meth:`Feed._shrink`): свой, чтобы не задеть рабочий каталог кодировщика.
SHRINK_DIR: Final = "shrink"

#: Имя склеенного куска (:func:`merge_tracks`) внутри каталога прогона. Начинается **не**
#: с ``v``: каталог прогона перебирается глобом ``v*.ts``, и склейка не должна попасть в
#: него ни как готовый сегмент, ни как признак «следующий открыт, прошлый дописан».
MIXED_PREFIX: Final = "mix"

#: Приставка к имени заголовка, который прогон оставляет рядом с выложенным куском
#: (:func:`torrcast.domain.head_name.head_name`). Начинается **не** с ``v`` по той же
#: причине, что и склейка: каталоги перебираются глобом ``v*``.
HEAD_PREFIX: Final = "head"

#: Расширение записи «с каким заголовком это место УШЛО наружу». Пишет её выкладка
#: (:func:`torrcast.adapters.stream_pack._own_head._own_head`), и только по ней сосед
#: узнаёт, чем настроен декодер приёмника: готовый кусок кодировщика на это не отвечает.
HEAD_SENT: Final = ".sent.mp4"

#: Сколько байт несданных кусков разрешено одному прогону держать в tmpfs
#: (:meth:`Packer.pending`, :meth:`Feed.sweep`). Законно несданными бывают ровно два
#: рода кусков: тот, который ffmpeg пишет прямо сейчас, и те, что придержаны под перекод
#: (:data:`torrcast.adapters.recode.recoder_settings.RUN_MAX` - шесть). На потолке сегмента это 7 ×
#: 16 МБ = 112 МБ; берём вдвое с запасом, чтобы порог отделял поломку от плотной работы, а не спорил
#: с ней.
PACK_PENDING_BYTES: Final = 256 << 20

#: Список сегментов, который ведёт сам ffmpeg: ``имя,начало,конец`` на каждый закрытый
#: кусок. Приёмнику он не отдаётся - по нему показ сверяет, что нарезал ровно то, что
#: обещал в манифесте (:meth:`Packer.drift`).
PACK_LIST: Final = "pack.csv"

#: На сколько секунд последний кусок прогона имеет право не дотянуть до обещанного
#: сеткой конца и всё-таки считаться дописанным (:meth:`Packer.finished`).
#:
#: Допуск нужен из-за одной законной причины: длительность фильма берётся из контейнера,
#: а кончается поток на последнем пакете. Замер на mkv, mp4 и avi с дробными
#: длительностями: последний кусок фильма не дотягивает до обещанного на 0.000-0.065 с.
#: Полсекунды - на порядок больше этой разницы и на порядок меньше обрыва: замер обрыва
#: входа на 90 местах файла дал недобор от 0.6 до 10.0 с при кусках по 10 с.
PACK_SHORT_SECONDS: Final = 0.5

#: Допуск при сравнении времени границы с меткой кадра: границы сетки стоят на опорных
#: кадрах, но метки одного и того же кадра при упаковке от нуля и из середины файла
#: отличаются на кадр (ffmpeg не пускает dts ниже нуля). Полкадра 24 к/с - 0.02 с.
SPLIT_SLACK: Final = 0.02

#: На сколько раньше первого сэмпла встаёт первый пакет НАШЕГО звука: кодировщик AAC
#: отдаёт метки со своей начальной набивкой (1024 сэмпла - 21 мс при 48 кГц, 23 мс при
#: 44.1), и ffmpeg честно вычитает её из выходных меток. Замер на ролике с нулём вместо
#: начала: первый пакет звука приходит на -0.021 с, то есть НИЖЕ нуля, ровно как первый
#: кадр видео с B-кадрами.
#:
#: Число нужно ровно затем, чтобы вся лента фильма встала выше нуля (:func:`pack_origin`),
#: и взято с запасом: переоценка стоит лишних миллисекунд начала на всей ленте разом,
#: недооценка возвращает дефект - муксер досдвинет первый кусок сам и только его.
AUDIO_PRIMING: Final = 0.05

#: Флажок «на экране картинка»: его кладёт показ, когда приёмник впервые ответил
#: ``PLAYING``, и ждёт CLI. Спросить приёмник из CLI нельзя - сендер к нему ровно один
#: (:mod:`torrcast.adapters.chromecast.cast`), поэтому доказательство картинки передаётся файлом.
PLAYING_FLAG: Final = "playing.flag"

#: Аудио всегда перекодируется: passthrough AC3/DTS запрещён.
AUDIO_CODEC: Final = "aac"

AUDIO_BITRATE: Final = "192k"

AUDIO_CHANNELS: Final = 2

#: Потолок веса ОДНОГО сегмента: сколько байт разрешено уехать на ТВ одним куском.
#:
#: 🔴 Это и есть механизм подвиса, найденный замером.
#: Приёмник Q70D срывается в BUFFERING на 4-8 с ровно на границе, за которой лежит
#: сегмент тяжелее ~19 МБ, и снимается сам, **повторно скачав** уже полученные куски -
#: то есть выбрасывает буфер и набирает его заново. Секунды тут ни при чём, и это
#: доказано в обе стороны на живом ТВ:
#:
#: * 20.0 с и 14.3 МБ («Моана 2», два лёгких куска слиты в один) - прошло чисто;
#: * 19.9 с и 24.2 МБ (та же «Моана 2», тяжёлый кусок) - приёмник не подвис, а **потерял
#:   сессию** целиком;
#: * 16.934 с / 18.7 МБ - чисто, 16.892 с / 20.3 МБ («Тачки 3») - стоп 8 с: одна и та же
#:   длина, разный вес, разный исход;
#: * тот же тяжёлый кусок, разрезанный пополам (12.0 и 9.0 МБ), - чисто.
#:
#: Граница отбраковки лежит между 18.7 МБ (чисто) и 19.4 МБ (стоп), поэтому потолок
#: поставлен на 16 МБ - запас 15 % и ни одного лишнего сегмента в манифесте на лёгком
#: кино (там 10 с весят 6-8 МБ и правило не срабатывает вовсе).
#:
#: 🔴 Это замер ОДНОГО приёмника, поэтому число живёт в его профиле
#: (:data:`torrcast.domain.profile.CAUTIOUS`), а здесь остаётся умолчанием для тестов и щупов.
MAX_SEGMENT_BYTES: Final = CAUTIOUS.max_segment_bytes

#: На сколько сетка целится НИЖЕ потолка веса приёмника, доля потолка.
#:
#: Потолок - свойство приёмника, а вес куска при постройке сетки не известен, а предсказан
#: по карте опорных кадров (:func:`torrcast.adapters.stream_pack.weigher.weigher`).
#: Предсказание сходится с готовой копией в пределах -4.9...+2.0 % (замер на трёх релизах),
#: и на границе этот промах решает судьбу куска: обещанный ровно в потолок кусок рождается
#: за ним на доли процента, а платит за это показ вторым прогоном ffmpeg над тем же местом
#: (:func:`torrcast.usecases.feed_pack.feed_shrink._shrink`).
#:
#: Замер класса по 84 сохранённым картам опорных кадров (101 час плёнки, 31 269 кусков):
#: у 0.75 % кусков предсказанный вес стоит в пределах процента под потолком - то есть
#: 2.2 куска на час плёнки уходят в ужатие из-за промаха, а не из-за содержимого. Число
#: почти не зависит от величины промаха внутри известной полосы: плотность предсказанных
#: весов под потолком ровная. Цена отступа на том же корпусе: 2 % стоят 0.32 % лишних
#: кусков в манифесте и убирают рождение за потолком при промахе до 2 % - с 440 до 22.
#: Промах больше двух процентов по-прежнему кончается ужатием: ужатие для того и есть.
#:
#: Живой замер настоящим ffmpeg (1080p 37 Мбит/с, дорожки с неровным весом): сетка без
#: отступа обещала кусок в 27 785 060 байт, а уехало 28 229 328 при потолке 28 000 000.
#: С отступом за потолком не родился ни один кусок, самый тяжёлый вышел 98.1 % потолка,
#: а манифест вырос на один кусок из двадцати семи.
#:
#: 🔴 Потолок приёмника отступом НЕ двигается: наружу кусок по-прежнему судят полным
#: потолком (:mod:`torrcast.adapters.stream_pack.packer_publish`). Ниже целится только сетка,
#: и только потому, что она целится предсказанием.
GRID_WEIGHT_MARGIN: Final = 0.02

#: Сколько упаковка имеет право не выложить ни куска, прежде чем это признают обрывом
#: связи (:meth:`Feed._mute`), секунды.
#:
#: Не «сколько поднимается ffmpeg»: подъём стоит 1-3 с, а первый кусок сетки - это ещё
#: 10-20 с фильма, которые ``readrate 1`` честно читает столько же. 45 с - вдвое сверх
#: самого длинного куска сетки плюс подъём: это уже не «медленно», это «никак».
MUTE_SECONDS: Final = 45.0

_SEGMENT_RE: Final = re.compile(r"v(\d+)\.(?:ts|m4s)")
