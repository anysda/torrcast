"""Поля настроек про вес картинки: пороги отбора релиза и перекодирование на лету.

Наследует их :class:`torrcast.domain.config.Config`, и только он.
"""

from __future__ import annotations

from dataclasses import dataclass

from torrcast.domain._config_hls import _ConfigHls
from torrcast.domain.profile import CAUTIOUS


@dataclass(slots=True)
class _ConfigRecode(_ConfigHls):
    """Лестница веса: с какого места релиз не берут и с какого кусок перекодируют."""

    #: Практический потолок битрейта приёмника, Мбит/с (урок Q70D).
    #:
    #: ⚠️ 16, а не 20: замер на живом Q70D - честный 1080p «Моаны 2» на
    #: 17.8 Мбит/с встаёт в ребуфер раз в 30-60 секунд при полной упаковке впереди, и
    #: каждый такой подвис стоит 8 с пропущенного фильма.
    #:
    #: ⚠️ Это число **не фильтр отбора**: тяжёлые куски перекодируются на лету
    #: (:mod:`torrcast.adapters.recode`), поэтому тяжёлый честный 1080p играбелен. Это порог,
    #: ВЫШЕ которого сегмент перекодируют.
    #: Отбраковка релиза живёт в :attr:`bitrate_hard_mbit`.
    #:
    #: 🔴 Умолчание - осторожный профиль приёмника: у приставки Android TV на этом месте
    #: 28 Мбит/с, и там же лежит замер.
    bitrate_warn_mbit: float = CAUTIOUS.warn_mbit
    #: Битрейт, выше которого релиз не берём вовсе, Мбит/с. Это уже не про декодер (его
    #: чинит перекодирование), а про то, что перекодировать пришлось бы весь фильм: и
    #: процессор, и рой должны тянуть это непрерывно, а запаса впрок взять неоткуда.
    #: 25 - вдвое выше практического потолка приёмника: «Моана 2» 13.3 ГБ (19 Мбит/с)
    #: проходит, 4K-ремукс на 49.9 Мбит/с - нет.
    bitrate_hard_mbit: float = 25.0
    #: Потолок отбора, когда файл перекодируется ЦЕЛИКОМ одним прогоном, Мбит/с.
    #:
    #: Выше :attr:`bitrate_hard_mbit` посегментное перекодирование теряет смысл: тяжёл
    #: КАЖДЫЙ кусок, и вместо сотни коротких ffmpeg дешевле один сплошной - тот самый,
    #: которым уже играет HEVC. Отсюда и второй потолок: релиз годен, пока сплошной
    #: перекод успевает за показом.
    #:
    #: 40 - замер на 4 vCPU, живые аниме BD-ремуксы 1080p:
    #: «Shingeki no Kyojin S3 ep.07» 36.4 Мбит/с h264 (37.8 Мбит/с по куску) перекод
    #: ultrafast в 9 Мбит/с идёт 3.36-3.50x реального времени, чтение раздачи из роя
    #: 47.7 МБ/с против нужных 4.7 МБ/с, самый тяжёлый сегмент 13.2 МБ при потолке 16.
    #: HEVC того же веса (30 Мбит/с) - 2.35x. Запас до единицы у h264 3.4x, у HEVC 2.3x;
    #: 40 оставляет его и на менее удачную машину, а 4K-ремукс на 50 Мбит/с по-прежнему
    #: не берётся.
    #:
    #: ⚠️ Потолок ростом кадра НЕ пользуется: 2160p судится прежним
    #: :attr:`bitrate_hard_mbit` (25). Прежнее объяснение («4К в реальное время не
    #: укладывается») замером TC-157 снято - ужатый до 1080p перекод 2160p идёт 1.53×, -
    #: но послабления это не даёт, и вот почему: запас у 4К вдвое тоньше, чем у 1080p
    #: (1.5× против 3.4×), а тянуть из роя надо ровно столько же мегабайт в секунду,
    #: сколько весит релиз. 40 Мбит/с 4К - это 5 МБ/с из роя ПЛЮС декод вчетверо большего
    #: кадра, и запас на такое замером не подтверждён ни разу.
    bitrate_recode_mbit: float = 40.0
    #: Перекодировать тяжёлые куски заранее. ``false`` - тяжёлое просто не берётся,
    #: потолком отбора становится :attr:`bitrate_warn_mbit`.
    recode: bool = True
    #: Битрейт, ВЫШЕ которого сегмент перекодируется, Мбит/с. Отдельно от
    #: :attr:`bitrate_warn_mbit` намеренно: то - потолок ОТБОРА (и он остаётся 16),
    #: а это - замеренная планка приёмника.
    #:
    #: ⚠️ 10, а не 16. Живой Q70D (`scripts/tvprobe.py`, «Моана 2» 13.3 ГБ,
    #: тяжёлый участок 4840...5040 с): при перекодировании в 12 Мбит/с приёмник всё равно
    #: вставал раз в 10-15 с, а сегменты на 13-15 Мбит/с роняли его и без всякого
    #: перекодирования - то есть прежние оценки «потолок между 18 и 22» и даже
    #: опущенная до 16 были завышены. Контроль: «Моана» 2016 на 4 Мбит/с -
    #: 5 опросов BUFFERING из 60, и все на прогреве.
    #:
    #: 🔴 Умолчание - осторожный профиль приёмника.
    recode_at_mbit: float = CAUTIOUS.recode_at_mbit
    #: Во сколько Мбит/с перекодируем тяжёлый кусок. Ниже планки приёмника с запасом.
    #:
    #: ⚠️ 9, а не 12: замер на живом Q70D (тот же участок, 200 с показа). 12 Мбит/с -
    #: 46 опросов BUFFERING, показ прошёл 154 с из 200. 9 Мбит/с - 13 опросов, из них
    #: после прогрева 3, показ прошёл 179 с. 6 Мбит/с - 18 и 3, показ прошёл 177 с, то
    #: есть ниже девяти уже ничего не покупается, а чёткость теряется.
    #:
    #: 🔴 Умолчание - осторожный профиль приёмника. У приставки оно то же, и это не
    #: недосмотр: цель перекода упирается в наш кодировщик, а не в её декодер.
    recode_mbit: float = CAUTIOUS.recode_mbit
    #: Самый качественный пресет libx264, с которого начинает кодировщик. Замер на 4 vCPU (Xeon
    #: E5-2696 v4, 1080p): ``veryfast`` 1.54× реального времени, ``superfast`` 2.62×, ``ultrafast``
    #: 4.36×. Когда до куска остаётся мало времени, кодировщик сам берёт пресет быстрее
    #: (:func:`torrcast.adapters.recode.preset_for`).
    recode_preset: str = "veryfast"
    #: Приводить ли HDR-исходник к SDR при сплошном перекоде
    #: (:data:`torrcast.adapters.recode.encode_settings.TONEMAP`).
    #:
    #: 🔴 TC-223, и выключено оно по ЗАМЕРУ, а не из осторожности. Замер 09-08-2026 на 4 vCPU,
    #: «Матрица» 2160p HEVC 10 бит HDR10 (PQ, BT.2020), тяжёлое место 93 с, ``ultrafast`` 9 Мбит/с:
    #: перекод с одним скейлом до 1080p - 1.34× реального времени, он же с тонемапом после скейла -
    #: 1.00×, тонемап ДО скейла (на 4К) - 0.37×. То есть тонемап съедает запас скорости целиком:
    #: 1.00× - это упаковка вровень с показом, а рядом ещё работает прогрев, который замерено
    #: отнимает 30 % (:data:`torrcast.adapters.recode.pace.NEIGHBOUR_TOLL`). Гейт показа - ноль
    #: подгрузов, и он сильнее цвета: выцветший кадр смотреть можно, стоящий - нельзя.
    #:
    #: ``true`` - включить и посмотреть глазами: механизм готов и работает, цена известна.
    #: Без него HDR-исходник уезжает со СВОИМИ метками (BT.2020/PQ) - как уезжал и раньше:
    #: цвет не преобразован, но и не переклеен на чужой ярлык.
    recode_tonemap: bool = False
    #: Насколько далеко впереди показа работать впрок, секунды фильма. Ограничение не по
    #: времени, а по tmpfs: готовые куски лежат в памяти. Модель показа «Моаны 2»: 300 с
    #: держат пик кэша на 459 МБ и не стоят ни одного опоздания.
    recode_ahead: float = 300.0
    #: Потолок кэша перекодированного, МБ. Достигнут - кодировщик спит, а не растёт.
    recode_cache_mb: float = 384.0
    #: Сколько ждать перекод ПЕРВОГО сегмента показа, секунды (:meth:`Recoder.holding`).
    #:
    #: Первый сегмент - единственный, до которого форы нет вовсе: показ начинается ровно
    #: с него, и уйди он копией - приёмник встаёт в первую же секунду (старт, resume,
    #: перемотка в тяжёлое место). Ждать его не подгруз, а старт: картинки ещё нет.
    #: Ноль - не ждать вовсе.
    #:
    #: 12 с - потолок, а не цена. Цена замерена («Моана 2» 13.3 ГБ, ultrafast,
    #: `nice 0`): v0 длиной 19.96 с - 5.8 с, v45 длиной 19.96 с - 6.0 с, v358 длиной
    #: 16.00 с в самом тяжёлом месте - 9.0 с. То есть **не 2.3 с**, как прикидывалось из
    #: 4.36× и сегмента 10 с: сегменты сетки по опорным кадрам вдвое длиннее, а к чистому
    #: кодированию добавляются подъём ffmpeg и чтение 50-80 МБ из роя.
    #: Просрочен - копия уходит как есть: тяжёлый кусок хуже, чем чёрный экран.
    recode_head_wait: float = 12.0
