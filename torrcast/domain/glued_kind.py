"""Правило glued kind; используют модели и фасады разбора имён."""

from __future__ import annotations

from torrcast.domain.kind import Kind
from torrcast.domain.picture import Picture


def _glued_kind(merged: list[Picture]) -> Kind:
    """Вид склеенной картины: сериал перевешивает фильм.

    🔴 Разные виды в одной склейке бывают ровно от одного правила - «одно имя, один год,
    а каталог развёл фильм и сериал» (``one_picture_two_kinds``): ключ остальных вёдер
    вид уже содержит, и смешаться им нечем. Значит спор тут всегда один и тот же, и
    решался он ПОРЯДКОМ СКЛЕЙКИ - видом той кучки, где раздач больше. Число раздач о
    виде не говорит ничего: у «Байки Мэтра» 11 имён без серийных меток против 6 с ними
    (``[Season 1-2]``, ``[S01-03]``, ``1-3 сезоны: 1-9 серии``), и сериал 2008 года
    выходил из склейки полным метром - без пометки в меню и без права на правила вида.

    Сериал перевешивает потому, что серийная метка - это УЛИКА, а её отсутствие уликой
    не бывает: разбор имени ставит «фильм» всякий раз, когда сериала он не увидел
    (``parse_release_name``). Одно имя с метками весит больше десяти молчащих.
    """
    return "tv" if any(picture.kind == "tv" for picture in merged) else merged[0].kind


__all__ = ["_glued_kind"]
