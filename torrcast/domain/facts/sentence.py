"""Первая фраза статьи целиком; её читают все гейты справки."""

from __future__ import annotations

from torrcast.domain.facts.patterns import (
    _ABBREV,
    _LAST_WORD_RE,
    _SENTENCE_START_RE,
)
from torrcast.domain.facts.unhatted import unhatted


def sentence(text: str) -> str:
    """Первая фраза статьи целиком — от начала до точки, которая её действительно кончает.

    Википедия открывает статью паспортом («американский компьютерно-анимационный
    спортивный комедийный фильм 2006 года, снятый студией Pixar для кинокомпании Walt
    Disney Pictures») — самодостаточным ответом на «про что кино». Ценность его именно
    в целости: обрубок «американский компьютерно-анимационный…» не говорит ни жанра,
    ни года, а дочитать его негде.

    Точка кончает фразу не всякая, и все четыре исключения взяты с живых статей:

    * **скобки и кавычки.** «(англ. Cars)» стоит в первой фразе почти каждой статьи о
      зарубежном кино, а у «Оппенгеймера» внутри «ёлочек» лежит название книги с точкой
      посередине («Оппенгеймер. Триумф и трагедия Американского Прометея»). Пока скобка
      или кавычка не закрыта, точка внутри — не граница;
    * **сокращения.** «реж.», «им.», «т. е.» — после них фраза продолжается;
    * **инициалы.** «Г. А. Потёмкина»: одна буква перед точкой словом не бывает;
    * **само название картины** (:func:`_title_end`): «Звёздные войны. Войны клонов» -
      точка стоит ВНУТРИ него, и описание обрывалось на двух словах (TC-913).

    Плюс общее правило: за границей фразы идёт пробел и заглавная буква (или кавычка
    названия). «2001: A Space Odyssey» и «6.7» так не разрежешь.

    ⚠️ Перед первой фразой у статьи бывает строка-указатель («О сериале см. статью 7
    самураев.», «Не путать с ...») - её снимает :func:`~torrcast.domain.facts.unhatted.
    unhatted` вместе с порядком, которым она снимается, и оттуда же её читают гейты
    (TC-908, TC-912).
    """
    flat = unhatted(text)
    titled = _title_end(flat)
    depth = 0
    for pos, char in enumerate(flat):
        if char in "([«“":
            depth += 1
        elif char in ")]»”":
            depth = max(depth - 1, 0)
        elif char in ".!?" and depth == 0 and pos > titled and _ends_phrase(flat, pos):
            return flat[: pos + 1]
    return flat


def _title_end(flat: str) -> int:
    """Докуда тянется название, которым статья открывается; ``-1`` - если его не видно.

    🔴 Точка внутри названия и точка конца фразы выглядят одинаково, и по буквам их не
    развести: «Звёздные войны. Войны клонов» - это ОДНО название, а описание обрывалось
    на первой его половине, и зритель читал в меню два слова (TC-913).

    Развести их умеет только разметка: в статье название набрано полужирным, и выделение
    честно накрывает точку внутри. До нас оно не доезжает - справка просит выдачу плоским
    текстом (``explaintext``, :func:`~torrcast.domain.facts.extract_params.
    extract_params`), и MediaWiki снимает ``<b>`` вместе со всеми прочими тегами. Взять
    выделение можно только вместе с HTML целиком, а он приезжает в ту же строку, которую
    полка держит сырой и которую читают все правила разбора: цена такой замены - разбор
    HTML в каждом из них и ещё один подъём номера правил.

    Поэтому границей служит второй маркер того же паспорта, тоже структурный и в плоском
    тексте уцелевший: тире между названием и рассказом о картине. Русская Википедия
    открывает статью формулой «НАЗВАНИЕ (язык. оригинал) — паспорт», и первое тире
    ВЕРХНЕГО уровня отделяет одно от другого. Всё, что стоит до него, - это ещё имя
    картины, и точка там ничего не кончает.

    Тире ищется только парное пробелам: в «2003—2005 годах» тире стоит внутри числа и
    границей не является. Не нашлось ни одного - правило молчит вовсе (``-1``), и фраза
    режется как прежде: выдумывать границу там, где паспорт написан иначе, опаснее, чем
    оставить всё как было.

    🔴 Опора приблизительная, и цена у неё известна числом. На 935 статьях, где выделение
    названия видно в HTML и годится в оракулы, разбор расходился с ним 23 раза, а стал
    расходиться 2. Обе оставшиеся - один и тот же промах, и молчанием он не лечится:
    паспортного тире в зачине нет вовсе, зато тире находится дальше по тексту, во ВТОРОМ
    предложении, и правило глушит законный конец первого. Так вышло у «Айнбо. Сердце
    Амазонии», где на месте паспортного тире стоит опечатка «ー» (U+30FC), и у статьи о
    языках, где паспорта нет по природе жанра. Развести это умеет только разметка, цена
    которой названа выше.
    """
    depth = 0
    for pos, char in enumerate(flat):
        if char in "([«“":
            depth += 1
        elif char in ")]»”":
            depth = max(depth - 1, 0)
        elif char in "—–" and depth == 0 and flat[pos - 1 : pos] == " " == flat[pos + 1 : pos + 2]:
            return pos
    return -1


def _ends_phrase(flat: str, pos: int) -> bool:
    """Кончает ли точка (или «!», «?») на позиции ``pos`` первую фразу."""
    tail = flat[pos + 1 :]
    if tail and not tail.startswith(" "):
        return False  # «2001: A Space Odyssey», «6.7» - точка внутри слова
    word = _LAST_WORD_RE.search(flat[:pos])
    if word and (len(word.group(1)) == 1 or word.group(1).lower() in _ABBREV):
        return False  # «А. Тарковского», «англ.», «т. е.»
    return not tail.strip() or bool(_SENTENCE_START_RE.match(tail.strip()))
