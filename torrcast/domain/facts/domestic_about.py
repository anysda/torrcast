"""Описание картины прямо называет её отечественной: «российский комедийный телесериал»."""

from __future__ import annotations

import re
from typing import Final

__all__ = ["domestic_about"]

#: Страна стоит в первой фразе сразу за тире, перед видом картины. Совместное производство
#: («российско-американский») сюда не попадает: дефис после основы не пропускается.
_DOMESTIC_RE: Final = re.compile(
    r"^[^.]{0,160}?[—–]\s*(?:это\s+)?(?:[а-яё]+\s+){0,2}?(?:российск|советск)(?:ий|ая|ое|ие)\s+"
    r"(?:[а-яё]+\s+){0,4}?(?:теле|мульт|мини-)?(?:сериал|фильм|ситком|шоу)",
    re.IGNORECASE,
)


def domestic_about(about: str) -> bool:
    """Отечественная ли картина по описанию справки.

    🔴 TC-1267. Паспорт происхождения «Интернов» назвал английское имя статьи («англ.
    Interns») и отечественной картину не признал: безымянная русская дорожка сериала
    бракуется как неподтверждённая. Страна производства в описании - то самое
    доказательство, которого паспорт не дал; «японский аниме-сериал» («Лэйн», TC-492) им
    не становится.
    """
    return bool(_DOMESTIC_RE.search(about))
