"""Сроки добора справки под нынешний язык продукта; зовёт их справка к меню."""

from __future__ import annotations

from torrcast.domain.catalogs.tongue import RU, tongue
from torrcast.domain.facts.settings import FACTS_BUDGET, HTTP_TIMEOUT


def _spoken_wave() -> float:
    """Доплата за ВТОРУЮ волну справки: сколько стоит чужой язык продукта.

    🔴 TC-957. Первая печать меню под русским языком ждёт ОДИН сетевой запрос - статьи
    русской Википедии. Под чужим языком запросов до первой печати ДВА, и второй зависит
    от первого: описание берётся из Википедии языка продукта, а её адрес известен только
    из межъязыковой ссылки, приехавшей первой волной
    (:func:`~torrcast.adapters.wiki.wiki_translated.wiki_translated`). Волна вторая, и
    стоит она не только запросом: у нового имени свой резолв и своё TLS-рукопожатие.

    Потолок же считал одну волну, и английское меню опаздывало к нему всякий раз:
    замерено на стенде, ``titanic`` тремя парами прогонов - под ``--ru`` описания
    приезжали на 0.43-0.68 с, под ``--en`` не приезжали к 1.5 с ни разу, и весь
    английский показ выходил без единой справки при полной справке русского. Доплата
    ровно одна и ровно за волну: её сетевой потолок (:data:`HTTP_TIMEOUT`).
    """
    return 0.0 if tongue() == RU else HTTP_TIMEOUT


def facts_budget() -> float:
    """Сколько меню согласно ждать ПЕРВУЮ справку на нынешнем языке, секунды.

    Русский платит ровно прежнее (:data:`FACTS_BUDGET`) - ни на сотую больше; чужой язык
    доплачивает за свою вторую волну (:func:`_spoken_wave`). Потолок остаётся потолком,
    а не сроком: приехало раньше - меню выходит раньше, и почти всегда так и выходит.
    """
    return FACTS_BUDGET + _spoken_wave()
