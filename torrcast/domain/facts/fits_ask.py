"""Та ли это картина: сверка года и рода найденной статьи; зовёт отбор статей постера."""

from __future__ import annotations

from typing import Final

from torrcast.domain.facts.ask import Ask
from torrcast.domain.facts.dated import Dated

#: Допуск по году, лет. Ноль тут выбран не из строгости: у P577 лежат ВСЕ даты
#: публикации разом (фестиваль, прокат, издания), и совпадение ищется с любой из них, а
#: допуск в год добирал бы уже соседку по имени - «Аниматрица» 2003-го приезжала так под
#: «Возвращение к источнику» 2004-го.
_SLACK: Final = 0


def fits_ask(ask: Ask, row: Dated, known: dict[str, set[int]]) -> bool:
    """Подходит ли статья этой картине; ``known`` - годы, добранные из Wikidata.

    Про род молчание - не отказ: род читается из категорий и есть не у всех статей.
    Про год молчание - отказ, и это главное правило: неподтверждённый год отдавал пяти
    «Паразитам» разных лет одну и ту же картинку 2019 года.
    """
    return _same_kind(ask.kind, row) and _same_year(ask, row, known)


def _same_kind(kind: str, row: Dated) -> bool:
    """Тот ли это род: спрошен не фильм и не сериал - подходит любая статья.

    Год один и тот же бывает у фильма и у сериала под одним именем: «Паразиты» 2019
    года - это и корейский фильм, и сериал, и без рода в список приезжали две строки с
    ОДНОЙ картинкой.

    🔴 Молчание категорий тут ОТКАЗ, а не согласие. «Чернобыль. Два цвета времени» 1986
    года получал фотографию станции из статьи «Авария на Чернобыльской АЭС»: род та
    статья не называет вовсе - она про событие, а не про картину, - зато год у события
    ровно тот же. Пока молчание проходило наравне с «да», человек читал под нашей
    подписью чужой снимок; пустая строка честна, чужая картинка врёт.

    Молчать статье теперь почти нечем: категории приезжают тем же запросом с ОБЕИХ
    сторон (:func:`~torrcast.domain.facts.page_kinds.page_kinds`), и всякая картина
    называет себя ими - «1999 films», «television miniseries», «Фильмы 1999 года». Не
    назвала ни одной - это не картина, и постера у неё нет.
    """
    return kind not in ("movie", "tv") or kind in row.kinds


def _same_year(ask: Ask, row: Dated, known: dict[str, set[int]]) -> bool:
    """Тот ли это год: год не спрошен - подходит любая статья.

    🔴 У СЕРИАЛА года нет, у него есть срок показа. Раздача пишет в название номер
    сезона («Чернобыль 2. Зона отчуждения»), а годом ставит год ЭТОГО сезона - 2017; сама
    же статья называет 2014 и 2019, начало и конец. Пока сверялось членство в списке
    годов, сезон между началом и концом оставался без обложки при живой статье своего
    сериала. Внутрь срока сериал пускается, наружу - нет: «Чернобыль» 2022 года за
    сроком «Зоны отчуждения» и её постера не получит.

    Фильму срока не бывает: у него в :data:`known` лежат ВСЕ даты публикации разом
    (фестиваль, прокат, издания), и промежуток между ними - не показ, а разнобой
    источников. Поэтому растяжение тут только для рода ``tv`` и только там, где годов
    названо больше одного: одинокий год - это дата, а не срок.
    """
    if ask.year is None:
        return True
    seen = row.years or known.get(row.entity, set())
    if any(abs(one - ask.year) <= _SLACK for one in seen):
        return True
    return ask.kind == "tv" and len(seen) > 1 and min(seen) <= ask.year <= max(seen)
