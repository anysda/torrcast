"""Год, названный самим именем статьи; зовёт отбор статей постера."""

from __future__ import annotations

import re
from typing import Final

#: Уточнение года в имени русской статьи: «Матрица (фильм, 1999)». Разделитель тут
#: именно запятая с годом в скобках - так уточняет русский раздел, и так же складывает
#: кандидатов :func:`~torrcast.domain.facts.titles_for.titles_for`.
_YEAR_RE: Final = re.compile(r",\s*(\d{4})\s*\)\s*$")


def named_year(name: str) -> int | None:
    """Год из уточнения в имени статьи; уточнения нет - ``None``.

    Имя, которое год называет само, сверять больше нечем и незачем: русский раздел уже
    ответил статьёй ровно под этим именем. Такое подтверждение стоит ноль запросов, и
    ради него уточнённые кандидаты и стоят в очереди имён.
    """
    match = _YEAR_RE.search(name.strip())
    return int(match.group(1)) if match else None
