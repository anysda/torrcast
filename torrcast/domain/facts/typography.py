"""Тем же именем, но типографикой раздела; зовёт очередь имён статьи.

Подпись у картины одна, а знаков препинания для неё два набора. Раздача пишет своими:
прямые кавычки и двоеточие перед подзаголовком. Википедия пишет своими: ёлочки и точка.
Расходятся они молча, и статья при этом ЕСТЬ - «Рерберг и Тарковский. Обратная сторона
«Сталкера»» лежит на месте, а под именем раздачи не находится ничего.

🔴 Редирект со «своей» формы раздел держит НЕ всегда, и надеяться на его нормализацию
нельзя: из пяти проверенных форм три не нашли статьи вовсе («Всё ещё на троне: наследие
"Короля и Шута"», «Читаем "Блокадную книгу"», «Рерберг и Тарковский: Обратная сторона
"Сталкера"»), а две нашли («Анатомия "Тату"» и та же «Обратная сторона» с точкой). То
есть форма раздачи угадывает примерно через раз - это и делает разнобой классом, а не
одной строкой.
"""

from __future__ import annotations

import re
from typing import Final

#: Прямая или «программистская» пара кавычек вокруг куска имени. Ёлочки раздел ставит и
#: внутри имени, и по краям, поэтому меняется ПАРА целиком, а не отдельный знак: одиночная
#: кавычка бывает апострофом («Rock'n'Roll»), и трогать её нечем.
_QUOTED: Final = re.compile(r'["“]([^"“”]+)["”]')
#: Двоеточие перед подзаголовком. Пробел после обязателен: без него двоеточие бывает
#: частью времени или счёта, а не разделителем подписи.
_COLON: Final = ": "


def typography(title: str) -> list[str]:
    """Формы этого имени в типографике раздела, в порядке доверия.

    Первой идёт форма с ёлочками: под ней статья лежит, а прямые кавычки раздел держит
    редиректом через раз. Второй - она же с точкой вместо двоеточия, и только когда
    двоеточие в имени есть: у сериалов и франшиз («Дюна: Часть вторая») двоеточие как раз
    СВОЁ, поэтому форма с точкой не заменяет первую, а становится рядом.
    """
    named = title.strip()
    if not named:
        return []
    quoted = _QUOTED.sub(r"«\1»", named)
    out = [quoted]
    if _COLON in quoted:
        out.append(quoted.replace(_COLON, ". ", 1))
    return out
