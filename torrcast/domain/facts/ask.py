"""Просьба о постере одной картины; её знают и список обзора, и карточка плеера."""

from __future__ import annotations

from typing import NamedTuple


class Ask(NamedTuple):
    """Картина, про которую спрашивают постер: чем её отличают от тёзки.

    Год и род тут не украшение: «Матрица» 1999 года и «Матрица» 2021-го - разные
    картины, и постер соседки хуже, чем никакого. Оригинальное имя стоит рядом
    отдельным полем, потому что у части находок русской статьи нет вовсе, а
    английская лежит ровно под ним («Armitage: Dual-Matrix»).
    """

    title: str
    year: int | None
    kind: str
    original: str = ""
