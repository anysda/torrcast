"""Разбиение очереди на порции под предел одного запроса; зовут адаптеры справки.

Предела тут два, и второй не очевиден. Первый - сколько имён API берёт за раз
(полсотни для гостя). Второй - ДЛИНА адреса: имена уезжают в строке запроса, а русская
буква в ней занимает шесть знаков вместо одного, и полсотни русских имён дают адрес,
на который Википедия отвечает «414 URI Too Long» - молча для того, кто считал имена.
"""

from __future__ import annotations

from collections.abc import Iterator, Sequence


def in_budget(names: Sequence[str], size: int, budget: int) -> Iterator[list[str]]:
    """Порции имён под оба предела разом: и по счёту, и по длине будущего адреса.

    Длина считается по худшему случаю кодирования - три знака на байт: так порция
    остаётся годной и для имени из одних русских букв, и для имени из одних латинских.
    Имя, которое не влезает в бюджет в одиночку, всё равно уезжает своей порцией: пусть
    ответит сервер, а не молчаливый пропуск.
    """
    part: list[str] = []
    taken = 0
    for name in names:
        cost = len(name.encode("utf-8")) * 3 + 3
        if part and (len(part) >= max(size, 1) or taken + cost > budget):
            yield part
            part, taken = [], 0
        part.append(name)
        taken += cost
    if part:
        yield part
