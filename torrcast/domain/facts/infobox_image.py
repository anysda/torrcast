"""Имя файла постера из вики-текста инфобокса; зовёт адаптер постера."""

from __future__ import annotations

import re
from typing import Final

#: Строка инфобокса с постером. Имя параметра тут ровно ``image`` либо русское
#: ``изображение``, а не всё, что с них начинается: ``image_size``, ``image_upright``,
#: ``image_alt``, «описание изображения» и «формат изображения» описывают ВЁРСТКУ и
#: подпись, и попади они сюда, за адресом уехало бы «250px» или пустая строка.
#: Русское имя пишется в шаблонах и со строчной («Телесериал»), и с прописной
#: («Фильм»), поэтому сверка идёт без учёта регистра.
_IMAGE_RE: Final = re.compile(
    r"^[ \t]*\|[ \t]*(?:image|изображение)[ \t]*=[ \t]*(?P<value>[^\n]*)",
    re.MULTILINE | re.IGNORECASE,
)
#: Что вокруг имени файла бывает написано: разметка вставки и комментарий редактора.
_WRAPPERS: Final = re.compile(r"<!--.*?-->|\[\[|\]\]|\{\{|\}\}", re.DOTALL)
#: Приставка пространства имён файла. Разделов тут ДВА, английский и русский, поэтому
#: и приставок четыре: русская разметка пишет «Файл:» и «Изображение:».
_PREFIX: Final = re.compile(r"^(?:file|image|файл|изображение)\s*:\s*", re.IGNORECASE)
#: Чем обязано кончаться имя файла. Это не украшение, а гейт: у «Уэнздей» в ``image``
#: стоит логотип ``.svg``, а у соседних статей на том же месте бывает ``{{multiple
#: image}}`` или голый комментарий редактора - без проверки за адресом уехало бы слово
#: «multiple image», и ``imageinfo`` ответил бы пустотой на каждой такой картине.
_PICTURE_RE: Final = re.compile(r"\.(?:jpe?g|png|gif|svg|webp)$", re.IGNORECASE)


def infobox_image(wikitext: str) -> str:
    """Файл постера из первой секции статьи; нет такой строки - пустая строка.

    Постер несвободен, и поэтому его не отдаёт ни ``pageimages`` (берёт только свободные
    файлы), ни список файлов статьи: список неупорядочен, и «портретный jpg покрупнее» -
    это снимок NASA у «Интерстеллара» и портрет Киану Ривза у «Матрицы». Единственное
    место, где статья называет свой постер ИМЕНЕМ, - строка ``| image =`` инфобокса
    (в русском разделе ``| изображение =``), и читается она отсюда.

    🔴 Русский раздел свою обложку держит, вопреки прежнему тут утверждению: у
    «Чернобыль. Зона отчуждения» английская статья есть, а ``| image =`` в ней ПУСТ,
    и постер лежит только в русской. Пока читался один английский раздел, такие
    находки получали имя картинки без единого байта за ним.

    Значение бывает завёрнуто в разметку вставки (``[[File:…|250px]]``) и разбавлено
    комментарием редактора; всё это снимается, а от оставшегося берётся голова до первой
    вертикальной черты - дальше идут подписи и размеры, а не имя.
    """
    found = _IMAGE_RE.search(wikitext)
    if found is None:
        return ""
    value = _WRAPPERS.sub("", found.group("value")).split("|", 1)[0].strip()
    name = _PREFIX.sub("", value).strip()
    return name if _PICTURE_RE.search(name) else ""
