"""Доказала ли справка отечественное происхождение картины; зовут оба места отбора звука."""

from __future__ import annotations

from torrcast.domain.facts.origin import Origin
from torrcast.domain.facts.same_name import same_name


def proven_native(about: Origin, title: str) -> bool:
    """Доказано ли справкой, что безымянная дорожка этой картины - её собственная.

    Признак дорогой: им безымянная дорожка засчитывается за русскую
    (:func:`~torrcast.usecases.rank.voice_unproven.voice_unproven`) и поднимается над всеми
    переводами (:data:`~torrcast.domain.audio_track.STEP_NATIVE`). Ошибка тут стоит зрителю
    картины: чужой звук поедет на экран при непустой очереди позади.

    Поэтому нужны ОБА условия, и они про разное:

    * :attr:`~torrcast.domain.facts.origin.Origin.native` - справка утверждает, что имени на
      чужом языке у картины нет. Одного пустого ``title`` мало: он же получается, когда
      имя есть, но записано не латиницей, и когда статью не читали вовсе;
    * :func:`same_name` - утверждение это про ТУ САМУЮ картину: заголовок статьи и имя,
      названное человеком, - одно имя.

    Карта прокатных имён сюда не отвечает никогда, и это не пробел. Оригинал она называет
    всегда, но романизацией: у «Бригады» там стоит ``Brigada``, и отличить по такому
    ответу отечественную картину от зарубежной нечем.

    Молчит справка - молчит и признак: прежнее поведение, показ не роняется, а безымянная
    дорожка просто остаётся неподтверждённой, как всякая другая.
    """
    return bool(about.native and about.name and not about.title and same_name(title, about.name))
