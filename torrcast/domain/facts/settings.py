"""Пороги, сроки и пути справки; их читают правила и адаптеры справки."""

from __future__ import annotations

from pathlib import Path
from typing import Final

#: Выгрузка IMDb ``title.ratings.tsv``: ``tconst<TAB>рейтинг<TAB>голоса``. Кладёт и
#: обновляет `install.sh`; нет файла - просто не будет рейтинга.
RATINGS_PATH: Final = Path("/var/lib/torrcast/imdb-ratings.tsv")


#: Офлайн-карта русских прокатных имён IMDb: ``имя<TAB>tconst<TAB>тип<TAB>оригинал<TAB>год``.
#: Собирает `install.sh` из выгрузок ``title.akas`` и ``title.basics``; нет файла -
#: картина без русской статьи остаётся без паспорта, и это не сбой.
RU_NAMES_PATH: Final = Path("/var/lib/torrcast/imdb-ru-names.tsv")


#: Чем отвечена справка: русская Википедия. Сюда же попадают все её обходы - выборка по
#: имени, поиск, подсказки написания, перенаправление: источник у них один.
SOURCE_WIKI: Final = "wiki"


#: Чем отвечена справка: офлайн-карта русских прокатных имён IMDb (:data:`RU_NAMES_PATH`).
SOURCE_MAP: Final = "map"


#: Чем подтверждён год одинокого ответа: Wikidata P577 (:func:`_second_source_year`).
SOURCE_WIKIDATA: Final = "wikidata"


#: Разделитель, когда паспорт собран из двух источников («wiki+map»): имя дала статья, год
#: дописала карта. Порядок - в котором источники отвечали, и он значащий.
SOURCE_JOIN: Final = "+"


#: Найденная справка ложится сюда, чтобы второй показ той же франшизы не ходил в сеть.
CACHE_PATH: Final = Path("/var/lib/torrcast/facts.json")


#: Сколько меню согласно ждать справку, секунды. Потолок, а не ожидание: в норме оба
#: запроса укладываются в секунду, и ждать нечего - они идут, пока греются раздачи.
FACTS_BUDGET: Final = 1.5


#: Потолок одного сетевого запроса. Меньше общего бюджета: их два, и второй зависит от
#: первого; залипший запрос обязан отпустить меню, а не съесть весь бюджет.
HTTP_TIMEOUT: Final = 1.2


#: Сколько добор живёт ВСЕГО, секунды, считая от :meth:`Facts.start`. Меню отпускается
#: через :data:`FACTS_BUDGET`, а поток дописывает кэш ещё столько - уже никого не держа.
TOPUP_LIMIT: Final = 3.0


#: Сколько помним, что справки нет, секунды. Пустой ответ - тоже ответ: без него каждое
#: меню снова шло в сеть за той же самой пустотой, снова не успевало к дедлайну и снова
#: печаталось голым. Срок конечный - статью могли и написать.
EMPTY_TTL: Final = 7 * 24 * 3600


#: Потолок правдоподобного хронометража, минуты. Картины длиннее суток не бывает, а
#: число, которое врёт в шестьдесят раз, подрывает доверие ко ВСЕЙ строке справки -
#: и к рейтингу рядом с ним тоже. Поэтому за этой границей хронометраж не печатается
#: вовсе: лучше строка без него, чем строка с выдумкой.
RUNTIME_CAP_MINUTES: Final = 24 * 60


#: Кем представляемся Wikimedia: у них это требование к автоматике, а не вежливость.
USER_AGENT: Final = "torrcast/1.0 (https://github.com/anysda/torrcast)"


#: Сколько статей влезает в один запрос ``prop=extracts`` (лимит самого API).
_EXLIMIT: Final = 20


#: Сколько таких запросов справка задаёт РАЗОМ (:func:`wiki_extracts`). Кандидатов на
#: статью у картины около десятка, и в меню из семи их под сотню: одним запросом до
#: Википедии доезжала пара имён на картину, а уточнение «(мультфильм)» не доезжало вовсе.
#: Запросы ждут сеть, а не друг друга, поэтому втрое больше имён стоят семи сотых секунды.
_EXBATCHES: Final = 3


#: Сколько символов статьи просим у Википедии. Раньше просили две фразы (``exsentences``),
#: но фразы там режет тот же наивный счёт точек, от которого мы уходим: у «Дюны» ответ
#: приезжал обрубком ««Дюна» (англ. Dune), в титрах «Дюна: Часть первая» (англ.» - и
#: дочитать его было негде. Символы такого не умеют, а границу фразы мы ставим сами
#: (:func:`sentence`). 500 символов на статью - это ~20 КБ на всю франшизу и те же 0.5 с.
_EXCHARS: Final = 500


#: Потолок описания в меню, символы. Первая фраза статьи почти всегда короче (у «Тачек»
#: 158, у «Моаны» 216); длиннее бывают биографические - у «Оппенгеймера» она идёт на 360
#: символов вместе с полным названием книги-первоисточника. Такую дочитывать в меню незачем,
#: и только её мы обрываем многоточием.
BLURB_CAP: Final = 240


#: Сколько статей смотрим в выдаче поиска Википедии. Нужная лежит в первых строках;
#: глубже идут актёры и саундтреки, и они только тянут ответ.
_SEARCH_HITS: Final = 6


#: Сколько подсказок берём у Википедии на одно написание. Нужное лежит в первых строках,
#: дальше идут однофамильцы - и всё равно каждую подсказку сверяет :func:`_near_name`.
_SUGGEST_HITS: Final = 6


#: Со скольких слов имя можно спрашивать по куску: у двух слов кусок - это одно слово, а
#: одним словом в заголовке совпадает пол-Википедии.
_PHRASE_WORDS: Final = 3


#: Во сколько раз совпавшая часть имени обязана перевесить разошедшееся слово. Полтора -
#: это «мальчик и цапля» против «Мальчик и птица» (8 букв совпало, 5 разошлось), но уже
#: не «Все мы незнакомцы» против «Все мы убийцы» (5 против 10).
_ODD_WEIGHT: Final = 1.5


#: Короче этого одна буква разницы - уже другое имя, а не другая транскрипция.
_NEAR_LETTERS: Final = 7
