"""Найденная статья вместе с тем, чем сверяется её год; зовёт отбор статей постера."""

from __future__ import annotations

from typing import NamedTuple


class Dated(NamedTuple):
    """Статьи одной картины и чем сверить их год: годы даром и сущность Wikidata на запас.

    ``years`` пусто - значит, статья про свой год не сказала ничего, и спрашивать
    придётся Wikidata по ``entity``. Это НЕ то же самое, что «год не тот».

    🔴 Статей тут ДВЕ, и обе несут постер. ``page`` - английская, ``source`` - русская;
    любая из них бывает пустой. Русская держится рядом не для полноты: несвободную
    обложку английский раздел кладёт в инфобокс не всегда, а русский на том же месте
    держит свою - и снятая с неё картинка спасает ровно те находки, у которых
    ``| image =`` английской статьи пуст.
    """

    page: str
    entity: str
    years: frozenset[int]
    kinds: frozenset[str] = frozenset()
    source: str = ""
