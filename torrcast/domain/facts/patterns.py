"""Выражения, которыми справка читает статью Википедии; зовут их правила разбора."""

from __future__ import annotations

import re
from typing import Final

#: Уточнения в скобках, которыми русская Википедия разводит одноимённые статьи.
#: «Моана» - это страница значений, а мультфильм лежит под «Моана (мультфильм)».
_QUALIFIERS: Final = (
    "",
    " (мультфильм)",
    " (фильм)",
    " (телесериал)",
    " (мультфильм, {year})",
    " (фильм, {year})",
)


#: Как русская Википедия подписывает оригинальное название: «(англ. Kingsman: The Secret
#: Service)». Язык любой - важно, что перед названием стоит его сокращение с точкой.
_ORIGINAL_RE: Final = re.compile(r"\(\s*(?:[а-яё]{2,12}\.\s*)+([^)]+)\)")


#: Год выпуска из паспортной фразы статьи: «...комедийный боевик 2014 года». Именно «года»,
#: а не первое попавшееся число: у фильма «1917» первым в тексте стоит его название.
_YEAR_RE: Final = re.compile(r"\b(1[89]\d{2}|20\d{2})\s+года")


#: Про кино ли статья вообще. «Восхождение» - это ещё и альпинизм, а «Матрица» - таблица.
#: Франшиза сюда входит намеренно: у «Кингсмана» отдельной статьи о первой части нет,
#: а имя франшизы - ровно то, которым её подписывают индексеры.
#:
#: ⚠️ Слова «фильм» и «сериал» ловятся ЦЕЛИКОМ, а не подстрокой, и это ограждение, а не
#: придирка. Подстрокой сюда проходила чужая биография: у Эммы Уотсон стоит «в фильмах о
#: Гарри Поттере», у Аарона Пола - «в сериале „Во все тяжкие“», и справка бодро выдавала
#: «Emma Charlotte Duerre Watson» за оригинальное название картины. Косвенный падеж - это
#: упоминание кино, а сама статья про человека; тип картины стоит в именительном.
#:
#: ⚠️ «Серия фильмов» вписана отдельным оборотом, и это ровно та поблажка, которую
#: правило целого слова запрещает. Статью о франшизе русская Википедия открывает словами
#: «Гарри Поттер (англ. Harry Potter) - серия фильмов, основанных на книгах», где «фильмов»
#: стоит в косвенном падеже - и гейт её отвергал. А отвергнув франшизу, справка доходила
#: до первой попавшейся ЧАСТИ и выдавала её паспорт за паспорт всей серии. Косвенный падеж
#: пропускается только в связке со словом «серия»: «в фильмах о Гарри Поттере» (биография
#: Эммы Уотсон) под неё не подходит, и та дыра остаётся закрытой.
_CINEMA_RE: Final = re.compile(
    r"(?:фильм|сериал)\b|сери[яию]\s+(?:мульт)?фильмов|кинокартин|аниме|франшиз", re.IGNORECASE
)


#: Тип картины, записанный без киношного слова: статья о «Во все тяжкие» открывается
#: словами «американская телевизионная криминальная драма» - ни «фильма», ни «сериала» в
#: ней нет, и оригинал (Breaking Bad) поиску не доставался. Экранного признака одного мало:
#: «американская телевизионная сеть» - это NBC, а «телевизионных сервисов» - HBO, поэтому
#: рядом обязан стоять жанр. Жанр тоже сам по себе ничего не значит: драма бывает и
#: театральная, и книжная.
_SCREEN_RE: Final = re.compile(r"телевизионн", re.IGNORECASE)


#: Каким словом статья объявляет СВОЙ тип: фильм она или сериал. Ими разводится
#: экранизация и исходный сериал - см. :func:`_fits_type`. Подстрокой намеренно:
#: «мультфильм», «кинофильм», «телефильм» - всё это фильм, а «телесериал» и
#: «аниме-сериал» - сериал.
_FILM_WORD_RE: Final = re.compile(r"фильм|кинокартин|полнометражн", re.IGNORECASE)


_SERIES_WORD_RE: Final = re.compile(r"сериал|телевизионн|сезон", re.IGNORECASE)


#: Жанр картины. Приставки «кино-» и «теле-» приклеены нарочно: классику русская
#: Википедия подписывает одним словом - «эпическая самурайская кинодрама» у «Семи
#: самураев», - и без них жанра в статье будто нет вовсе.
_GENRE_RE: Final = re.compile(
    r"\b(?:кино|теле)?"
    r"(?:драма|драмеди|комедия|мелодрама|боевик|триллер|детектив|вестерн|мюзикл|антология)\b",
    re.IGNORECASE,
)


#: Первая фраза открывается названием в кавычках: «Похитители велосипедов» (итал. Ladri di
#: biciclette) - так русская Википедия начинает статью о ПРОИЗВЕДЕНИИ. У человека, студии
#: и телесети начало другое - имя без кавычек, - и это ровно та граница, на которой стоит
#: гейт :func:`_about_cinema`.
_TITLED_RE: Final = re.compile(r"^[«\"“]")


#: Год выпуска в паспортной формуле: «1948 года», «вышедший на экраны в 1962 году». Год
#: тут - признак того, что у произведения есть дата выхода, а не опора для гейтов
#: (для них :func:`picture_year` строже).
_MADE_RE: Final = re.compile(r"\b(?:1[89]\d{2}|20\d{2})\s+год")


#: Кириллица в заголовке: по ней видно, годится ли он сам как оригинальное название.
_CYRILLIC: Final = re.compile(r"[а-яё]", re.IGNORECASE)


#: Иероглифы и слоговые азбуки. Скобка первой фразы у японского кино двуязычна («яп.
#: 進撃の巨人 エンド オブ ザ ワールド Shingeki no Kyojin: Endo obu za Wārudo»), и латиница в
#: ней есть - но выдать ЭТО индексеру за название нельзя. Такую скобку пропускаем: имя
#: возьмётся из английской статьи (:func:`english_title`), где оно записано именем.
_CJK: Final = re.compile(r"[぀-ヿ㐀-鿿가-힯]")


#: Строка-указатель, которой статья открывается ДО собственной первой фразы: «О сериале
#: см. статью 7 самураев.» Ею Википедия разводит одноимённое, а фразой о картине она не
#: является вовсе - и именно её читали все, кто читает первую фразу. У «Семи самураев»
#: (Куросава, 1954) из-за неё :func:`_fits_type` видел слово «сериале», отвергал статью
#: фильма и уходил в соседнюю - аниме-ремейк «7 самураев», - откуда справка уверенно
#: приносила ``Samurai 7`` как оригинал классики. Указатель отрезается целиком: он
#: кончается точкой и пробелом, а за ним стоит настоящая первая фраза.
_HATNOTE_RE: Final = re.compile(
    r"^\s*(?:О[бо]?|Не\s+следует|У\s+этого|Запрос)\b[^.]{0,120}?\bсм\.\s[^.]{0,160}?\.\s+"
)


#: Уточнение в конце заголовка статьи: «Wednesday (TV series)», «Восхождение (фильм, 1976)».
#: Им Википедия разводит одноимённое, а индексерам оно ни к чему - раздачу подписывают
#: именем без скобки, и именно имя мы у справки и берём.
_TAIL_RE: Final = re.compile(r"\s*\([^)]*\)\s*$")


#: Последнее слово перед точкой - по нему видно, конец это фразы или сокращение.
_LAST_WORD_RE: Final = re.compile(r"([A-Za-zА-Яа-яЁё]+)[^A-Za-zА-Яа-яЁё]*$")


#: С чего начинается новая фраза: заглавная буква или открывающая кавычка названия.
_SENTENCE_START_RE: Final = re.compile(r"[«\"“A-ZА-ЯЁ]")


#: Сокращения, после которых точка ничего не кончает. Языки оригинала («англ.», «бел.»,
#: «фр.») в русской статье о кино стоят в каждой первой фразе, остальное - то, чем она
#: обрастает: «реж.», «т. е.», «им.», «др.». Однобуквенные сюда не нужны: инициал
#: («Г. А. Потёмкина») и «т. е.» ловятся правилом «одна буква - не слово».
_ABBREV: Final = frozenset(
    (
        # языки оригинала
        "англ", "фр", "нем", "итал", "исп", "яп", "кит", "кор", "бел", "укр", "рус",
        "лат", "греч", "польск", "чеш", "швед", "норв", "фин", "дат", "нидерл", "порт",
        "тур", "перс", "араб", "иврит", "серб", "хорв", "рум", "венг", "эст", "лит",
        # прочее, чем обрастает первая фраза
        "букв", "дословно", "транслит", "сокр", "совр", "устар", "прим", "ср", "см",
        "напр", "др", "пр", "тыс", "млн", "млрд", "руб", "коп", "гг", "вв", "нэ", "ок",
        "реж", "сцен", "опер", "комп", "худ", "прод", "им", "ул", "пл", "св", "стр", "гл",
    )
)  # fmt: skip


#: Разбор готовой строки хронометража обратно в минуты (:func:`minutes_of`).
_RUNTIME_RE: Final = re.compile(r"^(?:(\d+)\s*ч)?\s*(?:(\d+)\s*мин)?$")


#: Каким произведением статья себя объявляет - в любом виде, а не только экранном. Список
#: нужен единственному пути :func:`redirected_name`, где статья и так доказана
#: перенаправлением, и отвечает он на один вопрос: произведение это или что-то ещё.
_WORK_RE: Final = re.compile(
    r"визуальн|новелл|манга|манги|ранобэ|аниме|\bигр\w*|роман|фильм|сериал|франшиз|комикс",
    re.IGNORECASE,
)
