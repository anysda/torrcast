"""Выдача статьи без строки-указателя, склеенная в строку; её читают первая фраза и гейты."""

from __future__ import annotations

import re

from torrcast.domain.facts.patterns import _HATNOTE_LINE_RE, _HATNOTE_RE


def unhatted(text: str) -> str:
    """Текст статьи без шляпки и в одну строку - всё, что статья говорит О СЕБЕ.

    Шляпка («Не путать с ...», «О сериале см. статью 7 самураев.») это разводка
    одноимённого: чужой текст про ЧУЖУЮ картину, приклеенный к началу выдачи. Своего в
    нём нет ни слова, и всякий, кто судит статью по её тексту, обязан читать выдачу
    отсюда, а не из ``extract``.

    🔴 Снимается шляпка ДВАЖДЫ и в таком порядке: сперва абзацем по сырому тексту
    (:data:`~torrcast.domain.facts.patterns._HATNOTE_LINE_RE`), пока переносы строк ещё
    на месте, и только потом - по склеенной строке
    (:data:`~torrcast.domain.facts.patterns._HATNOTE_RE`). Наоборот нельзя: указатели без
    слова «см.» точкой не кончаются вовсе, кончаются они переносом строки, а склейка
    съедает эту единственную границу - и резать указатель приходится по угаданной
    подстроке. Стоил этот порядок половины строки меню (TC-908).
    """
    lead = _HATNOTE_LINE_RE.sub("", text.lstrip())
    return _HATNOTE_RE.sub("", re.sub(r"\s+", " ", lead).strip())
