"""Одна другая часть той же франшизы; её собирает разбор ответа Wikidata."""

from __future__ import annotations

from typing import NamedTuple


class Kin(NamedTuple):
    """Родня картины: как её зовут, какого она года и её Q-идентификатор.

    ``entity`` едет вместе с именем и годом не для показа, а на запас: вторым шагом по
    ней можно спросить постер тем же путём, что и у выдачи, не гадая заново, какая из
    находок это была. ``ru`` - ЧИСТЫЙ русский ярлык Wikidata (не запасной ``name``,
    который иногда сползает на английский даже при живом русском ярлыке, TC-1321);
    пусто - Wikidata русского не назвала вовсе.
    """

    entity: str
    name: str
    year: int | None
    ru: str = ""
