"""Имена, под которыми статья может лежать в Википедии; зовёт добор справки."""

from __future__ import annotations

from collections.abc import Iterable

from torrcast.domain.facts.patterns import _QUALIFIERS
from torrcast.domain.facts.typography import typography


def titles_for(
    title: str, year: int | None, kind: str = "", asked: Iterable[str] = ()
) -> list[str]:
    """Под какими именами статья может лежать в русской Википедии, в порядке доверия.

    Первым — само название: «Тачки 2» так и называется. Дальше уточнения в скобках,
    которыми Википедия разводит одноимённое: «Моана» голым именем — это страница
    значений про полинезийское слово, а мультфильм 2016 года лежит под «Моана
    (мультфильм)», ремейк 2026-го — под «Моана (фильм, 2026)».

    Подзаголовок после двоеточия отрезается отдельным кандидатом: раздачи подписывают
    старое кино развёрнуто («Моана: романтика золотого века»), а статья называется
    короче.

    🔴 Отрезанное имя НЕ предлагается, когда им названа другая картина того же вопроса
    (``asked``). Сверка года тут не спасала и спасти не могла: «Титаник: анатомия
    катастрофы» 1997 года отрезается до «Титаника», кандидат «Титаник (фильм, 1997)» - это
    адрес соседа по меню, и год у соседа ТОТ ЖЕ. Документальная лента получала описание и
    хронометраж кэмероновского «Титаника», то есть паспорт чужой картины, а человек читал
    его как её собственный (TC-957). Имя, которым названа картина рядом, принадлежит ей;
    у длинного соседа остаётся своё полное имя, а не нашлось статьи под ним - справки нет,
    и это честнее чужой.

    🔴 Уточнения выстраиваются по СПРОШЕННОМУ типу (:func:`_ordered`), и это не украшение
    очереди. Имён у меню под сотню, а в запросы влезает шестьдесят
    (:func:`~torrcast.adapters.wiki.wiki_extracts.wiki_extracts`): до Википедии доезжают
    первые несколько кандидатов каждой картины, и уточнение чужого типа, стоящее раньше
    своего, просто съедает место настоящей статьи. У «Робокопа» так и было: «(телесериал)»
    уезжал, «(фильм, 1987)» - уже нет, и на весь показ у фильма оставалась одна чужая
    статья. Набор имён от порядка не меняется ни на одно - меняется, кто из них успеет.

    Регистр внутри слова Википедия сама не чинит: ``redirects=1`` нормализует лишь ПЕРВУЮ
    букву. «breaking bad» уходит в «Breaking bad» и мимо статьи, тогда как редирект есть с
    «Breaking Bad»; так же теряются «fruits basket», «twin peaks», «true detective». Поэтому
    к именам добавляются регистровые варианты голого имени - заглавные слова и нижний
    регистр. Лишний кандидат чужого не тащит (год и заголовок всё равно сверяются), а
    редирект по нужному написанию находится в той же прямой выборке, без похода в поиск.

    Знаки препинания раздача и раздел ставят РАЗНЫЕ (:func:`~torrcast.domain.facts.
    typography.typography`), поэтому имя приводится к типографике раздела, а вторая его
    форма встаёт сразу за голым именем - раньше уточнений. Место в очереди тут и есть весь
    смысл: до постера доезжают первые шесть имён, и форма, стоящая за семью уточнениями,
    не доезжает никуда.
    """
    forms = typography(title) or [title.strip()]
    bases = [forms[0]]
    head = forms[0].split(":", 1)[0].strip()
    others = {name.strip().casefold() for name in asked} - {bases[0].casefold()}
    if head and head != bases[0] and head.casefold() not in others:
        bases.append(head)
    out: list[str] = []
    for base in bases:
        for qualifier in _ordered(kind):
            if "{year}" in qualifier and year is None:
                continue
            name = base + qualifier.format(year=year)
            if name not in out:
                out.append(name)
    out[1:1] = [name for name in forms[1:] if name not in out]
    for base in bases:
        for variant in (base.title(), base.lower()):
            if variant != base and variant not in out:
                out.append(variant)
    return out


def _ordered(kind: str) -> tuple[str, ...]:
    """Уточнения в порядке спрошенного типа: чужой тип - в хвост очереди.

    Голое имя остаётся первым при любом типе: под ним лежит и сама статья, и страница
    значений, и разбирать это не очереди. Тип не назван или назван «other» - порядок
    остаётся объявленным: подсказывать нечем, и выдумывать подсказку нельзя.
    """
    if kind not in ("movie", "tv"):
        return _QUALIFIERS
    series = kind == "tv"
    ours = [name for name in _QUALIFIERS if name and ("сериал" in name) is series]
    theirs = [name for name in _QUALIFIERS if name and ("сериал" in name) is not series]
    return ("", *ours, *theirs)
