"""Паспорт картины и сверка двух паспортов; ими живут поиск и гейт добора."""

from __future__ import annotations

from dataclasses import dataclass

from torrcast.domain.slugify import slugify


@dataclass(frozen=True, slots=True)
class Origin:
    """Паспорт картины по справке: как она называется в оригинале и какого она года.

    Оба поля необязательны и означают ровно то, что сказано. Пустой ``title`` — у картины
    нет названия латиницей (советское и российское кино), а не «мы не нашли»: добирать
    латиницей такую картину нечем и не нужно. Пустой ``year`` — статью опознать не
    удалось; тогда гейт добора сверяет годы по самой выдаче, как умеет.

    ``name`` - как ту же картину зовут по-русски (заголовок русской статьи). Нужен
    зеркальному случаю: спросили латиницей, а половина каталога подписана по-русски
    («Cars» - одна мёртвая раздача при живых «Тачках»), и добирать надо русским именем.
    """

    title: str = ""
    year: int | None = None
    name: str = ""
    #: Q-идентификатор статьи в Wikidata. Не паспорт сам по себе (в :meth:`__bool__` не
    #: входит и в кэш пишется отдельно), а ключ ко второму источнику: по нему одинокий год
    #: сверяется с датой публикации P577 (:func:`origin_either`, :func:`confirmed_year`).
    entity: str = ""
    #: Статью не назвали по имени, а лишь ПРИЗНАЛИ похожей (:func:`_misremembered`): имя
    #: спросили одно, подписана она другим. Обычно это описка человека («Сальтберн» и
    #: «Солтберн»), но ровно так же выглядит и чужая картина («Все мы незнакомцы» и «Все мы
    #: убийцы»), поэтому гейт добора такому имени на слово не верит
    #: (:func:`~torrcast.usecases.discover._second_language._second_language`).
    guessed: bool = False
    #: 🔴 TC-567. Справка ПРОЧИТАЛА статью этой картины и имени на чужом языке в ней не
    #: нашла - ни латиницей, ни другим письмом (:func:`named_original`). Это и есть
    #: доказательство отечественного происхождения, и без него пустой ``title`` его не
    #: даёт: та же пустота получается у зарубежной картины, чьё имя записано иероглифами
    #: или кириллицей другой страны, и у любого ответа, который статью не читал вовсе -
    #: карты имён, догадки по сходству, перенаправления. Признак ставит только тот, кто
    #: статью читал; всем остальным путям тут нечего сказать, и они молчат.
    #:
    #: Им живёт единственный вопрос - чья безымянная дорожка в файле
    #: (:func:`~torrcast.domain.facts.proven_native.proven_native`): у отечественной
    #: картины она её собственная, а у зарубежной это чужой звук зрителю.
    native: bool = False
    #: Заголовок ДРУГОЙ картины того же года, которую справка знает под тем же именем
    #: (:func:`namesake`). Не паспорт, а повод для честной строки: развести такую пару
    #: разбору нечем, и человек обязан о ней прочитать
    #: (:func:`~torrcast.usecases.choice.namesake_note.namesake_note`).
    namesake: str = ""
    #: 🔴 TC-450. ЧЕМ отвечена справка: :data:`SOURCE_WIKI`, :data:`SOURCE_MAP` или их
    #: сумма («wiki+map» - имя дала статья, год дописала карта), плюс
    #: :data:`SOURCE_WIKIDATA` у года, подтверждённого вторым источником.
    #:
    #: В паспорт картины поле не входит и в :meth:`__bool__` не участвует: на показ оно не
    #: влияет никак. Нужно оно ровно для одного - чтобы по сохранённому прогону можно было
    #: СОСЧИТАТЬ, чего стоит каждый источник. Карта имён - отдельная фаза установки, свой
    #: греющий поток и сотни мегабайт промежуточных файлов, а без этой отметки «карта
    #: помогла N раз» оставалось догадкой: валовое покрытие не говорит, скольким запросам
    #: оригинал уже дала бы одна Википедия.
    #:
    #: Пустая строка - источник не записан. Так выглядят ряды кэша, снятые до этой отметки:
    #: старый кэш читается как читался, и «неизвестно» не выдаётся за «Википедия».
    source: str = ""

    def __bool__(self) -> bool:
        return bool(self.title or self.year or self.name)


def _same_picture_origin(one: Origin, two: Origin) -> bool:
    """Один ли это фильм у двух паспортов: сходятся оригинал латиницей либо год.

    Русское имя у обоих одно (его и спросили), поэтому различает картины оригинал и год.
    «Дедвуд»: фильм ``Deadwood: The Movie`` 2006 и сериал ``Deadwood`` 2004 - ни оригинал,
    ни год не сходятся, значит это разные картины и подсказывать нечего.
    """
    same_latin = bool(slugify(one.title)) and slugify(one.title) == slugify(two.title)
    same_year = one.year is not None and one.year == two.year
    return same_latin or same_year
