"""Чем кончился разбор справки на языке продукта; читают их след и замер.

🔴 Пустая справка «статьи на этом языке нет» человеку НЕОТЛИЧИМА от пустой справки
«разборщик сломался», а это две разные новости: первая - честный итог, вторая - дефект.
Слей их в одно «пусто» - и долю пропавшей справки нельзя посчитать в принципе, потому что
знаменатель у неё разный. Поэтому исход называется тремя различимыми словами, и
:data:`BLANK` из них - именно дефект, а не отсутствие статьи.
"""

from __future__ import annotations

from typing import Final

#: Статья на языке продукта нашлась, и разбор вытащил из неё описание.
PARSED: Final = "разобрана"
#: Статьи на этом языке нет вовсе: межъязыковой ссылки у найденной статьи не оказалось.
#: Справки не будет, и подставлять чужой язык вместо неё нельзя - остаются имя, год, оценка.
ABSENT: Final = "нет статьи"
#: Статья названа, но разбор не вытащил из неё ничего: страница не приехала, оказалась
#: пустышкой или отдала пустой пересказ. Это ДЕФЕКТ, и виден он обязан быть дефектом.
BLANK: Final = "пусто"

__all__ = ["ABSENT", "BLANK", "PARSED"]
