"""Род, названный самим именем статьи; зовёт сверка рода у отбора статей постера.

Уточнение рода в имени - это слово не про картину, а про её ОКРУЖЕНИЕ: Википедия
приписывает его тогда и только тогда, когда голое имя занято тёзкой. «Паразиты (фильм)»
значит, что «Паразиты» бывают и не фильмом; «Аниматрица» значит, что других «Аниматриц»
на свете нет.
"""

from __future__ import annotations

import re
from typing import Final

#: Уточнение рода в имени статьи, русское и английское. Год внутри уточнения не мешает:
#: «Паразиты (фильм, 2019)» и «Parasite (2019 film)» разводят по роду ровно так же.
#: Русская половина повторяет :data:`~torrcast.domain.facts.patterns._QUALIFIERS` теми же
#: словами, какими очередь имён складывает своих кандидатов.
_KIND_RE: Final = re.compile(
    r"\(\s*(?:[а-яё]+[\s-])*(?:мульт|теле)?(?P<ru>фильм|сериал)\w*\s*(?:,\s*\d{4}\s*)?\)\s*$"
    r"|\(\s*(?:[a-z0-9]+\s)*(?P<en>film|movie|series|miniseries)\s*\)\s*$",
    re.IGNORECASE,
)
#: Слова уточнения, которыми назван СЕРИАЛ; всё остальное, что ловит выражение, - фильм.
#: Мини-сериал и мультсериал сериалы и есть, а «мультфильм» тут слово про фильм: родов у
#: справки два, и мультипликация не третий.
_SERIES_WORDS: Final = frozenset({"сериал", "series", "miniseries"})


def named_kind(heading: str) -> str:
    """Род, которым Википедия развела это имя: «movie», «tv»; имя не разведено - пусто.

    🔴 Пустота тут утверждение, а не незнание. Голое имя означает, что тёзки другого рода
    у картины нет, и значит наша ДОГАДКА о роде (метка серии в имени раздачи) целить в
    тёзку не может: статья под голым именем - это статья спрошенной картины, какого бы
    рода она ни оказалась. Полнометражная антология, раздаваемая по новеллам
    («Аниматрица»), опознаётся ровно этим (:func:`~torrcast.domain.facts.fits_ask.fits_ask`).

    Обратное так же строго: разведённое имя («Паразиты (фильм)») означает, что тёзка
    другого рода есть, и принять его вместо неё значит отдать зрителю чужую картинку под
    нашей подписью. Сериалу «Паразиты» постер корейского фильма 2019 года не достаётся.
    """
    match = _KIND_RE.search(heading.strip())
    if match is None:
        return ""
    said = (match.group("ru") or match.group("en") or "").casefold()
    if said in _SERIES_WORDS:
        return "tv"
    return "movie"
