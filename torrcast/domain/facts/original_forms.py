"""Формы оригинального имени картины: арабский номер части и римский; зовёт отбор статей."""

from __future__ import annotations

import re
from typing import Final

#: Номера частей, какие вообще встречаются у картин. Выше десятой франшизы не уходят, а
#: всё, что длиннее двух знаков, - это год или число в самом названии.
_ROMAN: Final = {
    "2": "II",
    "3": "III",
    "4": "IV",
    "5": "V",
    "6": "VI",
    "7": "VII",
    "8": "VIII",
    "9": "IX",
    "10": "X",
}
#: Номер части - ОТДЕЛЬНОЕ слово, а не цифра внутри слова. Без этой границы «Se7en» и
#: «District 9» разбирались бы по цифре посреди имени, а «2012» - по своему году.
_PART_RE: Final = re.compile(r"(?<!\w)(?:10|[2-9])(?!\w)")


def original_forms(original: str) -> list[str]:
    """Имена, под которыми английский раздел может держать эту картину; пусто - ничего.

    Раздачи пишут номер части арабской цифрой, а английский раздел - римской:
    «Poltergeist 2: The Other Side» лежит там под именем «Poltergeist II: The Other
    Side», и точная выборка по имени раздачи отвечала про него ``missing``. Так же
    устроены «Rocky IV», «Rambo III», «Halloween II» и «The Godfather Part II».

    Обратное тоже бывает - «Ocean's 11», «Mad Max 2» и «Final Destination 5» стоят под
    арабской цифрой, - поэтому форма не ЗАМЕНЯЕТСЯ, а добавляется второй. Обе едут в
    один и тот же запрос ``titles``, то есть в тот же поход: дорожает строка запроса, а
    не число походов.
    """
    name = original.strip()
    return (
        list(dict.fromkeys([name, _PART_RE.sub(lambda m: _ROMAN[m.group()], name)])) if name else []
    )
