"""Год раздачи - год ПЕРЕВЫПУСКА картины, а не год чужой; зовёт отбор статей постера.

Расширенная версия, юбилейное издание и реставрация выходят отдельной раздачей, и год
она пишет свой - год издания. Статья держит год выхода: у «Властелин колец: Братство
кольца» раздача несёт 2011-й, а статья - 2001-й. Пока годы сверялись членством в списке,
такая раздача оставалась без обложки при живой статье своей собственной картины.

🔴 Допуск :data:`~torrcast.domain.facts.fits_ask._SLACK` под это трогать нельзя. Он
симметричен - и потому добирает соседку по имени: «Аниматрица» 2003-го приезжала так под
«Возвращение к источнику» 2004-го. Перевыпуск же несимметричен, и опознаётся не
близостью годов, а именем.
"""

from __future__ import annotations

from torrcast.domain.facts.ask import Ask
from torrcast.domain.facts.dated import Dated
from torrcast.domain.facts.original_forms import original_forms


def reissued(ask: Ask, row: Dated, known: dict[str, set[int]]) -> bool:
    """Эта статья - та же картина, а год раздачи у неё год издания; признаков четыре.

    Первый - имя статьи ТОЧНО совпало с оригинальным именем раздачи. Это не догадка по
    похожести слов, а совпадение строк, и страницу значений с пустышкой сюда не пускает
    :func:`~torrcast.domain.facts.wiki_reply._article`. Именно этим перевыпуск и отличается
    от тёзки: у «Аниматрицы» имя не совпадало вовсе.

    Второй - год раздачи ПОЗЖЕ всех названных статьёй. Переиздают вышедшее, а не будущее,
    и обратная сторона допуска остаётся закрытой: год до выхода чужую картинку не тащит.

    Третий - статья называет себя картиной того же рода, и род этот - фильм. У сериала
    растяжение своё и уже есть, срок показа, а перезапуск под тем же оригинальным именем
    («Battlestar Galactica» 1978 и 2004) вёл бы сюда картинку старого сериала.

    Четвёртый признак живёт не здесь, а у зовущего
    (:meth:`~torrcast.adapters.wiki.poster_pages.PosterPages._checked`): своей статьи под
    год раздачи не нашлось НИ ОДНОЙ. Без него правило врало на римейках: у «Короля Льва»
    2019 года оригинальное имя «The Lion King» совпадает со статьёй мультфильма 1994-го
    точно, и человек получил бы картинку старого мультфильма вместо нового.
    """
    seen = row.years or known.get(row.entity, set())
    return (
        ask.kind == "movie"
        and ask.year is not None
        and "movie" in row.kinds
        and bool(seen)
        and max(seen) < ask.year
        and row.page.casefold() in {form.casefold() for form in original_forms(ask.original)}
    )
