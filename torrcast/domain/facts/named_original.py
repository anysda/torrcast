"""Назвала ли статья имя картины на чужом языке; зовёт разбор паспорта."""

from __future__ import annotations

from torrcast.domain.facts.patterns import _LANGUAGE_NAME_RE, _LANGUAGES


def named_original(extract: str) -> bool:
    """Назвала ли первая фраза статьи имя картины на чужом языке - НА ЛЮБОМ ПИСЬМЕ.

    Отвечает на вопрос, которого пустое поле паспорта не различает:
    :func:`~torrcast.domain.facts.latin_title.latin_title` отдаёт пустую строку и когда
    имени на другом языке у картины нет вовсе, и когда оно есть, но записано не
    латиницей, - у японского кино в скобке иероглифы, у украинского кириллица. Оба
    случая ложатся в паспорт одной пустотой (:attr:`~torrcast.domain.facts.origin.Origin.title`),
    и отличить «мы знаем, что такого имени нет» от «мы его не разобрали» после этого нечем.

    Тут разбирать нечего: важно не имя, а сам факт, что статья его НАЗВАЛА. Поэтому
    письмо не проверяется вовсе, а проверяется сокращение перед именем: оно обязано быть
    языком (:data:`~torrcast.domain.facts.patterns._LANGUAGES`). Скобка устроена одинаково у
    имени и у года рождения режиссёра («(род. 1950)»), и без этой проверки статья о любом
    человеке отвечала бы «имя названо».

    ⚠️ Русский язык из списка исключён: «(рус. …)» - это то же самое имя, которым картина
    уже подписана, и чужого имени оно не называет.
    """
    return any(
        match.group(1) in _LANGUAGES and match.group(1) != "рус" and match.group(2).strip()
        for match in _LANGUAGE_NAME_RE.finditer(extract)
    )
