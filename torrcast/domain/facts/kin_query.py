"""Строка SPARQL за родней картины по её Q-идентификатору; зовёт адаптер Wikidata."""

from __future__ import annotations

#: Что считается фильмом здесь: и полный метр, и короткий, и мультфильм - лишь бы не
#: список персонажей и не отдельная статья про актёра. Проверяется КЛАССОМ, а не самим
#: ``P31=фильм``: у мультфильма и короткометражки свой подкласс, и голая проверка отсекла
#: бы «Аниматрицу» и «Кота в сапогах» из родни живой франшизы.
_FILM_CLASS = "wd:Q11424"


def kin_query(entity: str) -> str:
    """SPARQL за другими частями франшизы: серия (P179) и цепочка (P155/P156) разом.

    Оба свойства читаются ОДНИМ запросом через ``UNION``, а не друг за другом: у части
    франшиз есть общий элемент серии, а у части - только цепочка «предыдущая/следующая»
    без единого элемента-родителя (замер 06-09-2026, `/home/claude/probe-franchise/`).
    Само запрошенное убирается ``FILTER`` - у P155/P156 путь идёт со звёздочкой и нулевым
    шагом включает саму картину.

    Имя берётся русским с английским запасным (`SERVICE wikibase:label`): голый
    английский ярлык звучал бы чужим на русской странице, а без запасного часть родни
    осталась бы вовсе без имени.
    """
    return (
        "SELECT ?item ?itemLabel ?date WHERE { "
        f"{{ wd:{entity} wdt:P179 ?series . ?item wdt:P179 ?series }} "
        f"UNION {{ wd:{entity} (wdt:P155|wdt:P156)* ?item }} "
        f"?item wdt:P31/wdt:P279* {_FILM_CLASS} . "
        f"FILTER(?item != wd:{entity}) "
        "OPTIONAL { ?item wdt:P577|wdt:P580 ?date } "
        'SERVICE wikibase:label { bd:serviceParam wikibase:language "ru,en". } }'
    )
