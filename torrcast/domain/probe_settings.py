"""Сроки опроса внешних служб и граница глубины цвета для осмотра файла."""

from typing import Final

from torrcast.domain.profile import CAUTIOUS

_TIMEOUT: Final = 30.0

#: Сколько ждём ответа источника, когда спрашиваем его на краю показа (:class:`Supply`).
#:
#: Три секунды - это с запасом: сам перезапуск службы стоит 3.0-3.1 с недоступности
#: (замерено), а её настоящая паника - 5 с, и оба случая ловятся не длинным сроком одного
#: вопроса, а повторным вопросом. Долгий срок тут вреден: пока мы ждём ответа, показ уже
#: гаснет, и человеку нужна строка, а не наше терпение.
PROBE_TIMEOUT: Final = 3.0

#: Сколько даём вернувшейся раздаче на метаданные, прежде чем снова счесть её пустышкой.
#:
#: Раздача, добавленная магнитом заново, секунду-другую стоит без списка файлов - рой
#: только собирается. Без этой отсрочки показ считал бы её той самой «раздачей по голому
#: хэшу» и добавлял магнит на каждом опросе: замер на живой службе - возврат магнитом на
#: КАЖДОМ вопросе, пока едут метаданные.
META_GRACE: Final = 30.0

#: Глубина цвета, которую приёмник берёт копией. Выше - перекод целиком.
#:
#: 🔴 Замер на живом Q70D (09-08, «Death Note» BDRip 1080p, ``h264`` / ``High 10`` /
#: ``yuv420p10le``, 6.5 Мбит/с): доигрывает ровно то, что успело влезть в буфер (~70 с),
#: и встаёт в вечную петлю «залип - закрываю приложение - LOAD - BUFFERING - залип».
#: Позиция при этом стоит колом, а упаковка ушла на 259-339 с вперёд, то есть куски
#: приезжают - их не берёт декодер. Контрольный опыт с выключенным прогревом даёт то же
#: самое: стык источников ни при чём, дело в самом потоке.
#:
#: Восьмибитный H.264 (``High``, ``yuv420p``) в тех же условиях играет часами - потому
#: граница и стоит по глубине, а не по имени профиля: имён у десятибитного потока много
#: (``High 10``, ``High 10 Intra``), а ``pix_fmt`` один и честен.
#:
#: 🔴 Как и набор кодеков, это свойство приёмника и живёт в его профиле
#: (:attr:`torrcast.domain.profile.Profile.copy_depth`); здесь остаётся умолчание.
COPY_DEPTH: Final = CAUTIOUS.copy_depth
