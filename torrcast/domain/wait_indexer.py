"""Опорные источники: их выдачу круг дожидается, прежде чем показать список."""

from __future__ import annotations

from typing import Final

from torrcast.domain.quorum_indexer import QUORUM_INDEXERS

#: Источники, которым даём доехать в первый пул. Кроме кворумного здесь стоят те, кто
#: несёт русскую озвучку: RuTor и JacRed. Кворумом они не считаются - без них каталог
#: беднеет, а не пустеет, - но их строки обязаны попасть в пул до того, как человек
#: выберет картину, иначе весь русский каталог становится лотереей.
#:
#: Замер на сериале с русскими раздачами: JacRed отдаёт на такой запрос 84 строки, и там,
#: где второго русского источника рядом нет, тратит на них 4.4 с - дольше, чем кворумному
#: нужно на его ответ. Круг поэтому закрылся бы раньше, чем JacRed заговорит. Без
#: ожидания его строки приезжают доливом (TC-118) уже после выбора картины, и пул сериала
#: собирается из 11 раздач с одной названной озвучкой; с ожиданием - из 27-28 раздач, где
#: озвучка названа у 8-12. Разница читается человеком как «годного релиза нет» против
#: обычного меню с дубляжом.
#:
#: Цена ожидания - секунды из тех же 10 с цели
#: (:data:`~torrcast.domain.goal_spare.GOAL`), и в цель она укладывается: путь до картинки
#: занял 1.9-7.1 с в 11 запросах подряд, причём верх этого разброса приходится на случай,
#: когда русский пул несёт один JacRed и ждать больше некого. Личный бюджет при этом не
#: тронут: некворумному положена ровно цель
#: (:data:`~torrcast.domain.indexer_budget.EXTRA_TIMEOUT`). У RuTor тот
#: же расчёт короче: сохранённые 170 кругов дали максимум живого ответа 1.761 с, поэтому
#: три секунды сохраняют все его строки, а смерть отнимает только эти три секунды.
WAIT_INDEXERS: Final = (*QUORUM_INDEXERS, "rutor", "jacred")


def wait_indexer(name: str) -> bool:
    """Нужен ли источник в первом пуле, даже если без него поиск способен жить."""
    low = name.lower()
    return any(part in low for part in WAIT_INDEXERS)


__all__ = ["WAIT_INDEXERS", "wait_indexer"]
