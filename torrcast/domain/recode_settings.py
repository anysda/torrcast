from typing import Final

#: Потолок высоты кадра, который сплошной перекод успевает в реальном времени.
#:
#: 🔴 Это про НАШУ МАШИНУ, а не про приёмник, и живёт оно поэтому здесь, рядом с
#: пресетом и множителем битрейта, а не в профиле приёмника (:mod:`torrcast.profile`
#: говорит это прямым текстом). Замер на 4 vCPU: 1080p идёт 3.4-4.04× реального времени.
#: Смени телевизор - число не изменится ни на знак; поставь вдвое больше ядер - изменится.
#:
#: 🔴 Прежнее объяснение («у 2160p вчетверо больше пикселей, и в бюджет старта такой
#: перекод не влезает») замером TC-157 опровергнуто, и это не оговорка, а разворот всей
#: ветки 4К. Замер на 4 vCPU, 2160p HEVC 10 бит → h264 ``ultrafast`` 9 Мбит/с: БЕЗ скейла
#: 1.03× реального времени, СО скейлом до 1080p - 1.53×. То есть число тут не «выше него
#: мы не умеем», а «до него мы ужимаем»: x264 получает вчетверо меньше пикселей, и
#: ужатый перекод идёт быстрее неужатого в полтора раза.
#:
#: ⚠️ Ровно то же число носит :data:`~torrcast.domain.rank_settings.FULL_HEIGHT`, и совпадение это
#: случайное: там - ступень лестницы качества, свойство РЕЛИЗА («честный 1080p»), и
#: меняются эти два числа по разным поводам. Один источник ограничения - одно имя.
RECODE_HEIGHT: Final = 1080
