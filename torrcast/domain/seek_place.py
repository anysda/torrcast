"""Куда встаёт показ после относительной перемотки: внутри картины, а не за её краями.

Сдвиг режется с обеих сторон. Снизу - началом картины. Сверху - длительностью без
:data:`END_MARGIN`: пять «+600» у конца файла слали приёмнику место за длительностью, и
карточка рисовала его, хотя показ туда встать не мог. Длительность неизвестна (``0``) -
верх не режется: выдумывать край хуже, чем отдать приёмнику его же решение.

Нажатия подряд режутся ПО ОДНОМУ, как их получает показ: позиция 100, «-240», «+60» - это
0, потом 60, а не ``max(0, 100 - 180)``. Так считают и показ (:mod:`torrcast.usecases.
choice._ctl`), и ползунок карточки (:mod:`hass.aim`), иначе у нуля они расходились.
"""

from __future__ import annotations

__all__ = ["END_MARGIN", "seek_place"]

#: Сколько секунд до конца оставляет перемотка за край: показ доигрывает хвост и кончается
#: сам, а не обрывается на месте, которого у картины уже нет.
END_MARGIN = 5.0


def seek_place(pos: float, by: float, duration: float) -> float:
    """Место после сдвига ``by`` от ``pos``, внутри ``[0, duration - END_MARGIN]``."""
    place = max(0.0, pos + by)
    if duration > 0.0:
        # Вперёд из самого хвоста показ назад не мотают: потолок не ниже нынешнего места.
        place = min(place, max(0.0, duration - END_MARGIN, min(pos, duration)))
    return place
