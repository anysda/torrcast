"""Бюджет КРУГА: сколько круг держит показ, прежде чем уйти без отставшего."""

from __future__ import annotations

from typing import Final

#: 🔴 TC-1046. Потолок ПЕРВОГО круга - и единственное место, где он назван.
#:
#: Личный бюджет отвечает на вопрос «сколько ждать ЭТОГО источника»
#: (:func:`~torrcast.domain.indexer_budget.indexer_budget`), и у кворумного он двадцать
#: секунд (TC-226). Круг же ждёт каждого опорного отдельно, поэтому цена показа - это
#: бюджет САМОГО МЕДЛЕННОГО опорного, а не медиана круга. Первый круг шёл без потолка
#: вовсе, и двадцать секунд Knaben были ценой меню.
#:
#: Замер 05-09-2026 по следу моста, 1341 круг: Knaben - медиана 1.48 с, 90-я доля 2.79 с,
#: 95-я 3.04 с, максимум 17.53 с; JacRed - медиана 0.98 с, 90-я 4.25 с, максимум 8.11 с;
#: RuTor - медиана 0.42 с, максимум 3.03 с. Хвост, ради которого стоит потолок, лежит
#: за 95-й долей: на шести секундах он срабатывает у 37 кругов из 1341 (2.8%).
#:
#: Шесть, а не пять и не три: спека называет 99-ю долю ЧЕСТНОГО ответа - 5.6 с
#: (``SPEC.md``, замер на 1985 запросах), и потолок обязан стоять выше неё, иначе он
#: режет не молчание, а живой ответ. Выше шести смысла нет: между 6 и 8 секундами лежит
#: 9 ответов из 1341, то есть потолок перестаёт срабатывать раньше, чем перестаёт стоить.
#:
#: 🔴 Отставший этим НЕ выбрасывается. Его запрос живёт своей полной жизнью
#: (:data:`~torrcast.domain.response_budget.LATE_TIMEOUT` - 45 с кворумному), поток
#: остаётся в :attr:`~torrcast.adapters.prowlarr.indexer_circle.IndexerCircle._late`, и
#: строки забирает долив: в пул выбранной картины (TC-118) и в пустой пул до показа
#: (TC-318). Потолок отдаёт СОБРАННОЕ вовремя, а не отменяет несобранное.
FIRST_CIRCLE_TIMEOUT: Final = 6.0

__all__ = ["FIRST_CIRCLE_TIMEOUT"]
