"""Правило part of picture; используют модели и фасады разбора имён."""

from __future__ import annotations

from torrcast.domain.part_number import part_number
from torrcast.domain.release import Release
from torrcast.domain.seasons_in import seasons_in


def part_of_picture(
    part: int | None, title: str, original: str | None, group: list[Release]
) -> int | None:
    """Номер части, который несёт САМА картина, а не имя отдельной её раздачи.

    🔴 TC-859. Считает номер :func:`~torrcast.domain.compose._compose` по одним номерным
    именам: знаменатель там - раздачи, у которых номер вообще ЕСТЬ, а не все раздачи
    картины. Поэтому семь имён из тридцати становятся единогласным большинством, и
    картина «Моб Психо 100» (2016), несущая первый сезон, подписана чужой частью голосом
    меньшинства. Дальше номер части у сериала читается как номер сезона
    (:func:`~torrcast.usecases.choice.asked_season.asked_season`), и подпись меньшинства
    становится утверждением о содержимом: «эта картина - сезон N».

    Менять сам знаменатель нельзя: на этом счёте держится линейка франшизы. «Матрица:
    Перезагрузка» зовётся второй частью тремя раздачами из двадцати трёх, «Рэмбо: Первая
    кровь» - первой одной из сорока одной, и большинства у них не будет никогда. Правка в
    лоб чинит сезон ценой пяти таких личностей - замерено 27-08-2026 и откачено.

    Поэтому номер отбирается только тогда, когда против него сошлись ТРИ свидетеля разом,
    и любого одного за - довольно:

    * имя самой картины номера не несёт - ни :attr:`Picture.title`, ни
      :attr:`Picture.original`, а оба выбраны большинством имён группы
      (:func:`~torrcast.domain.by_majority.by_majority`), то есть это и есть подпись
      картины, а не подпись отдельной раздачи;
    * номер называет меньшинство ВСЕХ раздач группы - тот самый знаменатель, которого нет
      в счёте ``part``: молчащие о номере считаются наравне с говорящими;
    * картина сама говорит, что в ней лежит: её раздачи называют сезоны вслух
      (:func:`~torrcast.domain.seasons_in.seasons_in`), и спорного номера среди них нет.

    Чего признак НЕ обещает:

    - фильмов он не трогает вовсе: третий свидетель говорит только у сериала, и картина,
      чьи раздачи о сезонах молчат, номер сохраняет любой ценой. Молчание тут не довод;
    - чистоты кластера: раздачи чужой части, склеенные в одну картину, он не находит и
      находить не берётся;
    - кворума у первых двух свидетелей: одной номерной раздачи из сорока довольно, чтобы
      номер устоял, если сезоны картины его подтверждают.
    """
    if part is None:
        return None
    if part in (part_number(title), part_number(original or "")):
        return part
    said = sum(1 for release in group if part_number(release.title) == part)
    if said * 2 > len(group):
        return part
    named = seasons_in(group)
    return None if named and part not in named else part


__all__ = ["part_of_picture"]
