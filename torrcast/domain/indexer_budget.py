"""Личный бюджет индексера: сколько секунд круг ждёт именно этого источника."""

from __future__ import annotations

from typing import Final

from torrcast.domain.goal_spare import GOAL
from torrcast.domain.quorum_indexer import quorum_indexer

#: Личный бюджет КВОРУМНОГО индексера. Замеры на живом стенде (1985 запросов к четырём
#: индексерам): половина ответов до 0.5 с, 99-я доля - 5.6 с, самый долгий честный
#: ответ - 16 с (отказ трекера и повтор внутри Prowlarr). Всё, что дольше, - уже не
#: медленный ответ, а молчание: канал рвёт поток посреди тела, и Prowlarr сидит на нём
#: до своей сотой секунды. Бюджет отрезает такое молчание, не задев ни одного живого
#: ответа, и стоит поиску не 100 с, а этих секунд - да и то лишь молчуну.
#:
#: 🔴 TC-226. Двадцать секунд с целью в десять не сходятся, и это осознанный выбор, а не
#: недосмотр. Хвост поиска - это Knaben: ``api.knaben.org`` отдаёт 502 через 10-15 с
#: (холодный бэкенд), а Prowlarr сверху ретраит с отсрочкой (в его же логе: «Request for
#: Knaben failed with status BadGateway. Retrying in 0.26-4.19 s»), и один поиск из семи
#: стоит 10-20 с. Резать хвост можно двумя способами, и оба замерены:
#:
#: * личный бюджет Knaben 3-5 с - тогда его строки просто не доезжают, а он несёт 41%
#:   каталога. Цена: 1 подмена дефолта и 7 подмен верхнего релиза на 100 запросов;
#:   выигрыш - те самые 10-15 с на 14 запросах из 100, около 154 с на сотню;
#: * ждать Knaben дольше остальных - кворумному полный бюджет, некворумным столько,
#:   сколько их выдаче ещё есть куда лечь (:data:`EXTRA_TIMEOUT`). Подмен ноль,
#:   экономия 85 с на сотню.
#:
#: Разница в скорости между вариантами - 69 с на 100 запросов, то есть 0.7 с в среднем на
#: запрос: против цели в 10 с это не видно. Разница в честности - 8 молчаливых подмен на
#: сотню, и одна из них - ДЕФОЛТ, то есть не тот фильм по Enter. Гейт «ноль подмен»
#: сильнее скорости, поэтому взят второй вариант: 1 поиск из 7 выходит за цель, и это
#: названо здесь прямо, а не спрятано в число.
QUORUM_TIMEOUT: Final = 20.0
#: Личный бюджет НЕКВОРУМНОГО индексера (Nyaa, YTS). Круг их не ждёт (TC-118), поэтому
#: бюджет отвечает не за путь до меню, а за то, до каких пор их выдаче ещё есть куда
#: лечь: долив попадает в пул выбранной картины, а выбирают её в пределах цели
#: (:data:`~torrcast.domain.goal_spare.GOAL`). Что приехало позже - опоздало ко всему
#: сразу. Живых ответов это не режет: 99-я доля честного ответа - 5.6 с, то есть цель
#: вдвое шире.
EXTRA_TIMEOUT: Final = GOAL
#: Личный - и заметно более короткий - бюджет для тех, кому нечего терять. Общий бюджет
#: щедр нарочно: за ним стоят индексеры, чьё молчание стоит находок. У YTS не стоит:
#: замер (TC-141) дал +2.1% к пулу и НОЛЬ запросов, где он единственный источник
#: играбельного HD, - кириллицы у него нет, сериалов нет. А платим мы за него полным
#: бюджетом: канал рвёт его выдачу на объёме тела, и залипший ответ выбирает все 20 с
#: (замер на стенде: «barbie» - ровно 20.02 с молчания). Честный ответ у него укладывается
#: в секунду (там же: 0.5-0.9 с), так что шесть - это шестикратный запас к норме.
#: 🔴 TC-232: с тех пор сама выдача подрезана там, где она рождается - в определении
#: индексера (десять картин вместо пятидесяти, ``YTS_LIMIT`` в ``install.sh``), и по
#: объёму тела до порога обрыва теперь троекратный запас. Этот бюджет остался страховкой
#: на случай, когда порог просядет ещё, а не главной защитой от молчания.
#: 🔴 TC-273: YTS ЖИВ, и держим мы его честно. Числился он мёртвым по HTTP 400 в ответ на
#: свой персональный запрос - но 400 у Prowlarr это не смерть индексера, а его бан
#: («Search failed due to all selected indexers being unavailable»), и приходил он на
#: любой забаненный индексер одинаково. Живая проба на здоровом стенде: 24 раздачи на
#: «matrix» за 0.1 с, повторно после снятия бана - те же 24. Место в круге он занимает
#: своим коротким бюджетом, и вклад его прежний (+2.1%, ноль уникальных дыр) - но раз он
#: отвечает, молчащим в списке ему не место: круг платит за него шесть секунд ХВОСТА,
#: который никого не ждёт, а не шесть секунд пути.
SHORT_TIMEOUT: Final = 6.0
#: Кому этот бюджет достаётся - по подстроке в имени индексера, как и у аниме-списка.
SHORT_BUDGET: Final = ("yts",)
#: Бюджет источников, у которых живой ответ заведомо короче, а молчание дорого.
#: Сохранённый круг на 170 запросах (TC-318) содержит 74 вызова Nyaa: медиана
#: 0.156 с, 73 ответа не позже 0.484 с; единственный ответ за 8.339 с был пуст.
#: Поэтому три секунды не отрезают ни одной строки корпуса (0 запросов, 0 раздач),
#: но оставляют молчуну лишь 30% продуктовой цели вместо прежних 100%.
FRAGILE_TIMEOUT: Final = 3.0
FRAGILE_BUDGET: Final = ("nyaa", "rutor")


def indexer_budget(name: str) -> float:
    """Сколько секунд ждём ЭТОГО индексера. Единственное место, где считается бюджет.

    Складывается из двух вещей, и обе замерены:

    * РОЛЬ в круге (TC-226): кворумного (:data:`~torrcast.domain.quorum_indexer.
      QUORUM_INDEXERS`) ждём полный :data:`QUORUM_TIMEOUT`, потому что без него каталога
      нет; остальных - столько, сколько их выдаче ещё есть куда лечь
      (:data:`EXTRA_TIMEOUT`), круг их и так не ждёт;
    * КОРОТКИЙ СПИСОК (TC-213): у кого нечего терять, тот и ждать себя не заставляет
      (:data:`SHORT_BUDGET`). Берём меньшее из двух - короткий список только урезает,
      поднять бюджет он не может.
    """
    low = name.lower()
    role = QUORUM_TIMEOUT if quorum_indexer(name) else EXTRA_TIMEOUT
    short = any(mark in low for mark in SHORT_BUDGET)
    fragile = any(mark in low for mark in FRAGILE_BUDGET)
    if fragile:
        return min(role, FRAGILE_TIMEOUT)
    return min(role, SHORT_TIMEOUT) if short else role


