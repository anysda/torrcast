"""Определяет порядок звуковых дорожек."""

from torrcast.domain.audio_track import STEP_NATIVE, STEP_RU_PLAIN, AudioTrack


def voice_order(track: AudioTrack, native: bool = False) -> tuple[int, int, int]:
    """Место дорожки в очереди на дефолт: ступень, вес студии, порядок в файле.

    Сортируем по трём ключам слева направо (меньше = лучше):
    - ступень лестницы (дубляж=0, многоголосый=1, ...)
    - минус fame: чем выше вес, тем левее студия внутри ступени; отрицательный fame
      (AniDub) уходит правее незнакомых студий с нулевым весом
    - порядок дорожки в файле: сборщик раздачи кладёт первой ту, которую считает главной

    Ступень тут берётся ОТБОРНАЯ (:attr:`AudioTrack.rank_step`), а не та, что
    произносится вслух: «Кубик в Кубе» двухголосые, но крутее всей многоголосой ступени.
    Вслух они остаются двухголосыми - см. :class:`Studio`.

    ``native`` - картина снята по-русски (:attr:`torrcast.domain.picture.Picture.native`).
    Тогда лестница переводов ей не начало, а продолжение: у отечественной картины есть
    СВОЯ дорожка - не перевод, а сам фильм, - и она лучшее, что в файле лежит. Дубляж
    поверх русского оригинала - такая же потеря, как чужой дубляж поверх иностранного.

    Своей считается русская дорожка, которая переводом себя НЕ называет, - ровно ступень
    «прочий русский» (:data:`STEP_RU_PLAIN`). Ступенью и проверяется, а не заголовком, и
    это несёт всю нагрузку:

    * знакомая студия - переводчик, и у отечественной картины её дорожка всё равно
      переозвучка. Отдельной проверки на это не нужно: у каждой студии справочника
      вид перевода назван (:data:`~torrcast.domain.studio.STUDIOS`), а названный вид - это
      ступень ВЫШЕ «прочего русского», то есть на неё такая дорожка не попадает;
    * служебные дорожки (тифлокомментарий, комментарии) и нерусские не попадают сюда
      тоже - их ступени НИЖЕ, и трогать их нельзя: «есть ли русский вообще» важнее, чем
      какая именно русская дорожка играет.

    Незнакомая подпись выбор не роняет: она оставляет дорожку на «прочем русском», а
    значит у отечественной картины поднимает её, у иностранной - оставляет как было.
    Молчит паспорт происхождения (``native`` не проставлен) - лестница ровно прежняя.
    """
    step = track.rank_step
    if native and step == STEP_RU_PLAIN:
        step = STEP_NATIVE
    studio = track.studio
    return (step, -(studio.fame if studio else 0), track.index)
