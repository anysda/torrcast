"""Профиль вкладки браузера: то, что Chromium и Firefox реально играют через hls.js."""

from typing import Final

from torrcast.domain.receiver_profile import ReceiverProfile

__all__ = ["BROWSER"]

#: 🔴 Вкладке он достаётся только там, где передать показ некому: приёмник машины -
#: вкладка, ТВ не назван, а сама вкладка из замеренных
#: (:func:`torrcast.domain.for_tab.for_tab`), прочим - осторожный, как раньше.
#: Кнопка «На ТВ» отдаёт телевизору тот же ``url`` (:mod:`web.to_tv`), и поток,
#: упакованный под вкладку, телевизор мог бы не доиграть.
BROWSER: Final = ReceiverProfile(
    key="browser",
    title_key="receiver.profile_browser",
    # Кодеки остаются осторожными, и это замер, а не лень. ``MediaSource.isTypeSupported``
    # у Chromium: hvc1/hev1 нет ни Main, ни Main10, mp4v нет - такой файл едет перекодом,
    # копия HEVC давала чёрный экран без единого запрошенного куска. VP9 и AV1 Chromium
    # играет, но в кусок MPEG-TS их не положить, и они остаются отказом отбора. High10
    # строкой типа принимается, а живьём не проверен - остаётся перекодом.
    # снято: tabprobe · mpegts · TC-1259
    #
    # Потолки веса и длины куска у вкладки - не декодер, а запас hls.js: он держит до
    # 60 МБ и 30 с впереди, то есть два куска по 28 МБ и 15 с. Осторожные 16 МБ и
    # 10 Мбит/с резали вкладке тяжёлые куски копии склейкой и перекодом, которые она и
    # так играет: «Оно» и «Матрица» стояли на этом по 4-6 с до первого кадра.
    # снято: tabprobe · mpegts · TC-1259
    max_segment_bytes=28_000_000,  # снято: tabprobe · mpegts · TC-1259
    max_segment_seconds=15.0,  # снято: tabprobe · mpegts · TC-1259
    # 28 МБ - цель сетки, а не предел вкладки: кусок легче - раньше первый кадр. Предел
    # замерен тем же hls.js с теми же 60 МБ / 30 с: куски 58 и 80 МБ по 15 с Chromium
    # играет без единого `waiting` и потерянного кадра, 115 МБ встают на каждой границе
    # (квота MSE). Кусок между 28 и 80 МБ уезжает копией, а не склейкой. Firefox 153
    # тем же прибором - то же: 58 и 80 МБ чисто, 115 встают. WebKit щупа (GStreamer, не
    # AVFoundation Safari) рвётся уже на 58 МБ: ему и телефонам - осторожный профиль.
    # снято: tabprobe · mpegts · TC-1259
    refuse_segment_bytes=80_000_000,  # снято: tabprobe · mpegts · TC-1259
    # Битрейт куска вкладке не декодер: avc1.640033 (5.1) MSE берёт, а потолок видео
    # Blu-ray - 40 Мбит/с. На 28 вкладке пережимали пики обычного BD-рипа: «Оно» держало
    # куски 29.7 и 30.8 Мбит/с, «Интерстеллар» - первый кусок 28.1 до первого кадра.
    # Вес куска сторожит предел байтов выше, он и остаётся поводом для перекода.
    # снято: tabprobe · mpegts · TC-1259
    recode_at_mbit=40.0,  # снято: tabprobe · mpegts · TC-1259
)
