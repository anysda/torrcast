def quality_text(release: Release, media: Media) -> str:
    """Разрешение, которое реально поедет на ТВ. ffprobe уже прочитан — врать нечем.

    Порядок именно такой: сначала подтверждённая высота кадра, и только если ffprobe её
    не отдал (экзотика, битый заголовок) — заявка из имени. Раньше было наоборот, и
    «Моана 2» печаталась 1080p при 1150×574 внутри: заявка выигрывала у факта, то есть
    ровно та молчаливая подмена, которой быть не должно.

    Буква развёртки тоже из потока (:attr:`torrcast.stream.Media.quality`): названный
    «1080p» чересстрочник печатается «1080i» - гребёнку нельзя подписать прогрессивом.
    """
    return media.quality if media.height else (release.quality or "?")


def understated(release: Release, media: Media) -> str:
    """Чем подтверждённое разрешение хуже обещанного; пусто — релиз честен.

    Две половины, и обе взяты с живой выдачи «моаны 2»:

    1. имя называет разрешение, а внутри заметно меньше (:data:`HONEST_RATIO`);
    2. имя не называет ничего, а внутри не HD вовсе (:data:`HD_HEIGHT`) — это и есть
       верхний кандидат «Моаны 2»: ``WEB-DL-AVC`` без единой цифры в заголовке, 3.14 ГБ,
       140 сидов, а на деле 1150×574.

    И третья, про развёртку: имя обещает прогрессивный кадр, а поток чересстрочный
    (:attr:`~torrcast.stream.Media.interlaced`). Разрешение тут не врёт, поэтому
    высотой её не поймать - ловится только буквой.

    Возвращает кусок фразы, а не флаг: строка про подмену обязана назвать обе цифры,
    иначе она ничего не объясняет.
    """
    if not media.height:  # ffprobe высоту не отдал - сравнивать не с чем, молчим
        return ""
    if release.height:
        if media.frame < release.height * HONEST_RATIO:
            return f"назван {release.quality}, на деле {media.quality}"
        if media.interlaced and not release.interlaced:
            return f"назван {release.quality}, на деле {media.quality}"
        return ""
    return f"на деле {media.quality}" if media.frame < HD_HEIGHT else ""


def promises_more(release: Release, media: Media) -> bool:
    """Стоит ли вообще смотреть на этот запасной: обещает HD и больше, чем дал верх."""
    return release.height >= HD_HEIGHT and release.height > media.frame


def voice_unproven(media: Media, *, native: bool = False) -> bool:
    """Русская дорожка в этом файле НЕ ПОДТВЕРЖДЕНА: паспорт либо отрицает, либо молчит.

    🔴 TC-301. У паспорта три ответа, а не два. «Русская есть»
    (:attr:`~torrcast.stream.Media.russian`) - играем. «Русской нет»
    (:attr:`~torrcast.stream.Media.foreign`) - гейт бракует релиз и очередь идёт дальше
    (:meth:`_Bench.resolve`). А между ними лежит третий: дорожка БЕЗ ТЕГА ЯЗЫКА
    (:attr:`~torrcast.stream.AudioTrack.named`), и по замеру паспортов таких файлов 28%.

    🔴 TC-492. Третий ответ засчитывался за первый, и стоило это зрителю картины:
    «Эксперименты Лэйн» уехали с нерусской дорожкой ровно потому, что язык её никто не
    назвал, - а в очереди оставалось ещё четыре нетронутых релиза. Незнание - это не
    «сойдёт»: правило продукта требует русской озвучки, а не отсутствия доказательств
    обратного. Поэтому годным считается только первый ответ, а второй и третий отправляют
    релиз в один и тот же запасной ход (:meth:`_Bench._mute_fallback`): очередь идёт
    дальше, а когда спрашивать больше некого - играет лучшее из отложенного, и говорит об
    этом вслух.

    Имя раздачи тут не судья ни в одну сторону (TC-191): «[RUS(int)]» русской дорожки не
    гарантирует, и подменять им паспорт значит вернуть ту же ошибку с другого конца.

    ``native`` - справка подтвердила отечественное происхождение картины. Тогда безымянная
    дорожка не пробел, а паспорт происхождения: «Бригаду» никто не озвучивал, она так и
    снята. Та же развилка стоит в :func:`sound_note`.

    ⚠️ Граница проведена по ДОРОЖКЕ, а не по паспорту целиком: файл, у которого ffprobe не
    отдал ни одной звуковой дорожки, сюда не относится. Это не «язык не назван», а «звук
    не прочитан» - паспорт, дочитанный до половины, и бракует он не релиз, а нашу спешку
    (:attr:`~torrcast.stream.Media.foreign` о том же). В замере паспортов таких файлов нет
    ни одного из 92, а стоила бы такая строгость всей выдачи разом.
    """
    if media.russian or not media.tracks:
        return False
    return media.foreign or not native


def honest_shot(release: Release, media: Media) -> bool:
    """Запасной подтвердил своё имя: кадр из ffprobe не ниже заявленной ступени. Имя
    молчало — тогда достаточно, чтобы внутри оказался HD.
    """
    if not media.height:
        return False
    if release.height:
        return media.frame >= release.height * HONEST_RATIO
    return media.frame >= HD_HEIGHT


def is_disc(release: Release) -> bool:
    """Образ диска (DVD-Video, BDMV, ISO): цельного файла внутри нет — не дефолт."""
    return bool(_DISC_RE.search(release.raw_name))


def is_extra(release: Release, runtime: float) -> bool:
    """Раздача - приложение к картине, а не сама картина: так сказало имя, так вышло по весу.

    🔴 TC-290. Ворота отбора судили, КАК раздача снята - разрешение, битрейт, живость,
    звук, - и ни одна ступень не спрашивала, картина ли это вообще. Дополнительные
    материалы (фильм о фильме, интервью, вырезанные сцены, трейлер) проходили обычным
    кандидатом, а из-за малого веса выглядели по битрейту даже прилично. У «Тачек 2» из
    сохранённой выдачи «HDRip … фильм о фильме» на 0.4 ГБ стоял в очереди четырнадцатым,
    а в пуле, где у картины всего две раздачи, - ПЕРВЫМ, то есть дефолтом Enter. Человек
    просит кино и получает получасовой ролик о съёмках; молча.

    Признаков два, и по отдельности ни один не годится.

    Имя (:attr:`~torrcast.parse.Release.extras`) без веса отбраковало бы законную картину,
    у которой такое слово стоит в её же названии, и раздачу «картина + приложение».

    Вес без имени - это уже :func:`is_dated`, и он про другое: мизерный битрейт бывает у
    честного SD-рипа, и выкидывать такой нельзя, пока другого нет. Здесь же имя прямо
    говорит, что играть тут не картину, и вес это подтверждает: при длительности из
    справки (:func:`torrcast.facts.minutes_of`, она же знаменатель :func:`bitrate_of`)
    столько весит ролик, а не фильм.

    ⚠️ Короткометражке признак не грозит, и не по доброте: её длительность справка называет
    честно, а ролик от картины отличает не абсолютный размер файла, а вес НА МИНУТУ. Пока
    справка молчит, в знаменателе стоит прикидка «фильм это два часа»
    (:data:`torrcast.stream.RUNTIME_GUESS`), и она короткометражку занижает - но занизить
    раздачу без пометки приложения в имени всё равно некуда: ворота её и не смотрят.

    ⚠️ Признак отнимает и единственную раздачу картины (TC-432): показать трейлер на
    запрос сериала - это подмена картины, а не «лучше, чем ничего». Вернуть её может
    только сам человек, номером из таблицы (``--release N`` в ворота не ходит).

    🔴 TC-339. Весу есть предел измерения: «Титаник | Дополнительные материалы» на
    11.6 ГБ, «Довод» на 22.5 ГБ, «Хоббит: Приложения» на 19.2 ГБ по битрейту выглядят
    картиной и ворота проходили, а подменить её могут, стоит умереть всему выше них.
    Поэтому однозначная метка (:attr:`~torrcast.parse.Release.extras_sure`) судит БЕЗ
    веса: «дополнительные материалы» и «бонус-диск» не бывают картиной ни при каком
    битрейте. Прочие метки без веса не судятся по-прежнему: их носят и раздачи самой
    картины, и сохранённая выдача это подтверждает - отсев по любой метке оставил бы
    без живых кандидатов 10 картин корпуса из 107 пулов, по однозначной - ни одной.
    ⚠️ Замер тот считал верх ранжира неприкосновенным, а TC-432 повёл через ворота и
    его: там, где однозначная метка стоит на ЕДИНСТВЕННОЙ раздаче картины, очередь
    теперь пустеет, и человек получает честный отказ (:func:`unfit_line`), а не
    бонус-диск вместо картины.

    🔴 TC-344. Молчание веса - не «лёгкий»: у сериала, чьё имя серий не считает,
    :func:`bitrate_of` отдаёт ``None``, и приложение с таким весом ворота НЕ отсекают -
    выкидывать раздачу по весу, которого нет, значит карать за собственное незнание.
    Порядок её всё равно уводит под картину (:func:`rank_releases`), а судит содержимое
    ffprobe, как и всякую молчаливую раздачу.
    """
    if not release.extras:
        return False
    if release.extras_sure:
        return True
    mbit = bitrate_of(release, runtime)
    return mbit is not None and mbit < EXTRAS_MBIT


def is_candidate(
    release: Release,
    runtime: float,
    warn_mbit: float,
    loose: bool = False,
    hard_mbit: float = 0.0,
    last: bool = False,
    copy_hevc: bool = False,
) -> bool:
    """Кандидат в дефолт: первый сорт (:attr:`Release.prime`), не образ диска, не
    приложение к картине (:func:`is_extra`) и в пределах потолка декодера. Жирнее потолка —
    в таблице остаётся с пометкой, но Enter его не возьмёт: ресивер на таком битрейте встаёт.

    ``loose`` — ворота открыты (:func:`gate_open`): живых именных кандидатов у картины
    нет, и тогда кандидатом становится ещё и раздача, чьё имя о качестве просто МОЛЧИТ
    (:attr:`Release.quiet`). Судить её будет ffprobe после выбора — механизм отбраковки
    и перехода к следующему уже стоит на пути (:meth:`_Bench.resolve`), и стоит он
    ровно тех же секунд, что и на любом другом релизе.

    Имя, сказавшее о себе правду, послаблением ``loose`` не пользуется: названный HEVC,
    MPEG-4 и «480p» остаются снаружи, потому что про них известно, а не неизвестно.
    Образ диска и потолок битрейта тоже не двигаются: там играть нечего и там ресивер
    встаёт, а от открытых ворот это не меняется.

    ``last`` — последняя надежда (:func:`last_hope`): живого кандидата с нужной серией
    нет ВООБЩЕ, и тогда в очередь пускается названный HEVC (:func:`hevc_hope`). Это не
    смягчение ворот, а признание того, что тракт умеет: такой файл играется сплошным
    перекодом (:data:`torrcast.stream.RECODE_CODECS`) ровно как десятибитный H.264.
    Предпочтением это не становится ни на шаг — ворота открываются только когда живого
    обычного кандидата нет, а порядок держит HEVC ниже всех живых (:func:`rank_releases`).

    ``copy_hevc`` - ответ единственного судьи кодека (:meth:`Profile.verdict`): свой
    ресивер объявил HEVC играющим копией через наш HLS. Для него HEVC проходит обычные
    ворота; профиль не снимает ограничения образа диска, качества и битрейта.

    ⚠️ Не-видео (``kind == "other"``: игры, музыка, книги) послабление не пускает
    никогда, и это не перестраховка. Замер на живой выдаче «one piece»: репак игры
    «One Piece: Pirate Warriors 4 … PC | RePack» несёт 97 сидов и о качестве видео
    молчит по той простой причине, что видео там нет, — при открытых воротах он
    перевешивал настоящий сериал с русским дубляжом и вставал дефолтом меню.

    ``hard_mbit`` — потолок для тех, у кого запас сплошного перекода тонок: имя, обещающее
    кадр выше 1080p, судится им, а не поднятым ``warn_mbit``. Причина не в качестве и уже
    не в «4К не успевает» (замер TC-157 это снял: ужатый до 1080p перекод идёт 1.34-1.53×
    реального времени), а в том, сколько остаётся про запас. У 1080p-ремукса запас 3.4×,
    у ужатого 4К - полтора, и рою при этом всё равно надо отдавать вес ИСХОДНИКА.
    Ноль — ступени нет, всё судится одним потолком.
    """
    if (
        is_disc(release)
        or is_extra(release, runtime)
        or over_ceiling(release, runtime, warn_mbit, hard_mbit)
    ):
        return False
    if (
        release.prime
        or (copy_hevc and release.is_hevc)
        or (loose and release.quiet and release.kind != "other")
    ):
        return True
    return hevc_hope(release, last)


def over_ceiling(
    release: Release, runtime: float, warn_mbit: float, hard_mbit: float = 0.0
) -> bool:
    """Битрейт релиза выше потолка отбора: играть его нечем, и в очередь он не идёт.

    Потолок у кадра выше 1080p свой (``hard_mbit``): запас скорости у ужатого 4К вдвое
    тоньше, а из роя тянуть надо вес исходника — см. :func:`is_candidate`.

    Отдельной функцией это стоит затем, что решение «выкинуть по битрейту» обязано
    называться одним и тем же кодом и в воротах, и в счёте отсева (:func:`drop_reason`):
    иначе счёт объяснял бы отказ не тем, чем он случился.
    """
    ceiling = warn_mbit
    if hard_mbit > 0 and release.height > RECODE_HEIGHT:
        ceiling = min(warn_mbit, hard_mbit)
    mbit = bitrate_of(release, runtime)
    # Вес неизвестен (TC-344) - потолок молчит: выкидывать по весу, которого нет,
    # нельзя, а тяжесть файла рассудит ffprobe уже после выбора (:meth:`_Bench._trouble`).
    return mbit is not None and mbit > ceiling


#: Раздачи картины, отсеянные до очереди, по причинам (:func:`drop_reason`). Порядок
#: слов один на весь код: причина называется там, где считается, и печатается в
#: `cast log` теми же словами (:func:`torrcast.trace._event_line`).
OFF_SEASON: Final = "нужного сезона нет"
_NO_EPISODE: Final = "нужной серии нет по имени"
_DISC: Final = "образ диска"
_EXTRAS: Final = "дополнительные материалы, а не сама картина"
_HEAVY: Final = "тяжелее потолка"
_HEVC: Final = "hevc, а сплошного перекода нет"
_CODEC: Final = "кодек не тот"
_SMALL: Final = "кадр ниже 720p по имени"
_SOURCE: Final = "источник не HD"
_QUIET: Final = "имя молчит о качестве"
_PINNED: Final = "релиз назван руками"


def drop_reason(release: Release, plan: _Plan) -> str:
    """Почему раздача не доехала до очереди отбора; пусто — доехала.

    🔴 TC-186. Пул картины и очередь отбора — не одно и то же: между ними стоят ворота
    (:func:`is_candidate`), сезонный фильтр и потолок битрейта, и на замере тысячи
    запросов между ними терялось 895 раздач из 3164 — без строки на экране и без
    события в недельном следе. «В журнале нет строки» это не «события не было»:
    отказавшая арифметика выглядела в следе ровно как её отсутствие.

    Причины перечислены в том же порядке, в каком судит :meth:`_Plan.candidates`, и
    каждая раздача получает ПЕРВУЮ подошедшую: у выкинутой их бывает несколько сразу,
    а объяснять человеку надо ту, на которой её и выкинули.
    """
    if misses_episode(release, plan.want):
        return _NO_EPISODE
    if is_disc(release):
        return _DISC
    if is_extra(release, plan.runtime):
        return _EXTRAS
    if over_ceiling(release, plan.runtime, plan.warn_mbit, plan.hard_mbit):
        return _HEAVY
    if release.is_hevc and plan.copy_hevc:
        return ""
    if release.is_hevc and not (plan.last_resort or plan.copy_hevc):
        return _HEVC
    # Дальше раздача не прошла ворота (:attr:`~torrcast.parse.Release.prime`), и причина
    # у ворот ровно та, чем имя о себе сказало: назван чужой кодек, назван мелкий кадр,
    # назван не-HD-источник. Не сказало ничего - это молчание, и оно отдельная причина:
    # молчаливую раздачу судит ffprobe, когда ворота открыты (:attr:`_Plan.loose`).
    if release.codec:
        return _CODEC
    if release.height:
        return _SMALL
    if release.source:
        return _SOURCE
    return _QUIET


def queue_drops(plan: _Plan, queue: list[int], pinned: bool = False) -> dict[str, int]:
    """Сколько раздач картины выкинуто до очереди и по каким причинам.

    Считается ПО ПУЛУ КАРТИНЫ, а не по :attr:`_Plan.ranked`: раздачи, у которых нет
    нужного сезона, отсекаются ещё при сборке плана (:func:`_plan_for`) и до сих пор не
    попадали ни в одну строку вовсе. Поэтому сумма очереди и всех причин сходится с
    длиной ``plan.picture.releases`` — это и есть проверка того, что счёт полон.

    Свёрткой, а не событием на раздачу, — намеренно: 895 событий на один запрос это не
    диагностика, а способ переполнить очередь записи, из которой события теряются молча
    (:class:`torrcast.trace._Writer`).

    ``pinned`` — релиз назван руками (``--release N``), и остальные не «выкинуты», а не
    спрошены: причин отбора у них нет.
    """
    counts: dict[str, int] = {}
    if plan.off_season:
        counts[OFF_SEASON] = plan.off_season
    taken = set(queue)
    for number, release in enumerate(plan.ranked, start=1):
        if number in taken:
            continue
        why = _PINNED if pinned else drop_reason(release, plan)
        counts[why] = counts.get(why, 0) + 1
    return counts


def hevc_hope(release: Release, last: bool) -> bool:
    """Релиз проходит в очередь ТОЛЬКО последней надеждой: он названный HEVC.

    Ворота отбора держали HEVC снаружи с самого начала, и это было правдой ровно до тех
    пор, пока показ его не умел. Теперь умеет: сплошной перекод по файлу закрыл
    десятибитный H.264 (:func:`torrcast.stream.recodes_whole`), и HEVC идёт по тому же
    пути тем же кодом. Ворота при этом отбраковывали то, что тракт играет, — и на
    «Гинтаме» это стоило показа целиком: первая серия во всём каталоге лежит в двух
    раздачах, DVDRip-AVC с НУЛЁМ сидов и ``BDRip-HEVC 720p`` с четырьмя, то есть
    единственный живой носитель серии в очередь не попадал вовсе.

    ``last`` — ворота последней надежды открыты (:func:`_plan_for`). Закрыты — признак
    не срабатывает никогда, и ни отбор, ни порядок не меняются ни на знак: при живом
    обычном релизе HEVC по-прежнему не кандидат. Это не осторожность, а цена: сплошной
    перекод занимает процессор от первой секунды до титров и стартует медленнее
    (замер: 8 с против 5 с).

    🔴 Про ПРИЁМНИК здесь не спрашивается ничего, и это не забывчивость. Вопрос «а этот
    декодер вообще спотыкается о HEVC» — один на весь код
    (:func:`torrcast.stream.recodes_whole`), задаётся он профилю
    (:mod:`torrcast.profile`) и задан уже в воротах, при вычислении ``last``. Спросить
    его и тут значило бы развести решение о кодеке на два места, а именно от этого и
    ломался десятибитный H.264.

    🔴 TC-222. Кадр выше 1080p сюда ПРОХОДИТ, и это разворот прежнего правила. Прежнее
    стояло на арифметике «скорость сплошного перекода замерена на 1080p, у 2160p вчетверо
    больше пикселей, в бюджет старта не влезает», а замер TC-157 её перевернул: тот же
    перекод СО СКЕЙЛОМ до 1080p идёт 1.53× реального времени против 1.03× без скейла -
    вчетверо меньше пикселей достаётся кодировщику, и он от этого не тонет, а ускоряется.
    Отказывать тут значило бы отказывать в единственном носителе картины ради потолка,
    которого больше нет. Решение владельца ровно такое: нет 1080p - 2160p перекодируется
    вниз как последняя надежда, а не отбрасывается.

    ⚠️ Предпочтением 4К от этого не становится: под 1080p его топит ступень
    :func:`needs_whole_recode` (она стоит выше живости), а слишком тяжёлый 4К по-прежнему
    не проходит потолок :func:`over_ceiling`.

    Имя, о разрешении молчащее, проходит и здесь: судить его будет ffprobe после выбора
    (:meth:`_Bench._trouble`), у которого высота кадра не заявка, а факт.
    """
    return last and release.is_hevc


def needs_whole_recode(release: Release, runtime: float, hard_mbit: float) -> bool:
    """Релиз играбелен только сплошным перекодом: он тяжелее ``hard_mbit`` или крупнее кадром.

    Ступень отбора, а не отказ. Такой релиз берётся — но последним из годных: держать
    его показ дороже во всём сразу. Процессор занят с первой секунды и до титров
    (посегментному перекоду хватало тяжёлых мест), рою надо отдавать ~4.7 МБ/с
    непрерывно вместо ~1 МБ/с, и любая просадка роя, которую лёгкий релиз пережил бы за
    счёт запаса, тут сразу становится подгрузом. Поэтому ремукс на 36 Мбит/с обязан
    уступать честному релизу на 8, даже когда сидов у него больше.

    🔴 TC-221. Кадр выше :data:`torrcast.recode.RECODE_HEIGHT` стоит на этой ступени рядом
    с весом, и это ровно то место, где решение владельца «2160p отбраковывается в пользу
    ЖИВОГО 1080p» и превращается в порядок. 4К играется только сплошным перекодом со
    скейлом вниз - копией приёмник его не берёт (TC-157), - то есть по стоимости это тот
    же класс, что ремукс: процессор занят от первой секунды до титров, а из роя надо
    тянуть все 20 Мбит/с ради 9 на экране. Ступень стоит ВЫШЕ живости и выше
    :func:`is_full_hd`, поэтому 4К никогда не обгоняет живой 1080p, а берётся ровно
    тогда, когда 1080p нет.

    ``hard_mbit`` ноль — ступени по весу нет: перекодирование выключено, и тяжёлое
    отсеяно раньше, самим потолком отбора. Кадра это не касается: 2160p и без
    перекодирования не играется, и внизу списка ему самое место.
    """
    if release.height > RECODE_HEIGHT:
        return True
    mbit = bitrate_of(release, runtime)
    return hard_mbit > 0 and mbit is not None and mbit > hard_mbit


def gate_open(
    releases: list[Release],
    runtime: float,
    warn_mbit: float,
    want: Episode | None = None,
    hard_mbit: float = 0.0,
    copy_hevc: bool = False,
) -> bool:
    """Пора ли открыть ворота отбора: живого именного кандидата у картины нет.

    ``copy_hevc`` приходит из профиля и делает HEVC обычным именным кандидатом только
    для ресивера, который объявил его играющим копией через наш HLS.

    Ворота (:attr:`Release.prime`) защищают от мусора и делают это по делу — пока в
    выдаче есть из чего выбирать. У аниме выбирать нечасто есть из чего: имена раздач
    там сплошь без разрешения, кодека и HD-источника, и ворота оставляют картину вообще
    без живых кандидатов. Живой случай, ради которого написано: «Наруто» (2002) — полный
    сериал «[E220 of 220] [RUS(ext), ENG, JAP+Sub] … DVDRip», 157 ГБ, 91 сид, в
    кандидаты не проходит; проходят «[1-5 из 220]» на 3 сида и «[S01E01-08 of 220]» на
    один. Очередь из двух умирающих огрызков — это не защита от мусора, это отсутствие
    показа.

    «Живой» здесь — доля от лидера пула (:data:`GATE_LIVENESS`), как и у
    :func:`is_full_hd`: абсолютное число в пулах разной населённости значит разное.
    Раздачи, у которых нужной серии нет по их же имени, в счёт не идут — они и в
    очередь не попадают.

    Ворота остаются закрытыми и тогда, когда живых нет вовсе (лидер пула на нуле
    сидов): открывать их незачем, показывать всё равно нечего.
    """
    alive = max((r.seeders for r in releases), default=0)
    if alive <= 0:
        return False
    return not any(
        r.seeders >= alive * GATE_LIVENESS
        and is_candidate(r, runtime, warn_mbit, hard_mbit=hard_mbit, copy_hevc=copy_hevc)
        and not misses_episode(r, want)
        for r in releases
    )


def last_hope(
    releases: list[Release],
    runtime: float,
    warn_mbit: float,
    want: Episode | None = None,
    loose: bool = False,
    hard_mbit: float = 0.0,
    copy_hevc: bool = False,
) -> bool:
    """Пора ли пускать в очередь названный HEVC: живого кандидата нет ВООБЩЕ.

    Ступень за :func:`gate_open`, и порог у неё жёстче нарочно. Открытые ворота ещё
    ничего не гарантируют: они пускают молчаливые имена, а те могут все до одного лежать
    с нулём сидов. Ровно это и есть «Гинтама»: 162 раздачи в каталоге, первая серия — в
    двух, и та, что проходит ворота (``DVDRip-AVC``, 99 ГБ), раздаётся нулём пиров.
    Кандидат формально есть, показа нет.

    Поэтому здесь спрашивается не «есть ли кандидат», а «есть ли кандидат, которым
    МОЖНО СЫГРАТЬ»: годен по :func:`is_candidate`, несёт нужную серию и жив. Живость —
    строгий ноль, а не доля от лидера (:func:`is_dead`): доля это размен качества на
    рой, а тут разменивать нечего — либо рой есть, либо показа нет.

    ``loose`` — те же ворота, что у самого плана: молчаливое имя, если оно живое, —
    полноценный кандидат, и последнюю надежду оно закрывает наравне с именным.

    HEVC в выдаче может и не быть вовсе — тогда открытые ворота не меняют ничего:
    признак :func:`hevc_hope` не сработает ни на одной раздаче.

    ⚠️ Про приёмник тут не спрашивается: «тяжёлый ли для него HEVC» — вопрос профиля, и
    задаёт его :func:`_plan_for` перед этой ступенью, одним и тем же
    :func:`torrcast.stream.recodes_whole` на весь код.
    """
    return not any(
        release.seeders > 0
        and is_candidate(release, runtime, warn_mbit, loose, hard_mbit, copy_hevc=copy_hevc)
        and not misses_episode(release, want)
        for release in releases
    )


def sound_step(release: Release, alive: int = 0) -> int:
    """Ступень звука по имени раздачи: 0 — русская дорожка обещана, 1 — не обещана.

    Решение владельца по аниме: субтитров не делаем, а японскую дорожку без перевода
    смотреть нельзя — значит, при прочих равных релиз с русской озвучкой обязан
    обыграть чисто японский, даже если тот сидастее. У аниме дубляж часто лежит
    ОТДЕЛЬНОЙ раздачей (RuTor, Knaben), а не в релизе Nyaa, и по сидам эта раздача
    проигрывает вчистую: у «Боруто» русский «[RUS(int)]» держит 3 сида против 8 у
    «[JAP+Sub]», у «Врат Штейна» — 2 против 3.

    Ступеней ровно две, и это осознанно сжато с трёх. Промежуточная «имя прямо назвало
    чужой звук» (``[Dual Audio]``, ``[JAP+Sub]``) звучит разумно, но на живой выдаче
    покупается зря: у «Steins;Gate» она меняла верх с 397 сидов на 17, у «Chainsaw Man» —
    с 221 на 34, и русского звука ни там, ни там не появлялось. Менять живой рой на
    мёртвый, ничего не выигрывая, — прямая дорога к подгрузам, а гейт показа обратный.
    Поэтому ступень срабатывает ровно тогда, когда в выдаче ЕСТЬ что предпочесть.

    Молчание имени и чужой звук стоят в ней рядом по той же причине, по какой ворота
    отбора не судят молчание (:attr:`Release.quiet`): молчаливая раздача вполне может
    нести русскую дорожку, и узнать это можно только у ffprobe.

    ``alive`` — сиды лидера пула: мёртвый рой выигрышем не бывает ни на каком языке
    (:data:`SOUND_LIVENESS`). Без него ступень поднимала у «Наруто: Ураганные хроники»
    раздачу с НУЛЁМ сидов над играбельной — то есть меняла японский показ на никакой.
    Ноль (умолчание) читается как «пул не назван» и оставляет чистый сигнал имени: так
    ступень зовут таблица релизов и тесты.
    """
    if not release.dubbed:
        return 1
    return 0 if release.seeders >= alive * SOUND_LIVENESS else 1


def is_dated(release: Release, runtime: float) -> bool:
    """Раздача пахнет старьём — до всякого ffprobe, по имени и размеру.

    Три части признака, и они не взаимозаменяемы:

    1. :attr:`Release.dated` — имя признаётся само: XviD/DivX, ``.avi``, DVDRip/VHSRip/
       SATRip/TVRip/CAM.
    2. Имя называет ступень ниже :data:`HD_HEIGHT` — «480p», «576p». Тут спорить не с чем:
       раздача сама говорит, что она не HD, и место ей ниже любого HD. SD играется, только
       если HD в каталоге нет вовсе, — и тогда порядок внутри группы прежний.
    3. Имя не называет РАЗРЕШЕНИЯ, а размер даёт меньше :data:`SD_BITRATE` Мбит/с. Это и
       есть та раздача, ради которой всё затевалось: «Моана 2 … WEB-DL] Dub (MovieDalen)»,
       221 сид, 1.46 ГБ — в заголовке rutracker ни слова про кодек, а внутри
       ``Moana.2.2024.WEB-DLRip.ELEKTRI4KA.avi`` (проверено по самому .torrent). Ни один
       маркер из пункта 1 её не ловит.

       ⚠️ Названный кодек эту часть больше не отключает, и вот почему. Про РАЗРЕШЕНИЕ
       кодек не говорит ничего: ``BDRip-AVC`` — это и честный 1080p на 6 Мбит/с, и рип
       720×304 на 1.7. Пока «назван кодек» означало «имя не молчит», от эвристики
       ускользал целый пласт rutracker-раздач на 1.45–1.47 ГБ: у «Тёмного рыцаря:
       Возрождение легенды» такая стояла верхом с 58 сидами, у «Форреста Гампа» — со 105,
       у «Зелёной мили» — с 64, и рядом в каждой лежал названный 1080p. Ровно они и дали
       SD-фолбэк топа замера. Разрешение в имени эвристику по-прежнему отключает: там имя
       говорит по делу, и спорить с ним — работа ffprobe (:func:`understated`), а не
       прикидки по размеру.

    Почему это в cli, а не свойством релиза рядом с ``dated``: последней части нужна
    длительность картины, а её знает только план (:class:`_Plan`), не парсер. Ровно та
    же причина держит здесь :func:`bitrate_of` и :func:`is_candidate`.

    Сериалу вторая половина считается **на серию**, а не на раздачу: в ней лежит весь
    сезон, и «6 ГБ» это не битрейт фильма, а восемь серий. Делит их :func:`bitrate_of`
    по счёту серий из имени (``[S01E01-08 of 220]`` → восемь). Раньше здесь стоял
    отказ «сериалу не считаем вовсе», и подтверждённый .avi «Легенды об Аанге» 2024
    года эвристика не понижала — ловил его только ffprobe, то есть 2-5 секунд живого
    старта на раздачу, которую всё равно выбросят.

    ⚠️ Аниме (:attr:`~torrcast.parse.Release.anime`) вторая половина не судит вовсе, и это
    не поблажка жанру, а отказ от заведомо неверного счёта. Прикидка врёт там дважды:
    делит на типовые 45 минут сериала, тогда как серия аниме идёт 24, и сравнивает с
    порогом, который писан по полнометражному кино с живой съёмкой, — а рисованная
    картинка жмётся в разы лучше, и 1-1.5 Мбит/с на серию у честного 1080p там норма.
    Пока прикидка судила, получалась ровно та бессмыслица, ради которой признак и
    заведён: пак, чьё имя серии ПЕРЕСЧИТАЛО, получал метку «старьё» за свой законный
    битрейт и топился, а сосед, чьё имя серий не считает (битрейт не вычислить), метки
    не получал и стоял верхом. Судит такую раздачу ffprobe после выбора — как и всякую,
    про которую имя молчит.

    ⚠️ Имя, которое серий не считает («Локи [S01]»), по-прежнему судится только ffprobe:
    сколько внутри файлов, до метаданных не знает никто, а делить на выдуманное число
    хуже, чем промолчать. Отбраковку это не роняет — :meth:`_Bench._trouble` читает
    настоящий кодек и выбрасывает MPEG-4 в любом случае; цена молчания — те самые
    секунды, а не подмена.

    Признак меняет только ПОРЯДОК: годность решает ffprobe, а :func:`is_candidate` его
    не спрашивает — иначе у картины, где ни в одном имени нет маркера качества, не
    осталось бы ни одного кандидата.
    """
    if release.dated:
        return True
    if release.height:  # имя назвало ступень - верим ему, спорить с ним дело ffprobe
        return release.height < HD_HEIGHT
    if release.anime:  # жанровый битрейт: 1-1.5 Мбит/с на серию - это норма, а не SD
        return False
    mbit = bitrate_of(release, runtime)
    if mbit is not None and mbit < SD_BITRATE:
        return True
    return 0.0 < pack_mbit(release, runtime) < SD_BITRATE


def pack_mbit(release: Release, runtime: float) -> float:
    """Потолок битрейта серии у пака, чьё имя считает СЕЗОНЫ, но не серии; 0 — не считает.

    Дыра, которую это закрывает, и есть 🟡 «Чёрные паруса»: имена вида
    ``[S01-04] (2014-2017) HDTV-AlexFilm`` и ``HDRip, WEB-DL, HDTV … | КПК`` не называют
    ни разрешения, ни кодека, а серий не считают вовсе — :func:`bitrate_of` на них
    молчит, :func:`is_dated` промолчать обязана, и такая раздача с ОДНИМ сидом встаёт
    в очереди перебора ВЫШЕ живого сериала на 61 сид. А внутри у них SD: показ либо
    сожжёт на них :data:`MAX_TRIES` и 130 секунд, либо сыграет SD, не дойдя до живого
    720p, — и то и другое при живом каталоге.

    Считается это не выдумкой, а потолком. Сколько серий в сезоне, имя не сказало — но
    меньше :data:`SEASON_EPISODES` их почти не бывает, а делённый на МЕНЬШЕЕ число размер
    даёт БОЛЬШИЙ битрейт: если даже потолок ниже :data:`SD_BITRATE`, внутри SD наверняка.
    Числа того же случая: 10.24 ГБ на четыре сезона — потолок 1.3 Мбит/с, 27.24 ГБ —
    3.4 Мбит/с, а настоящий ``BDRip 720p`` на 114 ГБ — 14 Мбит/с, и его признак не
    трогает. Двухгигабайтный ``HDTV | BaibaKo-iPhone`` на один сезон — 1.3 Мбит/с.

    ⚠️ Это по-прежнему только ПОРЯДОК (:func:`is_dated`), и годность им не решается.
    Отдельно от :func:`bitrate_of` — нарочно: тот кормит ВОРОТА отбора
    (:func:`is_candidate`, :func:`needs_whole_recode`), а потолок в воротах означал бы
    «раздача слишком тяжёлая», то есть отказ показывать честный 114-гигабайтный пак.
    Ворота судят по подтверждённому счёту серий, как и судили; порядок — по потолку.
    """
    if release.kind != "tv" or release.episode_count or not release.seasons:
        return 0.0
    return bitrate_mbit(release.size // (len(release.seasons) * SEASON_EPISODES), runtime)


def misses_episode(release: Release, want: Episode | None) -> bool:
    """Раздача сама, своим именем, признаётся, что нужной серии в ней нет.

    Первая ступень порядка и единственная, которая стоит выше образов дисков: релиз без
    нужной серии не «хуже качеством», а бесполезен — играть в нём нечего. Молчаливое
    имя сюда не попадает никогда (:meth:`Release.covers_episode`), поэтому у сериала,
    где серии не перечисляет ни одно имя, порядок остаётся прежним.
    """
    return want is not None and not release.covers_episode(want)


def rank_releases(
    releases: list[Release],
    runtime: float,
    warn_mbit: float,
    want: Episode | None = None,
    loose: bool = False,
    hard_mbit: float = 0.0,
    last: bool = False,
    copy_hevc: bool = False,
) -> list[Release]:
    """Порядок меню: сверху самый обсиженный кандидат, потом всё остальное по
    сидам, образы дисков всегда внизу — цельного файла внутри нет, стримить нечего.

    Первой ступенью для сериала идёт :func:`misses_episode`: раздача, которая своим
    именем говорит «нужной серии тут нет», уходит под всех, кто может её содержать, —
    даже под мёртвые и под образы дисков. Живой случай, ради которого ступень
    появилась: у «Наруто» верхом стоял ``[S01E01-08 of 220]``, у «Локи» и
    «Сверхъестественного» — такие же огрызки, а полный сезон лежал строкой ниже, и
    авто-выбор упирался в «серии s1e1 в этой раздаче нет» уже после похода в рой.

    Сразу под годностью стоит :attr:`~torrcast.parse.Release.extras` — раздача, чьё имя
    называет её приложением к картине, а не картиной: фильм о фильме, дополнительные
    материалы, бонус-диск, трейлер. Ступень судит ОДНО имя, без веса, и права выкинуть
    раздачу у неё нет — она только уводит её под всё, что и правда картина. Выкидывает
    ворота (:func:`is_extra`), и им нужен ещё и вес. Разница видна ровно там, где и должна:
    бонус-диск на 11 ГБ ворота пропускают (столько ролик не весит, а ошибиться тут дорого),
    а порядок всё равно держит его последним из годных — у картины есть она сама.

    Там же сборник уступает одиночной раздаче картины. Внутри дилогии или коллекции
    выбор файла снова должен угадать часть, хотя индексер уже умеет отдать ровно
    спрошенный фильм. Сборник остаётся кандидатом, когда одиночного релиза нет.

    ⚠️ Ниже годности, а не выше, и это не мелочь. Выше она топила бы годную раздачу под
    негодную из-за одного слова в имени: у документального «Нечто: Ужас обретает форму»
    оба релиза подписаны «фильм о фильме», и BDRip на 2.2 ГБ уходил под DVDRip на 0.7,
    то есть меткой наказывалась сама картина, которую человек и звал.

    Сразу за годностью идёт ступень :func:`is_dead`: раздача с НУЛЁМ сидов уходит под
    всех, у кого рой хоть какой-то есть. Ступень стоит выше качества нарочно: качество
    это выбор между двумя показами, а ноль сидов — это отсутствие показа, и никакой
    1080p его не перевешивает. Живой случай: у «Наруто» верхом отбора стоял
    124-гигабайтный пак с нулём сидов, а сериал на 91 сид ждал ниже, потому что
    проигрывал ему по ступени старья; старт при этом упирался в двадцатисекундное
    молчание DHT ещё до первого кадра.

    Между «живостью» и «сидами» вклинена ступень :func:`is_dated`: обсиженное
    старьё уступает место годному даже при кратной разнице в сидах. Цена вопроса
    измерена: подъём такой раздачи стоит 2–5 секунд живого старта — метаданные по DHT
    плюс чтение дорожек, — и это ровно те секунды, которые незачем держать в
    критическом пути. На «Моане 2» так и было: первым
    кандидатом стоял 1.46-гигабайтный .avi с 221 сидом, а годный WEB-DL-AVC с 140
    сидами ждал своей очереди вторым.

    Следом за ней — ступень :func:`sound_step`: звук, которого не понять, — это не
    «качество похуже», а несмотренный тайтл. Поэтому она стоит ВЫШЕ :func:`is_full_hd`:
    обе ступени размениваются на сиды, и размен «1080p вместо 720p» дешевле размена
    «по-русски вместо по-японски». Ниже :func:`is_dated` она стоит по обратной причине:
    русский .avi вместо честного 1080p — это уже не размен, а откат по всему фронту.

    Следом — ступень :func:`is_full_hd`: живой 1080p обходит 720p, даже когда сидов
    у него меньше. Дальше внутри каждой группы всё как было — сиды, потом размер.

    Сразу под годностью стоит :func:`needs_whole_recode`: релиз, который играется только
    сплошным перекодом (BD-ремукс на 28-37 Мбит/с), годен, но идёт последним из годных.
    Ступень стоит выше живости нарочно: тяжёлое берётся, когда легче ничего нет, а не
    потому, что у ремукса больше сидов.

    Сразу под живостью стоит :func:`hevc_hope` — релиз, попавший в очередь последней
    надеждой. Ступень пустая, пока ворота ``last`` закрыты: ключ у всех одинаковый, и
    порядок обычного случая не меняется ни на строку. Открылись — HEVC уходит под всех
    прочих кандидатов, потому что стоит он дороже во всём: процессор занят сплошным
    перекодом от первой секунды до титров, а старт замерен на 3 с медленнее.

    Ниже живости, а не выше, она стоит по той же причине, по которой :func:`is_dead`
    поднялась над качеством: ворота последней надежды открываются только тогда, когда
    живого обычного кандидата нет вовсе, и единственный, кто остаётся против HEVC, —
    раздача с нулём сидов. Она не «обычный релиз», она отсутствие показа, и двадцать
    секунд молчания DHT перед живым HEVC — чистая потеря старта.

    ``loose`` — ворота отбора открыты (:func:`gate_open`), и молчаливые имена идут
    в кандидатах наравне с именными. ``last`` — открыты ворота последней надежды
    (:func:`last_hope`). ``copy_hevc`` - профиль разрешил HEVC копией, поэтому это
    обычный кандидат, а не последняя надежда.
    """
    alive = max((r.seeders for r in releases), default=0)
    steps = {
        id(r): (
            misses_episode(r, want),
            is_disc(r),
            not is_candidate(r, runtime, warn_mbit, loose, hard_mbit, last, copy_hevc),
            r.collection,
            r.extras,
            r.stereoscopic,
            needs_whole_recode(r, runtime, hard_mbit),
            is_dead(r, alive),
            hevc_hope(r, last),
            is_dated(r, runtime),
            sound_step(r, alive),
        )
        for r in releases
    }
    # Цена размена «1080p вместо 720p» меряется сидами сильнейшего из тех, кого этот
    # 1080p и правда потеснит, - равных по всем ступеням выше. Лидер пула тут не мерка:
    # он может сидеть на другой ступени (старьё, чужой звук, сплошной перекод) и в споре
    # за верх не участвовать вовсе, а его сиды всё равно раздували знаменатель.
    rivals: dict[tuple[object, ...], int] = {}
    for r in releases:
        key = steps[id(r)]
        rivals[key] = max(rivals.get(key, 0), r.seeders)
    return sorted(
        releases,
        key=lambda r: (
            *steps[id(r)],
            not is_full_hd(r, rivals[steps[id(r)]]),
            -r.seeders,
            -r.size,
            r.magnet,
        ),
    )


def is_dead(release: Release, alive: int) -> bool:
    """Ноль сидов при живых соседях: играть тут нечего ни на каком качестве.

    Живость участвовала в порядке и раньше, но только ВНУТРИ ступеней качества
    (:func:`is_full_hd`, :func:`sound_step`) — то есть мёртвая раздача имела полное
    право стоять верхом, если по имени она годнее живой. Так и было на живой выдаче
    «наруто»: 124-гигабайтный пак с нулём сидов обходил сериал на 91 сид, потому что у
    того в имени стоит ``DVDRip``. Enter в такой верх — это двадцать секунд молчания
    DHT и переход к следующему, то есть чистая потеря старта.

    Порог тут ровно ноль, и никакой доли от лидера: доля — это размен «поменьше сидов
    ради ступени качества», и её уже держат :data:`FULL_HD_LIVENESS` и
    :data:`SOUND_LIVENESS`, каждый со своей ценой. А ноль — не размен: раздача,
    которую никто не раздаёт, не играется вовсе.

    ``alive`` — сиды лидера пула. Пул, где на нуле ВСЕ (свежая раздача, индексер не
    отдал числа), ступень не трогает: понижать там некого и не в пользу кого.
    """
    return alive > 0 and release.seeders <= 0


def is_full_hd(release: Release, alive: int) -> bool:
    """Имя обещает 1080p (или выше), и раздача при этом жива.

    Ступень нужна затем, что до неё разрешение в порядке не участвовало вовсе: среди
    кандидатов правили одни сиды, и названный 1080p проигрывал названному 720p с
    троекратным перевесом сидов. На «Мастере и Маргарите» так и было — верхом стоял
    ``WEB-DL 720p`` со 146 сидами, а ``WEB-DL 1080p`` с 59 ждал вторым.

    Живость в условии не для красоты, и цена у неё замерена на той же выдаче: у «Зелёной
    мили» единственные названные 1080p имеют 4 и 1 сид против 38 у 720p, у «Форреста
    Гампа» — 2, 1, 0, 0 против 41. Поднять такой 1080p значило бы поменять ступень
    качества на подгрузы, а гейт показа прямо обратный: плавность выше пиковой чёткости.
    Порог :data:`FULL_HD_LIVENESS` разводит эти случаи с запасом — 0.40 против 0.10 и 0.05.

    ``alive`` — сиды сильнейшего из тех, кого 1080p потеснит этой ступенью, то есть
    равных ему по всем ступеням выше (:func:`rank_releases` считает максимум по группе).
    До этого знаменателем был лидер пула, и он топил живой 1080p под 720p всякий раз,
    когда лидер сидел на чужой ступени и в споре не участвовал: у «Истории игрушек 3»
    лидером числился 126-сидовый ``BDRip-AVC`` на 1.5 ГБ (старьё, утоплено своей
    ступенью), и названный 1080p с 30 сидами проигрывал 720p с 55 — 30 < 126 × 0.25,
    хотя против настоящего соперника у него 0.55.

    Второй пол условия — :data:`ALIVE_SEEDERS`: доля от соседа не оживляет рой, который
    не играет сам по себе. У «Сёгуна» верхом стоял 1080p на трёх сидах против 720p на
    пяти: доля 0.60 формально проходила, а двухсидовый рой — это подгрузы, и живой 720p
    честнее. Пол тот же, что у живости картины: один-два сида — не рой ни на какой
    ступени.

    Врущему имени ступень не помогает: подтверждает разрешение ffprobe, и «названный
    1080p, а внутри 574p» подменяется на честного соседа (:meth:`_Bench._honest`).

    2160p поднимается вместе с 1080p: это тоже честный HD, а его тяжесть снимает
    перекодирование на ходу — отбраковывает только ``bitrate_hard_mbit``.

    ⚠️ Живой 1080p от этого 4К не проигрывает: ступень «играется только сплошным
    перекодом» (:func:`needs_whole_recode`) стоит ВЫШЕ этой и топит 2160p под всех, у
    кого кадр по зубам приёмнику (TC-221). Здесь 2160p спорит уже только с 720p.
    """
    if release.interlaced or release.height < FULL_HEIGHT or release.seeders < ALIVE_SEEDERS:
        return False
    return release.seeders >= alive * FULL_HD_LIVENESS


def peer_grace(plan: _Plan, number: int, queue: list[int]) -> float:
    """Сколько этой раздаче даётся на ПЕРВЫЙ КОНТАКТ роя, секунды.

    🔴 TC-387. Отсрочка назначается ценой ошибки, а не свойствами раздачи. Обычная
    (:data:`PEER_GRACE`) стоит одного места в очереди: молчаливый релиз пропускается, а
    следующий спрашивается всё равно. Но когда следующий ступенью ниже, ошибка стоит
    обещанной чёткости - живой 1080p уступает 720p не своим роем, а нашим нетерпением, -
    и такой раздаче даётся :data:`STEP_GRACE`.

    Ступень тут решается ИМЕНАМИ соседей, а не сидами: живость раздачи в эту минуту как
    раз и есть то, чего мы ещё не знаем. Молчащее о разрешении имя стоит с низкими:
    подтвердить его нечем, пока раздачу не подняли, и ровно так же его судит
    :func:`is_full_hd`.

    Соседи берутся из фактического хвоста ``queue`` после этой раздачи. Поэтому ручной
    выбор, проверка по звуку и уже пройденный сосед отсрочку не удлиняют. Ворота и
    нужная серия учтены при построении самой очереди (:meth:`_Plan.candidates`).
    """
    release = plan.ranked[number - 1]
    if release.height < FULL_HEIGHT or number not in queue:
        return PEER_GRACE
    after = queue[queue.index(number) + 1 :]
    lower = any(plan.ranked[other - 1].height < FULL_HEIGHT for other in after)
    return STEP_GRACE if lower else PEER_GRACE


#: Насколько чужое обещание должно превышать наш кадр, чтобы считаться ступенью выше.
#: 1080 против 1078 — не ступень, а округление разных рипов одного и того же мастера.
STEP_RATIO: Final = 0.95


def stepdown_note(
    plan: _Plan,
    number: int,
    media: Media | None,
    queue: list[int],
    judged: dict[int, str] | None = None,
    reached: int = 0,
) -> str:
    """Одна строка о том, что показ едет ступенью НИЖЕ, чем в выдаче было доступно.

    🔴 TC-187. «Интерстеллар», «Форрест Гамп», «Зелёная миля», «Нелюбовь» доезжали в
    720p и SD при живых 1080p в той же выдаче — и ни одна строка об этом не говорила.
    Молчаливых подмен нет: снижение ступени — такое же авто-решение, как выбор релиза,
    и человек обязан услышать не только «что взяли», но и «почему не лучшее».

    Взятое меряется ПАСПОРТОМ, а не именем: ffprobe уже прочитан, и «названный 1080p, а
    внутри 574p» обязан считаться SD, иначе строка молчала бы ровно там, где подмена и
    случилась. Соседей мерить нечем, кроме имени, — их паспорта нет и не будет, пока их
    не подняли; поэтому у них берётся заявка, а порог :data:`STEP_RATIO` не даёт считать
    ступенью разницу в округлении.

    Причина — из того, чем кончилась их очередь:

    - ``отбраковали`` — раздачу трогали, и ffprobe (или рой) её осудил; приговор в строке;
    - ``не дошли`` — стояла в очереди, но до неё не добрались: годный нашёлся раньше;
    - ``в очередь не попал`` — выкинули воротами ещё до каста (:func:`drop_reason`);
    - ``рой мёртв`` — лучшее в выдаче есть, а сидов у него ноль: это не показ.

    Лучшего не было — строки нет вовсе: сообщать нечего, а лишняя строка на каждом
    показе обесценивает все остальные.
    """
    judged = judged or {}
    taken = plan.ranked[number - 1]
    frame = media.frame if media is not None and media.height else taken.height
    better = [
        (n, r)
        for n, r in enumerate(plan.ranked, start=1)
        if n != number
        and r.height * STEP_RATIO > frame
        and not misses_episode(r, plan.want)
        and not is_disc(r)
    ]
    if not better:
        return ""
    alive = [(n, r) for n, r in better if r.seeders > 0]
    best = max(alive or better, key=lambda pair: (pair[1].height, pair[1].seeders))
    at, rival = best
    if not alive:
        why = "рой мёртв"
    elif at in judged:
        why = f"отбраковали ({judged[at]})"
    elif at in queue:
        why = "не дошли" if queue.index(at) >= reached else "не ответил"
    else:
        why = f"в очередь не попал: {drop_reason(rival, plan)}"
    took = media.quality if media is not None and media.height else (taken.quality or "?")
    return f"взял {took}, рядом был {rival.quality} (релиз {at}, сидов {rival.seeders}) - {why}"


def bitrate_of(release: Release, duration: float) -> float | None:
    """Оценка битрейта по размеру раздачи. У одиночного фильма берётся вся раздача,
    у сборника - один фильм, у сериала - ОДНА СЕРИЯ: «9.7 ГБ» на восемь серий это
    3 Мбит/с, а не 30, и по оценке целиком самые обсиженные раздачи сезона улетали бы
    вниз с пометкой «тяжёлый».

    Сколько внутри серий, говорит имя раздачи (:attr:`Release.episode_count`):
    ``[S01E01-08 of 220]`` — восемь, ``[E220 of 220]`` — двести двадцать. Имя молчит —
    отдаём ``None``, и это 🔴 TC-344: «не знаю» и «мало» — разные ответы. Ноль здесь
    раньше значил «ниже любого порога», и ворота читали молчание имени как «лёгкий и
    безопасный»: весовая половина :func:`is_extra` у таких сериалов срабатывала всегда,
    а потолок :func:`over_ceiling` - никогда. Делить на выдуманный счёт значит врать
    себе, а настоящий битрейт серии всё равно померит ffprobe по её файлу - поэтому
    каждый, кто зовёт эту прикидку, обязан решить свой ``None`` сам: в отказ молчание
    не превращается нигде.
    """
    if release.kind != "tv":
        count = release.collection_count
        return bitrate_mbit(release.size // count, duration) if count else None
    count = release.episode_count
    return bitrate_mbit(release.size // count, duration) if count else None


def render_table(
    releases: list[Release],
    runtime: float,
    warn_mbit: float,
    limit: int = TABLE_LIMIT,
    recode_at: float = 0.0,
    hard_mbit: float = 0.0,
) -> str:
    """Таблица релизов: N · качество · размер · сиды · озвучка · кодек. Битрейт для
    пометки прикидывается по размеру и типовой длительности, пока настоящая не прочитана
    ffprobe; ниже ``limit`` — раздачи без сидов, выбирать там нечего.
    """
    shown = releases[:limit]
    rows = [
        (
            str(number),
            r.quality or "?",
            _gb(r.size),
            str(r.seeders),
            _cut(", ".join(r.voices) or "-", 34),
            ((r.codec or "?") + " " + warned(r, runtime, warn_mbit, recode_at, hard_mbit)).strip(),
        )
        for number, r in enumerate(shown, start=1)
    ]
    head = ("N", "Качество", "Размер", "Сиды", "Озвучка", "Кодек")
    width = [max(len(c[i]) for c in (head, *rows)) for i in range(len(head))]

    def line(cells: tuple[str, ...]) -> str:
        return "  " + "  ".join(_pad(c, w) for c, w in zip(cells, width, strict=True))

    out = ["Релизы:", line(head), *(line(row).rstrip() for row in rows)]
    if len(releases) > len(shown):
        out.append(f"  ... и ещё {len(releases) - len(shown)} с меньшим числом сидов")
    return "\n".join(out)


def pick_voice(media: Media, args: Args, remembered: str = "") -> tuple[int, str]:
    """Какую дорожку играем и что после этого лежит в памяти картины.

    **На счастливом пути вопроса про озвучку нет.** Дорожка выбирается сама
    (:meth:`Media.default_track`), и её подпись печатается в строке запуска —
    молчаливых подмен не бывает.

    Спросить можно только явно: ``--voice N`` берёт дорожку N, ``--voice`` без номера
    показывает меню. Оба — явный выбор, и только он пишется в память картины
    (:attr:`torrcast.state.Entry.voice`). Автовыбор память не трогает: иначе первый же
    запуск с другим релизом переписал бы то, что пользователь выбрал руками.

    Возвращает пару «номер дорожки в этом релизе, память картины».
    """
    if not media.tracks:
        raise InfraError("в файле нет звуковых дорожек")
    if args.voice is not None:
        index = _ask_voice(media) if args.voice == VOICE_MENU else _voice_number(media, args.voice)
        return index, media.tracks[index].label
    if remembered:
        found = media.find_voice(remembered)
        if found is not None:
            return found, remembered
        # Память живёт на картину, а релиз временный: озвучки в нём нет - говорим и
        # играем обычную, но выбор пользователя не забываем (:attr:`Entry.voice`).
        print(f"озвучки «{remembered}» в этом релизе нет - беру обычную")
    return media.default_track(), remembered


#: Языковые коды ffprobe → как язык зовут вслух. Список короткий и ровно про то, что
#: живёт в раздачах кино и аниме; чего в нём нет, называется «оригинальный».
_SPOKEN: dict[str, str] = {
    "jpn": "японский",
    "ja": "японский",
    "jap": "японский",
    "eng": "английский",
    "en": "английский",
    "kor": "корейский",
    "zho": "китайский",
    "chi": "китайский",
    "fra": "французский",
    "fre": "французский",
    "deu": "немецкий",
    "ger": "немецкий",
    "spa": "испанский",
    "ita": "итальянский",
}


def spoken(track: AudioTrack) -> str:
    """Как назвать язык дорожки вслух: «японский»; неизвестный — «оригинальный»."""
    return _SPOKEN.get((track.language or "").strip().casefold(), "оригинальный")


def heard(media: Media) -> str:
    """Каким языком заговорит этот файл: язык дорожки, которую взял бы показ.

    Нужен строкам отбора (:meth:`_Bench.resolve`): «релиз 1 без русской озвучки» само по
    себе не говорит человеку ничего о том, что он услышит, а «(японский)» говорит. Берётся
    та же дорожка, что и играла бы (:meth:`torrcast.stream.Media.default_track`), - иначе
    строка отбора и строка запуска называли бы разные языки одного файла.

    🔴 TC-492. Дорожка без тега языка называется «не назван», а не «оригинальный»: это
    ровно тот случай, ради которого гейт и бракует релиз (:func:`voice_unproven`), и
    придумывать ей язык в той же строке было бы второй такой же ошибкой.
    """
    if not media.tracks:
        return "не назван"
    index = media.default_track()
    track = media.tracks[index] if index < len(media.tracks) else media.tracks[0]
    return spoken(track) if track.named else "не назван"


def sound_note(
    media: Media,
    audio: int,
    pool: list[Release],
    release: Release | None = None,
    files: Sequence[TorrFile] = (),
    *,
    native: bool = False,
) -> str:
    """Честная строка про звук, когда русской дорожки в файле не оказалось; иначе пусто.

    Решение владельца по аниме: субтитров не делаем — значит японский тайтл без
    перевода останется японским, и показ обязан сказать это ДО картинки, а не оставить
    человека выяснять на слух. Показ при этом играет: решает он сам, наше дело —
    предупредить честно.

    Строки три, и разница между ними не косметическая:

    * перевод в каталоге есть, но в этом релизе его не оказалось — строка называет и
      запасной ход: выбрать раздачу руками;
    * 🔴 TC-191: перевод в каталоге есть, но только ОТДЕЛЬНЫМ ФАЙЛОМ
      (:attr:`~torrcast.parse.Release.external_dub`, «[RUS(ext)]») — тогда выбирать
      руками нечего: играть звук из соседнего файла показ не умеет, и честнее сказать
      это прямо, чем отправить человека по кругу за тем же японским;
    * перевода нет вообще ни у кого в выдаче — «только японский звук, перевода в
      каталоге нет», и делать тут больше нечего.

    Чей звук играет, читается из дорожки (:func:`spoken`), а не додумывается: у
    французского фильма без перевода японского звука взяться неоткуда.
    """
    if not media.tracks or any(t.is_russian for t in media.tracks):
        return ""
    track = media.tracks[audio] if audio < len(media.tracks) else media.tracks[0]
    if not track.named:
        if native:
            return ""
        # Раздача язык дорожки не назвала (тег ``und``). Единственная косвенная улика -
        # имя раздачи: русский маркер в нём (:attr:`Release.dubbed`) - повод СКАЗАТЬ про
        # русскую, назвав источник, а не молча подставить её (и не выдать за неё). Улики
        # нет - язык так и остаётся неизвестным, и об этом честная строка.
        if release is not None and release.dubbed:
            return "звук без метки языка - по имени релиза русская"
        return "язык дорожки неизвестен - раздача не назвала язык озвучки"
    lang = spoken(track)
    if any(r is not release and r.dubbed and r.seeders > 0 for r in pool):
        return f"только {lang} звук - в каталоге, возможно, есть перевод в другой раздаче"
    if _russian_audio_file(files) or any(r.external_dub and r.seeders > 0 for r in pool):
        return f"только {lang} звук - в каталоге перевод есть, но лежит отдельным файлом"
    return f"только {lang} звук, перевода в каталоге нет"


_AUDIO_FILE_EXT: Final = frozenset(
    {".aac", ".ac3", ".dts", ".eac3", ".flac", ".m4a", ".mka", ".mp3", ".ogg", ".opus", ".wav"}
)
_RU_FILE_RE: Final = re.compile(
    r"(?:^|[ ._\[(+-])(?:rus|russian|рус(?:ский|ская)?)(?:$|[ ._\])+-])", re.I
)


def _russian_audio_file(files: Sequence[TorrFile]) -> bool:
    """Есть ли в раздаче отдельный файл звука, прямо названный русским."""
    return any(
        Path(file.name).suffix.casefold() in _AUDIO_FILE_EXT and _RU_FILE_RE.search(file.base)
        for file in files
    )


def voice_note(media: Media, audio: int) -> str:
    """Одна строка про то, из чего выбиралась озвучка: «дорожек rus 4, беру дубляж
    (LostFilm)»; выбора не было — пусто.

    Подпись взятой дорожки печатается и так, но она отвечает на вопрос «что играет», а
    не «почему это». У «Барби» рядом лежат три русские дорожки, и человек, услышав не ту,
    до сих пор не знал ни что выбор был, ни что рядом было из чего выбрать.

    Молчим ровно там, где выбирать было не из чего: одна русская дорожка (или ни одной) -
    это не решение, а единственный вариант, и строка про него была бы шумом. Список
    студий целиком тут не печатается намеренно: он длинный, а нужен по запросу -
    ``cast voices <запрос>``.

    🔴 TC-242. Когда взятое расходится с лестницей по типу - двухголосый обошёл живой
    многоголосый - строка называет и ПРИЧИНУ, коротким хвостом: иначе человек читает её
    как противоречие лестнице. Причина одна: студию судят по её отборной ступени
    (:attr:`torrcast.stream.AudioTrack.rank_step`), а не по той, что произносится вслух.
    Нет расхождения - нет и хвоста: счастливый путь не засоряем.
    """
    russian = sum(1 for t in media.tracks if t.is_russian)
    if russian < 2 or not 0 <= audio < len(media.tracks):
        return ""
    track = media.tracks[audio]
    # Русских две, а играет нерусская - значит обе служебные; это тоже выбор, и назвать
    # его надо языком, а не видом перевода.
    what = (track.kind or "русскую") if track.is_russian else spoken(track)
    studio = track.studio
    tail = f" ({studio.name})" if studio and studio.name else ""
    why = ""
    if track.is_russian and studio and studio.ranks and track.rank_step < track.step:
        why = f" - эта студия у нас на уровне «{studio.ranks}»"
    return f"дорожек rus {russian}, беру {what}{tail}{why}"


def _voice_number(media: Media, number: int) -> int:
    """Номер дорожки от человека → индекс; чужого номера нет — честная строка."""
    if not 1 <= number <= len(media.tracks):
        raise NotFoundError(
            f"дорожек {len(media.tracks)}, номера {number} нет - посмотри: cast voices <запрос>"
        )
    return number - 1


def _ask_voice(media: Media) -> int:
    """Меню озвучек — только по ``--voice`` без номера. Дефолт тот же, что и без флага."""
    default = media.default_track()
    if len(media.tracks) == 1:  # выбора нет - вопроса тоже
        return default
    print(voices_table(media, default))
    return ask("Озвучка?", len(media.tracks), default=default + 1) - 1


def voices_table(media: Media, default: int, remembered: str = "") -> str:
    """Список озвучек с пометками «дефолт» и «запомнено» — для меню и ``cast voices``."""
    found = media.find_voice(remembered) if remembered else None
    rows = []
    for track in media.tracks:
        marks = (("дефолт", track.index == default), ("запомнено", track.index == found))
        note = [word for word, on in marks if on]
        tail = f"   [{', '.join(note)}]" if note else ""
        rows.append(f"  {track.index + 1}. {track.label}{tail}")
    return "\n".join(["Озвучка:", *rows])


def _gb(size: int) -> str:
    return f"{size / 1024**3:.1f} ГБ" if size else "-"


def _cut(text: str, limit: int) -> str:
    return text if len(text) <= limit else text[: limit - 3] + "..."


def _pad(text: str, width: int) -> str:
    return text + " " * (width - len(text))


def _hms(seconds: float) -> str:
    total = int(seconds)
    return f"{total // 3600}:{total % 3600 // 60:02d}:{total % 60:02d}"


