#: менять поток, который телевизор и так играет, ничего не выигрывая.
_LEVELS: Final = ((8192, "4.1"), (8704, "4.2"), (22080, "5.0"), (36864, "5.1"), (139264, "6.0"))

#: Цепочка «HDR → SDR»: PQ разворачивается в линейный свет, тонемап сжимает динамический
#: диапазон, и картинка собирается обратно уже в BT.709.
#:
#: 🔴 TC-223. Одних выходных меток ``-color_primaries/-color_trc/-colorspace bt709`` тут
#: мало, и это не придирка: метка описывает поток, а не меняет его. Пометить кадр в PQ
#: как BT.709, не преобразовав, - переклеенный ярлык: приёмник растянет кривую не той
#: гамма-характеристикой, и картинка поедет тусклой и серой. Преобразование делает вот
#: эта цепочка, метки после неё - правда.
#:
#: ``npl=100`` - яркость экрана, на которую сводим (кд/м², обычный SDR-телевизор);
#: ``hable`` - кривая, которая не срезает света в белое пятно; ``desat=0`` - без
#: автоматического обесцвечивания ярких мест: оно и даёт тот самый «выцветший» кадр.
TONEMAP: Final = (
    "zscale=t=linear:npl=100,tonemap=tonemap=hable:desat=0,"
    "zscale=t=bt709:m=bt709:p=bt709:r=tv,format=yuv420p"
)


def _scale_to(frame: int) -> str:
    """Фильтр, ужимающий кадр в габарит ступени лестницы, - и ни пикселя вверх.

    🔴 Габарит, а не одна высота. Прямое ``scale=-2:1080`` судит по высоте, а высота
    ступени не задаёт: скоуп 3840×1600 - это тот же 2160p (:attr:`torrcast.stream.Media.frame`
    считает по 16:9-габариту), и ``-2:1080`` развернул бы его в 2592×1080 - кадр, который
    ШИРЕ 1080p и приёмнику по-прежнему не по зубам. Габарит 1920×1080 с сохранением
    пропорций даёт из него честные 1920×800.

    ``min(iw,…)`` - страховка от увеличения: ``force_original_aspect_ratio=decrease``
    ужимает габарит до пропорций входа, но САМ по себе мелкий вход растянул бы до
    габарита. Нам растягивать нечего: 720p должен остаться 720p.

    ``force_divisible_by=2`` - стороны обязаны быть чётными: у ``yuv420p`` цветность
    вдвое реже яркости, и нечётная сторона кодировщику просто не даётся.
    """
    return (
        f"scale=w=min(iw\\,{frame * 16 // 9}):h=min(ih\\,{frame})"
        ":force_original_aspect_ratio=decrease:force_divisible_by=2"
    )


def level_for(frame: int) -> str:
    """Уровень H.264, в который кадр этой ступени лестницы заведомо влезает.

    🔴 TC-224. Уровень в потоке - обещание декодеру: «кадр не больше такого-то». Меряется
    оно в макроблоках 16×16, и у ``4.1`` их 8192. 1080p - это 120×68 = 8160, влезает с
    запасом в 32 макроблока; 2160p - 240×135 = 32400, вчетверо больше потолка. То есть
    прибитая строка «4.1» на 4К-кадре была прямым враньём в поток, и держалась она ровно
    на том, что 4К до кодировщика не доходило.

    Считается по ступени лестницы (:attr:`torrcast.stream.Media.frame`), то есть по
    габариту 16:9, а не по настоящим сторонам кадра: у скоупа 1920×800 макроблоков
    меньше, чем у 1920×1080, и оценка сверху тут именно то, что надо. Уровень - потолок:
    занижать его нельзя (декодер вправе не начать показ), завышать можно.

    Ступень ноль - кадр неизвестен вовсе (паспорт промолчал). Запись прежней версии без
    поля кадра сюда больше не доезжает: свой кадр она добирает тем же одним ffprobe, что
    и глубину цвета, при первом продолжении (:func:`torrcast.cli._duration`, TC-251) -
    иначе 4К-файл уехал бы в поток с этими «4.1», то есть с обещанием кадра вчетверо
    меньше настоящего. На нуле отдаём прежние ``4.1``: уровень - потолок, а не заявка.
    """
    if frame <= 0:
        return _LEVELS[0][1]
    blocks = ((frame * 16 // 9 + 15) // 16) * ((frame + 15) // 16)
    for limit, name in _LEVELS:
        if blocks <= limit:
            return name
    return _LEVELS[-1][1]


@dataclass(frozen=True, slots=True)
class Encode:
    """Чем перекодировать тяжёлый кусок: то же разрешение, тот же кодек, ниже битрейт."""

    preset: str = "veryfast"
    #: Целевой битрейт, Мбит/с. Умолчание и его замер - :attr:`torrcast.state.Config.recode_mbit`.
    mbit: float = 9.0
    #: Ступень кадра ИСТОЧНИКА (:attr:`torrcast.stream.Media.frame`); ``0`` - не спрашивали.
    frame: int = 0
    #: Потолок кадра НАРУЖУ - самый большой кадр, который берёт приёмник
    #: (:attr:`torrcast.profile.Profile.recode_frame`); ``0`` - потолка нет.
    #:
    #: Два числа рядом, а не одно готовое, нарочно: перекод обязан знать и что пришло, и
    #: что приёмнику по зубам. Из первого считается, нужен ли скейл вообще, из второго -
    #: во что ужимать, а из их встречи - уровень в потоке (:func:`level_for`).
    ceiling: int = 0
    #: Источник в HDR (PQ или HLG) - картинку надо привести к SDR (:data:`TONEMAP`).
    hdr: bool = False

    @property
    def maxrate(self) -> float:
        """Потолок мгновенного битрейта. Выше цели на 8 % — иначе кап душит движение."""
        return self.mbit * 1.08

    @property
    def scaled(self) -> bool:
        """Ужимаем ли кадр: источник крупнее того, что берёт приёмник."""
        return self.ceiling > 0 and self.frame > self.ceiling

    @property
    def out_frame(self) -> int:
        """Ступень кадра, который уедет НАРУЖУ; ``0`` - кадра не спрашивали."""
        return self.ceiling if self.scaled else self.frame

    @property
    def mark(self) -> str:
        """Чем этот перекод отличается от прежних в имени каталога прогретого; пусто - ничем.

        Ключ прогретого собирает всё, от чего зависит СОДЕРЖИМОЕ куска
        (:func:`torrcast.warm.warm_key`), и ужатый кадр с тонемапом - ровно оно. Пустая
        строка на неужатом SDR не косметика: она оставляет ключи прежних прогонов теми же,
        какими они были, и прогретое прошлого показа находится.
        """
        return (f":{self.out_frame}p" if self.scaled else "") + (":sdr" if self.hdr else "")

    @property
    def filters(self) -> str:
        """Цепочка ``-vf``; пусто - фильтровать нечего, поток идёт как шёл.

        Порядок в цепочке замерен, а не выбран на глаз (TC-223): скейл стоит ПЕРВЫМ,
        тонемап работает уже на 1080p. Тонемап - самый дорогой фильтр в тракте, и цена
        его линейна по пикселям, так что вчетверо меньший кадр стоит вчетверо дешевле.
        """
        chain = [_scale_to(self.ceiling)] if self.scaled else []
        if self.hdr:
            chain.append(TONEMAP)
        return ",".join(chain)

    def args(self, grid: Grid, slot: int, until: int) -> list[str]:
        """Аргументы видео для :func:`torrcast.stream.ffmpeg_pack_command`.

        Принудительные опорные кадры стоят на границах сетки — без них сегментный муксер
        с ``-break_non_keyframes 0`` ждал бы ближайший кадр кодировщика и резал бы куда
        попало, а обещание ``EXT-X-INDEPENDENT-SEGMENTS`` в манифесте стало бы враньём.

        Профиль здесь НЕ задаётся, и это не забывчивость. ``-profile:v`` у x264 - потолок,
        а не пол: он умеет только запретить лишнее, а включить ничего не может. Замер:
        строка параметров, которую x264 пишет в поток, с ``-profile:v high`` и без него
        совпадает символ в символ - на ``ultrafast`` обе дают ``cabac=0 8x8dct=0`` и в SPS
        ``profile_idc=66`` (Constrained Baseline), на ``veryfast`` обе дают ``cabac=1`` и
        ``profile_idc=100`` (High). То есть флаг в коде читался как обещание High, а на
        самом быстром пресете наружу всё равно уходил Baseline. Потолок тут и не нужен:
        десятибитный источник обрезает ``-pix_fmt yuv420p`` (без него тот же вход даёт
        High 10), выше High подняться не на чем. Настоящий High на ``ultrafast`` стоит
        ``-x264-params cabac=1:8x8dct=1``, и это уже не переименование, а другой поток:
        замер на 1080p дал +24 % ко времени перекода (1.85 с → 2.30 с на 30 с материала)
        ровно на том пресете, который берут, когда времени и так нет.

        🔴 Уровень считается от КАДРА, который уедет наружу (:func:`level_for`), а не
        пишется строкой. Прибитые «4.1» на 2160p обещали декодеру кадр вчетверо меньше
        того, что лежит в потоке (TC-224).

        🔴 Метки цвета ставятся ровно тогда, когда цвет и правда преобразован
        (:data:`TONEMAP`). Метка без преобразования - переклеенный ярлык: HDR-кадр,
        помеченный BT.709, приёмник разворачивает не той кривой. А SDR-источнику метки
        не нужны вовсе: его цвет мы не трогаем, и врать нам не о чем.
        """
        keys = ",".join(
            f"{grid.start(k) - _KEY_SLACK:.3f}" for k in range(slot, min(until + 2, grid.count))
        )
        video = [
            "-c:v", "libx264",
            "-preset", self.preset,
            "-b:v", f"{self.mbit:.2f}M",
            "-maxrate", f"{self.maxrate:.2f}M",
            "-bufsize", f"{self.mbit * 2:.2f}M",
            "-pix_fmt", "yuv420p",
            "-level", level_for(self.out_frame),
            "-sc_threshold", "0",
            "-force_key_frames", keys,
        ]  # fmt: skip
        if chain := self.filters:
            video = ["-vf", chain, *video]
        if self.hdr:
            video += [
                "-color_primaries", "bt709",
                "-color_trc", "bt709",
                "-colorspace", "bt709",
            ]  # fmt: skip
        return video


def whole_encode(
    mbit: float, video_mbit: float = 0.0, frame: int = 0, ceiling: int = 0, hdr: bool = False
) -> Encode:
    """Чем перекодировать ВЕСЬ файл: пресет, битрейт и кадр - одним решением.

    Живёт здесь, а не у показа, ровно потому, что спрашивают об этом трое: сам показ
    (:func:`torrcast.cli._encode_all`), сетка прогрева и щупы замера. Разойдись они хоть
    в одном числе - щуп мерил бы не тот тракт, а прогретое легло бы под чужим ключом.

    ``video_mbit`` - вес видеодорожки источника: перекодировать лёгкое аниме в полные
    ``mbit`` значит потратить процессор на биты, которых во входе нет
    (:data:`FULL_GAIN`, :data:`FULL_FLOOR`).
    """
    want = mbit
    if video_mbit > 0:
        want = min(want, max(FULL_FLOOR, video_mbit * FULL_GAIN))
    return Encode(preset=FULL_PRESET, mbit=want, frame=frame, ceiling=ceiling, hdr=hdr)


def preset_for(
    seconds: float, slack: float, presets: tuple[tuple[str, float], ...] = PRESETS
) -> str:
    """Самый качественный пресет, который успевает уложить ``seconds`` фильма в ``slack``.

    Не успевает ни один — берём самый быстрый: кратковременное снижение качества дешевле
    подгруза. ``slack <= 0`` (кусок уже играют) — тоже самый быстрый.
    """
    for name, speed in presets:
        if slack > 0 and seconds / speed <= slack * DEADLINE_MARGIN:
            return name
    return presets[-1][0]


@dataclass(slots=True)
class Pace:
    """Фактическая скорость перекода на ЭТОЙ машине, этом фильме и при этих соседях.

    Зачем. :data:`PRESETS` — прибитые числа, снятые один раз на разогретом файле без
    соседей, и срок по ним врёт в обе стороны. Улика, ради которой это написано: журнал
    показа, где ``veryfast`` шёл 1.00×, 1.15× и 1.30× при табличных 1.40 — то есть
    арифметика «успею ли к показу» обещала запас, которого не было, и кусок приезжал
    впритык. Обратный промах не безобиднее: на лёгком материале тот же ``veryfast``
    идёт 2.62×, и по таблице показ отказывается от качества, которое успевал.

    Что меряется. Не скорость кодека, а **весь путь**: от запуска ffmpeg до готового
    куска, вместе с подъёмом процесса, чтением исходника из раздачи и выкладкой. Ровно
    это и стоит между решением «беру пресет получше» и куском на экране; чистая скорость
    кодека из ``--speed`` этой цены не видит вовсе.

    Как. Один общий масштаб на всю таблицу, а не число на пресет. Так каждый заход
    уточняет срок для ВСЕХ пресетов, включая те, которыми на этом показе ещё не ходили,
    а замер соседа говорит, что это честно: прогрев роняет все три пресета одинаково,
    на 30 % (:data:`NEIGHBOUR_TOLL`). Пропорцию пресетов друг к другу таблица знает
    заведомо лучше одного шумного замера.
    """

    #: Скользящее среднее «факт / табличка». До первого замера - :data:`NEIGHBOUR_TOLL`.
    factor: float = NEIGHBOUR_TOLL
    #: Последние :data:`PACE_MEMORY` замеров того же отношения.
    recent: list[float] = field(default_factory=list)
    #: Сколько заходов легло в замер. ``0`` - планируем по умолчанию, а не по факту.
    seen: int = 0

    @property
    def plan(self) -> float:
        """Масштаб, по которому считается срок: худшее из недавнего, а не среднее."""
        return min([self.factor, *self.recent])

    def table(self) -> tuple[tuple[str, float], ...]:
        """:data:`PRESETS`, пересчитанные в скорость, которая тут и правда бывает."""
        scale = self.plan
        return tuple((name, speed * scale) for name, speed in PRESETS)

    def speed(self, preset: str) -> float:
        """Скорость одного пресета по тому же масштабу; неизвестный - самый быстрый."""
        return dict(self.table()).get(preset, self.table()[-1][1])

    def record(self, preset: str, seconds: float, spent: float) -> float:
        """Учесть состоявшийся заход: ``seconds`` фильма за ``spent`` секунд стены.

        Возвращает замеренное отношение к таблице - его печатает журнал. Заход, который
        не дал ни куска (сорвался, брошен перемоткой), сюда не попадает: он мерит не
        скорость, а помеху.
        """
        table = dict(PRESETS).get(preset)
        if table is None or seconds <= 0 or spent <= 0:
            return self.plan
        got = seconds / spent / table
        # Первый замер кладём целиком: до него масштаба нет, есть умолчание.
        self.factor = got if self.seen == 0 else (self.factor + got) / 2
        self.seen += 1
        self.recent.append(got)
        del self.recent[:-PACE_MEMORY]
        return got


@dataclass(slots=True)
class Weights:
    """Профиль тяжести фильма: сколько Мбит/с уедет на ТВ в каждом сегменте сетки.

    Считается из карты опорных кадров до всякой упаковки. Байты карты — контейнер целиком,
    поэтому из них вычитается всё, что на ТВ не уезжает (:attr:`extra`), а само это число
    уточняется по факту (:meth:`calibrate`).
    """

    #: Мбит/с по контейнеру для каждого слота сетки.
    raw: tuple[float, ...]
    #: Что в контейнере есть, а на ТВ не уезжает: лишние дорожки и субтитры, Мбит/с.
    extra: float = 0.0
    #: Сколько замеров легло в :attr:`extra` (0 - только оценка по ffprobe).
    measured: int = 0
    #: Средний битрейт контейнера по карте, Мбит/с - тот же, что у файла целиком.
    container: float = 0.0

    @classmethod
    def of(
        cls, keys: FilmKeys, grid: Grid, extra: float = 0.0, delivered: float = 0.0
    ) -> Weights | None:
        """Профиль по карте и сетке. Карта без смещений (кэш прошлой версии) — ``None``.

        ``delivered`` — сколько Мбит/с уедет на ТВ в среднем по фильму, по паспорту
        ffprobe (:attr:`torrcast.stream.Media.delivered_mbit`). Дан — поправка «контейнер
        → ТВ» известна сразу и точно: это разница между средним по карте и им. Не дан
        (mp4 без тегов, паспорт молчит) — поправка набирается вслепую по первым
        выложенным копиям (:meth:`calibrate`).
        """
        if not keys.offset or len(keys.offset) != len(keys.at) or len(keys.at) < 3:
            return None
        raw: list[float] = []
        for slot in range(grid.count):
            span = grid.span(slot)
            head = keys.byte_at(grid.start(slot))
            tail = keys.byte_at(grid.end(slot))
            # У последнего сегмента следующей границы нет, и хвост файла картой не описан:
            # берём вес предыдущего. Один сегмент из полутысячи - цена честнее выдумки.
            if slot + 1 >= grid.count or tail <= head:
                raw.append(raw[-1] if raw else 0.0)
                continue
            raw.append((tail - head) * 8 / span / 1e6 if span > 0 else 0.0)
        total = sum(grid.span(s) for s in range(grid.count))
        container = sum(w * grid.span(s) for s, w in enumerate(raw)) / total if total > 0 else 0.0
        found = cls(raw=tuple(raw), extra=extra, container=container)
        if delivered > 0 and container > 0:
            found.extra = max(0.0, container - delivered)
            found.measured = PASSPORT_WEIGHT
        return found

    def at(self, slot: int) -> float:
        """Сколько Мбит/с уедет на ТВ в сегменте ``slot``."""
        if not 0 <= slot < len(self.raw):
            return 0.0
        return max(0.0, self.raw[slot] - self.extra)

    def heavy(self, threshold: float) -> tuple[int, ...]:
        """Слоты, которые приёмник не потянет: ``threshold`` Мбит/с и выше."""
        return tuple(s for s in range(len(self.raw)) if self.at(s) >= threshold)

    def size(self, slot: int, span: float) -> float:
        """Сколько байт весит **копия** этого куска — предсказание по карте, без потолка.

        ⚠️ Это не то же число, которым сетка проверяет потолок веса
        (:func:`torrcast.stream._weigher`): там вес зажат ``ceiling_mbit`` в предположении,
        что тяжёлый кусок перекодируют. Здесь — честный вес того, что лежит в файле, и
        именно он решает, можно ли отпустить копию наружу (:meth:`Recoder.oversize`).

        Точность замерена на «Тачках 3»: предсказание 57.8 МБ против 51.4 МБ уехавших
        на самом деле (+12 %, в безопасную сторону). То есть картой предсказывать вес
        копии МОЖНО.
        """
        return max(0.0, self.at(slot)) * max(span, 0.0) * 1e6 / 8

    def bulky(self, grid: Grid, cap: float) -> tuple[int, ...]:
        """Слоты, копия которых тяжелее ``cap`` байт, — их обязан взять кодировщик.

        Отдельно от :meth:`heavy` и не совпадает с ним: замер по картам трёх релизов
        при пороге 10 Мбит/с — «Тачки 3» 5 таких кусков вне тяжёлых, «Моана 2» 3,
        «Моана» 2016 (лёгкое кино, тяжёлых почти нет) 2 куска по 17–18.3 МБ. Каждый из
        них — это ровно тот стоп 4–8 с от слишком увесистого сегмента, только пришедший
        не битрейтом, а длиной куска на лёгком месте.
        """
        return tuple(s for s in range(len(self.raw)) if self.size(s, grid.span(s)) > cap)

    def calibrate(self, slot: int, size: int, span: float) -> None:
        """Уточнить :attr:`extra` по реально выложенному сегменту-копии.

        Скользящее среднее: одиночный сегмент может соврать (дорожки в mkv лежат
        неравномерно), а десяток — уже нет. Замер на восьми сегментах подряд дал
        разброс 3.97…4.26 Мбит/с при среднем 4.10.
        """
        if not 0 <= slot < len(self.raw) or span <= 0:
            return
        seen = size * 8 / span / 1e6
        gap = self.raw[slot] - seen
        # Здравый смысл: лишние дорожки не могут весить больше самого фильма. Всё, что
        # выходит за половину контейнера, - это не поправка, а перекодированный кусок или
        # обрезанный файл, и учиться на нём нельзя.
        if not 0.0 <= gap < self.raw[slot] * 0.5:
            return
        self.measured += 1
        weight = min(self.measured, 10)
        self.extra += (gap - self.extra) / weight


@dataclass(slots=True)
class Recoder:
    """Фоновый кодировщик тяжёлых кусков: работает впрок, пока играет остальное.

    Порядок работы — от места показа вперёд: ближайший тяжёлый кусок важнее дальнего, а
    перемотка меняет место показа и тем самым переприоритезирует очередь на следующем же
    заходе. Готовый кусок ложится в :data:`RECODE_DIR` и ждёт там своего часа; наружу его
    выкладывает упаковщик, когда дойдёт до этого места (:meth:`Packer.publish`).
    """

    source: str
    audio: int
    grid: Grid
    spare: Path
    weights: Weights
    threshold: float = 15.0
    encode: Encode = field(default_factory=Encode)
    #: Горизонт: дальше этого места фильма впрок не работаем. Ограничение не по времени, а
    #: по tmpfs - готовые куски лежат в памяти. Модель показа «Моаны 2»: 300 с горизонта
    #: держат пик кэша на 459 МБ и не стоят ни одного опоздания.
    ahead: float = 300.0
    #: Потолок кэша перекодированного, МБ. Достигнут - кодировщик спит, а не растёт.
    cache_mb: float = 384.0
    run_max: int = RUN_MAX
    #: Запас, с которым перекод обязан успеть, чтобы его стоило ждать (секунды).
    hold_guard: float = 2.0
    #: Сколько кодировщику отпущено на подъём первого захода. Пока он поднимается,
    #: упаковщик уже выкладывает ``burst`` - и без этой форы первые тяжёлые куски успевали
    #: уйти копией просто потому, что ffmpeg ещё не стартовал.
    grace: float = 6.0
    #: Во сколько секунд обходится подъём одного захода: ffmpeg открывает вход, TorrServer
    #: доезжает до нужного места. Замер - 1-3 с, берём верх.
    startup: float = 3.0
    #: Потолок ожидания перекода ПЕРВОГО сегмента прогона (:meth:`opening`), секунды.
    #: Умолчание и его замер - :attr:`torrcast.state.Config.recode_head_wait`.
    head_wait: float = 12.0
    #: Сколько ЖДЁМ перекод куска, копия которого тяжелее потолка (:meth:`_hold_bulky`),
    #: секунды. Это не срок «успеет ли», а предохранитель от вечного ожидания: копию
    #: тяжелее :data:`torrcast.stream.MAX_SEGMENT_BYTES` по сроку не отпускают вовсе, и
    #: без потолка сдохший кодировщик держал бы показ до 404.
    #:
    #: 45 с - с запасом впятеро: самый длинный кусок сетки (20 с фильма) ultrafast'ом
    #: считается 5 с, плюс подъём захода 3 с, плюс доработка чужого захода (до 6 кусков).
    over_wait: float = 45.0
    #: Фактическая скорость перекода на этом показе (:class:`Pace`). Всё, что считает срок,
    #: спрашивает её, а не :data:`PRESETS` напрямую.
    pace: Pace = field(default_factory=Pace)
    log: Any = None

    #: Где сейчас показ; обновляет :func:`torrcast.cli._hold`.
    played: float = 0.0
    #: Докуда дошла упаковка - последний выложенный наружу сегмент (:meth:`note`).
    #:
    #: ⚠️ Срок готовности считается от НЕЁ, а не от места показа, и это не мелочь.
    #: Упаковщик идёт впереди показа на ``burst`` (60 с) и на старте выкладывает эти
    #: 60 секунд разом. Считай кодировщик срок по показу - и он спокойно взялся бы за
    #: заход на полторы минуты, пока упаковщик уже выложил тяжёлые куски как есть.
    #: Ровно это и было видно в первом прогоне: v361 и v362 (26 и 28 Мбит/с) ушли копией,
    #: потому что кодировщик считал, что до них ещё полторы минуты.
    edge: int = -1
    #: Первый сегмент текущего прогона упаковки - тот, с которого пойдёт картинка
    #: (:meth:`opening`). ``-1`` - упаковка ещё не начиналась.
    head: int = -1
    #: Когда этот прогон начался (``time.monotonic``): от неё считается :attr:`head_wait`.
    head_at: float = 0.0
    done: set[int] = field(default_factory=set)
    late: int = 0
    made: int = 0
    seconds: float = 0.0
    stopped: bool = False
    #: Что кодировщик делает прямо сейчас: ``(первый слот, последний, крайний срок,
    #: когда начали, скорость пресета)``. По нему же решается, придерживать ли копию.
    job: tuple[int, int, float, float, float] | None = None
    #: Когда кодировщик подняли (:meth:`start`).
    began: float = 0.0
    #: Слот, на котором ВСТАЛА выкладка из-за слишком тяжёлой копии (:meth:`_hold_bulky`);
    #: ``-1`` - не встала. По нему кодировщик бросает чужой заход: пока упаковка стоит,
    #: работа впрок не стоит ничего (:meth:`_run`).
    blocked: int = -1
    #: С какой секунды держим слишком тяжёлую копию: слот → ``time.monotonic``.
    stuck: dict[int, float] = field(default_factory=dict)
    thread: Any = None
    packer: Any = None
    lock: Any = field(default_factory=threading.Lock)

    @property
    def working(self) -> bool:
        """Идёт ли заход прямо сейчас. По этому и уступает прогрев (:class:`torrcast.warm.Warmer`).

        Замер, ради которого свойство появилось: живой перекод под работающим прогревом
        теряет 30 % скорости (:data:`NEIGHBOUR_TOLL`), а ``nice`` от этого не спасает -
        прогрев идёт под ``nice 19`` и всё равно забирает 128 % из 400 %.
        """
        return self.job is not None

    @property
    def targets(self) -> tuple[int, ...]:
        """Слоты, которые обязан взять кодировщик: тяжёлые **или** слишком увесистые.

        Две мерки, и они не совпадают. Первая — битрейт: приёмник не тянет
        ``threshold`` Мбит/с и выше как есть. Вторая — вес куска: сегмент тяжелее
        :data:`torrcast.stream.MAX_SEGMENT_BYTES` роняет приёмник независимо от битрейта,
        а такой кусок бывает и на скромных 12 Мбит/с, если он длинный. Замер по
        картам: «Моана» 2016 — лёгкое кино, тяжёлых кусков нет вовсе, а увесистых семь,
        самый большой 18.3 МБ при замеренной границе срыва 19.4 МБ.
        """
        from torrcast.stream import MAX_SEGMENT_BYTES

        heavy = self.weights.heavy(self.threshold)
        bulky = self.weights.bulky(self.grid, MAX_SEGMENT_BYTES)
        return heavy if not bulky else tuple(sorted(set(heavy) | set(bulky)))

    def oversize(self, slot: int, size: int = 0) -> bool:
        """Копия этого куска тяжелее потолка, то есть наружу её отдавать нельзя.

        ``size`` — вес копии, уже лежащей на диске (:meth:`torrcast.stream.Packer.publish`
        знает его точно, один ``stat``); ноль — копии ещё нет, берём предсказание по карте
        (:meth:`Weights.size`), оно завышает на 12 % и промахивается в безопасную сторону.
        """
        from torrcast.stream import MAX_SEGMENT_BYTES

        if size > 0:
            return size > MAX_SEGMENT_BYTES
        return self.weights.size(slot, self.grid.span(slot)) > MAX_SEGMENT_BYTES

    def start(self) -> None:
        """Поднять поток кодировщика. Тяжёлых кусков нет — не поднимать вовсе."""
        if not self.targets:
            self._say("тяжёлых кусков нет - перекодировать нечего")
            return
        heavy = self.targets
        share = sum(self.grid.span(s) for s in heavy) / max(self.grid.duration, 1.0)
        self._say(
            f"тяжёлых кусков {len(heavy)} из {self.grid.count} "
            f"({share * 100:.0f}% фильма, порог {self.threshold:.0f} Мбит/с) - "
            f"перекодирую заранее в {self.encode.mbit:.0f} Мбит/с"
        )
        self.spare.mkdir(parents=True, exist_ok=True)
        self.began = time.monotonic()
        self.thread = threading.Thread(target=self._work, daemon=True, name="torrcast-recode")
        self.thread.start()

    def stop(self) -> None:
        """Снять кодировщик и его процесс. Готовые куски не трогаем — их уберёт показ."""
        self.stopped = True
        with self.lock:
            packer, self.packer = self.packer, None
        if packer is not None:
            packer.stop(keep_files=True, reason="показ окончен")

    def ready(self, slot: int) -> Path | None:
        """Путь к готовому перекодированному куску или ``None``."""
        from torrcast.stream import segment_name

        path = self.spare / segment_name(slot)
        return path if path.exists() else None

    def opening(self, slot: int) -> None:
        """Упаковка начинается заново с сегмента ``slot`` (:meth:`torrcast.stream.Feed.restart`).

        Зовётся на старте показа, на возврате с паузы и на каждой перемотке. Делает три
        вещи, и все три нужны ровно ради первого сегмента:

        * помечает ``slot`` головой прогона — только его копию можно придержать, пока
          картинки ещё нет (:meth:`holding`);
        * отматывает :attr:`edge` назад: наружу этот прогон не выложил ещё ничего, а
          старое значение осталось от прошлого места показа и заставило бы :meth:`_pick`
          пропустить саму голову (после перемотки назад — весь остаток фильма);
        * ставит :attr:`played` на начало этого сегмента. Место показа приходит в
          кодировщик раз в две секунды (:func:`torrcast.cli._hold`), и на перемотке оно
          столько же врёт — а очередь кодировщика решается прямо сейчас.
        """
        self.head = slot
        self.head_at = time.monotonic()
        self.edge = slot - 1
        self.played = self.grid.start(slot)

    def _head_pending(self) -> bool:
        """Голова прогона тяжёлая, ещё не готова и её ещё ждут (:attr:`head_wait`)."""
        head = self.head
        if head < 0 or head in self.done or self.ready(head) is not None:
            return False
        return self._hold_head(time.monotonic())

    def holding(self, slot: int, size: int = 0) -> bool:
        """Придержать ли копию этого куска ради перекода, который вот-вот будет готов.

        Правило одно и оно про срок, а не про расстояние: ждать стоит ровно тогда, когда
        перекод успеет **раньше**, чем показ дойдёт до этого места. Плоский порог «держим
        всё, что дальше N секунд» тут не работает в обе стороны — живой прогон на Q70D
        показал оба края: v359 (26 Мбит/с) при пороге 25 с не придержали, хотя кодировщику
        было нужно три секунды, а v360 придержали и отпустили раньше, чем заход дошёл до
        него, — и оба ушли копией, и оба уронили показ в BUFFERING.

        Кусок, до которого показ уже дошёл, не держим никогда: ожидание под носом у
        показа — это и есть подгруз. **Кроме одного** — головы прогона (:meth:`opening`):
        показ стоит ровно на ней, картинки ещё нет ни одного кадра, и ждать тут значит
        не подгружаться, а стартовать. Уйди голова копией — приёмник встаёт на первой же
        секунде показа в тяжёлом месте (старт, «Продолжить?», перемотка). Ожидание
        ограничено :attr:`head_wait` и стоит ровно один ultrafast-сегмент (2.3–3.6 с).

        ⚠️ **Одно исключение стоит выше всех сроков: копия тяжелее потолка.**
        Срок тут ни при чём — такой кусок не «хуже», он гарантированно валит приёмник
        (замер: 19.4 МБ — стоп 8 с, 24 МБ — потеря сессии целиком). Поэтому
        решает отдельное правило (:meth:`_hold_bulky`), и оно про факт, а не про срок.
        """
        now = time.monotonic()
        # Перекод уже лежит - держать нечего, :meth:`Packer.publish` возьмёт его сам.
        if self.ready(slot) is not None:
            self._unstick(slot)
            return False
        # Копию тяжелее потолка по сроку не отпускаем вовсе - ни на голове, ни в середине.
        if self.oversize(slot, size):
            return self._hold_bulky(slot, now)
        if slot == self.head:
            return self._hold_head(now)
        left = self.grid.start(slot) - self.played
        if left <= 0:
            return False
        job = self.job
        if job is None:
            # Заход не идёт: кодировщик либо ещё поднимается (первый раз), либо стоит
            # МЕЖДУ заходами - и то и другое секунды, а не минуты.
            #
            # ⚠️ Раньше тут стоял отказ по истечении :attr:`grace`, и он стоил живого
            # прогона: заход за головой длился 8 с при форе 6 с, а очередь идёт от места
            # показа вперёд - то есть следующим кодировщик взялся бы ровно за этот кусок.
            # В журнале это выглядело как «тяжёлый v359 (26 Мбит/с) ушёл копией: заход
            # не идёт», а на экране - как 16 опросов BUFFERING из 34.
            if slot not in set(self.targets):
                return False
            warm = max(self.startup, self.grace - (now - self.began))
            quickest = self.pace.table()[-1][1]
            return self.grid.span(slot) / quickest + warm + self.hold_guard <= left
        first, last, until, since, speed = job
        if slot < first or now >= until:
            return False
        if slot <= last:
            todo = sum(self.grid.span(k) for k in range(first, slot + 1)) / speed - (now - since)
            return max(0.0, todo) + self.hold_guard <= left
        # Кусок ЗА текущим заходом. Раньше тут стоял отказ - и он честно стоил живого
        # прогона: заход за головой берёт один кусок (:meth:`_pick`), а упаковщик за эти
        # пять секунд успевал выложить копией три следующих тяжёлых. Считаем так же, как
        # внутри захода: кодировщику остаётся доделать этот заход, а дальше он пойдёт
        # самым быстрым пресетом - до срока ему деваться некуда.
        # Дальше следующего захода (:data:`RUN_MAX`) планов у кодировщика нет, и гадать
        # за него нельзя: там всё решит перемотка, потолок кэша и срок соседей.
        if slot > last + self.run_max or slot not in set(self.targets):
            return False
        rest = sum(self.grid.span(k) for k in range(first, last + 1)) / speed - (now - since)
        quickest = self.pace.table()[-1][1]
        rest += sum(self.grid.span(k) for k in range(last + 1, slot + 1)) / quickest
        return max(0.0, rest) + self.hold_guard <= left

    def _hold_bulky(self, slot: int, now: float) -> bool:
        """Ждать перекод куска, копия которого тяжелее потолка. Правило про факт, не срок.

        Замер, ради которого правило написано («Тачки 3» со старта 3880):
        сетка поставила ``v364`` длиной 10.43 с, предсказав его вес по ``ceiling_mbit``
        в 11.7 МБ — «тяжёлое перекодируют». Кодировщик к сроку не успел, :meth:`holding`
        отпустил копию по сроку, и на ТВ уехали **51.4 МБ** — втрое выше потолка. Двадцать
        опросов ``BUFFERING`` за 46 с. Обе половины по отдельности честны, а вместе дают
        дыру; закрывает её ровно одна мысль: **отпускать такую копию некуда**. Приёмник её
        не переварит ни при каком сроке, значит выбор не «ждать или отдать», а «ждать или
        ждать зря».

        ⚠️ Разрезать этот кусок сеткой мельче было НЕЛЬЗЯ, и это замерено, а не сказано:
        внутри 3914.911…3925.338 нет ни одного опорного кадра — это один GOP на 51 МБ.
        Сетка режет только по опорным кадрам (иначе кусок не декодируется сам по себе), и
        никакая настройка потолка тут границы не добавит. Отсюда и деление труда: сетка
        отвечает за то, что можно разрезать, кодировщик — за то, что нельзя.

        Ждём, пока кодировщик за кусок берётся. Три случая, когда ждать нечего:
        кодировщик снят, кусок не в его списке или он на нём уже сдался (:attr:`done`).
        Плюс предохранитель :attr:`over_wait` - на случай, когда ffmpeg не поднимается
        вовсе. Что делать с отпущенной копией, решает выкладка: ужимает её на месте
        или честно пропускает (:meth:`torrcast.stream.Feed._shrink`).
        """
        from torrcast.stream import MAX_SEGMENT_BYTES

        if self.stopped or slot in self.done or slot not in set(self.targets):
            return False
        since = self.stuck.get(slot)
        if since is None:
            self.stuck[slot] = since = now
            self.blocked = slot
            mark("держу тяжёлую копию", слот=slot, мбит=round(self.weights.at(slot), 1))
            self._say(
                f"v{slot} копией тяжелее {MAX_SEGMENT_BYTES / 1e6:.0f} МБ - жду перекод: "
                "такой кусок приёмник не доигрывает"
            )
        if now - since < self.over_wait:
            self.blocked = slot
            return True
        # Предохранитель сработал: кодировщик за эти секунды не дал ничего. Снимаем
        # ожидание - дальше кусок решает выкладка (ужатие на месте или пропуск).
        self._say(f"⚠️ v{slot}: перекода нет {self.over_wait:.0f} с - снимаю ожидание")
        self._unstick(slot)
        return False

    def _unstick(self, slot: int) -> None:
        """Кусок больше не держит выкладку: перекод готов, ушёл наружу или мы сдались."""
        self.stuck.pop(slot, None)
        if self.blocked == slot:
            self.blocked = -1

    def _hold_head(self, now: float) -> bool:
        """Ждать ли перекод головы прогона. Отдельно от :meth:`holding` — правило другое.

        Голову ждёт чёрный экран, а не запас впрок, поэтому решает не «успеет ли раньше
        показа» (показ стоит ровно на ней), а «работает ли кодировщик над ней прямо
        сейчас». Пока заход за головой идёт и не выдохся — ждём: секунда чёрного экрана
        дешевле, чем встающий приёмник, и дешевле, чем бросить перекод, готовый на три
        четверти, ради копии втрое тяжелее.

        ⚠️ Плоские 12 с от начала прогона стоили живого прогона на «Тачках 3»: там голова
        (17.4 с фильма, 28.9 Мбит/с по контейнеру) кодировалась 16 с — не потому, что
        кодировщик медленный, а потому, что те же 58 МБ в это же время тянул из холодного
        роя упаковщик. Ожидание сдавалось на 12-й секунде, копия уезжала на ТВ как есть —
        и приёмник вставал ровно на её стыке со следующим куском на 10 с. Ждать эти
        лишние 4 с было БЕСПЛАТНО: картинка всё равно появлялась на 16-й секунде, только
        уже испорченная.

        Потолок остаётся: :data:`HEAD_LIMIT` от :attr:`head_wait`. Кодировщик, который не
        взялся за голову вовсе (нет процессора, сорвался ffmpeg), не имеет права держать
        показ дольше отпущенного — просроченная копия хуже тяжёлой, но лучше чёрного
        экрана без конца.

        ⚠️ Собственный срок захода (:attr:`job`) головы НЕ касается: он посчитан по
        :data:`PRESETS`, а те сняты на разогретом файле без соседей. На холодном рое голова
        «Тачек 3» шла 26 с при обещанных четырёх — по сроку захода ожидание сдавалось на
        20-й секунде, ровно за шесть секунд до готового перекода.
        """
        waited = now - self.head_at
        if self.head_wait <= 0 or self.head not in set(self.targets):
            return False
        job = self.job
        if job is not None and job[0] == self.head:
            return waited < self.head_wait * HEAD_LIMIT
        return waited < self.head_wait

    def note(self, slot: int, how: str) -> None:
        """Сегмент ушёл наружу: уточнить профиль по факту и посчитать опоздания.

        ``how`` — чем именно он ушёл: ``копия``, ``склейка`` (картинка перекода со звуком
        копии) или ``перекод`` (склейка не вышла). Копия — это
        единственный честный замер «сколько на самом деле уезжает на ТВ»: по ней и
        правится поправка :attr:`Weights.extra`, из-за которой байты карты (контейнер
        целиком) не равны байтам сегмента (видео и одна дорожка).

        ⚠️ «Склейка» и «перекод» в журнале обязаны различаться: отказ склейки — это
        вернувшийся разрыв на стыке, и молчать о нём значит разбирать подвисы вслепую.
        """
        recoded = how != "копия"
        from torrcast.stream import TRACE

        # Не максимум, а именно последний: перемотка назад начинает упаковку заново, и
        # край обязан уехать назад вместе с ней - иначе кодировщик решит, что всё позади
        # уже выложено, и до конца показа не возьмётся ни за один кусок.
        self.edge = slot
        # Кусок ушёл наружу - выкладку он больше не держит, каким бы ни был исход.
        self._unstick(slot)
        # Сколько ушло на ТВ на самом деле. Это единственный честный замер профиля, и
        # стоит он один `stat`: без него «почему приёмник встал» разбирается по размерам
        # файлов в чужом журнале, а предсказание профиля не с чем сверить.
        span, went = self.grid.span(slot), 0.0
        size = 0
        with contextlib.suppress(OSError):
            size = (self.spare.parent / f"v{slot}.ts").stat().st_size
            went = size * 8 / span / 1e6 if span > 0 else 0.0
        mark(
            "сегмент",
            слот=slot,
            перекод=recoded,
            чем=how,
            мбит=round(went, 2),
            профиль=round(self.weights.at(slot), 2),
        )
        if TRACE:
            self._say(
                f"выложен v{slot}: {how} {went:.1f} Мбит/с (профиль {self.weights.at(slot):.1f})"
            )
        # Отказ склейки - это вернувшийся разрыв на голове захода, и молчать о
        # нём нельзя даже без TRACE: он редкий, поэтому дешёвый, и он объясняет подвис.
        if how == "перекод":
            self._say(f"склейка v{slot} не вышла - перекод ушёл как есть, стык под вопросом")
        if recoded:
            return
        if size:
            self.weights.calibrate(slot, size, span)
        # Куски позади показа не в счёт: после перемотки прошлый прогон дописывает то,
        # что уже никто не увидит, и считать это опозданием - врать себе в отчёте.
        if slot in set(self.targets) and self.grid.end(slot) >= self.played:
            self.late += 1
            # Тяжёлый кусок, ушедший копией, - это будущий BUFFERING, и разбирать его
            # задним числом по размеру файла в журнале раздачи слишком дорого: пишем
            # сразу, чем в этот момент был занят кодировщик и куда смотрел показ.
            job = self.job
            self._say(
                f"тяжёлый v{slot} ({self.weights.at(slot):.0f} Мбит/с) ушёл копией: "
                f"показ {self.played:.0f} с, край {self.edge}, "
                + (f"заход v{job[0]}...v{job[1]}" if job else "заход не идёт")
            )

    def report(self) -> str:
        """Одна строка итога: сколько успели, сколько тяжёлых ушло как есть."""
        if not self.targets:
            return ""
        return (
            f"перекодировано {self.made} кусков ({self.seconds:.0f} с фильма), "
            f"тяжёлых ушло как есть {self.late}"
        )

    # ------------------------------------------------------------------ внутреннее

    def _say(self, text: str) -> None:
        if self.log is not None:
            self.log(text)

    def _weight(self) -> float:
        total = 0
        for path in self.spare.glob("v*.ts"):
            with contextlib.suppress(OSError):
                total += path.stat().st_size
        return total / 1e6

    def _sweep(self) -> None:
        """Выбросить готовые куски позади показа: их час прошёл, tmpfs не резиновый."""
        from torrcast.stream import segment_slot

        behind = self.grid.slot_at(max(0.0, self.played - 30.0))
        for path in self.spare.glob("v*.ts"):
            slot = segment_slot(path.name)
            if 0 <= slot < behind:
                path.unlink(missing_ok=True)
                self.done.discard(slot)

    def slack(self, slot: int) -> float:
        """Сколько секунд осталось до того, как этот кусок понадобится наружу.

        Считается от упаковщика, а не от показа: наружу сегмент выкладывает он, и опоздать
        к нему — значит выпустить тяжёлый кусок как есть (см. :attr:`edge`).
        """
        reached = self.grid.end(self.edge) if self.edge >= 0 else self.played
        return self.grid.start(slot) - max(self.played, reached)

    def _pick(self) -> tuple[int, int] | None:
        """Ближайший заход: подряд идущие тяжёлые куски, ещё не готовые и ещё успеваемые.

        Заход не растягивается дальше, чем кодировщик успеет: каждый следующий кусок
        обязан быть готов раньше, чем до него дойдёт упаковщик, — иначе длинный заход
        сам себе и создаёт опоздание.
        """
        # Считать от края упаковки, а не от показа: то, что уже выложено, перекодировать
        # поздно - приёмник это либо забрал, либо заберёт из tmpfs.
        here = max(self.grid.slot_at(self.played), self.edge + 1)
        horizon = self.played + self.ahead
        heavy = set(self.targets)
        quickest = self.pace.table()[-1][1]
        first = None
        for slot in sorted(heavy):
            if slot < here or self.grid.start(slot) > horizon:
                continue
            if slot in self.done or self.ready(slot) is not None:
                continue
            first = slot
            break
        if first is None:
            return None
        # Голова прогона идёт заходом в один кусок - и потому самым быстрым пресетом
        # (:func:`preset_for` от нулевого срока). Возьми её в общий заход - срок считался
        # бы по последнему куску, вышел бы superfast, и голова была бы готова к 4-5-й
        # секунде вместо 2-3-й. Остальное подхватит следующий заход.
        if first == self.head:
            return first, first
        last = first
        spent = self.grid.span(first) / quickest
        while (
            last + 1 in heavy
            and last + 1 - first + 1 <= self.run_max
            and last + 1 not in self.done
            and self.ready(last + 1) is None
        ):
            spent += self.grid.span(last + 1) / quickest
            if spent > self.slack(last + 1):
                break
            last += 1
        return first, last

    def _work(self) -> None:
        while not self.stopped:
            try:
                self._sweep()
                job = self._pick()
                if job is None:
                    time.sleep(1.0)
                    continue
                # Потолок кэша голову прогона не касается: её ждёт показ, а не запас
                # впрок, и уснуть тут значит отдать первый сегмент копией. Ровно так же
                # он не касается куска, на котором ВСТАЛА выкладка (:attr:`blocked`):
                # заснуть под потолком кэша значит держать показ до предохранителя и
                # потом всё равно выпустить тяжёлую копию.
                if job[0] not in (self.head, self.blocked) and self._weight() >= self.cache_mb:
                    time.sleep(2.0)
                    continue
                self._run(*job)
            # Кодировщик не имеет права ронять показ: он работает впрок, и его беда -
            # это в худшем случае тяжёлый кусок, ушедший как есть, а не конец фильма.
            except Exception as exc:
                self._say(f"перекодирование сорвалось ({exc}) - показ идёт как есть")
                time.sleep(5.0)

    def _run(self, first: int, last: int) -> None:
        from torrcast.stream import Packer, ffmpeg_pack_command

        seconds = sum(self.grid.span(s) for s in range(first, last + 1))
        # Срок - у ПОСЛЕДНЕГО куска захода: до него кодировщик доберётся позже всех, и
        # именно он решает, каким пресетом идти всему заходу.
        table = self.pace.table()
        preset = preset_for(seconds, self.slack(last), table)
        quickest = table[-1][1]
        # Выкладка стоит на куске этого захода (:meth:`_hold_bulky`) - качество тут больше
        # не торгуется: пока мы выбираем пресет получше, приёмник ждёт наш кусок и никакого
        # другого. Срок у такого захода нулевой по определению.
        if first <= self.blocked <= last:
            preset = PRESETS[-1][0]
        mark(
            "заход",
            первый=first,
            последний=last,
            пресет=preset,
            срок=round(self.slack(last), 1),
            срочный=round(self.slack(first), 1),
        )
        encode = Encode(preset=preset, mbit=self.encode.mbit)
        # ⚠️ Пробного прогона тут нет и быть не должно: перекодирующий ffmpeg встаёт по
        # ``-ss`` точно, докатки не делает, и ``at`` равен границе сетки ровно.
        command = ffmpeg_pack_command(
            self.source,
            self.audio,
            str(self.spare / "run"),
            self.grid,
            first,
            self.grid.start(first),
            readrate=0.0,
            burst=0.0,
            encode=encode,
            until=last,
        )
        command = ["nice", "-n", str(HEAD_NICE if first == self.head else NICE), *command]
        began = time.monotonic()
        # Срок, до которого упаковщику имеет смысл придерживать копии этого захода:
        # вдвое больше ожидаемого да ещё десять секунд сверху. Просрочен - копия уходит
        # как есть, потому что подгруз хуже тяжёлого куска.
        speed = self.pace.speed(preset)
        with self.lock:
            # ``last`` тут не украшение: без него огрызок за ``-to`` (секунда фильма
            # вместо десяти) лёг бы в каталог перекода как готовый кусок и уехал бы на ТВ
            # вместо честной копии (:attr:`torrcast.stream.Packer.last`).
            self.packer = packer = Packer.start(
                command, self.spare, self.spare / "run", first, last=last
            )
            self.job = (first, last, began + seconds / speed * 2.0 + 10.0, began, speed)
        try:
            while not self.stopped:
                packer.publish()
                if packer.edge >= last or packer.poll() is not None:
                    break
                # Перемотали за пределы этого захода - он больше не самый нужный.
                gone = self.played > self.grid.end(last)
                far = self.played < self.grid.start(first) - self.ahead
                if gone or far:
                    packer.stop(keep_files=True, reason="перемотка")
                    return
                # Голова нового прогона важнее любого запаса впрок: её ждёт чёрный экран,
                # а всё остальное - только tmpfs. Доработать заход и потом взяться за
                # голову значит проесть её ожидание чужой работой: замер -
                # заход за `v0` (7 с) съедал ровно столько же от ожидания `v358`.
                if self._head_pending() and not first <= self.head <= last:
                    packer.stop(keep_files=True, reason="голова прогона важнее")
                    return
                # Выкладка встала на слишком тяжёлой копии (:meth:`_hold_bulky`) - этот
                # кусок нужен ПРЯМО сейчас, а не впрок. Бросаем заход и берём его отдельно:
                # новый заход начнётся ровно с него, а срок у него нулевой, то есть пресет
                # выйдет самый быстрый (:func:`preset_for`). Заход, который уже идёт над
                # ним самым быстрым пресетом, не трогаем - быстрее всё равно не будет.
                stuck = self.blocked
                if stuck >= 0 and (stuck < first or (stuck <= last and speed < quickest)):
                    packer.stop(keep_files=True, reason=f"упаковка встала на v{stuck}")
                    return
                time.sleep(0.3)
        finally:
            with self.lock:
                self.packer = None
                self.job = None
            packer.stop(keep_files=True, reason="заход окончен")
        # ⚠️ Считаем по краю СВОЕГО упаковщика, а не по тому, что осталось в каталоге:
        # готовый кусок оттуда уже мог забрать показ (:meth:`Packer.publish`), и глоб
        # каталога честный заход объявлял бы провалившимся. Ровно так «перекодировал v0»
        # печаталось как «не дало ни куска за 7 с» - и стоило часа отладки не там.
        got = list(range(first, min(last, packer.edge) + 1))
        self.done.update(got)
        self.made += len(got)
        self.seconds += sum(self.grid.span(s) for s in got)
        spent = time.monotonic() - began
        if got:
            # Замер сроку, а не отчёту: столько фильма за столько стены вышло ЗДЕСЬ - с
            # подъёмом ffmpeg, чтением из раздачи и соседями (:class:`Pace`).
            made = sum(self.grid.span(s) for s in got)
            ratio = self.pace.record(preset, made, spent)
            mark(
                "темп перекода",
                пресет=preset,
                секунд=round(made, 1),
                стена=round(spent, 1),
                факт=round(made / spent, 2),
                масштаб=round(ratio, 2),
                план=round(self.pace.plan, 2),
            )
            self._say(
                f"перекодировал v{first}...v{first + len(got) - 1} "
                f"({seconds:.0f} с фильма за {spent:.0f} с, {preset}, "
                f"{made / spent:.2f}x - план {self.pace.plan:.2f} от таблицы)"
            )
        else:
            self._say(f"перекодирование v{first}...v{last} не дало ни куска за {spent:.0f} с")
            # Чтобы не крутиться на одном и том же месте вечно.
            self.done.update(range(first, last + 1))
