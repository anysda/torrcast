"""Фронт подготовки отбора: какие релизы очереди греются к этой секунде."""

from __future__ import annotations

from torrcast.domain.pick_settings import PICK_FRONT


def _bench_front(queue: list[int], attempt: int) -> list[int]:
    """Номера очереди, обязанные греться на попытке ``attempt``: этот и следующие за ним.

    Первый в ответе - тот, чьего ответа ждут прямо сейчас; остальные готовятся ему на
    смену, чтобы их метаданные и дорожки читались внахлёст с этим ожиданием, а не после
    него. Хвост очереди фронт укорачивает сам: у последней попытки в ответе один номер.

    🔴 TC-739. На ПЕРВОЙ попытке фронт на одного уже: пока верх ранжира не осуждён,
    третий сосед - это лишний ffprobe и лишний спрос к рою ровно в те секунды, когда
    читается тот файл, который вот-вот поедет на экран. Счастливый путь платить за
    неудачный не обязан, а к моменту, когда очередь и правда пошла дальше, разница
    съедается: релиз, до которого дойдёт дело, встаёт на прогрев одной попыткой позже
    и всё равно успевает ответить раньше, чем его спросят.
    """
    width = PICK_FRONT - 1 if attempt == 1 else PICK_FRONT
    return queue[attempt - 1 : attempt - 1 + width]
