"""Имя добора - лишь догадка справки: чем она доказывается и когда за ней не идут."""

from __future__ import annotations

from torrcast.domain.facts.origin import Origin
from torrcast.domain.facts.same_name import same_name
from torrcast.domain.slugify import slugify


def _second_hearsay(name: str, alt: str, about: Origin) -> bool | None:
    """Стоит ли за именем добора одно лишь слово справки; ``None`` - это другая картина.

    🔴 TC-253, TC-359. Имя добора - догадка справки, и гейт (:func:`same_picture`) против
    неё безоружен в обоих случаях: на пустой выдаче сверять добор не с чем, а с вожаком
    гейт сверяет добор со СПРАВКОЙ - но оба они тут про одну и ту же чужую картину, и
    сверка сходится. Справка на этом пути ошибается уверенно: статьи «Все мы незнакомцы»
    в Википедии нет, и по сходству имён находится «Все мы убийцы» - французская картина
    1952 года. Раньше эту ложь чаще прятал потолок в полторы секунды; теперь справке тут
    отдают весь остаток цели, и доезжать она будет ЧАЩЕ. Поэтому имя, лишь признанное
    похожим, само себя не доказывает - ему нужен второй признак, и требование одно и то
    же, есть вожак или нет:

    * справка назвала ту же картину тем же именем (:func:`~torrcast.facts.same_name`,
      «Сальтберн» и «Солтберн») - второй признак есть, идём как шли (``False``);
    * назвала другим («Все мы незнакомцы» против «Все мы убийцы») - это другая картина, и
      второго захода за ней не делаем вовсе (``None``): круг по индексерам тут не нужен,
      а честное «ничего не нашлось» не хуже чужого фильма под знакомым именем;
    * своего русского имени у статьи нет (аниме подписано латиницей) - сверить было не с
      чем (``True``), и добор берётся со строкой ровно об этом. Молча выдать его за
      проверенный нельзя: имя человек назвал сам, а картину под ним выбрала справка.

    ⚠️ Имени, за которым стоит САМА Википедия, это не касается: перенаправление «Мальчик
    и цапля» → «Мальчик и птица» - её собственное утверждение о том, что это одна вещь,
    и отметки ``guessed`` у такого паспорта нет.
    """
    hearsay = about.guessed and slugify(alt) == slugify(about.title)
    if not (hearsay and about.name):
        return hearsay
    return None if not same_name(name, about.name) else False
