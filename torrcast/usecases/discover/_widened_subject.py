"""Расширил ли добор предмет поиска: счёт картин после круга против того, что был до."""

from __future__ import annotations


def _widened_subject(pictures: int, first: int) -> bool:
    """Расширил ли добор ПРЕДМЕТ поиска, вместо того чтобы уточнить найденное.

    Одна новая картина бывает второй, несклеившейся языковой половиной той же картины:
    латинская раздача не несёт ни русского имени, ни оригинала, и кластеру нечем сшить её
    с русской половиной. Всё сверх этой одной - оригинал притащил соседние картины, а не
    ту же самую, и брать такую выдачу нельзя: широкий пул сдвинет нумерацию франшизы и
    подсунет человеку чужое кино под знакомым именем.

    🔴 TC-866. **Считать прибавку можно, только пока есть ОТ ЧЕГО считать.** Мерка говорит
    о РАСШИРЕНИИ предмета, а на пустой первой выдаче предмета нет вовсе: расширять нечего,
    и «больше чем на одну» вырождается в «не больше одной». Любой добор, привёзший
    вторую картину, отвергался - ровно там, где добор остался единственным источником
    картины и где его отказ означает отказ всего поиска.

    Живой стенд, запрос «эксперементы лейн» (описка внутри слова, картина в природе есть):
    первый круг привозит 0 строк, справка называет ``Serial Experiments Lain``, второй круг
    привозит 171 строку и 24 картины - и все они выбрасывались здесь, при 24 > 0 + 1.
    Человек читал «ничего не нашлось» при существующей картине, то есть худший из отказов.

    Отпускать мерку на пустой выдаче безопасно ровно потому, что без добора там
    ГАРАНТИРОВАН отказ: :func:`~torrcast.usecases.reinforce._as_is._as_is` вернёт ту же пустую
    выдачу, а по ней поиск и откажет. То есть эта ветка не выбирает между хорошей выдачей и
    плохой - она выбирает между какой-нибудь и никакой.

    ⚠️ Предмет поиска на пустой ветке задаёт не счёт картин, а само ИМЯ добора, и
    охраняют его два других гейта, оба на месте:

    * имя сперва сверяет справка
      (:func:`~torrcast.usecases.discover._second_hearsay._second_hearsay`): названное ДРУГИМ
      именем сюда не доезжает вовсе, за ним не идут и круга не платят. Живая проба той же
      карточки - «очень странные вещи»: картины с таким именем нет, справка отвечает
      «Очень странные дела», и гейт имени отвергает её до всякого счёта картин;
    * из привезённого берётся не всё подряд, а подписанное этим именем и заручившееся им
      (:func:`~torrcast.usecases.discover._second_wider._second_wider`,
      :func:`~torrcast.usecases.discover._vouched._vouched`): имя от справки, а не вычитанное у
      чужой раздачи, и год, который не спорит.

    ⚠️ Непустую выдачу это не трогает: там предмет есть, мерка считается как считалась, и
    счастливый путь сюда не заходит вовсе.

    **Размен замерен парно**, на 18 запросах с пустым первым кругом: выдачи сняты с живого
    каталога, канон размечен вручную. Один и тот же корпус переигран дважды - этим кодом и
    им же без ограды: **отказов ушло восемь, подмен пришло ноль**. Ключ сверки - картина,
    которая пойдёт по Enter (имя и год), а не строка выдачи: сверка по строке однажды уже
    дала ложный ноль. Пять имён, которых нет в природе («крёстный внук», «властелин
    перстней», «звёздные тропы», «матрица перевозка», «очень странные вещи»), остались
    отказом: за четырьмя справка молчит вовсе, пятую отвергает гейт имени.

    **Цена ветки - только счёт уже привезённого.** Круг добора платится и БЕЗ этой правки,
    его выдачу лишь выбрасывали: на живом стенде до правки видны оба круга и следом отказ.
    Замер на тех же выдачах: медиана +0.006 с, максимум +0.011 с, ни одного нового захода
    в сеть.
    """
    return bool(first) and pictures > first + 1


__all__ = ["_widened_subject"]
