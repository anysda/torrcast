"""Бюджет дешёвого добора: остаток цели либо его собственные секунды."""

from __future__ import annotations

from torrcast.domain.facts.settings import FACTS_BUDGET
from torrcast.domain.goal_spare import CIRCLE_SHARE, GOAL, SECOND_LEAST
from torrcast.ports.progress.progress import Progress
from torrcast.ports.torrent_catalogue.indexer_client import IndexerClient


def _no_budget(client: IndexerClient, what: str, progress: Progress) -> float | None:
    """Бюджет дешёвого добора: остаток цели либо его собственные 2.5 секунды.

    🔴 TC-228. Второй круг зовётся в 18 запросах из 100 и удваивает цену поиска: сквозной
    замер 1.93-2.39 с там, где он есть, против 0.01-0.09 с там, где его нет. ⚠️ Доля «18 из
    100» описывает СТО ЗАПРОСОВ ТОГО ЗАМЕРА, а не поиск вообще, и какая это была сотня, в
    описи сырья не сохранилось: на эталонный список в 1000 запросов её переносить нечем.
    Своего
    бюджета у него не было вовсе - он платил хвост первого круга плюс свой полный, и на
    хвосте Knaben (502 плюс ретрай, 10-20 с) это давало 30 с при цели в 10.

    Теперь у него есть остаток цели (:meth:`~torrcast.adapters.prowlarr.prowlarr.Prowlarr.spare`), и
    остаток этот честный: часы идут от начала поиска, поэтому справка на пути добора
    (:func:`~torrcast.usecases.passport.Passport.of`) считается наравне со всем прочим, а не
    «бесплатно». Возвращается она же как потолок справки - чтобы та не съела то, на что рассчитывает
    сам круг (:data:`~torrcast.domain.goal_spare.CIRCLE_SHARE`).

    🔴 TC-512. Молчащий первый индексер способен съесть всю цель один, но это не делает
    следующий добор дорогим: его цена складывается из потолка справки
    (:data:`~torrcast.domain.facts.settings.FACTS_BUDGET`, 1.5 с) и пола круга
    (:data:`~torrcast.domain.goal_spare.CIRCLE_SHARE`, 1 с). Поэтому съеденная общая цель больше не
    отменяет добор: справка получает свой потолок, круг - свой уже установленный пол.
    Выход за цель называется строкой до запроса.

    🔴 **Частный бюджет выдаётся ОДИН раз за поиск.** Пол круга это потолок бюджета
    ОДНОГО индексера, а не цена круга: круг индексеров ждёт
    каждого опорного отдельно и по ``budget + _ASK_SLACK``, поэтому круг с полом в
    секунду стоит замеренных 2.0 с на одном молчащем опорном и 4.0 с на двух, а весь
    добор - до 5.5 с вместо расчётных 2.5. Охраняемых заходов на пути до трёх
    (переспрос строкой или уточнение, затем сезонная и голосовая строки), и раздать
    частный бюджет каждому значило бы дописать к съеденной цели ещё до пятнадцати
    секунд - то есть дать больному источнику ТОРМОЗИТЬ путь, а не сужать каталог.
    Поэтому за целью идёт ровно один добор: он и есть та картина, которой не хватало,
    а следующий на той же съеденной цели удваивал бы уже превышенное. Остальным
    отвечает то, что уже найдено, и отказ им по-прежнему сказан вслух.

    ⚠️ Охранник это заходов, у которых есть честный отступ: уточнение по потолку
    индексера, сезонная и голосовая строки, переспрос всей строкой - без них отвечает
    то, что уже найдено. Добор по второму ИМЕНИ картины сюда не приходит: у него свой
    счёт бюджета, и отмены в нём нет вовсе (:func:`_second_language`, TC-386).
    """
    spare = client.spare()
    if spare >= SECOND_LEAST:
        return min(FACTS_BUDGET, spare - CIRCLE_SHARE)
    progress.phase("")
    if client.over_goal:
        progress.note(f"{what} не делаю: поиск уже съел цель в {GOAL:.0f} с")
        return None
    client.over_goal = True
    progress.note(
        f"{what} всё равно делаю в свои {SECOND_LEAST:g} с: поиск уже съел цель в {GOAL:.0f} с"
    )
    return FACTS_BUDGET
