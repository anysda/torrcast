"""Стоит ли переспросить каталог оригинальным названием картины."""

from __future__ import annotations

from typing import TYPE_CHECKING

from torrcast.domain._name_data import THIN_POOL
from torrcast.domain.config import Config
from torrcast.domain.picture import Picture
from torrcast.domain.profile import CAUTIOUS, Profile
from torrcast.usecases.discover.unfit_pool import unfit_pool

if TYPE_CHECKING:
    from torrcast.ports.choice_types import Args


def worth_asking_original(
    found: list[Picture], args: Args, config: Config, profile: Profile = CAUTIOUS
) -> bool:
    """Стоит ли переспросить оригинальным названием (:func:`_second_language`).

    Поводов два, и оба про одно: русской выдачи не хватило.

    1. Пул ТОЩИЙ - строк выдачи меньше :data:`~torrcast.parse.THIN_POOL`. Мера считается
       строками (:attr:`~torrcast.parse.Picture.rows`), а не склеенными раздачами:
       зеркалящие индексеры несут один торрент по разу каждый, и по склеенному пулу
       порог срабатывал бы тем чаще, чем больше зеркал в круге.
    2. 🔴 TC-245. Пул НЕГОДЕН - раздач много, а играть нечем (:func:`unfit_pool`).
       Тощесть тут ничего не ловит, а беда та же самая: «Оранжевый хит сезона» приезжал
       57 русскими строками без единого HD, отбор перебирал мертвецов и сдавался, тогда
       как под ``Orange Is the New Black`` лежат 93 HD. То же у «Звёздного пути:
       Следующее поколение» (24 строки без HD против 116 со ста живыми HD). Толщина пула
       про его годность не говорит ровно ничего, и мерить надо годность.

    Второй повод считается по УЖЕ вынесенным приговорам отбора, а не заранее: пул
    прогоняется через тот же :func:`_plan_for`, что построит меню, и вопрос к нему один -
    осталось ли после отбора хоть что-нибудь, чем стоит играть. Лишнего круга на здоровой
    выдаче отсюда не берётся: годная раздача есть - второго захода нет.

    ⚠️ Цена ПЕРВОГО повода (тощий пул) ниже не названа, и назвать её сегодня нечем:
    единственный замер на тысяче запросов - прогон ``tc262-run1-1000``, а он снят на
    голодном дне, когда индексеры почти не отвечали (медиана строк выдачи 14 против 139 на
    богатом корпусе, 202 выдачи пустых совсем). Тощесть на нём срабатывает в 622 запросах
    из 1000, но это число меряет ДЕНЬ, а не порог: переносить его на живую выдачу нельзя.

    🔴 TC-262. **Цена второго повода замерена, и она мала.** Тысяча запросов в один поток:
    ОДИН ЛИШЬ второй повод (пул не тощий, но негоден) срабатывает в 16 запросах из 1000, и
    сквозной поиск на них дорожает на 1.84 с по медиане (p90 2.07 с, максимум 2.45 с) -
    пятая часть цели в :data:`~torrcast.search.GOAL` секунд. Мерено двумя способами: тем же
    поиском со старым поводом (только тощесть) в чередующихся арках и отдельным
    секундомером вокруг самого добора (медиана 2.18 с, из них справка до 1.5 с, круг по
    индексерам 0.5-1.8 с).

    Круг этот вдобавок не всегда лишний: в 7 запросах из 16 он ЗАМЕНЯЕТ собой тот, что
    иначе заплатил бы добор голоса (:func:`_voice_reinforce`) - там дельта нулевая. И
    платит он за дело: в 12 запросах из 16 после круга у картины впервые появился годный
    релиз, впустую круг ушёл ровно в одном.

    ⚠️ Сузить повод до «негоден И мёртв» (то есть требовать, чтобы живого не было даже
    среди старья) - соблазн, но замер против: одну лишнюю трату в 2.3 с это сняло бы
    вместе с ПЯТЬЮ спасёнными вечерами, где живым в пуле было только старьё («Конклав»,
    «Реальная любовь», «Крёстный отец 2», «Шёпот сердца», «Иван Васильевич меняет
    профессию»). Старьё играется, когда другого нет вовсе, - но это не повод не искать
    другого.

    Цель второй повод не роняет: единственный запрос замера, перевалив 10 с, простоял их
    на ПЕРВОМ круге. Тогда остаток цели отменял второй заход вовсе - и ровно это стоило
    картины (TC-386): с тех пор добор по второму имени бюджетом не отменяется, а идёт с
    полом в целую цель (:func:`_second_language`).

    Рядом, тем же решением «идти ли на второй круг», стоит третий повод: пул упёрся в
    потолок индексера, а картины с именем запроса в ней нет вовсе
    (:func:`_ceiling_hides_name`). Он срабатывает лишь когда эти два молчат: тощий или
    негодный пул важнее обрезанного хвоста.
    """
    if max((p.rows for p in found), default=0) < THIN_POOL:
        return True
    return unfit_pool(found, args, config, profile)
