"""Убирает из прогретого куски, которые приёмнику не отдать и починить их некому."""

from __future__ import annotations

import contextlib
from typing import TYPE_CHECKING

from torrcast.usecases.warm._state import Grid
from torrcast.usecases.warm._vault_disk import _size

if TYPE_CHECKING:
    from torrcast.usecases.warm.vault import Vault


def trim(vault: Vault, cap: int, grid: Grid, spots: tuple[int, ...] = ()) -> tuple[int, int]:
    """Удалить куски тяжелее ``cap``, кроме тех, что ещё починят; вернуть число и вес.

    🔴 Тяжёлый кусок не всегда мусор. Прогрев кладёт тяжёлое место СПЕРВА копией, во весь
    вес, а поздний точечный перекод ужимает его под потолок уже на диске
    (:func:`torrcast.usecases.warm.lay_heavy._lay_heavy`,
    :func:`torrcast.usecases.warm._warm_count._spots_left`): порядок «сначала весь фильм копией,
    потом тяжёлые места» держит прогретое играбельным целиком в любой момент. Значит, в
    каталоге посреди прогрева штатно и подолгу лежат куски тяжелее потолка, у которых
    впереди своя очередь на перекод.

    Замер на настоящем каталоге посреди прогрева («Дюна: Часть вторая», 1080p 11.9 Мбит/с,
    осторожный потолок 16 МБ): на диске 105 кусков, тяжелее потолка 64 из них, и 59 - это
    цели точечного перекода, 1.32 ГБ. На весь фильм таких мест 632 из 1028. Судя их одним
    потолком, уборка забирала бы больше половины каталога на КАЖДОМ продолжении показа, а
    прогрев тянул бы их из роя заново - то есть главный путь продукта платил бы за уборку
    гигабайтами трафика.

    Поэтому забирается только то, чинить что уже некому: кусок тяжелее потолка и либо не
    назван целью точечного перекода (``spots``), либо назван, а перекод по нему уже
    прошёл (метка :meth:`Vault.spot`) и легче он не стал. Пустые ``spots`` - точечного
    перекода у этого показа нет вовсе, и тогда тяжёлый кусок и правда мёртвый груз.

    🔴 Хвост сетки судится не тем же числом, и это не поблажка, а её устройство.
    Последний кусок такой, какой остался: короткий хвост прилипает к предыдущему
    (:meth:`torrcast.adapters.stream_pack.grid.Grid.uniform`,
    :func:`torrcast.usecases.warm.warm_key.warm_key`), а потолок веса на него не
    распространяется, потому что предсказать этот вес нечем - карта опорных кадров
    кончается на последнем кадре, и байты за ним она не описывает
    (:func:`torrcast.adapters.stream_pack.weigher.weigher`).

    Живой замер на файле 10 Мбит/с с опорным кадром каждые 8.5 с: осторожная сетка
    режет по 8.5 с и кладёт куски по 11.04 МБ при потолке 16, а хвост выходит 16.65 с
    и 21.63 МБ - законно, по построению. Судя его общим потолком, уборка забирала бы
    хвост на КАЖДОМ старте показа, прогрев делал бы его заново, и так без конца.

    Поэтому хвосту достаётся тот же вес НА СЕКУНДУ, что потолок разрешает обычному
    куску этой же сетки: во сколько раз хвост длиннее, во столько ему позволено быть
    тяжелее. Мусор это по-прежнему забирает - кусок, слипшийся из всего фильма
    (243 МБ при потолке 16), тяжелее хвостовой доли в разы.
    """
    gone = 0
    freed = 0
    tail = grid.count - 1
    allow = _tail_cap(grid, cap)
    waited = frozenset(spots)
    with contextlib.suppress(OSError):
        for path in vault.dir.glob("v*.m4s" if vault.container == "fmp4" else "v*.ts"):
            try:
                slot = int(path.stem[1:])
            except ValueError:
                continue
            size = _size(path)
            if size <= (allow if slot == tail else cap):
                continue
            # Метка спрашивается только у тяжёлых кусков и только у названных целью: на
            # каталоге в тысячу мест обход и без того стоит миллисекунды, и платить за
            # него ещё одним ``stat`` на каждый лёгкий кусок незачем.
            if slot in waited and not vault.spot(slot).exists():
                continue
            vault.reject(slot)
            gone += 1
            freed += size
    return gone, freed


def _tail_cap(grid: Grid, cap: int) -> int:
    """Потолок веса хвоста: ``cap``, растянутый на его длину, но не ниже ``cap``.

    Сравнивается хвост с САМЫМ ДЛИННЫМ обычным куском этой же сетки, а не с настройкой
    шага: длину куска называет приёмник (:meth:`Grid.on_keyframes` заполняет измеренный
    запас до его потолка), и мерка обязана быть той же, по которой сетка и резалась.
    Хвост короче обычного куска - никакой прибавки: она нужна ровно там, где хвост
    длиннее. Сетка из одного куска - хвоста в ней нет, сравнивать не с чем.
    """
    if grid.count < 2:
        return cap
    longest = max(grid.span(slot) for slot in range(grid.count - 1))
    if longest <= 0:
        return cap
    return max(cap, int(cap * grid.span(grid.count - 1) / longest))
