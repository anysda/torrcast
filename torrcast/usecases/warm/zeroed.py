"""Есть ли в уложенном куске затёртый нулями участок, которого не пишет ни один муксер."""

from __future__ import annotations

from pathlib import Path
from typing import Final

#: Сколько нулей подряд выдают затёртое место: полная полезная нагрузка пакета TS (188 байт
#: минус заголовок в 4). Здоровому куску её не набрать нигде. Внутри NAL картинки три нуля
#: подряд запрещены самим стандартом (байт защиты от эмуляции стартового кода), набивка
#: пакетов, PAT и PMT идёт байтом ``0xFF``, а между пакетами стоит синхробайт ``0x47``.
ZERO_RUN: Final = 184
#: Чем читается кусок: файл не держится в памяти целиком, стык окон перекрыт.
CHUNK: Final = 1 << 20


def zeroed(path: Path) -> bool:
    """Нашёлся ли в куске затёртый участок; не прочтя файла, ответ ``False``.

    🔴 Правило выросло из замера (TC-1251, «Оно» 2017 с закладки 140.76). Прогретый
    ``v14.ts`` нёс внутри картинки ровно 16 КиБ нулей, размер блока раздачи: место пришло
    из TorrServer пустым, а перегрев того же места нулей не несёт. Копия видео переносит
    байты как есть, и кусок лёг под верным именем, в своей сетке и в своём весе, а декодер
    Chromium падал на кадре 141.2 с с ``MEDIA_ERR_DECODE``. Вкладка повторяла тот же кусок
    трижды и вставала навсегда: прогретое с диска переживает и показ, и выкатку, поэтому
    сломанное место ломалось в каждом следующем показе с той же закладки.

    Порог проверен на всём прогретом двух стендов: 763 куска, 12.5 ГБ, срабатывает только
    этот самый ``v14`` (на втором стенде - его же подсаженная копия).
    """
    tail = b""
    needle = b"\x00" * ZERO_RUN
    try:
        with path.open("rb") as handle:
            while chunk := handle.read(CHUNK):
                window = tail + chunk
                if needle in window:
                    return True
                tail = window[-(ZERO_RUN - 1) :]
    except OSError:
        return False
    return False


__all__ = ["ZERO_RUN", "zeroed"]
