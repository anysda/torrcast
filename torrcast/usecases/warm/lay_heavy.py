"""Укладка куска, который тяжелее потолка приёмника: на диск он всё равно обязан лечь.

Зовёт выкладка прогона прогрева
(:attr:`torrcast.adapters.stream_pack.packer.Packer.shrink`) на каждом таком куске.
"""

from __future__ import annotations

import contextlib
import os
from typing import TYPE_CHECKING

from torrcast.usecases.warm.settings import RUN_DIR

if TYPE_CHECKING:
    from torrcast.usecases.warm.warmer_state import _State


def _lay_heavy(state: _State, slot: int, _size: int) -> bool:
    """Кусок тяжелее потолка приёмника: уложить на диск и не вставать на нём.

    Зовётся выкладкой на последнем гейте, где вес куска зажат потолком приёмника
    (:attr:`torrcast.adapters.stream_pack.packer.Packer.shrink`). Гейт этот про ЖИВУЮ отдачу:
    тяжёлую копию приёмник не доигрывает, и наружу она идти не имеет права. У прогрева адресат
    другой - диск, - и там тяжёлая копия обязана лежать:

    * ею считается сделанная работа (:meth:`_missing`). Не лёг кусок - прогрев вернётся
      на это место следующим прогоном, и тяжёлое место перекладывалось бы вечно
      (:meth:`Vault.slots`);
    * поверх неё идёт точечный перекод (:meth:`_spots_left`), а он берёт место в работу
      только тогда, когда копия уже лежит;
    * запасом она при этом не становится ни на секунду: и :attr:`warmed`, и
      :attr:`done` считают только то, что показ и правда возьмёт с диска
      (``slots(cap)``), а :meth:`torrcast.usecases.feed_pack.feed.Feed._warm` тяжёлую копию не
      отдаёт.

    🔴 Без этого хука выкладка прогрева ВСТАВАЛА на первом же таком куске (``shrink``
    не задан - поведение до TC-467) и дальше не двигалась никогда: ffmpeg честно паковал
    в темпе :attr:`rate`, куски копились в каталоге прогона, а на диск не попадало
    ничего. Замер на живой раздаче (BDRip 1080p 12.3 Мбит/с, сетка 10 с): за 421 с
    каталог прогона набрал 140 кусков, прогретым стал ОДИН - ``v0`` на 2.3 МБ, потому
    что ``v1`` весил 19.8 МБ при потолке 16 МБ.

    Ответ всегда ``False``: ужимать прогрев не умеет и не должен - это работа живого
    кодировщика. Выкладке ответ важен только когда рядом лежит готовый перекод, а у
    прогрева его нет.
    """
    # 🔴 Имя куска в каталоге прогона спрашивается У КАТАЛОГА ПРОГРЕТОГО, а не у общего
    # :func:`torrcast.adapters.stream_probe.segment_name`: тот зовётся тут без контейнера и отвечает
    # осторожным умолчанием завода (``v{slot}.ts``). На приёмнике с FMP4 (профиль Android TV,
    # приставка) заход пакует ``v{slot}.m4s``, замена не находила НИЧЕГО, а выкладка сразу за
    # этим стирала тяжёлую копию (:mod:`torrcast.adapters.stream_pack.packer_publish`). Место
    # оставалось непрогретым навсегда, фильм копией не достраивался, и точечный перекод
    # (:func:`torrcast.usecases.warm._warm_count._spots_left`) не начинался ни разу.
    laid = state.vault.path(slot)
    with contextlib.suppress(OSError):
        os.replace(state.vault.dir / RUN_DIR / laid.name, laid)
    return False
