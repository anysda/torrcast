"""Ключ каталога прогретого: один и тот же показ - один и тот же каталог.

Зовут показ (:mod:`torrcast.usecases.playback`) и сборка прогрева следующей серии.
"""

from __future__ import annotations

import hashlib

from torrcast.domain.segment_container import MPEGTS, SegmentContainer
from torrcast.ports.recode.encoding_key import EncodingKey
from torrcast.usecases.warm._state import Grid


def _bounds_mark(grid: Grid) -> str:
    """Отпечаток границ сетки: где стоят резы, а не сколько их.

    Границы и есть содержимое куска: имя ``v17`` называет не «семнадцатый кусок», а
    отрезок ленты ``[bounds[17], bounds[18])``. Двинулась граница - под тем же именем
    лежат другие байты, и на стыке прогретого со свежим метки идут НАЗАД, от чего
    приёмник и умирает.

    Считается по договору сетки (:meth:`torrcast.ports.feed_grid.FeedGrid.start`), а не по
    внутреннему списку: сценарий знает у сетки её договор, а не её устройство.

    Тысячная доля секунды тут не осторожность, а мера: границы стоят на опорных кадрах,
    соседние кадры разнесены на два-четыре сотых, и рез, сдвинувшийся меньше чем на
    миллисекунду, - это не другой рез, а шум последнего разряда.

    Цена: 0.53 мс на фильме в два часа (698 границ) и 9.8 мс на заведомо непосильных
    12 000 границах; на пути показа отпечаток считается дважды - показу и прогреву
    следующей серии.
    """
    line = ";".join(f"{grid.start(slot):.3f}" for slot in range(grid.count))
    return hashlib.sha1(line.encode("utf-8")).hexdigest()[:16]


def warm_key(
    source: str,
    audio: int,
    grid: Grid,
    encode: EncodingKey | None = None,
    spots: tuple[int, ...] = (),
    container: SegmentContainer = MPEGTS,
    voice: str = "",
    decided: EncodingKey | None = None,
) -> str:
    """Ключ каталога прогретого: один и тот же показ — один и тот же ключ.

    В ключ входит всё, от чего зависит СОДЕРЖИМОЕ сегмента: раздача с номером файла
    (это уже есть в ``source``), звуковая дорожка, сетка, то, чем кодируем видео, и
    правила, которыми это решение разворачивается в команду (``decided``).
    Разошлось хоть что-то — ключ другой, и прогретое прошлого прогона не подсунется
    под чужие имена. Это дешевле и честнее, чем сверять паспорта: чужой каталог просто
    не находится, а его уберёт бюджет по давности.

    ⚠️ ``mark`` у перекода - это кадр и цвет наружу
    (:attr:`torrcast.adapters.recode.encode.Encode.mark`), и в ключе он не для полноты. Один и тот
    же файл под разными приёмниками ужимается по-разному (потолок кадра - свойство приёмника), а
    сегменты у них при этом одного имени и одного веса: разойдись ключ - показ подсунул бы
    1080p-куски туда, где сам режет 720p. На неужатом показе строка пустая, то есть ключи прежних
    прогонов ключами и остаются.
    """
    parts = [
        # Отдельный файл звука входит В источник, а не отдельным звеном списка: без
        # него строка ключа обязана остаться прежней до байта, иначе каждый уже
        # прогретый каталог перестанет находиться под своим именем.
        source if not voice else f"{source}>{voice}",
        f"a{audio}",
        # Сетка входит сюда САМИМИ границами (:func:`_bounds_mark`), а не их числом.
        # Число кусков - слишком грубая мера: правило реза двигает границы, не трогая их
        # количества (короткий хвост прилипает к последнему куску и съедает лишний рез), и
        # тогда прогретое прошлого правила легло бы под теми же именами на новые границы.
        #
        # Начало ленты - тоже содержимое куска
        # (:func:`torrcast.adapters.stream_pack.pack_origin.pack_origin`).
        # Прогретое прошлой сборкой лежит на другой ленте, а показ берёт куски из ДВУХ
        # производителей вперемешку: не разойдись тут ключ, старый кусок с диска встал бы рядом со
        # свежим из упаковки, и на их стыке метки пошли бы назад - ровно тот отказ, который тут и
        # лечится.
        f"g{_bounds_mark(grid)}:{grid.duration:.3f}:{grid.on_keys:d}:{grid.origin:.3f}",
        "" if encode is None else f"e{encode.preset}:{encode.mbit:.2f}{encode.mark}",
        # Точечно перекодированные куски - тоже содержимое каталога: сменился список
        # тяжёлых мест (другой порог, другой профиль тяжести) - каталог другой.
        "" if not spots else f"s{len(spots)}:{spots[0]}:{spots[-1]}",
        # 🔴 Отпечаток ПРАВИЛ, которыми кусок собран, а не решения, которым он взят
        # (:attr:`torrcast.ports.recode.encoding_key.EncodingKey.imprint`). Пресет и цель
        # выше называют решение, и его одного мало: правило кодирования живёт в коде.
        # Снятый ``-level`` (TC-871) не тронул ни пресета, ни цели, а SPS каждого
        # перекодированного куска переписал - и ключ этой правки не замечал, то есть
        # починка доезжала до зрителя только на пустой полке.
        #
        # Спрашивается у РЕШЕНИЯ, которым куски каталога и собраны: сплошной перекод
        # приезжает в ``encode``, точечный - только сюда, и без него правка правил
        # проехала бы мимо ровно того пути, на котором ``-level`` и убивал показ.
        #
        # Решения нет вовсе (каталог из одних копий) - строка пуста, и ключи прежних
        # прогонов остаются прежними: копию правила кодирования не трогают, обесценивать
        # её на каждом выпуске - цена дороже болезни.
        "" if decided is None else f"r{decided.imprint}",
        f"c{container}",
    ]
    return hashlib.sha1("|".join(parts).encode("utf-8")).hexdigest()[:16]
