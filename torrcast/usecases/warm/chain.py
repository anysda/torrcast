"""Цепочка серий: взяться за следующую, когда текущая уже не нуждается в сети.

Зовёт нитка прогрева (:func:`_work`) ровно один раз за серию.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

import torrcast.usecases.warm._state as _state
from torrcast.usecases.warm.missing import _pending

if TYPE_CHECKING:
    from torrcast.usecases.warm.warmer_state import _State


def _chain(state: _State) -> None:
    """Серия легла на диск целиком - взяться за следующую (:attr:`follow`).

    Ровно за одну, и ни серией дальше. Причина не в бюджете, а в том, ради чего
    прогрев вообще есть: обрыв связи убивает показ на **стыке** серий - досмотрели
    текущую, а следующей нет ни куска, и автопереход упирается в мёртвую раздачу.
    Закрывает эту дыру одна серия вперёд; сезон-пак впрок - это уже не страховка
    показа, а выкачивание раздачи на диск, чего мы не делаем нигде.

    Поднимается ровно здесь и ни секундой раньше: пока текущая серия не на диске,
    каждый байт раздачи нужен ей, а не следующей. «На диске» тут - всё, что прогрев
    в силах положить (:meth:`_pending`), а не обязательно «готово» (:attr:`done`):
    место тяжелее потолка приёмника без перекода прогретым не станет никогда, и
    держать из-за него цепочку - значит оставить стык серий без страховки вовсе.
    """
    if state.stopped or state.follow is None or state.after is not None or _pending(state):
        return
    following = _ask_follow(state)
    if following is None:
        return
    # Текущая серия для соседнего прогрева - чужой каталог, и бюджет вытеснил бы её
    # первой: она и старше, и досматривать её ещё полчаса (:attr:`Vault.keep`).
    following.vault.keep = following.vault.keep | {state.vault.key}
    state.after = following
    following.slack = state.slack
    # Кодировщик живых кусков у показа один на всех, и уступать ему обязана вся
    # цепочка: прогрев следующей серии жжёт тот же процессор, что и прогрев этой.
    following.rival = state.rival
    following.start()
    _state._environment.mark("прогрев следующей серии")


def _ask_follow(state: _State) -> _State | None:
    """Собрать прогрев следующей серии, дожидаясь сети; ``None`` - собирать нечего.

    🔴 Спрашиваем ПОВТОРНО, пока показ жив. Сборка следующей серии - это два вопроса
    к раздаче (паспорт файла и карта опорных кадров, :func:`torrcast.playback._next_warmer`),
    и приходятся они ровно на тот миг, когда текущая серия дописала последний кусок.
    Обрыв связи в этот миг раньше кончал цепочку навсегда: ``follow`` спрашивали один
    раз, ошибку записывали в журнал - и прогрев следующей серии не начинал никто, хотя
    показу идти ещё полсерии и сеть успевала вернуться.

    Замер на стенде, ради которого повтор и заведён: обрыв на 10-й секунде, сеть
    вернулась на 194-й, прогон шёл до 720-й - то есть 526 с здоровой сети, - и
    следующая серия получила НОЛЬ кусков (на здоровой сети тот же прогон кладёт её
    целиком: 107 кусков из 107). Теряется при этом не пара кусков, а вся следующая
    серия - ровно та дыра на стыке, ради которой прогрев впрок и существует.

    Отличать «не смогли» от «нечего»: исключение - это сеть, и его ждём; ``None`` -
    это фильм, последняя серия раздачи или запись без списка серий, и ждать тут
    нечего никогда.
    """
    said = False
    while not state.stopped:
        if state._must_yield():
            # Живое окно показа сильнее прогрева всегда: паспорт и карта опорных
            # кадров - это запрос в ту же раздачу и тот же процессор.
            _nap(state, 1.0)
            continue
        make = state.follow
        if make is None:
            return None  # продолжать нечем - тот же ответ, что читает :func:`_chain`
        try:
            # Через переменную с типом: фабрика отдаёт прогрев следующей серии либо
            # ``None``, и отдавать её ответ наружу без сужения значит увести тип из подписи.
            following: _State | None = make()
        except Exception as exc:  # прогрев не имеет права ронять показ
            if not said:
                # Строка одна на весь обрыв: повтор идёт раз в полминуты, и жаловаться
                # каждый раз значит забить журнал показа своей же неудачей.
                state._say(f"прогрев следующей серии не собрался ({exc}) - жду сеть и пробую снова")
                said = True
            _nap(state, state.chain_retry)
            continue
        return following
    return None


def _nap(state: _State, seconds: float) -> None:
    """Поспать, просыпаясь на снятие показа.

    Сон в цепочке измеряется десятками секунд (:data:`CHAIN_RETRY`), а :meth:`stop`
    обязан срабатывать сразу: показ кончился - прогреву спать незачем.
    """
    end = _state._environment.monotonic() + seconds
    while not state.stopped:
        left = end - _state._environment.monotonic()
        if left <= 0:
            return
        _state._environment.sleep(min(0.5, left))
