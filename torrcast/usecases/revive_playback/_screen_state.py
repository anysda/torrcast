"""Что показ помнит между двумя опросами приёмника: закладка, запас и признаки экрана.

Держит это при себе держатель показа (:func:`torrcast.usecases.revive_playback._hold.
_hold`), а читают и двигают - строки экрана (:mod:`torrcast.usecases.revive_playback.
_screen`).
"""

from __future__ import annotations

from dataclasses import dataclass, field

from torrcast.domain.pointer_lag import PointerLag


@dataclass(slots=True)
class _Screen:
    """Признаки экрана и закладка показа - всё, что переживает один круг опроса."""

    #: Взял ли приёмник старт. ``False`` - показа не было ни кадра, и картинку добудет
    #: лестница воскрешения (:meth:`_Revival.resurrect`).
    raised: bool = True
    #: Картинка на экране уже была: право CLI сказать «старт NN с» выдано.
    seen: bool = False
    #: С какого монотонного момента показ стоит на паузе; ``0.0`` - паузы нет.
    #:
    #: 🔴 Это решение ЗРИТЕЛЯ, и потеря сессии его не отменяет: слово приёмника,
    #: различавшее паузу и смерть показа, приёмник теряет вместе с сессией
    #: (``UNKNOWN`` с нулём), а показ - не теряет. Поэтому ветки «пауза» и «показ
    #: погас» различаются этой памятью, а не словом приёмника
    #: (:mod:`torrcast.usecases.revive_playback._paused`).
    paused: float = 0.0
    #: С какого момента приёмник потерял сессию на паузе и когда её последний раз
    #: возвращали на закладку БЕЗ начала показа; нули - сессия жива.
    restore_since: float = 0.0
    restore_at: float = 0.0
    #: Когда в последний раз отчитывались вслух (:data:`SAY_SECONDS`).
    said: float = 0.0
    #: Позиция приёмника с прошлого опроса - от неё считается запас показа. Прошлая, а не
    #: сегодняшняя, потому что запас нужен раньше, чем приходит ответ приёмника, и взять
    #: его больше неоткуда. На решение сторожа это не влияет: нудж срабатывает только
    #: после :attr:`STALL_SECONDS` неподвижности, то есть когда прошлая позиция и есть
    #: сегодняшняя. А сразу после перемотки, где число ещё старое, позиция изменилась -
    #: и счётчик подвиса обнулён.
    last: float = 0.0
    #: Последний кадр, который человек ДЕЙСТВИТЕЛЬНО видел. Ровно оттуда показ и
    #: поднимают (:class:`_Revival`), и ровно он уходит в закладку для resume:
    #: у мёртвой сессии позиции нет вовсе, там ноль.
    #:
    #: 🔴 ``BUFFERING`` в закладку не идёт, и это не придирка к состоянию: картинки на
    #: экране в нём нет, а позиция при этом двигается. Сторож подвиса
    #: (:meth:`torrcast.adapters.chromecast.cast.chromecast_receiver.ChromecastReceiver._nudge`)
    #: прыгает вперёд по 8 с, вытаскивая приёмник из зависания, и туда же смотрит повтор LOAD
    #: посреди показа. Замерено на живом Q70D: пока экран стоял на 2:39, сторож сделал 12 прыжков и
    #: увёл позицию на 4:15 - и показ воскресал с места, которого зритель не видел, ровно на 1:36
    #: впереди последнего кадра. Сторож при этом прав, а закладка - нет: место показа отмеряет глаз,
    #: а не указатель.
    #:
    #: ``IDLE`` не идёт по другой причине: у мёртвой сессии позиции нет вовсе, там ноль.
    #: Всё остальное - показанный кадр: и пауза (на экране стоит он же), и честно
    #: доигранный конец входа. Штатная перемотка человеком тоже: после неё приёмник
    #: возвращается в ``PLAYING``, и первый же показанный кадр двигает закладку за ним.
    #:
    #: ⚠️ Ноль тут остаётся нулём, и подставлять сюда место захода нельзя: закладка - это
    #: то, что зритель ВИДЕЛ, и по ней же сторож решает, был ли показ вообще
    #: (:attr:`torrcast.usecases.watch.Watch.seen`). Подставь мы заход - запись у титров плюс
    #: сдохший приёмник снова помечали бы картину досмотренной, не показав ни кадра.
    #: Лестнице воскрешения место захода нужно, и берёт она его отдельно (``start``).
    held: float = 0.0
    #: Позиция, на которой приёмник ВПЕРВЫЕ сказал ``PLAYING``; ``-1`` - ещё не говорил.
    #:
    #: 🔴 Слово состояния приходит раньше картинки, и разница не мелочь. Замер на живом
    #: Q70D (заход в тяжёлое место, сплошной перекод): приёмник отвечает ``PLAYING`` на
    #: 8.2-й секунде, а указатель стоит на месте захода ещё 6.0 с и трогается только
    #: тогда, когда показ выложил ВТОРОЙ кусок. Тот же прогон на другой сетке: ``PLAYING``
    #: на 10.4-й секунде, первый кадр - на 15.4-й. То есть каждое наше «старт NN с» было
    #: занижено на 5-6 с, и занижено ровно там, где человеку хуже всего - на тяжёлом месте.
    #: Отсюда правило: картинку доказывает ДВИЖЕНИЕ указателя, а не слово приёмника.
    still_at: float = -1.0
    #: Приёмник прямо сейчас в ``BUFFERING``: ребуфер пишется в след на входе в него.
    buffering: bool = False
    #: Счёт потерянной зрителем плёнки (:class:`torrcast.domain.pointer_lag.PointerLag`).
    #: Слову приёмника о подгрузе верить нечем, ходу его указателя - есть.
    lag: PointerLag = field(default_factory=PointerLag)
    #: Об обрыве сети уже сказано: строка про аварию печатается один раз, а не каждые 2 с.
    was_offline: bool = False
    #: Указатель, на котором приёмник стоит у самого конца картины, и с каких пор
    #: (страховка перехода, см. :func:`_hold`). ``-1`` - стоять ещё не начинал.
    tail_at: float = -1.0
    tail_since: float = 0.0
