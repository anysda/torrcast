"""Раздача упакованного по http в объёме, который нужен показу.

Поднимает её показ (:func:`_play`) на время показа и гасит вместе с ним: своих демонов
у нас нет. Строит её медиатракт (:class:`torrcast.stream.HlsServer`).
"""

from __future__ import annotations

from typing import Protocol


class StreamServer(Protocol):
    """Живёт ровно на время показа: поднялась - отдаёт манифест и куски, погасла - всё."""

    def start(self) -> None:
        """Открыть порт и начать отвечать приёмнику."""

    def stop(self) -> None:
        """Закрыть порт. Зовётся при любом исходе показа, включая аварийный."""
