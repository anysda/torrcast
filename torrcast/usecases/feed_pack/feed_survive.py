"""Два вида обрыва источника: молчащий вход и умерший ffmpeg.

Спрашивает отсюда решение об упаковке (:mod:`torrcast.usecases.feed_pack.feed_steer`).
"""

from __future__ import annotations

from typing import TYPE_CHECKING

import torrcast.usecases.feed_pack._state as _state
from torrcast.domain.hls_settings import MUTE_SECONDS

if TYPE_CHECKING:
    from torrcast.ports.pack_run.pack_run import PackRun
    from torrcast.usecases.feed_pack.feed_state import _State


def _mute(state: _State) -> None:
    """Источник молчит: прогон жив, а не выложил ни куска дольше :data:`MUTE_SECONDS`.

    🔴 Обрыв связи бывает двух видов, и показ знал только один. Оборванный **вход**
    убивает ffmpeg, и это ловит :func:`_survive`. А пропавший интернет при живом
    TorrServer вход не рвёт вовсе: раздача просто перестаёт отдавать байты, ffmpeg
    висит на чтении, `poll()` возвращает ``None``, и с точки зрения :meth:`_steer` всё
    в порядке - просто «кусок вот-вот допакуется», раз за разом, вечно.

    Замер на живом Q70D («Тачки 3», интернет в drop): показ доел прогретое на 1:12:35,
    встал в BUFFERING и **2.5 минуты не сказал ни слова** - ни строки о сети, ни о
    прогретом, - после чего приёмник сам перегрузил фильм с нуля. Молчаливая смерть с
    полным диском кино рядом. Отсюда эти часы: молчание дольше срока - такой же обрыв,
    как и мёртвый ffmpeg, и говорится о нём теми же словами.
    """
    if state.vault is None or state.offline:
        # Без прогретого «молчит» неотличимо от «медленный рой на старте», а идти
        # показу всё равно некуда: тут работает прежний счёт обрывов, а не часы.
        return
    if _state.clock_port.monotonic() - state.moved <= MUTE_SECONDS:
        return
    state.offline = f"источник молчит дольше {MUTE_SECONDS:.0f} с"
    state._say(f"источник не читается ({state.offline}) - иду с прогретого, жду возврата сети")


def _doubts(state: _State) -> None:
    """Снять условные приговоры местам: их выносил не вес куска, а мёртвый источник.

    Ужатие, не отдавшее ни байта, о самом куске не говорит ничего
    (:func:`torrcast.usecases.feed_pack.feed_shrink._skip`), и держать такой приговор весь
    показ значит пробить в фильме дыру из-за перезагрузки соседа.

    🔴 TC-725. Зовут отсюда ДВОЕ, и второй важнее первого. Запрос сегмента
    (:func:`torrcast.usecases.feed_pack.feed_steer._steer`) до пересмотра не доходит ровно
    тогда, когда пересмотр и нужен: приёмник, упёршийся в дыру, просит ИМЕННО
    приговорённое место, а такой запрос отвечается молчанием, не заглядывая в прогон.
    Живой замер: службу раздач убили на 70-й минуте показа, два места по десять секунд
    ушли в приговор, служба вернулась через пять секунд - и показ всё равно встал
    насмерть на 4234-й секунде, потому что единственный, кто мог снять приговор,
    спрашивал только про него. Поэтому пересмотр висит ещё и на ЧАСАХ показа
    (:func:`torrcast.usecases.feed_pack.feed_sweep._sweep`), которым приёмник не указ.

    ⚠️ Признака обрыва (:attr:`_State.offline`) это НЕ снимает, и в этом вся разница
    между двумя зовущими. «Источник вернулся» - событие, и видно оно только с запроса
    сегмента: на часах показа тот же вопрос отвечает край СТАРОГО прогона, который стоит
    там, где его застала смерть. Сняв по нему признак обрыва, часы будили бы показ из
    темноты, не дождавшись сети (замер: воскрешение на 10-й секунде вместо 300-й).
    Ошибиться же с приговором места дёшево: место просто упакуется заново.
    """
    if state.doubted:
        state.skipped -= state.doubted
        state.doubted.clear()


def _reread(state: _State) -> None:
    """Прогон что-то выложил - значит источник снова читается: снять обрыв и приговоры."""
    state.moved = _state.clock_port.monotonic()
    state.offline = ""
    _doubts(state)


def _survive(state: _State, packer: PackRun) -> bool:
    """Упаковка оборвалась сама: пробуем ещё или сдаёмся честной ошибкой.

    ⚠️ Считаются ПРОГОНЫ, а не опросы. Пока держит защита «не толкаемся» (2 с),
    перезапуска не происходит, а потоки раздачи приходят сюда каждые 0.2 с — и один
    и тот же труп съедал все попытки меньше чем за секунду, не дав показу ни одного
    настоящего перезапуска. Ровно так выглядел бы обрыв входа сразу после старта:
    TorrServer выронил раздачу — ffmpeg умирает мгновенно, то есть внутри этих 2 с.
    """
    if packer.blamed:
        return True
    packer.blamed = True
    if packer.stopped:
        return True  # прогон сняли мы сами - это не обрыв, и попытку он не тратит
    state.crashes += 1
    why = packer.why()  # там же и код возврата, если ffmpeg смолчал
    if state.crashes > state.limit:
        if state.vault is None:
            state.fatal = why
            return False
        # ⚠️ Прогретое на диске меняет смысл обрыва: раньше три подряд оборванных
        # прогона означали «источника нет, показывать нечего», теперь - «сети нет, а
        # фильм есть». Умирать тут нельзя, но и молчать нельзя: показ говорит, докуда
        # он обеспечен, и продолжает пробовать. Вернулась сеть - прогон выложит кусок,
        # и признак снимется сам (:meth:`_steer`).
        state.crashes = 0
        state.offline = why
        state._say(f"источник не читается ({why}) - иду с прогретого, жду возврата сети")
        return True
    # 🔴 Ноль от ffmpeg на оборванном прогоне значит «вход умер на середине», а не
    # «фильм кончился» (:meth:`Packer.finished`), и зритель об этом узнать не мог:
    # «молча, код 0» - это наш код возврата, а не новость о его кино. Он видит паузу
    # и решает, что кино кончилось.
    #
    # Замер 15-08-2026, 80 обрывов входа на живом ffmpeg (457 прогонов): код 0 вышел
    # во ВСЕХ 457, то есть по коду эти два исхода не различаются вовсе - различает их
    # только недобор последнего куска. Обещать при этом, что перезапуск поможет,
    # нельзя: тот же замер развёл миры начисто - вернулся источник, и заново пакуется
    # 76 раз из 76; не вернулся - 1 из 76 на второй попытке и 0 из 76 на третьей.
    # Кто из двух перед нами, на первом обрыве не знает никто, поэтому строка говорит
    # ФАКТ («вход оборвался»), а не прогноз («сейчас починится»).
    torn = "вход оборвался на середине, фильм не кончился"
    what = torn if packer.poll() == 0 else f"упаковка оборвалась ({why})"
    state._say(f"{what} - начинаю заново, попытка {state.crashes}")
    return True
