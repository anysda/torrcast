"""Уборка по часам показа: сдать успевшее, поднять оборванное, придержать несданное.

Зовут отсюда часы показа (:mod:`torrcast.usecases.feed_pack.feed`), а не запрос сегмента.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

import torrcast.usecases.feed_pack._state as _state
from torrcast.domain.catalogs.phrase import phrase
from torrcast.ports.journal.slot import journal
from torrcast.usecases.feed_pack.feed_survive import _mute, _progress, _reread, _settle, _survive

if TYPE_CHECKING:
    from collections.abc import Callable

    from torrcast.usecases.feed_pack.feed_state import _State


def _sweep(state: _State, restart: Callable[[int], None]) -> None:
    """Сдать всё, что упаковка успела, и не дать несданному расти без предела.

    Зовётся по часам показа, а не по запросу приёмника, и в этом весь смысл. Выкладка
    (:meth:`Packer.publish`) стоит на пути запроса сегмента, а запросов может не быть
    вовсе: пока показ берёт куски с диска (:meth:`_warm`), к упаковке никто не
    обращается, а ffmpeg продолжает писать в tmpfs. Замер: 897 МБ несданного за 14
    минут показа, рост без предела и без единой строки о нём.

    Потолок (:data:`PACK_PENDING_BYTES`) нужен и сверх этого. Выкладка встаёт на
    куске, придержанном под перекод, - и всё, что за ним, копится в памяти, сколько
    бы её ни было. (Тяжёлая копия выкладку больше не держит: она ужимается на месте
    или честно пропускается - :meth:`_shrink`.) Дойдя до потолка, показ гасит прогон
    одной честной строкой: куски, которых никто не забирает, стоят памяти и не дают
    приёмнику ничего, а снятый прогон отдаёт её обратно (:meth:`Packer.stop`).

    Подгруза это не добавляет: гасится то, что и так никуда не шло, уже выложенное
    остаётся лежать, а запрос следующего сегмента поднимает упаковку заново
    (:meth:`_steer`) - ровно как после паузы на пульте.
    """
    packer = state.packer
    if packer is None or packer.halted:
        return
    moved = _progress(state, packer)
    packer.publish()
    _settle(state, packer)
    if moved:
        _reread(state)
    else:
        _mute(state)
    _torn(state, restart)
    pending = packer.pending()
    if pending <= state.pending_cap:
        return
    state._say(phrase("feed.pending_too_big", mb=pending / 1e6))
    journal().mark("несданное копится", мб=round(pending / 1e6), край=packer.edge)
    packer.halt(reason=phrase("feed.pending_reason", mb=pending / 1e6))


def _torn(state: _State, restart: Callable[[int], None]) -> None:
    """Прогон оборвался - поднять его СЕЙЧАС, не дожидаясь, пока полка сойдёт в ноль.

    🔴 TC-725. Оборванный прогон разбирали в одном месте - на запросе сегмента
    (:func:`torrcast.usecases.feed_pack.feed_steer._steer`). А запрос доходит до
    разбирательства только тогда, когда куска на полке НЕТ: пока полка полна,
    :func:`torrcast.usecases.feed_pack.feed_segment._segment` отвечает файлом и до
    упаковки не доходит вовсе. То есть труп прогона обнаруживался ровно в тот миг,
    когда запас показа кончился, и весь запас впереди уходил не на починку, а на
    ожидание её начала.

    Живой замер (фильм 2:00:23, BDRip 24.5 Мбит/с): служба раздач упала на 17-й минуте
    показа, вход оборвался - и показ молчал **31 секунду**, доедая полку со 115 с до
    13 с, после чего упаковка поднялась и первый кусок ждали ещё 9.1 с. Запаса на
    обрыв хватило с зазором в четыре секунды; упади служба минутой позже, на месте с
    тощей полкой, - и плёнка встала бы.

    Часы показа зовут уборку каждый круг опроса приёмника (те же две секунды), и полка
    им не мешает: тут смотрят на ПРОГОН, а не на файлы. Поэтому починка начинается от
    смерти прогона, а не от конца запаса, и запас впереди остаётся тем, чем он
    обещан, - временем на починку.

    🔴 Начинается она здесь, а идёт не здесь (:func:`_lift`). Внутри подъёма лежит
    пробный прогон, до минуты по потолку
    (:data:`torrcast.domain.hls_wait.PILOT_TIMEOUT`), и упирается он ровно в то, из-за
    чего прогон и оборвался, - в источник, который не читается. Пока часы показа стояли
    в этом ожидании сами, круг опроса не приходил вовсе: приёмника не спрашивали, и
    слепы были ВСЕ метрики показа разом - место, подвис, перемотка, - а не только та
    упаковка, которую поднимали. Ждать тут некому: часы обязаны вернуться через свои две
    секунды.
    """
    packer = state.packer
    if packer is None or state.fatal or packer.stopped or packer.finished():
        return
    if packer.poll() is None:
        return  # прогон жив: паковать дальше ему никто не мешает
    # 🔴 Толкаться незачем, когда про источник УЖЕ всё известно: подъём ffmpeg на мёртвую
    # сеть стоит секунды и не даёт ничего, а показ в это время идёт с диска
    # (:func:`torrcast.usecases.feed_pack.feed_steer._steer`). Часы показа идут вчетверо
    # чаще запросов приёмника, и без этой границы они съедали бы весь счёт обрывов за
    # секунды, превращая пятисекундную перезагрузку соседа в приговор. Здесь чинится
    # ПЕРВАЯ весть о смерти прогона - та, которой полка мешала прийти вовремя; дальше
    # обрыв ведёт разбирательство на запросе сегмента, у него на это есть выдержка.
    if state.offline:
        return
    if _state.clock_port.monotonic() - state.restarted < 2.0:
        return
    # ⚠️ Замок берётся без ожидания и по той же причине, что на запросе сегмента:
    # занятый замок значит «решение уже принимают», и вставать за ним в очередь
    # часам показа нельзя - внутри решения лежит пробный прогон до минуты по потолку.
    if not state.lock.acquire(blocking=False):
        return
    # 🔴 Охрана начинается ЗДЕСЬ, а не у подъёма: между взятием замка и подъёмом лежит
    # разбор обрыва, а он и печатает (:meth:`_State._say`), и читает лог прогона
    # (:meth:`Packer.why`) - то есть роняет `BrokenPipeError` и `OSError` на ровном
    # месте. Замок, оставшийся закрытым от такого броска, не отпустит уже никто:
    # починка ленты умолкла бы до конца показа и молча.
    handed = False
    try:
        if not _survive(state, packer):
            return  # упаковка сдалась насовсем - хоронит показ держатель, а не уборка
        state.restarted = _state.clock_port.monotonic()
        # Замок отсюда уносит подъём и отпускает его сам: он и есть то решение, за
        # которым соседу вставать в очередь нельзя.
        slot = packer.edge + 1
        _state.spawn(lambda: _lift(state, restart, slot))
        handed = True
    finally:
        # Отпускает тот, кто держит: подъём поднялся - замок теперь его, и трогать
        # чужой замок отсюда нельзя.
        if not handed:
            state.lock.release()


def _lift(state: _State, restart: Callable[[int], None], slot: int) -> None:
    """Поднять оборванный прогон, не занимая собой круг опроса показа.

    ⚠️ Показ может кончиться, пока прогон поднимают: конец гасит ТОТ прогон, который
    застал (:func:`torrcast.usecases.feed_pack.feed_stop._stop`), а поднятый следом
    остался бы жить и читать раздачу в каталог, которого уже нет. Поэтому свой прогон
    подъём за собой и убирает - решает это признак конца, а не порядок двух потоков.

    🔴 Кончившийся показ спрашивается ДО подъёма, а не только после него, и это не
    украшение. Внутри подъёма лежит пробный прогон, до минуты по потолку
    (:data:`torrcast.domain.hls_wait.PILOT_TIMEOUT`), а снос показа ждёт этот замок
    (:func:`torrcast.usecases.feed_pack.feed_stop._stop`) - и ждал бы всю минуту ради
    прогона, который тут же и гасят. Замер на сухом стенде, источник висит: снос ждал
    59.76 с. Успел признак конца встать до этой строки - ждать нечего, и ffmpeg не
    поднимается в каталог, который прямо сейчас убирают.
    """
    try:
        if not state.fatal:
            restart(slot)
        # Признак конца мог встать и до подъёма, и посреди него: прогон, который застали,
        # гасится в обоих случаях.
        if state.fatal and state.packer is not None:
            state.packer.stop()
    finally:
        state.lock.release()


def _prune(state: _State, played: float) -> None:
    """Убрать из tmpfs то, чего показу уже не нужно, — и позади показа, и впереди.

    Позади окно ``keep`` секунд: глубже — уже перемотка, и она честно перепакует поток.

    Впереди убирается то, что осталось от **прошлого места показа**. После отката
    назад глубже окна упаковка идёт с нового места, а сегменты той минуты, откуда
    ушёл зритель, лежат в tmpfs и не выметаются ничем: окно смотрит только назад, а
    снова дойти до них показ может уже и не дойти. Десяток откатов подряд — и в
    памяти лежат места фильма, которых на экране не будет.

    Граница честная и не задевает ни запаса, ни префетча: остаётся всё, что этот
    прогон уже выложил или вот-вот выложит (``edge + ahead``), и всё, что рядом с
    позицией приёмника. Выше — куски, которых текущий прогон не делал и в ближайшее
    время не сделает. Упаковки нет вовсе — вперёд не трогаем ничего: без прогона край
    неизвестен, а гадать на этом месте дороже, чем подождать.
    """
    #: Место зрителя запоминается ЗДЕСЬ, потому что здесь оно и приходит: часы показа
    #: спрашивают приёмник и зовут уборку каждый круг. Запросу сегмента его никто не
    #: передаёт, а решить без него «кто ленте хозяин» нельзя
    #: (:func:`torrcast.usecases.feed_pack.feed_steer._behind`).
    state.played = played
    packer = state.packer
    keep_upto = -1
    if packer is not None:
        keep_upto = max(state.grid.slot_at(played), packer.edge) + state.ahead
    behind = state.grid.slot_at(played - state.keep) if played - state.keep > 0 else 0
    for path in _state.segment_paths(state.out):
        slot = _state.segment_slot(path.name)
        if slot < 0:
            continue
        if slot < behind or (keep_upto >= 0 and slot > keep_upto):
            path.unlink(missing_ok=True)
