"""Поля ленты показа и цена каждого её порога.

Наследует их :class:`torrcast.usecases.feed_pack.feed.Feed`, и только он.
"""

from __future__ import annotations

import threading
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Protocol

import torrcast.usecases.feed_pack._state as _state
from torrcast.domain.hls_settings import PACK_PENDING_BYTES
from torrcast.domain.profile import CAUTIOUS
from torrcast.usecases.feed_pack._state import Grid
from torrcast.usecases.feed_pack.packer import Packer


class _Encode(Protocol):
    """Перекод в объёме, который нужен ленте: цель по битрейту, Мбит/с."""

    @property
    def mbit(self) -> float: ...


class _Paced(Protocol):
    """Лестница пресетов кодировщика: чем и с какой скоростью он умеет перекодировать."""

    def table(self) -> tuple[tuple[str, float], ...]: ...


class _Recoder(Protocol):
    """Кодировщик тяжёлых кусков в объёме, в каком его знает лента показа.

    Полный :class:`torrcast.recode.Recoder` сюда не приходит: он адаптер, а лента живёт
    слоем сценариев и спрашивает у него ровно то, что перечислено ниже.
    """

    #: Каталог перекодированных кусков и его же корень для ужатия на месте.
    spare: Path
    #: Потолок ожидания перекода, секунды: тот же, что у предохранителя кодировщика.
    over_wait: float
    #: Где идёт показ, секунды фильма: по нему кодировщик решает, за что браться.
    played: float
    #: Слоты, за которые кодировщику браться уже незачем.
    done: set[int]

    @property
    def pace(self) -> _Paced: ...

    def stop(self) -> None: ...
    def opening(self, slot: int) -> None: ...
    def note(self, slot: int, how: str) -> None: ...
    def holding(self, slot: int, size: int = 0) -> bool: ...
    def ready(self, slot: int) -> Path | None: ...
    def fit(self, span: float, preset: str) -> _Encode: ...


class _Vault(Protocol):
    """Хранилище прогретого в объёме, который нужен показу: путь куска на диске.

    Полный :class:`torrcast.usecases.warm.vault.Vault` сюда не приходит: бюджет диска,
    учёт каталогов и вытеснение - дело прогрева, а показу нужно одно имя файла.
    """

    def path(self, slot: int) -> Path: ...


@dataclass(slots=True)
class _State:
    """Всё, что лента знает про себя: источник, сетка, пороги приёмника и ход упаковки."""

    source: str
    audio: int
    out: Path
    grid: Grid
    readrate: float = 1.0
    #: Запас упаковки впереди показа: свойство приёмника, живёт в его профиле
    #: (:attr:`torrcast.profile.Profile.burst`). Здесь умолчание - осторожное.
    burst: float = CAUTIOUS.burst
    #: Сколько секунд позади показа держим сегменты - глубина «бесплатной» перемотки назад.
    keep: float = 120.0
    #: Запрос дальше упакованного края больше чем на столько **сегментов** - это перемотка,
    #: а не обычный ход показа. Порог считается не от балды: после ``seek`` живой Q70D
    #: просит шесть сегментов разом (замерено), и ни один из них не должен считаться новой
    #: перемоткой. Раньше тут стояли секунды - с сеткой по опорным кадрам сегменты разной
    #: длины, и считать их надо штуками.
    ahead: int = 7
    #: Сколько секунд имеет смысл ЖДАТЬ упаковку вместо того, чтобы перезапустить её с
    #: нужного места (:meth:`Packer.eta`). Считать надо и штуками, и секундами: семь
    #: сегментов впереди края - это до семидесяти секунд фильма, а упаковка идёт в темпе
    #: реального времени, и ждать их пришлось бы столько же.
    #:
    #: 15 с - вчетверо дороже перезапуска (пробный прогон, подъём ffmpeg и первый кусок
    #: стоят 3-4 с на живых смоках) и вчетверо дешевле замеренного ожидания на перемотке
    #: (57.8 с). Запас нужен с обеих сторон: после перезапуска приёмник просит шесть
    #: сегментов разом, и ни один не должен показаться новой перемоткой - но и не покажет,
    #: пока свежий прогон читает первые ``burst`` (60 с) на полной скорости.
    jump: float = 15.0
    #: Сколько держим запрос приёмника, пока упаковка догоняет. Это лучше 404: ресивер,
    #: поймавший 404, отказывается брать LOAD ещё пару минут (замерено).
    #: ⚠️ Было 30 с - и этого мало: замерено, когда TorrServer посреди показа
    #: выронил раздачу, упаковка встала, и через 30 с приёмник получил ровно тот 404,
    #: которого мы избегаем. Ждать почти бесплатно (это один поток раздачи), а зря
    #: ждать не придётся: безнадёжные случаи :meth:`_steer` отличает и говорит об этом.
    #: 🔴 Сколько именно держать - свойство приёмника: у приставки Android TV обиды на
    #: 404 нет вовсе (:data:`torrcast.profile.ANDROID_TV`), а у Q70D она стоит минут.
    wait: float = CAUTIOUS.hold_seconds
    #: Потолок веса одного куска - тоже свойство приёмника
    #: (:attr:`torrcast.profile.Profile.max_segment_bytes`). Здесь он нужен не сетке, а
    #: раздаче: прогретое на диске мимо упаковки не проходит, и проверить его вес больше
    #: негде (:meth:`_warm`). Умолчание осторожное, как и у соседей.
    cap: int = CAUTIOUS.max_segment_bytes
    #: Сколько байт несданных кусков терпим в tmpfs, прежде чем погасить прогон
    #: (:data:`PACK_PENDING_BYTES`, :meth:`sweep`).
    pending_cap: int = PACK_PENDING_BYTES
    #: Сколько раз упаковка успела оборваться сама. Пережить обрыв она обязана: TorrServer
    #: под просевшим роем закрывает вход, и ffmpeg честно умирает - а показу это уже не
    #: авария, потому что паковать заново он умеет с любого места. Но молча повторять до
    #: бесконечности нельзя: битый источник крутил бы этот круг вечно.
    limit: int = 3
    packer: Packer | None = None
    lock: threading.Lock = field(default_factory=threading.Lock)
    #: Когда последний раз перезапускали упаковку: защита от лавины на префетче.
    restarted: float = 0.0
    crashes: int = 0
    fatal: str = ""
    log: Callable[[str], None] | None = None
    #: Кодировщик тяжёлых кусков (:class:`torrcast.recode.Recoder`) или ``None``, если
    #: динамический битрейт выключен либо тяжёлых кусков в фильме нет.
    recoder: _Recoder | None = None
    #: Чем перекодировать ВЕСЬ фильм (:class:`torrcast.recode.Encode`); ``None`` - видео
    #: уезжает копией, как обычно.
    #:
    #: Ставится ровно на один случай: кодек, который приёмник не декодирует
    #: (:data:`RECODE_CODECS`). Тогда перекодирует сама упаковка, одним прогоном на весь
    #: показ, а кодировщик тяжёлых кусков не поднимается вовсе - перекодировать что-то
    #: ещё раз поверх уже перекодированного некуда, да и нечем: битрейт зажат тем же
    #: потолком, которым зажата сетка (``recode_mbit``).
    #:
    #: ⚠️ Смешивать копию и перекод в одном показе НЕЛЬЗЯ (:data:`RECODE_CODECS`), поэтому
    #: признак живёт на :class:`Feed`, а не на сегменте: он один на весь файл и не зависит
    #: ни от места показа, ни от перемотки.
    encode: _Encode | None = None
    #: Хранилище прогретого на диске (:class:`torrcast.warm.Vault`) или ``None``.
    #:
    #: Сетка детерминирована, поэтому прогретый кусок и живой - одно и то же место фильма
    #: под одним и тем же именем. Отсюда всё остальное: показ берёт прогретое напрямую с
    #: диска (:meth:`segment`), считает его своим запасом (:meth:`front`) и переживает на
    #: нём обрыв сети (:meth:`_survive`).
    vault: _Vault | None = None
    #: Когда упаковка в последний раз что-то выложила (:data:`MUTE_SECONDS`).
    #:
    #: Часы принадлежат ПОКАЗУ, а не прогону, и это существенно: на молчащем источнике
    #: прогон перезапускается каждые пару секунд, и часы, привязанные к прогону,
    #: обнулялись бы вечно - ровно так молчание и оставалось незамеченным.
    moved: float = field(default_factory=_state.clock_port.monotonic)
    #: Источник не читается (сеть пропала), а прогретое ещё есть: показ идёт с диска и
    #: ждёт возврата сети. Пусто - всё в порядке. Это НЕ :attr:`fatal`: умирать, пока на
    #: диске лежит фильм, нельзя, а молчать об этом - тем более.
    offline: str = ""
    #: Места, которых в показе не будет никогда: кусок тяжелее потолка приёмника, а
    #: ужать его не вышло (:meth:`_shrink`). Помнится на весь показ, переживая
    #: перезапуски упаковки: тяжёлый кусок детерминирован, и второй прогон над ним
    #: получит ровно ту же копию, поэтому перепаковывать это место незачем.
    #:
    #: 🔴 TC-501. Запрос такого места держится молча (:attr:`wait`), а НЕ отвечается
    #: быстрым 404. Манифест обещает весь фильм и это имя тоже (:meth:`Grid.manifest`),
    #: то есть приёмник придёт за ним обязательно, и вопрос только в том, что он
    #: услышит. Замер живого показа: на 404 приёмник гасит буфер, не доиграв его, -
    #: 24 запроса подряд, показ встал, погас, поднялся и попросил снова; на тишине тот
    #: же буфер доигрывается до конца, и застрявшее место перешагивает сторож приёмника
    #: сеткой (:meth:`torrcast.cast.ChromecastReceiver._nudge`, 8 с). 404 хуже задержки.
    skipped: set[int] = field(default_factory=set)
    #: Ужатие на месте одно на весь показ: зовётся оно из выкладки, а выкладку дёргают
    #: и запрос приёмника, и часы показа (:meth:`sweep`) - двум ffmpeg на один и тот же
    #: кусок тут не место.
    shrink_lock: threading.Lock = field(default_factory=threading.Lock)

    def _say(self, text: str) -> None:
        if self.log is not None:
            self.log(text)
