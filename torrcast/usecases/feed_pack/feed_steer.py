"""Что делать с упаковкой ради запрошенного сегмента: ждать, перепаковать или сдаться.

Зовёт отсюда ответ на запрос сегмента (:mod:`torrcast.usecases.feed_pack.feed_segment`).
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Final

import torrcast.usecases.feed_pack._state as _state
from torrcast.ports.journal.slot import journal
from torrcast.usecases.feed_pack.feed_survive import _mute, _progress, _reread, _settle, _survive

if TYPE_CHECKING:
    from collections.abc import Callable

    from torrcast.usecases.feed_pack.feed_state import _State

#: Сколько холостых кругов по одному месту терпим, прежде чем решить иначе.
#:
#: Круг стоит не меньше двух секунд (столько держится защёлка :attr:`restarted`), а на
#: живом замере выходил 2.5-3.2 с: три круга - это около десяти секунд, ровно тот срок,
#: за который зритель обязан получить картинку. Ниже опускать нельзя: перезапуск за одно
#: место подряд бывает и честным - перемотка внутри прогона, возврат источника, - и
#: второй заход там доходит до куска.
IDLE_CIRCLES: Final = 3


def _circling(state: _State, slot: int) -> bool:
    """Перепаковка этого места уже ходит по кругу без прогресса; ``True`` - хватит.

    Холостой круг - это перезапуск за то же место, которого прошлый прогон так и не
    выложил. Считается он по месту, а не по числу перезапусков вообще: перепаковка
    соседнего куска - это работа, а не круг, и счёт с неё начинается заново.

    Заход в такой круг детерминирован: пробный прогон садится туда же, выкладка решает
    то же самое, и следующий круг кончится тем же. Ждать тут нечего, и молчать нельзя -
    зритель обязан получить либо картинку, либо честную строку.
    """
    place, rounds = state.circling
    rounds = rounds + 1 if place == slot else 1
    state.circling = (slot, rounds)
    return rounds > IDLE_CIRCLES


def _give_up(state: _State, slot: int) -> None:
    """Сказать про место, которое перепаковка не берёт, и перестать за него браться.

    Дальше это место живёт как любое честно пропущенное (:attr:`skipped`): 404 приёмник
    переживает хуже тишины, поэтому имя, уже обещанное манифестом, просто остаётся без
    ответа, а дыру перешагивает сторож самого приёмника.
    """
    state.circling = (-1, 0)
    state.skipped.add(slot)
    if state.recoder is not None:
        state.recoder.done.add(slot)  # браться за это место кодировщику уже незачем
    state._say(
        f"⚠️ v{slot} пропускаю: {IDLE_CIRCLES} перепаковки подряд не дали этого куска - "
        "этого места в показе не будет"
    )
    journal().mark("перепаковка по кругу", слот=slot, кругов=IDLE_CIRCLES)


def _behind(state: _State, slot: int) -> bool:
    """Место осталось позади зрителя настолько, что показ его уже вымел; ``True`` - не наше.

    🔴 TC-634. Граница тут не новая и не подобранная: это ровно та черта, по которой
    уборка (:func:`torrcast.usecases.feed_pack.feed_sweep._prune`) сегменты СТИРАЕТ - окно
    :attr:`_State.keep` позади зрителя. Две половины показа расходились на ней в разные
    стороны: уборка говорила «этого места за спиной больше нет», а решение об упаковке в
    ответ на запрос того же места перепаковывало под него весь показ.

    Живой замер 17-08 (перемотка 32.3 → 900): 28 заходов упаковки за прогон, попеременно
    слот 85 (цель перемотки, 936.2 с) и слот 5 (место, откуда зритель ушёл, 50.9 с), ни
    один не дошёл до плёнки. Ждущий запрос старого места возвращается в это решение каждые
    0.2 с все :attr:`_State.wait` секунд, и держала его от перезапуска только защёлка по
    времени (:attr:`_State.restarted`): шаг заходов шёл 2.6-3.6 с при защёлке 2.0 и
    вырастал до 5.6-7.4 с, когда та становилась 5.0. Защёлка меряла ВРЕМЯ, а спор шёл о
    МЕСТЕ, и никакая её величина этого не чинит.

    Перемотку назад это не запирает. Зритель, ушедший вглубь, двигает за собой и это
    место: следующий же круг часов показа назовёт новое, и запрос (он всё ещё ждёт
    файла, а не очереди) перепакует поток обычным ходом. Цена честной перемотки назад -
    один круг опроса, а не показ.
    """
    if state.played - state.keep <= 0:
        return False  # показ ещё не отошёл от начала фильма: позади зрителя нет ничего
    return slot < state.grid.slot_at(state.played - state.keep)


def _steer(state: _State, slot: int, restart: Callable[[int], None]) -> bool:
    """Что делать с упаковкой ради сегмента ``slot``; ``False`` — файла не будет.

    Разница между «подожди» и «не будет» — это разница между медленным ответом и 404.
    Держать приёмник в ожидании можно долго и почти безнаказанно, а вот 404 он
    запоминает: замерено — поймав его, ресивер не берёт LOAD ещё пару
    минут. Поэтому 404 отдаётся только там, где ждать нечего: конец входа или
    упаковка, которая сдалась насовсем.

    🔴 TC-501. Пропущенное место (:attr:`skipped`) в этот список больше не входит.
    Файла там и правда не будет, но манифест его уже пообещал, а мерка тут не
    «есть ли надежда», а «что переживает приёмник»: 404 он не переживает, тишину -
    переживает. Ответ отсюда - «подожди», перезапуска упаковки такое ожидание не
    вызывает, и через 8 с место перешагивает сторож приёмника.

    Перезапуск приходит доводом: его подменяют наследники ленты на стендах показа, а
    импортировать сюда саму ленту нельзя - решение живёт внутри неё.
    """
    if state.fatal:
        # Показ этой раздачи кончился (:meth:`stop`) или упаковка сдалась насовсем:
        # диагностировать тут больше нечего, а труп прогона - не новость. ⚠️ Проверка
        # стоит ПЕРВОЙ намеренно: на стыке серий сюда приходит приёмник, оставшийся
        # на живом keep-alive прошлой серии, и раньше он получал в журнал «упаковка
        # оборвалась» про наш же намеренно снятый ffmpeg.
        return False
    if slot in state.skipped:
        # 🔴 TC-501. Место честно пропущено (:meth:`_shrink` уже сказал об этом один
        # раз), файла не будет никогда - но манифест это имя приёмнику УЖЕ пообещал,
        # и выбор тут не «ответить или нет», а «ответить 404 или промолчать».
        # Молчим (:attr:`skipped`): на 404 приёмник гасит недоигранный буфер и
        # начинает круг «встал - погас - поднялся - попросил снова», на тишине тот же
        # буфер доигрывается, а дыру перешагивает его собственный сторож
        # (:meth:`torrcast.adapters.chromecast.cast.chromecast_receiver.ChromecastReceiver._nudge`)
        # - сеткой и через 8 с. ⚠️ Упаковку это ожидание не поднимает и поднять не может: возврат
        # отсюда уходит мимо перезапуска, а иначе запрос детерминированно тяжёлого места крутил бы
        # перепаковку вечно, получая ровно ту же копию.
        return True
    packer = state.packer
    if packer is not None and not packer.halted:
        moved = _progress(state, packer)
        # Край берём честный - тот, что выложил ЭТОТ прогон (:attr:`Packer.edge`).
        # Глоб каталога (`frontier`) на этом месте и был багом: чужие куски
        # уводили край вперёд, запрос далеко назад попадал в «подожди, вот-вот
        # допакуется» - и висел все `wait` секунд, чтобы кончиться 404. Обратная
        # наивная починка («ждать только впереди глоба») давала 20 перезапусков за
        # 100 с. Работает только честный край: он растёт ровно на publish.
        packer.publish()
        _settle(state, packer)
        if moved:
            _reread(state)  # прогон получил байты - значит источник снова читается
        else:
            _mute(state)
        if (state.out / state.piece_name(slot)).exists():
            state.circling = (-1, 0)  # место выдано - круга по нему больше нет
            # ⚠️ Кусок допаковался ровно этим `publish` - и это не редкость, а
            # обычный ход показа: приёмник идёт вплотную за упаковкой и просит
            # сегмент за мгновение до того, как тот закрылся. Без этой проверки он
            # оказывался «ниже края, а файла нет», то есть перемоткой назад: замер -
            # перезапуск на каждом четвёртом сегменте.
            return True
        code, edge = packer.poll(), packer.edge
        if packer.finished() and slot > edge:
            return False  # упаковка честно дошла до конца входа - файла не будет
        if code is None and edge < slot <= edge + state.ahead:
            # ⚠️ «Вот-вот» - это про ВРЕМЯ, а не про номер сегмента, и разница стоила
            # 28 с чёрного экрана. Упаковка идёт `readrate 1`, то есть в темпе
            # реального времени: перемотка вперёд внутри прогона попадает в эти семь
            # сегментов, но семь сегментов - это ещё и семьдесят секунд фильма, которые
            # ffmpeg будет читать семьдесят секунд. Замер на живом Q70D: перемотка
            # 3984 → 4100 (+116 с), «запрос v385.ts · ждал 57.8 с» - ровно эта планка.
            # Ждать имеет смысл только то, что упаковка достанет быстрее, чем стоит её
            # перезапуск с нужного места (:meth:`Packer.eta`).
            if packer.eta(state.grid.start(slot)) <= state.jump:
                return True  # обычный ход показа: кусок вот-вот допакуется
            journal().mark(
                "перемотка внутри прогона",
                слот=slot,
                ждать=round(packer.eta(state.grid.start(slot)), 1),
            )
        # Всё остальное при живой упаковке - перемотка. Вперёд (дальше `ahead` за
        # краем) и назад (ниже края, а файла нет - значит выметен окном или паковал
        # его не этот прогон) лечатся одинаково: перепаковкой с этого места.
        # Оборвался - это и «умер с кодом», и «вышел нулём на недописанном куске»
        # (:meth:`Packer.finished`): второе выглядит концом фильма, а на деле обрыв
        # входа, и лечится он тем же перезапуском с нужного места.
        if code is not None and not packer.finished() and not _survive(state, packer):
            return False
    # Пока источник не читается, толкаться незачем: подъём ffmpeg на мёртвую сеть
    # стоит секунды и не даёт ничего, а показ в это время идёт с диска.
    if _state.clock_port.monotonic() - state.restarted < (5.0 if state.offline else 2.0):
        return True  # соседний запрос уже перезапустил упаковку - не толкаемся
    if _behind(state, slot):
        # 🔴 TC-634. Ответ тот же, что у честно пропущенного места (:attr:`skipped`):
        # молчим и ждём. Отказать 404 нельзя (приёмник его не переживает), а перепаковать
        # под это место весь показ - значит увести упаковку от зрителя. Счёт кругов сюда
        # не идёт: приговаривать место, на которое зритель ещё вернётся, не за что.
        journal().mark("место позади зрителя", слот=slot, зритель=round(state.played, 1))
        return True
    if _circling(state, slot):
        _give_up(state, slot)
        return True
    state.restarted = _state.clock_port.monotonic()
    restart(slot)
    return True
