"""Раздачи, отложенные сторожем добора: в меню не идут, но и не выбрасываются."""

from __future__ import annotations

from torrcast.domain.cluster import cluster
from torrcast.domain.picture import Picture
from torrcast.domain.release import Release


def _aside(found: list[Picture], extra: list[Release]) -> int:
    """Отложить каждой найденной картине раздачи, привезённые отвергнутым добором.

    🔴 TC-770. Сторож :func:`~torrcast.usecases.discover._widened_subject._widened_subject`
    выбрасывал ВЕСЬ добор, стоило тому привезти соседние картины, - вместе с раздачами
    той самой картины, которую человек назвал. Живой стенд, «врата штейна ONA»: добор по
    ``Steins;Gate`` привозит 33 картины вместо 2 и отвергается целиком, а с ним уходят 52
    раздачи «Врат Штейна», из которых 5 обещают русскую озвучку.

    🔴 Но и в очередь эти раздачи класть нельзя. Замер на замороженном пуле (стенд .66,
    обе полосы на одном снимке): пул картины вырос с 2 раздач до 23, отбор переставил
    голову очереди, и показ, шедший ПО-РУССКИ (AniLibria, 2160p), стал английским. Добор
    не только добавляет - он вытесняет. Поэтому отложенное лежит отдельно от
    :attr:`~torrcast.domain.picture.Picture.releases`: меню, очередь и порядок отбора
    остаются ровно теми же, что без добора, и достаётся отложенное только там, где иначе
    человек услышал бы «русской не нашлось».

    ⚠️ Чужой картины отсюда взяться не может: принадлежность решает та же склейка, что
    собирает меню (:func:`~torrcast.domain.cluster.cluster`), и берётся ровно тот её
    кластер, в котором уже лежат СВОИ раздачи. Картина без такого кластера не получает
    ничего.

    ⚠️ Склейка зовётся ОДИН раз на всю выдачу, а не на картину: на «наруто» (29 картин
    меню, 261 строка широкой выдачи) вызов на каждую стоил 475 мс - двадцатую часть всего
    срока до картинки, и платился он на СЧАСТЛИВОМ пути тоже, ещё до всякого вопроса про
    звук.

    🔴 Зовётся это В КОНЦЕ круга поиска, а не там, где сторож сработал: ступени лестницы
    добора после него пересобирают картины из строк выдачи заново, и поле датакласса до
    отбора не доезжало - карман приезжал пустым (замер на стенде .66, «эксперименты
    лейн»: сторож сработал, а в отборе ``len(aside) == 0``). Поэтому через лестницу едут
    РАЗДАЧИ, а навешиваются они на те картины, что человек и увидит.
    """
    grown = [
        ({r.raw_name for r in p.releases}, p.releases)
        for p in cluster([r for p in found for r in p.releases] + extra)
    ]
    put = 0
    for picture in found:
        mine = {r.raw_name for r in picture.releases}
        same = [(names & mine, pool) for names, pool in grown if names & mine]
        if not same:
            continue
        _shared, kin = max(same, key=lambda pair: len(pair[0]))
        picture.aside = [r for r in kin if r.raw_name not in mine]
        put += len(picture.aside)
    return put


__all__ = ["_aside"]
