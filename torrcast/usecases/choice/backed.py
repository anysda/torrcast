"""Из живых - те, за кем стоит очередь раздач, а не одно обещание индексера."""

from __future__ import annotations

from typing import TYPE_CHECKING

from torrcast.usecases.choice.liveliness import liveliness

if TYPE_CHECKING:
    from torrcast.usecases.select.plan import Plan


def backed(plans: list[Plan], alive: list[int]) -> list[int]:
    """Из живых - те, кому есть чем играть: за картиной больше одной раздачи.

    Порог живости считает сиды, и по сидам однораздачная картина обходит соседку с
    очередью на законных основаниях: у «Мальтийского сокола» 1931 года ровно одна
    раздача на 16 сид, а у «Мальтийского сокола» 1941 года лучшая ГОДНАЯ раздача из
    двадцати двух держит 28 - доля честная, порог пройден, дефолт садился на 1931 год.
    То же у «Люпена»: «Rupan sansei» 2014 года одной раздачей на 3 сида обходил «Замок
    Калиостро» с десятью раздачами.

    Но «прошла порог» и «есть чем играть» - разные вещи. Сиды в выдаче это обещание
    индексера, а не факт: раздача, которая не отдаёт ни метаданных, ни потока, числится
    в выдаче ровно так же бодро (:func:`silent_swarm`). За картиной с очередью стоит
    двенадцать таких обещаний и показ переберёт их все; за однораздачной - одно, и
    осечка на нём заканчивает вечер. Ставить дефолт на монетку, когда рядом стоит
    очередь, - это и есть «формально живая».

    Ранжировать картины числом раздач эта ступень НЕ начинает, и это важно: на том уже
    обжигались - до-вожак по числу раздач выдавал сиквел вместо основной картины.
    Порядок остаётся хронологическим, а однораздачная картина уступает не всякой очереди,
    а только той, которая её же и живее. Первая часть на 100 сид одной раздачей остаётся
    дефолтом при сиквеле с двумя раздачами на 90 - она сама и есть самое живое, что
    нашлось, и уступать ей нечему. А «Мальтийский сокол» 1931 года на 16 сид уступает
    тёзке 1941 года, у которой и раздач двадцать две, и лучшая годная живее.

    Живых с очередью нет вовсе - список остаётся как был: выбирать не из чего, и
    молчаливо превращать «живую» картину в «мёртвую» не за что.

    🔴 TC-192. Уступают друг другу картины ОДНОГО типа, и это ограждение, а не оттенок.
    Глубина очереди у сериала говорит о сериале и ровно ничего - о полнометражной тёзке:
    у сериала раздача на каждый сезон, у фильма она одна на всё кино, и мерить их одной
    линейкой значит объявлять фильм «формально живым» за то, что он фильм. Замер:
    «Нелюбовь» - фильм Звягинцева 2017 года одной раздачей на 40 сид против сериала
    «НЕлюбовь [S01]» двумя раздачами на 120, и дефолтом молча вставал сериал. Тип запрос
    называет вслух ровно одним способом (:func:`asked_kind`), и там, где он промолчал,
    подменять кино сериалом за него нельзя.
    """
    deep = [n for n in alive if len(plans[n - 1].ranked) > 1]
    if not deep:
        return alive
    return [n for n in alive if n in deep or liveliness(plans[n - 1]) > _rival(plans, deep, n)]


def _rival(plans: list[Plan], deep: list[int], number: int) -> int:
    """Самая живая очередь СВОЕГО типа - её и обязана перебить однораздачная картина.
    Очередей своего типа нет вовсе - уступать нечему, и порог равен нулю.
    """
    kind = plans[number - 1].picture.kind
    return max(
        (liveliness(plans[n - 1]) for n in deep if plans[n - 1].picture.kind == kind), default=0
    )
