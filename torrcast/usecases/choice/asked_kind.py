"""Номера картин того типа, который назвал сам запрос."""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from torrcast.ports.choice_types import _Plan


def asked_kind(plans: list[_Plan]) -> list[int]:
    """Номера (с единицы) картин того типа, который назвал сам запрос.

    Тип назван вслух ровно одним способом: запрос спросил СЕРИЮ (``s1e1``). Тогда
    одноимённая полнометражка — не «вариант поживее», а другое кино, и дефолт обязан
    считаться среди сериалов. Замер по живой выдаче:

    * «хорошая жена s1e1» — дефолтом вставал ФИЛЬМ 1987 года (3 раздачи, ни одной
      живой) при сериале 2015 года на 30 раздач и 18 сид;
    * «синий экзорцист s1e1» — дефолтом вставала полнометражка 2012 года;
    * «великий из бродячих псов s1e1» — дефолтом вставал чиби-спин-офф, приехавший
      отдельными сериями и потому опознанный как полный метр.

    Сериалов в выдаче нет вовсе — считаем как считали: гейт тут не судья тому, чего
    он не видел, и пустой ответ вместо картины был бы хуже неточного типа.

    Серии запрос не называл — тип не назван, и все картины равны: «мальтийский сокол»
    одинаково может оказаться и фильмом, и сериалом, и гадать за человека нечего.
    """
    if not any(plan.asked_series for plan in plans):
        return list(range(1, len(plans) + 1))
    series = [n for n, plan in enumerate(plans, start=1) if plan.picture.kind == "tv"]
    return series or list(range(1, len(plans) + 1))
