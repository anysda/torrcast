"""Насколько картина живая: сиды самой живой раздачи, которой она может играть."""

from __future__ import annotations

from typing import TYPE_CHECKING

from torrcast.usecases.choice.configure import _environment_port

if TYPE_CHECKING:
    from torrcast.usecases.select.plan import Plan


def liveliness(plan: Plan) -> int:
    """Насколько картина живая — сиды самой живой раздачи, которой картина **может играть**.

    Мерок было три, и две отброшены на живой выдаче:

    * сумма сидов по всем релизам — вытягивает картину числом раздач, а не их
      качеством: у «Матрицы» 1999 сорок релизов против одиннадцати у «Воскрешения»,
      и сумма выбрала бы первую даже с мёртвыми DVD-рипами в хвосте;
    * сиды одной «лучшей» раздачи картины, выбранной до отбора, — не знают ни про потолок
      битрейта, ни про образы дисков, ни про старьё, а это и есть отбор.

    Осталось честное: сиды лучшей раздачи из тех, что годны по :func:`is_candidate`.
    Негодные в счёт не идут вовсе — ни 41-гигабайтный 4K-ремукс «Тачек» 2006 на 49.9
    Мбит/с (выше потолка декодера), ни образы дисков, ни старьё, которое отсеет
    :func:`is_dated`: играть ими картина не может, и вес им не положен.

    Считалось это раньше по ОДНОМУ релизу — верху :func:`rank_releases`, — и мерка
    получалась случайной: очередь сортируется не только сидами, и наверху у картины
    стоит то, что лучше СМОТРЕТЬ, а не то, что живее. У «Мальтийского сокола» 1941
    года на верху очереди 5 сидов при 97 у годного соседа ниже, и картина с 22
    раздачами весила меньше однораздачной тёзки 1931 года на 16 сидов - дефолт
    садился на неё. Считать по одному верху было честно, пока очередь и обрывалась
    на трёх номерах; с тех пор как :meth:`Plan.candidates` отдаёт все годные
    раздачи, показ дойдёт до любой из них, и «чем играть» — это они все.

    Ворота спрашиваются те же, что у самого плана (:attr:`Plan.loose`), и это не
    мелочь: пока они спрашивались строго, аниме с молчаливыми именами весило ноль
    целиком — у «наруто» дефолтом меню вместо сериала на 91 сид вставал полнометражный
    «Ниндзя в стране снега» на два.

    🔴 Последняя надежда (:attr:`Plan.last_resort`) сюда НЕ спрашивается, и это
    осознанно. Вес картины решает, какой пункт меню предложить человеку, а HEVC — не
    предпочтение, а единственный оставшийся носитель ВНУТРИ уже выбранной картины.
    Замер на кэше выдачи «синий экзорцист s1e1»: стоило дать HEVC вес, и дефолт меню
    переезжал с «Blue Exorcist» (1080p H.264, 5 сидов) на одноимённую картину с
    ``HEVC``, то есть ровно то предпочтение, которого быть не должно.
    """
    return max(
        (
            release.seeders
            for release in plan.ranked
            if _environment_port().is_candidate(
                release,
                plan.runtime,
                plan.warn_mbit,
                plan.loose,
                plan.hard_mbit,
                copy_hevc=plan.copy_hevc,
            )
        ),
        default=0,
    )
