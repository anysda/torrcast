"""Спрошенной части франшизы в выдаче нет вовсе - случай, где вопрос уже не нужен."""

from __future__ import annotations

from typing import TYPE_CHECKING

from torrcast.usecases.choice.part_one_swap import _first_part

if TYPE_CHECKING:
    from torrcast.usecases.select.plan import Plan


def absent_first_part(plans: list[Plan], asked: str) -> bool:
    """Первой части спрошенной франшизы в выдаче НЕТ - ни живой, ни мёртвой.

    🔴 TC-830, решение владельца 26-08-2026 - «включать живейшую вслух»: тут показ
    начинается сам, дефолтом прибора (:func:`first_alive`), и не молча
    (:func:`~torrcast.usecases.choice.absent_part_line.absent_part_line`). Второго правила
    выбора отсюда не заводится: дефолт у прибора один, и слова строки сверены с ним.
    Прежде страж франшизы (:func:`part_one_swap`) снимал дефолт и на этом случае, и
    ``cast тачки`` спрашивал номер БЕЗ ``--menu``: показ без человека не начинался вовсе.

    ⚠️ Этот случай и «спрошенная часть нашлась, но не играет» - РАЗНЫЕ, и путать их
    нельзя. Там первая часть в выдаче есть, её можно назвать номером, и страж остаётся
    стражем: подставлять другую часть вместо живой спрошенной по-прежнему запрещено.
    Здесь называть нечего - выбора между «той» и «другой» не существует, и вопрос сводился
    к «назови номер из списка, в котором нужного пункта нет».

    Молчание стража отделено от «первой части нет» вторым значением :func:`_first_part`:
    без него оба случая выглядели бы снаружи одинаково пустыми.
    """
    first, franchise = _first_part(plans, asked)
    return franchise and first is None
