"""Приговор ступени взятия: чей номер возьмёт Enter и что о нём говорят вслух."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class Take:
    """Приговор ступени взятия: чей номер возьмёт Enter и что об этом говорят вслух.

    🔴 TC-829. Номер тут ОДИН, и это главное свойство записи. Прогрев под меню
    (:func:`~torrcast.usecases.choice.warm_order.warm_order`) и вопрос
    (:func:`~torrcast.usecases.choice._pick_plan._pick_plan`) читают одно и то же поле
    :attr:`number`, а не считают каждый своё: пока целились они порознь - прогрев
    в :func:`first_alive`, а взятие в стражей поверх него, - эти двое совпадали лишь
    иногда и расходились МОЛЧА. Замер до правки, корпус ``pools-both.jsonl``: 10 запросов
    из 74 грели не ту картину, которую включал Enter; на 6 из них взятая не попадала в
    прогретую голову вовсе, и зритель платил за неё подъёмом роя с нуля.

    Разойтись этим двоим теперь нечем: расходятся не мнения, а числа, а число одно.
    """

    #: Номер картины (с единицы): её греют первой, её же включит Enter. Всегда есть -
    #: даже там, где вопрос задаётся без дефолта: греть-то всё равно кого-то надо, и
    #: другого основания, кроме дефолта франшизы, у прогрева нет.
    number: int
    #: Берёт ли Enter эту картину. ``False`` - вопрос без дефолта: номер называет человек
    #: сам (:func:`part_one_swap`, :func:`named_elsewhere`), либо взятия нет вовсе.
    takes: bool = True
    #: Поднимается ли список с вопросом.
    asks: bool = False
    #: Строка перед взятием, а на пути со списком - строка ПОД списком.
    note: str = ""
    #: Строка НАД списком: ею говорят, ЧТО нашлось, прежде чем показать найденное.
    heading: str = ""
    #: Причина отказа; "" - отказа нет.
    refusal: str = ""
    #: Каким правилом номер взят - имя ветки :func:`enter_take`. Уезжает в журнал замера
    #: (TC-108) рядом с отметкой о пуске прогрева: без него в разборе видно, ЧТО грелось,
    #: но не видно, почему грелось именно это.
    why: str = ""
