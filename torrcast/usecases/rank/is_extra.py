"""Признак «раздача - приложение к картине, а не картина»; зовут ворота отбора."""

from __future__ import annotations

from torrcast.domain.rank_settings import EXTRAS_MBIT
from torrcast.domain.release import Release
from torrcast.usecases.rank.bitrate_of import bitrate_of


def is_extra(release: Release, runtime: float) -> bool:
    """Раздача - приложение к картине, а не сама картина: так сказало имя, так вышло по весу.

    🔴 TC-290. Ворота отбора судили, КАК раздача снята - разрешение, битрейт, живость,
    звук, - и ни одна ступень не спрашивала, картина ли это вообще. Дополнительные
    материалы (фильм о фильме, интервью, вырезанные сцены, трейлер) проходили обычным
    кандидатом, а из-за малого веса выглядели по битрейту даже прилично. У «Тачек 2» из
    сохранённой выдачи «HDRip … фильм о фильме» на 0.4 ГБ стоял в очереди четырнадцатым,
    а в пуле, где у картины всего две раздачи, - ПЕРВЫМ, то есть дефолтом Enter. Человек
    просит кино и получает получасовой ролик о съёмках; молча.

    Признаков два, и по отдельности ни один не годится.

    Имя (:attr:`~torrcast.parse.Release.extras`) без веса отбраковало бы законную картину,
    у которой такое слово стоит в её же названии, и раздачу «картина + приложение».

    Вес без имени - это уже :func:`is_dated`, и он про другое: мизерный битрейт бывает у
    честного SD-рипа, и выкидывать такой нельзя, пока другого нет. Здесь же имя прямо
    говорит, что играть тут не картину, и вес это подтверждает: при длительности из
    справки (:func:`torrcast.facts.minutes_of`, она же знаменатель :func:`bitrate_of`)
    столько весит ролик, а не фильм.

    ⚠️ Короткометражке признак не грозит, и не по доброте: её длительность справка называет
    честно, а ролик от картины отличает не абсолютный размер файла, а вес НА МИНУТУ. Пока
    справка молчит, в знаменателе стоит прикидка «фильм это два часа»
    (:data:`torrcast.domain.runtime_guess.RUNTIME_GUESS`), и она короткометражку занижает - но
    занизить раздачу без пометки приложения в имени всё равно некуда: ворота её и не смотрят.

    ⚠️ Признак отнимает и единственную раздачу картины (TC-432): показать трейлер на
    запрос сериала - это подмена картины, а не «лучше, чем ничего». Вернуть её может
    только сам человек, номером из таблицы (``--release N`` в ворота не ходит).

    🔴 TC-339. Весу есть предел измерения: «Титаник | Дополнительные материалы» на
    11.6 ГБ, «Довод» на 22.5 ГБ, «Хоббит: Приложения» на 19.2 ГБ по битрейту выглядят
    картиной и ворота проходили, а подменить её могут, стоит умереть всему выше них.
    Поэтому однозначная метка (:attr:`~torrcast.parse.Release.extras_sure`) судит БЕЗ
    веса: «дополнительные материалы» и «бонус-диск» не бывают картиной ни при каком
    битрейте. Прочие метки без веса не судятся по-прежнему: их носят и раздачи самой
    картины, и сохранённая выдача это подтверждает - отсев по любой метке оставил бы
    без живых кандидатов 10 картин корпуса из 107 пулов, по однозначной - ни одной.
    ⚠️ Замер тот считал верх ранжира неприкосновенным, а TC-432 повёл через ворота и
    его: там, где однозначная метка стоит на ЕДИНСТВЕННОЙ раздаче картины, очередь
    теперь пустеет, и человек получает честный отказ (:func:`unfit_line`), а не
    бонус-диск вместо картины.

    🔴 TC-344. Молчание веса - не «лёгкий»: у сериала, чьё имя серий не считает,
    :func:`bitrate_of` отдаёт ``None``, и приложение с таким весом ворота НЕ отсекают -
    выкидывать раздачу по весу, которого нет, значит карать за собственное незнание.
    Порядок её всё равно уводит под картину (:func:`rank_releases`), а судит содержимое
    ffprobe, как и всякую молчаливую раздачу.
    """
    if not release.extras:
        return False
    if release.extras_sure:
        return True
    mbit = bitrate_of(release, runtime)
    return mbit is not None and mbit < EXTRAS_MBIT
