"""Порядок меню раздач: лестница ступеней отбора; зовёт план картины."""

from __future__ import annotations

from torrcast.domain.episode import Episode
from torrcast.domain.release import Release
from torrcast.usecases.rank.fits_receiver import fits_receiver
from torrcast.usecases.rank.heavy_peers import heavy_peers
from torrcast.usecases.rank.hevc_hope import hevc_hope
from torrcast.usecases.rank.is_candidate import is_candidate
from torrcast.usecases.rank.is_dated import is_dated
from torrcast.usecases.rank.is_dead import is_dead
from torrcast.usecases.rank.is_disc import is_disc
from torrcast.usecases.rank.is_full_hd import is_full_hd
from torrcast.usecases.rank.misses_episode import misses_episode
from torrcast.usecases.rank.needs_whole_recode import needs_whole_recode
from torrcast.usecases.rank.sound_step import sound_step
from torrcast.usecases.rank.studio_step import studio_step


def rank_releases(
    releases: list[Release],
    runtime: float,
    warn_mbit: float,
    want: Episode | None = None,
    loose: bool = False,
    hard_mbit: float = 0.0,
    last: bool = False,
    copy_hevc: bool = False,
    studio: str = "",
    recode_at: float = 0.0,
) -> list[Release]:
    """Порядок меню: сверху самый обсиженный кандидат, потом всё остальное по
    сидам, образы дисков всегда внизу — цельного файла внутри нет, стримить нечего.

    Первой ступенью для сериала идёт :func:`misses_episode`: раздача, которая своим
    именем говорит «нужной серии тут нет», уходит под всех, кто может её содержать, —
    даже под мёртвые и под образы дисков. Живой случай, ради которого ступень
    появилась: у «Наруто» верхом стоял ``[S01E01-08 of 220]``, у «Локи» и
    «Сверхъестественного» — такие же огрызки, а полный сезон лежал строкой ниже, и
    авто-выбор упирался в «серии s1e1 в этой раздаче нет» уже после похода в рой.

    Сразу под годностью стоит :attr:`~torrcast.domain.release.Release.extras` — раздача, чьё имя
    называет её приложением к картине, а не картиной: фильм о фильме, дополнительные
    материалы, бонус-диск, трейлер. Ступень судит ОДНО имя, без веса, и права выкинуть
    раздачу у неё нет — она только уводит её под всё, что и правда картина. Выкидывает
    ворота (:func:`is_extra`), и им нужен ещё и вес. Разница видна ровно там, где и должна:
    бонус-диск на 11 ГБ ворота пропускают (столько ролик не весит, а ошибиться тут дорого),
    а порядок всё равно держит его последним из годных — у картины есть она сама.

    Там же сборник уступает одиночной раздаче картины. Внутри дилогии или коллекции
    выбор файла снова должен угадать часть, хотя индексер уже умеет отдать ровно
    спрошенный фильм. Сборник остаётся кандидатом, когда одиночного релиза нет.

    ⚠️ Ниже годности, а не выше, и это не мелочь. Выше она топила бы годную раздачу под
    негодную из-за одного слова в имени: у документального «Нечто: Ужас обретает форму»
    оба релиза подписаны «фильм о фильме», и BDRip на 2.2 ГБ уходил под DVDRip на 0.7,
    то есть меткой наказывалась сама картина, которую человек и звал.

    Следом идёт :attr:`~torrcast.domain.release.Release.stereoscopic` - имя обещает половину
    стереопары вместо обычного кадра (3D, ``half-ou``, ``sbs``). Ступень судит одно имя и
    раздачу не выкидывает: на плоском экране такая картинка смотрится сдвоенной, но когда
    другой нет вовсе, играть её всё-таки можно. Место у неё тем же порядком, что у
    :attr:`~torrcast.domain.release.Release.extras`: под всем, что обещает обычный кадр.

    Сразу за годностью идёт ступень :func:`is_dead`: раздача с НУЛЁМ сидов уходит под
    всех, у кого рой хоть какой-то есть. Ступень стоит выше качества нарочно: качество
    это выбор между двумя показами, а ноль сидов — это отсутствие показа, и никакой
    1080p его не перевешивает. Живой случай: у «Наруто» верхом отбора стоял
    124-гигабайтный пак с нулём сидов, а сериал на 91 сид ждал ниже, потому что
    проигрывал ему по ступени старья; старт при этом упирался в двадцатисекундное
    молчание DHT ещё до первого кадра.

    Между «живостью» и «сидами» вклинена ступень :func:`is_dated`: обсиженное
    старьё уступает место годному даже при кратной разнице в сидах. Цена вопроса
    измерена: подъём такой раздачи стоит 2–5 секунд живого старта — метаданные по DHT
    плюс чтение дорожек, — и это ровно те секунды, которые незачем держать в
    критическом пути. На «Моане 2» так и было: первым
    кандидатом стоял 1.46-гигабайтный .avi с 221 сидом, а годный WEB-DL-AVC с 140
    сидами ждал своей очереди вторым.

    Следом за ней — ступень :func:`sound_step`: звук, которого не понять, — это не
    «качество похуже», а несмотренный тайтл. Поэтому она стоит ВЫШЕ :func:`is_full_hd`:
    обе ступени размениваются на сиды, и размен «1080p вместо 720p» дешевле размена
    «по-русски вместо по-японски». Ниже :func:`is_dated` она стоит по обратной причине:
    русский .avi вместо честного 1080p — это уже не размен, а откат по всему фронту.

    Следом — ступень :func:`is_full_hd`: живой 1080p обходит 720p, даже когда сидов
    у него меньше. Дальше внутри каждой группы всё как было — сиды, потом размер.

    Сразу под годностью стоит :func:`needs_whole_recode`: релиз, который играется только
    сплошным перекодом (BD-ремукс на 28-37 Мбит/с), годен, но идёт последним из годных.
    Ступень стоит выше живости нарочно: тяжёлое берётся, когда легче ничего нет, а не
    потому, что у ремукса больше сидов.

    Сразу под живостью стоит :func:`hevc_hope` — релиз, попавший в очередь последней
    надеждой. Ступень пустая, пока ворота ``last`` закрыты: ключ у всех одинаковый, и
    порядок обычного случая не меняется ни на строку. Открылись — HEVC уходит под всех
    прочих кандидатов, потому что стоит он дороже во всём: процессор занят сплошным
    перекодом от первой секунды до титров, а старт замерен на 3 с медленнее.

    Ниже живости, а не выше, она стоит по той же причине, по которой :func:`is_dead`
    поднялась над качеством: ворота последней надежды открываются только тогда, когда
    живого обычного кандидата нет вовсе, и единственный, кто остаётся против HEVC, —
    раздача с нулём сидов. Она не «обычный релиз», она отсутствие показа, и двадцать
    секунд молчания DHT перед живым HEVC — чистая потеря старта.

    Последней, ПОД кадром и НАД сидами, идёт :func:`studio_step`: раздача, чьё имя
    обещает ту самую студию, которой картину уже смотрели, обходит равных ей во всём
    остальном. Ступень отвечает на единственный вопрос, который сериал задаёт каждой
    границей сезона: сезон кончается вместе со своей раздачей, следующий выбирается
    заново, и без памяти выбирается он по сидам - то есть по лотерее.

    Место выбрано замером, а не вкусом. Выше звука ступени нельзя вовсе: озвучка важнее
    конкретной студии, и «та же студия по-японски» - это не тот же сериал. Из двух
    оставшихся законных мест - над кадром и под ним - ЦЕЛИ не различает ни одно: на
    корпусе сохранённых выдач замеримых границ сезона 47, студию теряют на 9, у 5 из них
    та же студия в раздачах следующего сезона есть, и оба места держат ровно 2 из этих 5.
    Различают они ЦЕНУ. Над кадром ступень попадает в ключ группировки, которой
    :func:`is_full_hd` меряет свой размен, и соперником 1080p становится не пул, а его
    же студия: на «Чёрном зеркале» те же 2 границы покупались роем 61 → 10 сид и сменой
    кадра 720p → 1080p, а под кадром - роем 61 → 18 сид при том же кадре. Память про
    ЗВУК не вправе покупать картинку, поэтому ступень стоит под кадром и решает ровно
    один спор - между равными по всему, что лестница уже рассудила.

    ``studio`` - имя студии из памяти картины; пусто (первый просмотр) - ступень плоская,
    и порядок в точности прежний.

    Самой нижней ступенью, ПОД студией и НАД сидами, идёт :func:`fits_receiver`: из двух
    равных во всём остальном раздач берётся та, которую приёмник играет без перекода на
    ходу. Ступень отвечает на вопрос, которого весь порядок выше не задаёт: во что показ
    обойдётся зрителю. Кусок тяжелее потолка уезжает перекодированным на ходу, и платит
    за это плёнка - на осторожном приёмнике так уходит 616 кусков из 627 и 59.98 секунды
    подгрузов за сеанс.

    Ниже всех прочих ступеней она стоит нарочно, и обе границы замерены на корпусе.
    Выше звука её нельзя: релиз без русской дорожки негоден любым весом. Выше кадра
    тоже: 720p под потолком - это не выигрыш, это другая ступень чёткости. Спор ей
    остаётся ровно один - между раздачами, которые лестница уже признала равными, и там
    её ответ дешевле ответа по сидам.

    ``recode_at`` - потолок приёмника, Мбит/с (ноль - перекодирования нет и ступень
    плоская). Отсевом она не является: раздача выше потолка остаётся кандидатом.

    Снизу у ступени пол, и знаменатель ему даёт :func:`heavy_peers` - самый тяжёлый
    сосед по той же группе. Без пола «легче потолка» проходила и каша: раздача, названная
    1080p, при 0.05 Мбит/с вставала над честной на 9.5. Пол тоже предпочтение, а не
    отсев, и меряется он долей, а не Мбит/с
    (:data:`~torrcast.domain.rank_settings.TRADE_FLOOR`).

    ``loose`` — ворота отбора открыты (:func:`gate_open`), и молчаливые имена идут
    в кандидатах наравне с именными. ``last`` — открыты ворота последней надежды
    (:func:`last_hope`). ``copy_hevc`` - профиль разрешил HEVC копией, поэтому это
    обычный кандидат, а не последняя надежда.
    """
    alive = max((r.seeders for r in releases), default=0)
    steps = {
        id(r): (
            misses_episode(r, want),
            is_disc(r),
            not is_candidate(r, runtime, warn_mbit, loose, hard_mbit, last, copy_hevc),
            r.collection,
            r.extras,
            r.stereoscopic,
            needs_whole_recode(r, runtime, hard_mbit),
            is_dead(r, alive),
            hevc_hope(r, last),
            is_dated(r, runtime),
            sound_step(r, alive),
        )
        for r in releases
    }
    # Цена размена «1080p вместо 720p» меряется сидами сильнейшего из тех, кого этот
    # 1080p и правда потеснит, - равных по всем ступеням выше. Лидер пула тут не мерка:
    # он может сидеть на другой ступени (старьё, чужой звук, сплошной перекод) и в споре
    # за верх не участвовать вовсе, а его сиды всё равно раздували знаменатель.
    rivals: dict[tuple[object, ...], int] = {}
    for r in releases:
        key = steps[id(r)]
        rivals[key] = max(rivals.get(key, 0), r.seeders)
    # Пол размена (:func:`fits_receiver`) меряется тяжёлым соседом, а сосед тут - равный
    # по всем ступеням ВЫШЕ потолка приёмника. Поэтому ключ группы досчитывается целиком
    # до сортировки: в `rivals` его нет, там ступени только до кадра.
    full: dict[int, tuple[object, ...]] = {
        id(r): (*steps[id(r)], not is_full_hd(r, rivals[steps[id(r)]]), studio_step(r, studio))
        for r in releases
    }
    heavy = heavy_peers(releases, full, runtime, recode_at)
    return sorted(
        releases,
        key=lambda r: (
            *full[id(r)],
            not fits_receiver(r, runtime, recode_at, heavy.get(full[id(r)], 0.0)),
            -r.seeders,
            -r.size,
            r.magnet,
        ),
    )
