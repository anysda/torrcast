"""Потолок битрейта серии у пака, чьё имя считает сезоны, но не серии; зовёт признак старья."""

from __future__ import annotations

from torrcast.domain.bitrate_mbit import bitrate_mbit
from torrcast.domain.rank_settings import SEASON_EPISODES
from torrcast.domain.release import Release


def pack_mbit(release: Release, runtime: float) -> float:
    """Потолок битрейта серии у пака, чьё имя считает СЕЗОНЫ, но не серии; 0 — не считает.

    Дыра, которую это закрывает, и есть 🟡 «Чёрные паруса»: имена вида
    ``[S01-04] (2014-2017) HDTV-AlexFilm`` и ``HDRip, WEB-DL, HDTV … | КПК`` не называют
    ни разрешения, ни кодека, а серий не считают вовсе — :func:`bitrate_of` на них
    молчит, :func:`is_dated` промолчать обязана, и такая раздача с ОДНИМ сидом встаёт
    в очереди перебора ВЫШЕ живого сериала на 61 сид. А внутри у них SD: показ либо
    сожжёт на них :data:`MAX_TRIES` и 130 секунд, либо сыграет SD, не дойдя до живого
    720p, — и то и другое при живом каталоге.

    Считается это не выдумкой, а потолком. Сколько серий в сезоне, имя не сказало — но
    меньше :data:`SEASON_EPISODES` их почти не бывает, а делённый на МЕНЬШЕЕ число размер
    даёт БОЛЬШИЙ битрейт: если даже потолок ниже :data:`SD_BITRATE`, внутри SD наверняка.
    Числа того же случая: 10.24 ГБ на четыре сезона — потолок 1.3 Мбит/с, 27.24 ГБ —
    3.4 Мбит/с, а настоящий ``BDRip 720p`` на 114 ГБ — 14 Мбит/с, и его признак не
    трогает. Двухгигабайтный ``HDTV | BaibaKo-iPhone`` на один сезон — 1.3 Мбит/с.

    ⚠️ Это по-прежнему только ПОРЯДОК (:func:`is_dated`), и годность им не решается.
    Отдельно от :func:`bitrate_of` — нарочно: тот кормит ВОРОТА отбора
    (:func:`is_candidate`, :func:`needs_whole_recode`), а потолок в воротах означал бы
    «раздача слишком тяжёлая», то есть отказ показывать честный 114-гигабайтный пак.
    Ворота судят по подтверждённому счёту серий, как и судили; порядок — по потолку.
    """
    if release.kind != "tv" or release.episode_count or not release.seasons:
        return 0.0
    return bitrate_mbit(release.size // (len(release.seasons) * SEASON_EPISODES), runtime)
