"""Признак «релиз проходит в очередь только последней надеждой»; зовут ворота и порядок."""

from __future__ import annotations

from torrcast.domain.release import Release


def hevc_hope(release: Release, last: bool) -> bool:
    """Релиз проходит в очередь ТОЛЬКО последней надеждой: он названный HEVC.

    Ворота отбора держали HEVC снаружи с самого начала, и это было правдой ровно до тех
    пор, пока показ его не умел. Теперь умеет: сплошной перекод по файлу закрыл
    десятибитный H.264 (:func:`torrcast.domain.recodes_whole.recodes_whole`), и HEVC идёт по тому же
    пути тем же кодом. Ворота при этом отбраковывали то, что тракт играет, — и на
    «Гинтаме» это стоило показа целиком: первая серия во всём каталоге лежит в двух
    раздачах, DVDRip-AVC с НУЛЁМ сидов и ``BDRip-HEVC 720p`` с четырьмя, то есть
    единственный живой носитель серии в очередь не попадал вовсе.

    ``last`` — ворота последней надежды открыты (:func:`_plan_for`). Закрыты — признак
    не срабатывает никогда, и ни отбор, ни порядок не меняются ни на знак: при живом
    обычном релизе HEVC по-прежнему не кандидат. Это не осторожность, а цена: сплошной
    перекод занимает процессор от первой секунды до титров и стартует медленнее
    (замер: 8 с против 5 с).

    🔴 Про ПРИЁМНИК здесь не спрашивается ничего, и это не забывчивость. Вопрос «а этот
    декодер вообще спотыкается о HEVC» — один на весь код
    (:func:`torrcast.domain.recodes_whole.recodes_whole`), задаётся он профилю
    (:mod:`torrcast.profile`) и задан уже в воротах, при вычислении ``last``. Спросить
    его и тут значило бы развести решение о кодеке на два места, а именно от этого и
    ломался десятибитный H.264.

    🔴 TC-222. Кадр выше 1080p сюда ПРОХОДИТ, и это разворот прежнего правила. Прежнее
    стояло на арифметике «скорость сплошного перекода замерена на 1080p, у 2160p вчетверо
    больше пикселей, в бюджет старта не влезает», а замер TC-157 её перевернул: тот же
    перекод СО СКЕЙЛОМ до 1080p идёт 1.53× реального времени против 1.03× без скейла -
    вчетверо меньше пикселей достаётся кодировщику, и он от этого не тонет, а ускоряется.
    Отказывать тут значило бы отказывать в единственном носителе картины ради потолка,
    которого больше нет. Решение продукта ровно такое: нет 1080p - 2160p перекодируется
    вниз как последняя надежда, а не отбрасывается.

    ⚠️ Предпочтением 4К от этого не становится: под 1080p его топит ступень
    :func:`needs_whole_recode` (она стоит выше живости), а слишком тяжёлый 4К по-прежнему
    не проходит потолок :func:`over_ceiling`.

    Имя, о разрешении молчащее, проходит и здесь: судить его будет ffprobe после выбора
    (:meth:`_Bench._trouble`), у которого высота кадра не заявка, а факт.
    """
    return last and release.is_hevc
