"""Ступень «играется только сплошным перекодом»; зовёт порядок меню."""

from __future__ import annotations

from torrcast.domain.recode_settings import RECODE_HEIGHT
from torrcast.domain.release import Release
from torrcast.usecases.rank.bitrate_of import bitrate_of


def needs_whole_recode(release: Release, runtime: float, hard_mbit: float) -> bool:
    """Релиз играбелен только сплошным перекодом: он тяжелее ``hard_mbit`` или крупнее кадром.

    Ступень отбора, а не отказ. Такой релиз берётся — но последним из годных: держать
    его показ дороже во всём сразу. Процессор занят с первой секунды и до титров
    (посегментному перекоду хватало тяжёлых мест), рою надо отдавать ~4.7 МБ/с
    непрерывно вместо ~1 МБ/с, и любая просадка роя, которую лёгкий релиз пережил бы за
    счёт запаса, тут сразу становится подгрузом. Поэтому ремукс на 36 Мбит/с обязан
    уступать честному релизу на 8, даже когда сидов у него больше.

    🔴 TC-221. Кадр выше :data:`torrcast.domain.recode_settings.RECODE_HEIGHT` стоит на этой ступени
    рядом с весом, и это ровно то место, где решение продукта «2160p отбраковывается в пользу ЖИВОГО
    1080p» и превращается в порядок. 4К играется только сплошным перекодом со скейлом вниз - копией
    приёмник его не берёт (TC-157), - то есть по стоимости это тот же класс, что ремукс: процессор
    занят от первой секунды до титров, а из роя надо тянуть все 20 Мбит/с ради 9 на экране. Ступень
    стоит ВЫШЕ живости и выше :func:`is_full_hd`, поэтому 4К никогда не обгоняет живой 1080p, а
    берётся ровно тогда, когда 1080p нет.

    ``hard_mbit`` ноль — ступени по весу нет: перекодирование выключено, и тяжёлое
    отсеяно раньше, самим потолком отбора. Кадра это не касается: 2160p и без
    перекодирования не играется, и внизу списка ему самое место.
    """
    if release.height > RECODE_HEIGHT:
        return True
    mbit = bitrate_of(release, runtime)
    return hard_mbit > 0 and mbit is not None and mbit > hard_mbit
