"""Гейт дорожки на языке зрителя по паспорту файла; зовёт отбраковка релиза на стенде."""

from __future__ import annotations

from torrcast.domain.catalogs.tongue import EN, tongue
from torrcast.domain.media import Media
from torrcast.usecases.rank.sought_voice import sought_voice


def voice_unproven(media: Media, *, native: bool = False, language: str = "") -> bool:
    """Дорожка на языке зрителя в этом файле НЕ ПОДТВЕРЖДЕНА: паспорт отрицает или молчит.

    🔴 TC-301. У паспорта три ответа, а не два. «Дорожка есть» (:func:`sought_voice`) -
    играем. «Дорожки нет» (все языки названы, искомой среди них нет) - гейт бракует
    релиз, и очередь идёт дальше (:meth:`torrcast.usecases.select_bench.bench.Bench.resolve`).
    А между ними лежит третий: дорожка БЕЗ ТЕГА ЯЗЫКА
    (:attr:`~torrcast.domain.audio_track.AudioTrack.named`), и по замеру паспортов таких
    файлов 28%.

    🔴 TC-492. Третий ответ засчитывался за первый, и стоило это зрителю картины:
    «Эксперименты Лэйн» уехали с нерусской дорожкой ровно потому, что язык её никто не
    назвал, - а в очереди оставалось ещё четыре нетронутых релиза. Незнание - это не
    «сойдёт»: правило продукта требует дорожки на языке зрителя, а не отсутствия
    доказательств обратного. Поэтому годным считается только первый ответ, а второй и
    третий отправляют релиз в один и тот же запасной ход
    (:meth:`torrcast.usecases.select_bench.bench.Bench._mute_fallback`): очередь идёт
    дальше, а когда спрашивать больше некого - играет лучшее из отложенного, и говорит
    об этом вслух.

    Имя раздачи тут не судья ни в одну сторону (TC-191): «[RUS(int)]» русской дорожки не
    гарантирует, и подменять им паспорт значит вернуть ту же ошибку с другого конца.

    ``native`` - справка подтвердила отечественное происхождение картины. Под русской
    ручкой безымянная дорожка такой картины - не пробел, а паспорт происхождения:
    «Бригаду» никто не озвучивал, она так и снята. Под английской этой скидки нет
    ровно по той же причине, по какой она есть у русской: своя дорожка отечественной
    картины звучит по-русски, а английскому зрителю нужен английский, и безымянная
    дорожка его не подтверждает. Та же развилка стоит в :func:`sound_note`.

    ⚠️ Граница проведена по ДОРОЖКЕ, а не по паспорту целиком: файл, у которого ffprobe не
    отдал ни одной звуковой дорожки, сюда не относится. Это не «язык не назван», а «звук
    не прочитан» - паспорт, дочитанный до половины, и бракует он не релиз, а нашу спешку
    (:attr:`~torrcast.domain.media.Media.foreign` о том же). В замере паспортов таких файлов нет
    ни одного из 92, а стоила бы такая строгость всей выдачи разом.
    """
    spoken = language or tongue()
    if sought_voice(media, spoken) or not media.tracks:
        return False
    if spoken == EN:
        # Скидки ``native`` тут нет: она про собственную РУССКУЮ дорожку картины.
        return True
    return media.foreign or not native
