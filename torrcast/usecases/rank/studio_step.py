"""Ступень «та же студия, что и раньше»; зовёт порядок меню."""

from __future__ import annotations

from torrcast.domain.release import Release


def studio_step(release: Release, studio: str = "") -> int:
    """Ступень памяти студии: 0 — имя раздачи обещает ту самую студию, 1 — не обещает.

    Сериал смотрят одной озвучкой, а раздают его сезонами: один сезон - один релиз -
    одна студия. Внутри раздачи переход бесшовный (:meth:`torrcast.domain.entry.Entry.advance`
    хранит и релиз, и дорожку), а на границе сезона раздача кончается вместе с сезоном,
    и следующий выбирается заново - по сидам и качеству, то есть по лотерее. Ступень и
    есть то, чем «досмотреть тем же» вообще выражается: память дорожки работает ВНУТРИ
    уже выбранного релиза, а релиз выбирается до неё.

    ``studio`` - имя студии из памяти картины (:attr:`torrcast.domain.entry.Entry.studio`).
    Памяти нет - ступень ПЛОСКАЯ: ключ у всех одинаковый, и порядок первого просмотра не
    меняется ни на строку.

    Незнакомая студия ступень не роняет и роняться ей не даёт. Таблица студий
    (:data:`torrcast.domain.studio.STUDIOS`) заведомо неполная: раздача, чью студию мы не
    узнали, встаёт ровно туда же, где стояла бы без всякой памяти, - под ту, что узнали,
    и над ничем. Цена ошибки в одну сторону - прежнее поведение, в другую - слышимая
    подмена, и лестница выбрана в эту сторону.
    """
    if not studio:
        return 0
    want = studio.casefold()
    return 0 if any(known.name.casefold() == want for known in release.studios) else 1
