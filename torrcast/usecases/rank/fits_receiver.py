"""Ступень «приёмник играет раздачу без перекода на ходу»; зовёт порядок меню."""

from __future__ import annotations

from torrcast.domain.profile import CAUTIOUS, Profile
from torrcast.domain.rank_settings import ALIVE_SEEDERS, TRADE_FLOOR
from torrcast.domain.recodes_whole import recodes_whole
from torrcast.domain.release import Release
from torrcast.usecases.rank.bitrate_of import bitrate_of


def fits_receiver(
    release: Release,
    runtime: float,
    recode_at: float,
    heavy_mbit: float,
    profile: Profile = CAUTIOUS,
) -> bool:
    """Битрейт раздачи укладывается в потолок приёмника, а рой и картинка при этом живы.

    Потолок тут не тот, что у ворот отбора (:func:`over_ceiling`), и вопрос другой.
    Ворота спрашивают «сыграет ли это вообще», а ступень - «во что показ обойдётся
    зрителю»: кусок тяжелее ``recode_at`` уезжает на приёмник перекодированным на ходу,
    и платит за это плёнка. На осторожном приёмнике так уходит 616 кусков из 627, все
    616 - по битрейту, и стоит это 59.98 секунды подгрузов за сеанс, из них 35.42 в
    первые 110 секунд. Наружу при этом едет медиана 8.05 Мбит/с, пережатая из 15.65,
    тогда как родная раздача на 9.75 отдала бы больше картинки: чёткость от такого
    выбора не выигрывает, а платит дважды.

    Снизу у ступени пол, и без него она меняла бы перекод на кашу. Условие «легче
    потолка» само по себе бездонно: раздача, названная 1080p, при 0.05 Мбит/с проходит
    его вольготнее честной на 9.5 и встаёт над ней верхом. Зритель получает 1080p по
    паспорту, кашу на экране и ни одной строки об этом. Признак старья
    (:func:`is_dated`) тут не помощник: он верит НАЗВАННОМУ кадру, и у такой раздачи
    старья не находит.

    Пол задан долей, а не Мбит/с (:data:`~torrcast.domain.rank_settings.TRADE_FLOOR`), и
    ``heavy_mbit`` - её знаменатель: битрейт самой тяжёлой раздачи той же группы, ту
    считает :func:`heavy_peers`. Ноль - тяжёлых соседей нет, размена не будет, и пол
    молчит. Почему именно доля, а не число - замер лежит у самого порога: абсолютным
    числом честное от каши не отделить, потому что аниме на 1080p кодируется в те же
    Мбит/с, в которых игровое кино уже каша.

    На корпусе из 100 запросов пол не теряет ни одной из 16 смен, ради которых ступень
    заведена, и не меняет ни одной выбранной раздачи: самый глубокий законный размен -
    0.200, порог 0.13. Отнимает он предпочтение у 13 раздач, и все 13 - рип на
    0.95-2.37 Мбит/с вместо источника на 16.7-23.2. На приставке с её потолком 28 пол
    не срабатывает ни разу: самый глубокий размен там 0.300.

    🔴 Пол - тоже предпочтение, а не отсев. Раздача под полом остаётся кандидатом и
    играется ровно как игралась; ступень лишь перестаёт поднимать её над соседом.

    🔴 Это ПРЕДПОЧТЕНИЕ, а не отсев. Раздача выше потолка остаётся кандидатом и играется
    ровно как игралась: под потолком у картины живого может не быть вовсе, и «не
    нашлось» тут было бы браком, а не честным ответом. Ступень только уводит тяжёлую
    раздачу под равную ей лёгкую.

    Место у неё под звуком и под кадром, и обе границы замерены. Русская дорожка сильнее
    веса: на корпусе из 24 споров, которые ступень решает, дубляж не теряется ни в одном,
    потому что ступень звука стоит выше и спор до неё не доходит. Кадр ступень тоже не
    покупает: она стоит ПОД :func:`is_full_hd`, и живой 1080p остаётся верхом, даже
    когда рядом лежит лёгкий 720p.

    ``recode_at`` - потолок ПРИЁМНИКА, а не отдельное число отбора: у осторожного он
    10.0 Мбит/с, у приставки 28.0, и берётся он оттуда же, откуда его берут показ и
    таблица меню. Ноль - перекодирование выключено, играть тяжёлое всё равно нечем, и
    ступень плоская: порядок в точности прежний.

    Живость роя в условии по той же причине, по которой она стоит у кадра
    (:data:`ALIVE_SEEDERS`): менять перекод на подгрузы незачем, а один-два сида - это
    не рой ни на какой ступени. Порог отсекает ровно те споры, где меняться не на что:
    на корпусе из 24 таких споров 8 идут между двумя мёртвыми раздачами, и в них лёгкая
    сторона не выигрывает ничего. Остаются 16, и рой в них живой: самый бедный, до
    которого ступень опускается, - 6 сидов, самый крутой размен - 30 сидов против 225.

    Кадр на этих шестнадцати не падает ни разу: 14 раздач сменились на равные по
    названному кадру, 2 - на раздачи, чьё имя кадра не называет вовсе, и ни одна не
    ушла с 1080p ниже. Русскую дорожку не теряет ни одна.

    Вес неизвестен - ступень молчит: предпочитать по весу, которого нет, нельзя, а
    настоящий битрейт куска рассудит уже показ.

    🔴 TC-766. Потолок битрейта - не единственное, что у приёмника надо спросить. Раздача,
    которую декодер не берёт ВОВСЕ, укладывается в него вольготнее любой честной и на этой
    ступени вставала верхом: у «Матрицы: Воскрешение» это 9.06 Мбит/с при потолке 10.0, а
    едет она зрителю сплошным перекодом от первой секунды до титров - 888 кусков из 888
    через кодировщик. Ступень, заведённая ради вопроса «во что показ обойдётся зрителю», на
    этом классе отвечала ровно наоборот, и цена ошибки тут не оттенок: сплошной перекод
    занимает процессор целиком, требует из роя ~4.7 МБ/с вместо ~1 и стартует на 3 с позже.

    Спрашивается это у ``profile``, и одним и тем же вопросом, что у показа и прогрева
    (:func:`torrcast.domain.recodes_whole.recodes_whole`): второй список кодеков рядом со ступенью
    разошёлся бы с профилем молча. Имя раздачи для этого вопроса переводится на язык
    профиля (:attr:`Release.named_codec`, :attr:`Release.named_depth`) - названный HEVC и
    названный HDR суть ровно то, чего осторожный декодер не берёт копией.

    Приёмник, который этот кодек играет нативно, ничего не теряет: вопрос задан ЕГО
    профилю, и ответ у него другой. Предпочтением это по-прежнему не является: раздача,
    которую приёмник не декодирует, остаётся кандидатом и играется ровно как игралась -
    под 1080p, где живого нет вовсе, сплошной перекод и есть показ.
    """
    if recode_at <= 0 or release.seeders < ALIVE_SEEDERS:
        return False
    if recodes_whole(release.named_codec, release.named_depth, profile):
        return False
    mbit = bitrate_of(release, runtime)
    return mbit is not None and heavy_mbit * TRADE_FLOOR <= mbit <= recode_at
