Kind = Literal["movie", "tv"]

DEFAULT_STATE_PATH = Path("/var/lib/torrcast/state.json")
DEFAULT_CONFIG_PATH = Path("/etc/torrcast/config.json")

#: Доля длительности, после которой конец показа читается как титры, а не как авария.
#: Мерка щедрая намеренно: ею показ решает, воскрешать ли погасший экран, и сузить её
#: значит начать воскрешать доигранное. Переключением она не заведует: серия доигрывает
#: до конца потока, а доля отвечает только на вопрос «это был конец или обрыв».
WATCHED_RATIO = 0.95


def state_path() -> Path:
    """Путь к файлу состояния с учётом ``TORRCAST_STATE``."""
    return Path(os.environ.get("TORRCAST_STATE") or DEFAULT_STATE_PATH)


def config_path() -> Path:
    """Путь к конфигу с учётом ``TORRCAST_CONFIG``."""
    return Path(os.environ.get("TORRCAST_CONFIG") or DEFAULT_CONFIG_PATH)


@dataclass(slots=True)
class Config:
    """Настройки. Обязателен только ``tv``; остальное имеет рабочие дефолты."""

    tv: str | None = None
    receiver: Literal["chromecast", "mock"] = "chromecast"
    #: Профиль приёмника РУКАМИ (:mod:`torrcast.profile`): ``q70d``, ``androidtv``.
    #:
    #: **Пусто - нормальный режим**: профиль выбирается сам, по паспорту устройства, и
    #: спрашивать об этом человека не надо. Задавать стоит ровно в двух случаях: приёмник
    #: незнакомый, а его пороги уже известны, - или наоборот, хочется прибить осторожный
    #: набор на знакомом. Незнакомое имя тут не ошибка: будет осторожный профиль.
    receiver_profile: str = ""
    torrserver_url: str = "http://127.0.0.1:8090"
    prowlarr_url: str = "http://127.0.0.1:9696"
    prowlarr_apikey: str = ""
    #: Чем раздаём HLS. Дефолт - ``http``: ни серта, ни имени, ни облака в пути потока.
    #: ``https`` - выключенная опция: код жив и работает, но требует серта, которому
    #: доверяет ТВ, а с ним - имени и того, кто это имя выпишет.
    transport: Literal["http", "https"] = "http"
    #: База URL, под которой ТВ забирает HLS. **Пусто - нормальный режим**: адрес
    #: вычисляется по маршруту до ТВ (:func:`torrcast.stream.hls_base`), то есть берётся
    #: тот наш интерфейс, с которого нас видит сам телевизор. DNS в пути показа не
    #: участвует вовсе - упадёт локальный резолвер, каст продолжит играть. Задавать руками
    #: стоит ровно в одном случае: прямой путь почему-то не работает и нужен другой адрес.
    hls_base_url: str = ""
    hls_port: int = 8080
    #: Серт и ключ: нужны только при ``transport: https``.
    hls_cert: str = "/etc/torrcast/tls/torrcast.crt"
    hls_key: str = "/etc/torrcast/tls/torrcast.key"
    #: Сегменты живут в tmpfs - фильм на диск не пишем. Целиком он туда и не влезет: в
    #: каталоге всегда только окно вокруг того места, где смотрят.
    hls_dir: str = "/dev/shm/torrcast"
    #: Темп упаковки - ровно реальное время, а запас впереди приёмника даёт burst.
    #: Пара 1.0/60 держит упаковку на ~минуту впереди показа и не растёт: в
    #: tmpfs всегда ``burst`` + ``hls_keep`` секунд фильма, сколько бы он ни длился.
    #: ⚠️ 1.0 БЕЗ burst дважды вреден, замерено: первый сегмент готов не раньше
    #: своей же длительности (на «Моане 2» ключевые кадры дают ~12 с сегменты → +9 с к
    #: старту), а дальше приёмник идёт вровень с упаковкой и буферится на каждом стыке.
    #: Темп заметно выше единицы (было 1.5) уводит упаковку вперёд без предела - на
    #: двухчасовом фильме это лишний час потока в RAM.
    hls_readrate: float = 1.0
    #: Сколько секунд входа ffmpeg читает на полной скорости, прежде чем встать в темп
    #: (``-readrate_initial_burst``, нужен ffmpeg ≥ 6.1 - его ставит install.sh).
    #: 🔴 Умолчание - осторожный профиль приёмника (:data:`torrcast.profile.CAUTIOUS`);
    #: профиль живого приёмника его перебивает, а написанное сюда руками сильнее профиля
    #: (:func:`torrcast.profile.tune`). Так же читаются и остальные ключи с этой пометкой.
    hls_burst: float = CAUTIOUS.burst
    #: Сколько секунд позади приёмника держим сегменты - это и есть глубина перемотки
    #: назад «без последствий». Глубже - не 404, а перепаковка потока с нужной секунды.
    hls_keep: float = 120.0
    #: Шаг сетки сегментов, секунды. Не «длительность»: с сеткой по опорным кадрам
    #: сегмент длиннее шага на остаток GOP (:class:`torrcast.stream.Grid`).
    #: 🔴 Умолчание - осторожный профиль приёмника.
    hls_segment: float = CAUTIOUS.segment_seconds
    #: Ставить границы сегментов на опорные кадры (нужна карта из mkv). Так каждый кусок
    #: декодируется сам по себе и перемотка в любую точку сразу даёт картинку. ``false`` -
    #: ровная сетка ровно по ``hls_segment``: это режим для замеров, а не для показа.
    hls_keyframes: bool = True
    #: Практический потолок битрейта приёмника, Мбит/с (урок Q70D).
    #:
    #: ⚠️ 16, а не 20: замер на живом Q70D - честный 1080p «Моаны 2» на
    #: 17.8 Мбит/с встаёт в ребуфер раз в 30-60 секунд при полной упаковке впереди, и
    #: каждый такой подвис стоит 8 с пропущенного фильма.
    #:
    #: ⚠️ Это число **не фильтр отбора**: тяжёлые куски перекодируются на лету
    #: (:mod:`torrcast.recode`), поэтому тяжёлый честный 1080p играбелен. Это порог,
    #: ВЫШЕ которого сегмент перекодируют.
    #: Отбраковка релиза живёт в :attr:`bitrate_hard_mbit`.
    #:
    #: 🔴 Умолчание - осторожный профиль приёмника: у приставки Android TV на этом месте
    #: 28 Мбит/с, и там же лежит замер.
    bitrate_warn_mbit: float = CAUTIOUS.warn_mbit
    #: Битрейт, выше которого релиз не берём вовсе, Мбит/с. Это уже не про декодер (его
    #: чинит перекодирование), а про то, что перекодировать пришлось бы весь фильм: и
    #: процессор, и рой должны тянуть это непрерывно, а запаса впрок взять неоткуда.
    #: 25 - вдвое выше практического потолка приёмника: «Моана 2» 13.3 ГБ (19 Мбит/с)
    #: проходит, 4K-ремукс на 49.9 Мбит/с - нет.
    bitrate_hard_mbit: float = 25.0
    #: Потолок отбора, когда файл перекодируется ЦЕЛИКОМ одним прогоном, Мбит/с.
    #:
    #: Выше :attr:`bitrate_hard_mbit` посегментное перекодирование теряет смысл: тяжёл
    #: КАЖДЫЙ кусок, и вместо сотни коротких ffmpeg дешевле один сплошной - тот самый,
    #: которым уже играет HEVC. Отсюда и второй потолок: релиз годен, пока сплошной
    #: перекод успевает за показом.
    #:
    #: 40 - замер на 4 vCPU, живые аниме BD-ремуксы 1080p:
    #: «Shingeki no Kyojin S3 ep.07» 36.4 Мбит/с h264 (37.8 Мбит/с по куску) перекод
    #: ultrafast в 9 Мбит/с идёт 3.36-3.50x реального времени, чтение раздачи из роя
    #: 47.7 МБ/с против нужных 4.7 МБ/с, самый тяжёлый сегмент 13.2 МБ при потолке 16.
    #: HEVC того же веса (30 Мбит/с) - 2.35x. Запас до единицы у h264 3.4x, у HEVC 2.3x;
    #: 40 оставляет его и на менее удачную машину, а 4K-ремукс на 50 Мбит/с по-прежнему
    #: не берётся.
    #:
    #: ⚠️ Потолок ростом кадра НЕ пользуется: 2160p судится прежним
    #: :attr:`bitrate_hard_mbit` (25). Прежнее объяснение («4К в реальное время не
    #: укладывается») замером TC-157 снято - ужатый до 1080p перекод 2160p идёт 1.53×, -
    #: но послабления это не даёт, и вот почему: запас у 4К вдвое тоньше, чем у 1080p
    #: (1.5× против 3.4×), а тянуть из роя надо ровно столько же мегабайт в секунду,
    #: сколько весит релиз. 40 Мбит/с 4К - это 5 МБ/с из роя ПЛЮС декод вчетверо большего
    #: кадра, и запас на такое замером не подтверждён ни разу.
    bitrate_recode_mbit: float = 40.0
    #: Перекодировать тяжёлые куски заранее. ``false`` - тяжёлое просто не берётся,
    #: потолком отбора становится :attr:`bitrate_warn_mbit`.
    recode: bool = True
    #: Битрейт, ВЫШЕ которого сегмент перекодируется, Мбит/с. Отдельно от
    #: :attr:`bitrate_warn_mbit` намеренно: то - потолок ОТБОРА (и он остаётся 16),
    #: а это - замеренная планка приёмника.
    #:
    #: ⚠️ 10, а не 16. Живой Q70D (`scripts/tvprobe.py`, «Моана 2» 13.3 ГБ,
    #: тяжёлый участок 4840...5040 с): при перекодировании в 12 Мбит/с приёмник всё равно
    #: вставал раз в 10-15 с, а сегменты на 13-15 Мбит/с роняли его и без всякого
    #: перекодирования - то есть прежние оценки «потолок между 18 и 22» и даже
    #: опущенная до 16 были завышены. Контроль: «Моана» 2016 на 4 Мбит/с -
    #: 5 опросов BUFFERING из 60, и все на прогреве.
    #:
    #: 🔴 Умолчание - осторожный профиль приёмника.
    recode_at_mbit: float = CAUTIOUS.recode_at_mbit
    #: Во сколько Мбит/с перекодируем тяжёлый кусок. Ниже планки приёмника с запасом.
    #:
    #: ⚠️ 9, а не 12: замер на живом Q70D (тот же участок, 200 с показа). 12 Мбит/с -
    #: 46 опросов BUFFERING, показ прошёл 154 с из 200. 9 Мбит/с - 13 опросов, из них
    #: после прогрева 3, показ прошёл 179 с. 6 Мбит/с - 18 и 3, показ прошёл 177 с, то
    #: есть ниже девяти уже ничего не покупается, а чёткость теряется.
    #:
    #: 🔴 Умолчание - осторожный профиль приёмника. У приставки оно то же, и это не
    #: недосмотр: цель перекода упирается в наш кодировщик, а не в её декодер.
    recode_mbit: float = CAUTIOUS.recode_mbit
    #: Самый качественный пресет libx264, с которого начинает кодировщик. Замер на
    #: 4 vCPU (Xeon E5-2696 v4, 1080p): ``veryfast`` 1.54× реального времени, ``superfast``
    #: 2.62×, ``ultrafast`` 4.36×. Когда до куска остаётся мало времени, кодировщик сам
    #: берёт пресет быстрее (:func:`torrcast.recode.preset_for`).
    recode_preset: str = "veryfast"
    #: Приводить ли HDR-исходник к SDR при сплошном перекоде (:data:`torrcast.recode.TONEMAP`).
    #:
    #: 🔴 TC-223, и выключено оно по ЗАМЕРУ, а не из осторожности. Замер 09-08-2026 на
    #: 4 vCPU, «Матрица» 2160p HEVC 10 бит HDR10 (PQ, BT.2020), тяжёлое место 93 с,
    #: ``ultrafast`` 9 Мбит/с: перекод с одним скейлом до 1080p - 1.34× реального времени,
    #: он же с тонемапом после скейла - 1.00×, тонемап ДО скейла (на 4К) - 0.37×.
    #: То есть тонемап съедает запас скорости целиком: 1.00× - это упаковка вровень с
    #: показом, а рядом ещё работает прогрев, который замерено отнимает 30 %
    #: (:data:`torrcast.recode.NEIGHBOUR_TOLL`). Гейт показа - ноль подгрузов, и он сильнее
    #: цвета: выцветший кадр смотреть можно, стоящий - нельзя.
    #:
    #: ``true`` - включить и посмотреть глазами: механизм готов и работает, цена известна.
    #: Без него HDR-исходник уезжает со СВОИМИ метками (BT.2020/PQ) - как уезжал и раньше:
    #: цвет не преобразован, но и не переклеен на чужой ярлык.
    recode_tonemap: bool = False
    #: Насколько далеко впереди показа работать впрок, секунды фильма. Ограничение не по
    #: времени, а по tmpfs: готовые куски лежат в памяти. Модель показа «Моаны 2»: 300 с
    #: держат пик кэша на 459 МБ и не стоят ни одного опоздания.
    recode_ahead: float = 300.0
    #: Потолок кэша перекодированного, МБ. Достигнут - кодировщик спит, а не растёт.
    recode_cache_mb: float = 384.0
    #: Сколько ждать перекод ПЕРВОГО сегмента показа, секунды (:meth:`Recoder.holding`).
    #:
    #: Первый сегмент - единственный, до которого форы нет вовсе: показ начинается ровно
    #: с него, и уйди он копией - приёмник встаёт в первую же секунду (старт, «Продолжить?»,
    #: перемотка в тяжёлое место). Ждать его не подгруз, а старт: картинки ещё нет.
    #: Ноль - не ждать вовсе.
    #:
    #: 12 с - потолок, а не цена. Цена замерена («Моана 2» 13.3 ГБ, ultrafast,
    #: `nice 0`): v0 длиной 19.96 с - 5.8 с, v45 длиной 19.96 с - 6.0 с, v358 длиной
    #: 16.00 с в самом тяжёлом месте - 9.0 с. То есть **не 2.3 с**, как прикидывалось из
    #: 4.36× и сегмента 10 с: сегменты сетки по опорным кадрам вдвое длиннее, а к чистому
    #: кодированию добавляются подъём ffmpeg и чтение 50-80 МБ из роя.
    #: Просрочен - копия уходит как есть: тяжёлый кусок хуже, чем чёрный экран.
    recode_head_wait: float = 12.0
    #: Прогревать весь фильм на диск фоном (:mod:`torrcast.warm`), чтобы показ переживал
    #: обрыв связи. ``false`` - показ живёт только окном в tmpfs, как раньше.
    warm: bool = True
    #: Где лежит прогретое. **Диск, не tmpfs**: целый фильм в память не влезает.
    warm_dir: str = WARM_DIR
    #: Бюджет диска под всё прогретое, ГБ (:data:`torrcast.warm.WARM_BUDGET`).
    warm_budget_gb: float = WARM_BUDGET / 1e9
    #: Во сколько раз быстрее реального времени идёт прогрев (:data:`torrcast.warm.WARM_RATE`).
    warm_rate: float = 4.0

    @classmethod
    def from_json(cls, data: dict[str, Any]) -> Config:
        """Собрать конфиг из словаря, молча игнорируя незнакомые ключи."""
        return cls(**{k: v for k, v in data.items() if k in cls.__dataclass_fields__})


def load_config() -> Config:
    """Прочитать конфиг; отсутствующий файл — не ошибка, а дефолты."""
    path = config_path()
    if not path.exists():
        return Config()
    try:
        raw: Any = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise TorrcastError(f"битый конфиг {path}: {exc}") from exc
    if not isinstance(raw, dict):
        raise TorrcastError(f"битый конфиг {path}: ожидался объект JSON")
    return Config.from_json(raw)


def save_config(config: Config) -> None:
    """Записать конфиг атомарно, создав каталог при необходимости."""
    _write_atomic(config_path(), asdict(config))


@dataclass(slots=True)
class Entry:
    """Запись состояния: что смотрим, чем и с какого места."""

    title: str
    magnet: str
    kind: Kind = "movie"
    file_idx: int = 0
    audio: int = 0
    #: Память озвучки на эту картину: подпись дорожки
    #: (:attr:`torrcast.stream.AudioTrack.label`), которую пользователь выбрал
    #: **явно** - флагом ``--voice``. Пусто - явного выбора не было.
    #:
    #: Почему подпись, а не номер: номер живёт внутри одного релиза, а память - на
    #: картину. Следующий запуск может взять другую раздачу (сиды меняются, верх отбора
    #: тоже), и «дорожка 4» там будет другой студией. Подпись переживает смену релиза, а
    #: если такой озвучки в новом релизе нет - об этом говорится вслух и берётся дефолт,
    #: причём память НЕ стирается: релиз временный, выбор пользователя - нет.
    #:
    #: Автовыбор сюда не пишет ничего: запоминается только то, что человек назвал сам.
    #: У сериала память общая на сериал - она и лежит в одной записи на всю раздачу.
    voice: str = ""
    pos: float = 0.0
    dur: float = 0.0
    #: Хэш раздачи, которую держит в TorrServer живой показ этой записи (hex, нижний
    #: регистр). Лежит рядом с позицией и по той же причине: спросить живой показ из CLI
    #: нельзя, состояние тут единственный канал.
    #:
    #: 🔴 Пишется в ту же секунду, когда юнит поднял раздачу, и снимается в ту, когда он
    #: её убрал. Смысл ровно один: хозяин раздачи может умереть не по-людски (SIGKILL по
    #: таймауту, паника, перезагрузка), а раздача переживает свой процесс - она живёт в
    #: TorrServer до его перезапуска. Без записанного хэша убрать её потом нечем: после
    #: перезапуска службы своих раздач в её списке не остаётся вовсе (заводим их с
    #: ``save_to_db: false``), а «снести всё из list» снесло бы чужое. Непустое поле при
    #: мёртвом юните - сирота, и
    #: следующий ``cast`` убирает её по этому явному хэшу
    #: (:func:`torrcast.cli._release_orphans`).
    #:
    #: По этой же отметке уборка прогрева параллельного ``cast`` видит, что раздача
    #: чья-то, и не сносит её из-под живого показа (:meth:`State.held`).
    torrent: str = ""
    #: Разрешение, ПОДТВЕРЖДЁННОЕ ffprobe у того файла, который играем
    #: (:attr:`torrcast.stream.Media.quality`). Заявка имени сюда не попадает никогда:
    #: «1080p» в заголовке и 1150×574 внутри - живой случай «Моаны 2», а `cast status`
    #: обязан показывать то, что уехало на ТВ: молчаливых подмен нет. Пусто -
    #: записи прежней версии, о них честно молчим.
    quality: str = ""
    #: Ступень лестницы кадра числом (:attr:`torrcast.stream.Media.frame`) - то же, что
    #: :attr:`quality`, но пригодное для сравнения с порогом.
    #:
    #: 🔴 Лежит рядом с кодеком и глубиной по той же причине: решение «перекодировать файл
    #: целиком» принимается ДО первого сегмента, а кадр в этом решении - последнее слово
    #: (:attr:`torrcast.profile.Profile.recode_frame`). Без него запись, обошедшая отбор
    #: (``--release N``, ``--file N``), уезжала на ТВ и вставала там намертво.
    #:
    #: Ноль - кадр не спрашивали (записи прежних версий). Такая запись своё число
    #: получает на первом же продолжении (:func:`torrcast.cli._duration`) - тем же одним
    #: ffprobe, что и глубину цвета: без него 4К уезжало бы в поток с уровнем «4.1»
    #: (:func:`torrcast.recode.level_for`, TC-251).
    frame: int = 0
    #: Картинка в HDR по паспорту ffprobe (:attr:`torrcast.stream.Media.hdr`): её при
    #: сплошном перекоде надо ещё и привести к SDR (:attr:`Config.recode_tonemap`).
    #:
    #: ``false`` тут значит и «SDR», и «не спрашивали» - разницы нет: тонемап по
    #: умолчанию выключен, и запись прежней версии играется ровно как раньше.
    hdr: bool = False
    #: Битрейт видеодорожки по паспорту ffprobe, Мбит/с. Из него показ знает, сколько
    #: уедет на ТВ, ещё до первого упакованного сегмента - а значит и какие куски
    #: перекодировать. Читается тем же ffprobe, которым выбирается озвучка, и
    #: стоит ноль лишних запросов.
    #:
    #: ``0`` - ещё не спрашивали (запись прежней версии), **отрицательное** - спросили,
    #: и паспорт промолчал (mp4 без тегов mkvmerge). Разница нужна, чтобы молчаливый
    #: паспорт не стоил лишнего ffprobe на каждом запуске.
    vbps: float = 0.0
    #: Кодек видео по паспорту ffprobe (``h264``, ``hevc``). Из него показ знает, играть
    #: видео копией или перекодировать файл целиком (:data:`torrcast.stream.RECODE_CODECS`),
    #: и знает это ДО первого сегмента - решение принимается один раз на файл.
    #:
    #: Пусто - записи прежних версий и те, где паспорт не спрашивали: такие играются
    #: копией, как и раньше, а своё имя кодека получат на первом же обычном запуске.
    codec: str = ""
    #: Глубина цвета видео по паспорту ffprobe, бит (:func:`torrcast.stream.color_depth`).
    #:
    #: 🔴 Лежит рядом с кодеком, потому что кодека для решения НЕ ХВАТАЕТ: десятибитный
    #: H.264 (Hi10P, половина аниме-BDRip) зовётся тем же ``h264``, а приёмник его не
    #: декодирует - доигрывает буфер и встаёт в вечную петлю LOAD/BUFFERING. Решение
    #: «копия или перекод целиком» принимает :func:`torrcast.stream.recodes_whole` по
    #: паре «кодек + глубина», и одинаково у показа и у прогрева.
    #:
    #: ``0`` - не спрашивали (запись прежней версии). Такая запись своё число получает на
    #: первом же продолжении (:func:`torrcast.cli._duration`): одним ffprobe, один раз.
    depth: int = 0
    #: Сколько секунд фильма прогрето на диск (:mod:`torrcast.warm`). Пишет сторож показа,
    #: читает ``cast status`` - только затем и хранится: спросить живой показ из CLI
    #: нельзя, состояние тут единственный канал.
    #:
    #: Число относится к файлу, который играет СЕЙЧАС: прогретое досмотренного показа
    #: стирается с диска тем же выходом, а у следующей серии своё хранилище, - поэтому
    #: переход записи (:meth:`advance`, :meth:`jump`) сбрасывает поле в ноль, и своё
    #: честное число запись получает от сторожа нового показа.
    warm: float = 0.0
    #: Когда показ ПОГАС, стенное время (unix); ``0.0`` - на экране картинка. Пишет
    #: сторож показа, читает ``cast status`` - канал тот же, что у :attr:`warm`, и по той
    #: же причине: спросить живой показ из другого процесса нечем.
    #:
    #: 🔴 Живой юнит показом больше не считается. Пока этой отметки не было, `cast status`
    #: рапортовал «играю» всю темноту до потолка (:data:`torrcast.cli.REVIVE_LIMIT`) -
    #: четверть часа чёрного экрана, про который инструмент говорил, что всё хорошо.
    #:
    #: Время именно стенное, а не монотонное: читает его ДРУГОЙ процесс, а монотонное у
    #: двух процессов разное (:mod:`torrcast.timing`). Отметку ставит и снимает один
    #: писатель - сторож показа, - поэтому гонки на ней нет.
    dark: float = 0.0
    #: Из-за чего погас показ, одной строкой: та же причина, что ушла человеку в консоль
    #: и в недельный след (:meth:`torrcast.cli._Revival._why`). Пусто - темноты нет.
    dark_why: str = ""
    season: int | None = None
    episode: int | None = None
    #: Серии раздачи по порядку: ``[сезон, серия, номер файла]``. Это и есть кэш
    #: выбора: стык серий и прыжок на s2e5 обходятся без Prowlarr и без вопросов.
    episodes: list[list[int]] = field(default_factory=list)
    #: Slug исходного запроса: по нему resume находит запись, не ходя в Prowlarr.
    query: str = ""
    #: Досмотрено. У фильма это конец истории, у сериала - повод взять следующую.
    done: bool = False
    updated: str = ""

    @property
    def ending(self) -> bool:
        """Дошёл ли показ до титров: позиция ≥ 95 % длительности.

        🔴 Мерка не «досмотрено», а «это был конец, а не обрыв», и порогом переключения
        она НЕ является. Серия доигрывает до самого конца, и следующую берёт естественный
        конец потока (:meth:`torrcast.commands.Watch.close`); доля же отвечает на другой
        вопрос - считать ли погасший экран титрами или аварией, которую надо поднимать
        (:meth:`torrcast.playback_revival._Revival.resurrect`). Поэтому она щедрая: сузишь
        её - и обычный конец начнёт читаться как смерть, а показ полезет воскрешать
        доигранное. Она же и страховка: приёмник, который залип на последнем куске или
        молча ушёл в IDLE, кончает сеанс не сам, а по терпению - и переход всё равно
        случается, потому что позиция к этому времени давно за долей.
        """
        return self.dur > 0 and self.pos >= self.dur * WATCHED_RATIO

    @property
    def resumable(self) -> bool:
        """Есть ли что продолжать: недосмотренный прогресс."""
        return self.pos > 0 and not self.done

    @property
    def serial(self) -> bool:
        """Правда ли это сериал: тип ``tv`` и в раздаче **несколько** серий.

        Одна серия в списке — это не сериал, а осечка разбора: так в состоянии осталась
        «Moana 2», которую ``x264`` в имени сделал s1e1. Парсер починен, но записи-то
        остались, и строки «Серии: серий 1: s1e1…s1e1» в выводе фильма быть не должно
        ни у кого. Настоящей раздаче с одной серией это ничего не стоит: переходить
        всё равно некуда.
        """
        return self.kind == "tv" and len(self.episodes) > 1

    @property
    def label(self) -> str:
        """Подпись серии ``s1e2``; у фильма — пусто."""
        if not self.serial or self.season is None or self.episode is None:
            return ""
        return f"s{self.season}e{self.episode}"

    def where(self, season: int, episode: int) -> int:
        """Место серии в списке серий раздачи; ``-1`` — такой серии в раздаче нет."""
        for at, item in enumerate(self.episodes):
            if len(item) >= 2 and item[0] == season and item[1] == episode:
                return at
        return -1

    def jump(self, season: int, episode: int) -> Entry | None:
        """Прыжок на серию в пределах уже выбранной раздачи: ни поиска, ни вопросов.
        Серии в раздаче нет — ``None``, и цепочка честно идёт искать релиз нужного сезона.
        """
        at = self.where(season, episode)
        if at < 0:
            return None
        return self._go(at)

    def advance(self) -> Entry:
        """Что записать по достижении порога перехода: фильму — пометка «досмотрено» и
        сброс позиции (следующий ``cast`` начнёт сначала), сериалу — следующая серия
        раздачи с нуля, выбор релиза и дорожки при этом сохраняется. Серия была
        последней — «досмотрено» и для сериала: конец сезона или конец раздачи.

        Прогрев (``warm``) переход не переживает: досмотренному его стирает с диска
        сам выход показа, а прогретое следующей серии лежит в своём хранилище и своё
        число придёт от её сторожа - чужое здесь было бы враньём наружу. Отметка темноты
        (``dark``) не переживает по той же причине: она про экран, который погас на
        ПРОШЛОМ файле.
        """
        at = self.where(self.season or 0, self.episode or 0)
        if self.kind == "tv" and 0 <= at < len(self.episodes) - 1:
            return self._go(at + 1)
        return replace(self, pos=0.0, done=True, warm=0.0, dark=0.0, dark_why="")

    def _go(self, at: int) -> Entry:
        """Встать на серию номер ``at`` списка: новый файл, позиция, длительность,
        прогрев и отметка темноты с нуля - всё это относится к файлу, а файл теперь
        другой."""
        season, episode, file_idx = self.episodes[at][:3]
        return replace(
            self,
            season=season,
            episode=episode,
            file_idx=file_idx,
            pos=0.0,
            dur=0.0,
            done=False,
            warm=0.0,
            dark=0.0,
            dark_why="",
        )

    def touch(self) -> Entry:
        """Копия записи со свежей меткой времени."""
        return replace(self, updated=datetime.now(UTC).astimezone().isoformat())

    @classmethod
    def from_json(cls, data: dict[str, Any]) -> Entry:
        fields = {k: v for k, v in data.items() if k in cls.__dataclass_fields__}
        raw = fields.get("episodes")
        if isinstance(raw, list):  # битую строку списка серий лучше потерять, чем упасть
            fields["episodes"] = [
                [int(n) for n in item[:3]]
                for item in raw
                if isinstance(item, list) and len(item) >= 3
            ]
        return cls(**fields)


@dataclass(slots=True)
class State:
    """Состояние целиком: ключ ``<тип>:<slug>:<год>`` → :class:`Entry`."""

    entries: dict[str, Entry] = field(default_factory=dict)

    @classmethod
    def load(cls) -> State:
        """Прочитать состояние; отсутствующий или битый файл — пустое состояние."""
        try:
            raw: Any = json.loads(state_path().read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return cls()
        if not isinstance(raw, dict):
            return cls()
        return cls({str(k): Entry.from_json(v) for k, v in raw.items() if isinstance(v, dict)})

    def save(self) -> None:
        _write_atomic(state_path(), {k: asdict(v) for k, v in self.entries.items()})

    def get(self, key: str) -> Entry | None:
        return self.entries.get(key)

    def find(self, query: str) -> tuple[str, Entry] | None:
        """Запись по запросу пользователя, без похода в Prowlarr: сравниваем slug
        запроса с сохранённым запросом и со slug'ом в ключе; несколько — берём свежайшую.

        Запись, которая отвечает на другой вопрос, отсюда не возвращается вовсе
        (:func:`_other_part`): продолжать можно ту картину, которую назвали.
        """
        from torrcast.parse import slugify

        want = slugify(query)
        if not want:
            return None
        hits = [(k, e) for k, e in self.entries.items() if want in {e.query, _slug(k)}]
        # Сериал зовут коротко: «киберпанк» вместо «киберпанк бегущие по краю».
        # Фильму так нельзя: «матрица» - это запрос франшизы, а не «Матрица: Перезагрузка».
        hits = hits or [
            (k, e) for k, e in self.entries.items() if e.kind == "tv" and _slug(k).startswith(want)
        ]
        hits = [(k, e) for k, e in hits if not _other_part(query, want, k, e)]
        return max(hits, key=lambda item: item[1].updated) if hits else None

    def latest(self) -> tuple[str, Entry] | None:
        """Самая свежая запись — то, что показывает ``cast status``."""
        return max(self.entries.items(), key=lambda item: item[1].updated, default=None)

    def held(self) -> set[str]:
        """Хэши раздач, которые сейчас кто-то держит: непустой :attr:`Entry.torrent`.

        Счётчик владения по хэшу вырождается в множество: двух живых показов не бывает
        по устройству - юнит ``torrcast-play`` один на всю систему, и новый ``cast`` гасит
        прежний до своего старта (:func:`torrcast.stream.start_play_unit`). Поэтому
        раздача либо чья-то, либо ничья, и спрашивать «сколько держат» не приходится.

        Читает это уборка прогрева параллельного ``cast``: записанное сносить нельзя -
        это выдернет раздачу из-под живого показа. Гонки на записи тут нет, потому что
        писать нечего: операция одна, чтение, а отметку ставит и снимает один юнит.
        """
        return {entry.torrent for entry in self.entries.values() if entry.torrent}

    def showing(self) -> tuple[str, Entry] | None:
        """Показ, который идёт на приёмнике прямо сейчас, или ``None``.

        Признак тот же, что у :meth:`held`, - непустой :attr:`Entry.torrent`: отметку
        ставит юнит показа в ту же секунду, когда поднял раздачу, и снимает, когда её
        убрал. Двух живых показов не бывает по устройству, поэтому запись тут не больше
        одной; на всякий случай берётся свежайшая.

        🔴 Приёмник об этом НЕ спрашивается, и это правило, а не экономия: у всех
        соединений pychromecast один ``source_id``, поэтому второй опрашивающий процесс
        неотличим от владельца сессии и гасит живой показ
        (:class:`torrcast.cast.ChromecastReceiver`). Занятость телевизора мы знаем из
        своего состояния или не знаем вовсе.

        ⚠️ Чего этот признак НЕ видит: показ, убитый ``SIGKILL``, оставляет хэш записанным
        и выглядит отсюда живым. Разбирает такие сироты :func:`torrcast.cli._release_orphans`
        (он спрашивает systemd, а не приёмник) - и зовётся он до этой проверки.
        """
        live = [(key, entry) for key, entry in self.entries.items() if entry.torrent]
        return max(live, key=lambda item: item[1].updated) if live else None

    def put(self, key: str, entry: Entry) -> None:
        """Положить запись, обновив метку времени."""
        self.entries[key] = entry.touch()

    def drop(self, key: str) -> None:
        """Забыть запись (``--new``)."""
        self.entries.pop(key, None)

    def __iter__(self) -> Iterator[tuple[str, Entry]]:
        return iter(self.entries.items())


def _slug(key: str) -> str:
    """Slug канонического названия из ключа ``<тип>:<slug>:<год>``."""
    return key.split(":")[1] if ":" in key else ""


def _other_part(query: str, want: str, key: str, entry: Entry) -> bool:
    """Запись - другая часть франшизы, а не та картина, которую назвали.

    🔴 Сохранённая позиция отвечает на вопрос «где я остановился», а не «какую картину я
    прошу», - и стоять в очереди решений она обязана после выбора картины, а не перед
    ним. Записывается же рядом с позицией ТЕКСТ запроса (:attr:`Entry.query`), а он у
    имени франшизы общий на всю линейку: «Тачки 3», однажды выбранные по запросу «тачки»,
    отвечали потом на каждое «тачки» - молча, вопроса про картину не задавалось вовсе.
    Другое кино под знакомым именем - ровно та подмена, которой отбор не делает нигде
    (:func:`torrcast.choice.part_one_swap`), и продолжение делать её тоже не вправе.

    Спрашивается при этом НОМЕР, а не имя: имя у записи и у запроса живут на разных
    языках («Moana 2» под запросом «моана 2»), а номер части один на оба
    (:func:`~torrcast.parse.split_franchise_index`). Названный номер сошёлся с номером
    записи - назвали её и есть; номера нет ни там, ни там - речь об одной картине, и
    продолжение идёт как раньше. «Аполлон 13» на запрос «аполлон 13» тоже проходит:
    там номер назван, и он тот же самый.

    Имя остаётся запасной сверкой для записей, чей номер разбор в запросе не увидел:
    «моана-2» - это уже slug, пробела перед цифрой в нём нет.

    Сериала это правило не касается вовсе: его зовут коротко нарочно (:meth:`State.find`),
    и число в его названии - сезон, а не соседняя картина. «Кухня 6» на запрос «кухня»
    продолжает следующую невиденную серию, как и продолжала.

    Закладка при этом не теряется: у выбранной картины её предложат внутри
    (:func:`torrcast.cli._continue_picked`).
    """
    from torrcast.parse import slugify, split_franchise_index

    if entry.serial:
        return False
    part = split_franchise_index(entry.title)[1]
    if part is None or part == 1 or part == split_franchise_index(query)[1]:
        return False
    return want not in {_slug(key), slugify(entry.title)}


def _write_atomic(path: Path, payload: dict[str, Any]) -> None:
    """Записать JSON во временный файл рядом и переименовать поверх цели."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    tmp = Path(tmp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n")
            handle.flush()
            os.fsync(handle.fileno())
        tmp.replace(path)
    except OSError as exc:
        tmp.unlink(missing_ok=True)
        raise TorrcastError(f"не смог записать {path}: {exc}") from exc
