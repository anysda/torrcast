#: Каталог прогретого по умолчанию. Диск, не tmpfs - и это весь смысл модуля.
WARM_DIR: Final = "/var/lib/torrcast/warm"
#: ``TORRCAST_WARM=<каталог>`` - куда греть вместо настроенного места. Того же рода
#: переопределение, что ``TORRCAST_STATE`` и ``TORRCAST_CONFIG``: тестовый прогон не имеет
#: права ни писать в боевое хранилище, ни вытеснять из него чужое по бюджету.
WARM_ENV: Final = "TORRCAST_WARM"
#: Бюджет диска под всё прогретое, байты. Худший замеренный вечер требует 28 ГБ;
#: оставшиеся 2 ГБ - запас ошибки прогноза. Это десятичные ГБ, как в конфиге, щупе и
#: сообщениях :meth:`Vault.fit`.
WARM_BUDGET: Final = 30_000_000_000
#: Сколько места на диске не трогаем ни при каких обстоятельствах, байты. Бюджет считается
#: по нашим же файлам, а рядом живут чужие: упереть раздел в ноль прогревом нельзя.
FREE_FLOOR: Final = 3 << 30
#: Во сколько раз быстрее реального времени читает прогрев. Не «во весь опор»: прогрев
#: тянет из того же TorrServer, что и живая упаковка, и полная скорость отбирала бы у неё
#: и полосу, и кэш раздачи. Вчетверо - это 24-минутная серия за 6 минут и двухчасовой
#: фильм за полчаса, при этом живому окну остаётся втрое больше полосы, чем оно берёт.
WARM_RATE: Final = 4.0
#: ``nice`` прогрева: перекодирование впрок не имеет права отобрать процессор у показа.
WARM_NICE: Final = 19
#: Запас живого показа, ниже которого прогрев замирает, секунды.
GUARD_LOW: Final = 25.0
#: Запас, выше которого замерший прогрев оживает сразу. Разведены с :data:`GUARD_LOW`
#: намеренно: без гистерезиса прогрев дёргался бы стоп/старт на каждом опросе.
GUARD_HIGH: Final = 45.0
#: Сколько запас держится **над** :data:`GUARD_LOW`, прежде чем замерший прогрев оживает,
#: не дождавшись :data:`GUARD_HIGH`, секунды. Нужно ровно для тесного, но здорового показа:
#: когда смотрят вплотную за упаковкой, запас плавает у :data:`GUARD_LOW` и до
#: :data:`GUARD_HIGH` не дотягивает никогда - без этой поблажки прогрев голодал бы вечно и
#: "прогрета целиком" не наступало бы, а следующая серия так и не бралась в работу
#: (:meth:`Warmer._chain`). Отмеряем именно ВЫДЕРЖКУ над порогом стопа, а не разовое
#: касание: показ должен доказать, что запас и правда восстановился, а не мигнул. При
#: реально просевшем запасе (ниже :data:`GUARD_LOW`) выдержка обнуляется и прогрев стоит -
#: живой показ всегда важнее.
STARVE_GRACE: Final = 6.0
#: Сколько прогрев ждёт запаса живого показа, прежде чем начать работать несмотря ни на
#: что (:meth:`Warmer._wait_for_picture`), секунды.
START_GRACE: Final = 45.0
#: Через сколько секунд прогрев спрашивает следующую серию заново, если собрать её не
#: вышло (:meth:`Warmer._chain`), секунды.
#:
#: Сборка следующей серии - два вопроса к раздаче (паспорт файла и карта опорных кадров),
#: и посреди обрыва связи их некому задать. Замер на стенде: обрыв на 10-й секунде, сеть
#: вернулась на 194-й, показ шёл ещё 526 с здоровой сети - и следующая серия не получила
#: НИ ОДНОГО куска, потому что спросить её пробовали ровно один раз. Отсюда и повтор: пока
#: показ жив, сеть может вернуться, а стык серий без страховки оставлять нельзя.
CHAIN_RETRY: Final = 30.0
#: Файл-паспорт прогретого показа внутри его каталога.
META: Final = "warm.json"
#: Каталог прогона ffmpeg внутри каталога прогретого (см. :data:`torrcast.stream.PACK_DIR`).
RUN_DIR: Final = "run"
#: Насколько уложенный кусок вправе начаться РАНЬШЕ своей границы, секунды
#: (:meth:`Warmer._verify`). Порог отмерен от кадра, а не от нуля: у самого медленного
#: кино (23.976 к/с) кадр - это 41.7 мс, штатный преролл PCR у mpegts-муксера - около
#: 40 мс, и ``-segment_time_delta`` разрешает резать на 20 мс раньше границы
#: (:data:`torrcast.stream.SPLIT_SLACK`). Всё вместе - меньше сотой доли секунды сверх
#: кадра; берём с запасом. Дефект, ради которого сторож написан, давал 1.4-3.8 с, то есть
#: на порядок больше порога: сторож ловит поломку, а не дрожание меток.
SKEW_MAX: Final = 0.15
#: Сколько раз одно и то же место перепаковывается, прежде чем его признают непрогретым.
#: Один повтор: заход, вставший не туда, кладёт мимо сетки ВЕСЬ свой участок, и второй
#: такой же промах на том же месте - это не случайность, а поломка упаковки.
SKEW_TRIES: Final = 2
#: Сколько байт головы куска читает сверка. Пакет TS - 188 байт, PAT, PMT и первый пакет
#: видео лежат в самом начале файла; 64 КиБ - это 348 пакетов, то есть запас в сотню раз.
#: Больше читать нельзя: сверка идёт на пути укладки, а куски весят мегабайты.
HEAD_BYTES: Final = 64 << 10
#: Размер пакета MPEG-TS и его байт синхронизации.
TS_PACKET: Final = 188
TS_SYNC: Final = 0x47
#: Часы MPEG: 90 кГц у меток PES, 27 МГц у PCR.
PES_CLOCK: Final = 90_000.0
PCR_CLOCK: Final = 27_000_000.0


def segment_start(path: Path) -> float:
    """С какой секунды ФИЛЬМА кусок начинается на самом деле; ``nan`` - не прочли.

    Читается голова уже лежащего файла, и только она: ни ffprobe, ни ffmpeg, ни единого
    обращения к раздаче. Причина не в красоте, а в месте вызова - сверка стоит на пути
    укладки куска (:meth:`Warmer._verify`), рядом с показом, и не имеет права ни ждать
    сеть, ни поднимать процесс. Замер на куске 2.7 МБ: 0.04-0.10 мс, когда кусок только что
    записан и лежит в кэше страниц (это и есть штатный случай - сверяем сразу после
    укладки), и 0.4 мс с холодного диска против 20-40 мс у одного ``ffprobe``.

    Берётся PTS первого пакета видео. Именно PTS, а не DTS: граница сетки стоит на опорном
    кадре, а карта опорных кадров (:mod:`torrcast.keymap`) хранит их ВРЕМЯ ПОКАЗА. У релиза
    с B-кадрами DTS того же кадра лежит на кадр-другой раньше PTS, и сверка по DTS видела
    бы этот зазор как расхождение. Метки абсолютные - это ``-copyts`` у обоих упаковщиков
    (:func:`torrcast.stream.ffmpeg_pack_command`), поэтому PTS и есть время фильма.

    PCR - запасной ответ: если в голове файла пакета видео с меткой не нашлось, начало
    берётся по часам транспорта. Он на преролл муксера раньше PTS, и порог
    (:data:`SKEW_MAX`) этот преролл вмещает.

    ``nan`` - честное «не знаю»: файл не читается, не выровнен по пакетам TS или меток в
    голове нет вовсе. Гадать тут нельзя ни в одну сторону: сторож на догадке выбрасывал бы
    здоровые куски.
    """
    try:
        with path.open("rb") as handle:
            head = handle.read(HEAD_BYTES)
    except OSError:
        return math.nan
    pcr = math.nan
    for at in range(0, len(head) - TS_PACKET + 1, TS_PACKET):
        packet = head[at : at + TS_PACKET]
        if packet[0] != TS_SYNC:
            return math.nan  # файл не выровнен по пакетам - разбирать нечего
        payload = 4
        control = (packet[3] >> 4) & 0x3
        if control & 0x2:  # есть поле адаптации, а в нём может лежать PCR
            length = packet[4]
            if length >= 7 and packet[5] & 0x10 and math.isnan(pcr):
                base = (int.from_bytes(packet[6:10], "big") << 1) | (packet[10] >> 7)
                pcr = (base * 300 + (((packet[10] & 0x1) << 8) | packet[11])) / PCR_CLOCK
            payload = 5 + length
        if not control & 0x1 or payload + 14 > TS_PACKET or not packet[1] & 0x40:
            continue  # без содержимого, без места под заголовок PES или не начало PES
        pes = packet[payload:]
        if pes[:3] != b"\x00\x00\x01" or not 0xE0 <= pes[3] <= 0xEF or not pes[7] & 0x80:
            continue  # не видео или пакет без PTS
        return _stamp(pes[9:14])
    return pcr


def _stamp(raw: bytes) -> float:
    """Метка PES (33 бита вперемешку с маркерами) в секундах."""
    ticks = (
        ((raw[0] >> 1) & 0x7) << 30
        | raw[1] << 22
        | ((raw[2] >> 1) & 0x7F) << 15
        | raw[3] << 7
        | raw[4] >> 1
    )
    return ticks / PES_CLOCK


def warm_root(configured: str = WARM_DIR) -> Path:
    """Каталог прогретого с учётом :data:`WARM_ENV`."""
    return Path(os.environ.get(WARM_ENV) or configured or WARM_DIR)


def warm_key(
    source: str, audio: int, grid: Grid, encode: Any = None, spots: tuple[int, ...] = ()
) -> str:
    """Ключ каталога прогретого: один и тот же показ — один и тот же ключ.

    В ключ входит всё, от чего зависит СОДЕРЖИМОЕ сегмента: раздача с номером файла
    (это уже есть в ``source``), звуковая дорожка, сетка и то, чем кодируем видео.
    Разошлось хоть что-то — ключ другой, и прогретое прошлого прогона не подсунется
    под чужие имена. Это дешевле и честнее, чем сверять паспорта: чужой каталог просто
    не находится, а его уберёт бюджет по давности.

    ⚠️ ``mark`` у перекода - это кадр и цвет наружу (:attr:`torrcast.recode.Encode.mark`),
    и в ключе он не для полноты. Один и тот же файл под разными приёмниками ужимается
    по-разному (потолок кадра - свойство приёмника), а сегменты у них при этом одного
    имени и одного веса: разойдись ключ - показ подсунул бы 1080p-куски туда, где сам
    режет 720p. На неужатом показе строка пустая, то есть ключи прежних прогонов ключами
    и остаются.
    """
    parts = [
        source,
        f"a{audio}",
        f"g{grid.count}:{grid.duration:.3f}:{grid.on_keys:d}",
        "" if encode is None else f"e{encode.preset}:{encode.mbit:.2f}{encode.mark}",
        # Точечно перекодированные куски - тоже содержимое каталога: сменился список
        # тяжёлых мест (другой порог, другой профиль тяжести) - каталог другой.
        "" if not spots else f"s{len(spots)}:{spots[0]}:{spots[-1]}",
    ]
    return hashlib.sha1("|".join(parts).encode("utf-8")).hexdigest()[:16]


@dataclass(slots=True)
class Vault:
    """Каталог прогретого одного показа и бюджет диска на всех.

    Читается отсюда напрямую: показ отдаёт приёмнику файл из этого каталога, не копируя
    его в tmpfs (:meth:`torrcast.stream.Feed.segment`). Копия стоила бы памяти ровно там,
    где её и не хватает.
    """

    root: Path
    key: str
    budget: int = WARM_BUDGET
    #: Сколько байт раздела не трогаем ни при каких обстоятельствах (:data:`FREE_FLOOR`).
    floor: int = FREE_FLOOR
    title: str = ""
    #: Чужие ключи, которые бюджет вытеснять не имеет права: серия, которую смотрят
    #: прямо сейчас, для прогрева следующей - чужой каталог (:meth:`fit`). Без этого
    #: прогрев следующей серии выедал бы текущую и обрыв связи убивал бы показ ровно
    #: там, где его и должно было спасти прогретое.
    keep: frozenset[str] = frozenset()

    @property
    def dir(self) -> Path:
        return self.root / self.key

    def path(self, slot: int) -> Path:
        from torrcast.stream import segment_name

        return self.dir / segment_name(slot)

    def have(self, slot: int) -> bool:
        return self.path(slot).exists()

    def spot(self, slot: int) -> Path:
        """Метка «этот кусок уже перекодирован точечно», а не скопирован.

        Отдельный пустой файл рядом с куском, а не поле в паспорте: прогрев переживает
        снятие показа на любом месте, и после перезапуска надо знать поштучно, что уже
        сделано. Имя не подходит под ``v*.ts``, поэтому ни :meth:`slots`, ни вес каталога
        его не видят.
        """
        return self.dir / f"v{slot}.rec"

    def slots(self, cap: int = 0) -> set[int]:
        """Что уже прогрето. Читается глобом: другого источника правды тут нет и не надо.

        ``cap`` - потолок веса куска у приёмника: тогда считаются только те куски, которые
        показ и правда возьмёт с диска (:meth:`torrcast.stream.Feed._warm`). Ноль - всё, что
        лежит: прогреву решать, куда идти дальше, надо по файлам (:meth:`Warmer._missing`),
        иначе тяжёлое место перекладывалось бы вечно.
        """
        from torrcast.stream import segment_slot

        found: set[int] = set()
        with contextlib.suppress(OSError):
            for path in self.dir.glob("v*.ts"):
                slot = segment_slot(path.name)
                if slot < 0 or (cap > 0 and _size(path) > cap):
                    continue
                found.add(slot)
        return found

    def open(self) -> None:
        """Завести каталог и паспорт. Паспорт нужен ровно бюджету: по его времени
        изменения считается давность показа (:meth:`fit`)."""
        self.dir.mkdir(parents=True, exist_ok=True)
        self.touch()

    def touch(self) -> None:
        with contextlib.suppress(OSError):
            (self.dir / META).write_text(
                json.dumps({"key": self.key, "title": self.title, "at": time.time()}),
                encoding="utf-8",
            )

    def size(self) -> int:
        return _weigh(self.dir)

    def clear(self) -> None:
        """Показ досмотрен (или брошен насовсем) — прогретое стирается целиком."""
        shutil.rmtree(self.dir, ignore_errors=True)

    def free(self) -> int:
        """Сколько байт свободно на разделе прогрева."""
        try:
            stat = os.statvfs(self.root)
        except OSError:
            return 0
        return stat.f_bavail * stat.f_frsize

    def fit(self, need: int) -> str:
        """Место под ещё ``need`` байт: пусто — нашлось, иначе честная причина отказа.

        Бюджет один на всё прогретое, а не на показ: два фильма подряд не должны
        сложиться в сорок гигабайт. Вытесняются **чужие** каталоги, начиная с самого
        давнего, - свой не трогаем никогда, иначе прогрев съедал бы сам себя. Не свой,
        но и не чужой - :attr:`keep`: соседняя серия того же показа.

        Причин отказа две, и путать их нельзя: наш бюджет и чужое место на разделе.
        Рядом живут и состояние, и раздача, и система — упереть раздел в ноль прогревом
        не имеет права ни один бюджет.
        """
        mine = {self.key, *self.keep}
        others = sorted(
            (path for path in _dirs(self.root) if path.name not in mine),
            key=_touched,
        )
        while others and _weigh(self.root) + need > self.budget:
            gone = others.pop(0)
            # Вес и имя снимаем ДО сноса: после ``rmtree`` сказать, что именно и на сколько
            # освободили, уже не по чему, а в ленте это и есть вся ценность записи.
            trace.evict(key=gone.name, freed=_weigh(gone), need=int(need), title=_title(gone))
            shutil.rmtree(gone, ignore_errors=True)
        if need > self.budget - _weigh(self.root):
            return f"бюджет диска {self.budget / 1e9:.0f} ГБ исчерпан"
        if need + self.floor > self.free():
            return f"на разделе свободно {self.free() / 1e9:.1f} ГБ - это последний запас"
        return ""


def _dirs(root: Path) -> list[Path]:
    try:
        return [path for path in root.iterdir() if path.is_dir()]
    except OSError:
        return []


def _touched(path: Path) -> float:
    try:
        return (path / META).stat().st_mtime
    except OSError:
        return 0.0


def _title(path: Path) -> str:
    """Название вытесняемого показа из его паспорта; нет паспорта - пустая строка."""
    with contextlib.suppress(OSError, ValueError):
        found = json.loads((path / META).read_text(encoding="utf-8"))
        if isinstance(found, dict):
            return str(found.get("title", ""))
    return ""


def _size(path: Path) -> int:
    """Вес файла; не прочли - ноль. Ноль тут безопасен: кусок, пропавший между глобом и
    ``stat``, отдача уже переживает (404 → приёмник просит снова)."""
    try:
        return path.stat().st_size
    except OSError:
        return 0


def _weigh(where: Path) -> int:
    total = 0
    with contextlib.suppress(OSError):
        for path in where.rglob("v*.ts"):
            with contextlib.suppress(OSError):
                total += path.stat().st_size
    return total


@dataclass(slots=True)
class Warmer:
    """Фоновый прогрев всего фильма на диск (:class:`Vault`).

    Порядок работы: сначала вперёд от места, откуда начали смотреть, — это то, что
    понадобится раньше всего, — потом голова фильма, если начали с середины. Внутри
    каждого куска работы это ОДИН прогон ffmpeg от края до края (см. заголовок модуля).
    """

    source: str
    audio: int
    grid: Grid
    vault: Vault
    #: Чем кодировать видео (:class:`torrcast.recode.Encode`); ``None`` - копия.
    #:
    #: 🔴 Ставится ТЕМ ЖЕ решением, что у живой упаковки (:func:`torrcast.cli._warmer`).
    #: Прогретый кусок и живой - это одна лента для приёмника, и если они закодированы
    #: по-разному, на стыке источников у него меняется SPS.
    encode: Any = None
    #: Слоты, которые живой показ отдаёт перекодированными поштучно (тяжёлые куски,
    #: :attr:`torrcast.recode.Recoder.targets`). Прогрев обязан положить на диск их же и
    #: такими же: копия тяжёлого куска приёмнику не по зубам, а перекод всего фильма ради
    #: пяти кусков расходится с живой упаковкой во всём остальном.
    spots: tuple[int, ...] = ()
    #: Чем перекодировать :attr:`spots` - тот же :class:`torrcast.recode.Encode`, которым
    #: их берёт живой кодировщик.
    spot_encode: Any = None
    #: С какого места смотрим: прогрев идёт отсюда вперёд, голова - потом.
    began_at: int = 0
    #: Потолок веса одного куска у приёмника, байты
    #: (:attr:`torrcast.profile.Profile.max_segment_bytes`). Прогреву он нужен не для
    #: укладки, а для счёта: тяжелее потолка показ прогретое с диска не берёт
    #: (:meth:`torrcast.stream.Feed._warm`), и запасом такой кусок не является.
    cap: int = CAUTIOUS.max_segment_bytes
    rate: float = WARM_RATE
    nice: int = WARM_NICE
    log: Any = None
    #: Запас живого показа, секунды; кладёт :func:`torrcast.cli._hold` на каждом опросе.
    slack: float = 0.0
    #: Кодировщик живых кусков (:class:`torrcast.recode.Recoder`) или ``None``. Пока у него
    #: идёт заход, прогрев замирает: см. :meth:`_must_yield`.
    rival: Any = None
    #: Прогрев замер под просевшим запасом (:data:`GUARD_LOW`).
    idle: bool = False
    #: С какого момента (монотонные секунды) запас держится над :data:`GUARD_LOW`, пока
    #: прогрев замер; ``0.0`` - ещё не поднялся или прогрев не замирал. По этой выдержке
    #: тесный, но здоровый показ оживляет прогрев, не дожидаясь :data:`GUARD_HIGH`
    #: (:meth:`_may_resume`).
    healthy_since: float = 0.0
    #: Почему прогрев дальше не идёт: бюджет диска, мёртвый источник, место, которое не
    #: легло на сетку, тяжёлые места копией, которые перекодировать нечем. Пусто - идёт.
    trouble: str = ""
    stopped: bool = False
    thread: Any = None
    packer: Any = None
    lock: Any = field(default_factory=threading.Lock)
    #: Сколько прогонов оборвалось само (сеть). Считается ради честной строки, не ради лимита.
    breaks: int = 0
    #: Чем продолжить, когда эта серия ляжет на диск целиком: фабрика прогрева следующей
    #: серии (``() -> Warmer | None``) или ``None`` - продолжать нечем.
    #:
    #: Фабрика, а не готовый прогрев: следующей серии нужны и паспорт, и карта опорных
    #: кадров, а это запросы к рою, которые не имеют права идти, пока грузится текущая.
    #: Зовётся ровно один раз и ровно тогда, когда текущая серия уже не нуждается в сети.
    follow: Any = None
    #: Прогрев следующей серии, поднятый :meth:`_chain`; ``None`` - ещё не поднимали.
    after: Warmer | None = None
    #: Через сколько секунд спрашивать следующую серию заново, когда собрать её не вышло
    #: (:data:`CHAIN_RETRY`). Полем, а не константой, ради тестов: они проверяют повтор,
    #: а не ожидание.
    chain_retry: float = CHAIN_RETRY
    #: Сколько раз каждое место уже легло мимо сетки (:meth:`_verify`). Ключ - слот.
    skews: dict[int, int] = field(default_factory=dict)
    #: Слот, который прямо сейчас лёг мимо сетки; ``-1`` - прогон идёт ровно. По нему
    #: :meth:`_run` обрывает заход: промахнулся один кусок - промахнулся весь заход.
    misgrid: int = -1

    def start(self) -> None:
        self.vault.open()
        self.thread = threading.Thread(target=self._work, daemon=True, name="torrcast-warm")
        self.thread.start()

    def stop(self) -> None:
        """Снять прогрев. Прогретое **не трогаем**: показ может продолжиться завтра."""
        self.stopped = True
        with self.lock:
            packer, self.packer = self.packer, None
        if packer is not None:
            packer.stop(keep_files=True, reason="показ окончен")
        if self.after is not None:
            self.after.stop()

    def feed(self, slack: float) -> None:
        """Запас живого показа - прогреву и его продолжению (:meth:`_throttle`).

        Число одно на всю цепочку: и прогрев этой серии, и прогрев следующей тянут из той
        же раздачи и жгут тот же процессор, поэтому проседание показа обязано ронять оба.
        """
        self.slack = slack
        if self.after is not None:
            self.after.feed(slack)

    @property
    def warmed(self) -> float:
        """Сколько секунд фильма показ может взять с диска.

        Считается не «сколько лежит», а «что возьмут»: копия тяжелее потолка приёмника
        наружу не идёт (:meth:`torrcast.stream.Feed._warm`), под таким местом работает живая
        упаковка - значит, обрыва связи оно не переживёт и запасом не является. Тяжёлое
        место входит в счёт, когда прогрев приведёт его к перекоду (:meth:`_spots_left`),
        то есть к тому же виду, в котором его отдаёт показ.

        Замер, ради которого счёт такой («Тачки» 2006, 1080p): тяжелее потолка 38 % кусков,
        и число называло запас, которого у человека нет.
        """
        return sum(self.grid.span(slot) for slot in self.vault.slots(self.cap))

    @property
    def done(self) -> bool:
        """Весь фильм на диске: показ дальше не нуждается в сети вовсе.

        Считается ровно то же, что и в :attr:`warmed`, - только то, что показ и правда
        возьмёт с диска: копия тяжелее потолка приёмника наружу не идёт
        (:meth:`torrcast.stream.Feed._warm`), и пока на месте тяжёлого куска лежит она, а
        не перекод (:meth:`_spots_left`), «готово» - ложь: человек выключит интернет и
        упрётся в темноту на первом же тяжёлом месте.
        """
        return len(self.vault.slots(self.cap)) >= self.grid.count and not self._spots_left()

    def _pending(self) -> bool:
        """Осталась ли прогреву работа: непрогретое место или тяжёлый кусок под перекод.

        По этому признаку решается цепочка (:meth:`_chain`), а не по :attr:`done`: фильм
        с местами тяжелее потолка приёмника, которые перекодировать нечем, «готовым» не
        станет никогда - но и работа прогрева на нём кончилась, так что следующая серия
        ждать его не обязана.
        """
        return self._missing() is not None or bool(self._spots_left())

    def _spots_left(self) -> tuple[int, ...]:
        """Тяжёлые куски, которые ещё не перекодированы точечно.

        Кусок берётся в работу, только когда копия уже лежит: перекод идёт поверх неё, и
        порядок «сначала весь фильм копией, потом тяжёлые места» держит одно свойство -
        прогретое в любой момент играбельно целиком, даже если прогрев сняли посередине.
        """
        if not self.spots or self.spot_encode is None:
            return ()
        return tuple(
            slot
            for slot in self.spots
            if self.vault.have(slot) and not self.vault.spot(slot).exists()
        )

    def line(self) -> str:
        """Строка о прогреве для журнала и статуса — та самая «прогрето 42 мин из 96»."""
        from torrcast.cli import _hms

        head = f"прогрето {_hms(self.warmed)} из {_hms(self.grid.duration)}"
        if self.done:
            done = f"{head} - фильм целиком на диске, интернет больше не нужен"
            return done if self.after is None else f"{done}; следующая: {self.after.line()}"
        if self.trouble:
            return f"{head} - прогрев встал: {self.trouble}"
        if not self.idle:
            return f"{head} - грею дальше"
        why = "уступил перекоду" if self._busy_rival() else "жду запаса показа"
        return f"{head} - грею дальше ({why})"

    def _missing(self) -> tuple[int, int] | None:
        """Куда идти прогреву: ``(первый непрогретый, последний слот прогона)``.

        Сначала хвост от места показа, потом голова: обрыв связи бьёт по будущему, а не
        по уже пройденному. Прогон всегда доводится до конца своего участка — это и есть
        «один прогон, один непрерывный звук».
        """
        have = self.vault.slots()
        for first in range(self.began_at, self.grid.count):
            if first not in have:
                return first, self.grid.count - 1
        for first in range(0, self.began_at):
            if first not in have:
                return first, self.began_at - 1
        return None

    def _wait_for_picture(self) -> None:
        """Дождаться, пока у показа появится запас, и только потом лезть в раздачу.

        ⚠️ Замер: прогрев, поднятый вместе с показом, отнимает у первого сегмента 0.2 с
        (2.10 → 2.28 с готовности LOAD на «Моане 2») — свой ffmpeg, свой запрос к той же
        раздаче. Путь до картинки дорожать не имеет права ни на сотую, поэтому прогрев
        стоит, пока живая упаковка не наберёт запас, и трогается с места уже при играющем
        показе. Потолок ожидания нужен на случай, когда запас не меряют вовсе (mock,
        приёмник молчит): тогда прогрев всё равно начнётся, просто позже.
        """
        deadline = time.monotonic() + START_GRACE
        while not self.stopped and self.slack < GUARD_HIGH and time.monotonic() < deadline:
            time.sleep(0.5)

    def _work(self) -> None:
        self._wait_for_picture()
        # ``trouble`` тут не для порядка: им кончается и упёртый бюджет, и место, которое
        # так и не легло на сетку (:meth:`_verify`). Без этого условия прогрев ходил бы
        # кругами по одному и тому же непрогретому куску.
        while not self.stopped and not self.trouble:
            try:
                if self._must_yield():
                    # Уступать надо не только НАЧАТЫМ прогоном, но и не начатым. Между
                    # решением «пора греть» и первым :meth:`_throttle` прогрев успевает
                    # поднять пробный прогон (:meth:`_run`) - ещё один ffmpeg и ещё один
                    # запрос в ту же раздачу, и он не заморожен ничем. Разбор живого
                    # показа: пробный прогон встал ровно внутрь чужого захода на 15-й
                    # секунде, а сам прогрев замер через миллисекунду после старта - то
                    # есть весь процессор, который прогрев в ту минуту отобрал, был
                    # процессором пробного прогона.
                    time.sleep(0.5)
                    continue
                job = self._missing()
                if job is None:
                    left = self._spots_left()
                    if left:
                        # Фильм лёг копией целиком - осталось привести тяжёлые места к
                        # тому же виду, в котором их отдаёт живой показ.
                        self._run(left[0], left[0], spot=True)
                        continue
                    if not self.trouble:
                        if self.done:
                            self._say(self.line())
                            mark("прогрев готов", секунд=round(self.warmed))
                            self._trace("ready")
                        else:
                            # Лежит всё, что прогрев в силах положить, но часть мест -
                            # копиями тяжелее потолка приёмника, а перекодировать их нечем
                            # (перекод выключен или профиль тяжести их промахнул). «Готово»
                            # это назвать нельзя - под этими местами показу нужна сеть, -
                            # а вот работа прогрева кончилась, и цепочка идёт дальше.
                            self._stall(
                                "места тяжелее потолка приёмника остались копией - "
                                "без сети их не досмотреть"
                            )
                        self._chain()
                    return
                tight = self.vault.fit(int(self._forecast(*job)))
                if tight:
                    self._stall(tight)
                    return
                self._run(*job)
            except Exception as exc:  # прогрев не имеет права ронять показ
                self._say(f"прогрев сорвался ({exc}) - показ идёт как обычно")
                time.sleep(5.0)

    def _chain(self) -> None:
        """Серия легла на диск целиком - взяться за следующую (:attr:`follow`).

        Ровно за одну, и ни серией дальше. Причина не в бюджете, а в том, ради чего
        прогрев вообще есть: обрыв связи убивает показ на **стыке** серий - досмотрели
        текущую, а следующей нет ни куска, и автопереход упирается в мёртвую раздачу.
        Закрывает эту дыру одна серия вперёд; сезон-пак впрок - это уже не страховка
        показа, а выкачивание раздачи на диск, чего мы не делаем нигде.

        Поднимается ровно здесь и ни секундой раньше: пока текущая серия не на диске,
        каждый байт раздачи нужен ей, а не следующей. «На диске» тут - всё, что прогрев
        в силах положить (:meth:`_pending`), а не обязательно «готово» (:attr:`done`):
        место тяжелее потолка приёмника без перекода прогретым не станет никогда, и
        держать из-за него цепочку - значит оставить стык серий без страховки вовсе.
        """
        if self.stopped or self.follow is None or self.after is not None or self._pending():
            return
        following = self._ask_follow()
        if following is None:
            return
        # Текущая серия для соседнего прогрева - чужой каталог, и бюджет вытеснил бы её
        # первой: она и старше, и досматривать её ещё полчаса (:attr:`Vault.keep`).
        following.vault.keep = following.vault.keep | {self.vault.key}
        self.after = following
        following.slack = self.slack
        # Кодировщик живых кусков у показа один на всех, и уступать ему обязана вся
        # цепочка: прогрев следующей серии жжёт тот же процессор, что и прогрев этой.
        following.rival = self.rival
        following.start()
        mark("прогрев следующей серии")

    def _ask_follow(self) -> Warmer | None:
        """Собрать прогрев следующей серии, дожидаясь сети; ``None`` - собирать нечего.

        🔴 Спрашиваем ПОВТОРНО, пока показ жив. Сборка следующей серии - это два вопроса
        к раздаче (паспорт файла и карта опорных кадров, :func:`torrcast.playback._next_warmer`),
        и приходятся они ровно на тот миг, когда текущая серия дописала последний кусок.
        Обрыв связи в этот миг раньше кончал цепочку навсегда: ``follow`` спрашивали один
        раз, ошибку записывали в журнал - и прогрев следующей серии не начинал никто, хотя
        показу идти ещё полсерии и сеть успевала вернуться.

        Замер на стенде, ради которого повтор и заведён: обрыв на 10-й секунде, сеть
        вернулась на 194-й, прогон шёл до 720-й - то есть 526 с здоровой сети, - и
        следующая серия получила НОЛЬ кусков (на здоровой сети тот же прогон кладёт её
        целиком: 107 кусков из 107). Теряется при этом не пара кусков, а вся следующая
        серия - ровно та дыра на стыке, ради которой прогрев впрок и существует.

        Отличать «не смогли» от «нечего»: исключение - это сеть, и его ждём; ``None`` -
        это фильм, последняя серия раздачи или запись без списка серий, и ждать тут
        нечего никогда.
        """
        said = False
        while not self.stopped:
            if self._must_yield():
                # Живое окно показа сильнее прогрева всегда: паспорт и карта опорных
                # кадров - это запрос в ту же раздачу и тот же процессор.
                self._nap(1.0)
                continue
            try:
                # Через переменную с типом: ``follow`` - это ``Any`` (фабрика приходит из
                # показа), и отдавать его наружу без сужения значит увести тип из подписи.
                following: Warmer | None = self.follow()
            except Exception as exc:  # прогрев не имеет права ронять показ
                if not said:
                    # Строка одна на весь обрыв: повтор идёт раз в полминуты, и жаловаться
                    # каждый раз значит забить журнал показа своей же неудачей.
                    self._say(
                        f"прогрев следующей серии не собрался ({exc}) - жду сеть и пробую снова"
                    )
                    said = True
                self._nap(self.chain_retry)
                continue
            return following
        return None

    def _nap(self, seconds: float) -> None:
        """Поспать, просыпаясь на снятие показа.

        Сон в цепочке измеряется десятками секунд (:data:`CHAIN_RETRY`), а :meth:`stop`
        обязан срабатывать сразу: показ кончился - прогреву спать незачем.
        """
        end = time.monotonic() + seconds
        while not self.stopped:
            left = end - time.monotonic()
            if left <= 0:
                return
            time.sleep(min(0.5, left))

    def _forecast(self, first: int, last: int) -> float:
        """Во сколько байт обойдётся этот участок. Считаем по нашему же битрейту, когда
        перекодируем, и по карте опорных кадров, когда копируем."""
        from torrcast.stream import AUDIO_MBIT, MAX_SEGMENT_BYTES, TS_OVERHEAD

        seconds = sum(self.grid.span(s) for s in range(first, last + 1))
        if self.encode is not None:
            mbit = float(self.encode.mbit)
            return (mbit + AUDIO_MBIT) * TS_OVERHEAD * seconds * 1e6 / 8
        if self.grid.weigh is not None:
            # Копия: каждый кусок взвешивается по той же карте, по которой сетка ставила
            # границы, - «кусок равен потолку» ошибался в обе стороны разом: лёгкое кино
            # переспросило на треть и вытеснило соседей зря, тяжёлое недоспросило вдвое,
            # и бюджет проверялся на вдвое меньшем числе, чем потом легло.
            return sum(
                self.grid.weigh(self.grid.start(s), self.grid.end(s))
                for s in range(first, last + 1)
            )
        # Карты нет - вес куска неизвестен, просим по потолку сегмента, как раньше.
        return seconds / max(self.grid.span(first), 1.0) * MAX_SEGMENT_BYTES

    def _stall(self, why: str) -> None:
        self.trouble = why
        self._say(self.line())
        mark("прогрев встал", причина=why, секунд=round(self.warmed))
        self._trace("stall", why)

    def _trace(self, event: str, why: str = "") -> None:
        """Доля прогретого в недельный след - полями, а не строкой журнала.

        Строка (:meth:`line`) остаётся человеку в живом показе, а сюда идут те же числа
        врозь: секунды на диске, длина фильма и вес каталога. По ним и через неделю видно,
        сколько успел прогрев, - без разбора текста.
        """
        trace.warmth(
            event, secs=self.warmed, dur=self.grid.duration, size=self.vault.size(), why=why
        )

    def _run(self, first: int, last: int, spot: bool = False) -> None:
        """Один прогон ffmpeg: от ``first`` до ``last`` включительно, на диск, в темпе.

        ``spot`` - это не участок, а один тяжёлый кусок, который перекладывается поверх
        своей же копии перекодом (:attr:`spots`). Отдельный короткий прогон тут законен:
        ровно так же, отдельным прогоном на кусок, тяжёлое место берёт и живой показ
        (:class:`torrcast.recode.Recoder`), то есть стык звука на его границе у показа уже
        есть - и прогретое повторяет его один в один, а не добавляет свой.

        🔴 Где прогон встал на самом деле - :func:`torrcast.stream.pack_start`, ровно как у
        живой упаковки (:meth:`torrcast.stream.Feed.restart`), а не «где его задумала сетка».
        Разница не бухгалтерская: ``-segment_times`` считаются от ``at``, а муксер отмеряет
        их от ПЕРВОГО ПАКЕТА прогона. Отдали задуманное начало - и все резы захода
        попросились раньше на всю докатку. Замер на живом материале: ``-ss 2901.815`` ставит
        ffmpeg на 2899.730, докатка 2.085 с, и прогретый кусок начинался на 2932.638 вместо
        2934.432 - PCR на 1.668 с назад, DTS видео на 1.710 с (обратный ход -22 мс уже
        подтверждённо ронял показ, тут в 75 раз больше). Куски при этом лежали под
        правильными именами и весили правдоподобно, а манифест обещал 10.885 с против
        12.595 с в файле - около 40 дублированных кадров. Там, где в сдвинутом окне опорных
        кадров не было, рез вставал верно и кусок был побайтово равен живому - отсюда и
        незаметность.

        ⚠️ Пробный прогон нужен ровно копии. У перекодирующего захода (``spot``, сплошной
        :attr:`encode`) ``-ss`` точен, докатки нет, и измеренное начало увело бы весь заход
        на сегмент назад (:func:`torrcast.stream.ffmpeg_pack_command`).

        Цена честная: копирующих заходов у прогрева два на фильм - хвост от места показа и
        голова (:meth:`_missing`), - а точечные идут перекодом и пробного не просят вовсе.
        0.5-2.9 с на заход против получаса прогрева не считаются.
        """
        from torrcast.stream import Packer, ffmpeg_pack_command, pack_start

        encode = self.spot_encode if spot else self.encode
        at = self.grid.start(first)
        if encode is None:
            at = pack_start(self.source, at)
            mark("пробный прогон прогрева", слот=first, встали=round(at, 3))
        command = ffmpeg_pack_command(
            self.source,
            self.audio,
            str(self.vault.dir / RUN_DIR),
            self.grid,
            first,
            at,
            readrate=self.rate,
            burst=0.0,
            encode=encode,
            until=last,
        )
        command = ["nice", "-n", str(self.nice), *command]
        began = time.monotonic()
        # Копией заход идёт или перекодом - в журнале обязано стоять словом, а не выводиться
        # из соседней метки «пробный прогон прогрева». Разбор живого показа на этой
        # недоговорённости уже срывался: гипотезу «перекод не успевает, потому что делит
        # процессор с прогревом» проверяли там, где прогрев шёл копией, а копия соседу стоит
        # 2-3 % вместо 33 % (:data:`torrcast.recode.NEIGHBOUR_TOLL`).
        way, by = ("перекод", "перекодом") if encode is not None else ("копия", "копией")
        mark("прогрев пошёл", первый=first, последний=last, темп=self.rate, точечно=spot, режим=way)
        self._say(
            f"тяжёлый v{first} на диске кладу перекодом - тем же, каким его отдаёт показ"
            if spot
            else f"грею на диск с {self.grid.start(first) / 60:.0f}-й минуты {by}, "
            f"темп ×{self.rate:g}"
        )
        with self.lock:
            self.packer = packer = Packer.start(
                command,
                self.vault.dir,
                self.vault.dir / RUN_DIR,
                first,
                last=last,
                grid=self.grid,
                shrink=self._lay_heavy,
            )
        self.misgrid = -1
        laid = first - 1
        checked = first - 1
        try:
            while not self.stopped:
                packer.publish()
                laid = self._inspect(laid, min(packer.edge, last))
                if self.misgrid >= 0 or packer.edge >= last or packer.poll() is not None:
                    break
                if not spot and laid > checked:
                    # Заход - это весь остаток фильма, и за него и бюджет, и запас
                    # раздела меняются: перепроверяем по ходу укладки, а не раз на
                    # входе. По мере укладки, а не по таймеру: ``fit`` взвешивает весь
                    # каталог, и лишний раз гонять его каждые полсекунды незачем.
                    checked = laid
                    tight = self.vault.fit(int(self._forecast(laid + 1, last)))
                    if tight:
                        self._stall(tight)
                        break
                self._throttle(packer)
                time.sleep(0.5)
            if self.misgrid < 0:
                # Мёртвый ffmpeg дописал последний кусок, но выложить его успевает уже
                # не цикл (:meth:`torrcast.stream.Packer.publish`) - и сверить тоже.
                packer.publish()
                self._inspect(laid, min(packer.edge, last))
        finally:
            self._resume(packer)
            with self.lock:
                self.packer = None
            packer.stop(keep_files=True, reason="прогрев окончен")
            self.vault.touch()
        if self.misgrid >= 0:
            # Заход, вставший не туда, кладёт мимо сетки весь свой участок: доводить его
            # до конца значит намолотить ещё сотню таких же кусков.
            return
        got = max(0, min(last, packer.edge) - first + 1)
        spent = time.monotonic() - began
        if spot and got:
            # Метка ставится ПОСЛЕ выкладки: оборвался прогон - на месте куска осталась
            # копия, и следующий круг возьмётся за него снова.
            with contextlib.suppress(OSError):
                self.vault.spot(first).touch()
        if got and packer.poll() not in (0, None) and packer.edge < last:
            # Прогон оборвался сам - почти всегда это пропавшая сеть. Не авария:
            # следующий круг начнёт с первого непрогретого куска, когда сеть вернётся.
            self.breaks += 1
            self._say(f"прогрев оборвался на {self.grid.end(packer.edge) / 60:.0f}-й минуте")
            time.sleep(5.0)
        elif not got:
            self._say(f"прогрев не дал ни куска за {spent:.0f} с - жду и пробую снова")
            time.sleep(10.0)

    def _lay_heavy(self, slot: int, size: int) -> bool:
        """Кусок тяжелее потолка приёмника: уложить на диск и не вставать на нём.

        Зовётся выкладкой на последнем гейте, где вес куска зажат потолком приёмника
        (:attr:`torrcast.stream.Packer.shrink`). Гейт этот про ЖИВУЮ отдачу: тяжёлую копию
        приёмник не доигрывает, и наружу она идти не имеет права. У прогрева адресат
        другой - диск, - и там тяжёлая копия обязана лежать:

        * ею считается сделанная работа (:meth:`_missing`). Не лёг кусок - прогрев вернётся
          на это место следующим прогоном, и тяжёлое место перекладывалось бы вечно
          (:meth:`Vault.slots`);
        * поверх неё идёт точечный перекод (:meth:`_spots_left`), а он берёт место в работу
          только тогда, когда копия уже лежит;
        * запасом она при этом не становится ни на секунду: и :attr:`warmed`, и
          :attr:`done` считают только то, что показ и правда возьмёт с диска
          (``slots(cap)``), а :meth:`torrcast.stream.Feed._warm` тяжёлую копию не отдаёт.

        🔴 Без этого хука выкладка прогрева ВСТАВАЛА на первом же таком куске (``shrink``
        не задан - поведение до TC-467) и дальше не двигалась никогда: ffmpeg честно паковал
        в темпе :attr:`rate`, куски копились в каталоге прогона, а на диск не попадало
        ничего. Замер на живой раздаче (BDRip 1080p 12.3 Мбит/с, сетка 10 с): за 421 с
        каталог прогона набрал 140 кусков, прогретым стал ОДИН - ``v0`` на 2.3 МБ, потому
        что ``v1`` весил 19.8 МБ при потолке 16 МБ.

        Ответ всегда ``False``: ужимать прогрев не умеет и не должен - это работа живого
        кодировщика. Выкладке ответ важен только когда рядом лежит готовый перекод, а у
        прогрева его нет.
        """
        from torrcast.stream import segment_name

        with contextlib.suppress(OSError):
            os.replace(self.vault.dir / RUN_DIR / segment_name(slot), self.vault.path(slot))
        return False

    def _inspect(self, done: int, edge: int) -> int:
        """Сверить с сеткой всё, что легло после ``done`` и не дальше ``edge``.

        Возвращает новую границу сверенного. Обход не обрывается на первом же промахе, и
        это важнее, чем кажется: ``publish`` выкладывает пачкой (:meth:`_run` опрашивает
        его раз в полсекунды), а заход, вставший не туда, разъезжается с сеткой ЦЕЛИКОМ.
        Оборви обход - и остальные куски пачки остались бы лежать в показе непроверенными,
        то есть сторож ловил бы ровно один кусок из четырёх.
        """
        for slot in range(max(done + 1, 0), edge + 1):
            self._verify(slot)
        return max(done, edge)

    def _verify(self, slot: int) -> bool:
        """Кусок лёг на своё место сетки? Ложь - он уже убран и в показ не пойдёт.

        🔴 Ради этой сверки карточка и написана. Дефект, из-за которого прогрев резал куски
        мимо сетки, прожил незамеченным не потому, что был хитрым, а потому, что уложенное
        никто не сверял: код верил намерению (``-segment_times`` от нужного места), а
        муксер отмерял резы от ПЕРВОГО ПАКЕТА прогона (:meth:`_run`). Куски при этом лежали
        под правильными именами и весили правдоподобно, а начинались на 1.4-3.8 с раньше
        своих границ - на стыке с живой упаковкой метки шли НАЗАД до 1.7 с, около сорока
        кадров дублировалось. Здоровым он выглядел выборочно: там, где в сдвинутом окне не
        оказывалось опорного кадра, рез случайно вставал верно и кусок побайтово совпадал с
        живым. Поэтому сверяется КАЖДЫЙ уложенный кусок, а не один на заход.

        Ловится только сдвиг НАЗАД, и это не полумера. Раньше своей границы кусок начаться
        не может ни по одной законной причине: обе упаковки заходят от измеренного начала
        (:func:`torrcast.stream.pack_start`), а муксер режет по первому опорному кадру не
        раньше границы. Позже - может, и законно: на сетке, чьи границы не попали на
        опорные кадры, муксер ждёт следующего кадра, и ровно так же ведёт себя живая
        упаковка - её кусок в этом месте побайтово тот же самый. Выбрасывать такое значило
        бы выбрасывать то, что показ и так отдаёт с диска; расхождение сетки с потоком -
        это про карту опорных кадров, и меряет его :meth:`torrcast.stream.Packer.drift`.

        ``nan`` (не прочли) - пропускаем. Сторож, который бракует по незнанию, дороже того
        дефекта, ради которого он поставлен.

        Забракованный кусок именно СТИРАЕТСЯ, а не помечается: показ ищет прогретое глобом
        каталога (:meth:`Vault.slots`, :meth:`torrcast.stream.Feed.segment`), и никакой
        пометки он не читает. Отдачу это не роняет даже в самый неудачный момент - файл,
        пропавший между проверкой и чтением, отдача уже переживает (``OSError`` →
        404 → приёмник просит снова, :meth:`torrcast.stream._Handler._read`).
        """
        began = segment_start(self.vault.path(slot))
        want = self.grid.start(slot)
        if math.isnan(began) or began > want - SKEW_MAX:
            return True
        tries = self.skews.get(slot, 0) + 1
        self.skews[slot] = tries
        self.misgrid = slot if self.misgrid < 0 else self.misgrid
        # Дыра - это честное «тут не прогрето»: файла нет, значит нет его и в
        # :meth:`Vault.slots`, значит "прогрето целиком" (:attr:`done`) не наступит и
        # следующая серия в работу не возьмётся (:meth:`_chain`). Ровно так же считается
        # неготовым тяжёлый кусок, под которым лежит копия (:meth:`_spots_left`).
        hole = tries >= SKEW_TRIES
        with contextlib.suppress(OSError):
            self.vault.path(slot).unlink(missing_ok=True)
            self.vault.spot(slot).unlink(missing_ok=True)
        trace.skew(slot=slot, want=want, got=began, hole=hole)
        mark("кусок прогрева мимо сетки", слот=slot, сдвиг=round(began - want, 3), дыра=hole)
        where = f"v{slot} на {want / 60:.0f}-й минуте лёг мимо сетки ({began - want:+.2f} с)"
        if hole:
            self._stall(f"{where} - это место осталось непрогретым")
        else:
            self._say(f"{where} - перекладываю его заново")
        return False

    def _busy_rival(self) -> bool:
        """Идёт ли прямо сейчас заход живого перекода (:attr:`rival`)."""
        return bool(self.rival is not None and getattr(self.rival, "working", False))

    def _must_yield(self) -> bool:
        """Обязан ли прогрев замереть. Две причины, и обе про то, что показ важнее.

        Первая, старая: запас живого показа просел ниже :data:`GUARD_LOW`.

        Вторая, замеренная: рядом идёт заход живого перекода. Тяжёлый кусок обязан быть
        готов к своей секунде, и он единственный на всём показе работает по СРОКУ, а не
        впрок. ``nice`` тут не помогает - это замер, а не осторожность: прогрев под
        ``nice 19`` держит 128 % из 400 %, и живой перекод того же куска идёт 1.84×
        вместо 2.62×, то есть теряет 30 %. Ни ``-threads 2`` (2.04×), ни ``cpu.weight=1``
        в cgroup (2.30×) дыру не закрывают - процессор возвращает только ``SIGSTOP``
        (2.62×, вровень с пустой машиной).

        Цена честная и маленькая: заходы живого перекода коротки и редки (на «Тачках 3»
        это 5 кусков из 525), а прогрев работает впрок и ничего не теряет от паузы.
        """
        return self._busy_rival() or (0 < self.slack < GUARD_LOW)

    def _throttle(self, packer: Any) -> None:
        """Показ (или его перекод) просит процессор — прогрев замирает; отпустило — оживает.

        Именно ``SIGSTOP``, а не «снять и начать заново»: снятый прогон обошёлся бы
        показу дырой в звуке на стыке (заголовок модуля), а замерший продолжает с того
        же кадра. Живой упаковке это не грозит ничем: замирает читатель диска, а не тот
        ffmpeg, чьи куски забирает приёмник.
        """
        if self._must_yield():
            if not self.idle:
                self.idle = True
                self.healthy_since = 0.0
                with contextlib.suppress(OSError, ProcessLookupError):
                    packer.proc.send_signal(signal.SIGSTOP)
                mark("прогрев замер", запас=round(self.slack), перекод=self._busy_rival())
            return
        if self.idle and self._may_resume():
            self._resume(packer)

    def _may_resume(self) -> bool:
        """Пора ли оживлять замерший прогрев. Зовётся, когда уступать уже некому.

        Три повода, и все безопасны для показа. Первый - запаса не мерили вовсе
        (``mock``, приёмник молчит): гадать за показ нельзя, а держать прогрев вечно
        замершим из-за отработавшего перекода - тем более. Второй - запас перевалил
        :data:`GUARD_HIGH`: показ с большим отрывом от края, места хватает обоим. Третий -
        запас держится над :data:`GUARD_LOW` дольше :data:`STARVE_GRACE`: это тесный, но
        здоровый показ (идёт вплотную за упаковкой, до :data:`GUARD_HIGH` не дотягивает
        никогда), и без короткого захода прогрев голодал бы вечно.
        """
        if self.slack <= 0:
            return True
        if self.slack > GUARD_HIGH:
            return True
        if self.slack < GUARD_LOW:
            self.healthy_since = 0.0
            return False
        now = time.monotonic()
        if self.healthy_since == 0.0:
            self.healthy_since = now
            return False
        return now - self.healthy_since >= STARVE_GRACE

    def _resume(self, packer: Any) -> None:
        if not self.idle:
            return
        self.idle = False
        self.healthy_since = 0.0
        with contextlib.suppress(OSError, ProcessLookupError):
            packer.proc.send_signal(signal.SIGCONT)

    def _say(self, text: str) -> None:
        if self.log is not None:
            self.log(text)
