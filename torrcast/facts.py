#: Разрешённые адреса храним, пока живёт процесс: у справки два-три статических хоста, и
#: спрашивать их у DNS повторно незачем. Срок конечный - IP хоста может и смениться.
_RESOLVED: dict[str, tuple[float, str]] = {}
_RESOLVE_LOCK: Final = threading.Lock()
_RESOLVE_TTL: Final = 600.0


def _resolve(host: str, timeout: float) -> str:
    """IPv4-адрес хоста - со своим таймаутом и памятью на процесс.

    ``socket.getaddrinfo`` таймауту сокета не подчиняется: под бурей параллельных резолвов
    (её поднимает прогрев раздач, пока справка едет фоном) он залипает НАДОЛГО, дольше
    всего бюджета справки, и та не приезжает вовсе - хотя сам HTTP уложился бы в 0.7 с.
    Стек залипшего потока упирался ровно сюда: ``getaddrinfo`` <- ``connect`` <-
    ``get_json``. Поэтому, во-первых, резолвим в отдельном потоке с ``join`` по таймауту -
    залипший ``getaddrinfo`` держит демона, а не справку. Во-вторых, помним найденное: у
    справки два-три статических хоста, разрешить их надо однажды, а не на каждый запрос,
    и раз разрешённый адрес переживает бурю мимо DNS. IPv4-only намеренно: v6-адрес висит
    в SYN-SENT (см. :class:`_IPv4Connection`).
    """
    now = time.monotonic()
    with _RESOLVE_LOCK:
        hit = _RESOLVED.get(host)
        if hit is not None and now - hit[0] < _RESOLVE_TTL:
            return hit[1]
    box: list[str] = []

    def look() -> None:
        with contextlib.suppress(OSError):
            info = socket.getaddrinfo(host, None, socket.AF_INET, socket.SOCK_STREAM)
            if info:
                box.append(str(info[0][4][0]))

    worker = threading.Thread(target=look, daemon=True)
    worker.start()
    worker.join(timeout)
    if not box:
        raise OSError(f"{host}: адрес не разрешён за {timeout:.1f} с")
    address = box[0]
    with _RESOLVE_LOCK:
        _RESOLVED[host] = (time.monotonic(), address)
    return address


class _IPv4Connection(http.client.HTTPSConnection):
    """HTTPS строго по IPv4.

    Не придирка: на хосте с прописанным, но нерабочим IPv6-выходом (типовая история за
    NAT и на VPS без v6-маршрута) обычный клиент сначала честно висит в SYN-SENT по
    AAAA-адресу и только потом падает на IPv4. Замер на таком хосте: 5.4 с против 0.33 с
    на тот же запрос. Бюджет справки — полторы секунды, то есть при v6 её не бывает
    никогда. Показу это не мешает (пусто — норма), но и терять её на ровном месте незачем.

    Адрес берём у :func:`_resolve` - со своим таймаутом и памятью: голый ``getaddrinfo``
    таймауту сокета не подчиняется и под DNS-бурей прогрева топил справку насмерть.
    """

    #: Контекст TLS: проверка серта и имени - обычная, ничего тут не ослаблено.
    context: ssl.SSLContext = ssl.create_default_context()

    def connect(self) -> None:
        budget = self.timeout if isinstance(self.timeout, int | float) else HTTP_TIMEOUT
        address = _resolve(self.host, budget)
        raw = socket.create_connection((address, self.port), self.timeout)
        self.sock = self.context.wrap_socket(raw, server_hostname=self.host)


def get_json(host: str, path: str, params: dict[str, str], headers: dict[str, str],
             timeout: float) -> Any:  # fmt: skip
    """GET с разбором JSON. Любая неудача — исключение: ловит его :meth:`Facts._work`."""
    conn = _IPv4Connection(host, timeout=timeout)
    try:
        conn.request(
            "GET", f"{path}?{urlencode(params)}", headers={"User-Agent": USER_AGENT, **headers}
        )
        response = conn.getresponse()
        if response.status != 200:
            raise OSError(f"{host} ответил {response.status}")
        return json.loads(response.read())
    finally:
        conn.close()


@dataclass(frozen=True, slots=True)
class Fact:
    """Справка по одной картине. Пустые поля — норма: нет данных, значит нет строки."""

    about: str = ""
    #: Уже с источником: «IMDb 7.6». Голая цифра в меню не значила бы ничего.
    rating: str = ""
    #: Готовая строка «1 ч 47 мин» - не минуты: считать их в уме человек не обязан.
    runtime: str = ""

    def __bool__(self) -> bool:
        return bool(self.about or self.rating or self.runtime)


def hms(minutes: int) -> str:
    """Минуты → «1 ч 47 мин»; ровный час — «1 ч»; меньше часа — «47 мин»; ноль — пусто."""
    if minutes <= 0:
        return ""
    hours, rest = divmod(minutes, 60)
    if not hours:
        return f"{rest} мин"
    return f"{hours} ч {rest} мин" if rest else f"{hours} ч"


#: Разбор готовой строки хронометража обратно в минуты (:func:`minutes_of`).
_RUNTIME_RE: Final = re.compile(r"^(?:(\d+)\s*ч)?\s*(?:(\d+)\s*мин)?$")


def minutes_of(runtime: str) -> int:
    """«2 ч 49 мин» → 169 минут; пусто или не разобралось — ноль. Обратное :func:`hms`.

    Число, а не строка, нужно отбору: битрейт релиза считается делением размера на
    длительность, и до сих пор в знаменателе стояла прикидка «фильм это два часа»
    (:data:`torrcast.stream.RUNTIME_GUESS`). У «Интерстеллара» (2 ч 49 мин) она завышает
    битрейт в 1.4 раза, и честные 1080p отсекались потолком на ровном месте.

    Разбирается именно готовая строка, а не отдельное поле: хронометраж уже приехал в
    справке и уже лежит в её кэше (:func:`_cached`), а лишнее поле пришлось бы заводить
    вместе с миграцией кэша ради того же самого числа.
    """
    match = _RUNTIME_RE.match(runtime.strip())
    if match is None:
        return 0
    hours, rest = match.group(1), match.group(2)
    return int(hours or 0) * 60 + int(rest or 0)


def titles_for(title: str, year: int | None) -> list[str]:
    """Под какими именами статья может лежать в русской Википедии, в порядке доверия.

    Первым — само название: «Тачки 2» так и называется. Дальше уточнения в скобках,
    которыми Википедия разводит одноимённое: «Моана» голым именем — это страница
    значений про полинезийское слово, а мультфильм 2016 года лежит под «Моана
    (мультфильм)», ремейк 2026-го — под «Моана (фильм, 2026)».

    Подзаголовок после двоеточия отрезается отдельным кандидатом: раздачи подписывают
    старое кино развёрнуто («Моана: романтика золотого века»), а статья называется
    короче. Чужую статью это не притащит — год всё равно проверяется по тексту.

    Регистр внутри слова Википедия сама не чинит: ``redirects=1`` нормализует лишь ПЕРВУЮ
    букву. «breaking bad» уходит в «Breaking bad» и мимо статьи, тогда как редирект есть с
    «Breaking Bad»; так же теряются «fruits basket», «twin peaks», «true detective». Поэтому
    к именам добавляются регистровые варианты голого имени - заглавные слова и нижний
    регистр. Лишний кандидат чужого не тащит (год и заголовок всё равно сверяются), а
    редирект по нужному написанию находится в той же прямой выборке, без похода в поиск.
    """
    bases = [title.strip()]
    head = title.split(":", 1)[0].strip()
    if head and head != bases[0]:
        bases.append(head)
    out: list[str] = []
    for base in bases:
        for qualifier in _QUALIFIERS:
            if "{year}" in qualifier and year is None:
                continue
            name = base + qualifier.format(year=year)
            if name not in out:
                out.append(name)
    for base in bases:
        for variant in (base.title(), base.lower()):
            if variant != base and variant not in out:
                out.append(variant)
    return out


def confirms(extract: str, year: int | None) -> bool:
    """Про тот ли это фильм: в первых фразах статьи должен стоять нужный год.

    Проверка дешёвая и на удивление надёжная — русская Википедия открывает статью о кино
    ровно этой формулой: «американский компьютерно-анимационный фильм 2006 года».
    Без неё «Моана» тянула бы описание ремейка 2026 года на мультфильм 2016-го, а «Тачки»
    — статью про франшизу целиком.

    Год неизвестен (раздача его не назвала) — сверять нечем, и справки не будет: пустая
    строка честнее чужого фильма.
    """
    return year is not None and bool(re.search(rf"\b{year}\b", extract))


@dataclass(frozen=True, slots=True)
class Origin:
    """Паспорт картины по справке: как она называется в оригинале и какого она года.

    Оба поля необязательны и означают ровно то, что сказано. Пустой ``title`` — у картины
    нет названия латиницей (советское и российское кино), а не «мы не нашли»: добирать
    латиницей такую картину нечем и не нужно. Пустой ``year`` — статью опознать не
    удалось; тогда гейт добора сверяет годы по самой выдаче, как умеет.

    ``name`` - как ту же картину зовут по-русски (заголовок русской статьи). Нужен
    зеркальному случаю: спросили латиницей, а половина каталога подписана по-русски
    («Cars» - одна мёртвая раздача при живых «Тачках»), и добирать надо русским именем.
    """

    title: str = ""
    year: int | None = None
    name: str = ""
    #: Q-идентификатор статьи в Wikidata. Не паспорт сам по себе (в :meth:`__bool__` не
    #: входит и в кэш пишется отдельно), а ключ ко второму источнику: по нему одинокий год
    #: сверяется с датой публикации P577 (:func:`origin_either`, :func:`confirmed_year`).
    entity: str = ""
    #: Статью не назвали по имени, а лишь ПРИЗНАЛИ похожей (:func:`_misremembered`): имя
    #: спросили одно, подписана она другим. Обычно это описка человека («Сальтберн» и
    #: «Солтберн»), но ровно так же выглядит и чужая картина («Все мы незнакомцы» и «Все мы
    #: убийцы»), поэтому гейт добора такому имени на слово не верит
    #: (:func:`~torrcast.cli._second_language`).
    guessed: bool = False
    #: Заголовок ДРУГОЙ картины того же года, которую справка знает под тем же именем
    #: (:func:`namesake`). Не паспорт, а повод для честной строки: развести такую пару
    #: разбору нечем, и человек обязан о ней прочитать (:func:`~torrcast.cli.namesake_note`).
    namesake: str = ""

    def __bool__(self) -> bool:
        return bool(self.title or self.year or self.name)


def origin(title: str, series: bool | None = False, budget: float = FACTS_BUDGET) -> Origin:
    """Паспорт картины из Википедии. Жёсткий потолок по времени и кэш на диске.

    Зовётся только на тощей выдаче, то есть там, где поиск и так собирается идти на
    второй круг по индексерам (1-3 с). Полторы секунды потолка на его фоне не видны, а
    счастливый путь сюда не заходит вовсе.

    ⚠️ Год выдачи сюда НЕ передаётся, и это принципиально: паспорт нужен гейту как
    независимое мнение. Подсказали бы год - справка послушно нашла бы статью под него, и
    сверять после этого было бы нечего: на «Восхождении» с подсказкой ``2019`` она
    уверенно приносила «Hannibal Rising», а без подсказки честно отвечает «1976».

    Молчание сети стоит ровно :attr:`budget`: запрос живёт в отдельном потоке, и залипший
    сокет держит не поиск, а демона, который умрёт вместе с процессом. Любая ошибка -
    пустой паспорт: справка не вправе ни ронять поиск, ни задерживать его сверх обещанного.

    ``series=None`` - тип картины неизвестен (русская выдача пуста, спросить его неоткуда),
    и это отдельный случай: см. :func:`origin_either`. У сериала и фильма разные статьи,
    так что тип подсказывать надо, а наугад - нельзя (уводит в чужую статью).
    """
    if series is None:
        return origin_either(title, budget)
    stored = _cached_origin(title, series)
    if stored is not None:
        return stored
    box: list[Origin] = []

    def work() -> None:
        with contextlib.suppress(Exception):
            box.append(origin_now(title, series, min(HTTP_TIMEOUT, budget)))

    thread = threading.Thread(target=work, daemon=True)
    thread.start()
    thread.join(budget)
    found = box[0] if box else Origin()
    if found:
        _remember_origin(title, series, found)
    return found


def origin_either(title: str, budget: float = FACTS_BUDGET) -> Origin:
    """Паспорт, когда тип картины неизвестен: пробуем и фильм, и сериал, верим согласию.

    Тип статьи в Википедии разводит фильм и сериал по разным статьям, и спека требует его
    подсказывать. На пустой русской выдаче взять его неоткуда, а подсказать наугад -
    открыть дыру: с ``series=True`` «Восхождение» уводит в чужой сериал «Hunyadi» 2024
    вместо фильма Шепитько, а с ``series=False`` «Дедвуд» даёт фильм 2006 вместо сериала
    2004. Поэтому спрашиваем обе статьи разом и берём ответ, только если фильм и сериал
    сошлись на одной картине (один оригинал или один год). Разошлись - честнее промолчать:
    пустой паспорт гейт добора переживёт, а чужая статья открыла бы подмену.

    ⚠️ Ответил ровно один путь - паспорт отдаётся БЕЗ ГОДА, и это главная тонкость. Такой
    ответ никем не подтверждён: второй путь молчит не потому, что картины другого типа
    нет, а потому, что статьи о ней нет в русской Википедии. «Атака титанов» - ровно этот
    случай: статьи об аниме-сериале нет вовсе, отвечает только фильм, и он приносит верное
    имя ``Attack on Titan`` вместе с ЧУЖИМ годом 2015 (у сериала 2013). Имя и год стоят
    разного: именем добор ищет раздачи, и худшее, чем оно грозит, - лишние или пустые
    раздачи; а год объявлен сильнее выдачи, и на нём стоят гейты, которые молча выкидывают
    «не ту» картину - с годом 2015 из каталога вылетает весь сериал 2013 года. Поэтому
    одинокому ответу верим ровно настолько, насколько это безопасно: имя берём, год - нет.

    Живая проба по 30 именам: путь остаётся один у 10 из них, год при этом теряют шестеро
    («Моана» 2016, «Во все тяжкие» 2008, «Ход королевы» 2020, «Иван Васильевич меняет
    профессию» 1973, «Семнадцать мгновений весны» 1973 - верные, «Атака титанов» 2015 -
    чужой). Пять верных гейтов за одну молчаливую подмену - размен в ту сторону, которую
    требует спека, и справка при этом не замолкает: имя латиницей остаётся у всех шестерых.

    ⚠️ TC-243. ``budget`` тут СРОК, а не мерка на каждый шаг. Два пути идут разом и в срок
    укладываются оба, но следом за одиноким ответом шёл второй источник
    (:func:`_second_source_year`) - со своим полным бюджетом сверх уже потраченного, то
    есть режим «оба типа» стоил вдвое дороже обещанного. Пока потолок был полторы секунды,
    лишняя терялась в шуме; на пустой выдаче, где справке отдают весь остаток цели, эти
    «вдвое» - вся цель до картинки. Считаем от срока: сколько осталось, столько и спрашиваем.
    """
    deadline = time.monotonic() + budget
    box: dict[bool, Origin] = {}

    def look(series: bool) -> None:
        box[series] = origin(title, series, budget)

    threads = [threading.Thread(target=look, args=(s,), daemon=True) for s in (False, True)]
    for thread in threads:
        thread.start()
    for thread in threads:
        thread.join(max(0.0, deadline - time.monotonic()))
    movie, show = box.get(False, Origin()), box.get(True, Origin())
    if movie and show:
        return movie if _same_picture_origin(movie, show) else Origin()
    lone = movie or show
    year = _second_source_year(lone, max(0.0, deadline - time.monotonic()))
    return Origin(
        title=lone.title, year=year, name=lone.name, entity=lone.entity, guessed=lone.guessed
    )


def _second_source_year(lone: Origin, budget: float) -> int | None:
    """Год одинокого ответа - только если его подтверждает ВТОРОЙ источник (Wikidata P577).

    🔴 TC-134. Одинокий ответ (:func:`origin_either`) никем не подтверждён: второй путь
    молчит не потому, что картины другого типа нет, а потому, что статьи о ней нет в
    русской Википедии. Прежде год у такого ответа отбирался ВСЕГДА - и это отбирало год
    у верных одиночек тоже («Психо» 1960, «Моана» 2016, «Во все тяжкие» 2008), а на них
    стоит год-опора гейтов добора. Отобрать год у всех - лекарство хуже болезни.

    Второй источник - дата первой публикации P577 из Wikidata, тем же SPARQL и тем же
    IPv4-клиентом, что уже носят хронометраж (:func:`wikidata_ids`). Совпал её год с годом
    статьи - год подтверждён двумя источниками, отдаём. Разошлись, второго года нет или
    Wikidata молчит - МОЛЧИМ: год роняем, а не выбираем «поудачнее». При расхождении
    источников чужой год страшнее пустого - им гейт добора молча выкидывает всю картину.

    Хоп стоит времени до меню, поэтому спрашиваем P577 ТОЛЬКО когда год реально нужен: у
    ответа он есть (иначе сверять нечего) и есть чем спросить второй источник (``entity``).
    Латинописанное аниме приходит без Q-идентификатора - тогда второго источника нет, и
    год остаётся неподтверждённым, ровно как раньше.
    """
    if lone.year is None or not lone.entity:
        return None
    return lone.year if confirmed_year(lone.entity, lone.year, budget) else None


def confirmed_year(entity: str, year: int, budget: float = FACTS_BUDGET) -> bool:
    """Подтверждает ли Wikidata (P577) год статьи. Молчание/расхождение/ошибка - ``False``.

    Год живёт в бюджете справки, а лишний хоп его тратит, поэтому запрос идёт в отдельном
    потоке с ``join`` по бюджету: залипший сокет держит демона, а не путь до меню. Любая
    ошибка (сети нет, v6 висит в SYN-SENT, Wikidata ответила не так) - тоже ``False``:
    неподтверждённый год честнее чужого.
    """
    box: list[int | None] = []

    def work() -> None:
        with contextlib.suppress(Exception):
            box.append(published_year(entity, min(HTTP_TIMEOUT, budget)))

    thread = threading.Thread(target=work, daemon=True)
    thread.start()
    thread.join(budget)
    return bool(box) and box[0] == year


def published_year(entity: str, timeout: float = HTTP_TIMEOUT) -> int | None:
    """Год первой публикации картины из Wikidata (P577); нет даты - ``None``.

    Тот же SPARQL и тот же клиент, что у :func:`wikidata_ids`. Дат у P577 бывает несколько
    (разные страны проката, издания) - берём самую раннюю: она и есть «первая публикация».
    """
    query = f"SELECT ?date WHERE {{ wd:{entity} wdt:P577 ?date }}"
    head = {"Accept": "application/sparql-results+json"}
    payload = get_json(_WIKIDATA_HOST, _WIKIDATA_PATH, {"query": query}, head, timeout)
    return read_published(payload)


def read_published(payload: Any) -> int | None:
    """Ответ SPARQL на P577 → самый ранний год; ни одной даты - ``None``.

    Дата приезжает ISO-строкой («2016-11-14T00:00:00Z», у старого кино с точностью до года
    - «1960-01-01T00:00:00Z»); год - её первые четыре цифры.
    """
    if not isinstance(payload, dict):
        return None
    rows = (payload.get("results", {}) or {}).get("bindings", [])
    years: list[int] = []
    for row in rows:
        value = row.get("date", {}).get("value", "")
        match = re.match(r"(\d{4})-", value)
        if match:
            years.append(int(match.group(1)))
    return min(years) if years else None


def _same_picture_origin(one: Origin, two: Origin) -> bool:
    """Один ли это фильм у двух паспортов: сходятся оригинал латиницей либо год.

    Русское имя у обоих одно (его и спросили), поэтому различает картины оригинал и год.
    «Дедвуд»: фильм ``Deadwood: The Movie`` 2006 и сериал ``Deadwood`` 2004 - ни оригинал,
    ни год не сходятся, значит это разные картины и подсказывать нечего.
    """
    same_latin = bool(slugify(one.title)) and slugify(one.title) == slugify(two.title)
    same_year = one.year is not None and one.year == two.year
    return same_latin or same_year


def origin_now(title: str, series: bool = False, timeout: float = HTTP_TIMEOUT) -> Origin:
    """Синхронный поход за паспортом. Неудача — исключение, его ловит :func:`origin`.

    Два шага, и второй — только если первый промахнулся. Прямая выборка по именам
    (:func:`titles_for`) дешевле и точнее, ею и закрывается большинство: «Психо», «Печать
    зла», «Дедвуд (телесериал)» лежат ровно там, где их и ждёшь. Но не все: «Восхождение»
    голым именем — страница значений, а «Кингсман: Секретная служба» на ru.wikipedia
    подписана латиницей («Kingsman: Секретная служба»), и никаким перебором уточнений в
    неё не попасть. Тогда спрашиваем поиском самой Википедии — он эти случаи и разводит.

    Третий шаг (:func:`_misremembered`) — для имени, названного НЕ ТАК, как подписана
    статья: он стоит денег и идёт только на пустом месте, когда первые два уже промолчали.

    Четвёртый (:func:`_imdb_ru`) — офлайн-карта русских прокатных имён IMDb, для картины
    без русской статьи вовсе: сеть тут уже ответила «не знаю», и дальше слово за файлом.
    """
    warm = threading.Thread(target=_ru_names, daemon=True)
    warm.start()  # карта читается, пока отвечает Википедия: к моменту нужды она тёплая
    kind = "сериал" if series else "фильм"
    names = titles_for(title, None)
    if series:  # у сериала своя статья, и лежит она под своим уточнением
        names.sort(key=lambda name: "сериал" not in name)
    hops, pages = _pages(get_json(_WIKI_HOST, _WIKI_PATH, _extract_params(names), {}, timeout))
    direct = _own_name_first([_article(name, hops, pages) for name in names], title)
    found = read_origin(direct, title, trusted=True, series=series)
    if found:
        return found
    found = redirected_name(names, hops, pages, title)
    if found:
        return found
    payload = get_json(_WIKI_HOST, _WIKI_PATH, _search_params(f"{title} {kind}"), {}, timeout)
    found = read_origin(_ranked(payload), title, series=series)
    return found or _misremembered(title, series, timeout) or _imdb_ru(title, series)


def _own_name_first(pages: list[Any], title: str) -> list[Any]:
    """Кандидаты прямой выборки: сначала статьи, названные ИМЕНЕМ запроса.

    Уточнение в скобках порядка не задаёт: «девять (мультфильм)» стоит в перечне раньше
    «девять (фильм)» просто по алфавиту, и первая же киношная статья побеждала - справка
    отвечала про мультфильм «9», когда спрашивали «Девять». Между тем перенаправление
    «девять (мультфильм)» → ``9 (мультфильм, 2009)`` - это уже ДРУГОЕ имя: статья
    подписана не так, как спросили. Статья же «Девять (фильм)» названа ровно спрошенным
    словом, и её слово о картине с этим именем сильнее.

    Переименованные перенаправления («Уэнсдей» → «Уэнздей») ничего не теряют: они просто
    идут следом, и без тёзок впереди выбор остаётся прежним. Меняется ровно один случай -
    когда про кино есть и тёзка, и одноимённая подмена: раньше побеждал порядок уточнений,
    теперь - имя.
    """
    wanted = slugify(title)

    def own(page: Any) -> bool:
        heading = str((page or {}).get("title") or "")
        return bool(wanted) and slugify(heading.split(" (")[0]) == wanted

    return sorted(pages, key=lambda page: not own(page))


#: Каким произведением статья себя объявляет - в любом виде, а не только экранном. Список
#: нужен единственному пути :func:`redirected_name`, где статья и так доказана
#: перенаправлением, и отвечает он на один вопрос: произведение это или что-то ещё.
_WORK_RE: Final = re.compile(
    r"визуальн|новелл|манга|манги|ранобэ|аниме|\bигр\w*|роман|фильм|сериал|франшиз|комикс",
    re.IGNORECASE,
)


def redirected_name(
    names: list[str], hops: dict[str, str], pages: dict[str, Any], title: str
) -> Origin:
    """Русское имя, которое сама Википедия перенаправляет на латинский заголовок.

    Слепая зона справки на аниме, подписанном латиницей: «врата штейна» - живое
    перенаправление на статью ``Steins;Gate``, но статья эта о ВИЗУАЛЬНОЙ НОВЕЛЛЕ, с
    которой всё началось, и киношного гейта :func:`_about_cinema` она не проходит. Справка
    молчала, добор шёл транслитом ``vrata shteyna`` в никуда, а до-вожаком склейки
    оставался сиквел - и скачок года гейт добора честно читал как подмену.

    Отвечать тут есть чем, и ответ подтверждён источником: перенаправление русского имени
    на латинский заголовок - это и есть утверждение Википедии «то же самое зовут вот так».
    Ровно его мы и берём - ИМЕНЕМ, без года:

    * год такой статьи чужой картине не годится вовсе. У ``Steins;Gate`` первая врезка
      кончается словами «20 августа 2026 года выйдет ремейк новеллы», и :func:`picture_year`
      честно называет 2026 - год, которого у аниме 2011 года нет и близко. Год объявлен
      сильнее выдачи, поэтому чужого года не бывает: пусто;
    * заголовок обязан быть на латинице, а запрос - по-русски. Это граница, за которой
      начинаются статьи о людях: русская Википедия подписывает их по-русски («Питт,
      Брэд»), и киношный гейт им по-прежнему единственная преграда;
    * статья обязана назвать себя произведением (:data:`_WORK_RE`) - иначе перенаправление
      привело бы к компании или к городу.
    """
    if not _CYRILLIC.search(title):
        return Origin()
    for name in names:
        page = _article(name, hops, pages)
        if page is None:
            continue
        heading = str(page.get("title") or "")
        if not heading or _CYRILLIC.search(heading) or slugify(heading) == slugify(name):
            continue
        if not _WORK_RE.search(f"{heading} {page.get('extract') or ''}"):
            continue
        return Origin(title=_TAIL_RE.sub("", heading).strip() or heading)
    return Origin()


#: Сколько подсказок берём у Википедии на одно написание. Нужное лежит в первых строках,
#: дальше идут однофамильцы - и всё равно каждую подсказку сверяет :func:`_near_name`.
_SUGGEST_HITS: Final = 6
#: Со скольких слов имя можно спрашивать по куску: у двух слов кусок - это одно слово, а
#: одним словом в заголовке совпадает пол-Википедии.
_PHRASE_WORDS: Final = 3


def _misremembered(title: str, series: bool, timeout: float) -> Origin:
    """Имя названо не так, как подписана статья: описка, другая транскрипция, чужое слово.

    Третий и последний шаг справки, и ходит он только по пустому месту - когда прямая
    выборка и поиск Википедии уже промолчали. Счастливый путь сюда не заходит вовсе, так
    что бюджет справки этот шаг не трогает; на пустом же пути поиск и так собирается на
    второй круг по индексерам, и лишние доли секунды там не видны.

    Два способа спросить, оба идут разом и оба отвечают ЗАГОЛОВКАМИ, а не догадками:

    * **подсказки Википедии** (``opensearch``) - она сама правит транскрипцию:
      «Сальтберн» → «Солтберн». Спрашиваем и по-русски, и транслитом: аниме русская
      Википедия подписывает латиницей, и «ре зеро» находится только как ``re zero``
      («Re:Zero. Жизнь с нуля в альтернативном мире»);
    * **поиск по заголовкам без одного слова** (``intitle:``) - для имени, в котором
      человек одно слово помнит не то: «мужчина который удивил всех» ищется как
      ``intitle:"который удивил всех"`` и приводит к «Человек, который удивил всех».

    Найденное сверяется :func:`_near_name` - подсказка и поиск по куску притаскивают чужое
    («Сальтерас», «Сальтенья»), а тождество имени тут никем не доказано. Прошедшее сверку
    читается как выборка по имени (``trusted``): статью назвала сама Википедия.

    ⚠️ Паспорт этого шага - БЕЗ ГОДА, по той же причине, по которой без года отвечает
    одинокий путь :func:`origin_either`. Имя тут не доказано, а лишь признано похожим, и
    цена ошибки у двух полей разная: именем добор ищет раздачи (худшее - лишние), а год
    объявлен сильнее выдачи, и неверным годом гейт молча выкидывает всю картину. У «ре
    зеро» это видно прямо: русская статья - о ранобэ 2014 года, аниме же вышло в 2016-м.
    """
    box: dict[str, list[Any]] = {}

    def suggest(key: str, query: str) -> None:
        with contextlib.suppress(Exception):
            box[key] = _suggested(query, timeout)

    def phrase() -> None:
        with contextlib.suppress(Exception):
            box["phrase"] = _by_phrase(title, timeout)

    latin = transliterate(title)
    work = [
        threading.Thread(target=suggest, args=("ru", title), daemon=True),
        threading.Thread(target=phrase, daemon=True),
    ]
    if latin.lower() != title.lower():
        work.append(threading.Thread(target=suggest, args=("latin", latin), daemon=True))
    for thread in work:
        thread.start()
    for thread in work:
        thread.join(timeout)
    seen: set[str] = set()
    pages: list[Any] = []
    for key in ("ru", "latin", "phrase"):
        for page in box.get(key, []):
            heading = str(page.get("title") or "")
            if heading in seen or not _near_name(title, heading):
                continue
            seen.add(heading)
            pages.append(page)
    found = read_origin(pages, title, trusted=True, series=series)
    # Имя тут не доказано, а признано похожим - так и говорим паспортом, чтобы гейт добора
    # знал, на чём стоит второе имя (:attr:`Origin.guessed`).
    return Origin(title=found.title, name=found.name, guessed=bool(found))


#: Типы записей IMDb, которые паспорт считает СЕРИАЛОМ: у сериала и фильма в выгрузке
#: разные строки, и подсказанный тип разводит однофамильцев так же, как тип статьи.
_TV_KINDS: Final = frozenset({"tvSeries", "tvMiniSeries"})
#: Разобранная карта :data:`RU_NAMES_PATH`: нормализованное имя → кандидаты
#: ``(tconst, тип, оригинал, год, имя как в выгрузке)``. ``None`` - файл ещё не читали.
_RuName = tuple[str, str, str, str, str]
_RU_NAMES: dict[str, list[_RuName]] | None = None
_RU_LOCK: Final = threading.Lock()
#: Голоса IMDb по tconst - из того же файла, что и рейтинг меню. Спрашиваются, только
#: когда на одно русское имя претендуют несколько картин. ``None`` - ещё не читали.
_VOTES: dict[str, int] | None = None


def _read_ru_names(path: Path) -> dict[str, list[_RuName]]:
    """Файл карты → словарь по нормализованному имени; нет файла - пусто, и это не сбой."""
    out: dict[str, list[_RuName]] = {}
    try:
        with path.open(encoding="utf-8") as handle:
            for line in handle:
                fields = line.rstrip("\n").split("\t")
                name, tconst, kind, original, year = [*fields, "", "", "", "", ""][:5]
                if not name or not tconst:
                    continue
                candidates = out.setdefault(slugify(name), [])
                if all(tconst != known[0] for known in candidates):
                    candidates.append((tconst, kind, original, year, name))
    except (OSError, ValueError):  # нет файла или он битый - карты нет, и это не сбой
        pass
    return out


def _ru_names() -> dict[str, list[_RuName]]:
    """Карта русских прокатных имён IMDb. Читается один раз и лишь когда понадобилась.

    Файл - сотни тысяч строк: разбор это заметные доли секунды, поэтому читаем его по
    требованию и фоном (:func:`origin_now` греет чтение, пока отвечает Википедия), а не
    на старте каждого `cast`. Нет файла (установка без справки, не скачалось) - пустая
    карта, и паспорт молчит ровно так, как молчал без неё.
    """
    global _RU_NAMES
    with _RU_LOCK:
        if _RU_NAMES is None:
            _RU_NAMES = _read_ru_names(RU_NAMES_PATH)
        return _RU_NAMES


def _votes() -> dict[str, int]:
    """tconst → число голосов из выгрузки рейтингов; нет файла - пусто, и это не сбой."""
    global _VOTES
    with _RU_LOCK:
        if _VOTES is None:
            _VOTES = {}
            try:
                with RATINGS_PATH.open(encoding="utf-8") as handle:
                    next(handle, None)  # шапка «tconst averageRating numVotes»
                    for line in handle:
                        parts = line.split("\t")
                        if len(parts) >= 3 and parts[2].strip().isdigit():
                            _VOTES[parts[0]] = int(parts[2])
            except (OSError, ValueError):
                pass
        return _VOTES


def _imdb_ru(title: str, series: bool) -> Origin:
    """Паспорт по офлайн-карте русских прокатных имён IMDb - последний шаг справки.

    Зовётся, когда Википедия промолчала целиком: своей русской статьи у картины нет, и ни
    выборка по имени, ни поиск, ни подсказки её не нашли. Русское прокатное имя при этом
    часто существует - в выгрузке IMDb оно лежит парой к оригиналу и году, и карта
    :data:`RU_NAMES_PATH` отвечает без сети.

    Ручательство тут - САМА пара «имя - картина» из выгрузки: это утверждение каталога, а
    не сходство строк, поэтому единственный кандидат догадкой не считается. Несколько
    картин под одним именем - другое дело: выбор между ними делает число голосов IMDb, а
    это уже чья-то оценка, поэтому такой паспорт помечается ``guessed`` - решает гейт
    добора. Голосов нет (файл не доехал) - молчим: неподтверждённый выбор хуже пустого.

    Оригинал на кириллице (русская картина) латинским именем не является: добирать ей
    нечем, и ``title`` честно остаётся пустым - а вот год отдаём, он опора гейта.
    """
    typed = [
        candidate
        for candidate in _ru_names().get(slugify(title), [])
        if (candidate[1] in _TV_KINDS) == series
    ]
    if not typed:
        return Origin()
    guessed = False
    if len(typed) > 1:
        votes = _votes()
        best = max(typed, key=lambda candidate: votes.get(candidate[0], 0))
        if not votes.get(best[0]):
            return Origin()
        typed = [best]
        guessed = True
    _tconst, _kind, original, raw_year, name = typed[0]
    year = int(raw_year) if raw_year.isdigit() else None
    latin = "" if _CYRILLIC.search(original) else original
    return Origin(title=latin, year=year, name=name, guessed=guessed)


def _suggested(query: str, timeout: float) -> list[Any]:
    """Подсказки Википедии по написанию имени - сразу статьями, одним запросом.

    ``opensearch`` отвечает голыми заголовками, и за их первыми фразами пришлось бы ехать
    вторым запросом - то есть вторым кругом по сети внутри и без того последнего шага.
    ``generator=prefixsearch`` - тот же самый подсказчик (``opensearch`` им и работает
    внутри), но статьи приезжают с ним разом, за один поход и те же 0.4 с.
    """
    params = {
        **_search_params(""),
        "generator": "prefixsearch",
        "gpssearch": query,
        "gpslimit": str(_SUGGEST_HITS),
        "gpsnamespace": "0",
    }
    params.pop("gsrsearch", None)
    params.pop("gsrlimit", None)
    params.pop("gsrnamespace", None)
    return _ranked(get_json(_WIKI_HOST, _WIKI_PATH, params, {}, timeout))


def _by_phrase(title: str, timeout: float) -> list[Any]:
    """Статьи, у которых в ЗАГОЛОВКЕ стоит запрос без одного крайнего слова.

    Так ловится имя, в котором человек помнит не то одно слово: «мужчина который удивил
    всех» - это «Человек, который удивил всех». Обычный поиск такое не разводит вовсе: он
    полнотекстовый, и по этому запросу первым приносит биографию актёра. Отбрасывается
    ровно одно слово с краю (голову и хвост пробуем оба), и найденное всё равно сверяется
    по словам (:func:`_near_name`) - иначе ``intitle:"воспоминание"`` притащил бы что угодно.
    """
    words = title.split()
    if len(words) < _PHRASE_WORDS:
        return []
    out: list[Any] = []
    for phrase in (" ".join(words[1:]), " ".join(words[:-1])):
        payload = get_json(
            _WIKI_HOST, _WIKI_PATH, _search_params(f'intitle:"{phrase}"'), {}, timeout
        )
        out.extend(_ranked(payload))
        if out:
            break
    return out


def same_name(title: str, heading: str) -> bool:
    """То же ли это имя картины: заголовок статьи против того, что назвал человек.

    Сверка тесная нарочно - ею гейт добора решает, можно ли верить имени со справки там,
    где сверить его больше не с чем (:func:`~torrcast.cli._second_language`). Годится
    только само имя: точное (:func:`akin` знает и другой порядок слов, и слитное
    написание) либо в другой транскрипции - одна буква расхождения, «сальтберн» и
    «солтберн». Коротким именам и она не прощается: у имени из пяти букв одна буква
    разницы - это уже другое имя («Психо» и «Психи»).

    ⚠️ Одно слово из нескольких сюда НЕ входит, и это вся разница с :func:`_near_name`.
    «Все мы незнакомцы» и «Все мы убийцы» расходятся ровно в одном слове из трёх - и это
    разные картины (2023 и 1952 годов), а не описка.

    🔴 TC-338. Два соседних случая тоже не то же имя, хотя формально близки:

    * **номер части - не описка**: «Крепкий орешек 2» и «Крепкий орешек 3» различаются
      одной буквой-цифрой, и разбор «одна правка по слагу» признавал их одним именем.
      Цифра в имени - это другая часть франшизы, а не неверно нажатая клавиша: расхождение
      единственной цифрой имени не прощается (:func:`_digit_edit`);
    * **часть франшизы - не целое**: на голое «матрица» статья «Матрица: Перезагрузка»
      отвечать не вправе - это одна из частей, а не названное имя. Поэтому :func:`akin`
      зовётся с ``longer=False``: запрос, длиннее заголовка («Властелин колец: Братство
      кольца» против статьи «Властелин колец»), по-прежнему то же имя, а вот заголовок,
      продолжающий запрос частью франшизы, - нет. Угадать такую статью по сходству теперь
      не выйдет уже в :func:`_misremembered`, и до гейта она не доезжает вовсе.
    """
    if akin(title, heading, longer=False):
        return True
    wanted = slugify(title).split("-")
    base_words = slugify(heading.split(" (")[0]).split("-")
    if (
        len(wanted) == len(base_words) + 2
        and wanted[-len(base_words) :] == base_words
        and all(len(word) <= 3 for word in wanted[:2])
    ):
        return True
    name = heading.split(" (")[0]
    # Сверяем однородное с однородным: «Сальтберн» и «Солтберн» расходятся на две буквы
    # («а»/«о» и мягкий знак), а те же имена транслитом - ``saltbern`` и ``soltbern`` -
    # ровно на одну. Мягкий знак имя не различает, и латинская пара это знает.
    for want, base in (
        (slugify(title), slugify(name)),
        (slugify(transliterate(title)), slugify(transliterate(name))),
    ):
        if (
            want
            and base
            and len(want) >= _NEAR_LETTERS
            and _one_edit(want, base)
            and not _digit_edit(want, base)
        ):
            return True
    return False


def _near_name(title: str, heading: str) -> bool:
    """Почти то же имя: одна буква расхождения либо одно слово, которое имя перевешивает.

    Сверка последнего шага (:func:`_misremembered`), и она нарочно тесная - подсказки
    Википедии на «Сальтберн» приносят и «Сальтерас», и «Сальтенья», и «Салитерник, Цви».

    * **то же имя** (:func:`same_name`) - в том числе в другой транскрипции;
    * **одно слово** - имя из трёх и более слов, в котором ровно одно стоит не то:
      «мужчина который удивил всех» против «человек который удивил всех». Слов должно быть
      поровну и на своих местах: перестановки и пропуски сюда не входят, а само расхождение
      обязано перевесить совпавшим (:func:`_outweighed`).

    ⚠️ Второе послабление всё равно доказывает меньше первого: перевесить умеет и соседняя
    часть франшизы («Планета обезьян: Война» против «Планета обезьян: Революция»). Отсюда
    отметка :attr:`Origin.guessed` - имя, найденное этой сверкой, гейту добора не
    доказательство.
    """
    if same_name(title, heading):
        return True
    name = heading.split(" (")[0]
    for want, base in (
        (slugify(title), slugify(name)),
        (slugify(transliterate(title)), slugify(transliterate(name))),
    ):
        if not want or not base:
            continue
        mine, theirs = want.split("-"), base.split("-")
        if len(mine) >= _PHRASE_WORDS and len(mine) == len(theirs):
            odd = [
                spot
                for spot, (one, two) in enumerate(zip(mine, theirs, strict=True))
                if not same_word(one, two)
            ]
            if not odd or (len(odd) == 1 and _outweighed(mine, theirs, odd[0])):
                return True
    return False


#: Во сколько раз совпавшая часть имени обязана перевесить разошедшееся слово. Полтора -
#: это «мальчик и цапля» против «Мальчик и птица» (8 букв совпало, 5 разошлось), но уже
#: не «Все мы незнакомцы» против «Все мы убийцы» (5 против 10).
_ODD_WEIGHT: Final = 1.5


def _outweighed(mine: list[str], theirs: list[str], spot: int) -> bool:
    """Перевешивает ли совпавшая часть имени то единственное слово, что разошлось.

    🔴 TC-284. Одного слова из трёх мало само по себе: так расходятся и описка, и разные
    картины. Считаем БУКВАМИ, а не словами - разница между двумя случаями в том, сколько
    имени осталось стоять за совпадением:

    * «мужчина который удивил всех» и «Человек, который удивил всех» - совпало «который
      удивил всех», семнадцать букв против семи; спорит одно слово, а имя держат три;
    * «Все мы незнакомцы» и «Все мы убийцы» - совпало «Все мы», пять букв против десяти.
      Совпало тут ровно то, чем подсказчик Википедии искал (общее начало), и картину это
      не называет вовсе: под «Все мы» лежит что угодно.

    Мерка сверялась на 36 парах имён (описки, другие переводы, соседние части франшиз,
    однофамильцы): по одному слову из трёх проходили все 18 чужих картин, с этим весом -
    пять, и ни одна верная пара не потерялась.
    """
    kept = sum(len(word) for place, word in enumerate(mine) if place != spot)
    return kept >= _ODD_WEIGHT * max(len(mine[spot]), len(theirs[spot]))


#: Короче этого одна буква разницы - уже другое имя, а не другая транскрипция.
_NEAR_LETTERS: Final = 7


def _one_edit(one: str, two: str) -> bool:
    """Различаются ли строки не больше чем на одну букву (вставка, пропуск или замена)."""
    if abs(len(one) - len(two)) > 1:
        return False
    short, long = sorted((one, two), key=len)
    head = len(os.path.commonprefix([short, long]))
    if short == long:
        return True
    if len(short) == len(long):
        return short[head + 1 :] == long[head + 1 :]
    return short[head:] == long[head + 1 :]


def _digit_edit(one: str, two: str) -> bool:
    """Единственная разница строк - цифра: номер части («орешек-2»/«орешек-3»), а не описка.

    Зовётся вслед за :func:`_one_edit`, поэтому разница ровно одна и стоит она на первом
    несовпавшем месте. Одна цифра имени - другая часть франшизы, и прощать её как
    неверно нажатую клавишу значило бы пускать «Час пик 3» за «Час пик 2».
    """
    short, long = sorted((one, two), key=len)
    if short == long:
        return False
    head = len(os.path.commonprefix([short, long]))
    if len(short) == len(long):
        return short[head].isdigit() and long[head].isdigit()
    return long[head].isdigit()


def read_origin(
    pages: list[Any], title: str, trusted: bool = False, series: bool | None = None
) -> Origin:
    """Статьи-кандидаты → паспорт. Побеждает первая, которая про кино и про то самое.

    Статья должна быть про кино (:func:`_about_cinema`) — «Восхождение» это ещё и
    альпинизм, а «Матрица» — таблица, — и того же типа, что спросили
    (:func:`_fits_type`). А вот «про то самое» проверяется по-разному, и это ``trusted``.

    * **Поиск Википедии** (``trusted=False``) честно приносит однофамильцев, актёров и
      саундтреки — их отсеивает :func:`akin` по заголовку.
    * **Прямая выборка по имени** (``trusted=True``) — другое дело: имя мы назвали САМИ,
      и до статьи нас довела сама Википедия своим перенаправлением. Спорить с ней
      заголовком нельзя: она за тем и заведена, чтобы знать, что «Уэнсдей» пишется
      «Уэнздей», «ВандаВижн» — «Ванда/Вижн», а «Фруктовая корзинка» — «Корзинка
      фруктов». :func:`akin` все три заголовка отвергала, и справка молчала ровно там,
      где знала ответ: на этих именах поиск и оставался без оригинала.

    Название латиницей ищется по убыванию точности: скобка первой фразы («англ. …»),
    затем заголовок английской статьи, затем сам заголовок, если он и так на латинице
    (франшиза «Kingsman» подписана именно так — и именно так её ищут индексеры).

    ⚠️ Спросили ЛАТИНИЦЕЙ - :func:`akin` бессильна: заголовок русской статьи про «Тачки»
    с запросом ``cars`` не сверить ничем. Тождество тогда доказывает сам оригинал: статья
    «Тачки» открывается скобкой «англ. Cars», и это ровно то имя, которое спросили. Точное
    равенство обязательно - поиск Википедии по слову ``cars`` первой приносит «Тачки 4»
    («англ. Cars 4»), и на вхождении подстрокой человек получил бы не ту картину.

    ⚠️ Голое имя франшизы частью франшизы не отвечается (:func:`_crowded`): «гарри поттер»
    приносил паспорт ПЯТОГО фильма, добор уходил по его оригиналу и приводил 79 чужих
    раздач одной части. Либо статья самой франшизы, либо ничего.
    """
    crowd = _crowded(title, pages)
    shortened = Origin()
    for page in pages:
        if page is None:
            continue
        heading = str(page.get("title") or "")
        extract = str(page.get("extract") or "")
        if not _about_cinema(heading, extract) or not _fits_type(series, heading, extract):
            continue
        latin = (
            latin_title(extract)
            or english_title(page)
            or ("" if _CYRILLIC.search(heading) else heading)
        )
        if (
            not trusted
            and not akin(title, heading, longer=not crowd)
            and not _same_latin(title, latin)
        ):
            if not shortened and _localized_short_name(title, heading, latin):
                shortened = Origin(
                    title=latin,
                    name=_TAIL_RE.sub("", heading),
                    entity=str((page.get("pageprops") or {}).get("wikibase_item") or ""),
                    guessed=True,
                )
            continue
        found = Origin(
            title=latin,
            year=picture_year(extract),
            name=_TAIL_RE.sub("", heading) if _CYRILLIC.search(heading) else "",
            entity=str((page.get("pageprops") or {}).get("wikibase_item") or ""),
            namesake=namesake(pages, heading, picture_year(extract)),
        )
        if found:
            return found
    return shortened


def namesake(pages: list[Any], heading: str, year: int | None) -> str:
    """Заголовок ДРУГОЙ картины того же года, которую справка знает под тем же именем.

    🔴 TC-371. Двусмысленность бывает не в отборе, а в самих источниках: именем «Девять» и
    годом 2009 в русском прокате подписаны две разные картины - мюзикл (``Nine``) и
    мультфильм (``9``). Каталог сводит их в одну кучку: имя и год - оба признака отбора - у
    них совпадают, а больше в раздачах не сказано ничего. Развести их разбором нечем, и
    молчать об этом нельзя: человек просит «девять», получает одну из двух, и объяснения
    нет ни строчки.

    Признак стоит ровно ноль: статьи уже приехали. Справка спрашивается сразу под всеми
    уточнениями (:data:`_QUALIFIERS`), «(мультфильм)» и «(фильм)» среди них, и обе картины
    лежат в одном ответе - остаётся их сосчитать.

    Ограждения два, и оба про то, чтобы строка не стала шумом:

    * год ОДИН И ТОТ ЖЕ. Одноимённых картин в справке полно («Дюна» 1984 и 2021, «Моана»
      2016 и 2026), но год их разводит, и разводит его же отбор - говорить не о чем;
    * статья ДРУГАЯ: тот же заголовок приезжает по нескольку раз, потому что под разными
      уточнениями лежит одно перенаправление.

    Про кино ли вторая статья, решает тот же гейт, что и для первой (:func:`_about_cinema`):
    у «Матрицы» под тем же именем лежит таблица, и картиной она не станет.
    """
    if year is None:
        return ""
    for page in pages:
        if page is None:
            continue
        other = str(page.get("title") or "")
        extract = str(page.get("extract") or "")
        if other == heading or not _about_cinema(other, extract):
            continue
        if picture_year(extract) == year:
            return other
    return ""


def _localized_short_name(title: str, heading: str, latin: str) -> bool:
    """Прокатное имя длиннее заголовка на два коротких начальных слова.

    Так русская статья ``Незнакомцы`` находится по прокатному имени ``Все мы
    незнакомцы``: её оригинал ``All of Us Strangers`` подтверждает, что короткий
    заголовок не потерял слова картины. Одного совпавшего хвоста недостаточно - первый
    же кандидат поиска ``The Strangers`` был бы одноимённым фильмом 2008 года.

    Это по-прежнему догадка справки, поэтому найденный паспорт получает ``guessed`` и
    проходит обычный гейт второго захода, а не выдаётся за точное имя.
    """
    wanted = slugify(title).split("-")
    base = slugify(heading.split(" (")[0]).split("-")
    original = slugify(latin).split("-")
    return (
        len(wanted) == len(base) + 2
        and wanted[-len(base) :] == base
        and all(len(word) <= 3 for word in wanted[:2])
        and len(original) >= len(wanted)
    )


def _about_cinema(heading: str, extract: str) -> bool:
    """Про кино ли статья: либо назван киношный тип, либо экранный признак вместе с жанром.

    Гейт молчания: не пройдя его, статья не даст ни оригинала, ни года. Он же - главное
    ограждение справки, потому что оригинал вычитывается из первой скобки статьи
    (:func:`latin_title`), а такая скобка есть у кого угодно: у человека («англ. William
    Bradley Pitt»), у книги («англ. Dune» в статье о романе Герберта), у компании. Тихо
    подменить картину чужой строкой страшнее, чем промолчать, поэтому список типов -
    именно белый: чего в нём нет, того справка не знает.

    Второй путь нужен статьям, где тип записан описательно: «Во все тяжкие» открывается
    словами «американская телевизионная криминальная драма», и киношного слова там нет
    вовсе. Экранный признак и жанр требуются ОБА - поодиночке каждый врёт: «телевизионная
    сеть» это NBC, а «драма» бывает театральной.

    Третий путь - паспортная формула произведения, и заведён он ради неанглийской
    классики (TC-138). Статью о ней Википедия пишет без слова «фильм» в именительном:
    «Похитители велосипедов» (итал. Ladri di biciclette) - драма Витторио Де Сика 1948
    года»,  «Семь самураев» - «эпическая самурайская кинодрама ... в 1954 году». Первые
    два пути такую статью отвергали, справка молчала, и поиск уходил в индексер
    транслитом ``pokhititeli velosipedov`` - при живом ``Ladri di biciclette``.
    Требуются ВСЕ три приметы разом, и каждая отсекает свой класс чужих статей:

    * название в кавычках в начале фразы - так подписывают произведение, а не человека
      («Витторио Де Сика ... - итальянский кинорежиссёр» мимо, и это важно: у режиссёра
      в скобке своё имя латиницей, и справка выдала бы его за название картины);
    * жанр - роман, опера и пьеса своих жанров сюда не отдают («Дюна» - «роман»);
    * год выхода - у произведения он есть, у понятия и термина его нет.
    """
    text = f"{heading} {extract}"
    if _CINEMA_RE.search(text):
        return True
    if _SCREEN_RE.search(text) and _GENRE_RE.search(text):
        return True
    first = sentence(extract)
    return bool(_TITLED_RE.match(first) and _GENRE_RE.search(first) and _MADE_RE.search(first))


def picture_year(extract: str) -> int | None:
    """Год САМОЙ картины из статьи; не уверены - ``None``, и это честнее числа наугад.

    Год паспорта сильнее выдачи, поэтому ошибиться в нём - то же самое, что подменить
    картину. А брался он первым попавшимся «NNNN года» по всей первой врезке, и в статьях
    об экранизациях это через раз год СОСЕДА: у сериала «Фарго» 2014 года врезка второй
    фразой говорит «вдохновлён фильмом 1996 года», у «Дедвуд: Фильм» 2019 года - «по
    мотивам сериала 2006 года». Справка уверенно называла 1996 и 2006.

    Поэтому год ищется в два шага. Сначала - в первой фразе: там стоит паспортная формула
    («американский компьютерно-анимационный фильм 2006 года»), и она про эту картину, а не
    про соседа. Нет его там - годимся только на единогласие: когда во всей врезке год
    назван один-единственный, спутать его не с чем («Мастер и Маргарита (телесериал, 2005)»
    - только 2005). Названо несколько - выбирать между ними нечем, и мы молчим.
    """
    first = _YEAR_RE.search(sentence(extract))
    if first:
        return int(first.group(1))
    named = {match.group(1) for match in _YEAR_RE.finditer(extract)}
    return int(named.pop()) if len(named) == 1 else None


def _fits_type(series: bool | None, heading: str, extract: str) -> bool:
    """Того ли типа статья, что спросили: сериал против фильма.

    Гейт против худшего брака справки - молчаливой подмены картины её ЭКРАНИЗАЦИЕЙ.
    Тип картины у поиска есть, и он подсказывается (:func:`origin`), но одной подсказки
    мало: она только двигает кандидата с нужным уточнением в начало очереди
    (:func:`origin_now`), а не выкидывает чужие. Статьи «Атака титанов (телесериал)» в
    русской Википедии нет вовсе, и очередь спокойно доходила до «Атака титанов (фильм)» -
    японского игрового фильма 2015 года. Дальше не спасало ничто: статья про кино, гейт
    :func:`_about_cinema` её пропускал, заголовок под запрос подходил (:func:`akin` -
    «Атака титанов» слово в слово), а год ей никто не подсказывает. И поиск уходил
    добирать чужую картину с паспортом, который сильнее выдачи.

    Сверяется ОБЪЯВЛЕННЫЙ тип - тот, которым статья открывает первую фразу («японский
    художественный фильм», «американский телесериал-антология»), - и только по первой
    фразе с заголовком: дальше по тексту «фильм» и «сериал» стоят про соседей по
    франшизе, а не про саму картину.

    Отказ - только на ПРЯМОМ противоречии: статья назвала чужой тип и не назвала нужный.
    Молчание о типе отказом не считается, и это не поблажка, а необходимость: «Во все
    тяжкие» открывается словами «американская телевизионная криминальная драма» (ни
    «фильма», ни «сериала»), а «Блич» - «манга Тайто Кубо и её аниме-адаптации». Требуй
    мы явного слова, справка замолчала бы на картинах, которые сегодня знает.
    """
    if series is None:
        return True
    text = f"{heading} {sentence(extract)}"
    said_film = bool(_FILM_WORD_RE.search(text))
    said_series = bool(_SERIES_WORD_RE.search(text))
    asked, other = (said_series, said_film) if series else (said_film, said_series)
    return asked or not other


def _same_latin(title: str, latin: str) -> bool:
    """Спросили латиницей, и статья назвала ровно это же имя оригиналом - та самая картина."""
    wanted = slugify(title)
    return bool(wanted) and not _CYRILLIC.search(title) and slugify(latin) == wanted


def english_title(page: Any) -> str:
    """Как та же картина называется в английской Википедии; уточнение в скобке отрезано.

    Русская статья пишет оригинал в первой фразе не всегда: у аниме в скобке стоят
    иероглифы («Юная революционерка Утэна» — 少女革命ウテナ), и латиницы там нет вовсе.
    Межъязыковая ссылка отвечает на тот же вопрос и едет тем же запросом
    (:func:`_extract_params`), а «(TV series)» и «(film)» на конце — это разметка
    Википедии, а не часть имени: индексеру с ней делать нечего.
    """
    links = page.get("langlinks") or [] if isinstance(page, dict) else []
    name = str(links[0].get("title") or "") if links else ""
    return _TAIL_RE.sub("", name).strip()


def akin(title: str, heading: str, longer: bool = True) -> bool:
    """Про то же ли это, что спросили: заголовок статьи против запроса.

    Уточнение в скобках отбрасывается («Восхождение (фильм, 1976)» → «Восхождение»), а
    запрос сверяется и как есть, и латиницей: статья про «Кингсман» называется
    ``Kingsman``, и по-русски её заголовок не узнать.

    ⚠️ Сверяется НАЧАЛО имени, а не вхождение куда попало. «Ганнибал: Восхождение» тоже
    содержит слово «восхождение», и на вхождении справка уверенно выдавала его паспорт за
    паспорт фильма Шепитько - то есть ровно ту подмену, которую и должна ловить.

    Пробелы и знаки между словами картину не различают: статья про «ВандаВижн» называется
    «Ванда/Вижн», и одна косая черта делала имена чужими. Поэтому к трём сверкам добавлена
    четвёртая - точное равенство имён, у которых убраны все разделители. Именно точное:
    склей разделители у «начала имени», и «восхождение» совпало бы с «Ганнибалом».

    Пятая сверка - те же слова в другом порядке и другой форме (:func:`~torrcast.parse.same_words`):
    классику человек называет по памяти, и «Крики и шёпот» - это статья «Шёпоты и крики».

    ⚠️ ``longer`` запрещает шестую сверку - ту, где ДЛИННЕЕ заголовок статьи («Кингсман» →
    «Кингсман: Секретная служба»). Сверка нужная, но именно ею справка подменяла франшизу
    случайной частью: на голое «гарри поттер» ей подходили и «Орден Феникса», и
    «Принц-полукровка», и «узник Азкабана», а побеждал тот, кого выше поставил поиск.
    Выключает её :func:`_crowded` - там, где таких продолжений в выдаче несколько: одно
    продолжение это уточнение имени, а несколько - выбор части наугад.
    """
    base = slugify(heading.split(" (")[0])
    solid = base.replace("-", "")
    return bool(base) and any(
        want
        and (
            want == base
            or want.startswith(f"{base}-")
            or (longer and base.startswith(f"{want}-"))
            or want.replace("-", "") == solid
            or same_words(want, base)
        )
        for want in (slugify(title), slugify(transliterate(title)))
    )


def _crowded(title: str, pages: Iterable[Any]) -> bool:
    """Продолжают ли запрошенное имя сразу несколько статей выдачи.

    Так выглядит запрос голым именем франшизы: «гарри поттер» продолжают «Гарри Поттер и
    Орден Феникса», «...и Принц-полукровка», «...и узник Азкабана». Выбрать из них нечем -
    человек не называл части, - и любой выбор был бы молчаливой подменой картины. Значит
    годится только статья, названная РОВНО так же (сама франшиза), либо ничего.

    Одно продолжение - другое дело: «Кингсман» продолжает единственная статья «Кингсман:
    Секретная служба», и это не выбор, а уточнение имени.
    """
    wants = [want for want in (slugify(title), slugify(transliterate(title))) if want]
    seen = {
        base
        for page in pages
        if page is not None
        for base in (slugify(str(page.get("title") or "").split(" (")[0]),)
        if base and any(base.startswith(f"{want}-") for want in wants)
    }
    return len(seen) > 1


def latin_title(extract: str) -> str:
    """Оригинальное название из первой фразы статьи; нет латиницы — пустая строка.

    Русская Википедия открывает статью о зарубежном кино скобкой с языком оригинала:
    «Кингсман: Секретная служба» (англ. Kingsman: The Secret Service). Скобок в фразе
    бывает несколько, и не все они про название — «(род. 1950)» у режиссёра тоже скобка
    с сокращением, поэтому годится лишь та, внутри которой латиница и нет кириллицы.
    Хвост после запятой отрезается: там лежит дословный перевод, а не имя раздачи.

    ⚠️ Иероглифы отсекаются наравне с кириллицей. У японского кино скобка двуязычна -
    «(яп. 進撃の巨人 エンド オブ ザ ワールド Shingeki no Kyojin: Endo obu za Wārudo)», - и латиница
    в ней есть, так что прежняя проверка её принимала и отдавала поиску целиком, вместе с
    иероглифами. Искать по такой строке нечего. Пропустив скобку, имя берут из английской
    статьи (:func:`english_title`), где оно записано одним именем.
    """
    for match in _ORIGINAL_RE.finditer(extract):
        name = re.split(r"[,;]", match.group(1))[0].strip(" «»\"'")
        if _CJK.search(name):
            continue
        if re.search(r"[A-Za-z]", name) and not re.search(r"[А-Яа-яЁё]", name):
            return name
    return ""


def sentence(text: str) -> str:
    """Первая фраза статьи целиком — от начала до точки, которая её действительно кончает.

    Википедия открывает статью паспортом («американский компьютерно-анимационный
    спортивный комедийный фильм 2006 года, снятый студией Pixar для кинокомпании Walt
    Disney Pictures») — самодостаточным ответом на «про что кино». Ценность его именно
    в целости: обрубок «американский компьютерно-анимационный…» не говорит ни жанра,
    ни года, а дочитать его негде.

    Точка кончает фразу не всякая, и все три исключения взяты с живых статей:

    * **скобки и кавычки.** «(англ. Cars)» стоит в первой фразе почти каждой статьи о
      зарубежном кино, а у «Оппенгеймера» внутри «ёлочек» лежит название книги с точкой
      посередине («Оппенгеймер. Триумф и трагедия Американского Прометея»). Пока скобка
      или кавычка не закрыта, точка внутри — не граница;
    * **сокращения.** «реж.», «им.», «т. е.» — после них фраза продолжается;
    * **инициалы.** «Г. А. Потёмкина»: одна буква перед точкой словом не бывает.

    Плюс общее правило: за границей фразы идёт пробел и заглавная буква (или кавычка
    названия). «2001: A Space Odyssey» и «6.7» так не разрежешь.

    ⚠️ Перед первой фразой у статьи бывает строка-указатель («О сериале см. статью 7
    самураев.») - её отрезаем (:data:`_HATNOTE_RE`): это разводка одноимённого, а не
    паспорт картины, и читать её как первую фразу - значит приписать картине чужой тип.
    """
    flat = _HATNOTE_RE.sub("", re.sub(r"\s+", " ", text).strip())
    depth = 0
    for pos, char in enumerate(flat):
        if char in "([«“":
            depth += 1
        elif char in ")]»”":
            depth = max(depth - 1, 0)
        elif char in ".!?" and depth == 0 and _ends_phrase(flat, pos):
            return flat[: pos + 1]
    return flat


def _ends_phrase(flat: str, pos: int) -> bool:
    """Кончает ли точка (или «!», «?») на позиции ``pos`` первую фразу."""
    tail = flat[pos + 1 :]
    if tail and not tail.startswith(" "):
        return False  # «2001: A Space Odyssey», «6.7» - точка внутри слова
    word = _LAST_WORD_RE.search(flat[:pos])
    if word and (len(word.group(1)) == 1 or word.group(1).lower() in _ABBREV):
        return False  # «А. Тарковского», «англ.», «т. е.»
    return not tail.strip() or bool(_SENTENCE_START_RE.match(tail.strip()))


def shorten(extract: str, limit: int = BLURB_CAP) -> str:
    """Первая фраза статьи под потолок :data:`BLURB_CAP`; многоточие — только если не влезла.

    Ширина терминала тут ни при чём: фраза переносится по словам (:func:`~torrcast.cli.
    menu_lines`) и занимает столько строк, сколько ей нужно. Обрыв многоточием остаётся
    ровно для того случая, ради которого он и заводился — фраза длиннее всякого разумного.
    """
    first = sentence(extract)
    if len(first) <= limit:
        return first
    cut = first[:limit].rsplit(" ", 1)[0].rstrip(" ,;:-—")
    return f"{cut}..." if cut else ""


def ratings(path: Path | None = None) -> dict[str, str]:
    """``tconst`` → рейтинг из выгрузки IMDb. Нет файла — пустой словарь, и это не сбой.

    Файл читается целиком один раз за запуск и только тогда, когда рейтинг кому-то
    понадобился: на пути показа его не трогают вовсе. С отсечкой по числу голосов,
    которую ставит `install.sh`, это ~2 МБ и сотня тысяч строк — чтение на глаз мгновенное.
    """
    out: dict[str, str] = {}
    try:
        with (path or RATINGS_PATH).open(encoding="utf-8") as handle:
            next(handle, None)  # шапка «tconst averageRating numVotes»
            for line in handle:
                parts = line.split("\t")
                if len(parts) >= 2:
                    out[parts[0]] = parts[1].strip()
    except OSError:
        return {}
    return out


class Facts:
    """Фоновый добор справки: :meth:`start` — и живи дальше, :meth:`get` — забери.

    Поток один на всю франшизу, а не по потоку на картину: оба источника отвечают
    пакетом, и четыре картины стоят ровно столько же, сколько одна.
    """

    def __init__(self, pictures: Iterable[tuple[str, int | None]], budget: float = FACTS_BUDGET):
        self.wanted = list(pictures)
        self.budget = budget
        self.found: dict[tuple[str, int | None], Fact] = {}
        self._done = threading.Event()
        self._thread: threading.Thread | None = None
        self._deadline = 0.0
        self._started = 0.0

    def start(self) -> None:
        """Пустить добор фоном. Ошибки внутри гасятся: справка не вправе ронять показ."""
        self._started = time.monotonic()
        self._deadline = time.monotonic() + self.budget
        if not self.wanted:
            self._done.set()
            return
        self.found = _cached(self.wanted)
        if len(self.found) == len(self.wanted):  # всё уже лежит в кэше - сети не надо
            self._done.set()
            return
        self._thread = threading.Thread(target=self._work, daemon=True)
        self._thread.start()

    def get(self, title: str, year: int | None) -> Fact:
        """Справка по картине; не приехала к :attr:`budget` — пустая, и меню печатается.

        Дедлайн один на всё меню, а не бюджет на строку: иначе франшиза из четырёх картин
        ждала бы молчащий источник вчетверо дольше обещанного.
        """
        self._done.wait(max(0.0, self._deadline - time.monotonic()))
        return self.found.get((title, year), Fact())

    def finish(self) -> None:
        """Дать добору дописать кэш - уже ПОСЛЕ меню, чтобы следующее было полным.

        Дедлайн отпускает МЕНЮ, а не поток: тот идёт дальше и кладёт найденное на диск.
        В живом показе это и так успевает - пока человек читает меню и отвечает, поток
        давно закончил, и здесь ждать нечего. А вот там, где ход обрывается сразу за меню
        (``--dry``, отказ «картин много, а терминала нет»), процесс уносил поток с собой:
        в кэш не попадало ничего, и следующий заход снова печатал голое меню.

        Ждём не с нуля, а остаток :data:`TOPUP_LIMIT` от старта: полторы секунды бюджета
        уже прошли, и на Ctrl-C это оставляет не задержку, а её хвостик.
        """
        thread = self._thread
        if thread is not None:
            thread.join(max(0.0, self._started + TOPUP_LIMIT - time.monotonic()))

    def _work(self) -> None:
        try:
            fresh = fetch(self.wanted)
            # Дописываем к тому, что уже лежало в кэше, а не заменяем: сеть отвечает только
            # про ненайденное, и присваиванием мы выбрасывали справку, которая у нас была.
            self.found = {**self.found, **fresh}
            # Пустой ответ тоже запоминаем - иначе поход за ним повторяется каждое меню.
            _remember(fresh, [key for key in self.wanted if key not in self.found])
        except Exception:
            pass
        finally:
            self._done.set()


def fetch(
    wanted: list[tuple[str, int | None]], timeout: float = HTTP_TIMEOUT
) -> dict[tuple[str, int | None], Fact]:
    """Собрать справку по картинам: Википедия → Wikidata → выгрузка рейтингов.

    Цепочка тут не вся: Wikidata спрашивают по идентификаторам из Википедии, и эти два
    запроса иначе как друг за другом не идут. А вот выгрузка рейтингов - файл на диске, с
    сетью не связанный ничем; читалась она третьим шагом, и её сотня тысяч строк ложилась
    на те же полторы секунды дедлайна, что и оба запроса. Теперь она читается ПОКА идёт
    первый запрос и к моменту нужды уже готова.
    """
    scores: dict[str, str] = {}

    def load() -> None:
        nonlocal scores
        scores = ratings()

    reader = threading.Thread(target=load, daemon=True)
    reader.start()
    about, entities = wiki_extracts(wanted, timeout)
    ids = wikidata_ids(sorted(set(entities.values())), timeout) if entities else {}
    reader.join(timeout)
    out: dict[tuple[str, int | None], Fact] = {}
    for key in wanted:
        imdb_id, minutes = ids.get(entities.get(key, ""), ("", 0))
        fact = Fact(
            about=about.get(key, ""),
            rating=f"IMDb {scores[imdb_id]}" if imdb_id in scores else "",
            runtime=hms(minutes),
        )
        if fact:
            out[key] = fact
    return out


def wiki_extracts(
    wanted: list[tuple[str, int | None]], timeout: float
) -> tuple[dict[tuple[str, int | None], str], dict[tuple[str, int | None], str]]:
    """Одним запросом: описания по-русски и Q-идентификаторы Wikidata для второго шага.

    Кандидатов на статью у картины несколько (:func:`titles_for`), и все они уезжают в
    один и тот же запрос — API берёт до :data:`_EXLIMIT` статей за раз. Побеждает первый
    кандидат, который оказался статьёй (не страницей значений, не пустышкой) и подтвердил
    год (:func:`confirms`).
    """
    candidates = {key: titles_for(*key) for key in wanted}
    names: list[str] = []
    for depth in range(max((len(c) for c in candidates.values()), default=0)):
        for key in wanted:
            if depth < len(candidates[key]) and len(names) < _EXLIMIT:
                names.append(candidates[key][depth])
    return _read_pages(
        get_json(_WIKI_HOST, _WIKI_PATH, _extract_params(names), {}, timeout), candidates
    )


def _extract_params(names: list[str]) -> dict[str, str]:
    """Один запрос за первыми фразами сразу нескольких статей и их Q-идентификаторами."""
    return {
        "action": "query",
        "titles": "|".join(names[:_EXLIMIT]),
        "redirects": "1",
        # Ссылка на английскую статью едет тем же запросом и ничего не стоит, а имя за ней
        # - ровно то, которым картину подписывают индексеры. Русская статья про аниме
        # оригинал латиницей не пишет вовсе («Юная революционерка Утэна» - и японские
        # иероглифы в скобке), и без этой ссылки добирать было бы нечем.
        "prop": "extracts|pageprops|langlinks",
        "lllang": "en",
        # Потолок общий на все статьи запроса, а не на каждую: с ``1`` ссылка приезжала бы
        # только у первой из них, и повезло бы не тому кандидату.
        "lllimit": str(_EXLIMIT),
        "ppprop": "disambiguation|wikibase_item",
        "exintro": "1",
        "explaintext": "1",
        "exchars": str(_EXCHARS),
        "exlimit": str(_EXLIMIT),
        "format": "json",
        "formatversion": "2",
    }


def _read_pages(
    payload: Any, candidates: dict[tuple[str, int | None], list[str]]
) -> tuple[dict[tuple[str, int | None], str], dict[tuple[str, int | None], str]]:
    """Разобрать ответ Википедии: кандидат → статья → описание и Q-идентификатор.

    Запрошенное имя и заголовок статьи — не одно и то же: API нормализует регистр и ведёт
    по перенаправлениям, и «Моана (мультфильм)» вполне может ответить статьёй с другим
    заголовком. Обратный путь API отдаёт сам, списками ``normalized`` и ``redirects``.
    """
    hops, pages = _pages(payload)
    about: dict[tuple[str, int | None], str] = {}
    entities: dict[tuple[str, int | None], str] = {}
    for key, names in candidates.items():
        for name in names:
            page = _article(name, hops, pages)
            if page is None:
                continue
            extract = page.get("extract") or ""
            if not confirms(extract, key[1]):
                continue
            about[key] = extract
            props = page.get("pageprops") or {}
            if props.get("wikibase_item"):
                entities[key] = props["wikibase_item"]
            break
    return about, entities


def _search_params(query: str) -> dict[str, str]:
    """Тот же запрос, но статьи выбирает поиск Википедии, а не мы перебором имён."""
    return {
        **_extract_params([]),
        "titles": "",
        "generator": "search",
        "gsrsearch": query,
        "gsrlimit": str(_SEARCH_HITS),
        "gsrnamespace": "0",
    }


def _ranked(payload: Any) -> list[Any]:
    """Найденные статьи в порядке выдачи поиска; страницы значений сюда не попадают."""
    _hops, pages = _pages(payload)
    out = [page for page in pages.values() if "disambiguation" not in (page.get("pageprops") or {})]
    return sorted(out, key=lambda page: int(page.get("index") or _SEARCH_HITS))


def _pages(payload: Any) -> tuple[dict[str, str], dict[str, Any]]:
    """Ответ Википедии → (обратный путь имён, статьи по заголовку)."""
    query = payload.get("query", {}) if isinstance(payload, dict) else {}
    hops: dict[str, str] = {}
    for kind in ("normalized", "redirects"):
        for hop in query.get(kind, []) or []:
            hops[hop.get("from", "")] = hop.get("to", "")
    return hops, {page.get("title", ""): page for page in query.get("pages", []) or []}


def _article(name: str, hops: dict[str, str], pages: dict[str, Any]) -> Any:
    """Статья по запрошенному имени; страница значений и пустышка статьёй не считаются."""
    seen = name
    for _ in range(3):  # нормализация, затем перенаправление; больше не бывает
        seen = hops.get(seen, seen)
    page = pages.get(seen)
    if not page or page.get("missing") or "disambiguation" in (page.get("pageprops") or {}):
        return None
    return page


def wikidata_ids(items: list[str], timeout: float) -> dict[str, tuple[str, int]]:
    """Q-идентификаторы → (идентификатор IMDb, минуты). Один запрос на все картины.

    Хронометраж берём здесь, а не из выгрузки IMDb, по цене вопроса: за ``title.basics``
    пришлось бы качать 225 МБ. Расхождение с IMDb бывает в пару минут — это разница в том,
    считать ли титры, а не выдумка.
    """
    values = " ".join(f"wd:{item}" for item in items)
    query = (
        f"SELECT ?item ?imdb ?dur WHERE {{ VALUES ?item {{ {values} }} "
        "OPTIONAL { ?item wdt:P345 ?imdb } OPTIONAL { ?item wdt:P2047 ?dur } }"
    )
    head = {"Accept": "application/sparql-results+json"}
    return read_sparql(get_json(_WIKIDATA_HOST, _WIKIDATA_PATH, {"query": query}, head, timeout))


def read_sparql(payload: Any) -> dict[str, tuple[str, int]]:
    """Ответ SPARQL → ``{Q-идентификатор: (tt…, минуты)}``; чего нет — того нет."""
    out: dict[str, tuple[str, int]] = {}
    if not isinstance(payload, dict):
        return {}
    rows = (payload.get("results", {}) or {}).get("bindings", [])
    for row in rows:
        item = row.get("item", {}).get("value", "").rsplit("/", 1)[-1]
        if not item.startswith("Q"):
            continue
        imdb = row.get("imdb", {}).get("value", "")
        raw = row.get("dur", {}).get("value", "")
        minutes = int(float(raw)) if re.fullmatch(r"\d+(\.\d+)?", raw) else 0
        out[item] = (imdb, minutes)
    return out


def _key(title: str, year: int | None) -> str:
    return f"{title}|{year if year is not None else ''}"


def _origin_key(title: str, series: bool) -> str:
    """Паспорта лежат в том же файле, что и справка, но в своём ряду ключей."""
    return f"origin|{'tv' if series else 'movie'}|{title}"


def _read_cache() -> dict[str, Any]:
    """Кэш с диска. Битый или отсутствующий — пустой: перечитаем из сети."""
    try:
        raw = json.loads(CACHE_PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return raw if isinstance(raw, dict) else {}


def _write_cache(raw: dict[str, Any]) -> None:
    """Дописать кэш. Не вышло записать — молчим: это не путь показа."""
    try:
        CACHE_PATH.parent.mkdir(parents=True, exist_ok=True)
        tmp = CACHE_PATH.with_suffix(".tmp")
        tmp.write_text(json.dumps(raw, ensure_ascii=False), encoding="utf-8")
        tmp.replace(CACHE_PATH)
    except OSError:
        pass


def _cached_origin(title: str, series: bool) -> Origin | None:
    """Что лежит в кэше. ``None`` — не спрашивали; пустой паспорт — спрашивали, нет его."""
    row = _read_cache().get(_origin_key(title, series))
    if not isinstance(row, dict):
        return None
    shown = row.get("year")
    return Origin(
        title=str(row.get("title", "")),
        year=shown if isinstance(shown, int) else None,
        name=str(row.get("name", "")),
        entity=str(row.get("entity", "")),
        guessed=bool(row.get("guessed")),
        namesake=str(row.get("namesake", "")),
    )


def _remember_origin(title: str, series: bool, found: Origin) -> None:
    raw = _read_cache()
    raw[_origin_key(title, series)] = {
        "title": found.title,
        "year": found.year,
        "name": found.name,
        # Q-идентификатор нужен на диске, иначе одинокий год (:func:`origin_either`) на
        # втором показе терял бы второй источник и ронял год, подтверждённый на первом.
        "entity": found.entity,
        # Отметка «имя лишь похоже» тоже нужна на диске: без неё гейт добора на втором
        # показе той же картины поверил бы догадке как доказанному имени.
        "guessed": found.guessed,
        # Тёзка того же года (TC-371) - тоже на диск: со второго показа справку не
        # спрашивают вовсе, и честная строка про двусмысленность иначе пропадала бы.
        "namesake": found.namesake,
    }
    _write_cache(raw)


def _cached(wanted: list[tuple[str, int | None]]) -> dict[tuple[str, int | None], Fact]:
    """Что уже лежит на диске. Битый кэш — как пустой: перечитаем из сети.

    Ряд с отметкой ``empty`` — это записанное «справки нет»: картина отдаётся пустой, и в
    сеть за ней не идут. Отметка со сроком (:data:`EMPTY_TTL`): вышел — ряда как не было.
    """
    raw = _read_cache()
    out: dict[tuple[str, int | None], Fact] = {}
    for key in wanted:
        row = raw.get(_key(*key))
        if not isinstance(row, dict):
            continue
        blank = row.get("empty")
        if isinstance(blank, int | float) and time.time() - blank > EMPTY_TTL:
            continue
        out[key] = Fact(
            about=str(row.get("about", "")),
            rating=str(row.get("rating", "")),
            runtime=str(row.get("runtime", "")),
        )
    return out


def _remember(
    found: dict[tuple[str, int | None], Fact],
    misses: Iterable[tuple[str, int | None]] = (),
) -> None:
    """Дописать итог в кэш. Не вышло записать — молчим: это не путь показа.

    ``misses`` — картины, про которые источник ответил, но сказать ему нечего. Раньше они
    в кэш не попадали вовсе, и каждое меню шло за ними в сеть заново: поход не успевал к
    дедлайну, меню печаталось голым, следующее — точно так же. Пустой ответ — тоже ответ,
    и он тоже помнится, только со сроком (:data:`EMPTY_TTL`).
    """
    blanks = list(misses)
    if not found and not blanks:
        return
    raw = _read_cache()
    for key, fact in found.items():
        raw[_key(*key)] = {"about": fact.about, "rating": fact.rating, "runtime": fact.runtime}
    now = int(time.time())
    for key in blanks:
        raw[_key(*key)] = {"about": "", "rating": "", "runtime": "", "empty": now}
    _write_cache(raw)
