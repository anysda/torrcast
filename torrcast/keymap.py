"""Карта опорных кадров файла по HTTP — без скачивания фильма.

Зачем это в пакете, а не в диагностическом скрипте: по этой карте строится **сетка
сегментов** (:class:`torrcast.stream.Grid`). Границы, стоящие на опорных кадрах, дают
сегменты, каждый из которых декодируется сам по себе, — а значит перемотка в любую точку
показывает картинку сразу, а не с ближайшего опорного кадра где-то в середине куска.

Читать ради этого весь фильм нельзя (3–5 ГБ через рой), а ``ffprobe -show_packets``
именно это и делает. Обход один и тот же для обоих контейнеров: у них есть собственный
индекс перемотки, и он берётся Range-запросами.

===========  =========================================  ==========================
контейнер    где индекс                                 модуль
===========  =========================================  ==========================
mkv          ``Cues`` в хвосте, адрес — в ``SeekHead``   :mod:`torrcast.mkv`
mp4          ``stss``/``stts`` в ``moov``, обычно в      :mod:`torrcast.mp4`
             голове файла
===========  =========================================  ==========================

Здесь — только общее: чем читать (:class:`Reader`), что получается (:class:`KeyMap`) и
кто разбирает (:func:`keyframes`, по сигнатуре первых байт). Ни один из разборов не
знает про другой, и оба обязаны отдавать **одинаковую** карту: время опорного кадра от
начала фильма и абсолютное смещение его данных в байтах.

⚠️ Смещение — это начало кластера (mkv) или чанка (mp4), в котором лежит опорный кадр,
то есть место, с которого имеет смысл греть рой под перемотку (§7.2 SPEC-v2). Байт в
байт с первым байтом кадра оно не совпадает и совпадать не обязано.

⚠️ Время — это метка кадра **в контейнере**, и она точна: проверено побайтно на трёх
релизах (``scripts/mapcheck.py``, 07-08-2026) — время из ``Cues`` совпало с ``Timestamp``
кластера и с меткой самого блока до тысячной, Δ 0.000 во всех точках. При упаковке от
нуля метки всего фильма сдвинуты на один кадр вперёд (ffmpeg не пускает dts ниже нуля),
поэтому сравнивать карту с готовыми сегментами нужно с допуском в кадр, а не побайтно.

⚠️ И сравнивать — только с сегментами, упакованными с ``-muxdelay 0 -muxpreload 0``
(:data:`torrcast.stream.MPEGTS_MUX_DELAY`). Мультиплексор mpegts по умолчанию добавляет
к меткам свои 1.4 с, и разница карты с таким сегментом — это его добавка, а не ошибка
карты. Ровно на этом сгорело расследование §6.2.2 SPEC-v2.
"""

from __future__ import annotations

import itertools
import urllib.error
import urllib.request
from typing import Final, NamedTuple

from torrcast import InfraError, why

__all__ = ["HEAD_PEEK", "KeyMap", "Point", "Reader", "keyframes", "video_track"]

#: Сколько головы читаем сначала. Этого куска хватает и на то, чтобы узнать контейнер,
#: и на то, чтобы найти индекс: у mkv в первых килобайтах лежат SeekHead и Info, у mp4 —
#: заголовок ``moov``. У роя это не вопрос байтов, а вопрос **очереди**: пока не приехала
#: голова, запрос к любому другому месту даже не отправлен. Замер 06-08-2026 на стенде:
#: 4 МиБ головы стоят 1.5–5.2 с, 256 КиБ — 0.2–0.6 с.
HEAD_PEEK: Final = 256 << 10


class Point(NamedTuple):
    """Опорный кадр: время от начала фильма, абсолютное смещение в байтах, номер дорожки."""

    at: float
    offset: int
    track: int


class KeyMap(NamedTuple):
    """Карта опорных кадров файла и цена её снятия."""

    duration: float
    points: tuple[Point, ...]
    taken: int
    requests: int
    #: Контейнер, ``mkv`` или ``mp4``. Он уже известен по первым байтам головы, и знать
    #: его дальше по пути стоит ноль запросов, а решает многое: сколько головы греть,
    #: чтобы ffmpeg открыл вход (§7.3 SPEC-v2), — у mp4 там ``moov`` на мегабайты, у
    #: mkv хватает килобайт.
    kind: str = ""


class Reader:
    """Range-запросы к одному URL со счётчиком выкачанного — цена замера видна глазами."""

    def __init__(self, url: str, timeout: float = 120.0) -> None:
        self.url = url
        self.timeout = timeout
        self.taken = 0
        self.requests = 0

    def read(self, offset: int, size: int) -> bytes:
        request = urllib.request.Request(
            self.url, headers={"Range": f"bytes={offset}-{offset + size - 1}"}
        )
        try:
            with urllib.request.urlopen(request, timeout=self.timeout) as answer:
                data: bytes = answer.read()
        # ValueError — это «источник вообще не URL» (путь к файлу в тестах и на dev).
        # Без неё показ падал бы ещё до упаковки там, где достаточно ровной сетки.
        except (urllib.error.URLError, OSError, ValueError) as exc:
            raise InfraError(f"не читается голова файла: {why(exc)}") from exc
        self.taken += len(data)
        self.requests += 1
        return data


def keyframes(url: str) -> KeyMap:
    """Длительность и опорные кадры файла. Контейнер не тот или индекса нет — :class:`InfraError`.

    Контейнер узнаётся по первым байтам той же головы, которая нужна разбору, — лишнего
    захода к рою на «а что это за файл» не делается. Дальше работает разбор своего
    контейнера, и он же решает, сколько ещё читать.
    """
    reader = Reader(url)
    head = reader.read(0, HEAD_PEEK)
    if head[:4] == b"\x1a\x45\xdf\xa3":  # EBML — mkv/webm
        from torrcast import mkv

        return mkv.keys(reader, head)
    # ISO BMFF: первый бокс файла — ftyp (иногда его нет и файл начинается сразу с moov).
    if head[4:8] in {b"ftyp", b"moov", b"free", b"skip", b"mdat", b"wide"}:
        from torrcast import mp4

        return mp4.keys(reader, head)
    raise InfraError("это не mkv и не mp4: карту опорных кадров взять неоткуда")


def video_track(points: tuple[Point, ...]) -> int:
    """Дорожка видео: та, чьи точки покрывают фильм без длинных пробелов.

    Нужно это ради mkv: Cues пишутся и для звука с субтитрами (у «Моаны 2» их шесть), а
    нас интересует ровно та дорожка, по которой ffmpeg будет резать сегменты.
    ⚠️ «Больше всего точек» — неверный признак: у той же «Моаны 2» самая многочисленная
    дорожка (1786 точек) это звук, и пробелы в ней до 65 с, тогда как у видео (1119
    точек) — не больше 10.4 с. Поэтому берём по самому короткому наибольшему пробелу: у
    видео опорный кадр обязан быть регулярным, у звука точки ставятся как придётся.

    У mp4 гадать не приходится вовсе: ``hdlr`` называет тип дорожки прямо, и разбор
    отдаёт точки одной дорожки — тогда эта функция просто возвращает её номер.
    """

    def widest(track: int) -> tuple[float, int]:
        at = [p.at for p in points if p.track == track]
        gaps = [b - a for a, b in itertools.pairwise(at)]
        return (max(gaps, default=float("inf")), -len(at))

    return min({p.track for p in points}, key=widest)
