def in_digits(slug: str) -> str:
    """Слаг, где числительное СЛОВОМ записано цифрой: ``двенадцать-обезьян`` → ``12-обезьян``.

    Каталог подписывает число как придётся, и одна картина рассыпается на две кучки
    ровно по этому шву. Живой случай, ради которого написано: «Двенадцать обезьян»
    (1995) приезжает 35 строками, из них 29 раздач под именем «12 обезьян» (до 105
    сидов) и ОДНА - под именем прописью, образ диска на 4 сида. Имена как строки
    разные, поэтому :func:`glue` их не сшивал, а :func:`pick_franchise` по запросу
    прописью отдавал ту самую единственную раздачу: в меню выходило «раздач 1» при
    живой выдаче в тридцать.

    Замена пословная и только по точному совпадению слова: «двенадцать» - число,
    а «двенадцатая ночь» или «семья» - уже нет, и трогать их незачем.
    """
    return "-".join(_NUMERALS.get(word, word) for word in slug.split("-"))


#: Сколько знаков обязано остаться от названия, чтобы хвостовое число считалось номером
#: части. Франшизы из одной буквы не бывает: «Т-34» - это марка танка, а не тридцать
#: четвёртая часть серии «Т». Без порога картина уезжала во франшизу с ключом ``т``, где
#: ей соседями становились любые другие однобуквенные огрызки, а номером пункта меню -
#: тридцать четыре.
_FRANCHISE_MIN: Final = 2


#: Каналы, которыми каталог подписывает документалистику СПЕРЕДИ: «BBC. Живая планета»,
#: «Discovery. Смертельный улов», «BBC: Планета Земля 3». Это не часть названия и не
#: подзаголовок, а марка вещателя, и франшизой картины ей быть незачем.
#:
#: ⚠️ Требуется знак после имени канала - точка или двоеточие с пробелом. Без него имя
#: канала вполне может быть первым словом самого названия: «BBC Proms», «BBC Springwatch»,
#: «BBC Arena» лежат в каталоге ровно так, и резать у них нечего.
_CHANNEL_RE: Final = re.compile(
    r"^(?:bbc|discovery|national\s+geographic|nat\s+geo(?:\s+wild)?|animal\s+planet"
    r"|pbs|nhk|arte|би-би-си)\s*[.:]\s+(?=\S)",
    re.IGNORECASE,
)


def _unbranded(title: str) -> str:
    """Название без марки вещателя спереди (:data:`_CHANNEL_RE`); нечего резать - как было."""
    return _CHANNEL_RE.sub("", title.strip(), count=1)


def franchise_key(title: str) -> str:
    """Каноническое имя франшизы: «Матрица: Перезагрузка» и «Тачки 3» → одна серия.
    Режем подзаголовок после двоеточия и хвостовой номер части — именно они
    отличают фильмы внутри франшизы.
    """
    return slugify(franchise_name(title)) or slugify(title)


def franchise_name(title: str) -> str:
    """То же, что :func:`franchise_key`, но читаемым текстом: «Cars 3» → ``Cars``.

    ⚠️ Подзаголовок советское кино вводит не двоеточием, а словом «или»: «Кавказская
    пленница, или Новые приключения Шурика», «Ирония судьбы, или С лёгким паром!». Без
    этого разреза классика Гайдая жила в каталоге под своим ключом, а короткий запрос
    «кавказская пленница» точно попадал в ключ РЕМЕЙКА 2014 года - и человек, спросивший
    классику, молча получал ремейк, хотя 22 раздачи оригинала лежали в той же выдаче.

    🔴 TC-297. Имя КАНАЛА спереди подзаголовком не считается (:data:`_CHANNEL_RE`).
    Документалистику каталог подписывает «BBC. Живая планета / BBC. The Living Planet
    (1984)», и разрез по точке оставлял от названия ровно ``BBC``: франшизой картины
    становился канал, в одну кучу с ней сваливались «BBC. Океаны» и всё остальное
    вещание, а запрос «живая планета» не попадал в такой ключ вовсе. Дальше добор шёл
    вторым именем ``BBC`` - строкой, по которой приезжает какое угодно кино, кроме
    спрошенного, - и человек честно читал «по BBC приехала другая картина».
    """
    base = re.split(r"\s*:\s*|\.\s+|,\s+или\s+", _unbranded(title), maxsplit=1)[0]
    # Хвост «3», «- 8», «II», а также диапазон «1-4» у сборников.
    cut = re.sub(
        r"[\s,-]+(?:\d{1,2}(?:\s*[-,]\s*\d{1,2})*|[ivx]{1,4})\s*$", "", base, flags=re.IGNORECASE
    )
    if len(cut.rstrip(" -")) >= _FRANCHISE_MIN:
        base = cut
    return base.rstrip(" -")


def part_number(title: str) -> int | None:
    """Явный номер части в названии: «Тачки 3» → 3, «Терминатор II» → 2, иначе None.

    Номер после «Часть»/``Part`` здесь остаётся номером: по одному названию главу
    одной картины от второй части франшизы не отличить («Дары Смерти: Часть II»
    против «Стражи Галактики. Часть 2»). Это различие требует каталога целиком и
    стоит ступенью позже - :func:`_unchaptered`.
    """
    match = _PART_NUMBER_RE.match(title.strip())
    if not match:
        return None
    head = title[: match.start(1)]
    if len(head.rstrip(" ,-")) < _FRANCHISE_MIN:
        return None  # «Т-34», «В-2»: это марка, а не тридцать четвёртая часть франшизы
    if re.search(r"\d\s*[-,]\s*$", head):
        return None  # «Форсаж 1-4», «Матрица 1,2,3» - это диапазон, а не номер части
    token = match.group(1).lower()
    return int(token) if token.isdigit() else _ROMAN.get(token)


#: Ниже этого числа СТРОК выдачи (:attr:`Picture.rows`) пул картины считается тощим.
#: Число не с потолка: на живом каталоге у картины, найденной целиком, строк десятки
#: («Матрица» 59, «Бешеные псы» 69, «Клан Сопрано» 35), а у картины, до которой русский
#: запрос дотянулся лишь краем, - единицы («Птицы» 1, «Дилижанс» 1, «Дедвуд» 4, «Психо»
#: 10). Между этими кучами широкий провал, и порог стоит в нём: на полной выдаче второй
#: заход не случается вовсе.
#:
#: ⚠️ Строк, а не склеенных раздач - и это не мелочь. Замеры выше сняты общим запросом,
#: где зеркальный торрент приходил от каждого индексера отдельной строкой; склейка по
#: ``infoHash`` (:func:`~torrcast.search.merge`) те же выдачи ужимает на живом стенде со
#: 190 строк до 179 и со 176 до 136. Считай мы тощесть склеенными раздачами - порог
#: поехал бы вниз вслед за зеркальностью круга, и второй заход звался бы там, где
#: каталог полон. Каталог от способа опроса индексеров не меняется - значит и мера не
#: должна.
THIN_POOL: Final = 15

#: Кириллица → латиница. Не ГОСТ, а то, как русские названия пишут в именах раздач:
#: «Брат» → ``brat``, «Ёлки» → ``elki``, «Щи» → ``shchi``.
_TRANSLIT: Final[dict[str, str]] = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e", "ж": "zh",
    "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m", "н": "n", "о": "o",
    "п": "p", "р": "r", "с": "s", "т": "t", "у": "u", "ф": "f", "х": "kh", "ц": "ts",
    "ч": "ch", "ш": "sh", "щ": "shch", "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu",
    "я": "ya",
}  # fmt: skip


#: Латиница → кириллица по РАСКЛАДКЕ клавиш, а не по звучанию: клавиша ``n`` на
#: русской раскладке печатает «т». Это не транслит и путать их нельзя - здесь
#: соответствие физическое.
_LAYOUT: Final[dict[str, str]] = {
    "q": "й", "w": "ц", "e": "у", "r": "к", "t": "е", "y": "н", "u": "г", "i": "ш",
    "o": "щ", "p": "з", "[": "х", "]": "ъ", "a": "ф", "s": "ы", "d": "в", "f": "а",
    "g": "п", "h": "р", "j": "о", "k": "л", "l": "д", ";": "ж", "'": "э", "z": "я",
    "x": "ч", "c": "с", "v": "м", "b": "и", "n": "т", "m": "ь", ",": "б", ".": "ю",
    "`": "ё",
}  # fmt: skip


def unswap_layout(text: str) -> str:
    """Запрос, набранный НЕ ПЕРЕКЛЮЧИВ раскладку: ``«nfxrb»`` → «тачки».

    ``cast nfxrb`` - это «тачки», набранные на английской раскладке, клавиша в клавишу.
    Раскладку забывают все и всегда, а цена промаха тут максимальная: человек читает
    отказ по картине, которая в каталоге лежит двумя десятками раздач.

    Перевод только в одну сторону (латиница → кириллица) и только по клавишам
    (:data:`_LAYOUT`). Обратная сторона не нужна: русскую строку индексеры и так
    находят, а «cars», набранное по-русски, дало бы «сфкы» - слово, которого нет
    ни в одном имени раздачи, и искать по нему нечего.

    ⚠️ Сама по себе эта функция НИЧЕГО не решает и звать её вслепую нельзя: у любой
    латинской строки есть кириллический двойник, и «cars» превратился бы в «сфкы».
    Кто и когда её зовёт, решает :func:`~torrcast.cli._search` - и зовёт ровно тогда,
    когда обычный поиск не принёс НИ ОДНОЙ строки. На живом каталоге это стоит ноль:
    у запроса, который что-то нашёл, второго захода не случается вовсе.
    """
    lowered = unicodedata.normalize("NFKC", text).casefold()
    return "".join(_LAYOUT.get(ch, ch) for ch in lowered)


def transliterate(text: str) -> str:
    """Русское название латиницей; латинские куски и цифры остаются как есть."""
    lowered = unicodedata.normalize("NFKC", text).casefold()
    return re.sub(r"\s+", " ", "".join(_TRANSLIT.get(ch, ch) for ch in lowered)).strip()


#: Латинская буква, у которой в русском написании ДВА равноправных двойника: «кс» и «з».
#: ``Xena`` - это и «Ксена», и «Зена», и обе записи в каталоге живые. Транслит возвращает
#: из «Ксены» ``ksena``, а оригинал в раздаче подписан ``Xena``: как строки они разные,
#: и картина, лежащая под русским именем «Зена», по запросу «Ксена» не находилась вовсе.
_SPELL_X: Final = re.compile(r"x")


def spell(text: str) -> str:
    """Нормализованная транслитерация: «Ксена» и ``Xena`` пишутся одинаково - ``ksena``.

    Простой транслит (:func:`transliterate`) сводит русское написание к латинскому
    буква в букву, но САМА латиница пишет один звук по-разному, и русский переносит его
    то так, то этак (:data:`_SPELL_X`). Нормализация убирает именно это расхождение,
    оставляя всё остальное как есть: это ключ для сверки имён, а не запрос в индексер.
    """
    return _SPELL_X.sub("ks", transliterate(text))


#: Сколько букв слова должны совпасть, чтобы это было одно слово в другой форме. Четыре -
#: это «шепот»/«шепоты» и «самурае»/«самураи», но не «крик»/«кран».
_STEM: Final = 4
#: Насколько хвосты слов вправе разойтись сверх общего начала: русское окончание.
_ENDING: Final = 2


def same_word(one: str, two: str) -> bool:
    """Одно ли это слово: та же строка, та же основа или та же строка другой азбукой.

    Формы слова человек путает свободно: «Робот мечты» вместо «Мечты робота», «Крики и
    шёпот» вместо «Шёпоты и крики». Общее начало от :data:`_STEM` букв и не больше
    :data:`_ENDING` букв хвоста сверх него - это окончание, а не другое слово.

    ⚠️ Транслит сводит русское слово с латинским, но НИКОГДА двух русских между собой:
    мягкий знак он съедает, и «мать» стала бы «матом». Поэтому по звучанию сверяются
    только слова из РАЗНЫХ азбук.
    """
    if one == two:
        return True
    if bool(_CYRILLIC.search(one)) != bool(_CYRILLIC.search(two)):
        one, two = spell(one), spell(two)
        if one == two:
            return True
    common = len(os.path.commonprefix([one, two]))
    return common >= _STEM and len(one) - common <= _ENDING and len(two) - common <= _ENDING


def same_words(want: str, base: str) -> bool:
    """Те же слова, только в другом порядке и в другой форме.

    Классику человек зовёт по памяти, а каталог со справкой подписывают её точно: фильм
    Бергмана лежит под именем «Шёпоты и крики», а спрашивают его «Крики и шёпот»; «Мечты
    робота» спрашивают «Робот мечты». Слово в слово такие имена не совпадают ничем.

    Сверка нарочно тесная, потому что она единственная не требует совпадения по порядку.

    * слов должно быть **поровну** и **каждому** найдётся пара. Иначе «Восхождение»
      совпало бы с «Ганнибал: Восхождение» - той самой подменой, которую ловит
      :func:`~torrcast.facts.akin`;
    * имён из одного слова это не касается вовсе: у них порядок переставлять нечего, а
      совпадение по началу приняло бы «Персону» за «Персонажа»;
    * слово ПЕРЕСТАВЛЕННОЕ отличается от своей пары только окончанием (:func:`same_word`),
      а слово, оставшееся на своём месте, обязано совпасть буква в букву.
    """
    return _paired(want.split("-"), base.split("-"))


def _paired(mine: Sequence[str], theirs: Sequence[str]) -> bool:
    """Каждому слову одного имени нашлась своя пара в другом, и лишних не осталось.

    🔴 Форма слова прощается только ПЕРЕЕХАВШЕМУ слову. Слово, стоящее на том же месте,
    сверяется целиком, и вот почему: «Кольца власти» - это сериал 2022 года, а «Кольцо
    власти» - фильм 2007-го, лежащий в той же выдаче. Имена различает ровно одна буква
    окончания, и прости мы её на месте, запрос молча уезжал бы в чужое кино. Переставленное
    слово - другое дело: «Робот мечты» против «Мечты робота» это не однофамильцы, а одно
    имя, названное по памяти, и порядок тут единственная разница по существу.
    """
    if len(mine) < 2 or len(mine) != len(theirs):
        return False
    left = list(enumerate(theirs))
    for here, word in enumerate(mine):
        pair = next(
            (
                spot
                for spot in left
                if word == spot[1] or (spot[0] != here and same_word(word, spot[1]))
            ),
            None,
        )
        if pair is None:
            return False
        left.remove(pair)
    return True


def alt_query(query: str, releases: Iterable[Release], known: str = "", native: str = "") -> str:
    """Чем ещё называется то, что спросили по-русски: запрос для второго захода.

    Зачем он вообще. Индексеры ищут по ИМЕНИ раздачи, а не по картине: половина
    каталога подписана только латиницей («Psycho.1960.1080p»), и русский запрос до неё
    не достаёт - человеку пришлось бы догадаться набрать «Psycho».

    Источники названия идут по убыванию доверия.

    1. ``known`` - оригинал из справки (:func:`~torrcast.facts.origin`). Он лучший, потому
       что отвечает про ТУ САМУЮ картину, а не про то, что попало в выдачу: «Кингсман:
       Секретная служба» так и находится, хотя в русской выдаче оригинала нет вовсе.
       Подзаголовок здесь не режется - справка уже развела картины между собой, и резать
       нечего.
    2. Оригинал из выдачи: раздачи вида «Психо / Psycho (1960)» несут его сами, и он
       точнее транслита («Психо» → ``Psycho``, а не ``psikho``).
    3. Транслит - когда выдачи нет вовсе и читать нечего; он выручает короткие имена
       русского кино, которые за рубежом так и подписывают (``Brat``). При полностью
       пустой выдаче длинное русское имя транслитом ничем не подтверждено: это не второе
       имя, а тот же запрос другими буквами, и заведомо пустого второго круга для него
       не бывает. Если первая выдача картину уже назвала, транслит остаётся последней
       попыткой - так находятся латинописанные релизы ``Vrata Shteyna``.

    Зеркальный случай - ``native``, русское имя картины из той же справки. Спросили
    латиницей («cars»), а половина каталога подписана по-русски: под именем ``Cars`` в
    выдаче лежит одна мёртвая раздача, а «Тачки» живут четырьмя. Догадаться набрать
    по-русски человек не обязан ровно так же, как и наоборот. Русское имя берётся ТОЛЬКО
    из справки: в выдаче под латинским именем его взять неоткуда - там его и нет.

    🔴 TC-399. Но сперва - оригинал из справки, если он отличается от запроса. Короткое
    обиходное имя («lain») - это не полное название (``Serial Experiments Lain``), и
    добор русским именем тут проигрывает дважды: русскоязычные индексеры отвечают
    дольше всех, и круг добора закрывается кворумом быстрых ДО их ответа, а под
    полным оригиналом та же картина лежит сотней раздач у быстрых. Правило ровно
    зеркальное русской ветке: латинский оригинал от справки, не совпадающий с
    запросом, сильнее русского имени; совпадающий («cars» → ``Cars``) нового круга
    не даст, и тогда берётся русское имя.

    Пустая строка - добирать нечем: имени на другом языке никто не назвал.

    ⚠️ Оригинал ИЗ ВЫДАЧИ берётся по франшизе, поэтому номер части у него отрезается
    (:func:`franchise_name`). Без этого побеждало имя самой многолюдной части, и на
    «тачках» второй заход уходил в «Cars 3»: раздач у третьей части больше всех. Добор
    приносил ещё сорок «Тачек 3» и ни одной «Тачки» 2006 года - а у той в русской выдаче
    только образы DVD, и в меню первая часть выглядела мёртвой при живом 1080p BluRay
    на 66 сидов, который лежал под именем ``Cars 2006``.

    ⚠️ Само по себе это название НИЧЕГО НЕ ДОКАЗЫВАЕТ. Русским именем «Восхождение»
    подписаны и картина Шепитько 1977 года, и китайская 2019-го, поэтому оригинал из
    выдачи вполне может оказаться чужим фильмом. Кто именно приехал по этому имени,
    решает гейт добора в :func:`~torrcast.cli._second_language`, а не эта функция.
    """
    wanted = slugify(query)
    if not _CYRILLIC.search(query):
        known = known.strip()
        if known and not _CYRILLIC.search(known) and slugify(known) != wanted:
            return known
        native = native.strip()
        return native if _CYRILLIC.search(native) and slugify(native) != wanted else ""
    if known and not _CYRILLIC.search(known) and slugify(known) != wanted:
        return known.strip()
    pool = list(releases)
    names = Counter(
        franchise_name(original)
        for release in pool
        if (original := release.original) and _akin(wanted, slugify(release.title))
    )
    for name, _count in names.most_common():
        if name and not _CYRILLIC.search(name) and slugify(name) != wanted:
            return name
    words = slugify(query).split("-")
    return transliterate(query) if pool or len(words) == 1 else ""


def _akin(wanted: str, slug: str) -> bool:
    """Один ли это фильм по slug: точное совпадение или вхождение в любую сторону
    («психо» ↔ «психо-2», «сияние» ↔ «сияние»).
    """
    return bool(wanted) and bool(slug) and (wanted in slug or slug in wanted)


#: Слова-показатели, после которых цифра - часть САМОГО названия, а не номер части
#: франшизы: «Kill Bill: Vol. 1», «Deathly Hallows: Part 2», «Дюна: Часть вторая».
#: Сюда же попадает голая точка или двоеточие: каталог вводит ими подзаголовок, и
#: «Vol.» перед цифрой без слова уже сказал всё, что нужно.
_TITLE_NUMBER_RE: Final = re.compile(
    r"(?:[.:]|\b(?:vol|volume|part|pt|chapter|book|эпизод|часть|ч|глава|том|книга|кн))\s*$",
    re.IGNORECASE,
)


def split_franchise_index(query: str) -> tuple[str, int | None]:
    """Отделить хвостовой номер франшизы: ``«матрица 2»`` → ``("матрица", 2)``. Номер —
    позиция в отсортированной по году франшизе, а не часть названия;
    год (четыре цифры) номером не считается.

    🔴 Цифра после слова-показателя номером НЕ считается. «Kill Bill: Vol. 1» уходил в
    индексер как ``Kill Bill: Vol.`` — имя, которым раздачу не подписывает никто, — и
    каталог терялся целиком ещё до кластеризации: искать по обрубку нечего. То же самое
    ждало «…: Part 2» и «Дюна: Часть 2». Признак — то, что стоит ПЕРЕД цифрой
    (:data:`_TITLE_NUMBER_RE`): слово вроде ``Vol``/``Part``/«Часть» или просто точка с
    двоеточием, которыми каталог вводит подзаголовок.

    Обычный номер части при этом остаётся номером: «Тачки 3», «Моана 2», «Терминатор 2»
    заканчиваются буквой, а не показателем, и режутся как раньше.
    """
    match = re.search(r"^(?P<name>.+?)\s+(?P<index>\d{1,2})$", query.strip())
    if not match:
        return query.strip(), None
    name = match.group("name").strip()
    if _TITLE_NUMBER_RE.search(name):
        return query.strip(), None
    return name, int(match.group("index"))


def parse_episode(text: str) -> Episode | None:
    """Вытащить ``sNeM`` из строки: ``s02e05``, ``2x5``, «2 сезон 5 серия»."""
    for pattern in _SEASON_EPISODE_RES:
        match = pattern.search(text)
        if match:
            return Episode(int(match.group("season")), int(match.group("episode")))
    return None


def split_episode(text: str) -> tuple[str, Episode | None]:
    """Отделить от запроса указание серии: ``«киберпанк 2x5»`` → ``("киберпанк", s2e5)``.
    Хвост вырезается целиком — «2 сезон 5 серия» тоже, иначе в поиск уедет «киберпанк 2».
    """
    for pattern in _SEASON_EPISODE_RES:
        match = pattern.search(text)
        if match:
            rest = f"{text[: match.start()]} {text[match.end() :]}"
            title = re.sub(r"\s+", " ", rest).strip(" .,-—:")
            return title, Episode(int(match.group("season")), int(match.group("episode")))
    return text.strip(), None


class FileLike(Protocol):
    """Файл раздачи глазами парсера — ровно то, что отдаёт TorrServer."""

    @property
    def index(self) -> int: ...
    @property
    def name(self) -> str: ...
    @property
    def size(self) -> int: ...


@dataclass(frozen=True, slots=True)
class EpisodeFile:
    """Файл раздачи, опознанный как серия: список серий = файлы раздачи."""

    index: int
    season: int
    episode: int
    name: str
    size: int = 0

    @property
    def at(self) -> Episode:
        return Episode(self.season, self.episode)


def map_episodes(files: Sequence[FileLike], season_hint: int | None = None) -> list[EpisodeFile]:
    """Файлы раздачи → серии. Пак это или один сезон — решают ФАЙЛЫ, а не имя
    раздачи: сколько сезонов нашлось в путях, столько в ответе и будет.

    Читаем весь список одним способом и проверяем его на связность: сколько файлов
    разобрано, столько и должно выйти разных ``sNeM``. Иначе ``Naruto.Shippuuden.001.
    IPTVRip.2x2.XviD.avi`` (2x2 — телеканал-рипер, а не «2 сезон 2 серия») дал бы всем
    318 файлам один и тот же номер. Не сошлось — пробуем следующий способ:
    полный ``sNeM`` → номер серии без сезона → голый номер (аниме) → порядок файлов.
    """
    videos = [f for f in files if f.name.lower().endswith(VIDEO_EXT)]
    videos = [f for f in videos if not _JUNK_RE.search(f.name)]
    videos = _drop_small(videos)
    for read in (_read_sne, _read_episode_only, _read_bare):
        found = _collect(videos, read, season_hint)
        if found:
            return found
    return _collect(videos, _read_order, season_hint, strict=False)


def _collect(
    videos: Sequence[FileLike],
    read: Callable[[str, int], tuple[int | None, int] | None],
    hint: int | None,
    strict: bool = True,
) -> list[EpisodeFile]:
    """Применить способ чтения ко всем файлам и проверить результат на связность."""
    picked: dict[tuple[int, int], FileLike] = {}
    matched = 0
    for order, item in enumerate(videos, start=1):
        found = read(_base(item.name), order)
        if found is None:
            continue
        matched += 1
        season, episode = found
        if season is None:
            season = _season_of(item.name, hint)
        was = picked.get((season, episode))
        if was is None or item.size > was.size:  # тот же номер дважды - берём файл крупнее
            picked[(season, episode)] = item
    # Разнобой: номера повторяются (значит, читали не то) или разобралась горстка файлов.
    if strict and (not picked or len(picked) * 10 < matched * 9 or matched * 2 < len(videos)):
        return []
    return sorted(
        (EpisodeFile(f.index, s, e, _base(f.name), f.size) for (s, e), f in picked.items()),
        key=lambda f: (f.season, f.episode),
    )


def _read_sne(name: str, _order: int) -> tuple[int | None, int] | None:
    """Полный ``sNeM``: ``S01E01``, ``S01.E01``, ``01x01``, «2 сезон 5 серия»."""
    found = parse_episode(name)
    return (found.season, found.episode) if found else None


def _read_episode_only(name: str, _order: int) -> tuple[int | None, int] | None:
    """Номер серии есть, сезона в имени файла нет: ``E05``, «05 из 24», «5 серия»."""
    for pattern in _EPISODE_ONLY_RES:
        match = pattern.search(name)
        if match:
            return None, int(match.group("episode"))
    return None


def _read_bare(name: str, _order: int) -> tuple[int | None, int] | None:
    """Голый номер серии — норма для аниме: ``[Group] Title 05 [BDRip]``, ``Naruto - 216``.
    Скобки и технические токены (``1920x1080``, ``10bit``, год) выбрасываются, из
    оставшихся чисто числовых токенов берётся последний.
    """
    bare = _BRACKETS_RE.sub(" ", name)
    tokens = [t for t in re.split(r"[\s._\-]+", bare) if t and not _TECH_TOKEN_RE.match(t)]
    numbers = [int(t) for t in tokens if t.isdigit() and len(t) <= 3]
    return (None, numbers[-1]) if numbers else None


def _read_order(_name: str, order: int) -> tuple[int | None, int] | None:
    """Последняя надежда: в именах номеров нет вовсе — нумеруем по порядку файлов."""
    return None, order


def _season_of(path: str, hint: int | None) -> int:
    """Сезон файла: из каталога (``Season 3/``, ``S03/``, «3 сезон»), иначе из имени
    раздачи, иначе первый — односезонные аниме-раздачи о сезоне молчат вовсе.
    """
    folder = path.rsplit("/", 1)[0] if "/" in path else ""
    for pattern in _SEASON_ONLY_RES:
        match = pattern.search(folder)
        if match:
            return int(match.group("season"))
    return hint or 1


def _drop_small(videos: list[FileLike]) -> list[FileLike]:
    """Выбросить огрызки: сэмпл рядом с сериями весит проценты от их размера."""
    sizes = [f.size for f in videos if f.size > 0]
    if len(sizes) < 3:
        return videos
    edge = statistics.median(sizes) * _SMALL_RATIO
    return [f for f in videos if f.size >= edge or f.size == 0]


def _base(path: str) -> str:
    return path.replace("\\", "/").rsplit("/", 1)[-1]


def _bare_episode_span(zone: str) -> tuple[int, ...]:
    """Диапазон серий в хвосте латинского имени: ``Serial Experiments Lain 1-13``.

    Голая пара чисел слишком похожа на диапазон частей сборника, поэтому признак узкий:
    счёт начинается с первой серии, содержит хотя бы три серии, а перед ним стоят не
    меньше трёх слов латиницей. Остальные формы читает общий разбор диапазонов.
    """
    match = re.search(r"^(.+?)\s+1\s*-\s*(\d{1,3})\s*$", zone)
    if not match or len(re.findall(r"[A-Za-z]+", match.group(1))) < 3:
        return ()
    end = int(match.group(2))
    return tuple(range(1, end + 1)) if 3 <= end <= 500 else ()


def parse_release_name(name: str) -> Release:
    """Разобрать имя раздачи в структуру (форматы — в докстринге модуля)."""
    text = _normalize(name)
    year, span = _find_year(text)
    zone, collection = _title_zone(text, span)
    bare_episodes = _bare_episode_span(zone)
    if bare_episodes:
        zone = re.sub(r"\s+1\s*-\s*\d{1,3}\s*$", "", zone)
    title, original, aliases = _split_titles(zone)
    names = (title, *((original,) if original else ()), *aliases)
    latin_names = sum(bool(_LATIN.search(part) and not _CYRILLIC.search(part)) for part in names)
    russian_names = sum(bool(_CYRILLIC.search(part)) for part in names)
    # У одной картины бывают два оригинальных и два переводных имени. Три пары уже
    # перечисляют три картины: «Хоббит / Нежданное путешествие / Пустошь Смауга / ...».
    collection = collection or (latin_names >= 3 and russian_names >= 3)

    quality_match = _QUALITY_RE.search(text)
    quality = _normalize_quality(quality_match.group(1)) if quality_match else None

    season, episode, seasons, episodes, series = _parse_series(text)
    if bare_episodes and not episodes:
        episodes, series = bare_episodes, True
    kind: Kind = "other" if _is_non_video(text) else ("tv" if series else "movie")

    return Release(
        raw_name=name,
        title=title,
        original=original,
        aliases=aliases,
        year=year,
        quality=quality,
        codec=_parse_codec(text),
        source=_parse_source(text),
        hdr=bool(_HDR_RE.search(text)),
        voices=_parse_voices(text),
        season=season,
        episode=episode,
        seasons=seasons,
        episodes=episodes,
        kind=kind,
        collection=collection,
    )


def cluster(releases: list[Release]) -> list[Picture]:
    """Сгруппировать релизы в картины; порядок = хронология франшизы.
    Кросс-язычность: если хоть где-то встретилось ``Тачки 3 / Cars 3``, то чисто
    латинский релиз ``Cars 3`` попадёт в тот же кластер, что и русский.

    🔴 Разбор идёт в порядке, который НЕ зависит от того, чей индексер ответил первым.
    Развязки ничьих в самих сортировках (TC-227) для этого мало: словарь синонимов и
    канон оригинала берут первую попавшуюся строку (``setdefault``), а каноническое имя
    картины считается большинством (:func:`_compose`) - и при равном счёте побеждает
    опять же тот, кто пришёл раньше. Замерено на сырых пулах (99 запросов, по 10
    перетасовок каждый): без этой строки перетасовка меняла картину у 59 запросов из 99,
    а верхний релиз картины С ТЕМ ЖЕ именем и годом - у 25. Живой случай - «Дюна» 2000:
    картина приезжала то на 5 раздач с верхом на 7 сидах, то на 2 раздачи с верхом на 39,
    и узнать об этом человеку было неоткуда.
    """
    releases = sorted(releases, key=lambda r: (r.magnet, r.raw_name))
    aliases: dict[str, str] = {}
    paired: dict[tuple[Kind, str, int | None], set[str]] = {}
    original_kinds: dict[tuple[str, int | None], set[Kind]] = {}
    for release in releases:
        if release.original and _CYRILLIC.search(release.title):
            original = slugify(release.original)
            title = slugify(release.title)
            aliases.setdefault(original, title)
            paired.setdefault((release.kind, title, release.year), set()).add(original)
            original_kinds.setdefault((original, release.year), set()).add(release.kind)
    series_originals = {
        release.slug for release in releases if not release.original and release.kind == "tv"
    }

    # Обычно ключ кластера - русский slug: так варианты перевода одного оригинала
    # сходятся через ``canon``. Исключение - каталог явно назвал под одним переводом и
    # годом несколько оригиналов: «Девять / Nine» и «Девять / 9» - разные картины.
    disputed = {
        key
        for key, originals in paired.items()
        if len(originals) > 1 and any(len(x) == 1 for x in originals)
    }
    canon: dict[tuple[Kind, str, int | None], tuple[Kind, str, int | None]] = {}
    buckets: dict[tuple[Kind, str, int | None], list[Release]] = {}
    for release in releases:
        kind = release.kind
        slug = release.slug if release.original else aliases.get(release.slug, release.slug)
        if (
            not release.original
            and release.slug in series_originals
            and len(kinds := original_kinds.get((release.slug, release.year), set())) == 1
        ):
            # Непомеченный латинский релиз наследует тип у парной строки каталога.
            kind = next(iter(kinds))
        key = (kind, slug, release.year)
        if release.original:
            original = slugify(release.original)
            if (release.kind, slugify(release.title), release.year) in disputed:
                key = (kind, original, release.year)
            else:
                key = canon.setdefault((kind, original, release.year), key)
        buckets.setdefault(key, []).append(release)

    pictures = [_compose(kind, year, group) for (kind, _, year), group in buckets.items()]
    return _sorted(_unchaptered(glue(pictures)))


def _chapter_of(title: str) -> tuple[str, int] | None:
    """Глава в имени: «Дары Смерти: Часть II» → ``("дары смерти", 2)``; не глава - None."""
    match = _PART_NUMBER_RE.match(title.strip())
    if not match:
        return None
    head = title[: match.start(1)].rstrip(" ,-")
    if not _CHAPTER_RE.search(head):
        return None
    base = slugify(_CHAPTER_RE.sub("", head).rstrip(" ,-:."))
    token = match.group(1).lower()
    number = int(token) if token.isdigit() else _ROMAN.get(token)
    return (base, number) if base and number is not None else None


def _unchaptered(pictures: list[Picture]) -> list[Picture]:
    """Снять номер части франшизы с ГЛАВ одной картины; сами картины не трогаются.

    🔴 TC-406. «Гарри Поттер и Дары Смерти: Часть I» и «Часть II» - половины одной
    работы, но их номера 1 и 2 в широком меню «гарри поттер» читались номерами частей
    ВСЕЙ франшизы: линейкой становились две главы, а восемь настоящих фильмов уезжали
    в хвост с подписью «без номера части» - франшиза без номеров выглядела
    нумерованной.

    Глава доказывается сиблингом: каталог назвал «Часть 1» того же имени - значит,
    работа делилась на главы, и номера в ней - номера глав. Без сиблинга номер
    остаётся номером части: «Стражи Галактики. Часть 2» - вторая часть франшизы
    (первый фильм каталог подписал просто «Стражи Галактики», делить её не на что), и
    запрос «стражи галактики 2» отвечает ею, как прежде. Тем же правилом живы «Оно:
    Глава 2» и «Дюна: Часть вторая» - слово тут не решает ничего, решает подпись
    каталога. Меряется по сохранённым выдачам: снятие номера с глав не стоит ни одного
    настоящего номерного ответа.

    Запрос к самой главенной работе это не ломает: «дары смерти 2» отвечает второй
    главой по хронологии - как всякая франшиза, которую каталог номерами не подписал.
    """
    chaptered = {
        chapter[0]
        for picture in pictures
        for release in picture.releases
        if (chapter := _chapter_of(release.title)) is not None and chapter[1] == 1
    }
    if not chaptered:
        return pictures
    for picture in pictures:
        if picture.part is None:
            continue
        for release in picture.releases:
            chapter = _chapter_of(release.title)
            if chapter is not None and chapter[0] in chaptered and chapter[1] == picture.part:
                picture.part = None
                break
    return pictures


def by_majority(counted: Counter[str]) -> str:
    """Самое частое имя кучки; при РАВНОМ счёте - самое короткое, потом по алфавиту.

    Развязка тут не косметика. ``most_common`` при равенстве отдаёт то имя, что легло в
    счётчик первым, то есть то, чей индексер ответил быстрее: «Армитаж: Двойная матрица»
    приезжает с оригиналом ``Armitage III: Dual Matrix`` и ``Armitage: Dual-Matrix``
    поровну, и картина меняла паспорт от запуска к запуску.

    Короткое имя при равенстве - не произвол: длиннее его делают ровно довески каталога,
    номер части в переводе названия («Матрица 2: Перезагрузка» против «Матрица:
    Перезагрузка») или лишняя нумерация оригинала. Номер части при этом не теряется -
    его забирает :attr:`Picture.part` отдельным счётом.
    """
    return min(counted, key=lambda name: (-counted[name], len(name), name))


def _compose(kind: Kind, year: int | None, group: list[Release], also: str = "") -> Picture:
    """Кучка релизов → картина: каноническое имя, оригинал и номер части по большинству."""
    titles = Counter(r.title for r in group if _CYRILLIC.search(r.title))
    title = by_majority(titles or Counter(r.title for r in group))
    originals = Counter(r.original for r in group if r.original)
    # Номер части часто есть лишь в части переводов («Матрица 2: Перезагрузка»)
    # - забираем его на всю картину, он точнее года при двух фильмах за год.
    parts = Counter(n for r in group if (n := part_number(r.title)) is not None)
    original = by_majority(originals) if originals else None
    return Picture(
        title=title,
        year=year,
        kind=kind,
        original=original,
        part=min(parts, key=lambda n: (-parts[n], n)) if parts else None,
        also=also,
        aliases=_alias_slugs(group, title, original),
        releases=group,
    )


def _alias_slugs(group: list[Release], title: str, original: str | None) -> tuple[str, ...]:
    """Псевдонимы кучки слагами: имена из заголовков минус те, что уже стали паспортом.

    Порядок отсортирован нарочно: разбор не вправе зависеть от того, чей индексер ответил
    первым (:func:`cluster`), а псевдонимы приезжают из разных строк выдачи.
    """
    known = {slugify(title), slugify(original or "")}
    found = {slug for r in group for name in r.aliases if (slug := slugify(name))}
    return tuple(sorted(found - known))


def _sorted(pictures: list[Picture]) -> list[Picture]:
    return sorted(pictures, key=lambda p: (p.year is None, p.year or 0, p.title, p.original or ""))


def glue(pictures: list[Picture]) -> list[Picture]:
    """Склеить картины, тождество которых ДОКАЗАНО именем и годом.

    Кластер разводит релизы по ключу «имя + год», и одна картина рассыпается на кучки
    ровно там, где каталог подписывает её по-разному. Живые примеры с домашних индексеров:

    * «Врата Штейна» (2011, русская озвучка, 86 сидов) и ``Steins;Gate`` (36 раздач, года
      в именах нет вовсе) - две картины, и запрос латиницей русской озвучки не видел В
      ПРИНЦИПЕ: пул латиницей богатый, второго захода не будет, а склеивать было нечем;
    * «Кавказская пленница, или Новые приключения Шурика» приезжает с годами 1966, 1967
      и 1969 - каталог путает год производства с годом проката, и 22 раздачи классики
      выглядят как три хилые картины.

    Доказательство тождества - только имя, названное самим каталогом: полное название
    картины или её оригинал (``Врата Штейна / Steins;Gate`` несёт оба). Франшиза здесь не
    годится: «Тачки 2» и «Тачки 3» - одна франшиза и разные картины, поэтому номер части
    из имени не режется. Одинаковых имён при разных типах не бывает: у аниме сериал и
    полнометражка подписаны одинаково, а картины это разные, - ``kind`` разделяет.

    🔴 TC-308. **Третье имя в заголовке - такое же имя каталога.** У картины бывает ДВА
    оригинала: международное название и родное. «Унесённые призраками» приезжают строками
    «Унесённые призраками / Sen to Chihiro no Kamikakushi / Spirited Away (2001)» - в
    паспорт попадает второе, а по третьему картину зовёт полмира, и именно им подписаны
    46 латинских раздач. Имена как строки не сходились, склеивать было нечем, и в меню
    стояли ДВЕ картины 2001 года: у одной японский оригинал и русский звук, у другой
    ``Spirited Away`` и звук английский. Спросишь по-русски - одна, спросишь латиницей -
    другая, и человек об этом ниоткуда не узнает. Признак дешёвый и офлайновый: оба имени
    стоят в именах самих раздач, разбор их уже читает (:func:`_alias_slugs`).

    ⚠️ **Третья подпись сводит только с ОДИНОКИМ именем** - тем, которое каталог не спарил
    ни с чем (``original`` пуст). Пара имён в заголовке - это уже сказанное каталогом «эта
    картина зовётся так и так», и третья подпись чужого заголовка её не отменяет: третьим
    там стоит что угодно вплоть до имени студии. Без этого условия замер по сотне
    сохранённых выдач давал ложные склейки ровно того сорта, ради которого заведён гейт
    года: «Стальной алхимик» 2003-го впитывал «Братство» 2009-го, а «Наруто: Ураганные
    хроники» - «Путь ниндзя». С условием на тех же выдачах меняются 6 запросов из 104, и
    все шесть - сведение одной картины: ``Spirited Away`` с «Унесёнными призраками»,
    ``Chainsaw Man The Movie Reze Arc`` с «Историей Резе» (плюс полсотни раздач, включая
    2160p), «Рэмбо» с «Первой кровью».

    Гейт года при этом прежний: «Унесённые призраками: движущиеся картинки» 2011 года
    несут оригиналом ровно ``Spirited Away`` и остаются отдельной картиной.

    🔴 **Год - гейт, а не украшение.** Ремейк носит имя оригинала («Психо» 1960 и 1998),
    и склеить их значило бы молча подсунуть человеку чужой фильм. Поэтому:

    * годы расходятся больше чем на 1 - НЕ склеиваем (±1 - это разница между годом
      производства и годом проката, её раздачи путают постоянно);
    * год не назван вовсе - склеиваем с единственным известным годом под этим именем, но
      если под ним лежат ДВЕ картины разных лет, безымянная не достаётся никому: выбирать
      наугад между оригиналом и ремейком нельзя.
    """
    parent = list(range(len(pictures)))

    def identity(name: str) -> str:
        """Имя картины без подписи формата показа в его хвосте."""
        plain = re.sub(r"(?:-)?(?:в-)?3[дd]$", "", slugify(name)).rstrip("-")
        return re.sub(
            r"(?<=-)(?:часть|part)-([ivx]{1,4})$",
            lambda match: (
                match.group(0)[: match.group(0).rfind("-") + 1]
                + str(_ROMAN.get(match.group(1), match.group(1)))
            ),
            plain,
        )

    def alternative_release(release: Release) -> bool:
        title = release.raw_name.split(" / ", 1)[0]
        return bool(
            _ALTERNATIVE_PICTURE_RE.search(release.raw_name) or _ALTERNATIVE_TITLE_RE.search(title)
        )

    def root(i: int) -> int:
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    def union(a: int, b: int) -> None:
        ra, rb = root(a), root(b)
        if ra != rb:
            parent[max(ra, rb)] = min(ra, rb)

    alternative = [
        bool(p.releases) and all(alternative_release(r) for r in p.releases) for p in pictures
    ]
    disputed = {
        (picture.kind, slugify(picture.title), picture.year)
        for picture in pictures
        if picture.original
        and len(
            {
                slugify(other.original)
                for other in pictures
                if other.original
                and other.kind == picture.kind
                and other.year == picture.year
                and slugify(other.title) == slugify(picture.title)
            }
        )
        > 1
        and any(
            len(slugify(other.original)) == 1
            for other in pictures
            if other.original
            and other.kind == picture.kind
            and other.year == picture.year
            and slugify(other.title) == slugify(picture.title)
        )
    }
    named: dict[tuple[Kind, str, bool], list[int]] = {}
    for i, picture in enumerate(pictures):
        title = identity(picture.title)
        contested = (picture.kind, title, picture.year) in disputed
        names = set() if contested else {title}
        if picture.original:
            names.add(identity(picture.original))
        # Число словом и число цифрой - одно имя (:func:`in_digits`). Гейт года при этом
        # остаётся прежним, так что «12 обезьян» 1995-го с сериалом 2015-го не сшить.
        if not contested:
            names |= {in_digits(name) for name in names if name}
        for name in names:
            if name:
                named.setdefault((picture.kind, name, alternative[i]), []).append(i)
    for same in named.values():
        _link(pictures, same, union)
    # Третье имя из заголовка (:attr:`Picture.aliases`) сводит картину только с ОДИНОКИМ
    # именем - тем, которое каталог не спарил ни с чем (``original`` пуст).
    lone: dict[tuple[Kind, str, bool], list[int]] = {}
    for i, picture in enumerate(pictures):
        if picture.original:
            continue
        for name in {(slug := identity(picture.title)), in_digits(slug)}:
            if name:
                lone.setdefault((picture.kind, name, alternative[i]), []).append(i)
    for i, picture in enumerate(pictures):
        for alias in picture.aliases:
            for name in (alias, in_digits(alias)):
                if (
                    bucket := lone.get((picture.kind, name, alternative[i]))
                ) is not None and i not in bucket:
                    bucket.append(i)
    for same in lone.values():
        _link(pictures, same, union)

    groups: dict[int, list[int]] = {}
    for i in range(len(pictures)):
        groups.setdefault(root(i), []).append(i)
    out: list[Picture] = []
    for members in groups.values():
        if len(members) == 1:
            out.append(pictures[members[0]])
            continue
        merged = sorted(
            (pictures[i] for i in members),
            key=lambda p: (-len(p.releases), p.title, p.original or ""),
        )
        releases = [r for p in merged for r in p.releases]
        year = _glued_year(merged[0].kind, merged, releases)
        fresh = _compose(merged[0].kind, year, releases)
        # Второе имя - самое многолюдное из тех, что не стали каноническим: именно его
        # человек и набрал, если спрашивал латиницей, а в меню теперь русское название.
        fresh.also = next((p.title for p in merged if slugify(p.title) != slugify(fresh.title)), "")
        out.append(fresh)
    return out


def _glued_year(kind: Kind, merged: list[Picture], releases: list[Release]) -> int | None:
    """Год склеенной картины: у кино - по большинству раздач, у сериала - самый ранний.

    🔴 TC-201. **У сериала год - самый РАННИЙ из известных**, а не год самой толстой кучки.
    Со сшивкой сезонов кучки разъезжаются на десятилетия, и сериал подписывался годом
    самого обсиженного сезона: «Доктор Кто (2017)» при 12 раздачах 2005-го против 90
    раздач 2017-го, «Игра престолов (2019)», «Чёрное зеркало (2019)». Это не только кривая
    строка в меню: справку ищут по паре «имя + год» и сверяют год по первым фразам статьи
    (:func:`torrcast.facts.confirms`), а статья открывается годом НАЧАЛА сериала. С чужим
    годом справки нет вовсе - ни рейтинга, ни описания, ни хронометража, на котором
    считается битрейт (TC-185).

    🔴 TC-328. **У кино ранний год - не начало, а описка каталога**, и правило сериала на
    него не переносится. Гейт года (:func:`_link`) сводит в одну картину только соседние
    годы, так что спорят тут не оригинал с ремейком, а год производства с годом проката:
    «Титаник» стоял в меню как «Титаник (1996)» из-за трёх раздач из 68, подписанных
    1996-м. Год человек читает глазами, чтобы отличить оригинал от ремейка, - это наш же
    приём против подмены картины, и врущий год подрывает ровно тот признак, на который мы
    его учим смотреть. Слово за большинством раздач; при равном счёте - за ранним годом,
    то есть за прежним ответом.

    Считается по РАЗДАЧАМ, а не по кучкам: кучка тут - не голос, а лишь то, как каталог
    разложил одинаковые имена, и одна раздача с опиской весит там столько же, сколько
    шесть десятков без неё.
    """
    dated = [r.year for r in releases if r.year is not None]
    if kind != "tv" and dated:
        counted = Counter(dated)
        return min(counted, key=lambda year: (-counted[year], year))
    return min((p.year for p in merged if p.year is not None), default=None)


def _run_span(picture: Picture) -> tuple[int, int] | None:
    """Сквозной отрезок серий картины: ``[01-201]`` → (1, 201). Нет такого имени - None.

    Считаются только раздачи со СКВОЗНОЙ нумерацией - те, что перечислили серии, но не
    назвали сезона. Раздача, назвавшая сезон, нумерует серии внутри него и к общей линейке
    сериала отношения не имеет.
    """
    numbers = [
        n
        for r in picture.releases
        if r.episodes and not r.seasons and r.season is None
        for n in (r.episodes[0], r.episodes[-1])
    ]
    return (min(numbers), max(numbers)) if numbers else None


def _picture_season_span(picture: Picture) -> tuple[int, int] | None:
    """Сквозной отрезок сезонов картины. Нет таких имён - None."""
    numbers = [
        s
        for r in picture.releases
        for s in (r.seasons or ([r.season] if r.season is not None else []))
    ]
    return (min(numbers), max(numbers)) if numbers else None


def _continued(
    pictures: list[Picture], chains: list[list[int]], union: Callable[[int, int], None]
) -> list[list[int]]:
    """Сшить цепочки лет, которые ПРОДОЛЖАЮТ нумерацию серий, а не начинают её заново.

    🔴 TC-169, точечное послабление гейта года - и только для сериалов со сквозной
    нумерацией (:func:`_run_span`). Длинное аниме идёт по каталогу кусками, у каждого
    свой год, а серии считаются насквозь через весь сериал: «Гинтама / Gintama TV-1
    [01-201] (2006)», «TV-2 [202-252] (2011)», ... «TV-8 [354-367] (2018)». Между
    крайними кусками 12 лет, гейт года читал это как ремейк - и сериал рассыпался на
    шесть картин, из которых у той, где лежит ПЕРВАЯ серия, оставалось две раздачи.

    Гейт при этом не ослаблен: ремейк тем и ремейк, что начинает счёт заново, и его
    диапазон стартует с первой серии. Сшиваем, только когда поздний кусок:

    * начинается НЕ с первой серии/сезона - счёт не начат заново;
    * начинается там, где кончился ранний (с зазором не больше одной серии/сезона, а
      пересечение допустимо: сборник «TV [01-252]» перекрывает куски внутри себя).

    Обе стороны обязаны назвать свои серии/сезоны сами. Молчит хоть одна - сшивать
    нечем, и работает прежний гейт года.
    """
    if len(chains) < 2 or any(pictures[i].kind != "tv" for chain in chains for i in chain):
        return chains
    out: list[list[int]] = [chains[0]]
    for chain in chains[1:]:
        before_ep = [span for i in out[-1] if (span := _run_span(pictures[i]))]
        after_ep = [span for i in chain if (span := _run_span(pictures[i]))]
        start_ep = min((s for s, _ in after_ep), default=0)

        before_s = [span for i in out[-1] if (span := _picture_season_span(pictures[i]))]
        after_s = [span for i in chain if (span := _picture_season_span(pictures[i]))]
        start_s = min((s for s, _ in after_s), default=0)

        # Сшивает ЛЮБАЯ из двух линеек: сквозная нумерация серий (аниме) или нумерация
        # сезонов (длинный сериал, у которого каждый сезон датирован своим годом).
        if (before_ep and start_ep > 1 and start_ep <= max(e for _, e in before_ep) + 1) or (
            before_s and start_s > 1 and start_s <= max(e for _, e in before_s) + 1
        ):
            union(out[-1][0], chain[0])
            out[-1] = out[-1] + chain
            continue
        out.append(chain)
    return out


def _link(pictures: list[Picture], same: list[int], union: Callable[[int, int], None]) -> None:
    """Связать картины, приехавшие под одним именем: сначала по годам, потом безымянные.

    Годы выстраиваются в цепочки шагом не больше единицы: 1966 и 1967 - одна картина,
    1967 и 1969 - уже нет. Картина без года достаётся цепочке, только если она под этим
    именем одна: две цепочки - это оригинал и ремейк, и молча выбрать между ними нельзя.
    """
    dated = sorted(
        (i for i in same if pictures[i].year is not None),
        key=lambda i: (pictures[i].year or 0, pictures[i].title, pictures[i].original or ""),
    )
    chains: list[list[int]] = []
    for i in dated:
        current = pictures[i]
        year = current.year or 0
        previous = pictures[chains[-1][-1]] if chains else None
        close_outlier = False
        if previous is not None and previous.original and current.original:
            close_outlier = (
                year - (previous.year or 0) == 2
                and len(previous.releases) == 1
                and len(current.releases) >= 10
                and slugify(previous.original) == slugify(current.original)
            )
        if previous is not None and (year - (previous.year or 0) <= 1 or close_outlier):
            chains[-1].append(i)
        else:
            chains.append([i])
    for chain in chains:
        for i in chain[1:]:
            union(chain[0], i)
    chains = _continued(pictures, chains, union)
    blank = [i for i in same if pictures[i].year is None]
    if len(chains) > 1:  # оригинал и ремейк под одним именем: безымянной картине веры нет
        return
    for i in blank[1:]:
        union(blank[0], i)
    if chains and blank:
        union(chains[0][0], blank[0])


def seasons_named(picture: Picture) -> tuple[int, ...]:
    """Сезоны, которые раздачи картины назвали САМИ, по возрастанию; пусто - все молчат.

    Нужна одной честной строке. Сериал попадает в меню целой картиной, а план строится
    только по тем раздачам, чьё имя накрывает спрошенный сезон (:meth:`Release.covers`).
    Не накрыл никто - картина исчезала из меню молча, и человек читал дефолт, вставший
    на соседа. Живой промах: «Гинтама» (2018) переживает привязку с 41 раздачей и 33
    живыми, но все они подписаны сезонами 5-10, первого нет ни в одной, - и на `s1e1`
    дефолтом вставал спин-офф «Gintama: 3-nen Z-gumi Ginpachi-sensei», ни словом не
    объяснив, куда делся основной сериал.

    ⚠️ Это то, что сказало ИМЯ, а не то, что лежит в раздаче. Молчащие о сезоне раздачи
    сюда не попадают вовсе: они накрывают любой сезон (окончательный ответ дают файлы), и
    называть их сезон было бы выдумкой. Поэтому пустой ответ значит «имена молчат», а не
    «сезонов нет», и строка на нём не строится.
    """
    named = {s for r in picture.releases for s in (r.seasons or ((r.season,) if r.season else ()))}
    return tuple(sorted(named))


def franchises(pictures: list[Picture]) -> dict[str, list[Picture]]:
    """Картины → франшизы: общий канонический ключ, значение отсортировано по году.
    Два фильма за один год («Перезагрузка» и «Революция», обе 2003) разводит явный
    номер части; без него вперёд идёт картина с бо́льшим числом раздач — основной
    фильм, а не спин-офф или «киноляпы».
    """
    grouped: dict[str, list[Picture]] = {}
    for picture in pictures:
        grouped.setdefault(picture.franchise, []).append(picture)
    for items in grouped.values():
        items.sort(key=_franchise_item_key)
    return grouped


def _franchise_item_key(picture: Picture) -> tuple[bool, int, int, int, str]:
    """Порядок частей франшизы: год, названный номер, вес и имя."""
    return (
        picture.year is None,
        picture.year or 0,
        picture.part or 99,
        -len(picture.releases),
        picture.title,
    )


def _numbered_line(pictures: list[Picture]) -> tuple[list[Picture], list[Picture]]:
    """Франшиза → (основная линейка по номерам частей, всё остальное после неё).

    Каталог нумерует не всё: у «Тачек» номер стоит на второй и третьей части, а первая
    подписана просто «Тачки» - как и спин-офф «Тачки: Мультачки. Байки Мэтра» двумя
    годами позже. По хронологии спин-офф оказывался между первой и второй частью, и в
    меню выходило «2. Мультачки, 3. Тачки 2»: номер пункта не совпадал с номером части,
    хотя человек читает его именно так и именно им отвечает.

    Правило простое и держится на том, что каталог сказал вслух:

    * у кого номер части есть - те и есть линейка, по возрастанию номера;
    * первое место линейки свободно (номера ``1`` никто не назвал) - его занимает первая
      часть, которую каталог просто не с чем было нумеровать (:func:`_free_first`), и
      только если её с франшизой связала сама подпись каталога;
    * остальные безномерные идут ПОСЛЕ линейки, в хронологии.

    🔴 Не-видео (``kind == "other"``) места в линейке не занимает, даже когда в его имени
    есть номер: том аудиокниги «Homo Ludens 1. Класс: Сталкер» вставал ПЕРВЫМ пунктом
    меню кинофраншизы «Сталкер» - единственным носителем номера во всей выдаче - и мог
    быть принят за первую часть фильма. Здесь это ограждение обязано стоять само, а не
    полагаться на фильтр в :func:`_numbered`: сюда линейку приносят и
    :func:`menu_order`, и :func:`outside_numbering`, а они зовут её на всём меню целиком.
    Из хвоста не-видео при этом не исчезает: показать его - честно, давать ему номер
    части - нет.

    ⚠️ Нумерованных частей нет вовсе («Матрица», «Гарри Поттер») - порядок не трогаем:
    там хронология и есть нумерация, а любое «после линейки» было бы выдумкой.
    """
    numbered = sorted(
        (p for p in pictures if p.part is not None and p.kind != "other"),
        key=lambda p: (p.part or 0, p.year is None, p.year or 0, p.title),
    )
    if not numbered:
        return list(pictures), []
    rest = [p for p in pictures if p.part is None or p.kind == "other"]
    free = _free_first(rest, numbered) if rest and all(p.part != 1 for p in numbered) else None
    first = [free] if free is not None else []
    tail = [p for p in rest if p is not free]
    return first + numbered, tail


def _free_first(rest: list[Picture], numbered: list[Picture]) -> Picture | None:
    """Кто из безномерных занимает свободное первое место линейки; ``None`` - некому.

    🔴 TC-373. Претендент обязан быть связан с франшизой ПОДПИСЬЮ КАТАЛОГА, а не одним
    «раньше всех вышел»: либо он назван ровно именем франшизы («Форсаж» 2001, «Оно»,
    «Ледниковый период»), либо его оригинал делит корень с оригиналом нумерованной части
    («Властелин колец: Братство кольца» делит ``The Lord of the Rings`` с «Битвой за
    Средиземье 2»). Прежде место доставалось любой ранней безномерной, и на запрос
    «тачки 1» при пропавшей из выдачи первой части отвечал спин-офф «Тачки: Мультачки.
    Байки Мэтра» - другая картина той же франшизы (корень её оригинала ``Cars Toon``
    свой, а не ``Cars``), молча вставшая на место просимой.

    🔴 TC-361. Прежде место отдавалось самой ранней безномерной по хронологии, и на
    «форсаж 1» отвечал «Форсаж» 1992 года - однофамилец с оригиналом ``Afterburn``, одной
    раздачей и четырьмя сидами, - тогда как «Форсаж» 2001 года (``The Fast and the
    Furious``, 13 раздач, 56 сидов) стоял в стороне с подписью «без номера части». Имя
    франшизы плюс номер первой части - самый простой запрос из возможных, и отвечать на
    него однофамильцем нельзя. Тот же класс в сохранённых выдачах: «Ледниковый период:
    выжившие» (1 раздача) вместо «Ледникового периода» (7), «Оно» с оригиналом ``It
    Follows`` вместо «Оно» с оригиналом ``It``, «Человек Паук» 1967 года (1 раздача)
    вместо «Человека-паука» 2002-го (7).

    Правило сужено, а не выключено - место занимает картина, которая:

    * вышла РАНЬШЕ первой части, подписанной номером и годом. Первой частью может быть
      только то, что стоит перед нумерацией: иначе место забрал бы поздний спин-офф с
      богатой кучкой («Дэдпул и Росомаха», 59 раздач, против «Дэдпула», 15);
    * полнее прочих таких же КУЧКОЙ - тем же весом, каким франшиза разводит две картины
      одного года (:func:`franchises`) и каким живая часть перевешивает безгодового
      носителя номера (:func:`_living_part`). Число раздач - мера каталога, а не роя:
      сиды у одной и той же картины гуляют от прогона к прогону, и порог по ним отдал бы
      первое место «Тачек» спин-оффу «Мультачки» - на сохранённой выдаче у первой части
      4 сида, у спин-оффа 5.

    Кучки равны - остаётся ранняя, как и было. Сборник претендентом не бывает
    (:attr:`Picture.collection`): за ним пачка картин, а не картина.

    ⚠️ Раньше нумерации не вышло НИЧЕГО (или номера каталог назвал без года) - мерить не
    от чего, и место занимает самая ранняя безномерная, как прежде. Честный ответ тут
    только такой: линейка без первой части - это то, что сказал каталог.
    """
    roots = {franchise_key(p.original) for p in numbered if p.original}
    titled = [
        p
        for p in rest
        if p.kind != "other"  # первое место - картине, а не тому книги или репаку игры
        and (
            slugify(p.title) == p.franchise
            or (p.original is not None and franchise_key(p.original) in roots)
        )
    ]
    if not titled:
        return None
    anchor = min((p.year for p in numbered if p.year is not None), default=None)
    if anchor is None:
        return titled[0]
    early = [p for p in titled if p.year is not None and p.year < anchor and not p.collection]
    if not early:
        return titled[0]
    return max(early, key=lambda p: (len(p.releases), -(p.year or 0)))


def menu_order(pictures: list[Picture]) -> list[Picture]:
    """Меню франшизы: что в нём стоит и в каком порядке (номер пункта = номер части).

    🔴 TC-327. Сборник в меню не пункт. Раздача «Хоббит: Трилогия», «Гарри Поттер:
    Коллекция», «Хоббит / Властелин колец: Коллекция ... (2001-2014)» обрезается по слову
    про сборник до имени франшизы и заводит в каталоге картину, которой нет: в меню по
    «хоббит» стояло «Хоббит (2001)» одной раздачей на 165 ГБ - две трилогии сразу. Диапазон
    лет схлопывается в первый год, так что гейт года такое не разводит, а человек читает
    строку меню как картину и выбирает её.

    Убирается ПУНКТ МЕНЮ, а не раздача: сборник остаётся в каталоге, и там, где он и есть
    картина (сезон-пак сериала лежит в одной кучке с остальными раздачами сезона), его
    ничто не трогает - словом про сборник подписывают пачку ФИЛЬМОВ, а не сезоны
    (:attr:`Picture.collection`).

    ⚠️ Кроме сборников в меню не нашлось ничего - показываем их: выбирать всё равно не из
    чего, а пустое меню значит «ничего не нашлось» при живой выдаче в руках.
    """
    picked = [p for p in pictures if not p.collection]
    source = picked or list(pictures)
    keys = {p.franchise for p in source}
    if any(sum(other.startswith(f"{key}-и-") for other in keys) >= 2 for key in keys):
        return sorted(source, key=_franchise_item_key)
    line, tail = _numbered_line(source)
    return line + tail


def outside_numbering(pictures: list[Picture]) -> set[str]:
    """Ключи картин, стоящих ПОСЛЕ нумерованной линейки, - им и подписи в меню.

    Подпись честная - «без номера части», а не «спин-офф»: номер части каталог для них
    действительно не назвал, а вот спин-офф ли это, мы не знаем. У «Форсажа» безномерными
    подписаны «Двойной форсаж» и «Тройной форсаж» - это ровно основная линейка, и назвать
    их спин-оффами значило бы соврать в строке, которую человек не может проверить.
    """
    return {p.key for p in _numbered_line(pictures)[1]}


def _group_weight(groups: dict[str, list[Picture]], key: str) -> int:
    """Число раздач за ключом франшизы - вес не зависит от порядка выдачи."""
    return sum(len(p.releases) for p in groups[key])


def _by_words(wanted: str, groups: dict[str, list[Picture]]) -> str | None:
    """Ключ франшизы, в словах которого есть ВСЕ слова запроса - в любом порядке.

    Человек называет картину своими словами, а не так, как её подписал каталог:
    «бульвар сансет» вместо «Сансет бульвар», «гарри поттер дары смерти» вместо «Гарри
    Поттер И Дары Смерти». Подстрокой такое не ловится ни в одну сторону, и запрос
    падает в пустоту при живых раздачах прямо в той же выдаче.

    Сверяются слова, а не буквы, и целиком: «дети мужчин» не станет «Мужчины, женщины и
    дети» - слова «мужчин» там нет, есть «мужчины». Именно это и держит проверку узкой.

    Однобуквенные слова из запроса выбрасываются: союзы («и», «в») ставят и не ставят как
    попало, а решают совпадение всё равно не они. Слов должно остаться хотя бы два -
    одно слово, если оно в каталоге есть, находится обычной подстрокой.

    Из подошедших берётся самый тесный ключ: у «гарри поттер дары смерти» это
    ``гарри-поттер-и-дары-смерти``, а не ``гарри-поттер-и-дары-смерти-в-3д``.

    🔴 Вторым заходом слова сверяются ПО ФОРМЕ (:func:`same_words`): «Робот мечты» - это
    «Мечты робота», а буква в букву эти имена не сходятся ни одним из способов выше, и
    запрос падал в пустоту при восьми строках выдачи. Заход именно второй, а не общее
    послабление: пока слова совпадают целиком, всё решает первый, и ключ, найденный им,
    сильнее любой догадки об окончании.

    Дороги подмене это не открывает, и держат её два условия сразу (:func:`_paired`):
    слов должно быть ПОРОВНУ, и окончание прощается только слову, которое ПЕРЕЕХАЛО.
    «Дети мужчин» так и не станут «Мужчинами, женщинами и детьми» - слов там больше, - а
    «кольца власти» не станут «Кольцом власти»: там разница в окончании стоит на месте.
    """
    asked = _words(wanted)
    if len(asked) < 2:
        return None
    hits = [key for key in groups if asked <= _words(key)]
    if not hits:
        # Порядок слов тут значит всё (:func:`_paired`), поэтому сверяются списки в том
        # виде, как имя написано, а не множества.
        mine = _word_list(wanted)
        hits = [key for key in groups if _paired(mine, _word_list(key))]
    return (
        min(
            hits,
            key=lambda key: (len(_words(key)), len(key), -_group_weight(groups, key), key),
        )
        if hits
        else None
    )


def _words(slug: str) -> set[str]:
    return set(_word_list(slug))


def _word_list(slug: str) -> list[str]:
    """Слова имени по порядку, без односложных союзов («и», «в»): их ставят как попало."""
    return [word for word in slug.split("-") if len(word) > 1]


def other_words(query: str, picture: Picture | None) -> str:
    """Название картины, в которое запрос попал ТОЛЬКО другими словами - иначе пусто.

    Нужна одной честной строке: человек набрал «бульвар сансет», а играет «Сансет
    бульвар» - об этом надо сказать. Совпадение подстрокой (в любую сторону) и попадание
    по оригинальному названию молчаливы: там человек назвал картину ровно так, как её
    зовут, и объяснять нечего.

    ⚠️ Называется КАРТИНА целиком, а не корень её франшизы. Корень режет подзаголовок
    (:func:`franchise_name`), и на запросе подзаголовком строка выходила прямой
    бессмыслицей: «космическая одиссея» - в каталоге это «2001».
    """
    if picture is None:
        return ""
    wanted = slugify(query)
    keys = [picture.franchise]
    if picture.original:
        keys.append(franchise_key(picture.original))
    if any(wanted in key or key in wanted for key in keys):
        return ""
    return picture.title


def _aliases(groups: dict[str, list[Picture]]) -> dict[str, str]:
    """Оригинальное имя франшизы → ключ русской франшизы, в которой её больше всего раздач.

    ⚠️ Имён-однофамильцев в выдаче полно, и раньше побеждало последнее попавшееся: ``Steins;Gate``
    вело не на «Врата Штейна» (41 раздача), а на «Врата Штейна ONA» - одну раздачу-огрызок,
    случайно оказавшуюся в перечислении последней. Запрос латиницей после этого показывал
    именно огрызок, а русская озвучка так и оставалась за бортом.

    🔴 **Имя картины кладётся ЦЕЛИКОМ, а не только корнем франшизы.** Корень режет
    подзаголовок и номер части (:func:`franchise_key`), и латинское имя, которым каталог
    подписал саму картину, в указателе не появлялось вовсе. Живой промах: «Убить Билла»
    (2003, 58 раздач) приезжает строками ``Убить Билла / Kill Bill: Vol. 1``, то есть
    каталог сам ручается за пару, но в указатель попадал огрызок ``kill-bill`` - а точное
    ``kill-bill-vol-1`` доставалось сборнику саундтреков «VA - Убить Билла - 1» (одна
    раздача, ноль живых), у которого номер части в имени стоит без двоеточия и потому не
    режется. Запрос ``Kill Bill: Vol. 1`` попадал точным совпадением в этот огрызок: 96
    раздач первого круга схлопывались до ОДНОЙ мёртвой, и картину спасал только второй
    круг по русскому имени - лишний поход по всем индексерам на каждом старте.

    Дороги однофамильцам это не открывает, и вот почему: добавленное имя ДЛИННЕЕ того,
    что уже лежало в указателе. Корень ``kill-bill`` на ту же франшизу указывал и раньше;
    более точное имя может лишь развести то, что корень сводил, но не свести то, что он
    разводил. За саму пару «латиница ↔ русское имя» ручается не догадка, а строка
    каталога: имя берётся из ``picture.original``, а туда оно попадает только из релиза,
    назвавшего оба имени разом. Спор двух картин за одно имя решает тот же вес, что и
    для корня, - число раздач.
    """
    weight = {key: sum(len(p.releases) for p in items) for key, items in groups.items()}
    aliases: dict[str, str] = {}
    for key, items in groups.items():
        for picture in items:
            if not picture.original:
                continue
            for name in (franchise_key(picture.original), slugify(picture.original)):
                if name and weight[key] > weight.get(aliases.get(name, ""), 0):
                    aliases[name] = key
    return aliases


def pick_franchise(query: str, pictures: list[Picture]) -> list[Picture]:
    """``«матрица 2»`` → [«Матрица: Перезагрузка»]; без номера — вся франшиза. Ищем по
    каноническому ключу (русскому или оригинальному), затем по вхождению подстроки, а
    в последнюю очередь по словам (:func:`_by_words`); номер — индекс в хронологии, а не
    часть названия.
    """
    groups = franchises(pictures)
    aliases = _aliases(groups)
    # Каноническим именем картины становится то, которым её подписало БОЛЬШИНСТВО раздач,
    # и на «двенадцати обезьянах» это «12 обезьян» - цифрой. Спросили же прописью, поэтому
    # ключи ищутся ещё и в цифровой записи (:func:`in_digits`).
    digits = {in_digits(key): key for key in groups}
    # Одно и то же имя переносят в русский по-разному: «Зена - королева воинов / Xena»
    # лежит под одним написанием, а спрашивают её «Ксена» - тем же ``Xena``, только
    # перенесённым иначе. Нормализованная транслитерация (:func:`spell`) сводит обе записи
    # к одной строке.
    #
    # 🔴 Указатель строится по ОРИГИНАЛАМ (``aliases``), а не по русским ключам каталога.
    # Пару языков должна назвать сама раздача: транслит одного лишь русского имени - это
    # наша догадка о том, как его напишут латиницей, и ручаться ею за картину нельзя.
    spelled: dict[str, str] = {}
    for written, target in sorted(aliases.items()):
        spelled.setdefault(spell(written), target)
    # Третьи имена из заголовков раздач («Дикие истории / Relatos salvajes / Wild Tales»)
    # - тоже подпись каталога, только слабее оригинала: раздача назвала это имя, но не
    # поставила его ни названием картины, ни оригиналом. Точное совпадение с ним сильнее
    # НЕСТРОГИХ ступеней ниже (вхождение в чужой ключ, слова, звучание): «wild tales» -
    # это «Дикие истории» 2014 года, а не сериал ``Wild Tales From The Farm``, чей ключ
    # лишь содержит запрос подстрокой. Спор двух франшиз за одно третье имя не решаем -
    # ровно как в :func:`_by_alias`, честное «не нашлось» лучше однофамильца.
    third: dict[str, str] = {}
    for group_key, items in groups.items():
        for picture in items:
            for slug in picture.aliases:
                if not slug or slug in groups or slug in aliases:
                    continue
                if third.setdefault(slug, group_key) != group_key:
                    third[slug] = ""

    def named(name: str) -> str | None:
        """Ключ, которым каталог подписал картину ЦЕЛИКОМ: та же строка, её латинский
        двойник или она же цифрами. Нестрогих ступеней тут нет нарочно - на этот ответ
        опирается разбор «имя это или номер части» (:data:`_TITLE_NUMBER_RE` ниже).
        """
        wanted = slugify(name)
        if not wanted:
            return None
        pointed = aliases.get(wanted)
        if wanted in groups:
            # 🔴 TC-394. Имя может претендовать на ДВА места сразу: быть ключом своей
            # франшизы и указателем на чужую (оригинал другой картины). Однофамильцев
            # разводит вес - то же правило, что в :func:`_aliases`: «whiplash» - это
            # сериал-однофамилец 1961 года на одну раздачу и оригинал «Одержимости»
            # 2014-го на шесть десятков, и слово за тем, за кого каталог.
            if (
                pointed is not None
                and pointed != wanted
                and (_group_weight(groups, pointed) > _group_weight(groups, wanted))
            ):
                return pointed
            return wanted
        if pointed is not None:
            return pointed
        if (counted := in_digits(wanted)) in digits:
            return digits[counted]
        return None

    def lookup(name: str) -> str | None:
        if (exact := named(name)) is not None:
            return exact
        wanted = slugify(name)
        if not wanted:
            return None
        if pointed := third.get(wanted):
            return pointed
        if hits := [k for k in groups if wanted in k]:
            return min(hits, key=lambda key: (len(key), -_group_weight(groups, key), key))
        # Порядок слов и союзы - на совести человека, а не каталога (:func:`_by_words`).
        # Стоит выше грубого «ключ входит в запрос»: у «гарри поттер дары смерти» тот
        # находил франшизу «гарри поттер» и отсчитывал номер части по ней.
        if loose := _by_words(wanted, groups):
            return loose
        # Запрос длиннее канона: «киберпанк бегущие по краю» - это франшиза «киберпанк»
        # (подзаголовок после двоеточия в ключ не входит). Берём самое длинное совпадение.
        if hits := [k for k in groups if k and k in wanted]:
            return max(hits, key=len)
        # Последняя ступень - звучание (:data:`spelled`). Последняя нарочно: сверка по
        # звучанию отвечает, КАК имя произносится, а не как оно написано в каталоге, и
        # пока картину находит само написание, спрашивать больше не о чем. Транслит
        # русского имени («vrata shteyna») именно так и находит картину, подписанную
        # латиницей целиком, - вхождением, а не звучанием.
        return spelled.get(spell(wanted))

    name, index = split_franchise_index(query)
    key = lookup(name)
    if key is None:  # номер оказался частью названия: «пила 8», «форсаж 6»
        key, index = lookup(query), None
    if key is None:
        # Имени франшизы человек мог и не назвать: он зовёт картину подзаголовком или тем
        # именем, которое каталог поставил в заголовке третьим (:func:`_by_alias`).
        items = _by_subtitle(name, pictures) or _by_alias(name, pictures)
        if not items:
            items = _by_subtitle(query, pictures) or _by_alias(query, pictures)
            index = None
        if not items:
            # Слова запроса разошлись по двум именам картины - последняя и самая
            # нестрогая ступень, поэтому она идёт после псевдонимов (:func:`_by_alias`).
            items, index = _by_both_names(query, pictures), None
        return _numbered(items, index)

    franchise_items = _both_languages(groups, aliases, key)
    if index is None:
        continuation_groups = {
            grouped_key: [p for p in grouped_items if p.kind != "other"]
            for grouped_key, grouped_items in groups.items()
            if grouped_key.startswith(f"{key}-и-")
        }
        continuation_groups = {k: items for k, items in continuation_groups.items() if items}
        if len(continuation_groups) >= 2:
            continuations = [p for items in continuation_groups.values() for p in items]
            known = {p.key for p in continuations}
            franchise_items = sorted(
                [p for p in franchise_items if p.kind != "other" and p.key not in known]
                + continuations,
                key=_franchise_item_key,
            )
    items = _numbered(franchise_items, index)
    if not items and index is not None and (whole_name := named(query)) is not None:
        # 🔴 Номера в этой франшизе нет, а вся строка целиком - имя картины в каталоге:
        # значит цифра была частью названия. «Легенда 17» уходила во франшизу «легенда»
        # за семнадцатой частью, которой нет и быть не может, и человек читал «картин во
        # франшизе 2, номера 17 нет» при живой картине на девять десятков сидов. Тот же
        # класс, что «Kill Bill: Vol. 1», только показателя перед цифрой тут нет вовсе -
        # ручается за пару сам каталог, подписавший картину ровно этой строкой.
        #
        # Совпадение требуется ПОЛНОЕ (:func:`named`, без нестрогих ступеней): иначе
        # «матрица 7» находила бы франшизу вхождением и вместо честного «номера 7 нет»
        # выкладывала всю линейку.
        items = _both_languages(groups, aliases, whole_name)
    return _with_subtitled(items, name, pictures, index)


def catalog_has_name(query: str, pictures: list[Picture]) -> bool:
    """Подписана ли хоть одна картина каталога ТОЧНО именем запроса.

    Вопрос не «что похоже», а «есть ли оно тут»: по запросу «девять» каталог отвечает
    сотней строк про «Девять ярдов», «Девять песен» и «Девять королей», а самой «Девять»
    в ней нет - и это повод переспросить точнее, а не смириться с соседями по подстроке
    (:func:`~torrcast.cli._ceiling_reinforce`).

    Считается подписью: имя франшизы у ненумерованной или первой части, точное имя
    картины, её оригинал и подтверждённое несколькими раздачами третье имя. Нарочно НЕ
    считаются: одинокий сиквел, одиночный псевдоним, вхождение подстрокой и цифровая
    запись числительных (:func:`in_digits`): «9» и «Девять» - разные картины, и запрос
    словом не должен довольствоваться картиной, подписанной цифрой.
    """
    name, _index = split_franchise_index(query)
    wanted = slugify(name)
    if not wanted:
        return False
    for picture in pictures:
        if slugify(picture.title) == wanted:
            return True
        if picture.original and slugify(picture.original) == wanted:
            return True
        if franchise_key(picture.title) == wanted and picture.part in (None, 1):
            return True
        alias_support = sum(
            wanted in {slugify(alias) for alias in release.aliases} for release in picture.releases
        )
        if alias_support >= 2:
            return True
    return False


def _with_subtitled(
    items: list[Picture], name: str, pictures: list[Picture], index: int | None
) -> list[Picture]:
    """Картины, названные ПОДЗАГОЛОВКОМ, - вдобавок к найденным по ключу франшизы.

    🔴 TC-246. Подзаголовок читался только тогда, когда по ключу не нашлось ничего
    (:func:`_by_subtitle`), а найтись по ключу может огрызок. «Космическая одиссея» -
    это ключ картины 1987 года с одной мёртвой раздачей, и она забирала запрос себе
    целиком: «2001: Космическая одиссея» лежала в той же выдаче двумя десятками раздач,
    но её ключ - ``2001``, запрос в него не входит, и до меню она не доезжала вовсе.
    Человек читал «рой мёртв» по единственной раздаче чужой картины при 80 строках в
    пуле. Тот же класс - ``RahXephon`` при 76 строках.

    Берутся ОБЕ, а не одна вместо другой: имя человек назвал верно, и обе картины
    подписаны им честно - одна целиком, другая подзаголовком. Кому из них быть дефолтом,
    решает меню по живости (:func:`~torrcast.cli.first_alive`), а не порядок проверок
    здесь; смену видно и списком, и честной строкой.

    ⚠️ Номер части в запросе это выключает: номер отсчитывается по линейке франшизы, и
    добавленная в неё картина из чужой франшизы сдвинула бы нумерацию.
    """
    if index is not None or not items:
        return items
    keys = {p.key for p in items}
    return items + [p for p in _by_subtitle(name, pictures) if p.key not in keys]


def _numbered(items: list[Picture], index: int | None) -> list[Picture]:
    """Номер части из запроса → одна картина; номера нет — вся линейка как есть.

    🔴 TC-320. Считается номер по той же ЛИНЕЙКЕ, которой меню подписывает пункты
    (:func:`_numbered_line`), и состоит она только из КИНО. Две поправки к прежнему
    «index-й по хронологии», и обе об одном - чтобы номер отвечал картиной, а не тем,
    что оказалось на этом месте:

    * не-видео (``kind == "other"``: игры, саундтреки, книги) места в линейке не
      занимает. На «матрица 5» хронология выходила длиной в семь, пятым в ней стоял
      репак игры «Матрица: Путь Нео» на одну раздачу, и он же ехал в меню - при живых
      пятидесяти семи раздачах «Воскрешения» рядом. Из каталога это не-видео не
      выбрасывает: без номера части франшиза показывается как была;
    * то, что каталог номером не подписал, номером и не отвечает. Хронология - догадка,
      и годится она, пока каталог не назвал номеров вовсе («Гарри Поттер»): тогда
      линейка и есть вся хронология, как раньше. Назвал - линейку держат названные
      номера плюс свободное первое место, а всё прочее уходит за неё, и меню зовёт его
      «без номера части». У «Матрицы» подписаны части со второй по четвёртую, линейка
      кончается на них, и пятой в ней нет, как её ни считай;
    * явный номер сильнее позиции, но за него ручается ГОД носителя. Безгодовый
      претендент («Матрица 4 - As It Should Be», фанатская сборка на двух раздачах)
      держится на одной цифре в имени, и живой настоящей части - новее последней
      подписанной и полнее его кучкой - не соперник: номер отвечает ею
      (:func:`_living_part`).

    Пустой ответ тут не потеря, а честная строка «картин во франшизе N, номера K нет»
    (:func:`~torrcast.cli._nothing`): молча показать вместо просимой части соседнюю -
    ровно та подмена картины, которой быть не должно.

    ⚠️ У сериала номер отсчитывается СЕЗОНОМ, а не частью франшизы
    (:func:`reads_season`), и линейка частей его не касается вовсе.
    """
    if index is None:
        return items
    if reads_season(items):
        return [p for p in items if p.kind == "tv"]
    line = _numbered_line([p for p in items if p.kind != "other"])[0]
    # Явный номер части сильнее позиции: «тачки 2» → «Тачки 2», а не спин-офф.
    explicit = [p for p in line if p.part == index]
    if explicit:
        best = max(explicit, key=lambda p: len(p.releases))
        alternative = bool(best.releases) and all(
            _ALTERNATIVE_PICTURE_RE.search(r.raw_name)
            or _ALTERNATIVE_TITLE_RE.search(r.raw_name.split(" / ", 1)[0])
            for r in best.releases
        )
        if best.year is not None and not alternative:
            return [best]
        # 🔴 TC-335. Безгодовый носитель явного номера сам за себя не ручается: «Матрица 4
        # / Matrix 4 - As It Should Be» - фанатская перемонтажка на двух раздачах, и год
        # каталог ей назвать не смог. Живая настоящая часть рядом («Матрица: Воскрешение»,
        # 57 раздач) такому номеру не проигрывает - иначе человек, просивший четвёртую
        # часть известной франшизы, получает любительский перемонтаж.
        rival = _living_part(items, line, index, best)
        if rival is not None:
            return [rival]
        return [best]
    if not 1 <= index <= len(line):
        return []
    # В линейке бывают дыры: назван номер 2 и номер 5, а третьей и четвёртой в выдаче
    # нет. Пятая стоит на третьем месте, но третьей частью от этого не становится.
    found = line[index - 1]
    return [] if found.part is not None else [found]


def reads_season(pictures: list[Picture]) -> bool:
    """Номер при этом имени - СЕЗОН сериала, а не номер части франшизы.

    🔴 TC-363. У сериала частей не бывает - бывают сезоны, и номер к нему приложен
    человеком именно так. Прежде номер отсчитывался по хронологии всего, что нашлось под
    именем, и «chainsaw man 2» отвечал полнометражным фильмом к сериалу («Человек-бензопила.
    Фильм: История Резе», 65 раздач), а «chainsaw man 3» - его же безгодовым латинским
    дублем на 4 раздачи. Человек просил второй сезон, а получал кино; просил третий -
    получал ту же картину под другим именем.

    Признак берётся у каталога, а не у догадки, и условий два:

    * франшизу НАЧИНАЕТ сериал - самая ранняя картина под этим именем и есть он. Тогда имя
      носит сериал, а полный метр к нему приложен, как «История Резе» к «Человеку-бензопиле»;
    * ни одну картину каталог не подписал номером части. Подписал («Форсаж 5», «Пила 8»,
      «Легенда 17») - номер и есть номер части, а цифра в имени сама за себя ручается.

    ⚠️ Первенство сериала тут не украшение, а ограждение, и мерено оно на сохранённых
    выдачах: сериал попадается в хвосте у половины киношных франшиз (документальный «Титаник»
    2012 года, «Гарри Поттер: Турнир факультетов Хогвартса», мультсериал «Джуманджи» 1996-го).
    Хватило бы одного его присутствия - и «гарри поттер 1» отвечал бы кулинарным шоу вместо
    фильма, а «титаник 3» - документалкой вместо картины 1997 года.

    Не-видео (игры, саундтреки) в счёт не идёт ни с одной стороны: «Ведьмак 3» на полке -
    игра, а не третья часть франшизы, и месту в линейке она не соперник (:func:`_numbered`).

    Отвечают на такой номер сериалы франшизы, а фильмы к ним - нет: спрошен сезон, и
    подставить вместо него полный метр значило бы показать другое кино. Есть ли такой сезон
    в выдаче - вопрос следующий и отвечает на него сезонная машинерия
    (:func:`~torrcast.cli.season_gaps`, :func:`~torrcast.cli._season_reinforce`), вплоть до
    честного «раздач с сезоном N нет».
    """
    line = [p for p in pictures if p.kind != "other"]
    if not line or any(p.part is not None for p in line):
        return False
    return min(line, key=_franchise_item_key).kind == "tv"


def _living_part(
    items: list[Picture], line: list[Picture], index: int, claimant: Picture
) -> Picture | None:
    """Живая настоящая часть против безгодового носителя явного номера, либо ``None``.

    Раз решиться может только сверкой с живостью кучки: безгодовый претендент
    (фанатская сборка вроде «Матрица 4 - As It Should Be») держится ровно на одном
    признаке - цифре в имени. Против него играет безномерная картина, которая:

    * НОВЕЕ последней подписанной номером части (года претендента нет, и мерить
      хронологию приходится от тех номеров, за которые каталог поручился и годом);
    * ЖИВЕЕ самого претендента - самая полная кучка среди таких. Сборка на двух
      раздачах пятидесяти семи раздачам настоящей части не соперник; а если живой
      картины рядом нет вовсе, претендент остаётся единственным, кого каталог назвал
      этим номером, - и честно показывается он.

    Без подписанных номеров с меньшим числом мерить не от чего: всякая безномерная
    картина (включая первую часть) оказалась бы «новее», и ответ уезжал бы на неё.
    """
    anchor = max(
        (p.year for p in line if p.part is not None and p.part < index and p.year is not None),
        default=None,
    )
    if anchor is None:
        return None
    newer = [
        p
        for p in items
        if p.kind != "other"
        and not p.collection
        and p.part is None
        and p.year is not None
        and p.year > anchor
    ]
    rival = max(newer, key=lambda p: len(p.releases), default=None)
    if rival is not None and len(rival.releases) > len(claimant.releases):
        return rival
    return None


#: Чем каталог вводит подзаголовок: двоеточием, а советское кино — словом «или».
_SUBTITLE_RE: Final = re.compile(r"\s*:\s*|,\s+или\s+")


def _by_subtitle(query: str, pictures: list[Picture]) -> list[Picture]:
    """Картины, чей ПОДЗАГОЛОВОК человек и назвал: «кольца власти» → «Властелин колец:
    Кольца власти».

    Каталог подписывает сериал полным именем («Властелин колец: Кольца власти»), а зовут
    его тем словом, под которым знают, — подзаголовком. В ключ франшизы подзаголовок не
    входит, его режет :func:`franchise_name` первым делом, и до этой проверки запрос
    «кольца власти» падал в пустоту при 39 раздачах до 117 сидов в первой же выдаче:
    ключа ``кольца-власти`` в каталоге нет, а ``властелин-колец`` в запрос не входит ни
    подстрокой, ни словами. Дальше пустоту добивал добор, приносивший по оригиналу
    ``The Lord of the Rings`` всю чужую франшизу, — и человек читал «ничего не нашлось».

    🔴 Отдаётся КАРТИНА с этим подзаголовком, а не её франшиза. Подзаголовком человек
    называет одну часть, и подставить вместо «Двух крепостей» всего «Властелина колец»
    значило бы молча показать другое кино.

    Подзаголовок сверяется ЦЕЛИКОМ, поэтому однофамильцы мимо: «кольца власти» — это не
    «Кольцо власти» 2007 года, лежащее в той же выдаче. Ищется и в русском имени, и в
    оригинале: половина каталога подписана только латиницей.
    """
    wanted = slugify(query)
    if not wanted:
        return []
    items = [p for p in pictures if wanted in _subtitles(p)]
    items.sort(key=lambda p: (p.year is None, p.year or 0, p.part or 99, -len(p.releases), p.title))
    return items


def _by_alias(query: str, pictures: list[Picture]) -> list[Picture]:
    """Картины, которых человек назвал ТРЕТЬИМ именем из их же заголовка.

    🔴 TC-244. Каталог подписывает картину перечислением имён, и знают её сплошь и рядом
    не первым из них: «Одна из многих / Из многих / **Плюрибус** / Pluribus» (10 строк),
    «Птицы 2 / **Марш пингвинов** / La marche de l'empereur» (5), «А в душе я танцую /
    **Внутри себя я танцую**» (13), «Каждый за себя / **Загадка Каспара Хаузера**» (1).
    Разбор читал первое имя и оригинал, а всё между ними терял - и запрос падал в пустоту
    при живых раздачах в своей же выдаче. Лишнего похода к индексерам тут нет: ответ уже
    приехал, его надо просто прочитать.

    🔴 **Псевдоним не вправе свести разные картины.** Одноимённость - больное место
    каталога («Призраки», «Ангел», «Убийство»), поэтому:

    * шаг последний: любое имя, которым каталог подписал картину сам, сильнее псевдонима,
      и до сюда доходит лишь то, что не нашлось никак иначе (:func:`pick_franchise`);
    * имя сверяется ЦЕЛИКОМ, без нестрогих ступеней с вхождением подстроки;
    * псевдоним, который тянет к себе больше одной франшизы, не решает ничего: молчим,
      как молчали, - честное «не нашлось» лучше однофамильца.
    """
    wanted = slugify(query)
    if not wanted:
        return []
    items = [p for p in pictures if wanted in p.aliases]
    if len({p.franchise for p in items}) != 1:
        return []
    items.sort(key=lambda p: (p.year is None, p.year or 0, p.part or 99, -len(p.releases), p.title))
    return items


def _by_both_names(query: str, pictures: list[Picture]) -> list[Picture]:
    """Картины, у которых в ДВУХ именах разом нашлись все слова запроса.

    Имя франшизы человек читает с обложки, а подзаголовок помнит по озвучке, и в запросе
    они встречаются в разных азбуках: «Gundam 0080 Карманная война» - это «Мобильный воин
    ГАНДАМ 0080: Карманная война», подписанная в каталоге ещё и оригиналом ``Mobile Suit
    Gundam 0080: War in the Pocket``. Ни одно из двух имён по отдельности всех слов запроса
    не содержит: «карманной войны» нет в оригинале, ``Gundam`` нет в русском написании
    («ГАНДАМ» - это ``gandam``, а не ``gundam``). Порознь их не сводит ничто, и запрос
    падал в пустоту.

    🔴 Отдаётся КАРТИНА, а не её франшиза - ровно по той же причине, что и в
    :func:`_by_subtitle`: слова подзаголовка человек назвал про одну часть, и подставить
    вместо неё всю линейку «Гандама» значило бы молча показать другое кино.

    Проверка тесная: слова сверяются ЦЕЛИКОМ (ни форм, ни начал), их должно быть хотя бы
    два, и найтись обязаны ВСЕ. Лишние слова в именах картины запросу не мешают - он
    короче полного имени всегда, - но своё слово каждый обязан предъявить.

    🔴 И главное: имена должны понадобиться ОБА. Хватило одного - эта ступень молчит, а
    отвечает лестница выше (ключи, оригиналы, подстроки, слова). Иначе шаг подменял бы
    собой всё, что уже умеет каталог: на корпусе в 418 картин без этого условия он один
    отвечал на восемь десятков запросов вместо штатных ступеней - и разбор имени начинал
    зависеть не от того, как картина подписана, а от того, чьи слова где встретились.
    """
    asked = _words(slugify(query))
    if len(asked) < 2:
        return []
    items = [p for p in pictures if asked <= _both_words(p) and not _one_name_is_enough(asked, p)]
    items.sort(key=lambda p: (p.year is None, p.year or 0, p.part or 99, -len(p.releases), p.title))
    return items


def _one_name_is_enough(asked: set[str], picture: Picture) -> bool:
    """Хватило ли одного имени картины, чтобы покрыть все слова запроса."""
    return any(asked <= _words(slugify(name)) for name in (picture.title, picture.original or ""))


def _both_words(picture: Picture) -> set[str]:
    """Все слова обоих имён картины: русского и оригинального."""
    return _words(slugify(picture.title)) | _words(slugify(picture.original or ""))


def _subtitles(picture: Picture) -> set[str]:
    """Подзаголовки картины — то, что каталог написал после двоеточия, слагами."""
    found = set()
    for title in (picture.title, picture.original or ""):
        parts = _SUBTITLE_RE.split(title.strip(), maxsplit=1)
        if len(parts) == 2 and (slug := slugify(parts[1])):
            found.add(slug)
    return found


def _kindred(picture: Picture, base: list[Picture]) -> bool:
    """Есть ли у картины с франшизой общее что-то, КРОМЕ слова в имени (TC-394).

    Мост между русским и оригинальным именем заведён ради находимости по обоим именам
    (см. :func:`_both_languages`), но слово - это всё, что он проверяет, а однофамильцев
    под одним словом у каталога полно: «whiplash» - это и сериал 1961 года на одну
    раздачу, и оригинал «Одержимости» 2014-го на шесть десятков. Свести их в одну
    франшизу значит отдать номер запроса сериалу («whiplash 2» читался вторым сезоном
    сериала, которого нет), тогда как человек звал картину.

    Общее - это тип картины или год (с тем же допуском ±1, что у гейта года в
    :func:`glue`): у двух половин ОДНОЙ картины, записанных на двух языках, совпадает
    хотя бы что-то из этого. Не совпало ничего - картины разные, и мост их не сводит.
    """
    for other in base:
        if picture.kind == other.kind:
            return True
        if picture.year is None or other.year is None or abs(picture.year - other.year) <= 1:
            return True
    return False


def _both_languages(
    groups: dict[str, list[Picture]], aliases: dict[str, str], key: str
) -> list[Picture]:
    """Франшиза целиком, когда её половина названа по-русски, а половина — латиницей.

    «Моана» на Knaben живёт двумя кучками: первая часть подписана только ``Moana``,
    вторая — ``Моана 2 / Moana 2``. Ключи франшиз у них разные (``moana`` и ``моана``),
    и запрос ``cast moana`` показывал бы только первую часть, а ``cast моана`` — только
    вторую. Псевдоним по оригинальному названию у нас уже посчитан — этого хватает,
    чтобы показать человеку всю франшизу, не трогая саму кластеризацию.

    🔴 TC-394. Близнецом становится не всякая франшиза под тем же словом, а та, у
    которой со спрошенной есть общее, кроме слова (:func:`_kindred`): тип или год.
    """
    items = list(groups[key])
    base = list(items)
    # Псевдоним считается от оригинального названия к русскому, а спросить могут любым:
    # ``cast moana`` и ``cast моана`` обязаны показать одну и ту же франшизу.
    twins = {aliases.get(key, "")} | {a for a, target in aliases.items() if target == key}
    seen = {id(p) for p in items}
    for twin in twins:
        if not twin or twin == key:
            continue
        # ⚠️ В `seen` уходят только новички: пересчёт по всему списку стоил бы прохода на
        # каждого близнеца, то есть квадрата по числу картин на ровном месте.
        # Родство меряется со спрошенной франшизой, а не с уже принятыми близнецами:
        # иначе цепочка «у каждого звена что-то общее с соседом» стянула бы в одну
        # франшизу и чужие картины.
        fresh = [p for p in groups.get(twin, []) if id(p) not in seen and _kindred(p, base)]
        items += fresh
        seen |= {id(p) for p in fresh}
    items.sort(key=lambda p: (p.year is None, p.year or 0, p.part or 99, -len(p.releases), p.title))
    return items


def _normalize(name: str) -> str:
    # «№» снимается до NFKC, иначе он станет буквами «No» и прирастёт к числу
    # (:data:`_NUMERO_RE`): и в ключе, и в имени картины на экране.
    text = unicodedata.normalize("NFKC", _NUMERO_RE.sub(" ", name)).replace("\xa0", " ")
    text = text.replace("–", "-").replace("—", "-").replace("‐", "-")
    text = re.sub(r"(\d{3,4})\s*р\b", r"\1p", text)  # 720р (кириллица) → 720p
    return re.sub(r"\s+", " ", text).strip()


def _find_year(text: str) -> tuple[int | None, tuple[int, int] | None]:
    for pattern in _YEAR_PATTERNS:
        match = pattern.search(text)
        if match:
            return int(match.group(1)), match.span()
    return None, None


def _fansub_episode(text: str) -> re.Match[str] | None:
    """Совпадение ``[Группа] Название - 12 [...]`` или ``None``; год в имени запрещает.

    Одна точка правды для двух читателей: :func:`_title_zone` берёт отсюда НАЗВАНИЕ (без
    номера), :func:`_parse_series` - НОМЕР СЕРИИ. Разъедься они - и номер остался бы в
    названии, а кластер по-прежнему заводил бы под каждую серию свою «картину».
    """
    if _find_year(text)[0] is not None:
        return None
    return _FANSUB_EPISODE_RE.match(text)


def _title_zone(text: str, span: tuple[int, int] | None) -> tuple[str, bool]:
    """Отрезать от имени кусок, в котором лежат названия; вторым - сборник ли это.

    Сборник узнаётся ровно тем словом, по которому имя и обрезано
    (:data:`_COLLECTION_CUT_RE`): «Хоббит: **Трилогия** / The Hobbit: Trilogy», «Гарри
    Поттер: **Коллекция**». Второго разбора имени под это нет и не нужно - вопрос «где
    кончилось название» и вопрос «сборник ли это» решает одна и та же находка.
    """
    # Номер серии - не часть имени. Без этого «Gintama: 3-nen Z-gumi Ginpachi-sensei - 11»
    # и «- 12» становились РАЗНЫМИ картинами, каждая в пару раздач, и дефолт садился на
    # такой огрызок при полном каталоге рядом (TC-151). Зона при этом идёт дальше по
    # общему пути: «Haikyuu!! 2nd Season» обязана обрезаться там же, где обрезалась.
    fansub = _fansub_episode(text)
    zone = fansub.group("name") if fansub else (text[: span[0]] if span else text)
    # Скобки убираем ПЕРВЫМИ: иначе «сезон» внутри «(5 сезон: 1-3 серии из 3)»
    # обрежет строку раньше оригинального названия, которое идёт после скобки.
    zone = _BRACKETS_RE.sub(" ", zone)  # (Режиссёр), [S01], (IMAX Edition), [Group]
    cut = _TITLE_CUT_RE.search(zone)
    collection = bool(cut and _COLLECTION_CUT_RE.match(cut.group(0)))
    if cut:
        tail = zone[cut.end() :].lstrip()
        if cut.group(0).casefold() in _RU_CUT_WORDS and tail[:1] in ("/", "|"):
            # 🔴 TC-282. Метка сборника закрывает только СВОЙ кусок: «Матрица: Трилогия /
            # The Matrix: Trilogy». Рез по ней уносил и оригинал за слэшем - картина
            # оставалась без оригинального названия вовсе. Метка режется, а кусок за
            # слэшем живёт дальше; техтокены в нём режутся тем же правилом.
            rest = _TITLE_CUT_RE.search(tail)
            zone = zone[: cut.start()] + (tail[: rest.start()] if rest else tail)
        else:
            zone = zone[: cut.start()]
    zone = _OPEN_BRACKET_RE.split(zone)[0]  # обрезали внутри скобки: «Bleach ... [»
    # Отдельного правила для «от <релиз-группа>» нет и быть не должно: «от» -
    # обычный предлог («Человек-паук: Вдали от дома»), а хвост с группой и так
    # остаётся за техническим токеном, по которому строка уже обрезана.
    if zone.count(".") >= 2 and zone.count(" ") <= 1:  # scene-имя через точки
        zone = zone.replace(".", " ")
    zone = _TITLE_TAIL_RE.sub("", zone)
    return zone.strip(" .-_|,:;/"), collection


def _split_titles(zone: str) -> tuple[str, str | None, tuple[str, ...]]:
    """``«Матрица / The Matrix»`` → русское название, оригинал и всё, что между ними.

    🔴 TC-244. Третье имя в заголовке раздачи - не украшение, а единственное имя, под
    которым картину знают: «Одна из многих / Из многих / Плюрибус / Pluribus», «Птицы 2 /
    Марш пингвинов / La marche de l'empereur», «А в душе я танцую / Внутри себя я танцую».
    Читались только первое имя и оригинал, всё между ними терялось - и запрос «плюрибус»
    падал в пустоту при десяти строках этой самой раздачи в своей же выдаче.

    Отдаём такие имена третьим полем, а не подменяем ими первое: каноническое имя картины
    по-прежнему считает каталог большинством (:func:`_compose`), и подмены имени в меню
    тут нет. Псевдонимом ищут - и только (:func:`_by_alias`).

    Зона имён приходит уже обрезанной (:func:`_title_zone`): всё после первой скобки и
    после первого технического токена в неё не входит, так что перечислением имён считается
    ровно заголовок, а не хвост раздачи.
    """
    parts = [p.strip(" .-_|,:;") for p in re.split(r"[/|]", zone)]
    numeric_original = (
        len(parts) == 2 and bool(_CYRILLIC.search(parts[0])) and bool(re.fullmatch(r"\d", parts[1]))
    )
    # Односимвольное число бывает полным оригинальным именем картины: «Девять / 9».
    # Буквенные односимвольные куски остаются служебными метками и именем не становятся.
    parts = [
        p
        for p in parts
        if (len(p) > 1 or (numeric_original and p.isdigit())) and not _TAG_ONLY_RE.match(p)
    ]
    if not parts:
        return zone.strip() or "?", None, ()

    russian = next((p for p in parts if _CYRILLIC.search(p) and not _UKRAINIAN.search(p)), None)
    latin = next(
        (p for p in parts if (p.isdigit() or _LATIN.search(p)) and not _CYRILLIC.search(p)),
        None,
    )
    if russian is None:
        return latin or parts[0], None, ()
    return russian, latin, tuple(p for p in parts if p != russian and p != latin)


def _parse_codec(text: str) -> str | None:
    """Кодек из имени. ⚠️ H.264 проверяется раньше MPEG-4: «MPEG-4 AVC» — это H.264,
    так пишут на rutracker про BDRip-AVC, и без этого порядка годный релиз уехал бы
    в старьё.
    """
    if _HEVC_RE.search(text):
        return "HEVC"
    if _H264_RE.search(text):
        return "H.264"
    if _MPEG4_RE.search(text):
        return "MPEG-4"
    return "AV1" if _AV1_RE.search(text) else None


def _parse_source(text: str) -> str | None:
    for pattern, label in _SOURCES:
        if re.search(pattern, text, re.IGNORECASE):
            return label
    return None


def _parse_voices(text: str) -> tuple[str, ...]:
    """Собрать маркеры озвучки в порядке приоритета, без повторов."""
    found: list[str] = []
    for pattern, label in _VOICES:
        if re.search(pattern, text, re.IGNORECASE) and label not in found:
            found.append(label)
    for segment in re.split(r"[|/]", text)[1:]:  # хвост rutor/megapeer: «| D, P, A»
        if not _TAG_ONLY_RE.match(segment):
            continue
        for code in re.findall(r"[DPAL]2?", segment):
            label = _TAG_VOICES.get(code) or _TAG_VOICES[code[0]]
            if label not in found:
                found.append(label)
    order = {label: i for i, (_, label) in enumerate(_VOICES)}
    return tuple(sorted(found, key=lambda v: order.get(v, 99)))


def _parse_series(
    text: str,
) -> tuple[int | None, int | None, tuple[int, ...], tuple[int, ...], bool]:
    """Сезон, серия, сезоны пака, серии пака и признак сериальности.

    ⚠️ Перед разбором из имени вырезаются токены кодека (:data:`_CODEC_TOKEN_RE`). Иначе
    ``x264`` рядом с любой цифрой читается как ``NxM``: «Moana 2 2024 … DDP5 1 x264» —
    это «5.1» плюс кодек, а разбор видел «1 x264» и объявлял полнометражку сериалом
    s1e264. Кодек о сериях не говорит ничего, поэтому вырезать его здесь безопасно —
    а весь остальной парсер остаётся как был.

    Фансабовский номер (:data:`_FANSUB_EPISODE_RE`) читается ПОСЛЕДНИМ из номеров и до
    вырезания кодека: он привязан к началу имени, где кодека нет и быть не может. Ниже
    ``SxxExx`` и диапазонов он стоит потому, что те точнее — они называют ещё и сезон.
    """
    fansub = _fansub_episode(text)
    text = _CODEC_TOKEN_RE.sub(" ", text)
    seasons = _season_span(text)
    episodes = _episode_span(text)
    if seasons:
        # Диапазон сезонов задаёт покрытие, а отдельный E-диапазон считает серии
        # всего пака. Голый «S01-15» сериями не становится.
        return seasons[0], None, seasons, episodes, True
    found = parse_episode(text)
    if found is not None:
        # «S2E1-8 of 8» - это пак сезона, а не первая серия.
        pack = re.search(r"[eхx]\s*\d{1,3}\s*-\s*\d{1,3}", text, re.IGNORECASE)
        # В длинном полном паке S1 - начало сквозной нумерации, не единственный сезон.
        linear = bool(pack and found.season == 1 and len(episodes) > 24)
        return None if linear else found.season, None if pack else found.episode, (), episodes, True
    number = int(fansub.group("episode")) if fansub else None
    for pattern in _SEASON_ONLY_RES:
        match = pattern.search(text)
        if match:
            return int(match.group("season")), number, (), episodes, True
    if number is not None:
        # Сезон в фансабовском имени называют не всегда («Haikyuu!! - 03»); молчание о
        # сезоне у релиза значит «может быть любой» (:meth:`Release.covers`), а вот номер
        # серии теперь честный - и огрызок больше не выдаёт себя за весь сериал.
        return None, number, (), episodes, True
    # Перечисленные серии - сами по себе признак сериала: имя, назвавшее диапазон серий,
    # о сериальности уже сказало («[01-201]»), и ждать от него ещё и слова «сезон»
    # значило бы записать сквозную нумерацию в фильмы (TC-169).
    return None, None, (), episodes, bool(episodes) or bool(_SERIES_HINT_RE.search(text))


def _episode_span(text: str) -> tuple[int, ...]:
    """Серии внутри раздачи по имени: «1-5 из 220» → (1…5), «220 of 220» → (1…220).

    Пусто — имя о серияx молчит. Диапазон читается раньше счёта (:data:`_EPISODE_SPAN_RES`
    против :data:`_EPISODE_COUNT_RE`), иначе «1-5 из 220» дало бы «серии 1…1»: «5 из 220»
    прочиталось бы как счёт. Вывернутые и бессмысленные границы («8-1», «0-500»)
    отбрасываются молча — врать в обе стороны хуже, чем промолчать.
    """
    for pattern in _EPISODE_SPAN_RES:
        match = pattern.search(text)
        if match:
            start, end = int(match.group("start")), int(match.group("end"))
            if 1 <= start <= end:
                return tuple(range(start, end + 1))
    match = _EPISODE_COUNT_RE.search(text)
    if match:
        count, total = int(match.group("count")), int(match.group("total"))
        if 1 <= count <= total:
            return tuple(range(1, count + 1))
    return ()


def _season_span(text: str) -> tuple[int, ...]:
    """Диапазон сезонов из имени раздачи: ``[S01-06]``, «1-6 сезоны» → (1…6)."""
    for pattern in _SEASON_SPAN_RES:
        match = pattern.search(text)
        if match:
            first, last = int(match.group(1)), int(match.group(2))
            if 0 < first < last <= 40:
                return tuple(range(first, last + 1))
    return ()


def _is_non_video(text: str) -> bool:
    """Музыка/книги/игры: не-видео маркеры при полном отсутствии видео-маркеров."""
    return bool(_NON_VIDEO_RE.search(text)) and not _VIDEO_MARKER_RE.search(text)


def _normalize_quality(value: str) -> str:
    lowered = value.lower()
    return "2160p" if lowered in {"4k", "uhd"} else lowered
