"""Клиент индексеров: один на весь поиск вместе с доборами."""

from __future__ import annotations

from typing import Protocol

from torrcast.domain.raw_result import RawResult


class IndexerClient(Protocol):
    """Что круг поиска спрашивает у клиента индексеров - и ничего сверх того.

    Клиент заводится один на весь поиск вместе с доборами: у него общий счёт бюджета,
    и потому он ходит по кругам целым объектом, а не набором чисел. Договор тут узкий
    нарочно - это ровно те ручки, которыми поиск и добор им пользуются, - но пустым он
    быть перестал: пока ручки не были названы, тайпчек не мог сказать о них ничего, и
    сценарий звал у «возчика» то, чего в договоре не значилось.
    """

    #: Пол бюджета следующего круга, секунды: ниже него круг не сжимается остатком цели.
    cap_floor: float
    #: Частный бюджет за съеденной целью уже выдан - второй раз его не дают.
    over_goal: bool

    def search(self, query: str) -> list[RawResult]:
        """Один круг по индексерам; пусто - это не ошибка, а повод переспросить иначе."""

    def late(self) -> list[RawResult]:
        """Строки, доехавшие уже после того, как круг закрылся по кворуму."""

    def spare(self) -> float:
        """Остаток цели поиска, секунды: сколько ещё можно потратить, не выйдя за неё."""
