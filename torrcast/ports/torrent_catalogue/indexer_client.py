"""Клиент индексеров: один на весь поиск вместе с доборами."""

from __future__ import annotations

from typing import Protocol

from torrcast.ports.torrent_catalogue.torrent_catalogue import RawRow


class IndexerClient(Protocol):
    """Что круг поиска спрашивает у клиента индексеров - и ничего сверх того.

    Клиент заводится один на весь поиск вместе с доборами: у него общий счёт бюджета и
    общий счёт молчунов, и потому он ходит по кругам целым объектом, а не набором чисел.
    Договор тут узкий нарочно - это ровно те пять ручек, которыми поиск и добор им
    пользуются, - но пустым он быть перестал: пока ручки не были названы, тайпчек не мог
    сказать о них ничего, и сценарий звал у «возчика» то, чего в договоре не значилось.

    ⚠️ Счёт молчунов (``silent``, ``banned``, ``reported_silent``) сюда не входит: его
    читает :func:`torrcast.usecases.discover._ask._ask` через ``getattr``, потому что на
    месте клиента в наборах стоят подделки, обещающие один лишь поиск.
    """

    #: Пол бюджета следующего круга, секунды: ниже него круг не сжимается остатком цели.
    cap_floor: float
    #: Частный бюджет за съеденной целью уже выдан - второй раз его не дают.
    over_goal: bool

    def search(self, query: str) -> list[RawRow]:
        """Один круг по индексерам; пусто - это не ошибка, а повод переспросить иначе."""

    def late(self) -> list[RawRow]:
        """Строки, доехавшие уже после того, как круг закрылся по кворуму."""

    def spare(self) -> float:
        """Остаток цели поиска, секунды: сколько ещё можно потратить, не выйдя за неё."""
