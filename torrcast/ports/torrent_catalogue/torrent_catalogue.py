"""Сырая выдача каталога раздач: её склейка в один список и разбор в релизы.

Сама выдача - строки индексеров и клиент, который их привёз, - живёт в адаптере
:mod:`torrcast.adapters.prowlarr`, а слою сценариев адаптер не назвать: правило слоёв
такой импорт запрещает. Отсюда порт: сценарий добора зовёт склейку и разбор по
договору, а кто их считает, решает композиционный корень.
"""

from __future__ import annotations

from typing import Any, Protocol, TypeAlias

from torrcast.domain.release import Release

#: Строка сырой выдачи индексера
#: (:class:`~torrcast.adapters.prowlarr.raw_result.RawResult`). Сценарий добора её НЕ
#: ЧИТАЕТ - он только перекладывает строки между склейкой и разбором и отдаёт их дальше.
#:
#: ⚠️ Имя тут пока ``Any``, и снять его этим слоем нечем. Пустого договора-возчика, как
#: у клиента рядом (:class:`IndexerClient`), тут мало: строки ходят СПИСКАМИ, а список в
#: типах неизменен - ``list[RawResult]`` под ``list[RawRow]`` не подставляется, даже
#: когда сама строка договору отвечает. Склейка вдобавок собирает строку заново
#: (``dataclasses.replace``), а это умеет только настоящий класс, а не договор о нём.
#: Честное имя появится, когда сама строка переедет из адаптера в слой домена: тогда её
#: назовут и порт, и адаптер, и подстановка списков перестанет быть вопросом.
RawRow: TypeAlias = Any


class TorrentCatalogue(Protocol):
    """Что сценарию добора нужно от сырой выдачи каталога - и ничего сверх того."""

    def merge(self, *batches: list[RawRow]) -> list[RawRow]:
        """Склеить выдачи нескольких запросов, оставив каждую раздачу один раз."""

    def to_releases(self, rows: list[RawRow]) -> list[Release]:
        """Разобрать сырые строки в релизы: имя, размер, сиды, magnet."""
