"""Показанное меню, чью строку можно дописать на месте; зовёт его сценарий выбора."""

from typing import Protocol


class MenuPaint(Protocol):
    """Меню на экране: печатается разом, а отдельная строка переписывается там, где стоит.

    Меню не ждёт справку: список нужен человеку целиком и сразу, а рейтинг и хронометраж
    приезжают позже и дописываются в уже показанную строку - зритель видит, как она
    дополняется. Поэтому у показа два разных действия, а не одно: :meth:`show` печатает
    список, :meth:`redraw` переписывает одну его строку.

    ``live`` - можно ли вообще переписать напечатанное. Без терминала (пайп, файл, юнит)
    нельзя: строка уже ушла в поток, и управляющие последовательности там были бы мусором
    в журнале. Спрашивают это ДО печати: дорисовывать некому - меню имеет смысл дождаться
    справки и напечатать её сразу.

    :meth:`close` возвращает поток вывода как было; после него меню больше не живое.
    """

    @property
    def live(self) -> bool: ...

    def show(self, lines: list[str]) -> None: ...

    def redraw(self, index: int, line: str) -> None: ...

    def close(self) -> None: ...
