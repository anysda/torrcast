"""Слот отказа от подъёма: кто отвечает, снял ли человек свой заказ, и кто это назначает.

Подъём показа идёт минутами: поиск, раздача, упаковка, ожидание картинки. Всё это время
человек вправе передумать, и его отказ обязан дойти до самого подъёма, а не только до
того, кто принял команду. Отсюда и порт: спрашивает его запуск показа
(:func:`torrcast.usecases.playback._launch._launch`), а отвечает тот, кто знает про
человека, - у консоли это никто (отказаться там некому: команда и есть человек), а у
моста Home Assistant это его поручения (:meth:`hass.orders.Orders.abandoned`).
"""

from __future__ import annotations

from collections.abc import Callable


class Slot:
    """Отказался ли человек от идущего подъёма. Пока никто не назначен - не отказывался."""

    def __init__(self) -> None:
        self._asked: Callable[[], bool] = _never

    def asked(self) -> bool:
        """Снят ли заказ на показ, который поднимается прямо сейчас."""
        return bool(self._asked())

    def asking(self) -> Callable[[], bool]:
        """Кого сейчас спрашивают: нужно тому, кто ставит своё и обязан вернуть чужое."""
        return self._asked

    def install(self, asked: Callable[[], bool]) -> None:
        """Назначить, кого спрашивать про отказ. Зовёт это композиционный корень и тесты."""
        self._asked = asked


def _never() -> bool:
    """Умолчание: отказаться некому, и подъём идёт до своего конца."""
    return False


#: Порт - состояние ПРОЦЕССА, а не объект, который носят по вызовам: слот один на прогон.
_slot = Slot()
#: Прежние имена слоёв: их зовут отовсюду, и функциями они и остаются.
abandoned = _slot.asked
asking = _slot.asking
install = _slot.install
