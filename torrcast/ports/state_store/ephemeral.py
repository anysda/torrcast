"""Состояние без файла: прогон без композиционного корня помнит его до конца процесса."""

from __future__ import annotations

from torrcast.domain.entry import Entry
from torrcast.domain.watch_state import WatchState


class Ephemeral:
    """Умолчание порта состояния: помнит позицию, но файлов владельца не заводит.

    Не молчание, как у следа: показ обязан помнить позицию хотя бы в пределах своего
    запуска, иначе сторож на каждом тике возвращал бы пустоту и «досмотрено» не наступало
    бы никогда. А вот файла пользователя тут нет - его заводит только настоящее хранилище.
    """

    def __init__(self) -> None:
        self._entries: dict[str, Entry] = {}

    def load(self) -> WatchState:
        """Своё состояние на каждое чтение, а не общий изменяемый объект.

        Файловое хранилище отдаёт новое значение всякий раз, и подделка обязана врать
        так же: иначе правка без :meth:`save` доезжала бы до соседа сама собой, и тест
        зеленел бы на записи, которой боевой путь не делает.
        """
        return WatchState(dict(self._entries))

    def save(self, state: WatchState) -> None:
        self._entries = dict(state.entries)
