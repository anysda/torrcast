"""Хранит между запусками состояние просмотра: где остановились и что досмотрено.

Форма договора снята с настоящего вызова показа - «прочитать целиком, положить запись,
записать целиком», - а не придумана красивой. Прочитать частями нельзя намеренно: рядом
пишет другой ход показа, и запись по одному ключу затёрла бы его правку. Кто именно
хранит - файл или память, - решает композиционный корень (:mod:`torrcast.runtime.wire`);
до его слова состояние живёт в памяти процесса и файлов пользователя не заводит.
"""

from __future__ import annotations

from typing import Protocol

from torrcast.domain.watch_state import WatchState


class StateStore(Protocol):
    """Что сценариям нужно от состояния - и ничего сверх того."""

    def load(self) -> WatchState:
        """Состояние целиком. Перечитывается перед каждой записью: рядом пишет сосед."""

    def save(self, state: WatchState) -> None:
        """Записать состояние целиком, атомарно."""
