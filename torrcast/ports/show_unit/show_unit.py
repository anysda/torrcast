"""Даёт сценариям взгляд на юнит показа: жив ли он, что играет, почему погас и как погасить.

Зовут его ожидание картинки (:func:`torrcast.usecases.playback._launch._await_playing`), состояние
и остановка. Кто отвечает - systemd или подделка стенда, - решает композиционный корень
(:mod:`torrcast.runtime.wire`); до его слова юнита нет вовсе, и это не авария: прогон без
корня (щуп, отдельный тест) не имеет права дёргать службы хозяйской машины.
"""

from typing import Protocol


class ShowUnit(Protocol):
    """Юнит показа снаружи ровно в том объёме, в каком его спрашивают сценарии."""

    def active(self) -> bool:
        """Идёт ли показ прямо сейчас."""

    def why(self) -> str:
        """Последняя внятная строка самого показа: почему картинки нет."""

    def stop(self) -> None:
        """Погасить показ, не дождавшийся картинки за бюджет."""

    def key(self) -> str:
        """Ключ состояния играющего показа.

        Спрашивается у юнита, а не берётся свежайшей записью состояния: рядом мог писать
        другой ход, и ответ «что играет» тогда назвал бы чужую картину.
        """
