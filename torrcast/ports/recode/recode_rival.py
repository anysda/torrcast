"""Живой перекод как сосед по процессору: идёт ли у него заход прямо сейчас."""

from typing import Protocol


class RecodeRival(Protocol):
    """Кодировщик живых кусков в объёме, в каком его знает прогрев: идёт ли заход.

    Одно свойство, и это весь договор. Прогреву не нужно ни знать, что кодировщик берёт,
    ни трогать его: пока у соседа идёт заход, прогрев обязан замереть, и больше ничего.

    Замер, ради которого договор появился: живой перекод под работающим прогревом теряет
    30 % скорости (2.62x против 1.84x), и ``nice`` этого не лечит - прогрев идёт под
    ``nice 19`` и всё равно держит 128 % из 400 %. Процессор возвращает только пауза.
    """

    @property
    def working(self) -> bool:
        """Идёт ли заход перекода прямо сейчас."""
