"""Живой перекод глазами сборки прогрева: что он возьмёт, чем и занят ли он."""

from typing import Protocol

from torrcast.ports.recode.encoding import Encoding
from torrcast.ports.recode.recode_rival import RecodeRival


class SpotRival(RecodeRival, Protocol):
    """Кодировщик тяжёлых кусков в объёме, из которого собирается прогрев.

    🔴 Прогрев обязан положить на диск ТЕ ЖЕ слоты и ТЕМ ЖЕ решением, которыми их берёт
    живой кодировщик: куски приходят приёмнику из двух мест, и для него это одна лента.
    Отсюда и весь договор - два вопроса о чужой работе плюс признак захода, который
    прогрев потом спрашивает уже сам (:class:`RecodeRival`).

    Ни поднимать кодировщика, ни брать у него готовые куски прогрев не вправе: это дело
    показа и ленты, и в этом имени их ручек нет.
    """

    @property
    def targets(self) -> tuple[int, ...]:
        """Слоты сетки, которые кодировщик обязан взять: те же берёт и прогрев."""

    @property
    def encode(self) -> Encoding:
        """Чем он берёт свои слоты: тем же решением обязан взять их прогрев."""
