"""Цель перекода по битрейту: столько о решении спрашивает лента показа."""

from typing import Protocol


class EncodingRate(Protocol):
    """Решение о кодировании в объёме, который нужен ленте: одна цель по битрейту.

    Лента решение о перекоде не принимает и не читает: сплошной перекод она ВОЗИТ в
    сборку команды упаковщика как есть, а у точечного спрашивает ровно одно число - чтобы
    сказать человеку, до скольки мегабит ужимает тяжёлый кусок. Всё остальное про это
    решение знают показ и прогрев, и звать его отсюда ленте незачем.
    """

    @property
    def mbit(self) -> float:
        """Цель по битрейту, Мбит/с: средний битрейт прогона, а не потолок куска."""
