"""Лестница пресетов кодировщика: чем и с какой скоростью он умеет перекодировать."""

from typing import Protocol


class RecodePace(Protocol):
    """Фактическая скорость перекода на этой машине и этом фильме, пресет за пресетом.

    Скорость меряет сам кодировщик (:class:`torrcast.adapters.recode.pace.Pace`), а
    сценарии её только читают: по лестнице выбирается пресет, которым кусок ещё успеет
    перекодироваться к своей секунде.
    """

    def table(self) -> tuple[tuple[str, float], ...]:
        """Пары «пресет - во сколько раз быстрее реального времени», от медленных к быстрым."""
