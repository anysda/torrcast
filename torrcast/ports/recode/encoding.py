"""Чем перекодировать: договор кодировщика целиком, каким его держит показ.

Строит решение медиатракт (:class:`torrcast.adapters.recode.encode.Encode`), а показ
называет им и сплошной перекод всего файла, и точечный перекод тяжёлых кусков.
"""

from __future__ import annotations

from typing import Protocol

from torrcast.ports.recode.encoding_key import EncodingKey


class Encoding(EncodingKey, Protocol):
    """Решение о кодировании одним значением: пресет, битрейт, кадр и цвет.

    Показ и прогрев обязаны кодировать кусок ОДНИМ решением: куски приходят приёмнику
    из двух мест и для него это одна лента. Поэтому решение и есть значение, которое
    ходит между ними целиком, а не набор чисел, собираемый заново на каждой стороне.

    Договор тут самый широкий из трёх, и это не «на всякий случай»: решение ПРИНИМАЕТ
    показ, и только ему нужны потолки, кадр наружу и ужатие под самый длинный кусок
    сетки. Тем, кому решение достаётся готовым, названы узкие доли - :class:`EncodingKey`
    прогреву и :class:`~torrcast.ports.recode.encoding_rate.EncodingRate` ленте.
    """

    @property
    def maxrate(self) -> float:
        """Мгновенный потолок кодера, Мбит/с: по нему сетка считает вес куска."""

    @property
    def out_frame(self) -> int:
        """Кадр НАРУЖУ: во что ужата картинка, а не что пришло на вход."""

    @property
    def hdr(self) -> bool:
        """Источник в HDR и цвет приводится к SDR."""

    def fit(self, span: float, cap: float, cap_mbit: float = 0.0) -> Encoding:
        """То же решение, ужатое под самый длинный кусок сетки и потолок его веса."""
