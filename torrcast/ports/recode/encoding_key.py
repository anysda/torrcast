"""Решение о кодировании в объёме, которым его различает ключ прогретого на диске."""

from typing import Protocol

from torrcast.ports.recode.encoding_rate import EncodingRate


class EncodingKey(EncodingRate, Protocol):
    """Чем кодируем и как это зовётся в ключе прогретого - и ничего сверх того.

    Столько спрашивает у решения прогрев (:func:`torrcast.usecases.warm.warm_key.warm_key`):
    в ключ каталога входит всё, от чего зависит СОДЕРЖИМОЕ куска, и это пресет, цель по
    битрейту, метка кадра с цветом и отпечаток правил, которыми решение разворачивается в
    команду. Потолки, кадр наружу и ужатие под кусок прогрев не считает - решение
    приезжает к нему уже принятым.
    """

    @property
    def preset(self) -> str:
        """Пресет кодера: чем он торгует скорость за размер."""

    @property
    def mark(self) -> str:
        """Чем этот перекод отличается от прежних в имени каталога; пусто - ничем.

        Один и тот же файл под разными приёмниками ужимается по-разному (потолок кадра -
        свойство приёмника), а сегменты у них при этом одного имени и одного веса:
        разойдись ключ - показ подсунул бы 1080p-куски туда, где сам режет 720p.
        """

    @property
    def imprint(self) -> str:
        """Отпечаток ПРАВИЛ кодирования: чем кусок собран, а не каким решением взят.

        Решение может не измениться ни на знак, а байты куска - измениться: правило
        кодирования живёт в коде, а не в решении. Снятый ``-level`` (TC-871) не тронул
        ни пресета, ни цели по битрейту, но переписал SPS каждого перекодированного
        куска. Без этой строки ключ такой правки не замечал, и полка, прогретая до неё,
        продолжала отдавать вчерашние куски, пока её не снесут руками.

        Считает его сторона, которая команду и строит
        (:func:`torrcast.adapters.recode.encode_imprint.encode_imprint`): прогреву тут
        положено сравнить две строки, а не знать ни одного флага ffmpeg.
        """
