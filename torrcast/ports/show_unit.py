"""Даёт ожиданию картинки взгляд на юнит показа: жив ли он, почему погас и как погасить.
Зовёт его :func:`torrcast.usecases.playback._await_playing`.
"""

from typing import Protocol


class ShowUnit(Protocol):
    """Юнит показа снаружи ровно в том объёме, в каком его спрашивает ожидание картинки."""

    def active(self) -> bool:
        """Идёт ли показ прямо сейчас."""

    def why(self) -> str:
        """Последняя внятная строка самого показа: почему картинки нет."""

    def stop(self) -> None:
        """Погасить показ, не дождавшийся картинки за бюджет."""
