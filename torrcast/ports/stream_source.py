"""Отвечает показу, что творится с ИСТОЧНИКОМ потока, и возвращает раздачу после аварии.

Спрашивают его на краю показа, а не в горячем пути: упаковка объявила себя мёртвой или
приёмник погасил экран. Разница между «просел рой» и «службы раздач не стало» - вся
разница для зрителя, и знает её только источник. Кто отвечает - служба раздач или
подделка стенда, - решает композиционный корень (:mod:`torrcast.runtime.wire`).
"""

from typing import Protocol


class StreamSource(Protocol):
    """Что сценариям нужно от источника показа - и ничего сверх того."""

    #: Хэш НАШЕЙ раздачи: всё, что делает источник, делается по нему и только по нему.
    torrent_hash: str
    #: Магнит той же раздачи. Трекеры живут здесь: в URL потока едет только хэш, и
    #: заведённая по голому хэшу раздача остаётся без трекеров.
    magnet: str
    #: Последняя замеченная авария источника; пусто - её не было или её уже разгребли.
    lost: str
    #: Правда ли последняя проверка вернула раздачу магнитом. Об этом говорят вслух -
    #: и зрителю, и следу: это и есть возврат трекеров.
    restored: bool

    def check(self) -> str:
        """Что не так с источником прямо сейчас; пусто - источник в порядке."""
