"""Идущий прогон упаковки в том объёме, в каком его знает лента показа."""

from typing import Protocol

from torrcast.ports.feed_grid import FeedGrid


class PackRun(Protocol):
    """Прогон ffmpeg, пока он идёт: край, живость, запас в памяти и как его погасить.

    Договор снят с настоящих вопросов ленты (:mod:`torrcast.usecases.feed_pack`), а не
    придуман про запас: сам прогон - адаптер (он поднимает процесс, пишет во временный
    файл и меряет часами), и лента обязана знать о нём ровно столько.
    """

    #: Про обрыв ЭТОГО прогона показу уже сказано вслух: второй раз не говорим.
    blamed: bool

    @property
    def first(self) -> int:
        """С какого сегмента сетки начат прогон: всё, что раньше, паковал не он."""

    @property
    def edge(self) -> int:
        """Честный край прогона: последний сегмент, который ОН выложил наружу."""

    @property
    def halted(self) -> bool:
        """Прогон погашен паузой на пульте, а не аварией (:meth:`halt`)."""

    @property
    def stopped(self) -> str:
        """Почему прогон сняли мы сами; пусто - снимали не мы."""

    def publish(self) -> None:
        """Переименовать дописанные куски наружу: недописанный наружу не выходит."""

    def poll(self) -> int | None:
        """Код возврата ffmpeg; ``None`` - прогон ещё идёт."""

    def finished(self) -> bool:
        """Прогон дочитал вход до конца, а не просто вышел."""

    def eta(self, film: float) -> float:
        """Через сколько секунд ffmpeg дочитает вход до секунды ``film``."""

    def drift(self, grid: FeedGrid) -> float:
        """Насколько нарезанное разошлось с манифестом, секунды."""

    def pending(self) -> int:
        """Сколько байт прогон написал в память, но наружу не отдал."""

    def why(self) -> str:
        """Почему прогон кончился - наружу без трейсбеков."""

    def halt(self, reason: str = "") -> None:
        """Погасить упаковку, **не трогая уже упакованное**: приёмник на паузе."""

    def stop(self, keep_files: bool = False, reason: str = "") -> None:
        """Снять прогон, оставив показу уже выложенное."""
