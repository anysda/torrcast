"""Сырая выдача каталога раздач: её склейка в один список и разбор в релизы.

Сама выдача - строки индексеров и клиент, который их привёз, - живёт в
:mod:`torrcast.search`, а он по слоям ещё не разложен. Назвать его из слоя сценариев
нечем: правило слоёв импорт неразложенного модуля запрещает, а домена у этих строк
пока нет. Отсюда порт: сценарий добора зовёт склейку и разбор по договору, а кто их
считает, решает фасад :mod:`torrcast.reinforce`.

⚠️ Порт временный, и это видно по нему самому: склейка и разбор - чистые правила без
единого похода наружу. Их дом ``torrcast/domain/``, и переедут они туда вместе со
строкой выдачи, как только :mod:`torrcast.search` разложат по слоям; тогда этот файл
исчезнет, а сценарий будет звать их обычным импортом.
"""

from __future__ import annotations

from typing import Any, Protocol, TypeAlias

from torrcast.domain.release import Release

#: Строка сырой выдачи индексера (:class:`torrcast.search.RawResult`). Сценарий добора
#: её НЕ ЧИТАЕТ - он только перекладывает строки между склейкой и разбором и отдаёт
#: их дальше, - поэтому полей тут не названо ни одного: всё, что он о строке знает,
#: это что она приехала из каталога.
RawRow: TypeAlias = Any

#: Клиент индексеров (:class:`torrcast.search.Prowlarr`): один на весь поиск вместе с
#: доборами, со своим бюджетом и своим счётом молчунов. Сценарий добора и его не
#: спрашивает - он передаёт его кругу поиска (:func:`torrcast.usecases.discover._ask`)
#: и охраннику остатка цели (:func:`torrcast.usecases.discover._no_budget`), а договор
#: с ним держат они.
IndexerClient: TypeAlias = Any


class TorrentCatalogue(Protocol):
    """Что сценарию добора нужно от сырой выдачи каталога - и ничего сверх того."""

    def merge(self, *batches: list[RawRow]) -> list[RawRow]:
        """Склеить выдачи нескольких запросов, оставив каждую раздачу один раз."""

    def to_releases(self, rows: list[RawRow]) -> list[Release]:
        """Разобрать сырые строки в релизы: имя, размер, сиды, magnet."""
