"""Значение JSON, каким его видят слои: скаляр, список или словарь - и ничего сверх того.

Имя нужно там, где через границу едет разобранный ответ чужой службы или содержимое
файла настроек: сам разбор живёт в адаптере, а слою достаётся дерево из чисел, строк и
словарей. Без имени такое дерево объявляли ``Any``, и вместе с деревом слой получал
разрешение звать у него что угодно - в том числе методы, которых у JSON не бывает.
"""

