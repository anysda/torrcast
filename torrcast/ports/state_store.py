"""Хранит между запусками состояние просмотра: где остановились и что досмотрено.

Форма договора снята с настоящего вызова показа - «прочитать целиком, положить запись,
записать целиком», - а не придумана красивой. Прочитать частями нельзя намеренно: рядом
пишет другой ход показа, и запись по одному ключу затёрла бы его правку. Кто именно
хранит - файл или память, - решает композиционный корень (:mod:`torrcast.runtime.wire`);
до его слова состояние живёт в памяти процесса и файлов владельца не заводит.
"""

from __future__ import annotations

from typing import Protocol

from torrcast.domain.entry import Entry
from torrcast.domain.watch_state import WatchState


class StateStore(Protocol):
    """Что сценариям нужно от состояния - и ничего сверх того."""

    def load(self) -> WatchState:
        """Состояние целиком. Перечитывается перед каждой записью: рядом пишет сосед."""

    def save(self, state: WatchState) -> None:
        """Записать состояние целиком, атомарно."""


class _Ephemeral:
    """Состояние без файла: прогон без композиционного корня помнит его до конца процесса.

    Не молчание, как у следа: показ обязан помнить позицию хотя бы в пределах своего
    запуска, иначе сторож на каждом тике возвращал бы пустоту и «досмотрено» не наступало
    бы никогда. А вот файла владельца тут нет - его заводит только настоящее хранилище.
    """

    def __init__(self) -> None:
        self._entries: dict[str, Entry] = {}

    def load(self) -> WatchState:
        """Своё состояние на каждое чтение, а не общий изменяемый объект.

        Файловое хранилище отдаёт новое значение всякий раз, и подделка обязана врать
        так же: иначе правка без :meth:`save` доезжала бы до соседа сама собой, и тест
        зеленел бы на записи, которой боевой путь не делает.
        """
        return WatchState(dict(self._entries))

    def save(self, state: WatchState) -> None:
        self._entries = dict(state.entries)


_store: StateStore = _Ephemeral()


def store() -> StateStore:
    """Где состояние хранится прямо сейчас."""
    return _store


def install(target: StateStore) -> None:
    """Назначить хранилище. Зовёт это композиционный корень и тесты."""
    global _store
    _store = target
