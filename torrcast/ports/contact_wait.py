"""Даёт отбору отсрочку первого контакта с роем: часы, которые он же и пускает."""

from typing import Protocol


class ContactWait(Protocol):
    """Что отбор спрашивает у отсрочки первого контакта - и ничего сверх того.

    Отсрочка - это не число секунд, а число с часами: пустой рой становится приговором
    не через ``seconds`` после завода прогрева, а через ``seconds`` после того, как
    релиз действительно дошёл до вопроса. Прогрев начинается заранее и стоит в очереди
    молча, поэтому одни и те же часы нельзя ни пустить дважды, ни пустить за него.

    Ведёт часы тот, кто отсрочку выдал (:mod:`torrcast.runtime.wire`), а сценарию она
    приходит заводом, а не значением: у каждого прогрева часы свои. Числом она остаётся
    и сама - службе раздач (:meth:`torrcast.ports.torrent_engine.TorrentEngine.wait_files`)
    та же отсрочка приходит как ``grace``.
    """

    @property
    def activated_at(self) -> float | None:
        """Когда часы пошли; ``None`` - релиз до вопроса ещё не дошёл."""

    def activate(self, seconds: float) -> None:
        """Пустить часы на ``seconds``; уже пущенные повторный вызов не сдвигает."""

    def __float__(self) -> float:
        """Отсрочка секундами - для тех, кому нужен только срок."""
