"""Окружение обновления: всё, что ``cast --upgrade`` узнаёт и делает снаружи себя.

Порт делит работу надвое: КАК добраться до загрузчика и чем его запустить живёт тут и
в адаптере, а ЧТО СЧИТАЕТСЯ поводом отказаться - в сценарии
(:mod:`torrcast.usecases.upgrade`).
"""

from typing import Protocol


class UpgradeEnvironment(Protocol):
    """Права процесса, установленный загрузчик и его запуск."""

    def is_root(self) -> bool:
        """Хватает ли прав переставить пакет и переписать юниты."""
        ...

    def loader(self) -> str:
        """Путь к установленному загрузчику либо пустая строка, если его нет.

        Загрузчик - тот же файл ``install``, которым продукт ставится одностроком: его
        кладёт рядом с venv сам установщик. Пусто значит «поставлено до того, как
        обновление появилось», и это отдельный ответ, а не отказ.
        """
        ...

    def hand_off(self, loader: str, installed: str, language: str) -> int:
        """Отдать работу загрузчику и вернуть его код возврата.

        🔴 Загрузчик обязан запускаться КОПИЕЙ во временном каталоге, а не из
        ``/opt/torrcast``: обновление переставляет ровно тот venv, из которого работает
        зовущий процесс, и читать по ходу собственный код нельзя ни питону, ни sh.
        """
        ...
