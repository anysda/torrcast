"""Клиент Telegram автозаменой превращает дефисы флага в длинное тире: тут лечим."""

from __future__ import annotations

import re

#: Тире, которыми клиент подменяет пару дефисов: среднее `–` (U+2013), длинное `—`
#: (U+2014) и горизонтальная черта `―` (U+2015). Все три дают `--`, потому что все три
#: рождаются из `--`: одиночная трактовка среднего давала сломанный флаг (`–pick` →
#: `-pick`, которого argparse не знает). Единственный однодефисный флаг реестра, `-tg`,
#: набирается дефисом вплотную к букве, и автозаменой клиента такое тире не порождается,
#: поэтому проигрышного случая у пары не остаётся.
_DASHES = "–—―"
#: Тире меняем только там, где оно открывает слово без пробела следом: это и есть место
#: флага. Тире внутри названия картины всегда окружено пробелами с обеих сторон
#: (типографский разделитель) и под это условие не подходит - его replace не трогает.
_FLAG_DASH = re.compile(f"(?<!\\S)[{_DASHES}](?=\\S)")


def restore_flag_dashes(text: str) -> str:
    """Вернуть настоящие дефисы там, где клиент перед флагом подставил тире."""
    return _FLAG_DASH.sub("--", text)
