"""Срок доезда обложек холодного захода: одно правило от старта процесса и от вопроса.

Полку меряют от старта службы, цель - полная полка и погасший счётчик за 30 с. Заход
спрашивает обложки, лишь когда пришла лента, а лента ждёт молчащий индексер до 15 с:
по замерам вопрос ложится на 3.7-18.8 с от старта. Срок - позднейшее из двух: старт
процесса плюс ``FILL_BY`` (цель минус опрос страницы и закрытие полки) и вопрос плюс
``FILL_AT_LEAST``. Ранний вопрос ждёт до бюджета цели, поздний (Prowlarr поднялся позже,
холодный заход через час) всё равно получает ``FILL_AT_LEAST`` на свои обложки, а не
остаток окна: прежний срок «первому заходу - до старта плюс 25 с» давал вопросу на
24.5 с полсекунды, полка закрывалась тонкой и дорастала после «готово».
"""

from __future__ import annotations

from typing import Final

#: Цель: холодная полка полная, и счётчик погас, за столько секунд от старта процесса.
READY_BY: Final = 30.0
#: Страница спрашивает полки раз в секунду, пока они собираются (``home.js`` ``_shelfPause``).
_PAGE_POLL: Final = 1.0
#: От срока до снятой метки сборки: закрытие обеих полок (замер 01-10-2026 - до 2.1 с с опросом).
_CLOSING: Final = 2.0
#: До какого мига от старта процесса холодный заход ждёт доезда обложек.
FILL_BY: Final = READY_BY - _PAGE_POLL - _CLOSING
#: Сколько обложкам дано от вопроса в любом случае: гонка источников отвечает за 1.5 с,
#: и это остаток бюджета у самого позднего штатного вопроса (19 с от старта).
FILL_AT_LEAST: Final = 8.0


def fill_deadline(asked: float, started: float) -> float:
    """Миг (``time.monotonic``), до которого ждать обложки, спросив их в ``asked``."""
    return max(started + FILL_BY, asked + FILL_AT_LEAST)


__all__ = ["FILL_AT_LEAST", "FILL_BY", "READY_BY", "fill_deadline"]
