"""Срок доезда обложек холодного захода: от вопроса, но первый заход - от старта фона.

Полку меряют от старта службы, а заход спрашивает обложки, лишь когда пришла лента.
Медленный индексер сдвигает вопрос: замер 01-10-2026 на стенде - вопрос на 4.7 с, срок
от него кончился на 29.7 с, счётчик погас на 30.9 с от старта; Knaben отвечал ленту и за
8.9 с. Потому первый заход после старта ждёт обложки до ``FILL_BY`` от старта фона, а не
от своего вопроса. Позже (холодный заход через час) срок снова считается от вопроса.
"""

from __future__ import annotations

from typing import Final

#: Сколько холодный заход ждёт доезда обложек, прежде чем считать очередь полки полной:
#: гонка источников отвечает за 1.5 с, опоздавшие ложатся до ~24 с (:mod:`hass.both_posters`).
FILL_BY: Final = 25.0


def fill_deadline(asked: float, started: float) -> float:
    """Миг (``time.monotonic``), до которого ждать обложки, спросив их в ``asked``."""
    first = asked < started + FILL_BY
    return (started if first else asked) + FILL_BY


__all__ = ["FILL_BY", "fill_deadline"]
