"""Доклад приёмника ТВ назад без своей цели: излёт чтения или перемотка мимо страницы.

Своя перемотка назад узнаётся по цели (:func:`web.tv_stale.tv_stale`), а у нажатой пультом
ТВ или вторым отправителем цели нет: её отличает от излёта только устоявшееся место.
"""

from __future__ import annotations

from torrcast.domain.position import Position

__all__ = ["SETTLE_SECONDS", "tv_settled"]

#: Насколько второй доклад может уйти вперёд от первого и всё ещё подтверждать его: опрос
#: идёт раз в две секунды (:data:`web.live_receiver.POLL_SECONDS`), три такта с запасом.
SETTLE_SECONDS = 6.0


def tv_settled(spot: Position, doubt: Position | None) -> bool:
    """Подтверждает ли этот доклад назад прошлый, проглоченный как излёт (``doubt``).

    🔴 Прежде любой доклад назад без своей цели глотался навсегда: место каста залипало
    на старом, эхо не уходило, упаковка считала запрошенное место «позади зрителя» и
    молчала (стенд 06-10-2026: пульт 1681.8 -> 1381.8, карточка 31 с на 1678.5). Излёт -
    один доклад, перемотка - устоявшееся место: второй доклад рядом с первым, ушедший
    вперёд или стоящий на BUFFERING/PAUSED. Повтор того же числа у «играющего» приёмника -
    эхо прошлого статуса, а не место.
    """
    if doubt is None:
        return False
    step = spot.pos - doubt.pos
    standing = spot.state in ("BUFFERING", "PAUSED")
    return 0.0 <= step <= SETTLE_SECONDS and (step > 0.0 or standing)
