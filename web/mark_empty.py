"""Открытый сезон, за которым не нашлось ни одной серии: слово вместо тишины."""

from __future__ import annotations

from torrcast.domain.json_value import JsonValue


def mark_empty(seasons: list[JsonValue], target: int, known: bool) -> list[JsonValue]:
    """Пометить открытую вкладку, если раздачи сезона не дали ни одной играющей серии.

    Вкладка есть у каждого сезона, который назвали имена раздач, а серии приезжают только
    у открытого: остальные пусты просто потому, что их никто не разбирал. Поэтому метка
    ставится ровно одному сезону - тому, который на экране, - и только когда разбор
    ДОГОВОРИЛ: недоехавшая таблица это «не знаю», а не «нет».

    Пустая вкладка молчала совсем. «Классический Доктор Кто» рисовал тринадцать вкладок, и
    девять из них не отвечали ничем: ни строки, ни слова. Человек читает такое как поломку
    страницы, хотя ответ честный - серий в этих раздачах не опознать.
    """
    if not known:
        return seasons
    for season in seasons:
        if isinstance(season, dict) and season.get("n") == target and not season.get("episodes"):
            season["empty"] = True
    return seasons


__all__ = ["mark_empty"]
