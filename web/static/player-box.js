// Ящик показа (ТЗ §7.3): вкладка не читает его ОДИН раз, а перецепляется, когда показ
// в нём сменился. Смен таких три, и все штатные: «Сначала» с карточки, «Играть» другой
// картины из второй вкладки (§7.4) и автопереход на следующую серию (§4.5). Каждая
// кладёт в ящик НОВЫЙ ключ.
//
// 🔴 Плеер, взявший первый попавшийся ящик и переставший смотреть, играл прежнюю картину
// и слал её секунду в `POST /api/web/position` со старым ключом - получая 409 раз за
// разом. Продукт так и не узнавал, что показ пошёл, и висел в `starting` навсегда: ни
// закладки, ни `season`/`episode`, ни автоперехода (замер на живом приёмнике 07-09-2026,
// пункты 6 и 8 приёмки; в журнале - сплошная стена «POST /api/web/position 409»).
//
// 🔴 Сигналом подмены служит сам этот 409, а не отдельный опрос ящика: продукт УЖЕ
// говорит вкладке, что её ключ чужой, и спрашивать ящик секунда за секундой сверх
// этого - второй прибор о том же самом.
'use strict';

const TCPlayerBox = {
  //: Где вкладка держит ключ ящика, застигнутого заказом показа. sessionStorage, а не
  //: поле: перезагрузка `/play` посреди подготовки не должна снимать эту память.
  STALE: 'tc.box.stale',

  //: Шаг опроса пустого ящика. Показ кладёт ящик через 3-9 с после «Играть», и секунда
  //: шага доплачивала до секунды сверх этого; частый шаг живёт только первые 20 с
  //: подготовки (не больше 134 запросов на заказ), дальше прежняя секунда.
  FAST_MS: 150,
  FAST_FOR_MS: 20000,
  SLOW_MS: 1000,

  pace(sinceMs) {
    return sinceMs < TCPlayerBox.FAST_FOR_MS ? TCPlayerBox.FAST_MS : TCPlayerBox.SLOW_MS;
  },

  // 🔴 Запомнить ящик, который лежал ДО заказа: пока в нём тот же ключ, показ ЧУЖОЙ.
  // Ящик переписывает не «Играть», а показ, когда он готов, - и это десятки секунд
  // спустя. Всё это время вкладка находила в ящике ПРЕДЫДУЩУЮ картину и честно её
  // играла: зритель, попросивший «Интерстеллар», получал хвост вчерашнего фильма со
  // звуком, а прибор приёмки - откат позиции с 2900 на 0 в середине замера ровности
  // (замер на живом приёмнике 07-09-2026, пункт 4: `POST /api/web/position` -> 409,
  // и следом `t=2900.50` -> `t=0.00`).
  async holdStale() {
    const box = await TCApi.box();
    sessionStorage.setItem(TCPlayerBox.STALE, (box && box.key) || '');
  },

  // Заказ не состоялся или показ уже наш - метке больше нечего сторожить.
  dropStale() {
    sessionStorage.removeItem(TCPlayerBox.STALE);
  },

  // Перецепиться на ящик, если показ в нём другой; отвечает, случилось ли это.
  // Пустой ящик - не отказ, а «показ ещё не готов» (§7.3): зовущий спросит снова.
  //
  // 🔴 Пока плеер сам досчитывает плашку автоперехода (`player._counting`, `player-
  // next.js`), кадр СЕЙЧАС не ставим: `_screenBuffering()` стирает оверлей целиком
  // (`overlay.replaceChildren()`) и рвала карточку отсчёта на середине счёта (замер
  // Два живых приёмника, 17-09-2026: плашка обрывалась на «7» из 10). Ящик найден - копим его в
  // `_pendingBox`, открывает его сама плашка по своей "Смотреть"/истечению
  // (`TCPlayer._playNext`) ИЛИ следующий `rebox()`, если досчитать не дали («Отмена»,
  // `TCPlayer._cancelNext`, дефект мержера 17-09-2026 - раньше `_pendingBox` копился
  // и не открывался никогда, вкладка висела на замёрзшем кадре навеки).
  async rebox(player) {
    const box = await TCApi.box();
    if (!box) return false;
    TCPlayerBox._tv(player, !!box.tv);
    if (!box.url || !box.key || box.key === player._key) return false;
    if (box.key === sessionStorage.getItem(TCPlayerBox.STALE)) return false;
    // Ящик по заказу ЭТОЙ вкладки: уход до его первого кадра снимает показ (`_callOff`).
    player._ordered = sessionStorage.getItem(TCPlayerBox.STALE) !== null;
    TCPlayerBox.dropStale();
    if (player._counting) {
      player._pendingBox = box;
      return true;
    }
    TCPlayerBox.apply(player, box);
    return true;
  },

  //: Поставить ящик игроку прямо сейчас: новый ключ/адрес, кадр под «буферизацией» -
  //: тем же экраном, что и у первого кадра показа, вынесенным сюда из `rebox()`, чтобы
  //: `_playNext()` (`player.js`) открывала уже найденный ящик тем же путём.
  apply(player, box) {
    player._key = box.key;
    player._url = TCPlayerBox.near(box.url);
    // Потолок запаса вкладки ставится ДО `_attach`: он уходит в настройки `Hls`, а тот
    // создаётся ровно там и переживает весь показ.
    player._tab = box.tab || null;
    // Новая серия имеет право на свою плашку отсчёта: она уже не та, что доигралa.
    // `_ending` снимается ЗДЕСЬ, а не раньше в `_playNext()` (`player.js`): до этой
    // строки видео могло ещё стоять на старой, уже прошедшей длительности, и снятый
    // раньше флаг пускал бы `_onTimeUpdate` по ней второй раз (дефект мержера
    // 17-09-2026). `_counting` снимаем тут же для ящиков, пришедших не через
    // `_playNext()` (первая посадка, чужой заказ из другой вкладки).
    player._counting = false;
    player._ending = false;
    player._framed = false;  // кадра этого ящика ещё не было: панели нечего делать
    player._screenBuffering();
    player._attach(player._url, box.at || 0);
  },

  // Адрес потока в ящике собран для ТВ: наш адрес В СТОРОНУ ТЕЛЕВИЗОРА
  // (`hls_base.py`). У машины с ТВ в отдельной сети это адрес той сети, и вкладка из
  // домашней его не достаёт (живая установка, 13-09-2026: `198.51.100.60:8080` - таймаут,
  // тот же поток по `192.0.2.60:8080` - 200 за 8 мс). Раздача слушает все адреса, так
  // что вкладка берёт поток с того узла, откуда открыла страницу. Имя в адресе -
  // заданный руками ``hls_base_url``, его не трогаем.
  near(url) {
    try {
      const u = new URL(url, location.href);
      if (/^[\d.]+$/.test(u.hostname) && location.hostname) u.hostname = location.hostname;
      return u.href;
    } catch (e) {
      return url;
    }
  },

  // Режим «на ТВ» держит ПРОДУКТ, а не память вкладки: до сих пор он жил только в ней и
  // на каждом заходе начинался с «нет», так что вкладка, открытая во время каста
  // (перезагрузка страницы, переход в плеер из карточки), включала свою плёнку со звуком
  // поверх ТВ. Слово о касте приезжает тем же ящиком, полем ``tv`` (ТЗ §7.5.4).
  _tv(player, on) {
    if (on === player._onTv) return;
    player._onTv = on;
    if (player._video) player._video.muted = on;
  },
};

window.TCPlayerBox = TCPlayerBox;
