// Ящик показа (ТЗ §7.3): вкладка не читает его ОДИН раз, а перецепляется, когда показ
// в нём сменился. Смен таких три, и все штатные: «Сначала» с карточки, «Играть» другой
// картины из второй вкладки (§7.4) и автопереход на следующую серию (§4.5). Каждая
// кладёт в ящик НОВЫЙ ключ.
//
// 🔴 Плеер, взявший первый попавшийся ящик и переставший смотреть, играл прежнюю картину
// и слал её секунду в `POST /api/web/position` со старым ключом - получая 409 раз за
// разом. Продукт так и не узнавал, что показ пошёл, и висел в `starting` навсегда: ни
// закладки, ни `season`/`episode`, ни автоперехода (замер на стенде `.104` 07-09-2026,
// пункты 6 и 8 приёмки; в журнале - сплошная стена «POST /api/web/position 409»).
//
// 🔴 Сигналом подмены служит сам этот 409, а не отдельный опрос ящика: продукт УЖЕ
// говорит вкладке, что её ключ чужой, и спрашивать ящик секунда за секундой сверх
// этого - второй прибор о том же самом.
'use strict';

const TCPlayerBox = {
  //: Где вкладка держит ключ ящика, застигнутого заказом показа. sessionStorage, а не
  //: поле: перезагрузка `/play` посреди подготовки не должна снимать эту память.
  STALE: 'tc.box.stale',

  // 🔴 Запомнить ящик, который лежал ДО заказа: пока в нём тот же ключ, показ ЧУЖОЙ.
  // Ящик переписывает не «Играть», а показ, когда он готов, - и это десятки секунд
  // спустя. Всё это время вкладка находила в ящике ПРЕДЫДУЩУЮ картину и честно её
  // играла: зритель, попросивший «Интерстеллар», получал хвост вчерашнего фильма со
  // звуком, а прибор приёмки - откат позиции с 2900 на 0 в середине замера ровности
  // (замер на стенде `.104` 07-09-2026, пункт 4: `POST /api/web/position` -> 409,
  // и следом `t=2900.50` -> `t=0.00`).
  async holdStale() {
    const box = await TCApi.box();
    sessionStorage.setItem(TCPlayerBox.STALE, (box && box.key) || '');
  },

  // Заказ не состоялся или показ уже наш - метке больше нечего сторожить.
  dropStale() {
    sessionStorage.removeItem(TCPlayerBox.STALE);
  },

  // Перецепиться на ящик, если показ в нём другой; отвечает, случилось ли это.
  // Пустой ящик - не отказ, а «показ ещё не готов» (§7.3): зовущий спросит снова.
  async rebox(player) {
    const box = await TCApi.box();
    if (!box) return false;
    TCPlayerBox._tv(player, !!box.tv);
    if (!box.url || !box.key || box.key === player._key) return false;
    if (box.key === sessionStorage.getItem(TCPlayerBox.STALE)) return false;
    // Ящик по заказу ЭТОЙ вкладки: уход до его первого кадра снимает показ (`_callOff`).
    player._ordered = sessionStorage.getItem(TCPlayerBox.STALE) !== null;
    TCPlayerBox.dropStale();
    player._key = box.key;
    player._url = box.url;
    // Новая серия имеет право на свою плашку отсчёта: она уже не та, что доигралa.
    player._advanced = false;
    player._framed = false;  // кадра этого ящика ещё не было: панели нечего делать
    player._screenBuffering();
    player._attach(box.url, box.at || 0);
    return true;
  },

  // Режим «на ТВ» держит ПРОДУКТ, а не память вкладки: до сих пор он жил только в ней и
  // на каждом заходе начинался с «нет», так что вкладка, открытая во время каста
  // (перезагрузка страницы, переход в плеер из карточки), включала свою плёнку со звуком
  // поверх ТВ. Слово о касте приезжает тем же ящиком, полем ``tv`` (ТЗ §7.5.4).
  _tv(player, on) {
    if (on === player._onTv) return;
    player._onTv = on;
    if (player._video) player._video.muted = on;
  },
};

window.TCPlayerBox = TCPlayerBox;
