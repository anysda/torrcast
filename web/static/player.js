// Файл его, и app.js в него не пишет: так две полосы не встречаются в одной строке.
'use strict';

const TCPlayer = {
  // Проверка, что вендоренный hls.js доехал целиком: на этой машине его собирает не
  // страница, а раздача файлов, и «нет плеера» обязано быть видно сразу, а не при показе.
  ready() {
    return typeof window.Hls !== 'undefined' && window.Hls.isSupported();
  },
};

window.TCPlayer = TCPlayer;
