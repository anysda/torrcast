"""Доклад приёмника ТВ меньше прежнего посреди каста: излёт чтения или своя перемотка назад.

Приёмник на прогреве отдаёт место рывком назад (живой приёмник 10-09-2026: 5.4, следом 3.6),
а это число ведёт плёнку вкладки: такой доклад слушателю не уходит. Своя перемотка назад
(:meth:`web.tv_session.TvSession.steer`) - тоже доклад меньше прежнего. Она чистит
прежний доклад, но первое чтение после команды ещё бывает старым местом: оно снова
становилось «прежним», и тогда настоящий доклад у цели глотался как излёт - вкладка и
ползунок стояли на старом месте, пока ТВ играл новое (TC-1169).
"""

from __future__ import annotations

from torrcast.domain.position import Position

__all__ = ["tv_stale"]


def tv_stale(
    spot: Position, heard: Position | None, aim: tuple[float, float] | None
) -> tuple[bool, tuple[float, float] | None]:
    """Глотать ли доклад, и какая своя перемотка ещё ждёт приезда.

    ``aim`` - откуда и куда мотала своя перемотка. Доклад ближе к цели, чем к месту,
    откуда мотали, - перемотка приехала: он проходит в любую сторону, и ждать больше
    нечего. Иначе прежнее правило: меньший доклад - излёт.
    """
    if aim is not None and abs(spot.pos - aim[1]) < abs(spot.pos - aim[0]):
        return False, None
    return heard is not None and spot.pos < heard.pos, aim
