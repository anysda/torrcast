"""Клеймо правила отбора плиток на теле полок: прежнее просит пересборки.

Отбор плиток главной живёт в :func:`web.shelf_tiles._spoken`, а собранное им тело
переживает рестарт на диске (:mod:`web.shelves_cache`). Смена отбора не даёт старому
телу спорить с новым за планку усыхания, но не прячет его от человека до замены.

🔴 Номер двигать при КАЖДОЙ правке отбора. Тем же приёмом живёт ключ родни на диске
(:func:`torrcast.domain.facts.kin_rows._kin_key`, ``kin|2|`` -> ``kin|3|``): без сдвига
прогретая установка правки не видит вовсе.
"""

from __future__ import annotations

from typing import Final

from torrcast.domain.json_value import JsonValue

#: Поле тела полок с номером правила; наружу оно идёт вместе с телом
#: (``GET /api/shelves``), и страница его просто не читает.
FIELD: Final = "rule"
#: Нынешнее правило: 1 - отбор плиток по языку имени (TC-1321); 2 добавил отсев плиток,
#: которые не запускаются (:mod:`web.shelf_playable`); 3 перестал класть отрицательный
#: приговор играбельности на диск (TC-1343) - старые записи ``False`` правила 2 иначе
#: врали бы вечно, раз диск больше их не перезаписывает.
RULE: Final = 3


def built_by_rule(body: dict[str, JsonValue]) -> bool:
    """Собрано ли тело нынешним правилом для сравнения с новой попыткой."""
    return body.get(FIELD) == RULE


__all__ = ["FIELD", "RULE", "built_by_rule"]
