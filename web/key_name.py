"""Имя картины, восстановленное из её ключа (:attr:`torrcast.domain.picture.Picture.key`).

Правило отдельным модулем, а не строкой внутри :mod:`web.own_plan`: спрашивают его
двое, и спрашивают в разное время. :func:`web.own_plan.own_plan` берёт его последним
доводом, когда ни строка поиска, ни собственное имя картины не привели к ней, а
:func:`web.card.card` - раньше всякого поиска, чтобы решить, есть ли вообще о чём
спрашивать круг.
"""

from __future__ import annotations


def key_name(key: str) -> str:
    """Имя картины из ключа; ключ без имени - пустая строка.

    Ссылку вида ``/card/{key}`` без строки запроса делает не продукт, а человек: набрал
    руками, положил в закладки, переслал. Пока имя из ключа оставалось внутренним доводом
    поиска, такая ссылка упиралась в отказ ``no_query`` ещё до круга, а страница рисовала
    этот отказ словами «раздач не нашлось» у картины, раздачи у которой есть (TC-1365).
    Отказ остаётся только там, где спрашивать нечем вовсе: ни строки, ни своего имени,
    ни имени в ключе.
    """
    _, _, tail = key.partition(":")
    slug, _, _ = tail.rpartition(":")
    return slug.replace("-", " ")


__all__ = ["key_name"]
