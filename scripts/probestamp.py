#!/usr/bin/env python3
"""Подпись прибора: чем, каким трактом и где снято число.

Инструмент разработчика: в устанавливаемый пакет не входит. Отдельной командой не
зовётся - подпись пишут сами щупы рядом со своим выводом, а сторож
(:mod:`probesign`) спрашивает её у дерева.

🔴 Число без подписи прибора - это число без замера. Пороги приставки простояли в дереве
без единой отметки о том, чем они сняты: «чем мерили» приходилось восстанавливать по
истории git, и ровно так разъехались потолок веса, снятый на mpegts, и CMAF-тракт,
которого щуп до 28-08-2026 не отдавал вовсе (TC-870). Восстановление по git не
воспроизводится: строки уезжают, коммиты сливаются, а прибор в них не назван всё равно.

Подпись - ОДНА строка одной грамматики, и она годится в оба места сразу::

    снято: <прибор> · <тракт> · <где>[ · <число>...]

* рядом с числом в дереве - ``# снято: tvprobe · mpegts · TC-620``;
* в выводе живого щупа, откуда её и переносят, - с числами, которые были в силе.

Тракт назван отдельно от прибора нарочно: один и тот же щуп отдаёт приёмнику разные
контейнеры, и число, снятое на ``mpegts``, про ``fmp4`` не говорит ничего.

Соседний паспорт :mod:`runpass` отвечает на другой вопрос - каким КОДОМ считано, - и
подпись его не заменяет: код и прибор врут порознь.
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import Final

#: Слово, с которого начинается подпись. По нему её и ищут - грепом и сторожем.
SIGN: Final = "снято:"
#: Разделитель полей подписи. Точка посередине не встречается ни в путях, ни в числах.
APART: Final = " · "
#: Прибор не восстановлен. Это тоже подпись: долг замера, названный вслух и греповый,
#: - в отличие от пустого места, которое от «снято щупом» не отличается ничем.
UNNAMED: Final = "НЕ НАЗВАН"
#: Приборы, которыми вообще меряют живой приёмник. Список закрыт нарочно: новый щуп
#: попадает в подписи только вместе с правкой здесь, а не самоназванием в комментарии.
TOOLS: Final = frozenset({"tvprobe", "seekcheck", "seekbench", "swarmprobe", "cast", UNNAMED})
#: Тракт, которым материал уехал приёмнику. ``файлом`` - мимо нашей упаковки вовсе,
#: ``не при чём`` - число не про доставку (темп роя, терпение пустого экрана).
TRACTS: Final = frozenset({"mpegts", "fmp4", "файлом", "не при чём", "неизвестен"})


def stamp(tool: str, tract: str, where: str, extra: Sequence[str] = ()) -> str:
    """Собрать подпись прибора одной строкой.

    ``where`` - карточка или дата замера, ``extra`` - числа, которые были в силе на
    прогоне. Незнакомый прибор и незнакомый тракт - ошибка, а не подпись: подпись,
    которую сторож не разберёт, не отличается от её отсутствия.
    """
    if tool not in TOOLS:
        raise ValueError(f"прибор «{tool}» не из списка: {sorted(TOOLS)}")
    if tract not in TRACTS:
        raise ValueError(f"тракт «{tract}» не из списка: {sorted(TRACTS)}")
    if not where.strip():
        raise ValueError("подпись без места замера: карточка или дата обязательны")
    return APART.join([f"{SIGN} {tool}", tract, where.strip(), *extra])
