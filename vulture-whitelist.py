"""Живые имена, которых статический поиск не видит: их зовёт не наш код, а чужой.

Файл читают обе стадии мёртвого кода в `scripts/test-gate`: имя, к которому здесь
обратились, `vulture` считает использованным. Это не модуль и он не исполняется, поэтому
имена намеренно нигде не определены; `F821` и `B018` сняты с одного этого файла поимённо
в `pyproject.toml`.

Список узкий и поимённый: «замолчать файл целиком» нельзя, иначе завтра в замолчанном
файле заведётся настоящий мертвец, а стадия промолчит и о нём. Каждая строка отвечает на
один вопрос: кто зовёт это имя, если не мы.
"""

# `http.server.BaseHTTPRequestHandler` разбирает запрос сам и ищет обработчик по имени:
# `handle_one_request` берёт `getattr(self, "do_" + команда)`. Наш код эти три метода не
# зовёт ни разу и звать не должен, их зовёт сервер на каждый входящий запрос.
_.do_GET
_.do_HEAD
_.do_OPTIONS
_.do_POST

# `close_connection` читает сам `handle_one_request` после каждого ответа: этим полем
# обработчик говорит серверу, держать ли соединение дальше или закрыть его.
_.close_connection

# `urllib.request.OpenerDirector` выбирает обработчик тоже по имени метода: `https_open`
# зовётся на каждый запрос по https, `redirect_request` - на каждый ответ с переходом.
# Наш код зовёт `urlopen`, а не эти два метода, и звать их не должен.
_.https_open
_.redirect_request

# Каждую строку про запрос и про ошибку `BaseHTTPRequestHandler` печатает сам
# (`log_request` и `log_error` зовут `log_message`). Переопределяем его там, где не
# хотим, чтобы обращения приёмника сыпались в stderr вперемешку с выводом для человека.
_.log_message

# `socketserver.BaseServer.handle_error` зовётся, когда обработчик запроса упал с
# исключением; сервер передаёт в него сам запрос и адрес клиента, отсюда второй
# параметр. Имя параметра задано чужой сигнатурой, и переименовать его нельзя.
_.handle_error
client_address

# Поля-настройки, которые читает библиотека, а не мы. `protocol_version` уходит в строку
# ответа и включает HTTP/1.1 с живым соединением; `server_version` подставляется в
# заголовок `Server`; `daemon_threads` смотрит `socketserver.ThreadingMixIn`, решая,
# ждать ли потоки запросов при остановке сервера.
protocol_version
server_version
daemon_threads
request_queue_size
# `server_name` и `server_port` обычно проставляет сам `server_bind`, а читает их
# обработчик (заголовки ответа и `address_string`). Когда слушающий сокет приходит
# готовым от systemd, `server_bind` не зовётся вовсе, и поля выставляются руками.
_.server_name
_.server_port

# Пороги профиля приёмника читаются ПО ИМЕНИ из списка `_PROFILE_THRESHOLDS`
# (`torrcast/domain/thresholds.py`): `getattr(profile, key)` в цикле, а оттуда значение
# уходит в след порогов. Прямого обращения к полю нет по построению - и так у всех
# двадцати имён того списка, просто у этих двух имя больше нигде не встречается.
app_patience
dead_url_seconds

# Договор пробы (`torrcast/ports/prober.py`) описан как вызываемый объект: его
# единственный метод зовётся синтаксисом вызова `prober(...)`, а не по имени.
_.__call__
