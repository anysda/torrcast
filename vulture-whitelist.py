# `http.server.BaseHTTPRequestHandler` разбирает запрос сам и ищет обработчик по имени:
# `handle_one_request` берёт `getattr(self, "do_" + команда)`. Наш код эти три метода не
# зовёт ни разу и звать не должен, их зовёт сервер на каждый входящий запрос.
_.do_GET
_.do_HEAD
_.do_OPTIONS

# Каждую строку про запрос и про ошибку `BaseHTTPRequestHandler` печатает сам
# (`log_request` и `log_error` зовут `log_message`). Переопределяем его там, где не
# хотим, чтобы обращения приёмника сыпались в stderr вперемешку с выводом для человека.
_.log_message

# `socketserver.BaseServer.handle_error` зовётся, когда обработчик запроса упал с
# исключением; сервер передаёт в него сам запрос и адрес клиента, отсюда второй
# параметр. Имя параметра задано чужой сигнатурой, и переименовать его нельзя.
_.handle_error
client_address

# Поля-настройки, которые читает библиотека, а не мы. `protocol_version` уходит в строку
# ответа и включает HTTP/1.1 с живым соединением; `server_version` подставляется в
# заголовок `Server`; `daemon_threads` смотрит `socketserver.ThreadingMixIn`, решая,
# ждать ли потоки запросов при остановке сервера.
protocol_version
server_version
daemon_threads

