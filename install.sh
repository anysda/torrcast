# --- 5. Индексеры через API (ноль ручных шагов в вебе) ----------------------
#: Проверочный поиск в конце фазы: чем спрашиваем и сколько ждём ОДИН индексер. Ждать
#: столько же, сколько ждёт сам Prowlarr (100 с у .NET), незачем: штатный поиск у живого
#: индексера занимает 1-3 секунды, а мёртвый не ответит и за сто. Взятые 25 - восьмикратный
#: запас к норме. Молчание за этот срок - не приговор индексеру, а честная строка в отчёте.
#: ⚠️ Спрашивать поимённо дороже, чем одним общим поиском: общий Prowlarr отдаёт мгновенно,
#: потому что молчащий индексер у него уже под штрафом и в опрос не попадает - то есть
#: «проверка» на повторном заходе не проверяла ровно то, ради чего затевалась.
PL_SEARCH_TIMEOUT="${TORRCAST_SEARCH_TIMEOUT:-25}"
PL_SEARCH_PROBE="${TORRCAST_SEARCH_PROBE:-матрица}"
#: Prowlarr сам щупает источник на POST. Одновременное добавление поэтому
#: становится залпом к трекерам. Две секунды между началами оставляют
#: на критическом пути ровно одну живую пробу. Переопределение нужно только
#: для изолированной проверки установки.
INDEXER_ADD_GAP="${TORRCAST_INDEXER_ADD_GAP:-2}"
late_indexer() {  # $1 - definitionName; 0 = добавляем в фоне, а не на глазах у человека
    # Ключевой не откладывается ни при каких условиях: фон не имеет права спрятать то,
    # без чего каталог наполовину пуст.
    [ "$1" = "$KEY_INDEXER" ] && return 1
    local late
    for late in "${LATE_INDEXERS[@]}"; do [ "$late" = "$1" ] && return 0; done
    return 1
}

# Добавить отложенные индексеры. Тела запросов собраны заранее, так что здесь остаётся
# только сходить в свой Prowlarr - никакой сети, кроме той, что он дёрнет сам.
add_indexers() {  # $1 - apikey; дальше пары «имя<TAB>тело»
    local key="$1" spec iname ibody have
    shift
    for spec in "$@"; do
        IFS=$'\t' read -r iname ibody <<<"$spec"
        [ -n "$iname" ] || continue
        # Между запуском и этой минутой мог пройти второй заход установки и добавить его
        # сам - тогда просто уходим, а не плодим второй такой же индексер.
        have="$(curl -fsS "$PL_URL/api/v1/indexer?apikey=$key" 2>/dev/null \
            | jq -r --arg n "$iname" 'any(.[]; .name==$n)' 2>/dev/null)" || have=""
        if [ "$have" = true ]; then
            info "$iname уже на месте"
            continue
        fi
        if curl -fsS -X POST "$PL_URL/api/v1/indexer?apikey=$key" \
                -H 'Content-Type: application/json' -d "$ibody" >/dev/null 2>&1; then
            info "$iname добавлен"
        else
            info "⚠ $iname не добавился (недоступен из этой сети?) - не блокер"
        fi
    done
}

# 🔴 TC-259/TC-272. Снять бан с индексеров, которых Prowlarr увёл в недоступные.
#
# Prowlarr отпускает по своим часам, а не по здоровью источника: замер на стенде - канал
# пропадал на 12 с, а каталог оставался урезанным ещё 59.2 с ПОСЛЕ его возврата; отсрочка
# растёт по отказам до часа, и бан переживает перезапуск службы (он в базе). Прошлая
# гроза поэтому доживает до сегодняшней установки, а по списку индексеров её не видно:
# забаненный так и стоит "enable": true.
#
# Ручки «снять бан» у Prowlarr 2.5.2.5491 нет: DELETE на /api/v1/indexerstatus отвечает
# 405, PUT самого индексера с forceSave=true статус не трогает. Единственное, что его
# гасит, - УСПЕШНАЯ проверка индексера: она ходит в источник по-настоящему. Отсюда и
# честность: мёртвый источник этим не воскресить, неудачная проверка бан лишь продлит -
# поэтому зовём её один раз за установку и только для тех, кто уже забанен.
unban_indexers() {  # $1 - apikey
    local key="$1" list ids id body names="" n=0
    ids="$(curl -fsS "$PL_URL/api/v1/indexerstatus?apikey=$key" 2>/dev/null \
        | jq -r '.[].indexerId' 2>/dev/null)" || return 0
    [ -n "$ids" ] || return 0
    list="$(curl -fsS "$PL_URL/api/v1/indexer?apikey=$key" 2>/dev/null)" || list='[]'
    for id in $ids; do
        body="$(curl -fsS "$PL_URL/api/v1/indexer/$id?apikey=$key" 2>/dev/null)" || continue
        if curl -fsS -X POST "$PL_URL/api/v1/indexer/test?apikey=$key" \
                -H 'Content-Type: application/json' -d "$body" >/dev/null 2>&1; then
            n=$((n + 1))
            names="$names${names:+, }$(jq -r --argjson i "$id" \
                'map(select(.id==$i))|.[0].name // "индексер \($i)"' <<<"$list")"
        fi
    done
    if [ "$n" -gt 0 ]; then
        info "снят бан с недоступных индексеров: $names"
    else
        info "⚠ Prowlarr держит индексеры недоступными, и проверка их не вернула - источники ещё молчат"
    fi
}

# Проверочные поиски по индексерам, кроме ключевого: «индексер заведён» и «поиск что-то
# находит» - разные утверждения, но ждать второго человеку незачем. Ключевой проверяется
# на глазах (без него каталог урезан вдвое), остальные - здесь.
# 🔴 TC-292. Спрашиваем СТРОГО по одному, как и лечение бана (`Prowlarr._probe` в
# search.py): залп одновременных поисков - это ровно тот образ действий, за который
# трекер раздаёт баны. Живая проба: `POST /indexer/testall` САМ забанил Nyaa, а через
# шим Nyaa держит 2-4 одновременных запроса, дальше 504 и health-бан Prowlarr на часы.
# Установке это ничего не стоит: функция живёт в догреве (`late_run`), и человек её не
# ждёт - а вот забаненный индексер на выходе установки ждать приходится часами.
check_indexers() {  # $1 - apikey; дальше тройки «номер<TAB>имя»
    local key="$1" spec id iname n
    shift
    for spec in "$@"; do
        IFS=$'\t' read -r id iname <<<"$spec"
        [ -n "$id" ] || continue
        n="$(curl -fsS -m "$PL_SEARCH_TIMEOUT" -G "$PL_URL/api/v1/search" \
                --data-urlencode "apikey=$key" --data-urlencode "query=$PL_SEARCH_PROBE" \
                --data-urlencode "type=search" --data-urlencode "limit=100" \
                --data-urlencode "indexerIds=$id" 2>/dev/null | jq 'length' 2>/dev/null)" || n=""
        if [ -z "$n" ]; then
            info "⚠ $iname: не ответил за $PL_SEARCH_TIMEOUT с"
        else
            info "$iname: $n раздач в проверочном поиске «$PL_SEARCH_PROBE»"
        fi
    done
}

install_indexers() {
    log "индексеры Prowlarr"
    local key schema existing
    key="$(prowlarr_apikey)"
    [ -n "$key" ] || die "не вычитал apikey из config.xml Prowlarr"

    # Гейт версии: обвязка рассчитана на конкретный формат ответа Prowlarr. Если
    # поставилась версия, которая отвечает иначе (например, после отката пина на
    # latest), это должно быть видно здесь и словами, а не молчаливым выходом.
    schema="$(curl -fsS "$PL_URL/api/v1/indexer/schema?apikey=$key")" \
        || die "Prowlarr не отдал схему индексеров ($PL_URL/api/v1/indexer/schema) - API этой версии не тот, на который рассчитана установка"
    existing="$(curl -fsS "$PL_URL/api/v1/indexer?apikey=$key")" \
        || die "Prowlarr не отдал список индексеров ($PL_URL/api/v1/indexer)"
    jq -e 'type == "array" and length > 0 and all(.[]; has("definitionName"))' <<<"$schema" >/dev/null 2>&1 \
        || die "схема индексеров Prowlarr не в ожидаемом виде - API этой версии не тот, на который рассчитана установка"

    local spec def url extra over body name key_here=0
    local late=() answer status first=1
    for spec in "${INDEXERS[@]}"; do
        IFS='|' read -r def url extra <<<"$spec"
        name="$(jq -r --arg d "$def" '.[]|select(.definitionName==$d)|.name' <<<"$schema")"
        if [ -z "$name" ] || [ "$name" = null ]; then
            info "⚠ $def нет в схеме этой версии Prowlarr - пропускаю"
            continue
        fi
        if jq -e --arg n "$name" 'any(.[]; .name==$n)' <<<"$existing" >/dev/null; then
            skip "индексер $name"
            [ "$def" = "$KEY_INDEXER" ] && key_here=1
            continue
        fi
        # Поля определения, которые перебиваем: базовый URL плюс то, что задано третьим
        # полем строки (`поле=значение`, через пробел). Остальные берутся из схемы как есть.
        over="$(jq -cn --arg u "$url" --arg e "${extra:-}" '
            ($e|split(" ")|map(select(length>0)|split("=")|{key:.[0],value:(.[1:]|join("="))})
             |from_entries) + {baseUrl:$u}')"
        body="$(jq -c --arg d "$def" --argjson o "$over" '
            .[]|select(.definitionName==$d)
            |{name,implementation,configContract,definitionName,priority,protocol,
              enable:true, appProfileId:1, tags:[], added:"0001-01-01T00:00:00Z",
              fields:[.fields[]|{name, value:(if $o[.name] != null then $o[.name] else .value end)}]}
        ' <<<"$schema")"
        # Тот, кому не место на критическом пути, уезжает в фон целиком (:func:`late_indexer`):
        # его тело собрано, а добавит его подоболочка уже после «готово».
        if late_indexer "$def"; then
            late+=("$(printf '%s\t%s' "$name" "$body")")
            continue
        fi
        # Каждый POST запускает живую пробу Prowlarr. Начинаем следующую только
        # после конца предыдущей. Если бан уже пойман, тело отказа называет
        # это честнее, чем догадка о сети; установка в обоих случаях идёт дальше.
        [ "$first" = 1 ] || sleep "$INDEXER_ADD_GAP"
        first=0
        answer="$(mktemp)"
        status="$(curl -sS -o "$answer" -w '%{http_code}' -X POST \
            "$PL_URL/api/v1/indexer?apikey=$key" -H 'Content-Type: application/json' \
            -d "$body" 2>/dev/null)" || status=000
        if [[ "$status" = 2* ]]; then
            info "добавлен $name"
            [ "$def" = "$KEY_INDEXER" ] && key_here=1
        else
            info "⚠ $name не добавился: Prowlarr ответил HTTP $status$(jq -r 'if type==\"array\" then .[0].errorMessage // empty else .message // empty end | if length>0 then \": \"+. else \"\" end' "$answer" 2>/dev/null) - не блокер"
        fi
    done

    # Живая проверка: «индексер заведён» и «поиск что-то находит» - разные утверждения.
    # Первое бывает правдой при неправде второго - например когда сеть режет индексер.
    # 🔴 На глазах у человека проверяем ОДИН - ключевой. Остальные друг друга
    # подстраховывают, и ждать их молчания (до $PL_SEARCH_TIMEOUT с каждому) незачем: их
    # проверка уезжает в догрев, к оценкам IMDb. А этот не подстраховывает никто, поэтому
    # его пустота обязана быть видна словами прямо здесь - и стоит она секунду, если он
    # жив. Отказ самой проверки установку не роняет: это отчёт, а не условие.
    # Бан прошлой грозы переживает и перезапуск службы, и эту установку, а на проверке
    # ниже выглядел бы как «индексер заведён, но не отдал ничего» - то есть врал бы про
    # источник. Снимаем до проверки, чтобы проверялся источник, а не отсрочка Prowlarr.
    unban_indexers "$key"

    local list key_id="" key_name="" rest=() id iname n
    list="$(curl -fsS "$PL_URL/api/v1/indexer?apikey=$key")" || list='[]'
    info "индексеров сейчас: $(jq 'length' <<<"$list")"
    while IFS='|' read -r id def iname; do
        [ -n "$id" ] || continue
        if [ "$def" = "$KEY_INDEXER" ]; then
            key_id="$id"; key_name="$iname"
        else
            rest+=("$(printf '%s\t%s' "$id" "$iname")")
        fi
    done < <(jq -r '.[]|"\(.id)|\(.definitionName)|\(.name)"' <<<"$list")

    # Гейт веса: на этом индексере держится половина каталога, и замены ему в открытом
    # пуле нет. Установку не роняем (без него всё равно ищется), но и молчать нельзя:
    # человек должен понимать, что каталог у него урезан, а не гадать, почему западного
    # кино и аниме не находится.
    if [ "$key_here" != 1 ]; then
        loud "$KEY_INDEXER не завёлся - каталог западных релизов и аниме будет неполным"
        info "поиск продолжит работать на остальных индексерах; повторный ./install.sh \
заведёт его, когда он снова будет доступен"
    elif [ -z "$key_id" ]; then
        info "$KEY_INDEXER заведён, но в списке Prowlarr его нет - проверить нечем"
    else
        n="$(curl -fsS -m "$PL_SEARCH_TIMEOUT" -G "$PL_URL/api/v1/search" \
                --data-urlencode "apikey=$key" --data-urlencode "query=$PL_SEARCH_PROBE" \
                --data-urlencode "type=search" --data-urlencode "limit=100" \
                --data-urlencode "indexerIds=$key_id" 2>/dev/null | jq 'length' 2>/dev/null)" || n=""
        if [ -z "$n" ]; then
            info "$key_name заведён, но проверить его нечем - он не ответил за $PL_SEARCH_TIMEOUT с"
        elif [ "$n" -gt 0 ]; then
            info "$key_name отвечает: $n раздач в проверочном поиске «$PL_SEARCH_PROBE»"
        else
            loud "$key_name заведён, но не отдал ничего - каталог западных релизов и аниме \
будет неполным"
            info "поиск продолжит работать на остальных индексерах; состояние видно в cast doctor"
        fi
    fi

    # Догрев: сперва то, ради чего он заведён (индексер на сто секунд), следом проверка
    # остальных. Порядок не случаен - проверять имеет смысл уже полный список.
    if [ "${#late[@]}" -gt 0 ]; then
        local names=""
        for spec in "${late[@]}"; do names="$names${names:+, }${spec%%$'\t'*}"; done
        late_run "индексер $names (добавляется до двух минут)" add_indexers "$key" "${late[@]}"
    fi
    if [ "${#rest[@]}" -gt 0 ]; then
        late_run "проверочный поиск по остальным индексерам" check_indexers "$key" "${rest[@]}"
    fi
}

# --- 6. Конфиг, ключи, состояние --------------------------------------------
setup_config() {
    log "конфиг и ключи"
    install -d -m 0755 "$CONFIG_DIR" "$STATE_DIR"
    local key; key="$(prowlarr_apikey)"

    # Темп упаковки и окно сегментов — дефолты КОДА (torrcast/state.py), а не пользовательская
    # настройка: иначе обновление молча упирается в старые числа из конфига (ровно это и
    # случилось с hls_readrate=1.5). Вычищаем их отовсюду. Туда же транспорт: раздача по
    # http на IP — устройство системы, а не вкус, и старый https-адрес из конфига обязан
    # уйти. Потолок битрейта из того же класса: это замеренное свойство приёмника (Q70D
    # ребуферит уже на 17.8 Мбит/с). Оставь его в конфиге — и опущенный до 16 дефолт молча
    # упрётся в старые 20. Настройки перекодирования — тоже замеры процессора и приёмника,
    # а не вкус.
    local tuned='del(.hls_readrate, .hls_window, .hls_burst, .hls_keep, .bitrate_warn_mbit,'
    tuned="$tuned .bitrate_hard_mbit, .recode, .recode_mbit, .recode_at_mbit, .recode_preset,"
    tuned="$tuned .recode_ahead,"
    tuned="$tuned .recode_cache_mb)"
    tuned="$tuned | .transport=\$t | .hls_port=(\$p|tonumber) | .hls_base_url=\$b"

    if [ -f "$CONFIG_DIR/config.json" ]; then
        # Адрес ТВ и прочий выбор пользователя не трогаем — обновляем только ключ.
        skip "$CONFIG_DIR/config.json (обновляю apikey, транспорт и темп беру из кода)"
        local tmp; tmp="$(mktemp "$CONFIG_DIR/.config.json.XXXX")"
        jq --arg k "$key" --arg t "$HLS_TRANSPORT" --arg p "$HLS_PORT" --arg b "$HLS_BASE_URL" \
            "$tuned | .prowlarr_apikey=\$k" "$CONFIG_DIR/config.json" >"$tmp"
        mv "$tmp" "$CONFIG_DIR/config.json"
        return
    fi

    umask 077
    cat >"$CONFIG_DIR/config.json" <<JSON
{
  "tv": null,
  "receiver": "chromecast",
  "torrserver_url": "$TS_URL",
  "prowlarr_url": "$PL_URL",
  "prowlarr_apikey": "$key",
  "transport": "$HLS_TRANSPORT",
  "hls_base_url": "$HLS_BASE_URL",
  "hls_port": $HLS_PORT,
  "hls_cert": "$TLS_DIR/torrcast.crt",
  "hls_key": "$TLS_DIR/torrcast.key",
  "hls_dir": "$HLS_DIR"
}
JSON
    info "apikey Prowlarr перенесён в $CONFIG_DIR/config.json"
}

# --- 7. Юниты и https --------------------------------------------------------
# Локаль службам задаём явно: systemd не наследует ни /etc/default/locale, ни
# /etc/environment, поэтому без Environment= процесс живёт в POSIX-локали - кириллица
# в его журнале и в именах файлов приезжает кракозябрами. Значение то же, которое
# выбрала фаза `locale`.
write_unit() {  # $1 имя, $2 описание, $3 команда, $4 - лишние строки секции [Service]
    local path="/etc/systemd/system/$1.service"
    local body
    body="$(cat <<UNIT
[Unit]
Description=$2
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
Environment=LANG=$LOCALE
${4:+$4
}ExecStart=$3
Restart=on-failure
RestartSec=5

[Install]
WantedBy=multi-user.target
UNIT
)"
    if [ -f "$path" ] && [ "$(cat "$path")" = "$body" ]; then
        skip "юнит $1.service"
        return 1
    fi
    printf '%s\n' "$body" >"$path"
    systemctl daemon-reload
}

# Своего демона раздачи нет: сервер живёт внутри процесса `cast` ровно на время
# показа — отдельного caddy/nginx с их конфигами не заводим.
# Здесь только то, что должно существовать до первого запуска: каталог сегментов, а при
# выключенной по умолчанию опции `transport: https` — ещё и серт.
setup_hls() {
    log "раздача HLS ($HLS_TRANSPORT, порт $HLS_PORT, сегменты в $HLS_DIR)"
    install -d -m 0755 "$HLS_DIR"
    if [ "$HLS_TRANSPORT" != "https" ]; then
        info "адрес раздачи собирается по маршруту до ТВ - ни серта, ни имени, ни DNS"
        return
    fi
    install -d -m 0700 "$TLS_DIR"

    if [ -s "$TLS_DIR/torrcast.crt" ] && [ -s "$TLS_DIR/torrcast.key" ]; then
        skip "серт $TLS_DIR/torrcast.crt (до $(openssl x509 -noout -enddate \
            -in "$TLS_DIR/torrcast.crt" | cut -d= -f2))"
        return
    fi

    # Self-signed = рабочий дефолт для mock-приёмника. Chromecast его молча не примет:
    # сюда кладутся файлы настоящего серта (или правится путь в config.json) — и всё.
    openssl req -x509 -newkey rsa:2048 -nodes -days 3650 \
        -keyout "$TLS_DIR/torrcast.key" -out "$TLS_DIR/torrcast.crt" \
        -subj "/CN=$HLS_HOST" -addext "basicConstraints=critical,CA:TRUE" \
        -addext "subjectAltName=DNS:$HLS_HOST,DNS:localhost,IP:127.0.0.1" 2>/dev/null
    chmod 600 "$TLS_DIR/torrcast.key"
    info "выпущен self-signed на $HLS_HOST - mock-приёмке этого достаточно"
    info "⚠ живому ТВ нужен серт LE: Chromecast self-signed молча не играет"
}

setup_facts() {
    log "справка к меню: оценки IMDb ($IMDB_RATINGS_PATH)"
    install -d -m 0755 "$(dirname "$IMDB_RATINGS_PATH")"
    # Свежее суток не перекачиваем: выгрузка обновляется раз в день, а качать 8.6 МБ
    # на каждый прогон установщика незачем.
    if [ -s "$IMDB_RATINGS_PATH" ] && [ -z "$(find "$IMDB_RATINGS_PATH" -mtime +0)" ]; then
        skip "$IMDB_RATINGS_PATH ($(wc -l < "$IMDB_RATINGS_PATH") оценок)"
        return
    fi
    local tmp="$IMDB_RATINGS_PATH.part"
    # Справка - украшение, а не механизм показа: не скачалось, режется по имени, нет
    # сети - установка идёт дальше, а меню просто печатается без рейтинга.
    if ! fetch --max-time 120 "$IMDB_RATINGS_URL" -o "$tmp.gz"; then
        rm -f "$tmp.gz"
        info "выгрузка IMDb не скачалась - меню будет без рейтинга, на показ не влияет"
        return
    fi
    if ! gzip -dc "$tmp.gz" | awk -F'\t' -v min="$IMDB_MIN_VOTES" \
        'NR==1 || $3+0 >= min { print $1 "\t" $2 "\t" $3 }' > "$tmp"; then
        rm -f "$tmp" "$tmp.gz"
        info "выгрузка IMDb битая - меню будет без рейтинга, на показ не влияет"
        return
    fi
    mv "$tmp" "$IMDB_RATINGS_PATH"
    rm -f "$tmp.gz"
    info "оценок: $(wc -l < "$IMDB_RATINGS_PATH") (от $IMDB_MIN_VOTES голосов)"
}

setup_names() {
    log "паспорт картины: русские прокатные имена IMDb ($IMDB_NAMES_PATH)"
    install -d -m 0755 "$(dirname "$IMDB_NAMES_PATH")"
    # Свежее месяца не перекачиваем: 735 МБ на каждый прогон установщика незачем.
    if [ -s "$IMDB_NAMES_PATH" ] && [ -z "$(find "$IMDB_NAMES_PATH" -mtime +"$IMDB_NAMES_DAYS")" ]; then
        skip "$IMDB_NAMES_PATH ($(wc -l < "$IMDB_NAMES_PATH") имён)"
        return
    fi
    local tmp="$IMDB_NAMES_PATH.part" names basics
    names="$(mktemp)"
    basics="$(mktemp)"
    # Паспорт - подмога добора, а не механизм показа: не скачалось, нет сети - установка
    # идёт дальше, а справка отвечает ровно так, как отвечала без карты.
    if ! fetch --max-time 3600 "$IMDB_AKAS_URL" | gzip -dc | awk -F'\t' \
        'NR>1 && ($4=="RU" || $4=="SU" || $5=="ru") && !seen[$1"\t"$3]++ { print $1 "\t" $3 }' > "$names"; then
        rm -f "$names" "$basics"
        info "выгрузка имён IMDb не скачалась - паспорт останется как был, на показ не влияет"
        return
    fi
    # Тип, оригинал и год лежат в другой выгрузке; берём из неё только картины, у которых
    # нашлось русское имя, и только экранные: эпизоды и игры паспорту не нужны.
    if ! fetch --max-time 1800 "$IMDB_BASICS_URL" | gzip -dc | awk -F'\t' \
        'NR==FNR { keep[$1]; next } FNR>1 && ($1 in keep) \
        && $2!="tvEpisode" && $2!="videoGame" && $5!="1" \
        { o=$4; if (o=="\\N") o=$3; print $1 "\t" $2 "\t" o "\t" $6 }' "$names" - > "$basics"; then
        rm -f "$names" "$basics"
        info "выгрузка карточек IMDb не скачалась - паспорт останется как был, на показ не влияет"
        return
    fi
    if awk -F'\t' 'NR==FNR { b[$1]=$2 "\t" $3 "\t" $4; next } \
        ($1 in b) { print $2 "\t" $1 "\t" b[$1] }' "$basics" "$names" > "$tmp"; then
        mv "$tmp" "$IMDB_NAMES_PATH"
        info "имён: $(wc -l < "$IMDB_NAMES_PATH")"
    else
        rm -f "$tmp"
        info "карта имён IMDb не собралась - паспорт останется как был, на показ не влияет"
    fi
    rm -f "$names" "$basics"
}

cleanup_login_notice() {
    local motd_file="${TORRCAST_MOTD:-/etc/motd}"
    local motd_d="${TORRCAST_MOTD_D:-/etc/update-motd.d}"
    rm -f "$motd_d/00-torrcast"
    if [ -f "$motd_file" ] && grep -qF 'cast status | stop | doctor' "$motd_file"; then
        : >"$motd_file"
    fi
}

main() {
    need_root
    cleanup_login_notice
    # Локаль и apt идут первыми и по очереди, иначе никак: `curl`, `jq` и `python3-venv`
    # приезжают именно отсюда, а без них не начать ни одну загрузку.
    has locale     && setup_locale
    has packages   && install_packages

    # 🔴 Дальше вся работа - сеть, и вся она независима: статическая сборка ffmpeg, два
    # соседних сервера, пробы трекеров и определения индексеров ничего не знают друг о
    # друге. По очереди это стоило больше половины установки. Пускаем разом и ждём каждое
    # там, где его результат впервые нужен; вывод каждого приезжает целиком (:func:`job_start`).
    JOB_DIR="$(mktemp -d)"
    has ffmpeg     && job_start ffmpeg     install_ffmpeg
    has torrserver && job_start torrserver install_torrserver
    has sources    && job_start sources    check_sources
    has prowlarr   && job_start prowlarr   install_prowlarr
    log "в фоне: ffmpeg, TorrServer, Prowlarr, источники - их вывод придёт целиком"

    # Самое долгое (venv и колёса с pypi) держим на переднем плане: пока идёт оно,
    # соседи успевают скачаться, подняться и ответить.
    has torrcast    && install_torrcast

    # Индексерам нужны оба: шим с прибитыми именами и поднятый Prowlarr.
    if has sources; then
        job_wait sources || info "⚠ проверка источников не доработала - смотри строки выше"
    fi
    if has prowlarr; then
        job_wait prowlarr || die "Prowlarr не поставился - причина в строках выше"
    fi
    has indexers   && install_indexers
    has config     && setup_config
    has hls        && setup_hls

    # Без этих двух `cast` не покажет ничего, поэтому «готово» ждёт их обоих.
    if has ffmpeg; then
        job_wait ffmpeg || die "ffmpeg не поставился - причина в строках выше"
    fi
    if has torrserver; then
        job_wait torrserver || die "TorrServer не поставился - причина в строках выше"
    fi
    # А это первому показу не нужно: оценки украшают меню, и качать их человеку незачем.
    has facts      && late_run "оценки IMDb для справки в меню" setup_facts
    has facts      && late_run "русские прокатные имена IMDb для паспорта картины" setup_names
    [ -n "$JOB_DIR" ] && rm -rf "$JOB_DIR"

    log "готово. Осталось: cast --tv - найдёт телевизоры в сети и спросит, который твой"
    # «Готово» сказано, когда `cast` и правда может играть. Если что-то ещё догревается -
    # это отдельная строка ПОСЛЕ него, а не задержка перед ним.
    if [ -s "$LATE_NOTES" ]; then
        info "догрев: $(awk 'NR>1{printf "; "} {printf "%s", $0} END{print ""}' "$LATE_NOTES") \
(итог в $LATE_LOG)"
    fi
    rm -f "$LATE_NOTES"
}

main "$@"
