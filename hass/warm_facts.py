"""Прогрев офлайн-карты прокатных имён: убрать её разбор из первого живого поиска.

:class:`~torrcast.adapters.wiki.imdb_names.ImdbNames` читает выгрузку лениво и нарочно
(TC-493): ``cast`` живёт один запрос, и грузить сотни тысяч строк на старте каждого
показа значило бы платить их там, где карта чаще всего не понадобится вовсе. Мост -
другое дело: он не уходит после ответа, а стоит долго и отвечает на много поисков
подряд. Ленивость, рассчитанная на одноразовый ``cast``, для него означает одно -
первый же живой поиск, которому карта понадобится (:mod:`torrcast.usecases.passport`,
ветка «Википедия не ответила»), платит её разбор сам, ожиданием человека перед экраном.
Замер на живом стенде (TC-1126): холодная карта добавляет 1.4-2.1 с к тому самому
поиску, тёплая - укладывается в её собственный бюджет.

Прогрев уносит эту плату в старт сервиса, где её никто не ждёт: заходит фоновым
потоком, не задерживая ни объявление в mDNS, ни первый принятый запрос.
"""

from __future__ import annotations

import threading

from torrcast.runtime.facts_wiring import FACTS


def warm_facts() -> None:
    """Разобрать офлайн-карту фоном, пока сервис поднимается, а не на первом поиске."""
    threading.Thread(target=FACTS.catalogue.names, daemon=True, name="warm-facts").start()


__all__ = ["warm_facts"]
