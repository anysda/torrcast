"""Взять поручение показа: новый показ СНИМАЕТ идущий, а не отказывает ему.

ТЗ веб-кинотеатра §7.4 говорит это прямо: «Играть» другой картины из второй вкладки
останавливает текущий показ, как консольный ``cast`` поверх идущего. Отказ ``busy`` на
этом месте делал кнопку немой: страница жала «Играть», получала 409 и не меняла ни
строки - человек видел ровно ничего (замер на стенде `.104` 07-09-2026: приёмка не
доходила до показа ни разу, пока предыдущий пункт оставлял свой).

🔴 Ждать освобождения надо ДО :meth:`hass.orders.Orders.take`, а не после. Остановка
кладётся в очередь принудительно (:func:`hass.stopping.stopping`), и поручение, взятое
раньше, чем она оттуда ушла, встаёт ЗА ней: остановка снимет защёлку подъёма в своём
``finally``, и новый показ поедет уже без неё - мост будет считать, что не занят никем.
"""

from __future__ import annotations

from hass.orders import Orders
from hass.stopping import stopping
from torrcast.ports.playback_session import PlaybackSession

#: Сколько ждать, пока снятый показ отпустит очередь. Отказ подъём читает на своих
#: поворотах, а не в любой точке, и самый долгий из них - ожидание ответа сети.
YIELD_SECONDS = 30.0


def starting(orders: Orders, session: PlaybackSession, args: list[str]) -> bool:
    """Освободить очередь под новый показ и взять его; ``False`` - очередь не отдали."""
    if orders.underway():
        stopping(orders, session)
        orders.settled(YIELD_SECONDS)
    return orders.take(args)


__all__ = ["starting"]
