"""Имя картины разом на полке постеров и на маршруте ``/api/poster/``; зовут обе картинки.

🔴 Имя тут ОДНО на карточку играющего (:class:`hass.posters.Posters`) и на список находок
(:class:`hass.hit_posters.HitPosters`), и это не экономия. Полка у них общая, и разъехавшиеся
имена завели бы на ней две записи про одну картину: человек увидел бы в списке не ту
картинку, что потом заиграет. Отдельного хвоста «год сверен» тут больше нет - год сверяет
сам поход за постером, и сверяет одинаково для обоих.
"""

from __future__ import annotations

import hashlib


def poster_name(title: str, year: int | None, kind: str) -> str:
    """Чем картина отличается от соседки: имя, год и род, сведённые в отпечаток.

    Отпечаток, а не сама строка: имя уезжает в адрес, который собирает Home Assistant, и
    русское название с двоеточиями и кавычками в адресе - это чужая беда. Год без года
    пишется одним словом при любом виде пустоты: у снимка показа на его месте стоит ноль,
    у записи выдачи - ничего, и без сведения это были бы две разных картины.
    """
    identity = f"{title}|{year or None}|{kind}"
    return hashlib.sha256(identity.encode("utf-8")).hexdigest()[:16]
