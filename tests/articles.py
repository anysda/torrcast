def page(heading: str, extract: str, english: str = "") -> dict[str, Any]:
    """Статья в том виде, в каком её отдаёт ``action=query``."""
    out: dict[str, Any] = {"title": heading, "extract": extract}
    if english:
        out["langlinks"] = [{"lang": "en", "title": english}]
    return out


