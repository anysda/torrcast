"""Подсети к обходу: петля, точка-точка и дубли отсеяны, широкие названы отдельно."""

from __future__ import annotations

from torrcast.adapters.chromecast.scan.net import Net
from torrcast.adapters.chromecast.scan.subnets import MAX_HOSTS, subnets


def test_huge_subnets_are_set_aside_instead_of_being_walked() -> None:
    """Подсети шире потолка не обходим, но и не выбрасываем молча.

    ``/16`` - это 65534 адреса, то есть минуты вместо секунд. Молча уйти в такой обход
    хуже, чем сказать вслух: «эту не смотрю, задай адрес руками».
    """
    good, huge = subnets(
        [
            Net("lo", "127.0.0.1", "255.0.0.0"),
            Net("eth0", "10.0.0.7", "255.255.255.0"),
            Net("eth1", "10.5.0.7", "255.255.0.0"),
            Net("wg0", "10.9.0.2", "255.255.255.255"),
            Net("eth2", "10.0.0.9", "255.255.255.0"),  # та же подсеть второй ногой
            Net("br0", "172.30.0.1", "255.255.0.0"),
        ]
    )

    assert good == ["10.0.0.0/24"], "петля, точка-точка и дубль подсети отсеяны"
    assert huge == ["10.5.0.0/16", "172.30.0.0/16"]


def test_a_broken_mask_is_skipped_and_does_not_stop_the_rest() -> None:
    """Ядро отдало что-то неразбираемое - это минус одна подсеть, а не отказ поиска."""
    good, huge = subnets(
        [Net("чушь", "не адрес", "не маска"), Net("eth0", "10.0.0.7", "255.255.255.0")]
    )

    assert good == ["10.0.0.0/24"]
    assert huge == []


def test_the_ceiling_is_a_quarter_of_a_slash_22_and_lets_a_slash_24_through() -> None:
    """Потолок выбран так, чтобы домашняя ``/24`` проходила, а ``/16`` - нет.

    Это не вкусовщина: обход ``/24`` с секундным таймаутом укладывается в секунды, а
    ``/16`` - в минуты, и телевизор в такой сети всё равно ищут не перебором.
    """
    assert MAX_HOSTS == 1024
    good, huge = subnets([Net("eth0", "10.0.0.7", "255.255.255.0")], limit=100)

    assert good == []
    assert huge == ["10.0.0.0/24"], "потолок задаётся параметром, а не прибит внутри"
