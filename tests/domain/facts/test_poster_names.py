"""Зеркало :mod:`torrcast.domain.facts.poster_names`: имена, под которыми ищут статью."""

from torrcast.domain.facts.ask import Ask
from torrcast.domain.facts.poster_names import poster_names


def test_the_title_itself_stands_first_and_the_qualified_name_follows() -> None:
    """Порядок тут - порядок доверия: первым спрашивается то, чем картину и подписали."""
    names = poster_names(Ask("Матрица", 1999, "movie"))
    assert names[0] == "Матрица"
    assert "Матрица (фильм, 1999)" in names


def test_a_pack_of_films_is_also_asked_by_the_name_of_its_first_part() -> None:
    """Сборник называет себя перечнем частей, а статья у него - статья первой части."""
    names = poster_names(Ask("Матрица, Матрица: Перезагрузка, Матрица: Революция", 1999, "movie"))
    assert "Матрица" in names, "голова сборника спрошена отдельным именем"


def test_a_title_with_a_comma_is_not_cut_down_to_a_stranger_of_the_same_year() -> None:
    """🔴 Голова обязана повториться дальше в названии, иначе это не сборник (TC-957).

    Без этого условия «Титаник, любовь и катастрофа» спрашивался бы под именем
    «Титаник» - и получал бы статью кэмероновского фильма ТОГО ЖЕ года, то есть мимо
    всякой сверки: человеку отличить такую картинку нечем.
    """
    names = poster_names(Ask("Титаник, любовь и катастрофа", 1997, "movie"))
    assert "Титаник" not in names, f"голова отрезана у несборника: {names}"


def test_a_miniseries_is_asked_for_under_its_own_third_word() -> None:
    """🔴 ОТРИЦАТЕЛЬНАЯ ПРОБА: спрашивай две формы - и «Чернобыль» берёт чужую обложку.

    Русский раздел разводит одноимённое тремя словами, а не двумя: «Чернобыль» HBO лежит
    под «(мини-сериал)», и под «(телесериал)» его нет вовсе. Пока спрашивались только две
    формы, у него не оставалось ни одного своего кандидата, а полнотекстовый поиск
    приводил соседку «Чернобыль. Зона отчуждения» - и в списке мини-сериал получал ЕЁ
    картинку. Чужая обложка тут хуже пустого места: подпись НАША, а картина не наша.

    Уместиться форма обязана в тот же отвод имён, а не сверх него: до Википедии доезжают
    первые :data:`~torrcast.domain.facts.poster_names._NAMES`.
    """
    names = poster_names(Ask("Чернобыль", 2019, "tv", "Chernobyl"))

    assert "Чернобыль (мини-сериал)" in names, "мини-сериал спрашивают только телесериалом"


def test_the_miniseries_form_does_not_push_a_film_out_of_its_own_names() -> None:
    """Место форме нашлось в хвосте объявленного набора, а не в середине.

    Фильму и картине с неназванным родом очередь тут прежняя до последнего имени:
    у них отвод занят своими уточнениями, и третье слово сериала до него не доходит.
    """
    film = poster_names(Ask("Оно", 2017, "movie", "It"))
    other = poster_names(Ask("Нечто", 2019, "other", ""))

    assert film == [
        "Оно",
        "Оно (мультфильм)",
        "Оно (фильм)",
        "Оно (мультфильм, 2017)",
        "Оно (фильм, 2017)",
        "Оно (телесериал)",
    ]
    assert "Нечто (мини-сериал)" not in other, "у неназванного рода отвод занят чужой формой"
