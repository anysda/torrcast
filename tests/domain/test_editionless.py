"""Зеркало :mod:`torrcast.domain.editionless`: чем издание отличается от другой работы."""

from torrcast.domain.editionless import _editionless


def test_a_trade_edition_tail_is_dropped() -> None:
    """«X» и «X. Полное издание» это одна картина: хвост называет носитель, а не работу."""
    assert _editionless("врата-штейна-полное-издание") == "врата-штейна"
    assert _editionless("мастер-и-маргарита-коллекционное-издание") == "мастер-и-маргарита"
    assert _editionless("властелин-колец-братство-кольца-расширенное-издание") == (
        "властелин-колец-братство-кольца"
    )


def test_the_directors_cut_is_the_same_picture() -> None:
    """Решение продукта TC-910: другой монтаж - дело отбора раздачи, а не пункта меню."""
    assert _editionless("властелин-колец-возвращение-короля-режиссерская-версия") == (
        "властелин-колец-возвращение-короля"
    )


def test_stacked_tails_go_together() -> None:
    """«X. Расширенное издание. Режиссерская версия» - всё та же X, хвостов два."""
    assert _editionless("властелин-колец-расширенное-издание-режиссерская-версия") == (
        "властелин-колец"
    )


def test_a_neighbouring_work_keeps_its_whole_name() -> None:
    """🔴 Сторож против жадности: за этими хвостами стоит ДРУГАЯ работа с другим
    хронометражом, и снять их значило бы подсунуть зрителю не тот фильм."""
    assert _editionless("игра-престолов-дополнительные-материалы") == (
        "игра-престолов-дополнительные-материалы"
    )
    assert _editionless("властелин-колец-история-создания") == "властелин-колец-история-создания"
    assert _editionless("твин-пикс-огонь-иди-со-мной-пропавшие-фрагменты") == (
        "твин-пикс-огонь-иди-со-мной-пропавшие-фрагменты"
    )
    assert _editionless("властелин-колец-презентация-с-каннского-фестиваля") == (
        "властелин-колец-презентация-с-каннского-фестиваля"
    )
    assert _editionless("евангелион-дополнение") == "евангелион-дополнение"


def test_expanded_version_is_not_an_edition() -> None:
    """🔴 «Расширенная версия» - так переведено «Expanded», и это ДОКУМЕНТАЛЬНЫЙ фильм о
    картине: «Чужие: Расширенная версия / Aliens Expanded», «Нечто. Расширенная версия /
    The Thing Expanded». Хвост похож на издание, но за ним другая работа."""
    assert _editionless("чужие-расширенная-версия") == "чужие-расширенная-версия"
    assert _editionless("нечто-расширенная-версия") == "нечто-расширенная-версия"


def test_a_key_made_of_the_tail_alone_is_kept_whole() -> None:
    """Пустого ключа не отдаём: «Полное издание» - это всё, что о картине сказано."""
    assert _editionless("полное-издание") == "полное-издание"
    assert _editionless("режиссерская-версия") == "режиссерская-версия"


def test_the_tail_is_dropped_only_from_the_end() -> None:
    """Внутри имени хвост не служебный: «Специальное издание "Чёрное восстание"» - это
    подзаголовок картины, а не пометка выпуска, и середину правило не трогает."""
    assert _editionless("код-гиасс-полное-издание-черное-восстание") == (
        "код-гиасс-полное-издание-черное-восстание"
    )
