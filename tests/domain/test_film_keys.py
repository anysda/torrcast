"""Проверяет карту опорных кадров: времена и смещения идут парой и ищутся «не позже»."""

from torrcast.domain.film_keys import FilmKeys

KEYS = FilmKeys(600.0, [0.0, 100.0, 200.0, 300.0], [0, 90 << 20, 500 << 20, 505 << 20], "mp4")


def test_the_offset_is_the_keyframe_not_later_than_the_asked_second() -> None:
    """Не «ближайший», а «не позже»: ffmpeg с ``-ss`` встаёт на кадр не позже запрошенного.

    Долей «позиция от длительности на размер файла» тут обойтись нельзя: битрейт по
    фильму гуляет вдвое. На этой карте 200-я секунда - половина фильма, а лежит она на
    500 МБ из 505.
    """
    assert KEYS.byte_at(240.0) == 500 << 20
    assert KEYS.byte_at(200.0) == 500 << 20, "попадание в кадр - это он сам"
    assert KEYS.byte_at(199.9) == 90 << 20
    assert KEYS.byte_at(0.0) == 0 and KEYS.byte_at(-5.0) == 0
    assert KEYS.byte_at(10_000.0) == 505 << 20, "за краем карты - её край"


def test_a_map_without_offsets_warms_nothing() -> None:
    """Кэш прошлой версии смещений не знал: он годен для сетки, а грелка позиции молчит.

    Это лучше, чем выбросить карту целиком: без карты показ не построит сетку вовсе.
    """
    assert FilmKeys(600.0, [0.0, 100.0], [], "").byte_at(150.0) == 0


def test_the_container_is_remembered_with_the_map() -> None:
    """Контейнер решает и правило посадки после ``-ss``, и размер прогреваемой головы."""
    assert KEYS.kind == "mp4"
    assert FilmKeys(1.0, [], []).kind == "", "карта из кэша прошлой версии контейнера не знает"
