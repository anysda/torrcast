"""Зеркало :mod:`torrcast.domain.track_place`: порог отделяет поломку от устройства.

Сторожится связь с замером, а не само число. Опусти порог ниже здорового разброса - и
склейка перестанет выходить на КАЖДОМ куске ровной сетки, то есть шов звука вернётся всюду
разом. Подними его до величины поломки - и вернётся сама поломка.
"""

from __future__ import annotations

from torrcast.domain.track_place import TRACK_PLACE_MAX

#: Самая широкая здоровая дорожка в корпусе из 53 склеек настоящим ffmpeg (24, 23.976, 25,
#: 29.97 и 50 к/с, звук 44.1 и 48 кГц, перестановка 0-3 кадра, обе сетки). Это звук на РОВНОЙ
#: сетке: там рез идёт по времени, и пакет с меткой чуть раньше границы достаётся новому куску.
#: Живой показ на приставке (три прогона, 24-27 отданных кусков в каждом) дал 0.117 у картинки
#: и 0.155 у звука - шире синтетики по картинке и уже по звуку.
HEALTHY_WIDEST = 0.1867
LIVE_WIDEST = 0.155
#: Самый мелкий ВОСПРОИЗВЕДЁННЫЙ промах места. Мельче он не бывает по построению: муксер,
#: пропустивший рез, сдвигает нумерацию файлов, то есть промахивается сразу на целый слот.
BROKEN_NARROWEST = 9.936


def test_the_threshold_lets_every_healthy_track_through() -> None:
    """Здоровый разброс дорожек порог пропускает - иначе шов вернулся бы на каждый кусок."""
    assert HEALTHY_WIDEST < TRACK_PLACE_MAX, "порог режет по здоровым кускам"
    assert LIVE_WIDEST < TRACK_PLACE_MAX, "порог режет по кускам живого показа"


def test_the_threshold_catches_the_narrowest_reproduced_break() -> None:
    """🔴 TC-833. Самый мелкий воспроизведённый промах места порогом ловится."""
    assert TRACK_PLACE_MAX < BROKEN_NARROWEST, "порог пропускает чужое место"


def test_the_threshold_stands_in_the_free_gap_and_not_on_either_edge() -> None:
    """Порог стоит в пустом промежутке между двумя множествами, а не по краю одного из них.

    Запас нужен с обеих сторон: снизу - потому что корпус конечен и следующий контейнер
    вправе дать разброс шире замеренного, сверху - потому что промах бывает и мельче слота,
    когда рез не пропущен, а лишь опоздал до следующего настоящего опорного кадра.
    """
    assert TRACK_PLACE_MAX > HEALTHY_WIDEST * 2, "запас над здоровым разбросом меньше двойного"
    assert TRACK_PLACE_MAX < BROKEN_NARROWEST / 10, "порог прижат к поломке, а не к промежутку"
