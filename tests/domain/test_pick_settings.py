"""Зеркало :mod:`torrcast.domain.pick_settings`: во что фаза отбора вправе обойтись человеку.

Сторожатся связи между потолками: бюджет фазы собран из бюджетов одной раздачи, отсрочка
мёртвого роя обязана обрывать раньше полного щупа, а перевод потолка приговоров в секунды
не смеет оказаться послаблением ниже прежнего пола.
"""

from __future__ import annotations

from torrcast.domain.pick_settings import (
    HONEST_BUDGET,
    MAX_TRIES,
    META_BUDGET,
    PICK_BUDGET,
    PROBE_BUDGET,
    SWARM_GRACE,
    VERDICT_BUDGET,
)

#: Верхняя замеренная цена одного приговора: столько отбор простаивал на тяжёлом ремуксе.
DEAREST_VERDICT_SECONDS = 5.0


def test_the_phase_budget_is_assembled_from_the_budgets_of_one_release() -> None:
    """Потолок фазы - это прежние три полных раздачи, а не отдельно выбранное число.

    Изменилось только то, на что он тратится: раньше в него укладывались строго три
    раздачи, теперь - сколько успеет, пока осечки идут молчанием роя. Развяжи эту сумму - и
    потолок фазы перестанет быть выводом из потолков раздачи, то есть станет вкусовщиной.
    """
    assert PICK_BUDGET == MAX_TRIES * (META_BUDGET + PROBE_BUDGET)


def test_the_swarm_grace_cuts_a_dead_release_short_of_the_full_probe() -> None:
    """Отсрочка обязана обрывать мёртвый рой РАНЬШЕ полного щупа, иначе она не экономит ничего.

    Раздача с мёртвым роем метаданные отдаёт, а содержимого не отдаёт вовсе, и раньше на
    ней сгорал весь бюджет щупа - сорок секунд на одном молчащем релизе, когда рядом в
    очереди стояли живые.
    """
    assert SWARM_GRACE < PROBE_BUDGET
    assert PROBE_BUDGET - SWARM_GRACE >= 25.0, "экономия на молчащей раздаче меньше замеренной"


def test_the_verdict_budget_is_not_a_relaxation_below_the_old_floor() -> None:
    """Секундный потолок приговоров не смеет быть мягче прежнего счётчика.

    Пятнадцать секунд - это цена прежних трёх приговоров по верхней замеренной их цене.
    Опусти число - и отбор станет строже прежнего там, где приговоры дороги, то есть
    начнёт бросать очередь раньше, чем бросал до перевода потолка в секунды.
    """
    assert VERDICT_BUDGET >= MAX_TRIES * DEAREST_VERDICT_SECONDS
    assert VERDICT_BUDGET < PICK_BUDGET, "потолок приговоров не может съесть всю фазу"


def test_the_ask_to_an_honest_spare_stays_cheaper_than_a_fresh_probe() -> None:
    """За честного запасного платят разницей между двумя ffprobe, а не новым щупом.

    Запасной к этой секунде уже греется, поэтому его срок обязан быть короче полного щупа:
    иначе лишние секунды старта покупались бы там, где выигрыш - всего лишь чуть большая
    чёткость.
    """
    assert HONEST_BUDGET < PROBE_BUDGET
    assert META_BUDGET < PROBE_BUDGET, "метаданные по DHT дешевле чтения дорожек"
