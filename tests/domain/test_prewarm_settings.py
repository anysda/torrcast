"""Зеркало :mod:`torrcast.domain.prewarm_settings`: сколько греется впрок под меню.

Сторожится главная связь модуля: жёсткий потолок одновременных раздач обязан ровно
покрывать замеренный пик прогрева. Опустишь потолок - он начнёт резать то, ради чего
прогрев и заводился; поднимешь - вернётся то, от чего служба-источник панует.
"""

from __future__ import annotations

from torrcast.domain.prewarm_settings import MAX_LIVE, PREWARM, PREWARM_DUB, PREWARM_SPARE


def test_the_ceiling_is_exactly_the_measured_peak_of_the_warm_under_the_menu() -> None:
    """Потолок равен пику прогрева, а не «числу побольше» и не «числу поменьше».

    Пик - это топ картин франшизы плюс запасной релиз выбранной картины плюс сосед,
    обещавший русскую дорожку. Ниже потолок режет замеренный выигрыш (человек снова платит
    6-7 с за подъём второй раздачи), выше - копится то, что уже перестало быть нужным, а
    служба-источник панует тем вероятнее, чем больше живых раздач.
    """
    assert MAX_LIVE == PREWARM + PREWARM_SPARE + PREWARM_DUB


def test_the_menu_warms_more_than_one_picture_and_more_than_one_release_of_it() -> None:
    """Прогрев обязан вести в живое по ОБЕИМ осям: разные картины и запасной внутри картины.

    Обнули любое из двух - и меню снова упрётся в одну ветку: либо человек, ответивший не
    дефолтом, платит полный подъём, либо платит он же на бракованном верхе выбранной
    картины.
    """
    assert PREWARM > 1
    assert PREWARM_SPARE >= 1
    assert PREWARM_DUB >= 1, "сосед, обещавший русскую дорожку, обязан греться под меню"


def test_the_warm_under_the_menu_stays_the_handful_it_was_measured_to_be() -> None:
    """Картин под меню греется горстка - ровно верх очереди, а не вся выдача.

    Число названо замером: топ-2-3 картины франшизы. Расти ему нельзя, и держит его не
    вежливость, а живучесть службы-источника: она валится тем вероятнее, чем больше у неё
    живых раздач, а потолок одновременных (:data:`MAX_LIVE`) считается ровно от этого
    числа. Подними его - и потолок поднялся бы следом, вернув то, от чего служба панует.
    """
    assert 2 <= PREWARM <= 3
