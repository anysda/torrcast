"""Сторож на алфавит примет: кириллические двойники в пометке формата.

Восемь имён ниже сняты живой выдачей запроса «сталкер» с Prowlarr на стенде: все восемь
аудиокниги, все восемь проходили в меню целыми, потому что в `МР3` буквы `М` и `Р`
кириллические. Флаг `(?i)` снимает регистр, а алфавит - нет.

Вторая половина сторожа - что приведение НЕ трогает настоящие слова: «Ха**рс**» и
«ве**рс**ія» дают `pc`, «А**так**а» даёт `tak`, и приведение по букве убило бы на
корпусе-100 двенадцать живых картин. Кто снимет условие «токен целиком, заглавные
двойники, рядом латиница или цифра» - здесь обязан покраснеть.
"""

from torrcast.domain.nonvideo_release import _is_nonvideo_release, _latinise

LIVE = [
    "Иван Подрыгин - S.T.A.L.K.E.R.: Сталкер 2.0 (2024) МР3",
    "Сергей Кадышев - S.T.A.L.K.E.R.: Сталкеры бывают разные (2024) МР3",
    "Виктор Глумов - Сталкеры поневоле 02, Хранитель Зоны (2024) МР3",
    "Виктор Глумов - Сталкеры поневоле 01, Мышеловка (2024) МР3",
    "Дмитрий Силлов - S.T.A.L.K.E.R. Снайпер. Закон сталкера (2024) МР3",
    "Алексей Калугин - Так держать, сталкер! (2023) МР3",
    "Юрий Смирнов - Сталкер поневоле (2022) МР3",
    "Дмитрий Силлов - S.T.A.L.K.E.R.: Снайпер. Закон чёрного сталкера (2021) МР3",
]


def test_eight_live_audiobooks_with_cyrillic_mp3_are_nonvideo() -> None:
    assert [n for n in LIVE if not _is_nonvideo_release(n)] == []


def test_only_a_whole_mixed_token_of_twins_is_folded() -> None:
    assert _latinise("(2024) МР3") == "(2024) MP3"
    assert _latinise("[2160p, 4К]") == "[2160p, 4K]"
    assert _latinise("ВDRip, НЕVC") == "BDRip, HEVC"
    assert _latinise("Стеффен Харс") == "Стеффен Харс"
    assert _latinise("Невідома версія") == "Невідома версія"
    assert _latinise("ТАК ДЕРЖАТЬ") == "ТАК ДЕРЖАТЬ"
    assert _latinise("КинопоискHD") == "КинопоискHD"


def test_a_real_word_of_twin_letters_is_not_a_mark() -> None:
    assert not _is_nonvideo_release("Стеффен Харс - Новые пацаны (2016)")
    assert not _is_nonvideo_release("Невідома версія / Неизвестная версия (2008)")
    assert not _is_nonvideo_release("ТАК ДЕРЖАТЬ (1990)")
    assert not _is_nonvideo_release("АТАКА ТИТАНОВ 07 [DUB RUS]")
