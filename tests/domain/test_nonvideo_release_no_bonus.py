"""Сторож: N5 (доп.материалы, «фильм о фильме») в N1-N4 не входит и шиться не должен.

Слово `Bonus`/«фильм о фильме» стоит и в имени обычного релиза с бонус-диском, и в
имени самостоятельной работы; отсев по нему убил бы «Чернобыль: Зона отчуждения.
Финал» целиком - 9 раздач из 9 с хвостом `[01-03 из 03 + Фильм о фильме]`. N5
отвергнут числами и не шьётся ни в каком виде; кто добавит его - обязан покраснеть.
"""

from torrcast.domain.nonvideo_release import _is_nonvideo_release


def test_a_making_of_tail_release_stays_video() -> None:
    assert not _is_nonvideo_release(
        "Чернобыль: Зона отчуждения. Финал (2019) [01-03 из 03 + Фильм о фильме]"
    )
