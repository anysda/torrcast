"""Сторож на игру с пометкой `PC`/`РС` в САМОМ КОНЦЕ имени, без разделителя рядом.

Двенадцать имён ниже - раздачи корпуса-100, каждая уходила в меню целым пунктом рядом
с фильмом того же названия: правило N4 брало `PC` только вплотную к `|` или `-`. Все
двенадцать - игры, ни одной картины среди них нет (проверено поимённо контрфактом
`scripts/spanprobe.py`: раздач потеряно 12, пришло 0, смен верха меню 0).

Вторая половина сторожа - граница слова, считающая кириллическую букву буквой. Голый
токен с латинской границей (`(?<![a-z])`) на корпусах репы берёт лишними 1133 имени и
убивает 19 живых картин («Форсаж», «Властелин колец», «Мастер и Маргарита»): `рс` сидит
внутри «Фо**рс**аж» и «ве**рс**ия». Имени, которое КОНЧАЕТСЯ таким словом, в корпусах
нет ни одного, и число тут ноль, - граница держит случай, корпусом не купленный.
"""

from torrcast.domain.nonvideo_release import _is_nonvideo_release

LIVE = [
    "Шрек супербросок / Shrek SuperSlam (2005) PC",
    "Чёрное зеркало 2 / The Black Mirror 2 (2010) PC",
    "Черное зеркало 3 / The Black Mirror 3 (2011) РС",
    "Белое солнце пустыни (2005) PC",
    "РобоКоп / RoboCop (2003) PC",
    "Казаки: Последний довод королей (2001) PC",
    "Частная клиника / Theme Hospital (1997) PC",
    "Пасьянс Солитер: Настоящий Детектив (2015) PC",
    "Проклятый отель: В поисках Чарльза Декстера Уорда (2012) PC",
    "Темные притчи: Русалочка и пурпурный прилив (2014) PC",
    "Дома с Привидениями: Клиника Зеленые Холмы (2010) PC",
    "Русалочка и тайна древнего клада / SeaQuest (2012)  PC",
]


def test_twelve_live_games_marked_pc_at_the_very_end_are_nonvideo() -> None:
    assert [name for name in LIVE if not _is_nonvideo_release(name)] == []


def test_a_word_ending_in_pc_at_the_end_of_a_name_is_not_a_mark() -> None:
    assert not _is_nonvideo_release("Новые пацаны / New kids - Стеффен Харс")
    assert not _is_nonvideo_release("Неизвестная версия / Невідома версія")
    assert not _is_nonvideo_release("Тройной форсаж: Токийский дрифт / Tokyo Drift")
